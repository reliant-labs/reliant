#!/usr/bin/env bash
# Regenerate the demo's forge dashboard set,
# src/components/Forge/Demo/demoData/shop/forge-dashboards.json, from forge's
# own builders for project `shop`:
#
#   overview        the file's base overview, extended by obsbuiltin.ExtendOverview
#   service-orders  kept as the file holds it
#   workloads       kept as the file holds it
#   releases        obsdash.BuildReleases("shop") with the release markers
#   users, product, acquisition
#                   obsbuiltin.Dashboards for shop's declared analytics: goals
#                   checkout (purchase) and "Viewed the cart" (/cart), activation
#                   on order_created within 7d, the default channels, and the Buy
#                   funnel (view_product → add_to_cart → begin_checkout →
#                   purchase, per person, within 1d)
#
# Usage:
#   scripts/demo/regen-forge-dashboards.sh <forge checkout> <ref> [<ref>...]
#
# The refs are merged, in order, into a throwaway detached worktree of the
# forge checkout under $TMPDIR (removed afterwards); nothing is pushed. A
# conflict stops the script: resolve it in the printed worktree, commit there,
# and rerun with RESUME=<that worktree>. The file this repo carries was made with
#
#   scripts/demo/regen-forge-dashboards.sh ../../../forge \
#     1f42538fb 963d262a0
#
# (forge #2075 at 1f42538fb, the built-in dashboards, merged with #2111 at
# 963d262a0, the Releases dashboard). That merge conflicts; it was resolved by
# taking #2075's side everywhere (kcl, skills, testdata, the product_usage files
# #2075 retires), which keeps both branches' additions in pkg/dashspec (the
# conflicting hunk there is #2075's display.exact beside #2111's untouched line).
set -euo pipefail

web=$(cd "$(dirname "$0")/../.." && pwd)
out="$web/src/components/Forge/Demo/demoData/shop/forge-dashboards.json"
forge=${1:?usage: $0 <forge checkout> <ref> [<ref>...]}
shift
refs=("$@")
[ ${#refs[@]} -gt 0 ] || { echo "name at least one forge ref" >&2; exit 2; }

if [ -n "${RESUME:-}" ]; then
  work=$RESUME
else
  work=$(mktemp -d "${TMPDIR:-/tmp}/forge-demo-dash.XXXXXX")
  git -C "$forge" worktree add -q --detach "$work" "${refs[0]}"
  for ref in "${refs[@]:1}"; do
    if ! git -C "$work" -c user.email=regen@localhost -c user.name=regen merge -q --no-edit "$ref"; then
      echo "merging $ref conflicts: resolve in $work, commit, then rerun with RESUME=$work" >&2
      exit 1
    fi
  done
fi

cat >"$work/internal/obsdash/zz_demo_regen_test.go" <<'GO'
package obsdash

import (
	"encoding/json"
	"os"
	"testing"

	"github.com/reliant-labs/forge/pkg/dashspec"
	"github.com/reliant-labs/forge/pkg/obsbuiltin"
)

func TestRegenDemoDashboards(t *testing.T) {
	path := os.Getenv("DEMO_DASHBOARDS")
	raw, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	var file struct {
		Comment    string      `json:"$comment,omitempty"`
		Dashboards []Dashboard `json:"dashboards"`
	}
	if err := json.Unmarshal(raw, &file); err != nil {
		t.Fatal(err)
	}
	in := obsbuiltin.Input{Project: "shop", Web: true,
		Analytics: &obsbuiltin.Analytics{
			Goals:      []obsbuiltin.Goal{{ID: "checkout", Title: "Checkout", Event: "purchase"}, {ID: "cart", Title: "Viewed the cart", Route: "/cart"}},
			Activation: "order_created", ActivationWindow: "7d",
		},
		Funnels: []obsbuiltin.Funnel{
			{ID: "buy", Title: "Buy", Funnel: dashspec.Funnel{Steps: []string{"view_product", "add_to_cart", "begin_checkout", "purchase"}, By: obsbuiltin.FunnelByPerson, Window: "1d"}},
		}}
	byID := map[string]Dashboard{}
	for _, d := range file.Dashboards {
		byID[d.ID] = d
	}
	overview := byID["overview"]
	var base []Panel
	for _, p := range overview.Panels {
		if p.Section == "" || p.Section == "health" {
			p.Section = ""
			base = append(base, p)
		}
	}
	overview.Panels, overview.Sections, overview.DefaultRange = base, nil, ""
	out := []Dashboard{obsbuiltin.ExtendOverview(overview, in), byID["service-orders"], byID["workloads"], withReleaseMarkers(BuildReleases("shop"))}
	file.Dashboards = append(out, obsbuiltin.Dashboards(in)...)
	file.Comment = os.Getenv("DEMO_COMMENT")
	b, err := json.Marshal(file)
	if err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(path, append(b, '\n'), 0o644); err != nil {
		t.Fatal(err)
	}
}
GO

head=$(git -C "$work" log -1 --format=%h)
comment="Generated by frontends/web/scripts/demo/regen-forge-dashboards.sh from forge ${refs[*]} (merged at $head); do not edit by hand. See the script for the command and shop's declared analytics."
(cd "$work" && DEMO_DASHBOARDS="$out" DEMO_COMMENT="$comment" go test -count=1 -run '^TestRegenDemoDashboards$' ./internal/obsdash/ >/dev/null)
rm -f "$work/internal/obsdash/zz_demo_regen_test.go"
[ -n "${RESUME:-}" ] || git -C "$forge" worktree remove --force "$work"
echo "wrote $out"
