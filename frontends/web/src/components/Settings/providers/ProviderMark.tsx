/** Which mark each provider id shows. */
const MARK_FOR: Record<string, string> = {
  claude: "claude",
  anthropic: "anthropic",
  codex: "openai",
  openai: "openai",
  antigravity: "google",
  gemini: "gemini",
  copilot: "copilot",
  openrouter: "openrouter",
};

export type ProviderMarkSize = "sm" | "md";

const TILE: Record<ProviderMarkSize, string> = {
  sm: "h-6 w-6 rounded-md [&_svg]:h-3.5 [&_svg]:w-3.5",
  md: "h-8 w-8 rounded-lg [&_svg]:h-4 [&_svg]:w-4",
};

export function ProviderMark({
  provider,
  size = "md",
  className,
}: {
  provider: string;
  size?: ProviderMarkSize;
  className?: string;
}) {
  const path = PATHS[MARK_FOR[provider] ?? ""];
  return (
    <span
      aria-hidden="true"
      data-testid="provider-mark"
      data-mark={provider === "reliant" ? "reliant" : MARK_FOR[provider] ?? "fallback"}
      className={cn(
        "inline-flex shrink-0 items-center justify-center border border-border/60 bg-background text-foreground",
        TILE[size],
        className,
      )}
    >
      {provider === "reliant" ? (
        <ReliantIcon />
      ) : path ? (
        <svg viewBox="0 0 24 24" fill="currentColor" focusable="false">
          <path d={path} />
        </svg>
      ) : (
        <Bot />
      )}
    </span>
  );
}
