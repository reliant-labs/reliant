import type { ManifestCategory, Ownership, ScaffoldManifest } from "./fixtures";

/** Recorded file provenance, never inferred from a filename or language. */
export function recordedOwnership(manifest: ScaffoldManifest, path: string): Ownership | null {
  return manifest.categories.flatMap(category => category.entries).find(entry => entry[0] === path)?.[3] ?? null;
}
export function categoryOwnership(category: ManifestCategory): Ownership | "mixed" | null {
  const kinds = new Set(category.entries.map(entry => entry[3]));
  return kinds.size > 1 ? "mixed" : kinds.values().next().value ?? null;
}
export function OwnershipBadge({ ownership }: { ownership: Ownership | "mixed" | null }) {
  return <span className={`inline-flex rounded-md border border-border px-2 py-1 text-xs font-medium ${ownership === "regen" ? "bg-accent-surface text-accent-ink" : "bg-surface-sunken text-ink"}`} data-ownership={ownership ?? "unknown"}>
    {ownership === "regen" ? "Generated · regenerated by Forge" : ownership === "yours" ? "Scaffolded once · maintained by your agent" : ownership === "mixed" ? "Mixed ownership" : "Ownership not recorded"}
  </span>;
}
