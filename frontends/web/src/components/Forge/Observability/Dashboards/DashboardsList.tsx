/**
 * OBSERVABILITY › DASHBOARDS (console v3, decision DB): every dashboard of
 * the project in the console's scope, as the reader looks for one.
 *
 *   toolbar           search, Source (release / workspace), Owner (forge,
 *                     the repo, or a person) — narrowed in place, in the URL.
 *   Starred           cards with up to three headline panels drawn small
 *                     (the server picks them: number and line panels first).
 *                     The first three also sit in the nav.
 *   Recently viewed   the caller's last four, newest first.
 *   From your         generated by forge or declared in the repo; shipped in
 *   releases          a release, read-only here.
 *   Workspace         saved in the console: author, version, when, scope.
 *   Templates         the gallery to start from (and a blank dashboard).
 *
 * "New dashboard" offers a blank one, a template, or a forge dashboard file
 * to import. Authoring needs the admin role (the index says, `canWrite`):
 * without it the write actions stay visible, disabled, with the reason.
 */

import { useMemo, useRef, useState, type ReactNode } from "react";
import { ChevronDown, LayoutDashboard, Lock, Plus, Search } from "lucide-react";

import Card from "@/components/forge-ui/card";
import Link from "@/components/forge-ui/link";
import { GettingStarted } from "@/components/Forge/GettingStarted";
import Mono from "@/components/forge-ui/mono";
import Tag from "@/components/forge-ui/tag";
import { useDashboardIndex, useDashboardMutation, useDashboardTemplates, useStarDashboard } from "@/hooks/dashboard-queries";
import { useObservabilityOrg, usePanelQuery } from "@/hooks/observability-queries";
import type { DashboardRef, DashboardSummary } from "@/services/controlPlane/observability/dashboardTypes";
import type { Dashboard, ObsScope, Panel } from "@/services/controlPlane/observability/types";
import { cn } from "@/lib/utils";

import { ENV_ALL } from "../../Console/envScope";
import { formatAgo } from "../format";
import type { ObsEnvironment } from "../obsPlace";
import { OBS_TOPICS, ObsError } from "../ObsStates";
import { DashboardHeader } from "./DashboardHeader";
import { filterIndex, NAV_STARRED, ownerOf, ownersOf, recentOf, starredOf, type SourceFilter } from "./dashboardModel";
import { NewDashboardDialog, SaveCopyDialog, envScopeOf } from "./dialogs";
import { PanelBody } from "./PanelBody";
import { BUTTON_PRIMARY, INK_LINK, Menu, SourceTag, StarButton } from "./parts";
import { StackedTable } from "@/components/Forge/StackedTable";

export interface DashboardsSearch {
  q?: string;
  source?: SourceFilter;
  owner?: string;
}

export interface DashboardsListProps {
  project: string;
  /** The console scope: an environment name or "all". */
  env: string;
  environments: readonly ObsEnvironment[];
  search: DashboardsSearch;
  onSearch: (next: Partial<DashboardsSearch>) => void;
  hrefs: { dashboard: (ref: DashboardRef) => string; release: (version: string) => string };
  navigateTo: (href: string) => void;
}

export function DashboardsList({ project, env, environments, search, onSearch, hrefs, navigateTo }: DashboardsListProps) {
  const org = useObservabilityOrg();
  const orgId = org.orgId;
  const envId = env === ENV_ALL ? undefined : environments.find((candidate) => candidate.name === env)?.id;
  const index = useDashboardIndex(orgId, project, envId);
  const templates = useDashboardTemplates(orgId);
  const star = useStarDashboard(orgId);
  const galleryRef = useRef<HTMLDivElement | null>(null);
  const [creating, setCreating] = useState<"blank" | "import" | null>(null);
  const [fromTemplate, setFromTemplate] = useState<DashboardSummary | null>(null);

  const envIdOf = (name: string) => environments.find((candidate) => candidate.name === name)?.id;
  const create = useDashboardMutation(orgId, (api, org, input: { slug: string; spec: Dashboard; scope: "scope" | "all" }) =>
    api.saveDashboard({ orgId: org, projectId: project, slug: input.slug, spec: input.spec, envScope: envScopeOf(input.scope, env, envIdOf), baseVersion: 0, message: "Created" })
  );
  const copy = useDashboardMutation(orgId, (api, org, input: { from: DashboardRef; title: string; scope: "scope" | "all" }) =>
    api.saveDashboardAsCopy({ orgId: org, from: input.from, projectId: project, title: input.title, envScope: envScopeOf(input.scope, env, envIdOf) })
  );

  const scope = useMemo<ObsScope | null>(() => (orgId ? { orgId, projectId: project, envIds: envId ? [envId] : [], filters: [] } : null), [orgId, project, envId]);
  const all = useMemo(() => index.data?.dashboards ?? [], [index.data]);
  const canWrite = !!index.data?.canWrite;
  const shown = useMemo(() => filterIndex(all, search), [all, search]);
  const filtered = !!(search.q || search.source || search.owner);
  const starred = starredOf(shown);
  const recent = recentOf(shown);
  const releases = shown.filter((d) => d.ref.kind === "release");
  const workspace = shown.filter((d) => d.ref.kind === "workspace");
  const owners = ownersOf(all);
  const toggleStar = (d: DashboardSummary) => star.mutate({ ref: d.ref, starred: !d.starred });
  const writeHint = canWrite ? undefined : "Only organization admins can create dashboards.";

  const header = (
    <DashboardHeader
      title="Dashboards"
      meta={
        <>
          <span>
            {index.data ? `${all.length} dashboard${all.length === 1 ? "" : "s"} in ${project}` : project}
            {env === ENV_ALL ? " · all environments" : ""}
          </span>
          {env !== ENV_ALL && <Tag>{env}</Tag>}
          <span>Release dashboards are code; workspace dashboards are edited here</span>
        </>
      }
      actions={
        <Menu
          label="New dashboard"
          trigger={
            <>
              <Plus className="h-3.5 w-3.5" aria-hidden="true" />
              New dashboard
              <ChevronDown className="h-3 w-3" aria-hidden="true" />
            </>
          }
          triggerClassName={BUTTON_PRIMARY}
          testId="dashboards-new"
          entries={[
            { label: "Blank dashboard", onSelect: () => setCreating("blank"), disabled: !canWrite, hint: writeHint, testId: "dashboards-new-blank" },
            {
              label: "From a template…",
              onSelect: () => galleryRef.current?.scrollIntoView({ block: "start", behavior: "smooth" }),
              testId: "dashboards-new-template",
            },
            { label: "Import JSON…", detail: "a forge dashboard file", onSelect: () => setCreating("import"), disabled: !canWrite, hint: writeHint, testId: "dashboards-new-import" },
          ]}
        />
      }
    />
  );

  const gallery = (
    <div ref={galleryRef} className="scroll-mt-6">
      <Group title="Start from a template" meta="Filled with this project's services and environments">
        {templates.error ? (
          <p className="text-sm text-ink-muted">The template gallery could not be read.</p>
        ) : (
          <div className="grid grid-cols-1 gap-4 sm:grid-cols-2 xl:grid-cols-4" data-testid="dashboards-templates">
            <button
              type="button"
              disabled={!canWrite}
              title={writeHint}
              onClick={() => setCreating("blank")}
              className="flex min-h-24 items-center justify-center gap-2 rounded-lg border border-dashed border-border px-4 py-3 text-sm text-ink-muted transition-colors hover:border-ink-muted hover:text-ink focus-visible:outline-none focus-visible:ring-2 focus-visible:ring-accent disabled:cursor-not-allowed disabled:opacity-60"
              data-testid="dashboards-template-blank"
            >
              <Plus className="h-4 w-4" aria-hidden="true" />
              Blank dashboard
            </button>
            {templates.isLoading
              ? [0, 1, 2].map((i) => <div key={i} className="h-24 animate-pulse rounded-lg border border-border bg-surface motion-reduce:animate-none" />)
              : (templates.data ?? []).map((template) => (
                  <button
                    key={template.ref.key}
                    type="button"
                    disabled={!canWrite}
                    title={writeHint}
                    onClick={() => setFromTemplate(template)}
                    className="flex min-h-24 flex-col items-start gap-1 rounded-lg border border-border bg-surface px-4 py-3 text-left transition-colors hover:border-ink-muted focus-visible:outline-none focus-visible:ring-2 focus-visible:ring-accent disabled:cursor-not-allowed disabled:opacity-60"
                    data-testid={`dashboards-template-${template.ref.key}`}
                  >
                    <span className="flex w-full items-center justify-between gap-2">
                      <span className="truncate text-sm font-medium text-ink">{template.title}</span>
                      {template.category === "platform" && <Tag>platform</Tag>}
                    </span>
                    <span className="line-clamp-2 text-xs text-ink-muted">{template.description || `${template.panelCount} panels`}</span>
                  </button>
                ))}
          </div>
        )}
      </Group>
    </div>
  );

  let body: ReactNode;
  if (index.isLoading || org.isLoading) {
    body = <ListSkeleton />;
  } else if (index.error || (!orgId && org.error)) {
    body = <ObsError error={index.error ?? org.error} subject={project} onRetry={() => void (index.error ? index.refetch() : org.refetch())} retrying={index.isFetching} />;
  } else if (all.length === 0) {
    body = (
      <div data-testid="dashboards-empty">
        <GettingStarted
          testId="dashboards-getting-started"
          icon={<LayoutDashboard className="h-4 w-4" />}
          title="No dashboards yet"
          about={OBS_TOPICS.dashboards.about}
          steps={[
            {
              text: "Deploy a release. Forge generates a dashboard for every service and frontend, and they appear here with it.",
              command: `forge env deploy ${env === ENV_ALL ? "<env>" : env}`,
            },
            {
              text: "Keep one in your repository: add a panel to a dashboard under deploy/observability/dashboards, and it ships with the next release.",
              command: "forge obs dashboards add-panel <slug> --panel <panel.json>",
            },
            { text: "Or start one here, from a template or blank, below." },
          ]}
          docs={OBS_TOPICS.dashboards.docs}
        >
          <p>
            Dashboards ship with your releases, so none is here until one is promoted{env === ENV_ALL ? "" : ` to ${env}`}.
          </p>
        </GettingStarted>
      </div>
    );
  } else {
    body = (
      <>
        <Toolbar search={search} onSearch={onSearch} owners={owners} filtered={filtered} />
        {shown.length === 0 ? (
          <Card className="mt-4 py-8 text-center text-sm text-ink-muted" data-testid="dashboards-no-match">
            No dashboards match.{" "}
            <button type="button" className={INK_LINK} onClick={() => onSearch({ q: undefined, source: undefined, owner: undefined })}>
              Clear the filters
            </button>{" "}
            or start from a template below.
          </Card>
        ) : (
          <>
            {starred.length > 0 && (
              <Group title="Starred" meta={`${starred.length} · the first ${NAV_STARRED} also sit in the nav`}>
                <div className="grid grid-cols-1 gap-4 md:grid-cols-2 xl:grid-cols-3" data-testid="dashboards-starred">
                  {starred.map((d) => (
                    <StarredCard key={`${d.ref.kind}/${d.ref.key}`} summary={d} scope={scope} href={hrefs.dashboard(d.ref)} onStar={() => toggleStar(d)} />
                  ))}
                </div>
              </Group>
            )}
            {recent.length > 0 && (
              <Group title="Recently viewed">
                <Card padding="none" className="overflow-hidden" data-testid="dashboards-recent">
                  <table className="w-full text-sm">
                    <caption className="sr-only">Dashboards you opened recently</caption>
                    <tbody>
                      {recent.map((d) => (
                        <Row key={`${d.ref.kind}/${d.ref.key}`} href={hrefs.dashboard(d.ref)} navigateTo={navigateTo}>
                          <td className="h-10 px-4">
                            <Link href={hrefs.dashboard(d.ref)} className="no-color font-medium text-ink">
                              {d.title}
                            </Link>
                          </td>
                          <td className="h-10 px-4">
                            <SourceTag source={d.source} />
                          </td>
                          <td className="h-10 px-4 text-ink-muted">viewed {d.lastViewedAtMs ? formatAgo(d.lastViewedAtMs) : ""}</td>
                          <td className="hidden h-10 px-4 lg:table-cell">
                            <PreviewRow summary={d} scope={scope} />
                          </td>
                          <td className="h-10 w-11 pr-2 text-right">
                            <StarButton starred={d.starred} title={d.title} onToggle={() => toggleStar(d)} />
                          </td>
                        </Row>
                      ))}
                    </tbody>
                  </table>
                </Card>
              </Group>
            )}
            {releases.length > 0 && (
              <Group title="From your releases" meta={`${releases.length} · generated by forge or declared in the repo; read-only here`}>
                <Card padding="none" className="overflow-hidden" data-testid="dashboards-release">
                  <StackedTable className="w-full text-sm">
                    <thead>
                      <tr className="border-b border-border text-left text-xs text-ink-muted">
                        <th scope="col" className="h-9 px-4 font-medium">
                          Name
                        </th>
                        <th scope="col" className="h-9 px-4 font-medium">
                          Source
                        </th>
                        <th scope="col" className="h-9 px-4 font-medium">
                          Shipped in
                        </th>
                        <th scope="col" className="h-9 px-4 text-right font-medium">
                          Panels
                        </th>
                        <th scope="col" className="h-9 w-11">
                          <span className="sr-only">Star</span>
                        </th>
                      </tr>
                    </thead>
                    <tbody>
                      {releases.map((d) => (
                        <Row key={d.ref.key} href={hrefs.dashboard(d.ref)} navigateTo={navigateTo}>
                          <td className="h-10 px-4">
                            <span className="inline-flex items-center gap-2">
                              <Lock className="h-3.5 w-3.5 text-ink-muted" aria-label="read-only" />
                              <Link href={hrefs.dashboard(d.ref)} className="no-color font-medium text-ink">
                                {d.title}
                              </Link>
                            </span>
                          </td>
                          <td className="h-10 px-4">
                            <span className="inline-flex items-center gap-2">
                              <SourceTag source={d.source} />
                              {d.release?.filePath && <Mono value={d.release.filePath} copy={false} className="max-w-[18rem] truncate text-xs text-ink-muted" />}
                            </span>
                          </td>
                          <td className="h-10 px-4">
                            {d.release?.releaseVersion ? (
                              <Link href={hrefs.release(d.release.releaseVersion)} className={INK_LINK}>
                                {d.release.releaseVersion}
                              </Link>
                            ) : (
                              <span className="text-ink-muted">—</span>
                            )}
                          </td>
                          <td className="h-10 px-4 text-right tabular-nums text-ink-muted">{d.panelCount}</td>
                          <td className="h-10 w-11 pr-2 text-right">
                            <StarButton starred={d.starred} title={d.title} onToggle={() => toggleStar(d)} />
                          </td>
                        </Row>
                      ))}
                    </tbody>
                  </StackedTable>
                </Card>
              </Group>
            )}
            {workspace.length > 0 && (
              <Group title="Workspace" meta={`${workspace.length} · saved in place, versioned, promotable to code`}>
                <Card padding="none" className="overflow-hidden" data-testid="dashboards-workspace">
                  <StackedTable className="w-full text-sm">
                    <thead>
                      <tr className="border-b border-border text-left text-xs text-ink-muted">
                        <th scope="col" className="h-9 px-4 font-medium">
                          Name
                        </th>
                        <th scope="col" className="h-9 px-4 font-medium">
                          Author
                        </th>
                        <th scope="col" className="h-9 px-4 text-right font-medium">
                          Version
                        </th>
                        <th scope="col" className="h-9 px-4 font-medium">
                          Edited
                        </th>
                        <th scope="col" className="h-9 px-4 font-medium">
                          Environments
                        </th>
                        <th scope="col" className="h-9 w-11">
                          <span className="sr-only">Star</span>
                        </th>
                      </tr>
                    </thead>
                    <tbody>
                      {workspace.map((d) => (
                        <Row key={d.ref.key} href={hrefs.dashboard(d.ref)} navigateTo={navigateTo}>
                          <td className="h-10 px-4">
                            <Link href={hrefs.dashboard(d.ref)} className="no-color font-medium text-ink">
                              {d.title}
                            </Link>
                          </td>
                          <td className="h-10 px-4 text-ink">{ownerOf(d)}</td>
                          <td className="h-10 px-4 text-right tabular-nums text-ink">v{d.workspace?.version ?? 1}</td>
                          <td className="h-10 px-4 text-ink-muted">{d.workspace?.updatedAtMs ? formatAgo(d.workspace.updatedAtMs) : "—"}</td>
                          <td className="h-10 px-4">
                            <EnvScopeTags ids={d.workspace?.envIds ?? []} environments={environments} />
                          </td>
                          <td className="h-10 w-11 pr-2 text-right">
                            <StarButton starred={d.starred} title={d.title} onToggle={() => toggleStar(d)} />
                          </td>
                        </Row>
                      ))}
                    </tbody>
                  </StackedTable>
                </Card>
              </Group>
            )}
          </>
        )}
      </>
    );
  }

  return (
    <div className="space-y-2" data-testid="dashboards" data-state={index.isLoading ? "loading" : index.error ? "error" : "ready"}>
      {header}
      <div className="pt-4">{body}</div>
      {!index.isLoading && !index.error && gallery}
      {!canWrite && index.data && (
        <p className="pt-2 text-xs text-ink-muted" data-testid="dashboards-read-only">
          You can view and star dashboards. Creating, copying and changing them needs an organization admin.
        </p>
      )}
      {creating && (
        <NewDashboardDialog
          mode={creating}
          env={env}
          pending={create.isPending}
          error={create.error}
          onCancel={() => {
            create.reset();
            setCreating(null);
          }}
          onCreate={(input) =>
            create.mutate(input, {
              onSuccess: (saved) => {
                setCreating(null);
                navigateTo(hrefs.dashboard(saved.summary.ref));
              },
            })
          }
        />
      )}
      {fromTemplate && (
        <SaveCopyDialog
          sourceTitle={fromTemplate.title}
          what="template"
          env={env}
          pending={copy.isPending}
          error={copy.error}
          onCancel={() => {
            copy.reset();
            setFromTemplate(null);
          }}
          onSave={(input) =>
            copy.mutate(
              { from: fromTemplate.ref, ...input },
              {
                onSuccess: (saved) => {
                  setFromTemplate(null);
                  navigateTo(hrefs.dashboard(saved.summary.ref));
                },
              }
            )
          }
        />
      )}
    </div>
  );
}

// ── Pieces ──────────────────────────────────────────────────────────────────

function Group({ title, meta, children }: { title: string; meta?: string; children: ReactNode }) {
  return (
    <section className="pt-8 first:pt-4">
      <div className="mb-3 flex items-baseline gap-2">
        <h2 className="text-sm font-medium text-ink">{title}</h2>
        {meta && <span className="text-xs text-ink-muted">{meta}</span>}
      </div>
      {children}
    </section>
  );
}

const CHIP = "inline-flex h-8 items-center gap-1 whitespace-nowrap rounded-md border px-2.5 text-sm transition-colors focus-visible:outline-none focus-visible:ring-2 focus-visible:ring-accent";

function Toolbar({
  search,
  onSearch,
  owners,
  filtered,
}: {
  search: DashboardsSearch;
  onSearch: (next: Partial<DashboardsSearch>) => void;
  owners: string[];
  filtered: boolean;
}) {
  const chip = (on: boolean) => cn(CHIP, on ? "border-ink/40 bg-ink/8 text-ink" : "border-border bg-surface text-ink-muted hover:text-ink");
  return (
    <div className="flex flex-wrap items-center gap-2" data-testid="dashboards-toolbar">
      <label className="flex h-8 min-w-72 items-center gap-1.5 rounded-md border border-border bg-surface px-2.5 text-ink-muted focus-within:ring-2 focus-within:ring-accent">
        <Search className="h-3.5 w-3.5 shrink-0" aria-hidden="true" />
        <span className="sr-only">Search dashboards</span>
        <input
          value={search.q ?? ""}
          onChange={(event) => onSearch({ q: event.target.value || undefined })}
          placeholder="Search dashboards"
          className="min-w-0 flex-1 bg-transparent text-sm text-ink placeholder:text-ink-muted focus:outline-none"
          data-testid="dashboards-search"
        />
      </label>
      <button type="button" aria-pressed={search.source === "release"} className={chip(search.source === "release")} onClick={() => onSearch({ source: search.source === "release" ? undefined : "release" })} data-testid="dashboards-chip-release">
        Source: Release
      </button>
      <button type="button" aria-pressed={search.source === "workspace"} className={chip(search.source === "workspace")} onClick={() => onSearch({ source: search.source === "workspace" ? undefined : "workspace" })} data-testid="dashboards-chip-workspace">
        Source: Workspace
      </button>
      <Menu
        label="Owner"
        align="left"
        trigger={
          <>
            Owner: {search.owner ?? "anyone"}
            <ChevronDown className="h-3 w-3" aria-hidden="true" />
          </>
        }
        triggerClassName={chip(!!search.owner)}
        testId="dashboards-chip-owner"
        entries={[{ label: "anyone", checked: !search.owner, onSelect: () => onSearch({ owner: undefined }) }, ...owners.map((owner) => ({ label: owner, checked: search.owner === owner, onSelect: () => onSearch({ owner }) }))]}
      />
      {filtered && (
        <button type="button" className="h-8 px-2 text-sm text-ink-muted hover:text-ink" onClick={() => onSearch({ q: undefined, source: undefined, owner: undefined })} data-testid="dashboards-clear">
          Clear
        </button>
      )}
    </div>
  );
}

/** A table row that is one link: a click anywhere but a control opens the dashboard. */
function Row({ href, navigateTo, children }: { href: string; navigateTo: (href: string) => void; children: ReactNode }) {
  return (
    <tr
      className="cursor-pointer border-b border-border/70 last:border-b-0 hover:bg-ink/5"
      onClick={(event) => {
        if ((event.target as HTMLElement).closest("a, button, input")) return;
        navigateTo(href);
      }}
    >
      {children}
    </tr>
  );
}

function EnvScopeTags({ ids, environments }: { ids: string[]; environments: readonly ObsEnvironment[] }) {
  if (ids.length === 0) return <span className="text-ink-muted">all</span>;
  return (
    <span className="inline-flex flex-wrap gap-1">
      {ids.map((id) => (
        <Tag key={id}>{environments.find((candidate) => candidate.id === id)?.name ?? id}</Tag>
      ))}
    </span>
  );
}

function StarredCard({ summary, scope, href, onStar }: { summary: DashboardSummary; scope: ObsScope | null; href: string; onStar: () => void }) {
  return (
    <Card padding="none" className="relative min-w-0 transition-colors hover:border-ink-muted" data-testid={`dashboards-card-${summary.ref.key}`}>
      <div className="flex items-center justify-between gap-2 px-4 pt-3">
        <Link href={href} className="no-color min-w-0 truncate text-sm font-medium text-ink after:absolute after:inset-0 after:content-['']">
          {summary.title}
        </Link>
        <span className="relative z-10">
          <StarButton starred={summary.starred} title={summary.title} onToggle={onStar} />
        </span>
      </div>
      <div className="flex min-h-5 items-center gap-1.5 px-4">
        <SourceTag source={summary.source} />
        <span className="truncate text-xs text-ink-muted">
          {summary.release
            ? `shipped in ${summary.release.releaseVersion || "a release"}`
            : summary.workspace
              ? `v${summary.workspace.version} · ${ownerOf(summary)}${summary.workspace.updatedAtMs ? ` · ${formatAgo(summary.workspace.updatedAtMs)}` : ""}`
              : ""}
        </span>
      </div>
      <div className="grid grid-cols-3 gap-3 px-4 pb-3.5 pt-3">
        {summary.previewPanels.length ? (
          summary.previewPanels.slice(0, 3).map((panel, index) => <PreviewSpark key={`${panel.id}-${index}`} panel={panel} scope={scope} />)
        ) : (
          <p className="col-span-3 text-xs text-ink-muted">{summary.panelCount} panels</p>
        )}
      </div>
    </Card>
  );
}

/** One headline panel, small: its title and its last day, drawn by the same PanelBody as the dashboard. */
function PreviewSpark({ panel, scope, bare = false }: { panel: Panel; scope: ObsScope | null; bare?: boolean }) {
  const query = usePanelQuery(scope, "24h", panel, []);
  const body = <PanelBody panel={panel} query={query} compact height={bare ? 20 : 28} />;
  if (bare) return <span className="block w-14" title={panel.title}>{body}</span>;
  return (
    <div className="min-w-0">
      <div className="mb-1 truncate text-xs text-ink-muted" title={panel.title}>
        {panel.title}
      </div>
      {body}
    </div>
  );
}

function PreviewRow({ summary, scope }: { summary: DashboardSummary; scope: ObsScope | null }) {
  const panels = summary.previewPanels.filter((p) => p.kind === "line").slice(0, 3);
  if (panels.length === 0) return null;
  return (
    <span className="ml-auto inline-grid grid-cols-3 gap-2 align-middle" aria-hidden="true">
      {panels.map((panel, index) => (
        <PreviewSpark key={`${panel.id}-${index}`} panel={panel} scope={scope} bare />
      ))}
    </span>
  );
}

