/** A star toggle. The colour is the warning token on purpose: a star is a mark, not a status or an action. */
export function StarButton({
  starred,
  title,
  onToggle,
  disabled,
  testId,
}: {
  starred: boolean;
  title: string;
  onToggle: () => void;
  disabled?: boolean;
  testId?: string;
}) {
  return (
    <button
      type="button"
      aria-pressed={starred}
      aria-label={`${starred ? "Unstar" : "Star"} ${title}`}
      title={starred ? "Starred: your first three stars sit in the nav" : "Star"}
      disabled={disabled}
      onClick={(event) => {
        event.preventDefault();
        event.stopPropagation();
        onToggle();
      }}
      className={cn(ICON_BUTTON, starred && "text-warning hover:text-warning")}
      data-testid={testId}
    >
      <Star className={cn("h-4 w-4", starred && "fill-current")} aria-hidden="true" />
    </button>
  );
}

/** Where a dashboard came from, as a tag: a lock on the read-only ones. */
export function SourceTag({ source }: { source: DashboardSource }) {
  const readOnly = source === "generated" || source === "repo" || source === "builtin";
  return (
    <Tag
      icon={readOnly ? <Lock /> : undefined}
      title={
        source === "builtin" ? "Organization accounting from canonical billing sources. Requires cost-read permission, not billing management."
          : source === "generated"
          ? "Generated by forge from your services; ships with each release. Read-only here."
          : source === "repo"
            ? "Declared in your repo under deploy/observability/dashboards; ships with each release. Read-only here."
            : source === "workspace"
              ? "Saved in the console: versioned, editable, promotable to code."
              : "A starting point; using it saves a workspace copy."
      }
    >
      {SOURCE_LABELS[source]}
    </Tag>
  );
}

/** A row of mutually exclusive buttons (Compare: Off · Previous period · Previous release). */
export function Segmented<T extends string>({
  label,
  value,
  options,
  onChange,
  testId,
  disabledReason,
}: {
  label: string;
  value: T;
  options: { value: T; label: string }[];
  onChange: (value: T) => void;
  testId?: string;
  /** Per option: why it cannot be picked now. */
  disabledReason?: Partial<Record<T, string>>;
}) {
  return (
    <span role="group" aria-label={label} className="inline-flex items-center rounded-md border border-border bg-surface p-0.5" data-testid={testId}>
      <span className="px-1.5 text-xs text-ink-muted" aria-hidden="true">
        {label}
      </span>
      {options.map((option) => {
        const reason = disabledReason?.[option.value];
        return (
          <button
            key={option.value}
            type="button"
            aria-pressed={value === option.value}
            disabled={!!reason}
            title={reason}
            onClick={() => onChange(option.value)}
            data-value={option.value}
            className={cn(
              "h-6 rounded px-2 text-xs transition-colors focus-visible:outline-none focus-visible:ring-2 focus-visible:ring-accent disabled:cursor-not-allowed disabled:opacity-50",
              value === option.value ? "bg-ink/8 font-medium text-ink" : "text-ink-muted hover:text-ink"
            )}
          >
            {option.label}
          </button>
        );
      })}
    </span>
  );
}

/** A labelled native select, styled as a variable chip: `env  prod ▾`. */
export function VariableSelect({
  id,
  label,
  value,
  options,
  onChange,
}: {
  id: string;
  label: string;
  value: string;
  options: { value: string; label: string }[];
  onChange: (value: string) => void;
}) {
  return (
    <label htmlFor={id} className="inline-flex h-7 items-center gap-1.5 rounded-md border border-border bg-surface pl-2 text-xs focus-within:ring-2 focus-within:ring-accent">
      <span className="text-ink-muted">{label}</span>
      <span className="relative inline-flex items-center">
        <select
          id={id}
          value={value}
          onChange={(event) => onChange(event.target.value)}
          className="h-6 appearance-none bg-transparent pl-0.5 pr-6 text-xs font-medium text-ink focus:outline-none"
          data-testid={id}
        >
          {options.map((option) => (
            <option key={option.value} value={option.value}>
              {option.label}
            </option>
          ))}
        </select>
        <ChevronDown className="pointer-events-none absolute right-1.5 h-3 w-3 text-ink-muted" aria-hidden="true" />
      </span>
    </label>
  );
}

export interface MenuEntry {
  label: string;
  detail?: string;
  href?: string;
  onSelect?: () => void;
  disabled?: boolean;
  hint?: string;
  /** A line above this entry. */
  separated?: boolean;
  /** The entry currently in effect (a picked interval). */
  checked?: boolean;
  /** Independent choices, unlike an exclusive interval radio group. */
  multiple?: boolean;
  testId?: string;
}

const MENU_ITEM =
  "flex min-h-8 w-full items-center justify-between gap-3 rounded-md px-2 text-left text-sm text-ink transition-colors hover:bg-ink/5 focus-visible:bg-ink/5 focus-visible:outline-none disabled:cursor-not-allowed disabled:text-ink-muted disabled:hover:bg-transparent";

function MenuItems({ entries, heading, close }: { entries: MenuEntry[]; heading?: ReactNode; close: () => void }) {
  return (
    <>
      {heading && <div className="px-2 pb-1 pt-1.5 text-xs text-ink-muted">{heading}</div>}
      {entries.map((entry) => {
        const body = (
          <>
            <span className={cn(entry.checked && "font-medium")}>{entry.label}</span>
            {entry.detail && <span className="truncate text-xs text-ink-muted">{entry.detail}</span>}
          </>
        );
        return (
          <div key={entry.label}>
            {entry.separated && <div className="-mx-1 my-1 h-px bg-border" role="separator" />}
            {entry.href && !entry.disabled ? (
              <Link href={entry.href} role="menuitem" data-testid={entry.testId} onClick={close} className={`no-color ${MENU_ITEM}`}>
                {body}
              </Link>
            ) : (
              <button
                type="button"
                role={entry.checked !== undefined ? (entry.multiple ? "menuitemcheckbox" : "menuitemradio") : "menuitem"}
                aria-checked={entry.checked}
                data-testid={entry.testId}
                disabled={entry.disabled}
                title={entry.hint}
                onClick={() => {
                  close();
                  entry.onSelect?.();
                }}
                className={MENU_ITEM}
              >
                {body}
              </button>
            )}
          </div>
        );
      })}
    </>
  );
}

/** A dropdown under any trigger (the DROPDOWN_STANDARDS outside-click pattern; Escape closes it). */
export function Menu({
  trigger,
  label,
  entries,
  align = "right",
  triggerClassName,
  heading,
  testId,
}: {
  trigger: ReactNode;
  label: string;
  entries: MenuEntry[];
  align?: "left" | "right";
  triggerClassName?: string;
  heading?: ReactNode;
  testId?: string;
}) {
  const [open, setOpen] = useState(false);
  const ref = useRef<HTMLDivElement | null>(null);
  const menuRef = useRef<HTMLDivElement | null>(null);
  const [shift, setShift] = useState(0);
  // Controls wrap at both card and viewport widths. Clamp the floating menu,
  // not the whole toolbar: either fixed alignment can escape one of its edges.
  useLayoutEffect(() => {
    if (!open) { setShift(0); return; }
    const position = () => {
      const menu = menuRef.current;
      const anchor = ref.current;
      if (!menu || !anchor) return;
      const box = anchor.getBoundingClientRect();
      const width = menu.getBoundingClientRect().width;
      const left = align === "left" ? box.left : box.right - width;
      const clamped = Math.max(8, Math.min(left, window.innerWidth - width - 8));
      setShift(clamped - left);
    };
    position();
    window.addEventListener("resize", position);
    return () => window.removeEventListener("resize", position);
  }, [open, align]);
  const escapeLayer = useEscapeLayer(open, () => setOpen(false));
  useEffect(() => {
    if (!open) return;
    const onPointerDown = (event: MouseEvent) => {
      if (ref.current && !ref.current.contains(event.target as Node)) setOpen(false);
    };
    document.addEventListener("mousedown", onPointerDown);
    return () => document.removeEventListener("mousedown", onPointerDown);
  }, [open]);
  return (
    <div ref={ref} className="relative inline-flex">
      <button
        type="button"
        aria-label={label}
        aria-haspopup="menu"
        aria-expanded={open}
        onClick={() => setOpen((prev) => !prev)}
        className={triggerClassName ?? BUTTON_SECONDARY}
        data-testid={testId}
      >
        {trigger}
      </button>
      {open && (
        <div
          role="menu"
          ref={menuRef}
          style={{ transform: `translateX(${shift}px)` }}
          {...escapeLayer}
          className={cn(
            "absolute top-full z-50 mt-1 min-w-52 max-w-sm rounded-lg border border-border bg-surface p-1 text-left shadow-md",
            align === "right" ? "right-0" : "left-0"
          )}
        >
          <MenuItems entries={entries} heading={heading} close={() => setOpen(false)} />
        </div>
      )}
    </div>
  );
}

/** A menu opened at a point (where a series or row was clicked): the drill-down. */
export function PointMenu({
  at,
  heading,
  entries,
  onClose,
  testId,
}: {
  at: { x: number; y: number };
  heading?: ReactNode;
  entries: MenuEntry[];
  onClose: () => void;
  testId?: string;
}) {
  const ref = useRef<HTMLDivElement | null>(null);
  const escapeLayer = useEscapeLayer(true, onClose);
  useEffect(() => {
    const onPointerDown = (event: MouseEvent) => {
      if (ref.current && !ref.current.contains(event.target as Node)) onClose();
    };
    document.addEventListener("mousedown", onPointerDown);
    ref.current?.querySelector<HTMLElement>("a, button")?.focus();
    return () => document.removeEventListener("mousedown", onPointerDown);
  }, [onClose]);
  const left = Math.min(at.x, (typeof window === "undefined" ? 1200 : window.innerWidth) - 280);
  return (
    <div
      ref={ref}
      role="menu"
      {...escapeLayer}
      style={{ left: Math.max(8, left), top: at.y + 6 }}
      className="fixed z-[60] w-64 rounded-lg border border-border bg-surface p-1 text-left shadow-md"
      data-testid={testId}
    >
      <MenuItems entries={entries} heading={heading} close={onClose} />
    </div>
  );
}
