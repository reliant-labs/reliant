/**
 * How the Dashboards page folds a project's dashboards into a few places to
 * start from — pure, so the rule is tested on its own.
 *
 * A project with sixteen services used to list sixteen near-identical rows
 * ("control-plane: admin-api admin-api [service] generated …"), and forge's
 * Users, Product and Acquisition dashboards sat as three more rows beside the
 * repo's own. The page now leads with HUBS and single cards, and lists one
 * row per dashboard only for what the team wrote:
 *
 *   product    "Product analytics": forge's Users, Product and Acquisition
 *              dashboards (in that order), then a generated or built-in
 *              frontend one — one tab each. control-plane's older built-in
 *              "Product usage" (`usage`) is the same story told once more, so
 *              it is hidden whenever forge's set is there, and is the hub's
 *              only tab when it is not.
 *   services   "Services": the built-in Service health (every service at
 *              once, "All services"), each workload's generated dashboard,
 *              and the consolidated jobs dashboard. Tabs up to
 *              HUB_TAB_LIMIT, a picker beyond.
 *   cards      every other dashboard forge or Reliant provides (overview,
 *              releases, workloads, the organization views, LLM usage): one
 *              card each.
 *   own        the repo's and the workspace's dashboards: rows.
 *
 * Each tab stays its own dashboard with its own URL: a link to one opens the
 * hub on that tab, and stars, history and "Save as copy" are the tab's.
 */

import type { DashboardRef, DashboardSummary } from "@/services/controlPlane/observability/dashboardTypes";

import { BUILTIN_PRODUCT_ORDER, groupOf, workloadOf, type DashboardGroup } from "./dashboardGroups";
import { isOrganizationViewKey } from "./dashboardModel";

export type HubId = "product" | "services";

export interface HubTab {
  ref: DashboardRef;
  /** The tab's name: "Users", "admin-api", "All services". */
  label: string;
  summary: DashboardSummary;
}

export interface DashboardHub {
  id: HubId;
  title: string;
  about: string;
  tabs: HubTab[];
  /** Too many tabs to lay out in a row: the hub offers a picker instead. */
  picker: boolean;
}

/** The most tabs a hub lays out in a row; beyond it, a picker. */
export const HUB_TAB_LIMIT = 6;

const HUB_TITLES: Record<HubId, { title: string; about: string }> = {
  product: { title: "Product analytics", about: "Who your users are, what they do, and where they come from" },
  services: { title: "Services", about: "Requests, errors and latency, one service at a time" },
};

/** forge's product analytics keys, which the hub leads with. */
const PRODUCT_KEYS = BUILTIN_PRODUCT_ORDER as readonly string[];
/** control-plane's older built-in product dashboard: forge's set supersedes it. */
const LEGACY_USAGE_KEY = "usage";
/** control-plane's built-in all-services RED dashboard. */
const SERVICE_HEALTH_KEY = "service-red";

/** Generated by forge, or one of a project's standard built-ins: the dashboards nobody on the team wrote. */
export function isProvided(d: Pick<DashboardSummary, "source">): boolean {
  return d.source === "generated" || d.source === "builtin";
}

/**
 * An organization-wide view (Costs, Usage, Billing, LLM usage): a built-in,
 * but the organization's, never one of this project's. The server says so by
 * category ("billing") or by a typed viewKind; the URL contract says so by an
 * "org-" key. Any one of them is enough.
 */
export function isOrganizationView(d: Pick<DashboardSummary, "source" | "category" | "viewKind" | "ref">): boolean {
  if (d.source !== "builtin") return false;
  return d.category === "billing" || (d.viewKind !== undefined && d.viewKind !== "standard") || isOrganizationViewKey(d.ref.key);
}

/** One of this project's own provided dashboards: generated by forge, or a standard built-in over its data. */
const isProjectProvided = (d: DashboardSummary) => d.source === "generated" || (d.source === "builtin" && !isOrganizationView(d));
const isProjectBuiltin = (d: DashboardSummary) => d.source === "builtin" && !isOrganizationView(d);

// The hubs hold the project's dashboards only: an organization view keyed
// "product" or "frontend" stays a card of its own.
const isProductAnalytics = (d: DashboardSummary) => isProjectProvided(d) && PRODUCT_KEYS.includes(d.ref.key);
const isLegacyUsage = (d: DashboardSummary) => isProjectBuiltin(d) && d.ref.key === LEGACY_USAGE_KEY;
const isProvidedFrontend = (d: DashboardSummary) => isProjectProvided(d) && (d.ref.key === "frontend" || d.ref.key.startsWith("frontend-"));
const isServiceHealth = (d: DashboardSummary) => isProjectBuiltin(d) && d.ref.key === SERVICE_HEALTH_KEY;
const isJobs = (d: DashboardSummary) => d.source === "generated" && groupOf(d) === "jobs";

/**
 * The index less what another dashboard in it already says: the built-in
 * Product usage when forge's Users, Product and Acquisition are there.
 */
export function withoutSuperseded(dashboards: readonly DashboardSummary[]): DashboardSummary[] {
  const forgeProduct = dashboards.some(isProductAnalytics);
  return dashboards.filter((d) => !(forgeProduct && isLegacyUsage(d)));
}

/**
 * A title as the project's own pages show it: forge names a generated
 * dashboard "<project>: <what>", which inside the project says nothing.
 */
export function displayTitle(title: string, project: string | undefined): string {
  if (!project) return title;
  const prefix = `${project}:`;
  if (!title.toLowerCase().startsWith(prefix.toLowerCase())) return title;
  const rest = title.slice(prefix.length).trim();
  if (!rest) return title;
  // Words read as a title ("users" → "Users"); a workload's name ("admin-api") stays as it is spelled.
  return /^[a-z][a-z ]*$/.test(rest) ? rest[0]!.toUpperCase() + rest.slice(1) : rest;
}

/**
 * One dashboard per id: a release dashboard of a built-in's id is the
 * project's own version of it (control-plane lists only one; this holds if
 * an older one listed both).
 */
function onePerKey(dashboards: DashboardSummary[]): DashboardSummary[] {
  const byKey = new Map<string, DashboardSummary>();
  for (const d of dashboards) {
    const held = byKey.get(d.ref.key);
    if (!held || (held.source === "builtin" && d.source !== "builtin")) byKey.set(d.ref.key, d);
  }
  return [...byKey.values()];
}

function productTabs(dashboards: readonly DashboardSummary[], project: string | undefined): HubTab[] {
  // By id, whatever the source: forge ships them in the release, control-plane hosts them as built-ins.
  const forge = onePerKey(PRODUCT_KEYS.flatMap((key) => dashboards.filter((d) => isProductAnalytics(d) && d.ref.key === key)));
  const usage = forge.length ? [] : dashboards.filter(isLegacyUsage);
  const frontend = onePerKey(dashboards.filter(isProvidedFrontend));
  return [...forge, ...usage, ...frontend].map((d) => ({ ref: d.ref, summary: d, label: displayTitle(d.title, project) }));
}

function serviceTabs(dashboards: readonly DashboardSummary[]): HubTab[] {
  const health = dashboards.filter(isServiceHealth).map((d) => ({ ref: d.ref, summary: d, label: "All services" }));
  const workloads = dashboards
    .flatMap((d) => {
      const workload = workloadOf(d);
      return workload ? [{ ref: d.ref, summary: d, label: workload }] : [];
    })
    .sort((a, b) => a.label.localeCompare(b.label));
  const jobs = dashboards.filter(isJobs).map((d) => ({ ref: d.ref, summary: d, label: "Jobs" }));
  return [...health, ...workloads, ...jobs];
}

function hub(id: HubId, tabs: HubTab[]): DashboardHub | null {
  return tabs.length ? { id, ...HUB_TITLES[id], tabs, picker: tabs.length > HUB_TAB_LIMIT } : null;
}

/** The project's hubs, product analytics first; a hub with no dashboard is none. */
export function hubsOf(dashboards: readonly DashboardSummary[], project: string | undefined): DashboardHub[] {
  const shown = withoutSuperseded(dashboards);
  return [hub("product", productTabs(shown, project)), hub("services", serviceTabs(shown))].filter((h): h is DashboardHub => h !== null);
}

/**
 * Whether a tab is the dashboard a URL names. control-plane serves the old
 * built-in `usage` as `product` (an alias, control-plane #2618), so an old
 * "Product usage" link lands on the Product tab.
 */
export function isTabOf(tab: Pick<HubTab, "ref">, ref: Pick<DashboardRef, "kind" | "key">): boolean {
  if (tab.ref.kind === ref.kind && tab.ref.key === ref.key) return true;
  return ref.kind === "builtin" && ref.key === LEGACY_USAGE_KEY && tab.ref.key === "product";
}

const sameRef = (a: DashboardRef, b: Pick<DashboardRef, "kind" | "key">) => isTabOf({ ref: a }, b);

/** The hub a dashboard is a tab of, if any. */
export function hubOf(dashboards: readonly DashboardSummary[], ref: Pick<DashboardRef, "kind" | "key">, project: string | undefined): DashboardHub | null {
  return hubsOf(dashboards, project).find((h) => h.tabs.some((tab) => sameRef(tab.ref, ref))) ?? null;
}

/** The label of the tab a dashboard is in its hub: what the breadcrumb and the nav call it. */
export function hubTabLabel(h: DashboardHub, ref: Pick<DashboardRef, "kind" | "key">): string | undefined {
  return h.tabs.find((tab) => sameRef(tab.ref, ref))?.label;
}

/** One entry of the landing's grid: a hub, or one dashboard forge or Reliant provides. */
export type LandingCard =
  | { kind: "hub"; id: HubId; hub: DashboardHub }
  | { kind: "dashboard"; id: string; dashboard: DashboardSummary; title: string };

const GROUP_RANK: Record<DashboardGroup, number> = { overview: 0, services: 2, jobs: 2, product: 3, releases: 4, platform: 5, custom: 6 };

/** Organization views: right after the project's platform cards (Workloads), before any custom one. */
const ORGANIZATION_RANK = GROUP_RANK.platform + 0.5;

function cardRank(card: LandingCard): number {
  if (card.kind === "hub") return card.id === "product" ? 1 : 2;
  if (isOrganizationView(card.dashboard)) return ORGANIZATION_RANK;
  return GROUP_RANK[groupOf(card.dashboard)];
}

export interface Landing {
  cards: LandingCard[];
  /** The repo's and the workspace's dashboards, in the server's order. */
  own: DashboardSummary[];
}

/** The landing page: the hubs and provided dashboards as cards, then the team's own. */
export function landingOf(dashboards: readonly DashboardSummary[], project: string | undefined): Landing {
  const shown = withoutSuperseded(dashboards);
  const hubs = hubsOf(shown, project);
  const inHub = new Set(hubs.flatMap((h) => h.tabs.map((tab) => `${tab.ref.kind}/${tab.ref.key}`)));
  const cards: LandingCard[] = [
    ...hubs.map((h): LandingCard => ({ kind: "hub", id: h.id, hub: h })),
    ...shown
      .filter((d) => isProvided(d) && !inHub.has(`${d.ref.kind}/${d.ref.key}`))
      .map((d): LandingCard => ({ kind: "dashboard", id: `${d.ref.kind}/${d.ref.key}`, dashboard: d, title: displayTitle(d.title, project) })),
  ];
  // Array.prototype.sort is stable: equal ranks keep the server's order.
  cards.sort((a, b) => cardRank(a) - cardRank(b));
  return { cards, own: shown.filter((d) => !isProvided(d)) };
}
