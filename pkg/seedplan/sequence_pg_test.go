// sequenceMigration keys one table each way a sequence can feed a key: a
// BIGSERIAL, a GENERATED ALWAYS identity (which refuses an explicit value
// without OVERRIDING SYSTEM VALUE), a BY DEFAULT identity that STARTs above
// every seeded key, and a DEFAULT nextval over a sequence the column does
// not own.
const sequenceMigration = `
CREATE TABLE tasks (
    id BIGSERIAL PRIMARY KEY,
    title TEXT NOT NULL
);

CREATE TABLE notes (
    id INTEGER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    task_id BIGINT NOT NULL REFERENCES tasks(id),
    body TEXT NOT NULL
);

CREATE TABLE tickets (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,
    subject TEXT NOT NULL
);

CREATE SEQUENCE shared_seq;
CREATE TABLE labels (
    id BIGINT PRIMARY KEY DEFAULT nextval('shared_seq'),
    name TEXT NOT NULL
);

CREATE TABLE descending_notes (
    id BIGINT GENERATED ALWAYS AS IDENTITY (START WITH 5 INCREMENT BY -2 MINVALUE -100 MAXVALUE 5) PRIMARY KEY,
    body TEXT NOT NULL
);

CREATE TABLE descending_tickets (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH -100 INCREMENT BY -2 MINVALUE -1000 MAXVALUE 5) PRIMARY KEY,
    subject TEXT NOT NULL
);

`

const sequenceEdgesMigration = `
CREATE TABLE descending_cycle (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 5 INCREMENT BY -2 MINVALUE 0 MAXVALUE 5 CYCLE) PRIMARY KEY
);
CREATE TABLE exhausted_bigints (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 9223372036854775807) PRIMARY KEY
);`

func setupSequenceDB(t *testing.T) (*sql.DB, string) {
	t.Helper()
	db, cleanup, err := pgtest.New()
	if err != nil {
		t.Fatalf("pgtest.New: %v", err)
	}
	t.Cleanup(cleanup)
	if _, err := db.Exec(sequenceMigration); err != nil {
		t.Fatalf("apply migration to target: %v", err)
	}
	dir := t.TempDir()
	if err := os.WriteFile(filepath.Join(dir, "00001_init.up.sql"), []byte(sequenceMigration), 0o644); err != nil {
		t.Fatalf("write migration: %v", err)
	}
	return db, dir
}

// appInsert is the app's own next INSERT into table, which takes its key
// from the sequence; it returns that key.
func appInsert(t *testing.T, db *sql.DB, insert string) int64 {
	t.Helper()
	var id int64
	if err := db.QueryRow(insert + " RETURNING id").Scan(&id); err != nil {
		t.Fatalf("app insert after the seed (%s): %v", insert, err)
	}
	return id
}

// The seeder writes explicit keys 1..N, bypassing the sequences that feed
// them. It used to leave those sequences at 1, so the app's first INSERT
// after a seed failed on the primary key (obs b0273257). Each sequence is
// now advanced past the seeded keys — forward only.
func TestApply_AdvancesKeySequencesPastSeededRows(t *testing.T) {
	requirePG(t)
	ctx := context.Background()
	db, dir := setupSequenceDB(t)

	plan, err := BuildLivePlan(ctx, db, dir, "", Config{Rows: 5, Salt: 1})
	if err != nil {
		t.Fatal(err)
	}
	if _, err := Apply(ctx, db, plan); err != nil {
		t.Fatalf("Apply (a GENERATED ALWAYS identity refuses explicit keys without OVERRIDING SYSTEM VALUE): %v", err)
	}
	assertCount(t, db, "notes", 5)

	if id := appInsert(t, db, `INSERT INTO tasks (title) VALUES ('app')`); id != 6 {
		t.Errorf("tasks: app insert drew id %d, want 6 (BIGSERIAL past the 5 seeded rows)", id)
	}
	if id := appInsert(t, db, `INSERT INTO notes (task_id, body) VALUES (1, 'app')`); id != 6 {
		t.Errorf("notes: app insert drew id %d, want 6 (identity past the 5 seeded rows)", id)
	}
	if id := appInsert(t, db, `INSERT INTO labels (name) VALUES ('app')`); id != 6 {
		t.Errorf("labels: app insert drew id %d, want 6 (nextval DEFAULT past the 5 seeded rows)", id)
	}
	// Already past every seeded key: left where it was, not moved back.
	if id := appInsert(t, db, `INSERT INTO tickets (subject) VALUES ('app')`); id != 1000 {
		t.Errorf("tickets: app insert drew id %d, want 1000 (START WITH above the seeded keys is kept)", id)
	}

	if id := appInsert(t, db, `INSERT INTO descending_notes (body) VALUES ('app')`); id != -1 {
		t.Errorf("descending notes: app drew %d, want -1 (one -2 step past the seeded minimum 1)", id)
	}
	if id := appInsert(t, db, `INSERT INTO descending_tickets (subject) VALUES ('app')`); id != -100 {
		t.Errorf("descending tickets: app drew %d, want -100 (already past the seeded keys)", id)
	}

	// A re-apply inserts nothing new and must not move a sequence back
	// below the app's row.
	if _, err := Apply(ctx, db, plan); err != nil {
		t.Fatalf("re-Apply: %v", err)
	}
	if id := appInsert(t, db, `INSERT INTO tasks (title) VALUES ('app2')`); id != 7 {
		t.Errorf("tasks after re-apply: app insert drew id %d, want 7", id)
	}
	if id := appInsert(t, db, `INSERT INTO descending_notes (body) VALUES ('app2')`); id != -3 {
		t.Errorf("descending notes after re-apply: app drew %d, want -3", id)
	}

	// Reset's TRUNCATE ... RESTART IDENTITY puts every sequence back to
	// its start before the re-seed; the seed advances them again.
	if _, err := Reset(ctx, db, plan); err != nil {
		t.Fatalf("Reset: %v", err)
	}
	if id := appInsert(t, db, `INSERT INTO tasks (title) VALUES ('after reset')`); id != 6 {
		t.Errorf("tasks after reset: app insert drew id %d, want 6", id)
	}
}

func TestApply_DoesNotReissueSequenceKeysWithoutRows(t *testing.T) {
	requirePG(t)
	ctx := context.Background()
	db, dir := setupSequenceDB(t)
	// nextval is not transactional: a failed insert or rolled-back
	// transaction leaves these keys consumed but absent from the tables.
	if _, err := db.ExecContext(ctx, `
SELECT setval('tasks_id_seq', 30, true);
SELECT setval('descending_notes_id_seq', -30, true);`); err != nil {
		t.Fatal(err)
	}
	tx, err := db.BeginTx(ctx, nil)
	if err != nil {
		t.Fatal(err)
	}
	defer func() { _ = tx.Rollback() }()
	if _, err := tx.ExecContext(ctx, `
INSERT INTO tasks (title) VALUES ('rolled back');
INSERT INTO descending_notes (body) VALUES ('rolled back');`); err != nil {
		t.Fatal(err)
	}
	if err := tx.Rollback(); err != nil {
		t.Fatal(err)
	}
	assertCount(t, db, "tasks", 0)
	assertCount(t, db, "descending_notes", 0)
	plan, err := BuildLivePlan(ctx, db, dir, "", Config{Rows: 5, Salt: 1})
	if err != nil {
		t.Fatal(err)
	}
	for range 2 {
		if _, err := Apply(ctx, db, plan); err != nil {
			t.Fatal(err)
		}
	}
	if id := appInsert(t, db, `INSERT INTO tasks (title) VALUES ('app')`); id != 32 {
		t.Errorf("ascending sequence reissued a key: got %d, want 32", id)
	}
	if id := appInsert(t, db, `INSERT INTO descending_notes (body) VALUES ('app')`); id != -34 {
		t.Errorf("descending sequence reissued a key: got %d, want -34", id)
	}
}

func TestApply_SequenceBoundsDoNotOverflowOrWrap(t *testing.T) {
	requirePG(t)
	ctx := context.Background()
	db, cleanup, err := pgtest.New()
	if err != nil {
		t.Fatal(err)
	}
	t.Cleanup(cleanup)
	if _, err := db.Exec(sequenceEdgesMigration + `
INSERT INTO exhausted_bigints DEFAULT VALUES;
INSERT INTO descending_cycle (id) VALUES (0);`); err != nil {
		t.Fatal(err)
	}
	dir := t.TempDir()
	if err := os.WriteFile(filepath.Join(dir, "00001_init.up.sql"), []byte(sequenceEdgesMigration), 0o644); err != nil {
		t.Fatal(err)
	}
	plan, err := BuildLivePlan(ctx, db, dir, "", Config{Rows: 1, Salt: 1})
	if err != nil {
		t.Fatal(err)
	}
	if _, err := Apply(ctx, db, plan); err != nil {
		t.Fatalf("seeding beside a sequence at its bigint endpoint must not overflow: %v", err)
	}
	if id := appInsert(t, db, `INSERT INTO descending_cycle DEFAULT VALUES`); id != 5 {
		t.Errorf("cycling sequence moved to a wrap boundary: drew %d, want untouched start 5", id)
	}
}

// Render is the same SQL Apply runs, so a reader applying it by hand gets the
// sequence moves too.
func TestRender_CarriesTheSequenceMoves(t *testing.T) {
	requirePG(t)
	ctx := context.Background()
	db, dir := setupSequenceDB(t)
	plan, err := BuildLivePlan(ctx, db, dir, "", Config{Rows: 3, Salt: 1})
	if err != nil {
		t.Fatal(err)
	}
	sql := plan.Render()
	for _, want := range []string{
		`INSERT INTO "notes" ("id", "task_id", "body") OVERRIDING SYSTEM VALUE VALUES`,
		`(SELECT max("id") FROM "tasks")`,
		`'tasks_id_seq'::regclass`,
		`pg_get_serial_sequence('"notes"', 'id')::regclass`,
		`'shared_seq'::regclass`,
	} {
		if !strings.Contains(sql, want) {
			t.Errorf("Render lacks %q:\n%s", want, sql)
		}
	}
	if strings.Contains(sql, `INSERT INTO "tasks" ("id", "title") OVERRIDING`) {
		t.Errorf("a table with no identity column must not carry OVERRIDING SYSTEM VALUE:\n%s", sql)
	}
	if _, err := db.ExecContext(ctx, sql); err != nil {
		t.Fatalf("the rendered SQL does not apply: %v", err)
	}
	if id := appInsert(t, db, `INSERT INTO tasks (title) VALUES ('app')`); id != 4 {
		t.Errorf("tasks after the rendered SQL: app insert drew id %d, want 4", id)
	}
}
