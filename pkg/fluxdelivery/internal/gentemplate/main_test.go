package main

import (
	"errors"
	"flag"
	"os"
	"os/exec"
	"path/filepath"
	"strings"
	"testing"

	"github.com/reliant-labs/forge/pkg/fluxdelivery"
	"github.com/reliant-labs/forge/pkg/testkit"
)

// runAsMain makes the test binary call main() itself: the re-executed child
// of TestMainExitCode, since main ends in os.Exit.
var runAsMain = flag.Bool("gentemplate.main", false, "run main() instead of the test (internal: TestMainExitCode's child)")

func slow(t *testing.T) {
	t.Helper()
	testkit.Slow(t, "evaluates the forge KCL module through kclrender",
		testkit.Inputs("kcl/lib/flux_delivery.k", "kcl/render.k", "pkg/fluxdelivery/**"))
}

// TestRunWritesTheCommittedTemplate: run in an empty directory produces
// exactly the Go file `go generate ./pkg/fluxdelivery` committed, so the
// generator and the checked-in constant cannot drift apart.
func TestRunWritesTheCommittedTemplate(t *testing.T) {
	slow(t)
	committed, err := os.ReadFile(filepath.Join("..", "..", "template_gen.go"))
	if err != nil {
		t.Fatal(err)
	}

	t.Chdir(t.TempDir())
	if err := run(); err != nil {
		t.Fatalf("run: %v", err)
	}
	got, err := os.ReadFile("template_gen.go")
	if err != nil {
		t.Fatalf("run wrote no template_gen.go: %v", err)
	}
	if string(got) != string(committed) {
		t.Errorf("generated file differs from pkg/fluxdelivery/template_gen.go; run `go generate ./pkg/fluxdelivery`")
	}
	for _, want := range []string{
		"// Code generated by forge. DO NOT EDIT.\n// Source: kcl/lib/flux_delivery.k (go generate ./pkg/fluxdelivery)\n",
		"package fluxdelivery",
		"const Template = ",
	} {
		if !strings.Contains(string(got), want) {
			t.Errorf("generated file missing %q", want)
		}
	}
	if !strings.Contains(string(got), fluxdelivery.Template[:40]) {
		t.Errorf("generated file does not embed the template (starts %q)", fluxdelivery.Template[:40])
	}
}

// TestRunFailsWhenTheOutputCannotBeWritten: template_gen.go is a directory,
// so the atomic rename onto it fails and run must report it rather than
// claiming success.
func TestRunFailsWhenTheOutputCannotBeWritten(t *testing.T) {
	slow(t)
	dir := t.TempDir()
	if err := os.Mkdir(filepath.Join(dir, "template_gen.go"), 0o755); err != nil {
		t.Fatal(err)
	}
	t.Chdir(dir)
	if err := run(); err == nil {
		t.Fatal("run succeeded although template_gen.go is a directory")
	}
}

// TestMainExitCode runs main in a child process (it calls os.Exit), once in a
// directory it can write to and once where it cannot.
func TestMainExitCode(t *testing.T) {
	if *runAsMain {
		main()
		return
	}
	slow(t)

	runMain := func(t *testing.T, dir string) (string, error) {
		t.Helper()
		cmd := exec.Command(os.Args[0], "-test.run=^TestMainExitCode$", "-gentemplate.main")
		cmd.Dir = dir
		out, err := cmd.CombinedOutput()
		return string(out), err
	}

	t.Run("success writes the file and exits 0", func(t *testing.T) {
		dir := t.TempDir()
		if out, err := runMain(t, dir); err != nil {
			t.Fatalf("main failed: %v\n%s", err, out)
		}
		if _, err := os.Stat(filepath.Join(dir, "template_gen.go")); err != nil {
			t.Errorf("main wrote no template_gen.go: %v", err)
		}
	})

	t.Run("failure prints a gentemplate-prefixed error and exits 1", func(t *testing.T) {
		dir := t.TempDir()
		if err := os.Mkdir(filepath.Join(dir, "template_gen.go"), 0o755); err != nil {
			t.Fatal(err)
		}
		out, err := runMain(t, dir)
		var exit *exec.ExitError
		if !errors.As(err, &exit) || exit.ExitCode() != 1 {
			t.Fatalf("err = %v, want exit status 1", err)
		}
		if !strings.Contains(out, "gentemplate: ") {
			t.Errorf("output %q lacks the 'gentemplate:' prefix", out)
		}
	})
}
