// Command gentemplate writes pkg/fluxdelivery/template_gen.go: the Go
// constant of kcl/lib/flux_delivery.k's FLUX_DELIVERY_TEMPLATE, evaluated
// through forge's own KCL seam. Run by `go generate ./pkg/fluxdelivery`;
// TestTemplateMatchesKCL fails when the file is stale.
package main

import (
	"fmt"
	"go/format"
	"os"
	"strconv"
	"strings"

	"github.com/reliant-labs/forge/internal/atomicfile"
	"github.com/reliant-labs/forge/pkg/fluxdelivery/internal/kcleval"
)

func main() {
	if err := run(); err != nil {
		fmt.Fprintln(os.Stderr, "gentemplate:", err)
		os.Exit(1)
	}
}

func run() error {
	tmpl, err := kcleval.Template(os.TempDir())
	if err != nil {
		return err
	}
	literal := strconv.Quote(tmpl)
	if !strings.Contains(tmpl, "`") {
		literal = "`" + tmpl + "`"
	}
	// The canonical forge header and a Source line: pkg/ is vendored into every
	// project's .forge-pkg, where `forge lint`'s scaffold-ownership lane holds
	// each _gen.go to exactly these (internal/linter/scaffolds).
	src := "// Code generated by forge. DO NOT EDIT.\n" +
		"// Source: kcl/lib/flux_delivery.k (go generate ./pkg/fluxdelivery)\n\n" +
		"package fluxdelivery\n\n" +
		"// Template is kcl/lib/flux_delivery.k's FLUX_DELIVERY_TEMPLATE: the\n" +
		"// ResourceSet resourcesTemplate. Regenerate with `go generate ./pkg/fluxdelivery`.\n" +
		"const Template = " + literal + "\n"
	formatted, err := format.Source([]byte(src))
	if err != nil {
		return err
	}
	return atomicfile.WriteFile("template_gen.go", formatted, 0o644)
}
