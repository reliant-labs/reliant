package crud

import (
	"context"
	"reflect"
	"strings"
	"unicode"

	"github.com/reliant-labs/forge/pkg/observe"
)

// Automatic product events.
//
// Every write that lands through HandleCreate, HandleUpdate or HandleDelete
// records one product event (observe.Track): "<entity>_created",
// "<entity>_updated" or "<entity>_deleted", with <entity> the entity's
// snake_case name ("order_item"). It lives here, in the library every
// generated CRUD shim delegates to, so a project picks it up with a forge
// upgrade alone: no regenerate, no edit to the shim it owns.
//
// What an event carries, and what it does not:
//
//   - The user, from the claims the auth interceptor put in ctx, the way every
//     Track call reads it. A write with no authenticated caller is anonymous.
//   - No properties. In particular no primary key and no field value: an id
//     is unbounded cardinality and a value may be personal data, and the
//     product-event contract keeps both out. The event says WHAT KIND of
//     thing a user did; the row is in the database.
//
// When it fires: after the repository call returned nil, and only then. A
// refused, conflicting or failed write records nothing. A repository call
// here is one statement in autocommit, so "returned nil" is "committed",
// with one exception: a caller that runs the handler inside its own
// transaction (orm.RunTx around the RPC) gets the event when the statement
// succeeds, before that transaction commits. A rolled-back outer transaction
// is rare in a CRUD path and the event is a count, not a ledger, so it is not
// worth a transaction hook.
//
// It never fails or slows the rpc: Track writes one INFO record through the
// context's logger and returns, and a name the contract would refuse (an
// entity name too long for the 64-character limit) is skipped silently here
// rather than warned about on every write.
//
// Each event is one log record, which the hosted platform bills as log ingest
// (product_events itself is derived from it). FORGE_PRODUCT_EVENTS=off
// (observe.EnvProductEvents; KCL renders it from
// forge.ObservabilitySignals{product_events = False}) switches the automatic
// events off. An observe.Track the app calls itself is never gated.

// autoProductEvents is observe.AutoProductEvents, behind a var so this
// package's tests can switch it without the process environment, which
// observe reads once.
var autoProductEvents = observe.AutoProductEvents

// trackWrite records the automatic product event for a CRUD write that
// landed. entity is the op's resolved snake_case name (see eventEntity).
func trackWrite(ctx context.Context, entity, verb string) {
	if entity == "" || !autoProductEvents() {
		return
	}
	name := entity + "_" + verb
	if !observe.ValidEventName(name) {
		return
	}
	observe.Track(ctx, name)
}

// eventEntity resolves the snake_case entity name an op's events use.
//
// The generated ops set EntitySnake. An op generated by an older forge (or a
// hand-written one) leaves it empty, and the name then comes from the Go type
// the op is written over: the entity type itself (*db.OrderItem) for create
// and update, the request type (DeleteOrderItemRequest) for delete. Both are
// spelled from the entity's proto name, exactly as the generator's
// EntitySnake is, so an un-regenerated project emits the same name it will
// after a regenerate. EntityLower ("orderitem") is the last resort only: it
// has lost the word boundaries.
//
// It runs once, when the handler is built, not per request.
func eventEntity(entitySnake, entityLower string, t reflect.Type, trimPrefix, trimSuffix string) string {
	if entitySnake != "" {
		return entitySnake
	}
	for t != nil && t.Kind() == reflect.Pointer {
		t = t.Elem()
	}
	if t != nil {
		name := t.Name()
		// A generic instantiation's name carries its type arguments.
		if i := strings.IndexByte(name, '['); i >= 0 {
			name = name[:i]
		}
		if trimPrefix != "" || trimSuffix != "" {
			if !strings.HasPrefix(name, trimPrefix) || !strings.HasSuffix(name, trimSuffix) {
				name = ""
			} else {
				name = strings.TrimSuffix(strings.TrimPrefix(name, trimPrefix), trimSuffix)
			}
		}
		if s := snakeCase(name); s != "" {
			return s
		}
	}
	return entityLower
}

// snakeCase is the generator's naming.ToSnakeCase (internal/naming), the
// function that spells the generated ops' EntitySnake, kept letter for letter
// so the fallback in eventEntity agrees with it. A test holds the two equal.
func snakeCase(s string) string {
	runes := []rune(s)
	var b strings.Builder
	var prev rune
	for i, r := range runes {
		if unicode.IsUpper(r) {
			if i > 0 {
				if unicode.IsLower(prev) {
					b.WriteByte('_')
				} else if unicode.IsUpper(prev) && i+1 < len(runes) && unicode.IsLower(runes[i+1]) {
					b.WriteByte('_')
				}
			}
			b.WriteRune(unicode.ToLower(r))
		} else {
			b.WriteRune(r)
		}
		prev = r
	}
	return b.String()
}
