// The goose → forge cutover, in miniature. goose ran three migrations; the
// project squashed them into one baseline that declares that history, then
// added one forge migration on top.
//
// The baseline's DDL is deliberately NOT idempotent: CREATE TABLE without IF
// NOT EXISTS fails on any database where the tables exist. So every test that
// adopts a goose database also proves the baseline's SQL did not run — had it
// run, Up would have failed.
var (
	gooseHistory = []int64{20260101000001, 20260101000002, 20260101000003}
	gooseSchema  = []string{
		"CREATE TABLE accounts (id INT PRIMARY KEY)",
		"CREATE TABLE plans (id INT PRIMARY KEY, account_id INT REFERENCES accounts (id))",
		"ALTER TABLE plans ADD COLUMN retired_at TIMESTAMPTZ",
	}
	baselineName  = "20260201000000_baseline.up.sql"
	baselineFiles = map[string]string{
		baselineName: "-- forge:adopts goose 20260101000001 20260101000002\n" +
			"-- forge:adopts goose 20260101000003\n" +
			"CREATE TABLE accounts (id INT PRIMARY KEY);\n" +
			"CREATE TABLE plans (id INT PRIMARY KEY, account_id INT REFERENCES accounts (id), retired_at TIMESTAMPTZ);\n",
	}
	afterBaseline = map[string]string{
		"20260202000000_add_orgs.up.sql": "CREATE TABLE orgs (id INT PRIMARY KEY);",
	}
	cutoverRelease = merged(baselineFiles, afterBaseline)
)

// gooseMigrated builds the database the previous release left behind: goose's
// table exactly as goose v3 creates it (with its version-0 row), the schema,
// one applied row per version in `applied`, and a customer row the adoption
// must not touch.
func gooseMigrated(t *testing.T, applied []int64) (dsn string, db *sql.DB) {
	t.Helper()
	dsn = requirePG(t)
	db = openRecordDB(t, dsn)
	stmts := append([]string{
		`CREATE TABLE goose_db_version (
			id integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
			version_id bigint NOT NULL,
			is_applied boolean NOT NULL,
			tstamp timestamp NOT NULL DEFAULT now()
		)`,
		"INSERT INTO goose_db_version (version_id, is_applied) VALUES (0, true)",
	}, gooseSchema...)
	for _, v := range applied {
		stmts = append(stmts, fmt.Sprintf("INSERT INTO goose_db_version (version_id, is_applied) VALUES (%d, true)", v))
	}
	stmts = append(stmts, "INSERT INTO accounts (id) VALUES (42)")
	for _, s := range stmts {
		if _, err := db.Exec(s); err != nil {
			t.Fatalf("set up the goose database: %s: %v", s, err)
		}
	}
	return dsn, db
}

func up(t *testing.T, files map[string]string, dsn string) (Result, error) {
	t.Helper()
	mg, err := Open(Options{FS: release(files), Dir: "migrations", DSN: dsn})
	if err != nil {
		t.Fatalf("open: %v", err)
	}
	defer func() { _ = mg.Close() }()
	return mg.Up()
}

func gooseRows(t *testing.T, db *sql.DB) int {
	t.Helper()
	var n int
	if err := db.QueryRow("SELECT count(*) FROM goose_db_version").Scan(&n); err != nil {
		t.Fatal(err)
	}
	return n
}

func appliedRecord(t *testing.T, db *sql.DB) map[uint]string {
	t.Helper()
	rec, err := onSession(t, db, readApplied)
	if err != nil {
		t.Fatal(err)
	}
	return rec
}

// TestAdoptFreshDatabaseAppliesTheBaseline: a database goose never touched
// is the ordinary case — the baseline runs as SQL, nothing is adopted.
func TestAdoptFreshDatabaseAppliesTheBaseline(t *testing.T) {
	t.Parallel()
	dsn := requirePG(t)
	res, err := up(t, cutoverRelease, dsn)
	if err != nil {
		t.Fatalf("up: %v", err)
	}
	if res.Adopted != nil {
		t.Errorf("a fresh database was adopted (%+v); the baseline must run as SQL", res.Adopted)
	}
	if !res.Changed || res.After.Version != 20260202000000 {
		t.Errorf("result = %+v; want the baseline and add_orgs applied", res)
	}
	db := openRecordDB(t, dsn)
	for _, table := range []string{"accounts", "plans", "orgs"} {
		if !tableExists(t, db, table) {
			t.Errorf("table %s missing after a fresh apply", table)
		}
	}
}

// TestAdoptGooseDatabaseAtTheBaseline is the cutover on an existing database:
// goose applied exactly the history the baseline replaces. Up adopts it — the
// baseline is recorded, its SQL is not run (it would fail: the tables exist) —
// then applies the forge migration after it, in the same run. goose's table
// and the data are untouched.
func TestAdoptGooseDatabaseAtTheBaseline(t *testing.T) {
	t.Parallel()
	dsn, db := gooseMigrated(t, gooseHistory)
	rowsBefore := gooseRows(t, db)

	res, err := up(t, cutoverRelease, dsn)
	if err != nil {
		t.Fatalf("up: %v (the baseline's SQL ran against the goose schema, or adoption refused)", err)
	}
	want := &Adopted{Tool: "goose", Version: 20260201000000, Name: baselineName, Versions: 3}
	if !reflect.DeepEqual(res.Adopted, want) {
		t.Errorf("Adopted = %+v; want %+v", res.Adopted, want)
	}
	if !res.Changed || res.Before.Version != 20260201000000 || res.After.Version != 20260202000000 {
		t.Errorf("result = %+v; want add_orgs applied on top of the adopted baseline", res)
	}
	if !tableExists(t, db, "orgs") {
		t.Error("the migration after the baseline did not apply")
	}
	var n int
	if err := db.QueryRow("SELECT count(*) FROM accounts WHERE id = 42").Scan(&n); err != nil || n != 1 {
		t.Errorf("the existing row is gone (count %d, err %v)", n, err)
	}
	// Rollback safety: the previous release reads goose's table, and must
	// still find every version it knows applied.
	if got := gooseRows(t, db); got != rowsBefore {
		t.Errorf("goose_db_version has %d rows after adoption, %d before; it must be left alone", got, rowsBefore)
	}
	// The applied record names the baseline file, so a later binary's
	// mismatch check covers it like any applied migration.
	if rec := appliedRecord(t, db); rec[20260201000000] != "baseline" || rec[20260202000000] != "add_orgs" {
		t.Errorf("applied record = %v; want baseline and add_orgs by name", rec)
	}
}

// TestAdoptRefusesAGooseDatabaseThatIsBehind covers both ways a goose
// database falls short of the baseline: a version simply not yet applied, and
// — the case a high-water mark cannot see — an OLDER version skipped while a
// newer one ran (goose applied out of order), or rolled back by goose's
// is_applied=false row. Each refuses, names the version, and changes nothing.
func TestAdoptRefusesAGooseDatabaseThatIsBehind(t *testing.T) {
	t.Parallel()
	cases := []struct {
		name    string
		applied []int64
		extra   string
		missing []int64
	}{
		{name: "the newest version not applied", applied: gooseHistory[:2], missing: []int64{20260101000003}},
		{name: "a middle version skipped, the newest applied", applied: []int64{gooseHistory[0], gooseHistory[2]}, missing: []int64{20260101000002}},
		{
			name:    "a version rolled back (goose's latest row says is_applied=false)",
			applied: gooseHistory,
			extra:   "INSERT INTO goose_db_version (version_id, is_applied) VALUES (20260101000002, false)",
			missing: []int64{20260101000002},
		},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			t.Parallel()
			dsn, db := gooseMigrated(t, tc.applied)
			if tc.extra != "" {
				if _, err := db.Exec(tc.extra); err != nil {
					t.Fatal(err)
				}
			}
			_, err := up(t, cutoverRelease, dsn)
			var adoptErr *AdoptionError
			if !errors.As(err, &adoptErr) {
				t.Fatalf("Up err = %v; want an *AdoptionError", err)
			}
			if !reflect.DeepEqual(adoptErr.Missing, tc.missing) || len(adoptErr.Unexpected) != 0 {
				t.Errorf("missing = %v, unexpected = %v; want missing %v only", adoptErr.Missing, adoptErr.Unexpected, tc.missing)
			}
			if !strings.Contains(err.Error(), "run the last release that still migrates with goose") {
				t.Errorf("the refusal does not say how to catch up:\n%v", err)
			}
			assertUntouched(t, dsn, db)
		})
	}
}

// TestAdoptRefusesAGooseVersionTheBaselineDoesNotList: the database ran a
// goose migration the baseline does not account for — a branch's migration on
// a shared database, or a baseline cut before the last goose migration merged.
// Its schema is not the baseline's, so nothing built on the baseline may run.
func TestAdoptRefusesAGooseVersionTheBaselineDoesNotList(t *testing.T) {
	t.Parallel()
	dsn, db := gooseMigrated(t, append(append([]int64{}, gooseHistory...), 20260101000009))
	_, err := up(t, cutoverRelease, dsn)
	var adoptErr *AdoptionError
	if !errors.As(err, &adoptErr) {
		t.Fatalf("Up err = %v; want an *AdoptionError", err)
	}
	if len(adoptErr.Missing) != 0 || !reflect.DeepEqual(adoptErr.Unexpected, []int64{20260101000009}) {
		t.Errorf("missing = %v, unexpected = %v; want unexpected [20260101000009] only", adoptErr.Missing, adoptErr.Unexpected)
	}
	assertUntouched(t, dsn, db)
}

// assertUntouched: a refused adoption records nothing — no version, no
// applied record, no forge migration — and leaves goose's table as it was.
func assertUntouched(t *testing.T, dsn string, db *sql.DB) {
	t.Helper()
	mg, err := Open(Options{FS: release(cutoverRelease), Dir: "migrations", DSN: dsn})
	if err != nil {
		t.Fatal(err)
	}
	defer func() { _ = mg.Close() }()
	if st, err := mg.State(); err != nil || st.Applied {
		t.Errorf("state after a refusal = %+v, %v; want nothing recorded", st, err)
	}
	for _, table := range []string{appliedTable, compatTable, "orgs"} {
		if tableExists(t, db, table) {
			t.Errorf("a refused adoption created %s", table)
		}
	}
}

// TestAdoptOnceTheHistoryIsFinished follows the refusal's own instruction:
// the previous release catches the database up (goose applies the missing
// version), and the next run of this binary adopts it.
func TestAdoptOnceTheHistoryIsFinished(t *testing.T) {
	t.Parallel()
	dsn, db := gooseMigrated(t, gooseHistory[:2])
	if _, err := up(t, cutoverRelease, dsn); err == nil {
		t.Fatal("a database behind the baseline was not refused")
	}
	if _, err := db.Exec(fmt.Sprintf("INSERT INTO goose_db_version (version_id, is_applied) VALUES (%d, true)", gooseHistory[2])); err != nil {
		t.Fatal(err)
	}
	res, err := up(t, cutoverRelease, dsn)
	if err != nil || res.Adopted == nil || res.After.Version != 20260202000000 {
		t.Fatalf("up after catching up = %+v, %v; want adopted and add_orgs applied", res, err)
	}
}

// TestAdoptionHappensOnce: once golang-migrate records a version, goose's
// table is never consulted again. A re-run is an ordinary no-op, and nothing
// goose's table says afterwards — the previous release rolled back to and
// forward again, a stray row — can make this binary refuse or re-adopt.
func TestAdoptionHappensOnce(t *testing.T) {
	t.Parallel()
	dsn, db := gooseMigrated(t, gooseHistory)
	if res, err := up(t, cutoverRelease, dsn); err != nil || res.Adopted == nil {
		t.Fatalf("first up = %+v, %v; want adopted", res, err)
	}
	res, err := up(t, cutoverRelease, dsn)
	if err != nil {
		t.Fatalf("second up: %v", err)
	}
	if res.Adopted != nil || res.Changed {
		t.Errorf("second up = %+v; want a no-op", res)
	}
	if _, err := db.Exec("INSERT INTO goose_db_version (version_id, is_applied) VALUES (20260101000009, true)"); err != nil {
		t.Fatal(err)
	}
	if res, err := up(t, cutoverRelease, dsn); err != nil || res.Adopted != nil {
		t.Errorf("up after goose's table changed = %+v, %v; want a no-op that never reads goose again", res, err)
	}
}

// TestAdoptConcurrently: every replica of the cutover release starts at once,
// through both entry points (raceReplicas), against one goose database.
// Exactly one adopts; every one succeeds; the baseline's SQL never runs (it
// would fail, and fail that replica); add_orgs applies once.
func TestAdoptConcurrently(t *testing.T) {
	t.Parallel()
	dsn, db := gooseMigrated(t, gooseHistory)
	adopted := 0
	for _, r := range raceReplicas(t, release(cutoverRelease), dsn, 6) {
		if r.Res.Adopted != nil || strings.Contains(r.Logs, "ADOPTED") {
			adopted++
		}
	}
	if adopted != 1 {
		t.Errorf("%d replicas adopted the database; want exactly 1", adopted)
	}
	mg, err := Open(Options{FS: release(cutoverRelease), Dir: "migrations", DSN: dsn})
	if err != nil {
		t.Fatal(err)
	}
	defer func() { _ = mg.Close() }()
	if st, err := mg.State(); err != nil || st != (State{Version: 20260202000000, Applied: true}) {
		t.Errorf("state = %+v, %v; want clean at add_orgs", st, err)
	}
	if !tableExists(t, db, "orgs") {
		t.Error("add_orgs did not apply")
	}
}

// TestAutoMigrateAdoptsAndRefuses is the desktop path: nobody can run a step
// by hand, so boot itself adopts — and says so — or refuses to start.
func TestAutoMigrateAdoptsAndRefuses(t *testing.T) {
	t.Parallel()
	t.Run("adopts", func(t *testing.T) {
		t.Parallel()
		_, db := gooseMigrated(t, gooseHistory)
		var logs bytes.Buffer
		if err := AutoMigrate(release(cutoverRelease), "migrations")(db, slog.New(slog.NewTextHandler(&logs, nil))); err != nil {
			t.Fatalf("AutoMigrate: %v", err)
		}
		for _, want := range []string{"ADOPTED", "tool=goose", "baseline=" + baselineName, "verified_versions=3", "migrations applied"} {
			if !strings.Contains(logs.String(), want) {
				t.Errorf("boot log does not say %q:\n%s", want, logs.String())
			}
		}
		if !tableExists(t, db, "orgs") {
			t.Error("add_orgs did not apply at boot")
		}
	})
	t.Run("refuses", func(t *testing.T) {
		t.Parallel()
		_, db := gooseMigrated(t, gooseHistory[:1])
		err := AutoMigrate(release(cutoverRelease), "migrations")(db, nil)
		var adoptErr *AdoptionError
		if !errors.As(err, &adoptErr) || len(adoptErr.Missing) != 2 {
			t.Fatalf("AutoMigrate err = %v; want an *AdoptionError missing two versions", err)
		}
		if tableExists(t, db, "orgs") {
			t.Error("a refused boot applied add_orgs")
		}
	})
}
