package compat

import (
	"errors"
	"reflect"
	"strings"
	"testing"
	"testing/fstest"
)

func TestParseAdoption(t *testing.T) {
	cases := []struct {
		name string
		sql  string
		want *Adoption
	}{
		{name: "no directive", sql: "CREATE TABLE a (id INT);", want: nil},
		{
			name: "one line",
			sql:  "-- forge:adopts goose 20260101000002 20260101000001\nCREATE TABLE a (id INT);",
			want: &Adoption{Tool: ToolGoose, Versions: []int64{20260101000001, 20260101000002}, Line: 1},
		},
		{
			// A long history wraps across lines; the lists accumulate and the
			// result is in version order whatever order they were written in.
			name: "wrapped across lines, CRLF, indented, any case",
			sql:  "-- squashed history\r\n  --   FORGE:ADOPTS Goose 3 1\r\n-- forge:adopts goose 2\r\nCREATE TABLE a (id INT);\r\n",
			want: &Adoption{Tool: ToolGoose, Versions: []int64{1, 2, 3}, Line: 2},
		},
		{
			// A squashed forge history, as `forge db squash` writes it.
			name: "forge history",
			sql:  "-- Generated by `forge db squash`\n-- forge:adopts forge 20260101000001 20260101000002\nCREATE TABLE a (id INT);",
			want: &Adoption{Tool: ToolForge, Versions: []int64{20260101000001, 20260101000002}, Line: 2},
		},
		{
			// Inside a string or after SQL on the line, it is not a line
			// comment and not a declaration.
			name: "not a line comment",
			sql:  "SELECT '-- forge:adopts goose 1';\nCREATE TABLE a (id INT); -- forge:adopts goose 1",
			want: nil,
		},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			got, err := ParseAdoption(tc.sql)
			if err != nil {
				t.Fatalf("ParseAdoption: %v", err)
			}
			if !reflect.DeepEqual(got, tc.want) {
				t.Errorf("ParseAdoption = %+v; want %+v", got, tc.want)
			}
		})
	}
}

// TestParseAdoptionRefusesWhatItCannotRead: a declaration the migrator
// cannot read in full must never be taken as "no declaration". That would run
// the baseline's SQL against a database whose schema already is the baseline.
// Each refusal names its line, because the linter points there.
func TestParseAdoptionRefusesWhatItCannotRead(t *testing.T) {
	cases := []struct {
		name string
		sql  string
		line int
		want string
	}{
		{name: "misspelled directive", sql: "-- forge:adopt goose 1", line: 1, want: "spelled \"-- forge:adopts\""},
		{name: "no tool", sql: "SELECT 1;\n-- forge:adopts", line: 2, want: "names no tool"},
		{name: "unknown tool", sql: "-- forge:adopts flyway 1", line: 1, want: "cannot adopt \"flyway\""},
		{name: "no versions", sql: "-- forge:adopts goose", line: 1, want: "lists no versions"},
		{name: "not a number", sql: "-- forge:adopts goose 1 20260101_init", line: 1, want: "\"20260101_init\" is not a goose version"},
		{name: "zero", sql: "-- forge:adopts goose 0", line: 1, want: "\"0\" is not a goose version"},
		{name: "repeated version", sql: "-- forge:adopts goose 1 2\n-- forge:adopts goose 2", line: 2, want: "version 2 is listed twice"},
		{name: "two histories", sql: "-- forge:adopts goose 1\n-- forge:adopts forge 2", line: 2, want: "one baseline replaces one tool's history"},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			got, err := ParseAdoption(tc.sql)
			var syn *AdoptionSyntaxError
			if !errors.As(err, &syn) {
				t.Fatalf("ParseAdoption = %+v, %v; want an *AdoptionSyntaxError", got, err)
			}
			if syn.Line != tc.line {
				t.Errorf("line = %d; want %d", syn.Line, tc.line)
			}
			if !strings.Contains(err.Error(), tc.want) {
				t.Errorf("error %q does not say %q", err, tc.want)
			}
		})
	}
}

// TestScanCarriesTheAdoptionAndRefusesAMalformedOne: Scan is what the
// migrator reads at Open and at boot, so a malformed declaration fails there
// with the file named.
func TestScanCarriesTheAdoptionAndRefusesAMalformedOne(t *testing.T) {
	good := fstest.MapFS{
		"m/20260201000000_baseline.up.sql": {Data: []byte("-- forge:adopts goose 1 2\nCREATE TABLE a (id INT);")},
		"m/20260202000000_next.up.sql":     {Data: []byte("CREATE TABLE b (id INT);")},
	}
	ms, err := Scan(good, "m")
	if err != nil {
		t.Fatal(err)
	}
	if ms[0].Adopts == nil || !reflect.DeepEqual(ms[0].Adopts.Versions, []int64{1, 2}) || ms[1].Adopts != nil {
		t.Errorf("Scan adoptions = %+v, %+v; want the baseline's {1, 2} and nothing on the next", ms[0].Adopts, ms[1].Adopts)
	}

	bad := fstest.MapFS{"m/20260201000000_baseline.up.sql": {Data: []byte("-- forge:adopts goose one\n")}}
	if _, err := Scan(bad, "m"); err == nil || !strings.Contains(err.Error(), "20260201000000_baseline.up.sql") {
		t.Errorf("Scan err = %v; want a refusal naming the file", err)
	}
}
