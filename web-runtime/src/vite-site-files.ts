// Part of @reliantlabs/forge-web-runtime — the web twin of forge/pkg.
//
// forgeSiteFiles — a Vite plugin that writes `robots.txt` and `sitemap.xml`
// into the build output.
//
// # Why at build time
//
// A sitemap lists ABSOLUTE URLs, and robots.txt's `Sitemap:` line must be
// absolute too: a relative one is invalid, and crawlers ignore it. The site's
// origin is known only per environment (forge declares it as the frontend's
// `env_vars.SITE_URL`), so neither file can be a static file in `public/`.
// A release is built once and promoted by digest, so every environment that
// serves it carries the same canonical origin, which is what search engines
// want.
//
// # The rules
//
//   - It runs once, after the build has written its output (`closeBundle`),
//     and only for the client build: an SSR build, or a build with
//     `build.write: false`, writes nothing.
//   - It never overwrites a file the app ships. `public/robots.txt` (or
//     `public/sitemap.xml`) has already been copied into the output dir when
//     the hook runs; an existing file is left alone unless it carries this
//     plugin's own marker, i.e. it is a stale copy from an earlier build into
//     a directory that was not emptied.
//   - The sitemap lists every `.html` file of the output (`about.html` is
//     `/about`, `blog/index.html` is `/blog/`), plus `routes`, minus
//     `exclude`, under Vite's `base`. `404.html` and Search Console
//     verification files (`google<hex>.html`) are never listed.
//   - An empty `siteUrl` writes robots.txt with no `Sitemap:` line and no
//     sitemap, and warns with the fix. So
//     `forgeSiteFiles({ siteUrl: process.env.SITE_URL })` builds in every
//     environment, the first build before an env has a hostname included.
//
// Node builtins only, and structural types: this module imports nothing from
// `vite`, so the package takes no dependency on any Vite major. The plugin
// object is assignable to Vite's `Plugin` (vite-site-files.test.ts pins that).
import { existsSync } from "node:fs";
import { readdir, readFile, writeFile } from "node:fs/promises";
import { join, relative, resolve, sep } from "node:path";

/** The first line of every file this plugin writes; how it recognizes its own. */
const MARKER = "Generated by forgeSiteFiles (@reliantlabs/forge-web-runtime)";

/** The sitemap protocol's per-file limit. */
const SITEMAP_MAX_URLS = 50_000;

/** Pages a sitemap never lists, whatever `exclude` says. */
const NEVER_LISTED = [/^\/404$/, /^\/google[0-9a-f]+$/i];

export interface ForgeSiteFilesOptions {
  /**
   * The site's absolute origin, e.g. `https://example.com`: the frontend's
   * `env_vars.SITE_URL`. Undefined or empty writes robots.txt without a
   * `Sitemap:` line and no sitemap.xml, and warns. A path in it (a site
   * mounted at `https://example.com/docs`) prefixes every URL, and is not
   * doubled when Vite's `base` is the same path.
   */
  siteUrl?: string | undefined;
  /**
   * Routes to list beside the `.html` files of the output: the client-side
   * routes of an SPA, which have no file of their own. Paths are relative to
   * the site (Vite's `base` is prefixed), e.g. `"/pricing"`.
   */
  routes?: readonly string[];
  /**
   * Routes to leave out of the sitemap. An entry is an exact path
   * (`"/thanks"`) or a prefix ending in `*` (`"/admin/*"`), relative to the
   * site like `routes`. A file's route is `/about` for `about.html` and
   * `/blog/` for `blog/index.html`; an exact entry matches either spelling.
   */
  exclude?: readonly string[];
  robots?: {
    /**
     * Paths robots.txt disallows, relative to the site like `routes`, e.g.
     * `["/admin/"]`. Robots rules match by prefix.
     */
    disallow?: readonly string[];
  };
}

/** The part of Vite's resolved config forgeSiteFiles reads. */
export interface SiteFilesConfig {
  root: string;
  base: string;
  /** Absolute, or "" when `publicDir: false`. */
  publicDir: string;
  build: {
    outDir: string;
    write?: boolean;
    ssr?: unknown;
  };
  logger: { warn(msg: string): void };
}

/** The part of Vite's plugin context forgeSiteFiles reads. */
export interface SiteFilesContext {
  /** Vite 6+: the environment this hook runs for. */
  environment?: { name?: string };
}

/** The plugin object; structurally a Vite `Plugin`. */
export interface ForgeSiteFilesPlugin {
  name: string;
  apply: "build";
  configResolved(config: SiteFilesConfig): void;
  closeBundle(this: SiteFilesContext, error?: unknown): Promise<void>;
}

/** The URL prefix every route is joined to: an origin plus a path, no trailing "/". */
interface SitePrefix {
  origin: string;
  path: string;
}

/**
 * sitePrefix resolves siteUrl and Vite's base to the absolute prefix of every
 * URL, or null when siteUrl is empty or not an absolute http(s) URL.
 */
function sitePrefix(siteUrl: string, base: string): SitePrefix | null {
  let url: URL;
  try {
    url = new URL(siteUrl);
  } catch {
    return null;
  }
  if (url.protocol !== "http:" && url.protocol !== "https:") return null;
  const sitePath = url.pathname.replace(/\/+$/, "");
  // A relative base ("./", "") or a CDN base ("https://cdn…/") places the
  // assets, not the pages: the pages are served from the site's root.
  const basePath = base.startsWith("/") ? base.replace(/\/+$/, "") : "";
  const path =
    basePath === "" || sitePath === basePath || sitePath.endsWith(basePath)
      ? sitePath
      : sitePath + basePath;
  return { origin: url.origin, path };
}

/** normalizeRoute gives a route its leading "/" and drops a query or hash. */
function normalizeRoute(route: string): string {
  const r = route.trim().replace(/[?#].*$/, "");
  return r.startsWith("/") ? r : `/${r}`;
}

/** routeOfFile maps an output file (posix, relative) to the route it serves. */
function routeOfFile(file: string): string {
  if (file === "index.html") return "/";
  if (file.endsWith("/index.html"))
    return `/${file.slice(0, -"index.html".length)}`;
  return `/${file.slice(0, -".html".length)}`;
}

function excluded(route: string, exclude: readonly string[]): boolean {
  const bare = route.length > 1 ? route.replace(/\/$/, "") : route;
  if (NEVER_LISTED.some((re) => re.test(bare))) return true;
  return exclude.some((raw) => {
    const e = raw.trim();
    if (e.endsWith("*"))
      return route.startsWith(normalizeRoute(e.slice(0, -1)));
    const n = normalizeRoute(e);
    const nBare = n.length > 1 ? n.replace(/\/$/, "") : n;
    return nBare === bare;
  });
}

/** htmlFiles lists every .html file under dir, as posix paths relative to it. */
async function htmlFiles(dir: string): Promise<string[]> {
  const entries = await readdir(dir, { recursive: true, withFileTypes: true });
  return entries
    .filter((e) => e.isFile() && e.name.endsWith(".html"))
    .map((e) => relative(dir, join(e.parentPath, e.name)).split(sep).join("/"));
}

function escapeXml(s: string): string {
  return s
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&apos;");
}

/** absolute joins a site-relative path to the prefix, percent-encoding it. */
function absolute(prefix: SitePrefix, route: string): string {
  return new URL(prefix.path + route, prefix.origin).href;
}

function robotsTxt(
  prefix: SitePrefix | null,
  disallow: readonly string[],
): string {
  const lines = [`# ${MARKER}.`, "User-agent: *", "Allow: /"];
  const pathPrefix = prefix?.path ?? "";
  for (const d of disallow) {
    if (d.trim() === "") continue;
    const path = d.trim();
    lines.push(
      `Disallow: ${pathPrefix}${path.startsWith("/") ? path : `/${path}`}`,
    );
  }
  if (prefix !== null) {
    lines.push("", `Sitemap: ${absolute(prefix, "/sitemap.xml")}`);
  }
  return `${lines.join("\n")}\n`;
}

function sitemapXml(prefix: SitePrefix, routes: readonly string[]): string {
  const urls = routes.map(
    (r) => `  <url><loc>${escapeXml(absolute(prefix, r))}</loc></url>`,
  );
  return [
    '<?xml version="1.0" encoding="UTF-8"?>',
    `<!-- ${MARKER}. -->`,
    '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">',
    ...urls,
    "</urlset>",
    "",
  ].join("\n");
}

/** sortRoutes puts "/" first, then the rest in plain lexical order. */
function sortRoutes(routes: Iterable<string>): string[] {
  return [...routes].sort((a, b) =>
    a === "/" ? -1 : b === "/" ? 1 : a < b ? -1 : a > b ? 1 : 0,
  );
}

/**
 * writeOwned writes file unless one is already there that this plugin did
 * not write (the app's own, copied from `public/`). It reports whether it
 * wrote.
 */
async function writeOwned(file: string, body: string): Promise<boolean> {
  if (existsSync(file)) {
    const current = await readFile(file, "utf8");
    if (!current.includes(MARKER)) return false;
  }
  await writeFile(file, body);
  return true;
}

/**
 * forgeSiteFiles writes `robots.txt` and `sitemap.xml` into the build output
 * for `siteUrl`, leaving alone either file the app ships in `public/`. Add it
 * to `plugins` in vite.config.ts:
 *
 * ```ts
 * import { forgeSiteFiles } from "@reliantlabs/forge-web-runtime/vite";
 * export default defineConfig({
 *   plugins: [react(), forgeSiteFiles({ siteUrl: process.env.SITE_URL })],
 * });
 * ```
 */
export function forgeSiteFiles(
  options: ForgeSiteFilesOptions = {},
): ForgeSiteFilesPlugin {
  const siteUrl = (options.siteUrl ?? "").trim();
  let config: SiteFilesConfig | undefined;

  return {
    name: "forge-site-files",
    apply: "build",
    configResolved(resolved) {
      config = resolved;
    },
    async closeBundle(this: SiteFilesContext, error?: unknown) {
      const env = this?.environment?.name;
      // A failed build closes the bundle too (Rollup passes the error).
      if (
        error !== undefined ||
        config === undefined ||
        (env !== undefined && env !== "client")
      )
        return;
      if (config.build.write === false || config.build.ssr) return;
      const outDir = resolve(config.root, config.build.outDir);
      if (!existsSync(outDir)) return;
      const warn = (msg: string) =>
        config?.logger.warn(`[forge-site-files] ${msg}`);

      const prefix = siteUrl === "" ? null : sitePrefix(siteUrl, config.base);
      if (prefix === null) {
        warn(
          (siteUrl === ""
            ? "siteUrl is empty"
            : `siteUrl ${JSON.stringify(siteUrl)} is not an absolute http(s) URL`) +
            ", so robots.txt has no Sitemap: line and no sitemap.xml was written " +
            "(a sitemap needs absolute URLs). Set env_vars.SITE_URL on this frontend " +
            'in deploy/kcl/<env>/main.k (SITE_URL = forge.FrontendURL { frontend = "<name>" }) ' +
            "and pass forgeSiteFiles({ siteUrl: process.env.SITE_URL }).",
        );
      }

      const robotsFile = join(outDir, "robots.txt");
      if (
        !(await writeOwned(
          robotsFile,
          robotsTxt(prefix, options.robots?.disallow ?? []),
        ))
      ) {
        if (prefix !== null) {
          const own = await readFile(robotsFile, "utf8");
          if (!/^\s*sitemap\s*:/im.test(own)) {
            warn(
              "the app ships its own robots.txt, which was kept; it has no Sitemap: line, " +
                `so add "Sitemap: ${absolute(prefix, "/sitemap.xml")}" to it.`,
            );
          }
        }
      }

      if (prefix === null) return;
      const exclude = options.exclude ?? [];
      const routes = new Set<string>();
      for (const file of await htmlFiles(outDir)) routes.add(routeOfFile(file));
      for (const r of options.routes ?? []) {
        if (r.trim() !== "") routes.add(normalizeRoute(r));
      }
      const listed = sortRoutes(
        [...routes].filter((r) => !excluded(r, exclude)),
      );
      if (listed.length > SITEMAP_MAX_URLS) {
        warn(
          `the sitemap lists ${listed.length} URLs, over the protocol's ${SITEMAP_MAX_URLS}; ` +
            "search engines read only the first file's worth. Narrow it with exclude.",
        );
      }
      await writeOwned(join(outDir, "sitemap.xml"), sitemapXml(prefix, listed));
    },
  };
}
