function uuidFrom(rng: Rng): string {
  const h = rng.hex(32);
  return `${h.slice(0, 8)}-${h.slice(8, 12)}-4${h.slice(13, 16)}-${"89ab"[rng.int(0, 3)]}${h.slice(17, 20)}-${h.slice(20)}`;
}

function formatted(format: StrFormat, rng: Rng, n: number): string {
  switch (format) {
    case "email":
      return `user-${n}@example.com`;
    case "uri":
      return `https://example.com/${rng.hex(8)}`;
    case "hostname":
    case "address":
      return `host-${n}.example.com`;
    case "hostAndPort":
      return `host-${n}.example.com:8080`;
    case "ip":
    case "ipv4":
      return `10.${rng.int(0, 255)}.${rng.int(0, 255)}.${rng.int(1, 254)}`;
    case "ipv6":
      return `fd00::${rng.hex(4)}`;
    case "ipPrefix":
      return `10.${rng.int(0, 255)}.0.0/16`;
    case "uuid":
      return uuidFrom(rng);
    case "tuuid":
      return rng.hex(32);
    case "ulid": {
      const alphabet = "0123456789ABCDEFGHJKMNPQRSTVWXYZ";
      let s = "01";
      while (s.length < 26) s += alphabet[rng.int(0, 31)];
      return s;
    }
  }
}

/** A string for a field, from its name alone (before any rule applies). */
function stringByName(
  name: string,
  owner: DescMessage,
  n: number,
  rng: Rng,
  listItem = false,
): string {
  const w = words(name);
  const last = w[w.length - 1] ?? "";
  if (
    name === "next_page_token" ||
    name === "page_token" ||
    name === "cursor"
  ) {
    return "";
  }
  if (name === "trace_id") return rng.hex(32);
  if (name === "span_id" || name === "parent_span_id") return rng.hex(16);
  if (last === "uuid") return uuidFrom(rng);
  if (name === "id") return `${kebab(messageNoun(owner))}-${rng.hex(8)}`;
  if (last === "id" || last === "ids") {
    const thing = w.slice(0, -1).join("-") || "id";
    return `${thing}-${rng.hex(8)}`;
  }
  if (last === "email" || last === "emails") return `user-${n}@example.com`;
  if (["url", "uri", "link", "href", "endpoint", "website"].includes(last)) {
    return `https://example.com/${w.slice(0, -1).join("-") || "item"}/${n}`;
  }
  if (["host", "hostname", "domain", "fqdn"].includes(last)) {
    return `host-${n}.example.com`;
  }
  if (last === "ip" || name === "ip_address") {
    return `10.0.${rng.int(0, 255)}.${rng.int(1, 254)}`;
  }
  if (last === "phone") return `+1-555-01${String(n % 100).padStart(2, "0")}`;
  if (last === "version") return `1.${rng.int(0, 20)}.${rng.int(0, 9)}`;
  if (last === "color" || last === "colour") return `#${rng.hex(6)}`;
  if (["sha", "commit", "hash", "etag", "fingerprint"].includes(last))
    return rng.hex(40);
  if (last === "digest") return `sha256:${rng.hex(64)}`;
  if (
    last === "token" ||
    last === "secret" ||
    (last === "key" && w.includes("api"))
  ) {
    return `tok_${rng.hex(24)}`;
  }
  if (last === "json") return "{}";
  if (last === "locale" || last === "language") return "en-US";
  if (last === "currency") return "USD";
  if (last === "country") return "US";
  if (last === "timezone" || name === "tz") return "UTC";
  if (["name", "title", "label"].includes(name) || name === "display_name") {
    return `${human(messageNoun(owner))} ${n}`;
  }
  if (last === "name" || last === "title") {
    return `${human(w.slice(0, -1).join("_"))} ${n}`;
  }
  if (
    [
      "description",
      "summary",
      "message",
      "body",
      "text",
      "details",
      "detail",
      "reason",
      "comment",
      "note",
      "notes",
      "content",
      "error",
    ].includes(last)
  ) {
    return `Sample ${human(messageNoun(owner)).toLowerCase()} ${w.join(" ")} ${n}.`;
  }
  return `${kebab(listItem ? singularOf(name) : name)}-${n}`;
}

/** RE2's leading inline flags (`(?i)`, `(?s)`, `(?m)`), which JavaScript spells as RegExp flags. */
const INLINE_FLAGS = /^\(\?([ims]+)\)/;

/** RE2's `\s`: ASCII whitespace only (JavaScript's also matches \v and Unicode spaces). */
const RE2_SPACE = "\\t\\n\\f\\r ";

/**
 * An RE2 pattern body rewritten as JavaScript RegExp source that matches the
 * same strings, or null when it uses a construct the two engines read
 * differently (or that RE2 rejects outright): lookarounds, backreferences,
 * `\c`/`\u`/`\0` escapes, `\p{Key=Value}` properties, mid-pattern flags and
 * repeats over 1000. Null means "never satisfied", so a JavaScript-only match
 * is never taken for one the server's validator accepts.
 *
 * Under a leading `(?i)` (`fold`), `\w` and `\W` pass through unchanged: RE2
 * folds them exactly as JavaScript's `iu` does, so both match the Kelvin sign
 * and the long s. `\b` and `\B` do not: RE2's stay ASCII while JavaScript's
 * follow its folded `\w`, so they are null there (and in a class, where RE2
 * rejects them and JavaScript reads `\b` as a backspace).
 */
function re2Source(src: string, fold: boolean): string | null {
  let out = "";
  let inClass = false;
  for (let i = 0; i < src.length; i++) {
    const c = src[i] as string;
    if (c === "\\") {
      const e = src[++i];
      if (e === undefined) return null;
      if (/[0-9kcu]/.test(e)) return null;
      if ((e === "b" || e === "B") && (fold || inClass)) return null;
      if (e === "s") {
        out += inClass ? RE2_SPACE : `[${RE2_SPACE}]`;
        continue;
      }
      if (e === "S") {
        if (inClass) return null;
        out += `[^${RE2_SPACE}]`;
        continue;
      }
      if ((e === "p" || e === "P") && src[i + 1] === "{") {
        const end = src.indexOf("}", i);
        if (end < 0 || src.slice(i, end).includes("=")) return null;
        out += src.slice(i - 1, end + 1);
        i = end;
        continue;
      }
      out += c + e;
      continue;
    }
    if (inClass) {
      if (c === "]") inClass = false;
      out += c;
      continue;
    }
    if (c === "[") {
      inClass = true;
      out += c;
      if (src[i + 1] === "^") out += src[++i];
      // RE2 reads a `]` first in a class as a literal; JavaScript as the end.
      if (src[i + 1] === "]") {
        out += "\\]";
        i++;
      }
      continue;
    }
    if (c === "(" && src[i + 1] === "?") {
      const rest = src.slice(i + 2);
      if (rest.startsWith("P<")) {
        out += "(?<";
        i += 3;
        continue;
      }
      if (rest.startsWith(":") || /^<[A-Za-z_]/.test(rest)) {
        out += c;
        continue;
      }
      // Lookarounds (RE2 has none) and mid-pattern flag groups.
      return null;
    }
    if (c === "{") {
      const m = /^\{(\d+)(,(\d*))?\}/.exec(src.slice(i));
      if (m && (Number(m[1]) > 1000 || Number(m[3] ?? 0) > 1000)) return null;
    }
    out += c;
  }
  return inClass ? null : out;
}

/**
 * A protovalidate (RE2) pattern as a JavaScript RegExp with RE2's semantics,
 * leading inline flags included. Null when JavaScript cannot express it.
 */
function patternRegExp(pattern: string): RegExp | null {
  const m = INLINE_FLAGS.exec(pattern);
  let flags = "u";
  for (const f of m?.[1] ?? "") if (!flags.includes(f)) flags += f;
  const src = re2Source(
    m ? pattern.slice(m[0].length) : pattern,
    flags.includes("i"),
  );
  if (src === null) return null;
  try {
    return new RegExp(src, flags);
  } catch {
    return null;
  }
}

/**
 * Whether `s` matches an RE2 pattern compiled by patternRegExp. In multiline
 * mode JavaScript also ends lines at \r, U+2028 and U+2029 and RE2 only at
 * \n, so a string holding one of those is not taken as a match.
 */
function re2Test(re: RegExp | null, s: string): boolean {
  if (!re) return false;
  if (re.multiline && /[\r\u2028\u2029]/.test(s)) return false;
  return re.test(s);
}

/** A string matching a cheap regex, or undefined when it is not cheap. */
function fromPattern(pattern: string, rng: Rng): string | undefined {
  let i = 0;
  const src = pattern.replace(INLINE_FLAGS, "");

  type Node = () => string;

  const charClass = (): Node => {
    // At "[" — collect ranges; a negated class picks the first printable miss.
    i++;
    const negate = src[i] === "^";
    if (negate) i++;
    const ranges: Array<[number, number]> = [];
    let first = true;
    while (i < src.length && (src[i] !== "]" || first)) {
      first = false;
      let c = src[i++] as string;
      if (c === "\\") {
        const e = src[i++] as string;
        if (e === "d") {
          ranges.push([48, 57]);
          continue;
        }
        if (e === "w") {
          ranges.push([97, 122], [65, 90], [48, 57], [95, 95]);
          continue;
        }
        if (e === "s") {
          ranges.push([32, 32]);
          continue;
        }
        c = e;
      }
      if (src[i] === "-" && src[i + 1] !== "]" && i + 1 < src.length) {
        i++;
        let hi = src[i++] as string;
        if (hi === "\\") hi = src[i++] as string;
        ranges.push([c.charCodeAt(0), hi.charCodeAt(0)]);
      } else {
        ranges.push([c.charCodeAt(0), c.charCodeAt(0)]);
      }
    }
    i++; // "]"
    if (negate) {
      return () => {
        for (let code = 97; code < 127; code++) {
          if (!ranges.some(([lo, hi]) => code >= lo && code <= hi)) {
            return String.fromCharCode(code);
          }
        }
        return "_";
      };
    }
    return () => {
      const [lo, hi] = rng.pick(ranges);
      return String.fromCharCode(rng.int(lo, hi));
    };
  };

  const atom = (): Node | undefined => {
    const c = src[i];
    if (c === "(") {
      i++;
      if (src[i] === "?") {
        if (src[i + 1] !== ":") return undefined; // lookarounds: not cheap
        i += 2;
      }
      const inner = alternation();
      if (src[i] !== ")" || !inner) return undefined;
      i++;
      return inner;
    }
    if (c === "[") return charClass();
    if (c === ".") {
      i++;
      return () => String.fromCharCode(rng.int(97, 122));
    }
    if (c === "\\") {
      const e = src[i + 1] as string;
      i += 2;
      if (e === "d") return () => String(rng.int(0, 9));
      if (e === "w") return () => String.fromCharCode(rng.int(97, 122));
      if (e === "s") return () => " ";
      // Word boundaries match no characters: emit none, and let the final
      // test against the whole pattern decide.
      if (e === "b" || e === "B") return () => "";
      if (/[A-Za-z]/.test(e)) return undefined; // \p{..}, \A, ...: not cheap
      return () => e;
    }
    i++;
    return () => c as string;
  };

  const sequence = (): Node | undefined => {
    const parts: Node[] = [];
    while (i < src.length && src[i] !== "|" && src[i] !== ")") {
      if (src[i] === "^" || src[i] === "$") {
        i++;
        continue;
      }
      const a = atom();
      if (!a) return undefined;
      let min = 1;
      let max = 1;
      const q = src[i];
      if (q === "?" || q === "*" || q === "+") {
        i++;
        min = q === "+" ? 1 : 0;
        max = q === "?" ? 1 : min + 3;
      } else if (q === "{") {
        const m = /^\{(\d+)(,(\d*))?\}/.exec(src.slice(i));
        if (!m) return undefined;
        i += m[0].length;
        min = Number(m[1]);
        max = m[2] ? (m[3] ? Number(m[3]) : min + 3) : min;
      }
      if (src[i] === "?") i++; // lazy: same strings
      const lo = min;
      const hi = Math.min(max, min + 3);
      parts.push(() => {
        let s = "";
        const count = rng.int(Math.max(lo, 1), Math.max(hi, 1));
        for (let k = 0; k < (lo === 0 && hi === 0 ? 0 : count); k++) s += a();
        return s;
      });
    }
    return () => parts.map((p) => p()).join("");
  };

  const alternation = (): Node | undefined => {
    const branches: Node[] = [];
    for (;;) {
      const s = sequence();
      if (!s) return undefined;
      branches.push(s);
      if (src[i] !== "|") break;
      i++;
    }
    return () => rng.pick(branches)();
  };

  const re = patternRegExp(pattern);
  // An RE2 construct JavaScript does not accept: not cheap.
  if (!re) return undefined;
  try {
    const node = alternation();
    if (!node || i < src.length) return undefined;
    for (let attempt = 0; attempt < 8; attempt++) {
      const s = node();
      if (re2Test(re, s)) return s;
    }
  } catch {
    // A construct the walk above misreads: not cheap.
  }
  return undefined;
}

/** What a `format` rule accepts, as cheap checks of the shapes `formatted` emits and servers accept. */
const IPV4 = /^(25[0-5]|2[0-4]\d|1?\d?\d)(\.(25[0-5]|2[0-4]\d|1?\d?\d)){3}$/;
const IPV6 = /^(?=.*:)[0-9a-f:]{2,39}$/i;
const HOSTNAME =
  /^(?=.{1,253}$)[a-z0-9]([a-z0-9-]{0,61}[a-z0-9])?(\.[a-z0-9]([a-z0-9-]{0,61}[a-z0-9])?)*$/i;
const FORMAT_CHECKS: Record<StrFormat, (s: string) => boolean> = {
  email: (s) => /^[^@\s]+@[^@\s]+\.[^@\s]+$/.test(s),
  uri: (s) => /^[a-z][a-z0-9+.-]*:\S+$/i.test(s),
  hostname: (s) => HOSTNAME.test(s),
  address: (s) => HOSTNAME.test(s) || IPV4.test(s) || IPV6.test(s),
  hostAndPort: (s) => {
    const m = /^(.+):(\d{1,5})$/.exec(s);
    return !!m && HOSTNAME.test(m[1]!) && Number(m[2]) <= 65535;
  },
  ip: (s) => IPV4.test(s) || IPV6.test(s),
  ipv4: (s) => IPV4.test(s),
  ipv6: (s) => IPV6.test(s),
  ipPrefix: (s) => {
    const m = /^(.+)\/(\d{1,3})$/.exec(s);
    return (
      !!m &&
      ((IPV4.test(m[1]!) && Number(m[2]) <= 32) ||
        (IPV6.test(m[1]!) && Number(m[2]) <= 128))
    );
  },
  uuid: (s) =>
    /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i.test(s),
  tuuid: (s) => /^[0-9a-f]{32}$/i.test(s),
  ulid: (s) => /^[0-7][0-9A-HJKMNP-TV-Z]{25}$/.test(s),
};

/** Whether `s` meets every string rule the engine reads. A pattern JavaScript cannot express is never met. */
function satisfiesStr(s: string, r: StrRules): boolean {
  if (r.const !== undefined) return s === r.const;
  if (r.in?.length && !r.in.includes(s)) return false;
  if (r.notIn?.includes(s)) return false;
  const len = [...s].length;
  if (r.len !== undefined && len !== r.len) return false;
  if (r.minLen !== undefined && len < r.minLen) return false;
  if (r.maxLen !== undefined && len > r.maxLen) return false;
  if (r.prefix && !s.startsWith(r.prefix)) return false;
  if (r.suffix && !s.endsWith(r.suffix)) return false;
  if (r.contains && !s.includes(r.contains)) return false;
  if (r.format && !FORMAT_CHECKS[r.format](s)) return false;
  if (r.pattern && !re2Test(patternRegExp(r.pattern), s)) return false;
  return true;
}

/** Exact equality of a value (a bigint for 64-bit integers) and a rule's number. */
const numEq = (v: number | bigint, x: number) =>
  typeof v === "bigint" ? Number.isInteger(x) && v === BigInt(x) : v === x;

/**
 * Whether `v` meets a number's rules; gt above lt is protovalidate's exclusive
 * range (outside the band). A bigint is compared exactly: JavaScript's
 * relational operators order a bigint and a number by their true values.
 */
function satisfiesNum(v: number | bigint, r: NumRules): boolean {
  if (typeof v === "number" && !Number.isFinite(v)) return false;
  if (r.const !== undefined) return numEq(v, r.const);
  if (r.in?.length && !r.in.some((x) => numEq(v, x))) return false;
  if (r.notIn?.some((x) => numEq(v, x))) return false;
  const lo = r.gt ?? r.gte;
  const hi = r.lt ?? r.lte;
  const lowOk =
    (r.gt === undefined || v > r.gt) && (r.gte === undefined || v >= r.gte);
  const highOk =
    (r.lt === undefined || v < r.lt) && (r.lte === undefined || v <= r.lte);
  if (lo !== undefined && hi !== undefined && lo > hi) return lowOk || highOk;
  return lowOk && highOk;
}

/** Whether `v` is one of the enum's values and meets its rules. */
function satisfiesEnum(
  e: DescEnum,
  v: number,
  r: EnumRules | undefined,
): boolean {
  if (!e.values.some((d) => d.number === v)) return false;
  if (!r) return true;
  if (r.const !== undefined && v !== r.const) return false;
  if (r.in?.length && !r.in.includes(v)) return false;
  return !r.notIn?.includes(v);
}

function applyStringRules(
  value: string,
  rules: StrRules,
  rng: Rng,
  n: number,
  where: string,
): string {
  if (rules.const !== undefined) return rules.const;
  if (rules.in?.length) return rng.pick(rules.in);
  let s = value;
  if (rules.format) s = formatted(rules.format, rng, n);
  if (rules.pattern && !re2Test(patternRegExp(rules.pattern), s)) {
    s = fromPattern(rules.pattern, rng) ?? s;
  }
  if (rules.prefix && !s.startsWith(rules.prefix)) s = rules.prefix + s;
  if (rules.suffix && !s.endsWith(rules.suffix)) s = s + rules.suffix;
  if (rules.contains && !s.includes(rules.contains)) s = s + rules.contains;
  if (rules.notIn?.includes(s)) s = `${s}-${n}`;
  const min = rules.len ?? rules.minLen;
  const max = rules.len ?? rules.maxLen;
  const chars = [...s];
  if (max !== undefined && chars.length > max) {
    s = chars.slice(0, max).join("");
  } else if (min !== undefined && chars.length < min) {
    s = s + "x".repeat(min - chars.length);
  }
  if (satisfiesStr(s, rules)) return s;
  // The steps above can undo one another (a pattern's string cut to
  // max_len): look among the pattern's strings for one that meets them all.
  if (rules.pattern) {
    for (let attempt = 0; attempt < 32; attempt++) {
      const candidate = fromPattern(rules.pattern, rng);
      if (candidate === undefined) break;
      if (satisfiesStr(candidate, rules)) return candidate;
    }
  }
  const said = [
    rules.pattern !== undefined && `pattern ${JSON.stringify(rules.pattern)}`,
    rules.format && `format ${rules.format}`,
    rules.len !== undefined && `len ${rules.len}`,
    rules.minLen !== undefined && `min_len ${rules.minLen}`,
    rules.maxLen !== undefined && `max_len ${rules.maxLen}`,
    rules.prefix && `prefix ${JSON.stringify(rules.prefix)}`,
    rules.suffix && `suffix ${JSON.stringify(rules.suffix)}`,
    rules.contains && `contains ${JSON.stringify(rules.contains)}`,
  ].filter(Boolean);
  throw new Error(
    `mock values: ${where} has string rules no generated value satisfies (${said.join(", ")}); ` +
      "answer it from a scenario (mockService) or a mockFactory",
  );
}

// ── Numbers ─────────────────────────────────────────────────────────────

const INT_LIMITS: Partial<Record<ScalarType, [number, number]>> = {
  [ScalarType.INT32]: [-2147483648, 2147483647],
  [ScalarType.SINT32]: [-2147483648, 2147483647],
  [ScalarType.SFIXED32]: [-2147483648, 2147483647],
  [ScalarType.UINT32]: [0, 4294967295],
  [ScalarType.FIXED32]: [0, 4294967295],
  [ScalarType.UINT64]: [0, Number.MAX_SAFE_INTEGER],
  [ScalarType.FIXED64]: [0, Number.MAX_SAFE_INTEGER],
  [ScalarType.INT64]: [-Number.MAX_SAFE_INTEGER, Number.MAX_SAFE_INTEGER],
  [ScalarType.SINT64]: [-Number.MAX_SAFE_INTEGER, Number.MAX_SAFE_INTEGER],
  [ScalarType.SFIXED64]: [-Number.MAX_SAFE_INTEGER, Number.MAX_SAFE_INTEGER],
};

const isFloat = (t: ScalarType) =>
  t === ScalarType.DOUBLE || t === ScalarType.FLOAT;
const is64 = (t: ScalarType) =>
  t === ScalarType.INT64 ||
  t === ScalarType.UINT64 ||
  t === ScalarType.SINT64 ||
  t === ScalarType.FIXED64 ||
  t === ScalarType.SFIXED64;

/** Epoch unit a time-valued integer field is in, from its name. */
function epochUnit(name: string): number | undefined {
  const w = words(name);
  const timeish =
    hasWord(name, "unix", "epoch", "timestamp", "at") ||
    (w[w.length - 1] === "time" && !hasWord(name, "duration", "elapsed")) ||
    (w.includes("time") &&
      hasWord(name, "nano", "nanos", "ns", "ms", "millis"));
  if (!timeish || hasWord(name, "duration", "latency", "elapsed", "took"))
    return undefined;
  if (hasWord(name, "nano", "nanos", "ns")) return 1e6;
  if (hasWord(name, "us", "micros")) return 1e3;
  if (hasWord(name, "ms", "millis")) return 1;
  return 1e-3;
}

/** The range a number's name suggests: [lo, hi]. */
function numberRange(name: string, float: boolean): [number, number] {
  const durationish = hasWord(
    name,
    "duration",
    "latency",
    "elapsed",
    "took",
    "time",
  );
  if (durationish || hasWord(name, "ms", "millis")) {
    if (hasWord(name, "ns", "nanos", "nano")) return [100_000, 2_000_000_000];
    if (hasWord(name, "us", "micros")) return [100, 2_000_000];
    if (hasWord(name, "seconds", "secs", "s", "sec"))
      return float ? [0.01, 5] : [1, 120];
    return [1, 2000];
  }
  if (hasWord(name, "seconds", "secs")) return [1, 3600];
  if (hasWord(name, "percent", "pct", "percentage")) return [0, 100];
  if (
    hasWord(name, "ratio", "fraction", "share", "probability", "rate") &&
    float
  )
    return [0, 1];
  if (hasWord(name, "rate")) return [0, 100];
  if (hasWord(name, "bytes", "size") && !hasWord(name, "page"))
    return [1024, 104_857_600];
  if (hasWord(name, "port")) return [1024, 65535];
  if (hasWord(name, "year")) return [2020, 2026];
  if (hasWord(name, "month")) return [1, 12];
  if (hasWord(name, "day")) return [1, 28];
  if (hasWord(name, "hour")) return [0, 23];
  if (hasWord(name, "minute", "second")) return [0, 59];
  if (hasWord(name, "lat", "latitude")) return [-90, 90];
  if (hasWord(name, "lng", "lon", "longitude")) return [-180, 180];
  if (
    hasWord(
      name,
      "version",
      "revision",
      "generation",
      "attempt",
      "attempts",
      "retry",
      "retries",
      "priority",
      "level",
      "rank",
    )
  ) {
    return [1, 10];
  }
  if (name === "severity_number") return [1, 24];
  if (hasWord(name, "cents", "price", "amount", "cost"))
    return float ? [1, 1000] : [100, 100_000];
  if (
    hasWord(
      name,
      "count",
      "total",
      "num",
      "number",
      "length",
      "requests",
      "errors",
      "hits",
      "calls",
      "events",
      "items",
      "value",
    )
  ) {
    return [0, 1000];
  }
  return float ? [0, 1000] : [1, 100];
}

/** Clamp/choose a number by its rules. `step` is 1 for integers. */
function applyNumRules(
  value: number,
  rules: NumRules | undefined,
  rng: Rng,
  float: boolean,
): number {
  if (!rules) return value;
  if (rules.const !== undefined) return rules.const;
  if (rules.in?.length) return rng.pick(rules.in);
  const eps = float ? 0.01 : 1;
  let lo = -Infinity;
  let hi = Infinity;
  if (rules.gte !== undefined) lo = rules.gte;
  if (rules.gt !== undefined) lo = Math.max(lo, rules.gt + eps);
  if (rules.lte !== undefined) hi = rules.lte;
  if (rules.lt !== undefined) hi = Math.min(hi, rules.lt - eps);
  let v = value;
  // protovalidate allows an exclusive range (gt > lt: outside the band); then
  // either side is valid, and the value already on one side is kept.
  const exclusive = lo > hi;
  if (!exclusive) {
    if (v < lo || v > hi) {
      const width = Number.isFinite(hi - lo) ? hi - lo : 100;
      v =
        lo === -Infinity
          ? hi - rng.next() * Math.min(width, 100)
          : lo + rng.next() * Math.min(width, 100);
    }
    v = Math.min(Math.max(v, lo), hi);
  } else if (v < lo && v > hi) {
    v = lo;
  }
  if (!float) v = Math.round(v);
  if (!float && rules.gt !== undefined && v <= rules.gt) v = rules.gt + 1;
  if (!float && rules.lt !== undefined && v >= rules.lt) v = rules.lt - 1;
  for (let k = 0; rules.notIn?.includes(v) && k < 100; k++) v += eps;
  return v;
}

/** Two decimals, unless rounding would step outside the rules' bounds. */
function roundWithin(v: number, rules: NumRules | undefined): number {
  if (rules?.const !== undefined || rules?.in?.length) return v;
  const r = Math.round(v * 100) / 100;
  const lo = rules?.gt ?? rules?.gte ?? -Infinity;
  const hi = rules?.lt ?? rules?.lte ?? Infinity;
  const inside = r >= lo && r <= hi && r !== rules?.gt && r !== rules?.lt;
  return inside ? r : v;
}

// ── The walk ────────────────────────────────────────────────────────────

interface Ctx {
  seed: string;
  path: string;
  /** Position in the nearest enclosing list, or -1. */
  index: number;
  depth: number;
  maxDepth: number;
  now: number;
  /** Time the current message's own timestamps are anchored at. */
  baseTime: number;
  stack: readonly string[];
  echo: ReadonlyMap<string, Echo>;
  /** The request's selected oneof cases: oneof name → member field name. */
  cases: ReadonlyMap<string, string>;
  factories: ReadonlyMap<string, MockFactory<DescMessage>>;
}

interface Echo {
  value: unknown;
  scalar?: ScalarType;
  enumType?: string;
}

const rngAt = (ctx: Ctx, key: string) =>
  new Rng(`${ctx.seed}|${ctx.path}.${key}`);

/** The number list items are labelled with: their position, else a small stable one. */
const ordinal = (ctx: Ctx, rng: Rng) =>
  ctx.index >= 0 ? ctx.index + 1 : rng.int(1, 9);

/** Schemas the engine has walked, so `patch` can rebuild a nested message. */
const knownSchemas = new Map<string, DescMessage>();

function collectEcho(
  schema: DescMessage,
  message: Message,
): { echo: Map<string, Echo>; cases: Map<string, string> } {
  const out = new Map<string, Echo>();
  const cases = new Map<string, string>();
  const walk = (
    desc: DescMessage,
    msg: Record<string, unknown>,
    depth: number,
  ) => {
    for (const f of desc.fields) {
      let v: unknown;
      if (f.oneof) {
        // A oneof member is echoed only when it is the selected case.
        const selected = msg[f.oneof.localName] as
          | { case?: string; value?: unknown }
          | undefined;
        if (selected?.case !== f.localName) continue;
        if (!cases.has(f.oneof.name)) cases.set(f.oneof.name, f.name);
        v = selected.value;
      } else {
        v = msg[f.localName];
      }
      if (v == null) continue;
      if (f.fieldKind === "scalar") {
        if (f.scalar === ScalarType.BOOL || f.scalar === ScalarType.BYTES)
          continue;
        if (v === "" || v === 0 || v === 0n || CONTROL_FIELDS.has(f.name))
          continue;
        if (!out.has(f.name)) out.set(f.name, { value: v, scalar: f.scalar });
      } else if (f.fieldKind === "enum") {
        if (v === 0) continue;
        if (!out.has(f.name))
          out.set(f.name, { value: v, enumType: f.enum.typeName });
      } else if (f.fieldKind === "message" && depth < 2 && isMessage(v)) {
        walk(f.message, v as unknown as Record<string, unknown>, depth + 1);
      }
    }
  };
  walk(schema, message as unknown as Record<string, unknown>, 0);
  return { echo: out, cases };
}

function echoFor(
  ctx: Ctx,
  name: string,
  scalar?: ScalarType,
  enumType?: string,
): Echo | undefined {
  // A bare `id` is the record's own key: echo it only on the answer's top
  // record, never on list items or nested records (they would all collide).
  if (name === "id" && (ctx.index >= 0 || ctx.depth > 1)) return undefined;
  if (CONTROL_FIELDS.has(name)) return undefined;
  const e = ctx.echo.get(name);
  if (!e) return undefined;
  if (scalar !== undefined && e.scalar !== scalar) {
    // Same family is good enough: an int32 filter echoes into an int64 field.
    const fam = (t: ScalarType | undefined) =>
      t === undefined
        ? "?"
        : t === ScalarType.STRING
          ? "s"
          : isFloat(t)
            ? "f"
            : "i";
    if (fam(e.scalar) !== fam(scalar)) return undefined;
  }
  if (enumType !== undefined && e.enumType !== enumType) return undefined;
  return e;
}

function scalarValue(
  scalar: ScalarType,
  name: string,
  owner: DescMessage,
  rules: FieldRules | undefined,
  ctx: Ctx,
  longAsString: boolean,
): unknown {
  const rng = rngAt(ctx, name);
  const n = ordinal(ctx, rng);
  const echo = echoFor(ctx, name, scalar);
  if (echo) {
    const v = coerceScalar(scalar, echo.value, longAsString);
    if (echoMeetsRules(scalar, v, rules)) return v;
  }

  switch (scalar) {
    case ScalarType.STRING: {
      const s = stringByName(name, owner, n, rng, ctx.index >= 0);
      return rules?.str
        ? applyStringRules(s, rules.str, rng, n, `${owner.typeName}.${name}`)
        : s;
    }
    case ScalarType.BOOL: {
      if (rules?.bool !== undefined) return rules.bool;
      const likely = hasWord(
        name,
        "enabled",
        "active",
        "healthy",
        "success",
        "ok",
        "valid",
        "available",
        "ready",
        "visible",
        "verified",
        "public",
      );
      const rare = hasWord(
        name,
        "deleted",
        "disabled",
        "failed",
        "error",
        "errors",
        "truncated",
        "partial",
        "archived",
        "hidden",
        "locked",
        "null",
        "unknown",
        "expired",
        "revoked",
        "blocked",
        "provisional",
        "only",
      );
      return rng.next() < (likely ? 0.85 : rare ? 0.15 : 0.5);
    }
    case ScalarType.BYTES: {
      const len = bytesLength(owner, name, rules?.bytes);
      const out = new Uint8Array(len);
      for (let k = 0; k < len; k++) out[k] = rng.int(0, 255);
      return out;
    }
    default: {
      const float = isFloat(scalar);
      const unit = float ? undefined : epochUnit(name);
      let v: number;
      if (unit !== undefined && is64(scalar)) {
        // Epoch values: exact, so they are generated in bigint space.
        const ms = ctx.baseTime - rng.int(0, 30_000);
        const big =
          unit >= 1 ? BigInt(ms) * BigInt(unit) : BigInt(Math.floor(ms / 1000));
        return longAsString ? big.toString() : big;
      } else if (unit !== undefined) {
        v = Math.floor((ctx.baseTime - rng.int(0, 30_000)) / 1000);
      } else {
        const [lo, hi] = numberRange(name, float);
        v = float
          ? Math.round((lo + rng.next() * (hi - lo)) * 100) / 100
          : rng.int(lo, hi);
      }
      v = applyNumRules(v, rules?.num, rng, float);
      if (float) v = roundWithin(v, rules?.num);
      const limits = INT_LIMITS[scalar];
      if (limits) v = Math.min(Math.max(Math.round(v), limits[0]), limits[1]);
      return coerceScalar(scalar, v, longAsString);
    }
  }
}

/**
 * Length of a generated bytes value: 16 unless the rules say otherwise.
 * Bounds no value can satisfy throw, naming the field, rather than emit a
 * value the server's protovalidate would reject.
 */
function bytesLength(
  owner: DescMessage,
  name: string,
  b: FieldRules["bytes"],
): number {
  const min = Math.max(b?.len ?? 0, b?.minLen ?? 0);
  const max = Math.min(b?.len ?? Infinity, b?.maxLen ?? Infinity);
  if (min > max)
    throw new Error(
      `mock values: ${owner.typeName}.${name} has bytes rules no value satisfies ` +
        `(len ${b?.len ?? "-"}, min_len ${b?.minLen ?? "-"}, max_len ${b?.maxLen ?? "-"})`,
    );
  return Math.min(Math.max(16, min), max);
}

/** Whether an echoed request value may stand in the response: it fits the field's type and meets its rules. */
function echoMeetsRules(
  scalar: ScalarType,
  v: unknown,
  rules: FieldRules | undefined,
): boolean {
  if (scalar === ScalarType.STRING) {
    return !rules?.str || satisfiesStr(String(v), rules.str);
  }
  let num: number | bigint;
  if (is64(scalar)) {
    // Exact: a 64-bit value past 2^53 keeps every digit, and is checked
    // against the field type's own range, not JavaScript's safe one.
    const big = exactBigInt(v);
    const range = INT64_RANGE[scalar];
    if (big === undefined || !range || big < range[0] || big > range[1])
      return false;
    num = big;
  } else {
    if (typeof v !== "number" || !Number.isFinite(v)) return false;
    const limits = INT_LIMITS[scalar];
    if (limits && (!Number.isInteger(v) || v < limits[0] || v > limits[1]))
      return false;
    // A float field holds 32 bits: a double it cannot represent would reach
    // the client rounded, a different value from the one checked here.
    if (scalar === ScalarType.FLOAT && Math.fround(v) !== v) return false;
    num = v;
  }
  return !rules?.num || satisfiesNum(num, rules.num);
}

/** The protobuf range of each 64-bit integer type. */
const INT64_RANGE: Partial<Record<ScalarType, [bigint, bigint]>> = {
  [ScalarType.INT64]: [-(2n ** 63n), 2n ** 63n - 1n],
  [ScalarType.SINT64]: [-(2n ** 63n), 2n ** 63n - 1n],
  [ScalarType.SFIXED64]: [-(2n ** 63n), 2n ** 63n - 1n],
  [ScalarType.UINT64]: [0n, 2n ** 64n - 1n],
  [ScalarType.FIXED64]: [0n, 2n ** 64n - 1n],
};

/** `v` as a bigint without rounding, or undefined when it is not an integer. */
function exactBigInt(v: unknown): bigint | undefined {
  if (typeof v === "bigint") return v;
  if (typeof v === "string" && /^-?\d+$/.test(v)) return BigInt(v);
  if (typeof v === "number" && Number.isSafeInteger(v)) return BigInt(v);
  return undefined;
}

function coerceScalar(
  scalar: ScalarType,
  v: unknown,
  longAsString: boolean,
): unknown {
  if (is64(scalar)) {
    const big = exactBigInt(v) ?? BigInt(Math.round(Number(v)));
    return longAsString ? big.toString() : big;
  }
  if (scalar === ScalarType.STRING) return String(v);
  if (typeof v === "bigint" || typeof v === "string") return Number(v);
  return v;
}

function enumValue(
  e: DescEnum,
  name: string,
  owner: DescMessage,
  rules: FieldRules | undefined,
  ctx: Ctx,
): number {
  const echo = echoFor(ctx, name, undefined, e.typeName);
  if (echo && satisfiesEnum(e, echo.value as number, rules?.enm))
    return echo.value as number;
  const r = rules?.enm;
  // Every candidate is a declared value that meets every rule, const included.
  let values = e.values
    .map((v) => v.number)
    .filter((v) => satisfiesEnum(e, v, r));
  if (values.length === 0) {
    const said = [
      r?.const !== undefined && `const ${r.const}`,
      r?.in?.length && `in [${r.in.join(", ")}]`,
      r?.notIn?.length && `not_in [${r.notIn.join(", ")}]`,
    ].filter(Boolean);
    throw new Error(
      `mock values: ${owner.typeName}.${name} (${e.typeName}) has enum rules no declared value satisfies ` +
        `(${said.join(", ")}); answer it from a scenario (mockService) or a mockFactory`,
    );
  }
  // Skip the proto3 zero ("UNSPECIFIED") when anything else is allowed.
  if (values.length > 1) values = values.filter((v) => v !== 0);
  // Cycle across a list: item i takes value (offset + i), so a list of n
  // items shows every value once before any repeats.
  const offset = new Rng(
    `${ctx.seed}|${ctx.path.replace(/\[\d+\]/g, "")}.${name}`,
  ).int(0, values.length - 1);
  const i = ctx.index >= 0 ? ctx.index : 0;
  return values[(offset + i) % values.length] as number;
}

/** Recent instant for a Timestamp field, respecting start/end order and rules. */
function timestampMs(
  name: string,
  rules: FieldRules | undefined,
  ctx: Ctx,
): number {
  const rng = rngAt(ctx, name);
  let ms: number;
  if (
    hasWord(
      name,
      "end",
      "ended",
      "finish",
      "finished",
      "completed",
      "updated",
      "last",
      "stop",
      "stopped",
      "until",
      "to",
      "modified",
      "resolved",
      "closed",
    )
  ) {
    ms = ctx.baseTime;
  } else if (
    hasWord(
      name,
      "start",
      "started",
      "created",
      "first",
      "since",
      "from",
      "begin",
      "opened",
      "submitted",
    )
  ) {
    ms = ctx.baseTime - rng.int(1_000, 120_000);
  } else if (
    hasWord(
      name,
      "expires",
      "expiry",
      "expiration",
      "deadline",
      "due",
      "next",
      "scheduled",
    )
  ) {
    ms = ctx.now + rng.int(3_600_000, 7 * 86_400_000);
  } else {
    ms = ctx.baseTime - rng.int(0, 30_000);
  }
  const t = rules?.timestamp;
  if (t) {
    if (t.const !== undefined) return t.const;
    if (t.gtNow) ms = Math.max(ms, ctx.now + rng.int(60_000, 86_400_000));
    if (t.ltNow) ms = Math.min(ms, ctx.now - 1_000);
    if (t.withinMs !== undefined)
      ms = Math.min(
        Math.max(ms, ctx.now - t.withinMs + 1_000),
        ctx.now + t.withinMs - 1_000,
      );
    ms = applyNumRules(ms, t, rng, false);
  }
  return ms;
}

function timestampInit(ms: number) {
  const seconds = Math.floor(ms / 1000);
  return { seconds: BigInt(seconds), nanos: (ms - seconds * 1000) * 1_000_000 };
}

function durationInit(name: string, rules: FieldRules | undefined, ctx: Ctx) {
  const rng = rngAt(ctx, name);
  let seconds = hasWord(
    name,
    "timeout",
    "ttl",
    "interval",
    "period",
    "window",
    "retention",
    "expiry",
    "max",
    "age",
  )
    ? rng.int(30, 3600)
    : Math.round((0.005 + rng.next() * 5) * 1000) / 1000;
  seconds = applyNumRules(seconds, rules?.duration, rng, true);
  const ms = Math.round(seconds * 1000) / 1000;
  const d = rules?.duration;
  if (
    (d?.gt === undefined || ms > d.gt) &&
    (d?.gte === undefined || ms >= d.gte) &&
    (d?.lt === undefined || ms < d.lt) &&
    (d?.lte === undefined || ms <= d.lte)
  ) {
    seconds = ms;
  }
  const whole = Math.floor(seconds);
  return { seconds: BigInt(whole), nanos: Math.round((seconds - whole) * 1e9) };
}

function jsonObject(name: string, ctx: Ctx): JsonObject {
  const rng = rngAt(ctx, name);
  const out: JsonObject = {};
  const stem = kebab(name).replace(/s$/, "") || "key";
  const count = rng.int(2, 4);
  for (let k = 1; k <= count; k++) out[`${stem}-${k}`] = `value-${k}`;
  return out;
}

const WKT_TIMESTAMP = "google.protobuf.Timestamp";
const WKT_DURATION = "google.protobuf.Duration";
const WKT_STRUCT = "google.protobuf.Struct";
const WKT_VALUE = "google.protobuf.Value";
const WKT_LIST_VALUE = "google.protobuf.ListValue";
const WRAPPERS = new Set([
  "google.protobuf.DoubleValue",
  "google.protobuf.FloatValue",
  "google.protobuf.Int64Value",
  "google.protobuf.UInt64Value",
  "google.protobuf.Int32Value",
  "google.protobuf.UInt32Value",
  "google.protobuf.BoolValue",
  "google.protobuf.StringValue",
  "google.protobuf.BytesValue",
]);
const LEAVE_UNSET = new Set([
  "google.protobuf.Any",
  "google.protobuf.FieldMask",
  "google.protobuf.Empty",
]);

/**
 * The init value for one message-typed position. `unboxed` is true where
 * protobuf-es represents a wrapper as its primitive and a Struct as a
 * JsonObject (a singular field outside a oneof; Struct in lists too).
 */
function messageAt(
  msg: DescMessage,
  name: string,
  owner: DescMessage,
  rules: FieldRules | undefined,
  ctx: Ctx,
  unboxed: boolean,
): unknown {
  switch (msg.typeName) {
    case WKT_TIMESTAMP:
      return timestampInit(timestampMs(name, rules, ctx));
    case WKT_DURATION:
      return durationInit(name, rules, ctx);
    case WKT_STRUCT:
      return unboxed ? jsonObject(name, ctx) : undefined;
    case WKT_VALUE:
      return {
        kind: {
          case: "stringValue",
          value: `${kebab(name)}-${ordinal(ctx, rngAt(ctx, name))}`,
        },
      };
    case WKT_LIST_VALUE:
      return {
        values: [1, 2, 3].map((k) => ({
          kind: { case: "stringValue", value: `${kebab(name)}-${k}` },
        })),
      };
  }
  if (WRAPPERS.has(msg.typeName)) {
    const inner = msg.fields[0];
    if (!inner || inner.fieldKind !== "scalar") return undefined;
    const v = scalarValue(
      inner.scalar,
      name,
      owner,
      rules,
      ctx,
      inner.longAsString,
    );
    return unboxed ? v : { value: v };
  }
  if (LEAVE_UNSET.has(msg.typeName)) return undefined;
  // Depth and recursion guards: a self-referencing type nests once.
  if (ctx.depth >= ctx.maxDepth) return undefined;
  if (ctx.stack.filter((t) => t === msg.typeName).length >= 2) return undefined;
  return buildMessage(msg, ctx);
}

function singular(
  field: DescField,
  owner: DescMessage,
  rules: FieldRules | undefined,
  ctx: Ctx,
  index: number,
  unboxed: boolean,
): unknown {
  // A list item or map value is generated at its own path, so items differ.
  const at: Ctx =
    index >= 0 ? { ...ctx, index, path: `${ctx.path}[${index}]` } : ctx;
  const f = field as {
    scalar?: ScalarType;
    enum?: DescEnum;
    message?: DescMessage;
    longAsString?: boolean;
  };
  const kind =
    field.fieldKind === "list"
      ? field.listKind
      : field.fieldKind === "map"
        ? field.mapKind
        : field.fieldKind;
  switch (kind) {
    case "scalar":
      return scalarValue(
        f.scalar as ScalarType,
        field.name,
        owner,
        rules,
        at,
        f.longAsString ?? false,
      );
    case "enum":
      return enumValue(f.enum as DescEnum, field.name, owner, rules, at);
    default: {
      const msg = f.message as DescMessage;
      const c: Ctx = {
        ...at,
        path: `${at.path}.${field.name}`,
        depth: ctx.depth + 1,
        stack: [...ctx.stack, msg.typeName],
      };
      return messageAt(msg, field.name, owner, rules, c, unboxed);
    }
  }
}

function listCount(
  rules: FieldRules | undefined,
  ctx: Ctx,
  name: string,
  fallbackMax: number,
): number {
  const rng = rngAt(ctx, `${name}#count`);
  const r = rules?.repeated;
  const min = r?.minItems ?? 0;
  const max = r?.maxItems ?? Infinity;
  // Past half the depth budget lists shrink to their minimum, so a deep tree
  // of repeated messages stays a few hundred values rather than thousands.
  if (ctx.depth * 2 > ctx.maxDepth) return min;
  const n = rng.int(3, fallbackMax);
  return Math.max(min, Math.min(max, n));
}

function buildMessage(desc: DescMessage, ctx: Ctx): MessageShape<DescMessage> {
  knownSchemas.set(desc.typeName, desc);
  const rng = rngAt(ctx, "#time");
  // Newest first across a list: item i sits ~i·4 minutes before the anchor.
  const baseTime =
    ctx.index >= 0
      ? ctx.now - ctx.index * 240_000 - rng.int(0, 120_000)
      : ctx.now - rng.int(0, 3_600_000);
  const here: Ctx = { ...ctx, baseTime };
  const init: Record<string, unknown> = {};

  for (const member of desc.members) {
    if (member.kind === "oneof") {
      const fields = member.fields;
      if (fields.length === 0) continue;
      // The case the request selected, when this oneof has a member of that
      // name; otherwise one chosen by the seed.
      const requested = here.cases.get(member.name);
      const pick =
        (requested !== undefined
          ? fields.find((f) => f.name === requested)
          : undefined) ??
        (fields[
          rngAt(here, `${member.name}#case`).int(0, fields.length - 1)
        ] as DescField);
      const value = singular(pick, desc, rulesOf(pick), here, -1, false);
      if (value !== undefined)
        init[member.localName] = { case: pick.localName, value };
      continue;
    }
    const field = member;
    const rules = rulesOf(field);
    if (field.fieldKind === "list") {
      const count = listCount(rules, here, field.name, 10);
      const itemRules = rules?.repeated?.items;
      const items: unknown[] = [];
      for (let i = 0; i < count; i++) {
        const v = singular(
          field,
          desc,
          itemRules,
          here,
          i,
          field.listKind === "message" && field.message.typeName === WKT_STRUCT,
        );
        if (v !== undefined) items.push(v);
      }
      init[field.localName] = items;
    } else if (field.fieldKind === "map") {
      const r = rules?.map;
      const mrng = rngAt(here, `${field.name}#pairs`);
      let count = mrng.int(3, 5);
      if (here.depth * 2 > here.maxDepth) count = 0;
      count = Math.max(
        r?.minPairs ?? 0,
        Math.min(r?.maxPairs ?? Infinity, count),
      );
      const out: Record<string, unknown> = {};
      const stem = kebab(field.name).replace(/s$/, "") || "key";
      for (let i = 0; i < count; i++) {
        let key: string;
        if (field.mapKey === ScalarType.STRING) {
          key = `${stem}-${i + 1}`;
          if (r?.keys?.str)
            key = applyStringRules(
              key,
              r.keys.str,
              mrng,
              i + 1,
              `${desc.typeName}.${field.name} (map key)`,
            );
        } else if (field.mapKey === ScalarType.BOOL) {
          if (i > 1) break;
          key = String(i === 0);
        } else {
          key = String(applyNumRules(i + 1, r?.keys?.num, mrng, false));
        }
        const at: Ctx = { ...here, path: `${here.path}.${field.name}{${key}}` };
        const v =
          field.mapKind === "scalar" && field.scalar === ScalarType.STRING
            ? applyStringRules(
                `value-${i + 1}`,
                r?.values?.str ?? {},
                rngAt(at, "value"),
                i + 1,
                `${desc.typeName}.${field.name} (map value)`,
              )
            : singular(field, desc, r?.values, at, i, false);
        if (v !== undefined) out[key] = v;
      }
      init[field.localName] = out;
    } else {
      const v = singular(
        field,
        desc,
        rules,
        here,
        -1,
        field.fieldKind === "message",
      );
      if (v !== undefined) init[field.localName] = v;
    }
  }

  // A count beside the one list it counts reads as that list's length.
  const lists = desc.fields.filter(
    (f) => f.fieldKind === "list" && f.listKind === "message",
  );
  if (lists.length === 1) {
    const total = desc.fields.find(
      (f) =>
        f.fieldKind === "scalar" &&
        ["total_count", "total_size", "total", "total_items"].includes(f.name),
    );
    if (total && total.fieldKind === "scalar") {
      const len = (init[(lists[0] as DescField).localName] as unknown[]).length;
      init[total.localName] = coerceScalar(
        total.scalar,
        len,
        total.longAsString,
      );
    }
  }

  let message = create(desc, init as MessageInitShape<DescMessage>);
  const factory = ctx.factories.get(desc.typeName);
  if (factory) {
    const result = factory.build({
      base: message,
      index: ctx.index,
      seed: `${ctx.seed}|${ctx.path}`,
    });
    message = isMessage(result)
      ? (result as MessageShape<DescMessage>)
      : patch(message, result as PatchShape<Message>);
  }
  return message;
}

/**
 * One deterministic, schema-valid message of `schema` — see the header for
 * what each field becomes. Same options, same message.
 */
export function mockValue<Desc extends DescMessage>(
  schema: Desc,
  options: MockValueOptions = {},
): MessageShape<Desc> {
  return buildValue(schema, options);
}

/** mockValue, echoing `echo`'s scalar fields (the default handlers pass the request). */
function buildValue<Desc extends DescMessage>(
  schema: Desc,
  options: MockValueOptions,
  echo?: { schema: DescMessage; message: Message },
): MessageShape<Desc> {
  const now = anchorMs(options.now);
  const ctx: Ctx = {
    seed: options.seed ?? schema.typeName,
    path: "",
    index: -1,
    depth: 0,
    maxDepth: options.maxDepth ?? 6,
    now,
    baseTime: now,
    stack: [schema.typeName],
    ...(echo
      ? collectEcho(echo.schema, echo.message)
      : { echo: new Map(), cases: new Map() }),
    factories: new Map(
      (options.factories ?? []).map((f) => [f.schema.typeName, f]),
    ),
  };
  return buildMessage(schema, ctx) as MessageShape<Desc>;
}

function knownSchemaOf(message: Message): DescMessage | undefined {
  return knownSchemas.get(message.$typeName);
}

// ── patch ───────────────────────────────────────────────────────────────

type PatchValue<V> = V extends Message
  ? PatchShape<V> | V
  : V extends readonly (infer E)[]
    ? E extends Message
      ? readonly (E | PatchShape<E>)[]
      : V
    : V;

/** A deep partial of a message: nested messages merge, lists and maps replace. */
export type PatchShape<T extends Message> = {
  [K in Exclude<keyof T, "$typeName" | "$unknown">]?: PatchValue<T[K]>;
};

function isPlainObject(v: unknown): v is Record<string, unknown> {
  return (
    typeof v === "object" &&
    v !== null &&
    !Array.isArray(v) &&
    !(v instanceof Uint8Array) &&
    !isMessage(v)
  );
}

/**
 * Deep-merge `changes` onto `base` and return a NEW message (base is not
 * mutated). A nested message merges field by field; a list, a map, a oneof
 * and a scalar are replaced. Partial list items are completed with zero
 * values, as `create()` would.
 *
 *   const res = defaults.listTraces(req);
 *   return patch(res, { traces: res.traces.slice(0, 2), red: { errorRate: 0.5 } });
 */
export function patch<T extends Message>(base: T, changes: PatchShape<T>): T {
  const desc = knownSchemaOf(base);
  const merged = mergeInit(
    desc,
    base as unknown as Record<string, unknown>,
    changes as Record<string, unknown>,
  );
  return (desc ? rebuild(desc, merged) : merged) as unknown as T;
}

/**
 * create() over a merged init. The init still carries the base's $typeName,
 * and create() returns anything that looks like a message untouched — which
 * would leave a partial list item uncompleted — so the marker is dropped.
 */
function rebuild(desc: DescMessage, init: Record<string, unknown>): Message {
  const { $typeName: _drop, ...fields } = init;
  return create(desc, fields as MessageInitShape<DescMessage>);
}

function mergeInit(
  desc: DescMessage | undefined,
  base: Record<string, unknown>,
  changes: Record<string, unknown>,
): Record<string, unknown> {
  const out: Record<string, unknown> = { ...base };
  for (const [key, value] of Object.entries(changes)) {
    if (value === undefined) continue;
    const field = desc?.fields.find((f) => f.localName === key);
    const current = base[key];
    if (
      isPlainObject(value) &&
      isMessage(current) &&
      (!field || (field.fieldKind === "message" && !field.oneof))
    ) {
      const nested =
        field?.fieldKind === "message" ? field.message : knownSchemaOf(current);
      const m = mergeInit(
        nested,
        current as unknown as Record<string, unknown>,
        value,
      );
      out[key] = nested ? rebuild(nested, m) : m;
    } else {
      out[key] = value;
    }
  }
  return out;
}

// ── Services ────────────────────────────────────────────────────────────

type MethodsOf<S extends DescService> = S["method"];
type InputOf<M> = M extends { input: infer I extends DescMessage }
  ? I
  : DescMessage;
type OutputOf<M> = M extends { output: infer O extends DescMessage }
  ? O
  : DescMessage;
type Streams<M> = M extends {
  methodKind: "server_streaming" | "bidi_streaming";
}
  ? true
  : false;

/** A request as a default handler accepts it: the message, an init shape, or nothing. */
export type MockRequest<M> =
  | MessageShape<InputOf<M>>
  | MessageInitShape<InputOf<M>>;

/** One RPC's default: a response, or — for a server or bidi stream — a short stream of them. */
export type DefaultHandler<M> =
  Streams<M> extends true
    ? (
        req?: MockRequest<M> | readonly MockRequest<M>[],
      ) => MessageShape<OutputOf<M>>[]
    : (
        req?: MockRequest<M> | readonly MockRequest<M>[],
      ) => MessageShape<OutputOf<M>>;

/**
 * Every RPC of a service, answered from its descriptor. `$service` names the
 * service (non-enumerable, so the object spreads as its handlers alone).
 */
export type ServiceDefaults<S extends DescService = DescService> = {
  readonly [K in keyof MethodsOf<S>]: DefaultHandler<MethodsOf<S>[K]>;
} & { readonly $service: S };

/** Messages in a default stream. */
const STREAM_LENGTH = 3;

const defaultsCache = new WeakMap<DescService, ServiceDefaults>();

function requestMessage(method: DescMethod, req: unknown): Message {
  return isMessage(req)
    ? req
    : create(method.input, (req ?? {}) as MessageInitShape<DescMessage>);
}

/** The seed of one call: the method plus the request's wire bytes. */
function callSeed(method: DescMethod, reqs: readonly Message[]): string {
  let digest = "";
  for (const r of reqs) {
    try {
      digest += fnv1a(toBinary(method.input, r)).toString(16) + ".";
    } catch {
      digest += "?.";
    }
  }
  return `${method.parent.typeName}/${method.name}:${digest}`;
}

/**
 * The default handlers of every RPC of `service`: a deterministic,
 * schema-valid response per request (a 3-message stream for server and bidi
 * streams). Generated `src/mocks/services/*_gen.ts` modules export one per
 * service, and the mock transport serves them for any RPC that no scenario,
 * passthrough or entity fixture answered.
 *
 * Without options the result is memoized per service, so every caller shares
 * one object.
 */
export function serviceDefaults<S extends DescService>(
  service: S,
  options: Omit<MockValueOptions, "seed"> = {},
): ServiceDefaults<S> {
  const plain =
    options.now === undefined &&
    options.maxDepth === undefined &&
    !options.factories?.length;
  if (plain) {
    const cached = defaultsCache.get(service);
    if (cached) return cached as unknown as ServiceDefaults<S>;
  }
  const out: Record<string, unknown> = {};
  for (const method of service.methods) {
    const streams =
      method.methodKind === "server_streaming" ||
      method.methodKind === "bidi_streaming";
    out[method.localName] = (req?: unknown) => {
      const reqs = (Array.isArray(req) ? req : [req]).map((r) =>
        requestMessage(method, r),
      );
      const seed = callSeed(method, reqs);
      const last = reqs[reqs.length - 1];
      const echo = last ? { schema: method.input, message: last } : undefined;
      const one = (s: string) =>
        buildValue(method.output, { ...options, seed: s }, echo);
      if (!streams) return one(seed);
      return Array.from({ length: STREAM_LENGTH }, (_, i) =>
        one(`${seed}#${i}`),
      );
    };
  }
  Object.defineProperty(out, "$service", { value: service, enumerable: false });
  const defaults = out as unknown as ServiceDefaults<S>;
  if (plain) defaultsCache.set(service, defaults as unknown as ServiceDefaults);
  return defaults;
}

/**
 * Any service's defaults, as the transport and the generated registry hold
 * them: a list of ServiceDefaults<S> for different S has only `$service` in
 * common (their handlers' request types differ).
 */
export interface AnyServiceDefaults {
  readonly $service: DescService;
}

/** True for what {@link serviceDefaults} returns — how the generated registry finds them. */
export function isServiceDefaults(value: unknown): value is AnyServiceDefaults {
  if (typeof value !== "object" || value === null) return false;
  const service = (value as { $service?: { kind?: unknown } }).$service;
  return (
    typeof service === "object" &&
    service !== null &&
    service.kind === "service"
  );
}

type Awaitable<T> = T | Promise<T>;

/** One RPC's override: handed the typed request and the service's defaults. */
export type MockOverride<S extends DescService, M> =
  Streams<M> extends true
    ? (
        req: MessageShape<InputOf<M>>,
        defaults: ServiceDefaults<S>,
      ) =>
        | Awaitable<Iterable<MockResult<OutputOf<M>>>>
        | AsyncIterable<MockResult<OutputOf<M>>>
    : (
        req: MessageShape<InputOf<M>>,
        defaults: ServiceDefaults<S>,
      ) => Awaitable<MockResult<OutputOf<M>>>;

export type MockOverrides<S extends DescService> = {
  readonly [K in keyof MethodsOf<S>]?: MockOverride<S, MethodsOf<S>[K]>;
};

/**
 * Scenario handlers, keyed `${serviceTypeName}/${methodName}` — spread into a
 * scenario's `handlers`, or a test's `mockTransport({...})`. The handlers'
 * request parameter is typed by the override that produced them; the map's
 * own type stays open so it spreads into any handler table.
 */
export type MockHandlers = Record<string, (req: any) => any>;

/**
 * Typed overrides for one service, as scenario handlers:
 *
 *   handlers: {
 *     ...mockService(ObservabilityService, {
 *       listTraces: (req, d) => patch(d.listTraces(req), { traces: [] }),
 *     }),
 *   }
 *
 * Each override receives the typed request and the service's defaults (built
 * with `options.factories` when given). Only overridden RPCs get a handler —
 * the rest fall through to the transport's own defaults — unless factories
 * are given, in which case every RPC is answered with them.
 */
export function mockService<S extends DescService>(
  service: S,
  overrides: MockOverrides<S>,
  options: Omit<MockValueOptions, "seed"> = {},
): MockHandlers {
  const defaults = serviceDefaults(service, options);
  const out: MockHandlers = {};
  const everyMethod = (options.factories?.length ?? 0) > 0;
  for (const method of service.methods) {
    const override = (
      overrides as Record<
        string,
        ((req: unknown, d: unknown) => unknown) | undefined
      >
    )[method.localName];
    const fallback = (
      defaults as unknown as Record<string, (req: unknown) => unknown>
    )[method.localName];
    if (!override && !everyMethod) continue;
    out[`${service.typeName}/${method.name}`] = override
      ? (req: unknown) => override(requestMessage(method, req), defaults)
      : (req: unknown) => fallback?.(req);
  }
  return out;
}
