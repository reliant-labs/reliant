// Part of @reliantlabs/forge-web-runtime — the web twin of forge/pkg.
//
// Default mock responses for ANY Connect service, built from its descriptor.
//
// The entity fixtures (mock-transport.ts) serve generated CRUD only: every
// other RPC — a dashboard read, a search, a stream — used to need a
// hand-written scenario handler before a mocked page rendered anything at
// all. This module answers every RPC of every service with a deterministic,
// schema-valid message, so a scenario writes only what it wants to SAY, not
// the shape of the whole response:
//
//   serviceDefaults(Service)      every RPC's default handler (the generated
//                                 src/mocks/services/*_gen.ts call this)
//   mockService(Service, {...})   typed per-RPC overrides for a scenario,
//                                 each handed the defaults to start from
//   patch(message, {...})         deep-merge a change onto a default
//   mockValue(Schema)             one message, for a test or a factory
//
// Values are built at RUNTIME from the descriptor, not emitted as literals.
// protoc-gen-es embeds every file's FileDescriptorProto — options included —
// in its `_pb.ts`, so the protovalidate rules (min/max, len, pattern, `in`,
// formats) are read off `field.proto.options` (mock-rules.ts), with no buf.validate
// TypeScript in the app and no per-project codegen beyond one import per
// service. A vendored contract (another repo's protos, generated by its own
// buf template) works the same as the project's own.
//
// What a value is, by field (the field's NAME is a hint, never vocabulary —
// forge does not invent a domain the schema does not declare):
//
//   `id` / `*_id`        a stable id: `<thing>-<8 hex>`; `trace_id` and
//                        `span_id` are 32/16 hex, as OpenTelemetry's are
//   Timestamp, `*_at`    recent times; list items newest first; within one
//                        message, `start*`/`created*` precede `end*`/`updated*`
//   `email`, `url`, ...  example.com addresses and links
//   `name`, `title`      "<Message> <n>", numbered by list position
//   other strings        "<field>-<n>"
//   numbers              a range the name suggests (`*_ms`, `count`, `port`,
//                        `percent`, `*_bytes`, ...), else 1..100
//   enums                cycle through the defined values (skipping the
//                        zero UNSPECIFIED) across a list's items
//   repeated             3–10 items; maps 3–5 entries
//   oneof                one member, chosen by the seed
//   Duration, Struct, Value, wrappers   handled as their JSON forms suggest
//   `next_page_token`    always "" — a mock that pages forever is a bug
//
// Then the field's protovalidate rules constrain it: `const` and `in` win,
// numbers are clamped into gt/gte/lt/lte, strings meet len/min_len/max_len,
// prefix/suffix/contains, the well-known formats (email, uri, uuid, hostname,
// ip, ulid) and, where it is cheap, `pattern`. Repeated and map sizes honour
// min_items/max_items and min_pairs/max_pairs. CEL rules are not evaluated.
//
// Determinism: every value is a function of (seed, field path). The seed of a
// default handler is the method plus the request's wire bytes, so the same
// request always gets the same answer, and a field added to a message does not
// reshuffle the others. Scalar fields that the REQUEST also carries (by name
// and type) echo the request — `GetWorkload{id}` answers that id, and a filter
// field reads back as filtered — except paging and query controls. An echoed
// value is still a value the engine emits, so it must pass the RESPONSE
// field's rules; one that does not is generated instead. A oneof case the
// request selected is the case the response's same-named oneof takes, when it
// has a member of that name.
//
// A string the rules cannot be met for (a pattern the cheap generator cannot
// build, or rules that contradict one another) throws, naming the field,
// rather than emit a value the server's protovalidate would reject.
