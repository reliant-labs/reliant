/** Change how one message type is generated, wherever it appears. */
export interface MockFactory<Desc extends DescMessage = DescMessage> {
  readonly schema: Desc;
  readonly build: (ctx: MockFactoryContext<Desc>) => MockResult<Desc>;
}

export interface MockFactoryContext<Desc extends DescMessage> {
  /** The default the engine built for this position. */
  readonly base: MessageShape<Desc>;
  /** Position in the enclosing list, or -1 outside one. */
  readonly index: number;
  /** The seed of this position: stable for the same request and path. */
  readonly seed: string;
}

/**
 * A factory's or handler's answer: a full message passes through; a plain
 * object is a PATCH onto the default (factories) or the full response
 * completed with zero values (handlers), as the engine's F5 contract says.
 */
export type MockResult<Desc extends DescMessage> =
  | MessageShape<Desc>
  | MessageInitShape<Desc>;

/**
 * Typed factory helper: `mockFactory(TraceSummarySchema, ({ base, index }) =>
 * ({ rootService: index % 2 ? "web" : "api" }))` — the result is patched onto
 * the default for every TraceSummary the engine builds.
 */
export function mockFactory<Desc extends DescMessage>(
  schema: Desc,
  build: (ctx: MockFactoryContext<Desc>) => MockResult<Desc>,
): MockFactory<Desc> {
  return { schema, build };
}

