// ── Determinism ─────────────────────────────────────────────────────────

/** FNV-1a, 32-bit: small, fast, and stable across engines. */
function fnv1a(input: string | Uint8Array): number {
  let h = 0x811c9dc5;
  if (typeof input === "string") {
    for (let i = 0; i < input.length; i++) {
      h ^= input.charCodeAt(i);
      h = Math.imul(h, 0x01000193);
    }
  } else {
    for (const b of input) {
      h ^= b;
      h = Math.imul(h, 0x01000193);
    }
  }
  return h >>> 0;
}

/** mulberry32 over an FNV-1a seed: a deterministic stream per (seed, path). */
class Rng {
  private state: number;
  constructor(seed: string) {
    this.state = fnv1a(seed) || 0x9e3779b9;
  }
  next(): number {
    this.state = (this.state + 0x6d2b79f5) | 0;
    let t = this.state;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  }
  /** An integer in [lo, hi], inclusive. */
  int(lo: number, hi: number): number {
    if (hi <= lo) return lo;
    return lo + Math.floor(this.next() * (hi - lo + 1));
  }
  pick<T>(items: readonly T[]): T {
    return items[this.int(0, items.length - 1)] as T;
  }
  hex(n: number): string {
    let out = "";
    while (out.length < n) out += this.int(0, 15).toString(16);
    return out;
  }
}

let sessionNow: number | undefined;

function anchorMs(now: Date | number | undefined): number {
  if (now !== undefined) return typeof now === "number" ? now : now.getTime();
  sessionNow ??= Math.floor(Date.now() / 60_000) * 60_000;
  return sessionNow;
}

// ── Names ───────────────────────────────────────────────────────────────

const words = (s: string) =>
  s
    .replace(/([a-z0-9])([A-Z])/g, "$1_$2")
    .toLowerCase()
    .split(/[^a-z0-9]+/)
    .filter(Boolean);

const kebab = (s: string) => words(s).join("-");

/** `labels` → `label`, `entries` → `entry`: a list item is one of the list. */
function singularOf(s: string): string {
  if (/ies$/.test(s)) return s.slice(0, -3) + "y";
  if (/(ss|us|is)$/.test(s)) return s;
  return s.replace(/s$/, "");
}

function human(s: string): string {
  const w = words(s).join(" ");
  return w.charAt(0).toUpperCase() + w.slice(1);
}

/** The thing a message stands for: `ListTracesResponse` → `List traces`. */
function messageNoun(desc: DescMessage): string {
  return desc.name.replace(/(Request|Response)$/, "") || desc.name;
}

function hasWord(name: string, ...candidates: string[]): boolean {
  const w = words(name);
  return candidates.some((c) => w.includes(c));
}

