// Part of @reliantlabs/forge-web-runtime — the web twin of forge/pkg.
//
// forgeSiteFiles over a temp dist/: the hook is driven against a fake resolved
// config, and once through a real `vite build`, which is what proves the
// hook runs after Vite has copied public/ into the output.
import {
  mkdirSync,
  mkdtempSync,
  readFileSync,
  rmSync,
  writeFileSync,
  existsSync,
} from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";

import type { Plugin } from "vite";
import { afterEach, beforeEach, describe, expect, it, vi } from "vitest";

import {
  forgeSiteFiles,
  type ForgeSiteFilesOptions,
  type SiteFilesConfig,
} from "./vite.js";

let root: string;

beforeEach(() => {
  root = mkdtempSync(join(tmpdir(), "forge-site-files-"));
});

afterEach(() => {
  rmSync(root, { recursive: true, force: true });
});

/** dist writes files (relative path → body) into root/dist. */
function dist(files: Record<string, string>): void {
  for (const [name, body] of Object.entries(files)) {
    const file = join(root, "dist", name);
    mkdirSync(dirname(file), { recursive: true });
    writeFileSync(file, body);
  }
}

function read(name: string): string {
  return readFileSync(join(root, "dist", name), "utf8");
}

/** build runs the plugin's hooks as `vite build` would, and returns its warnings. */
async function build(
  options: ForgeSiteFilesOptions,
  over: { base?: string; build?: Partial<SiteFilesConfig["build"]> } = {},
  env?: string,
): Promise<string[]> {
  const warn = vi.fn();
  const plugin = forgeSiteFiles(options);
  plugin.configResolved({
    root,
    base: over.base ?? "/",
    publicDir: join(root, "public"),
    build: { outDir: "dist", ...over.build },
    logger: { warn },
  });
  await plugin.closeBundle.call(
    env === undefined ? {} : { environment: { name: env } },
  );
  return warn.mock.calls.map((c) => String(c[0]));
}

/** locs lists a sitemap's <loc> values in order. */
function locs(xml: string): string[] {
  return [...xml.matchAll(/<loc>([^<]*)<\/loc>/g)].map((m) => m[1] ?? "");
}

describe("forgeSiteFiles", () => {
  it("is a build-only Vite plugin", () => {
    const plugin: Plugin = forgeSiteFiles({ siteUrl: "https://example.com" });
    expect(plugin.name).toBe("forge-site-files");
    expect(plugin.apply).toBe("build");
  });

  it("writes robots.txt and a sitemap of every page, absolute", async () => {
    dist({
      "index.html": "",
      "about.html": "",
      "blog/index.html": "",
      "blog/first post.html": "",
      "assets/app.js": "",
    });
    const warnings = await build({
      siteUrl: "https://example.com/",
      routes: ["/pricing", "contact", "/about"],
    });
    expect(warnings).toEqual([]);

    const robots = read("robots.txt");
    expect(robots).toMatch(/^# Generated by forgeSiteFiles/);
    expect(robots).toContain("User-agent: *\nAllow: /\n");
    expect(robots).toContain("\nSitemap: https://example.com/sitemap.xml\n");
    expect(robots).not.toContain("Disallow");

    const xml = read("sitemap.xml");
    expect(xml.startsWith('<?xml version="1.0" encoding="UTF-8"?>\n')).toBe(
      true,
    );
    expect(xml).toContain(
      '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">',
    );
    expect(locs(xml)).toEqual([
      "https://example.com/",
      "https://example.com/about",
      "https://example.com/blog/",
      "https://example.com/blog/first%20post",
      "https://example.com/contact",
      "https://example.com/pricing",
    ]);
  });

  it("writes robots disallows, and escapes the sitemap's XML", async () => {
    dist({ "index.html": "" });
    await build({
      siteUrl: "https://example.com",
      routes: ["/search?q=x", "/a&b"],
      robots: { disallow: ["/admin/", "private", "/*?sort="] },
    });
    expect(read("robots.txt")).toContain(
      "Allow: /\nDisallow: /admin/\nDisallow: /private\nDisallow: /*?sort=\n",
    );
    const xml = read("sitemap.xml");
    expect(xml).toContain("<loc>https://example.com/a&amp;b</loc>");
    expect(locs(xml)).toEqual([
      "https://example.com/",
      "https://example.com/a&amp;b",
      "https://example.com/search",
    ]);
  });

  it("leaves out exclude, 404.html and Search Console verification files", async () => {
    dist({
      "index.html": "",
      "404.html": "",
      "google1a2b3c4d5e6f.html": "",
      "thanks.html": "",
      "admin/index.html": "",
      "admin/users.html": "",
      "docs/index.html": "",
    });
    await build({
      siteUrl: "https://example.com",
      exclude: ["/thanks", "/admin/*", "docs"],
    });
    expect(locs(read("sitemap.xml"))).toEqual(["https://example.com/"]);
  });

  it("never overwrites a file the app ships in public/", async () => {
    // Vite has copied public/ into dist/ by the time the hook runs.
    dist({
      "index.html": "",
      "robots.txt": "User-agent: *\nDisallow: /\n",
      "sitemap.xml": "<urlset>mine</urlset>",
    });
    const warnings = await build({ siteUrl: "https://example.com" });
    expect(read("robots.txt")).toBe("User-agent: *\nDisallow: /\n");
    expect(read("sitemap.xml")).toBe("<urlset>mine</urlset>");
    // The app's robots.txt has no Sitemap: line, and the warning names it.
    expect(warnings).toHaveLength(1);
    expect(warnings[0]).toContain("Sitemap: https://example.com/sitemap.xml");
  });

  it("keeps an app's robots.txt that names a sitemap without a word", async () => {
    dist({
      "index.html": "",
      "robots.txt": "User-agent: *\nSitemap: https://example.com/other.xml\n",
    });
    expect(await build({ siteUrl: "https://example.com" })).toEqual([]);
    expect(read("robots.txt")).toContain("other.xml");
    expect(existsSync(join(root, "dist", "sitemap.xml"))).toBe(true);
  });

  it("replaces its own output from an earlier build into an unemptied dir", async () => {
    dist({ "index.html": "" });
    await build({ siteUrl: "https://old.example.com" });
    dist({ "new.html": "" });
    await build({ siteUrl: "https://example.com" });
    expect(read("robots.txt")).toContain("Sitemap: https://example.com/");
    expect(locs(read("sitemap.xml"))).toEqual([
      "https://example.com/",
      "https://example.com/new",
    ]);
  });

  it("serves every URL under Vite's base", async () => {
    dist({ "index.html": "", "guide.html": "" });
    await build(
      {
        siteUrl: "https://example.com",
        routes: ["/faq"],
        robots: { disallow: ["/drafts/"] },
      },
      { base: "/docs/" },
    );
    const robots = read("robots.txt");
    expect(robots).toContain("Disallow: /docs/drafts/\n");
    expect(robots).toContain("Sitemap: https://example.com/docs/sitemap.xml\n");
    expect(locs(read("sitemap.xml"))).toEqual([
      "https://example.com/docs/",
      "https://example.com/docs/faq",
      "https://example.com/docs/guide",
    ]);
  });

  it("does not double a base the siteUrl already carries", async () => {
    dist({ "index.html": "" });
    await build({ siteUrl: "https://example.com/docs" }, { base: "/docs/" });
    expect(locs(read("sitemap.xml"))).toEqual(["https://example.com/docs/"]);
  });

  it("serves pages from the root under a relative or CDN base", async () => {
    for (const base of ["./", "https://cdn.example.net/assets/"]) {
      dist({ "index.html": "" });
      await build({ siteUrl: "https://example.com" }, { base });
      expect(locs(read("sitemap.xml"))).toEqual(["https://example.com/"]);
    }
  });

  it("with no siteUrl, writes robots.txt without Sitemap:, no sitemap, and warns with the fix", async () => {
    // F5's starter passes process.env.SITE_URL, which is undefined in a build
    // before the env has a hostname.
    for (const siteUrl of [undefined, "", "  "]) {
      rmSync(join(root, "dist"), { recursive: true, force: true });
      dist({ "index.html": "" });
      const warnings = await build({
        siteUrl,
        robots: { disallow: ["/admin/"] },
      });
      expect(read("robots.txt")).toContain(
        "User-agent: *\nAllow: /\nDisallow: /admin/\n",
      );
      expect(read("robots.txt")).not.toMatch(/sitemap/i);
      expect(existsSync(join(root, "dist", "sitemap.xml"))).toBe(false);
      expect(warnings).toHaveLength(1);
      expect(warnings[0]).toContain("siteUrl is empty");
      expect(warnings[0]).toContain("env_vars.SITE_URL");
    }
  });

  it("treats a siteUrl that is not an absolute http(s) URL as empty, and says so", async () => {
    dist({ "index.html": "" });
    const warnings = await build({ siteUrl: "example.com" });
    expect(existsSync(join(root, "dist", "sitemap.xml"))).toBe(false);
    expect(warnings[0]).toContain(
      '"example.com" is not an absolute http(s) URL',
    );
  });

  it("writes nothing for an SSR build, another environment, or a build that did not write", async () => {
    dist({ "index.html": "" });
    await build({ siteUrl: "https://example.com" }, { build: { ssr: true } });
    await build(
      { siteUrl: "https://example.com" },
      { build: { write: false } },
    );
    await build({ siteUrl: "https://example.com" }, {}, "ssr");
    expect(existsSync(join(root, "dist", "robots.txt"))).toBe(false);
    // An absent output dir (a failed build) is not an error.
    rmSync(join(root, "dist"), { recursive: true });
    await expect(build({ siteUrl: "https://example.com" })).resolves.toEqual(
      [],
    );
  });

  it("runs after vite build has copied public/, and keeps the app's file", async () => {
    const { build: viteBuild } = await import("vite");
    writeFileSync(join(root, "index.html"), "<!doctype html><title>t</title>");
    mkdirSync(join(root, "public"));
    writeFileSync(
      join(root, "public", "robots.txt"),
      "User-agent: *\nAllow: /\nSitemap: https://example.com/sitemap.xml\n",
    );
    await viteBuild({
      root,
      base: "/site/",
      logLevel: "silent",
      configFile: false,
      plugins: [forgeSiteFiles({ siteUrl: "https://example.com" })],
    });
    expect(read("robots.txt")).not.toContain("forgeSiteFiles");
    expect(locs(read("sitemap.xml"))).toEqual(["https://example.com/site/"]);
  });
});
