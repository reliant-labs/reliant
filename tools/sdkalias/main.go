// Command sdkalias writes gen/reliant/v1/sdk_alias.pb.go: the exported
// surface of the SDK's generated protobuf package, re-exported from the import
// path the app has always used.
//
// The public protos are generated once, into the SDK module's
// gen/reliant/v1 (buf.gen.yaml says which). A second generated copy in
// gen/reliant/v1 would register the same proto file twice and panic every
// binary at init, so gen/reliant/v1 keeps only the app's own protos and this
// file. A type alias is the same type under a second name, which is why ~1,500
// importers of gen/reliant/v1 compile unchanged and a *reliantv1.Run from either
// path is the same value.
//
// The names come from the SDK version go.mod pins (`go list -m`), not from
// this tree's sdk/go: that version is what the app links, so the aliases name
// exactly what it has. A public proto changed in this tree reaches the aliases
// when the pin moves.
//
// It runs as the sdk-aliases generate hook (forge.yaml). The file is named
// *.pb.go on purpose: forge's stale-scaffold check looks for the pb.<Name> a
// handler's scaffold test references only in *.pb.go and *connect*.go, and
// would call every worktree handler test stale without it.
package main

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"os"
	"os/exec"
	"path/filepath"
	"sort"
	"strings"
)

const (
	sdkModule  = "github.com/reliant-labs/reliant/sdk/go"
	sdkImport  = sdkModule + "/gen/reliant/v1"
	outputFile = "gen/reliant/v1/sdk_alias.pb.go"
)

func main() {
	if err := run(); err != nil {
		fmt.Fprintln(os.Stderr, "sdkalias:", err)
		os.Exit(1)
	}
}

func run() error {
	dir, err := pinnedSDKDir()
	if err != nil {
		return err
	}
	src, err := render(filepath.Join(dir, "gen", "reliant", "v1"))
	if err != nil {
		return err
	}
	if cur, err := os.ReadFile(outputFile); err == nil && bytes.Equal(cur, src) {
		return nil
	}
	return os.WriteFile(outputFile, src, 0o644)
}

// pinnedSDKDir is where the SDK version go.mod requires lives (the module
// cache), resolved as the build resolves it, outside any workspace.
func pinnedSDKDir() (string, error) {
	cmd := exec.Command("go", "list", "-m", "-f", "{{.Dir}}", sdkModule)
	cmd.Env = append(os.Environ(), "GOWORK=off")
	cmd.Stderr = os.Stderr
	out, err := cmd.Output()
	if err != nil {
		return "", fmt.Errorf("locate %s (is it required in go.mod?): %w", sdkModule, err)
	}
	dir := strings.TrimSpace(string(out))
	if dir == "" {
		return "", fmt.Errorf("%s has no directory: run `go mod download %s`", sdkModule, sdkModule)
	}
	return dir, nil
}

// render builds the alias file for the generated package in dir.
func render(dir string) ([]byte, error) {
	files, err := filepath.Glob(filepath.Join(dir, "*.pb.go"))
	if err != nil {
		return nil, err
	}
	if len(files) == 0 {
		return nil, fmt.Errorf("no *.pb.go in %s", dir)
	}
	sort.Strings(files)

	var types, consts, vars []string
	fset := token.NewFileSet()
	for _, f := range files {
		file, err := parser.ParseFile(fset, f, nil, 0)
		if err != nil {
			return nil, err
		}
		for _, decl := range file.Decls {
			gd, ok := decl.(*ast.GenDecl)
			if !ok {
				continue
			}
			for _, spec := range gd.Specs {
				switch s := spec.(type) {
				case *ast.TypeSpec:
					if s.Name.IsExported() {
						types = append(types, s.Name.Name)
					}
				case *ast.ValueSpec:
					for _, n := range s.Names {
						if !n.IsExported() {
							continue
						}
						if gd.Tok == token.CONST {
							consts = append(consts, n.Name)
						} else {
							vars = append(vars, n.Name)
						}
					}
				}
			}
		}
	}
	sort.Strings(types)
	sort.Strings(consts)
	sort.Strings(vars)

	var b strings.Builder
	b.WriteString("// Code generated by tools/sdkalias. DO NOT EDIT.\n\n")
	b.WriteString("// Package reliantv1 holds the app's own protos. The public ones (proto/public-api.txt)\n")
	b.WriteString("// are generated into the SDK module, and this file re-exports them so the\n")
	b.WriteString("// import path the app has always used keeps working. See tools/sdkalias.\n")
	b.WriteString("package reliantv1\n\n")
	fmt.Fprintf(&b, "import sdk %q\n\n", sdkImport)
	if len(types) > 0 {
		b.WriteString("type (\n")
		for _, n := range types {
			fmt.Fprintf(&b, "\t%s = sdk.%s\n", n, n)
		}
		b.WriteString(")\n\n")
	}
	if len(consts) > 0 {
		b.WriteString("const (\n")
		for _, n := range consts {
			fmt.Fprintf(&b, "\t%s = sdk.%s\n", n, n)
		}
		b.WriteString(")\n\n")
	}
	if len(vars) > 0 {
		b.WriteString("var (\n")
		for _, n := range vars {
			fmt.Fprintf(&b, "\t%s = sdk.%s\n", n, n)
		}
		b.WriteString(")\n")
	}
	return format.Source([]byte(b.String()))
}
