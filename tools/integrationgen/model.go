const generatedMarker = "Generated by tools/integrationgen"

// plan is a validated specSet plus everything the emitters need.
type plan struct {
	specs *specSet
	up    *upstream
	hooks map[string]bool
	// found records the optional fields some event's upstream declared.
	found map[*fieldSpec]bool
}

func newPlan(root string, s *specSet) (*plan, error) {
	p := s.provider
	if p.Provider == "" || p.Package == "" || p.Catalog == "" {
		return nil, fmt.Errorf("provider.yaml: provider, package and catalog are required")
	}
	if p.Upstream.File == "" || p.Upstream.SHA256 == "" || p.Upstream.Version == "" || p.Upstream.Package == "" {
		return nil, fmt.Errorf("provider.yaml: upstream needs package, version, file and sha256")
	}
	c := p.Caps
	if c.TextBytes <= 0 || c.DataBytes <= 0 || c.ListItems <= 0 || c.TruncatedSuffix == "" {
		return nil, fmt.Errorf("provider.yaml: caps needs text_bytes, data_bytes, list_items and truncated_suffix")
	}
	up, err := loadUpstream(filepath.Join(root, p.Upstream.File), p.Upstream.SHA256)
	if err != nil {
		return nil, err
	}
	pl := &plan{specs: s, up: up, hooks: map[string]bool{}, found: map[*fieldSpec]bool{}}
	if p.Hooks != "" {
		if err := pl.loadHooks(filepath.Join(root, "internal/integrations/webhook", p.Provider, p.Hooks)); err != nil {
			return nil, err
		}
	}
	return pl, nil
}

// loadHooks records the hooks a spec may name: top-level funcs of the form
// func(any) bool in the hand-written hooks file.
func (pl *plan) loadHooks(path string) error {
	f, err := parser.ParseFile(token.NewFileSet(), path, nil, 0)
	if err != nil {
		return fmt.Errorf("hooks: %w", err)
	}
	for _, d := range f.Decls {
		fn, ok := d.(*ast.FuncDecl)
		if !ok || fn.Recv != nil || fn.Type.Params.NumFields() != 1 || fn.Type.Results.NumFields() != 1 {
			continue
		}
		in, ok1 := fn.Type.Params.List[0].Type.(*ast.Ident)
		out, ok2 := fn.Type.Results.List[0].Type.(*ast.Ident)
		if ok1 && ok2 && in.Name == "any" && out.Name == "bool" {
			pl.hooks[fn.Name.Name] = true
		}
	}
	return nil
}

var fieldKinds = map[string]bool{
	"string": true, "integer": true, "boolean": true, "present": true,
	"names": true, "strings": true, "integers": true, "object": true, "list": true,
}

// check validates the specs against each other, the hooks, and the pinned
// upstream schema.
func (pl *plan) check(root string) error {
	s := pl.specs
	seenEvent := map[string]string{}
	var errs []string
	add := func(f string, args ...any) { errs = append(errs, fmt.Sprintf(f, args...)) }

	for name, o := range s.objects {
		pl.checkFields(o.Fields, "objects/"+name, &errs)
		if o.Absent != "" && o.Absent != "null" {
			add("objects/%s: absent is %q, want \"null\" or nothing", name, o.Absent)
		}
	}
	pl.checkFields(s.provider.Envelope.DataFirst, "envelope", &errs)
	pl.checkFields(s.provider.Envelope.Data, "envelope", &errs)

	groups := s.provider.AttributeGroups
	for _, a := range s.provider.Envelope.Attributes {
		if a.Use == "" {
			add("envelope.attributes: each is `use: <shared declaration>`")
		}
	}
	for g, list := range groups {
		for _, a := range list {
			pl.checkAttr(a, "attribute_groups."+g, &errs)
		}
	}

	for _, e := range s.events {
		where := e.ID
		if e.Event == "" || e.DisplayName == "" || e.Summary == "" {
			add("%s: event, display_name and summary are required", where)
		}
		if prev, dup := seenEvent[e.Event]; dup {
			add("%s: event %q is already declared by %s", where, e.Event, prev)
		}
		seenEvent[e.Event] = e.ID
		for _, o := range e.Omit {
			if !pl.envelopeHas(o) {
				add("%s: omit %q: the envelope has no such attribute or data field", where, o)
			}
		}
		for _, a := range e.Attributes {
			if a.Group != "" {
				if _, ok := groups[a.Group]; !ok {
					add("%s: attribute group %q is not declared in provider.yaml", where, a.Group)
				}
				continue
			}
			pl.checkAttr(a, where, &errs)
		}
		pl.checkFields(e.Data, where, &errs)
		if e.Shrink != nil {
			ok := false
			for _, f := range e.Data {
				ok = ok || (f.Name == e.Shrink.List && f.Kind == "list")
			}
			if !ok || e.Shrink.Flag == "" || len(e.Shrink.Drop) == 0 {
				add("%s: shrink needs a list that is one of the event's list fields, drop keys and a flag", where)
			}
		}
	}
	if len(errs) == 0 {
		pl.checkUpstream(&errs)
		pl.checkOptionalFound(&errs)
	}
	if len(errs) > 0 {
		sort.Strings(errs)
		return fmt.Errorf("%s", strings.Join(errs, "\n"))
	}
	return nil
}

func (pl *plan) envelopeHas(name string) bool {
	for _, a := range pl.specs.provider.Envelope.Attributes {
		if a.Use == name {
			return true
		}
	}
	for _, f := range pl.envelopeAll() {
		if f.Name == name {
			return true
		}
	}
	return false
}

func (pl *plan) envelopeAll() fieldList {
	e := pl.specs.provider.Envelope
	return append(append(fieldList{}, e.DataFirst...), e.Data...)
}

func (pl *plan) checkAttr(a attrSpec, where string, errs *[]string) {
	bad := func(f string, args ...any) {
		*errs = append(*errs, fmt.Sprintf("%s: attribute %q: %s", where, a.Name+a.Use, fmt.Sprintf(f, args...)))
	}
	if (a.Use == "") == (a.Name == "") {
		bad("is either `use:` a shared declaration or declares a `name:`")
		return
	}
	if a.Name != "" && (a.Description == "" || a.Example == "") {
		bad("needs a description and an example")
	}
	if a.Use != "" && (a.Description != "" || a.Example != "" || a.Type != "") {
		bad("is a shared declaration: its description, example and type live in schemas/attr_%s.yaml", a.Use)
	}
	switch a.Kind {
	case "", "string", "boolean", "present":
	default:
		bad("kind %q is not string, boolean or present", a.Kind)
	}
	if a.Hook != "" && !pl.hooks[a.Hook] {
		bad("hook %q is not a func(any) bool in the hooks file", a.Hook)
	}
	if len(a.From) == 0 {
		bad("needs `from:`, the payload path it is read from")
	}
	if a.StripPrefix != "" && (a.Kind != "" && a.Kind != "string" || a.Hook != "" || a.Lower || len(a.From) != 1) {
		bad("strip_prefix applies to one string path, with no hook or lower")
	}
	if a.Hook != "" && a.Kind != "" && a.Kind != "boolean" {
		bad("a hook yields a boolean")
	}
	if a.Lower && a.Kind != "" && a.Kind != "string" {
		bad("lower applies to a string")
	}
}

func (pl *plan) checkFields(fields fieldList, where string, errs *[]string) {
	for _, f := range fields {
		bad := func(format string, args ...any) {
			*errs = append(*errs, fmt.Sprintf("%s: field %q (line %d): %s", where, f.Name, f.line, fmt.Sprintf(format, args...)))
		}
		if !fieldKinds[f.Kind] {
			bad("kind %q is not one of string, integer, boolean, present, names, strings, integers, object, list", f.Kind)
			continue
		}
		switch f.Kind {
		case "names", "integers":
			if f.Pluck == "" {
				bad("%s needs `pluck:`, the key read from each element", f.Kind)
			}
		case "object":
			if (f.Object == "") == (len(f.Fields) == 0) {
				bad("an object is either `object: <name>` or inline `fields:`")
			}
			if f.Object != "" {
				if _, ok := pl.specs.objects[f.Object]; !ok {
					bad("object %q has no objects/%s.yaml", f.Object, f.Object)
				}
				if f.Description != "" {
					bad("a referenced object takes no description (a $ref has no siblings)")
				}
			}
			pl.checkFields(f.Fields, where+"."+f.Name, errs)
		case "list":
			if _, ok := pl.specs.objects[f.Object]; !ok {
				bad("list needs `object:` naming an objects/ file")
			}
			if _, ok := pl.specs.provider.Caps.Lists[f.Max]; !ok {
				bad("list needs `max:` naming an entry of caps.lists")
			}
		}
		if f.Cap && f.Kind != "string" {
			bad("cap applies to a string")
		}
		if f.Lower && f.Kind != "string" {
			bad("lower applies to a string")
		}
		if f.Cap && f.Lower {
			bad("cap and lower do not combine")
		}
		if f.OmitEmpty && f.Kind != "string" && f.Kind != "integer" && f.Kind != "object" {
			bad("omit_empty applies to a string, an integer or an object")
		}
		if f.Require != "" && (f.Kind != "object" || len(f.Fields) == 0 || !f.OmitEmpty) {
			bad("require applies to an inline omit_empty object")
		}
	}
}

// checkUpstream holds every path a spec keeps to the pinned upstream schema.
func (pl *plan) checkUpstream(errs *[]string) {
	s := pl.specs
	for _, e := range s.events {
		def := upstreamDefinition(e.Event)
		root, err := pl.up.root(def)
		if err != nil {
			*errs = append(*errs, fmt.Sprintf("%s: %v (event %q)", e.ID, err, e.Event))
			continue
		}
		where := fmt.Sprintf("%s [upstream %s@%s %s]", e.ID, s.provider.Upstream.Package, s.provider.Upstream.Version, def)
		pl.checkFieldsUp(e.Data, root, where, errs)
		pl.checkFieldsUp(pl.envelopeFields(e), root, where, errs)
		for _, a := range pl.eventAttrs(e) {
			if a.Parser || a.Unchecked != "" {
				continue
			}
			for _, from := range a.From {
				n, err := pl.up.walk(root, strings.Split(from, "."))
				if err != nil {
					*errs = append(*errs, fmt.Sprintf("%s: attribute %q reads %q: %v", where, a.Name+a.Use, from, err))
					continue
				}
				kind := a.Kind
				if a.Hook != "" || kind == "" {
					kind = "any"
				}
				if kind == "boolean" || kind == "present" {
					kind = map[string]string{"boolean": "boolean", "present": "object"}[kind]
					if !n.types()[kind] && len(n.types()) > 0 {
						*errs = append(*errs, fmt.Sprintf("%s: attribute %q reads %q, which upstream types %v, not %s", where, a.Name+a.Use, from, sortedKeys(n.types()), kind))
					}
				} else if a.Hook == "" && !accepts("string", n.types()) {
					*errs = append(*errs, fmt.Sprintf("%s: attribute %q reads %q, which upstream types %v, not a string", where, a.Name+a.Use, from, sortedKeys(n.types())))
				}
			}
		}
	}
}

func (pl *plan) checkOptionalFound(errs *[]string) {
	var visit func(fields fieldList, where string)
	visit = func(fields fieldList, where string) {
		for _, f := range fields {
			if f.Optional != "" && !pl.found[f] {
				*errs = append(*errs, fmt.Sprintf("%s: field %q is optional but no event's upstream declares %q", where, f.Name, f.srcPath()))
			}
			visit(f.Fields, where+"."+f.Name)
		}
	}
	for name, o := range pl.specs.objects {
		visit(o.Fields, "objects/"+name)
	}
	for _, e := range pl.specs.events {
		visit(e.Data, e.ID)
	}
}

// checkFieldsUp checks fields against the upstream node of the object they
// project.
func (pl *plan) checkFieldsUp(fields fieldList, at node, where string, errs *[]string) {
	for _, f := range fields {
		if f.Unchecked != "" {
			continue
		}
		path := strings.Split(f.srcPath(), ".")
		n, err := pl.up.walk(at, path)
		if err != nil && f.Optional != "" {
			continue
		}
		if err == nil && f.Optional != "" {
			pl.found[f] = true
		}
		if err != nil {
			*errs = append(*errs, fmt.Sprintf("%s: field %q reads %q: %v", where, f.Name, f.srcPath(), err))
			continue
		}
		if t := n.types(); !accepts(f.Kind, t) {
			*errs = append(*errs, fmt.Sprintf("%s: field %q (%s) reads %q, which upstream types %v", where, f.Name, f.Kind, f.srcPath(), sortedKeys(t)))
			continue
		}
		switch f.Kind {
		case "names", "integers":
			if _, err := pl.up.walk(pl.up.enterArrays(node(n)), []string{f.Pluck}); err != nil {
				*errs = append(*errs, fmt.Sprintf("%s: field %q plucks %q from %q: %v", where, f.Name, f.Pluck, f.srcPath(), err))
			}
		case "object":
			sub := f.Fields
			if f.Object != "" {
				sub = pl.specs.objects[f.Object].Fields
			}
			pl.checkFieldsUp(sub, n, where+" > "+f.Name, errs)
		case "list":
			pl.checkFieldsUp(pl.specs.objects[f.Object].Fields, pl.up.enterArrays(n), where+" > "+f.Name+"[]", errs)
		}
	}
}

// srcPath is the dotted path, relative to the object the field belongs to,
// that the value is read from.
func (f *fieldSpec) srcPath() string {
	if f.From != "" {
		return f.From
	}
	return f.Name
}

// upstreamDefinition names the upstream definition of an event type:
// "issues.opened" is `issues$opened`, a bare "push" is `push$event`.
func upstreamDefinition(event string) string {
	if strings.Contains(event, ".") {
		return strings.Replace(event, ".", "$", 1)
	}
	return event + "$event"
}

// envelopeFields is the envelope's data minus what the event omits.
func (pl *plan) envelopeFields(e *eventSpec) fieldList {
	return pl.envelopeSplit(e, pl.envelopeAll())
}

func (pl *plan) envelopeSplit(e *eventSpec, in fieldList) fieldList {
	var out fieldList
	for _, f := range in {
		if !contains(e.Omit, f.Name) {
			out = append(out, f)
		}
	}
	return out
}

// eventAttrs is every attribute the event declares, in order: the envelope's,
// then the event's own with groups expanded.
func (pl *plan) eventAttrs(e *eventSpec) []attrSpec {
	var out []attrSpec
	for _, a := range pl.specs.provider.Envelope.Attributes {
		if !contains(e.Omit, a.Use) {
			a.Parser = true
			out = append(out, a)
		}
	}
	for _, a := range e.Attributes {
		if a.Group != "" {
			out = append(out, pl.specs.provider.AttributeGroups[a.Group]...)
			continue
		}
		out = append(out, a)
	}
	return out
}

func contains(l []string, s string) bool {
	for _, x := range l {
		if x == s {
			return true
		}
	}
	return false
}
