// part is one section of a mock-shaped render: a name and a version.
type part struct {
	name string
	v    int
}

// sectionedRender is a mock-shaped render with a preamble and one named
// section per part. The version sits on the section's FIRST body line and is
// its LAST changing line: the worst case for adjacency.
func sectionedRender(parts ...part) []byte {
	var b strings.Builder
	b.WriteString("// Code generated by forge. DO NOT EDIT.\npackage p\n\n")
	for _, p := range parts {
		fmt.Fprintf(&b, "// forge:section Mock%s\ntype Mock%s struct{ v%d int }\n\n", p.name, p.name, p.v)
	}
	return []byte(b.String())
}

func parts(names ...string) []part {
	out := make([]part, len(names))
	for i, n := range names {
		out[i] = part{name: n}
	}
	return out
}

func TestStampSections_VerifyAndTamper(t *testing.T) {
	const rel = "internal/p/mock_gen.go"
	stamped, ok := Stamp(rel, sectionedRender(parts("A", "B")...))
	if !ok {
		t.Fatal("not stampable")
	}
	s := string(stamped)
	for _, name := range []string{"A", "B"} {
		if !strings.Contains(s, "// forge:section Mock"+name+"\n// forge:hash=") {
			t.Fatalf("section %s: want its named header followed by its hash line:\n%s", name, s)
		}
	}
	if !strings.HasPrefix(s, "// Code generated by forge. DO NOT EDIT.\n// forge:hash=") {
		t.Fatalf("head marker misplaced:\n%s", s)
	}
	if Verify(stamped) != Pristine {
		t.Fatalf("stamped sectioned file must verify:\n%s", s)
	}
	if again, _ := Stamp(rel, stamped); string(again) != s {
		t.Errorf("Stamp is not idempotent:\n%s\n---\n%s", again, s)
	}
	// Body hash is the same for the render and its stamp.
	if BodyHash(stamped) != BodyHash(sectionedRender(parts("A", "B")...)) {
		t.Error("BodyHash must not see section lines")
	}
	for name, edit := range map[string]func(string) string{
		"preamble": func(s string) string { return strings.Replace(s, "package p", "package q", 1) },
		"section": func(s string) string {
			return strings.Replace(s, "type MockB struct{ v0 int }", "type MockB struct{ x int }", 1)
		},
		"section name": func(s string) string {
			return strings.Replace(s, "// forge:section MockB\n", "// forge:section MockC\n", 1)
		},
		"section hash line removed": func(s string) string {
			i := strings.Index(s, "// forge:section MockB\n") + len("// forge:section MockB\n")
			j := strings.Index(s[i:], "\n")
			return s[:i] + s[i+j+1:]
		},
	} {
		if got := Verify([]byte(edit(s))); got != Modified {
			t.Errorf("%s edit: Verify = %v, want Modified", name, got)
		}
	}
	stripped := StripMarker(stamped)
	if Verify(stripped) != NoMarker {
		t.Error("a disowned (stripped) sectioned file must carry no marker")
	}
	if strings.Contains(string(stripped), sectionKey) {
		t.Errorf("a disowned file keeps no section header:\n%s", stripped)
	}
}

// A file stamped by forge before v1.0.12 carries each section's hash on its
// header line. It must still verify (so the next generate refreshes it as a
// pristine render rather than refusing it as a hand edit), and restamping it
// writes the named form.
func TestStampSections_LegacyOneLineFormVerifies(t *testing.T) {
	const rel = "internal/p/mock_gen.go"
	bodyA := "type MockA struct{}\n\n"
	bodyB := "type MockB struct{}\n\n"
	pre := "// Code generated by forge. DO NOT EDIT.\npackage p\n\n"
	legacy := "// Code generated by forge. DO NOT EDIT.\n// forge:hash=" + BodyHash([]byte(pre)) + "\npackage p\n\n" +
		"// forge:section forge:hash=" + BodyHash([]byte(bodyA)) + "\n" + bodyA +
		"// forge:section forge:hash=" + BodyHash([]byte(bodyB)) + "\n" + bodyB
	if got := Verify([]byte(legacy)); got != Pristine {
		t.Fatalf("legacy one-line sections: Verify = %v, want Pristine:\n%s", got, legacy)
	}
	tampered := strings.Replace(legacy, "type MockB struct{}", "type MockB struct{ x int }", 1)
	if got := Verify([]byte(tampered)); got != Modified {
		t.Errorf("an edited legacy section: Verify = %v, want Modified", got)
	}
	restamped, _ := Stamp(rel, []byte(legacy))
	if strings.Contains(string(restamped), "forge:section forge:hash=") {
		t.Errorf("Stamp must write the named two-line form, not the legacy one:\n%s", restamped)
	}
	if Verify(restamped) != Pristine {
		t.Errorf("restamped legacy file must verify:\n%s", restamped)
	}
}

// edit is one branch's change to the parts of a sectioned file.
type edit struct {
	label string
	apply func([]part) []part
	// touches is the part it changes, deletes or (for an insertion) adds.
	touches string
	// between names an insertion's neighbours, or a deleted part's,
	// "^" and "$" standing for the file's ends.
	between string
	deletes bool
}

// neighbours returns the names on either side of name in base.
func neighbours(name string, base []part) (prev, next string) {
	prev, next = "^", "$"
	for _, p := range base {
		switch {
		case p.name < name:
			prev = p.name
		case p.name > name && next == "$":
			next = p.name
		}
	}
	return prev, next
}

// lineMergeable reports whether a pair of independent edits is one line
// merging can take at all. Two cannot be, for any line format:
//   - two insertions between the same neighbours (git cannot order them);
//   - a deletion and a change that touches the deleted part's boundary (an
//     insertion beside it, or the deletion of a neighbour). A deletion removes
//     one whole period of the part-and-separator pattern, so it ends exactly
//     where the neighbouring change begins: no unchanged line can sit between
//     them.
//
// Both are why a generator whose parts are born and removed independently
// writes one file per part; sections keep the rest mergeable.
func lineMergeable(a, b edit) bool {
	if a.touches == b.touches {
		return false
	}
	if !a.deletes && !b.deletes {
		return a.between == "" || a.between != b.between
	}
	if a.deletes && b.deletes {
		return !strings.Contains("|"+a.between+"|", "|"+b.touches+"|")
	}
	del, other := a, b
	if b.deletes {
		del, other = b, a
	}
	return other.between == "" || !strings.Contains("|"+other.between+"|", "|"+del.touches+"|")
}

func changeEdit(name string) edit {
	return edit{label: "change " + name, touches: name, apply: func(ps []part) []part {
		out := append([]part(nil), ps...)
		for i := range out {
			if out[i].name == name {
				out[i].v++
			}
		}
		return out
	}}
}

func deleteEdit(name string, base []part) edit {
	prev, next := neighbours(name, base)
	return edit{label: "delete " + name, touches: name, between: prev + "|" + next, deletes: true, apply: func(ps []part) []part {
		var out []part
		for _, p := range ps {
			if p.name != name {
				out = append(out, p)
			}
		}
		return out
	}}
}

func insertEdit(name string, base []part) edit {
	prev, next := neighbours(name, base)
	return edit{label: "insert " + name, touches: name, between: prev + "|" + next, apply: func(ps []part) []part {
		out := append(append([]part(nil), ps...), part{name: name})
		sort.Slice(out, func(i, j int) bool { return out[i].name < out[j].name })
		return out
	}}
}

// TestStampSections_EveryIndependentPairMergesWithPlainGit is the property
// sections exist for, over every shape two independent changes can take:
// change, insert or delete a part, at the start, middle or end of the file,
// including NEIGHBOURING parts (a part inserted directly before one the other
// branch changed — the shape the one-line form conflicted on). Each pair
// merges with merge-ort, the engine of `git merge` and of GitHub's
// server-side merge (`git merge-tree --write-tree`, no merge driver), into
// exactly the stamp of the merged parts, which certifies itself.
//
// Excluded are the pairs no line format can merge (lineMergeable): two
// insertions at one point, and a deletion beside another change to its
// boundary.
func TestStampSections_EveryIndependentPairMergesWithPlainGit(t *testing.T) {
	const rel = "mock_gen.go"
	base := parts("B", "D", "F")
	var edits []edit
	for _, n := range []string{"B", "D", "F"} {
		edits = append(edits, changeEdit(n), deleteEdit(n, base))
	}
	for _, n := range []string{"A", "C", "E", "G"} {
		edits = append(edits, insertEdit(n, base))
	}
	stamp := func(ps []part) []byte {
		out, _ := Stamp(rel, sectionedRender(ps...))
		return out
	}
	variants := map[string][]byte{"base": stamp(base)}
	for i, e := range edits {
		variants[fmt.Sprint("e", i)] = stamp(e.apply(base))
	}
	repo := newMergeRepo(t, rel, variants)
	var pairs [][2]int
	neighbourPairs := 0
	for i, ours := range edits {
		for j := i + 1; j < len(edits); j++ {
			theirs := edits[j]
			if !lineMergeable(ours, theirs) {
				continue
			}
			pairs = append(pairs, [2]int{i, j})
			if strings.Contains("|"+theirs.between+"|", "|"+ours.touches+"|") || strings.Contains("|"+ours.between+"|", "|"+theirs.touches+"|") {
				neighbourPairs++
			}
		}
	}
	branches := make([][2]string, len(pairs))
	for k, p := range pairs {
		branches[k] = [2]string{fmt.Sprint("e", p[0]), fmt.Sprint("e", p[1])}
	}
	for k, res := range repo.mergeAll(branches) {
		{
			ours, theirs := edits[pairs[k][0]], edits[pairs[k][1]]
			got, ok := res.content, res.clean
			if !ok {
				t.Errorf("%s + %s: plain git merge conflicted:\n%s", ours.label, theirs.label, got)
				continue
			}
			if want := stamp(theirs.apply(ours.apply(base))); string(got) != string(want) {
				t.Errorf("%s + %s: merged file differs from the stamp of the merged parts:\n%s\n--- want ---\n%s", ours.label, theirs.label, got, want)
				continue
			}
			if Verify(got) != Pristine {
				t.Errorf("%s + %s: the merged file must certify itself", ours.label, theirs.label)
			}
		}
	}
	if len(pairs) < 30 || neighbourPairs < 6 {
		t.Fatalf("only %d independent pairs (%d of them neighbours) exercised; the matrix lost its shapes", len(pairs), neighbourPairs)
	}
}

// The control: the pre-v1.0.12 one-line form, whose header carried the hash,
// conflicts on the neighbour shape the named form merges (a part inserted
// directly before one the other branch changed). If this ever merges, the
// matrix above is no longer testing what it claims to.
func TestStampSections_LegacyFormConflictsOnNeighbours(t *testing.T) {
	const rel = "mock_gen.go"
	legacy := func(ps ...part) []byte {
		var b strings.Builder
		pre := "// Code generated by forge. DO NOT EDIT.\npackage p\n\n"
		b.WriteString("// Code generated by forge. DO NOT EDIT.\n// forge:hash=" + BodyHash([]byte(pre)) + "\npackage p\n\n")
		for _, p := range ps {
			body := fmt.Sprintf("type Mock%s struct{ v%d int }\n\n", p.name, p.v)
			b.WriteString("// forge:section forge:hash=" + BodyHash([]byte(body)) + "\n" + body)
		}
		return []byte(b.String())
	}
	base := parts("B", "D")
	changed := parts("B", "D")
	changed[1].v = 1
	repo := newMergeRepo(t, rel, map[string][]byte{
		"base":   legacy(base...),
		"ours":   legacy(changed...),
		"theirs": legacy(parts("B", "C", "D")...),
	})
	if got, ok := repo.merge("ours", "theirs"); ok {
		t.Fatalf("the legacy form merged a part inserted beside a changed neighbour; the control no longer controls:\n%s", got)
	}
}

// mergeRepo is a bare repository holding one commit per variant of rel, each
// a child of "base", so any two merge with merge-ort without a checkout.
type mergeRepo struct {
	t        *testing.T
	dir, rel string
}

func newMergeRepo(t *testing.T, rel string, variants map[string][]byte) mergeRepo {
	t.Helper()
	if _, err := exec.LookPath("git"); err != nil {
		t.Skip("git not on PATH")
	}
	r := mergeRepo{t: t, dir: t.TempDir(), rel: rel}
	r.git(nil, "init", "-q", "--bare")
	// One fast-import stream writes every commit: one git process, not one
	// per variant.
	var stream strings.Builder
	commit := func(name, from string) {
		fmt.Fprintf(&stream, "commit refs/heads/%s\n", name)
		if from == "" {
			stream.WriteString("mark :1\n")
		}
		stream.WriteString("committer t <t@t> 0 +0000\ndata 0\n")
		if from != "" {
			stream.WriteString("from :1\n")
		}
		fmt.Fprintf(&stream, "M 644 inline %s\ndata %d\n%s\n", rel, len(variants[name]), variants[name])
	}
	commit("base", "")
	names := make([]string, 0, len(variants))
	for n := range variants {
		if n != "base" {
			names = append(names, n)
		}
	}
	sort.Strings(names)
	for _, n := range names {
		commit(n, "base")
	}
	r.git(strings.NewReader(stream.String()), "fast-import", "--quiet")
	return r
}

func (r mergeRepo) git(stdin *strings.Reader, args ...string) (string, error) {
	cmd := exec.Command("git", args...)
	cmd.Dir = r.dir
	// No user or system config: no merge driver, no attributes.
	cmd.Env = append(os.Environ(), "GIT_CONFIG_NOSYSTEM=1", "GIT_CONFIG_GLOBAL=/dev/null")
	if stdin != nil {
		cmd.Stdin = stdin
	}
	out, err := cmd.CombinedOutput()
	if err != nil && stdin != nil {
		r.t.Fatalf("git %s: %v\n%s", strings.Join(args, " "), err, out)
	}
	return string(out), err
}

// mergeResult is one merge: the merged rel when clean, else the report.
type mergeResult struct {
	content []byte
	clean   bool
}

// mergeAll merges each pair's second branch into its first with merge-ort,
// all in one `git merge-tree --stdin` and one `git cat-file --batch`.
func (r mergeRepo) mergeAll(pairs [][2]string) []mergeResult {
	var in strings.Builder
	for _, p := range pairs {
		in.WriteString(p[0] + " " + p[1] + "\n")
	}
	out, err := r.git(strings.NewReader(in.String()), "merge-tree", "--stdin", "--no-messages", "--name-only")
	if err != nil {
		r.t.Fatalf("git merge-tree --stdin: %v\n%s", err, out)
	}
	// Each merge, NUL-separated: its status (1 clean, 0 conflicted), its
	// tree, the conflicted paths, then an empty field.
	fields := strings.Split(out, "\x00")
	results := make([]mergeResult, len(pairs))
	var batch strings.Builder
	var cleanIdx []int
	f := 0
	for k := range pairs {
		if f+1 >= len(fields) {
			r.t.Fatalf("git merge-tree --stdin: output ends before merge %d of %d: %q", k+1, len(pairs), out)
		}
		status, tree := fields[f], fields[f+1]
		f += 2
		var conflicted []string
		for f < len(fields) && fields[f] != "" {
			conflicted = append(conflicted, fields[f])
			f++
		}
		f++ // the empty field closing this merge
		if status != "1" {
			results[k] = mergeResult{content: []byte("conflicted: " + strings.Join(conflicted, ", "))}
			continue
		}
		results[k].clean = true
		cleanIdx = append(cleanIdx, k)
		batch.WriteString(tree + ":" + r.rel + "\n")
	}
	if len(cleanIdx) == 0 {
		return results
	}
	blobs, err := r.git(strings.NewReader(batch.String()), "cat-file", "--batch")
	if err != nil {
		r.t.Fatalf("git cat-file --batch: %v", err)
	}
	for _, k := range cleanIdx {
		// "<oid> blob <size>\n<content>\n"
		nl := strings.IndexByte(blobs, '\n')
		var oid, typ string
		var size int
		if _, err := fmt.Sscanf(blobs[:nl], "%s %s %d", &oid, &typ, &size); err != nil {
			r.t.Fatalf("git cat-file --batch: %q: %v", blobs[:nl], err)
		}
		results[k].content = []byte(blobs[nl+1 : nl+1+size])
		blobs = blobs[nl+1+size+1:]
	}
	return results
}

// merge merges branch theirs into ours: mergeAll of one pair.
func (r mergeRepo) merge(ours, theirs string) ([]byte, bool) {
	res := r.mergeAll([][2]string{{ours, theirs}})[0]
	return res.content, res.clean
}
