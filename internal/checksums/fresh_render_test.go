package checksums

import (
	"os"
	"path/filepath"
	"testing"
)

func writeRescueFixture(t *testing.T, root, rel, body string) {
	t.Helper()
	full := filepath.Join(root, filepath.FromSlash(rel))
	if err := os.MkdirAll(filepath.Dir(full), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(full, []byte(body), 0o644); err != nil {
		t.Fatal(err)
	}
}

// TestRescueFreshRender_Unstampable: a JSON output whose ledger entry is
// stale but whose bytes are this run's render gets its entry repaired.
func TestRescueFreshRender_Unstampable(t *testing.T) {
	root := t.TempDir()
	const rel = "observability/dashboards/api_gen.json"
	body := `{"v":2}` + "\n"
	writeRescueFixture(t, root, rel, body)
	if err := WriteSideRenderNoBase(root, rel, []byte(body)); err != nil {
		t.Fatal(err)
	}
	cs := &FileChecksums{Unstampable: map[string]string{rel: BodyHash([]byte(`{"v":1}` + "\n"))}}

	if !RescueFreshRender(root, rel, cs) {
		t.Fatal("bytes equal to the fresh render must be rescued")
	}
	if cs.Unstampable[rel] != BodyHash([]byte(body)) {
		t.Error("the ledger entry was not repaired")
	}
	if _, err := os.Stat(filepath.Join(root, RenderDir, rel)); !os.IsNotExist(err) {
		t.Error("the parked render must be removed once consulted")
	}
}

// TestRescueFreshRender_Stamped: a stamped file whose body is the fresh
// render under another vintage's marker is restamped.
func TestRescueFreshRender_Stamped(t *testing.T) {
	root := t.TempDir()
	const rel = "internal/x/x_gen.go"
	body := []byte("// Code generated by forge. DO NOT EDIT.\npackage x\n\nconst V = 2\n")
	stale, _ := StampWithValue(rel, body, BodyHash([]byte("package x\n")))
	writeRescueFixture(t, root, rel, string(stale))
	fresh, _ := Stamp(rel, body)
	if err := WriteSideRenderNoBase(root, rel, fresh); err != nil {
		t.Fatal(err)
	}

	if !RescueFreshRender(root, rel, &FileChecksums{}) {
		t.Fatal("a body equal to the fresh render must be rescued")
	}
	on, _ := os.ReadFile(filepath.Join(root, rel))
	if Verify(on) != Pristine {
		t.Errorf("the rescued file must self-verify:\n%s", on)
	}
}

// TestRescueFreshRender_RefusesEverythingElse: different bytes, and a path
// no emitter rendered this run, stay drift.
func TestRescueFreshRender_RefusesEverythingElse(t *testing.T) {
	root := t.TempDir()
	const rel = "observability/dashboards/api_gen.json"
	writeRescueFixture(t, root, rel, `{"v":"edited"}`+"\n")
	cs := &FileChecksums{Unstampable: map[string]string{rel: "recorded"}}

	if RescueFreshRender(root, rel, cs) {
		t.Fatal("with no fresh render parked there is nothing to compare against")
	}
	if err := WriteSideRenderNoBase(root, rel, []byte(`{"v":2}`+"\n")); err != nil {
		t.Fatal(err)
	}
	if RescueFreshRender(root, rel, cs) {
		t.Fatal("bytes this run would not write are a hand-edit")
	}
	if cs.Unstampable[rel] != "recorded" {
		t.Error("a refused rescue must not touch the ledger")
	}
}
