package contract

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"
	"testing"

	"golang.org/x/tools/go/analysis"
	"golang.org/x/tools/go/packages"
)

// Both contract lanes must agree about the real runtime lifecycle. Every
// fixture does SQL I/O; no connection is opened. Marked copies exercise the
// outbound opt-out gate, unmarked copies exercise require-contract itself.
func TestWorkerLifecycleContractLanes(t *testing.T) {
	if testing.Short() {
		t.Skip("loads and type-checks a fixture module via go/packages; runs in task test")
	}
	cases := []struct {
		name, role, methods string
		worker              bool
	}{
		{"wrapped", "workers", `func (*Worker) Start(context.Context) error { return nil }
func (*Worker) Stop(context.Context) error { return nil }`, true},
		{"direct", "workers", `func (*Worker) Name() string { return "direct" }
func (*Worker) Start(context.Context) error { return nil }`, true},
		{"value", "workers", `func (Worker) Start(context.Context) error { return nil }
func (Worker) Stop(context.Context) error { return nil }`, true},
		{"mixed", "workers", `func (Worker) Start(context.Context) error { return nil }
func (*Worker) Stop(context.Context) error { return nil }`, true},
		{"alias", "workers", `type Ctx = context.Context
func (*Worker) Start(Ctx) error { return nil }
func (*Worker) Stop(Ctx) error { return nil }`, true},
		{"helper", "workers", `func (*Worker) Fetch(context.Context) error { return nil }`, false},
		{"splitwrapped", "workers", `type Other struct{}
func (*Worker) Start(context.Context) error { return nil }
func (*Other) Stop(context.Context) error { return nil }`, false},
		{"splitdirect", "workers", `type Other struct{}
func (*Worker) Start(context.Context) error { return nil }
func (*Other) Name() string { return "not-worker" }`, false},
		{"badstart", "workers", `func (*Worker) Start(string) error { return nil }
func (*Worker) Stop(context.Context) error { return nil }`, false},
		{"badstop", "workers", `func (*Worker) Start(context.Context) error { return nil }
func (*Worker) Stop(context.Context) {}`, false},
		{"badname", "workers", `func (*Worker) Start(context.Context) error { return nil }
func (*Worker) Name() int { return 0 }`, false},
		{"variadic", "workers", `func (*Worker) Start(...context.Context) error { return nil }
func (*Worker) Stop(context.Context) error { return nil }`, false},
		{"lookalikectx", "workers", `type Context interface { Done() <-chan struct{} }
func (*Worker) Start(Context) error { return nil }
func (*Worker) Stop(Context) error { return nil }`, false},
		{"outofrole", "adapters", `func (*Worker) Start(context.Context) error { return nil }
func (*Worker) Stop(context.Context) error { return nil }`, false},
		{"pathlookalike", "workers_extra", `func (*Worker) Start(context.Context) error { return nil }
func (*Worker) Stop(context.Context) error { return nil }`, false},
		{"testonly", "workers", `func (*Worker) Start(context.Context) error { return nil }`, false},
		{"generatedonly", "workers", `func (*Worker) Start(context.Context) error { return nil }`, false},
		{"generatedheader", "workers", `func (*Worker) Start(context.Context) error { return nil }`, false},
	}
	dir := t.TempDir()
	write := func(name, body string) {
		t.Helper()
		file := filepath.Join(dir, name)
		if err := os.MkdirAll(filepath.Dir(file), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(file, []byte(body), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	write("go.mod", "module example.com/lifecycle\n\ngo 1.24\n")
	want := map[string]bool{}
	for _, tc := range cases {
		for _, marked := range []bool{false, true} {
			name := tc.name
			marker := ""
			if marked {
				name += "marked"
				marker = "//forge:exclude-contract: supervised worker\n"
			}
			rel := "internal/" + tc.role + "/" + name
			want["example.com/lifecycle/"+rel] = tc.worker
			write(rel+"/worker.go", marker+`package fixture
import ("context"; "database/sql")
type Worker struct { DB *sql.DB }
func (w *Worker) Sweep(ctx context.Context) error {
    _, err := w.DB.ExecContext(ctx, "DELETE FROM expired")
    return err
}
`+tc.methods)
			if tc.name == "testonly" || tc.name == "generatedonly" || tc.name == "generatedheader" {
				extra, header := "worker_test.go", ""
				if tc.name == "generatedonly" {
					extra = "worker_gen.go"
				}
				if tc.name == "generatedheader" {
					extra, header = "generated.go", "// Code generated by fixture. DO NOT EDIT.\n"
				}
				write(rel+"/"+extra, header+"package fixture\nimport \"context\"\nfunc (*Worker) Stop(context.Context) error { return nil }\n")
			}
		}
	}
	pkgs, err := packages.Load(&packages.Config{
		Dir: dir, Tests: true,
		Mode: packages.NeedName | packages.NeedFiles | packages.NeedCompiledGoFiles |
			packages.NeedSyntax | packages.NeedTypes | packages.NeedTypesInfo | packages.NeedModule,
	}, "./...")
	if err != nil {
		t.Fatal(err)
	}
	if n := packages.PrintErrors(pkgs); n != 0 {
		t.Fatalf("fixture has %d load errors", n)
	}
	findings := CheckExcludeDirectives(pkgs, ExcludeGateOptions{})
	outbound := map[string]bool{}
	for _, f := range findings {
		if f.Rule != RuleExcludeOutboundIO || !strings.Contains(f.Message, "database/sql") {
			t.Errorf("unexpected exclusion finding: %+v", f)
		}
		outbound[filepath.Dir(f.File)] = true
	}
	seen := map[string]bool{}
	for _, p := range pkgs {
		if p.ID != p.PkgPath {
			continue // Do not treat test variants as production source.
		}
		worker, ok := want[p.PkgPath]
		if !ok {
			continue
		}
		seen[p.PkgPath] = true
		t.Run(strings.TrimPrefix(p.PkgPath, "example.com/lifecycle/internal/"), func(t *testing.T) {
			if strings.HasSuffix(p.PkgPath, "marked") {
				if got := outbound[filepath.Dir(p.GoFiles[0])]; got == worker {
					t.Errorf("outbound refusal = %v, want %v", got, !worker)
				}
				return
			}
			var diagnostics []analysis.Diagnostic
			_, err := runRequireContract(&analysis.Pass{
				Pkg: p.Types, Files: p.Syntax, Fset: p.Fset, TypesInfo: p.TypesInfo,
				Report: func(d analysis.Diagnostic) { diagnostics = append(diagnostics, d) },
			})
			if err != nil {
				t.Fatal(err)
			}
			if got := len(diagnostics); (worker && got != 0) || (!worker && got != 1) {
				t.Errorf("require-contract diagnostics = %s, worker = %v", fmt.Sprint(diagnostics), worker)
			}
		})
	}
	if len(seen) != len(want) {
		t.Fatalf("checked %d fixture packages, want %d", len(seen), len(want))
	}
}
