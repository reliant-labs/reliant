// Package scaffolds enforces the forge ownership boundary between
// pure-generated, scaffold-with-placeholders, and pure user-space files.
//
// Two rules:
//
//  1. A scaffold-with-placeholders file (anything containing
//     "FORGE_SCAFFOLD:" markers) is PENDING WORK: fill in the
//     placeholders and remove the markers before shipping. This is a
//     WARNING, not an error — a freshly-scaffolded project ALWAYS
//     carries these markers, so error severity would make the scaffold
//     phase's expected state illegal (`forge lint` gates workflow
//     phases, and the scaffold phase could never pass). The warning
//     keeps the "did the LLM finish the task?" signal visible without
//     outlawing the intermediate state.
//
//  2. A pure forge-space "_gen" file MUST carry the canonical
//     "Code generated by forge. DO NOT EDIT." header AND a "Source:"
//     marker pointing at the input that drove its generation. Without
//     these two lines the LLM has no signal that the file is forge-owned
//     and may try to "fix" it in place. A missing canonical header is an
//     error; a missing "Source:" pointer is a warning.
//
// Findings with severity=error gate the build. Findings with
// severity=warning print but do not fail.
package scaffolds

import (
	"fmt"
	"go/parser"
	"go/token"
	"io/fs"
	"os"
	"path/filepath"
	"regexp"
	"strings"

	"github.com/reliant-labs/forge/internal/linter/finding"
)

// Severity and Finding now live in the shared internal/linter/finding
// package — these aliases keep the historical scaffolds.* spellings
// working for callers and tests. scaffold findings populate
// Rule/Severity/Path/Message (Path, not File — scaffold rules are
// whole-file, not line-scoped).
type (
	// Severity is the shared finding severity vocabulary, re-exported
	// under this package's historical spelling.
	Severity = finding.Severity
	// Finding is the shared linter finding shape, re-exported under this
	// package's historical spelling. scaffold findings populate
	// Rule/Severity/Path/Message (Path, not File — scaffold rules are
	// whole-file, not line-scoped).
	Finding = finding.Finding
)

// Severity enum values (aliases onto the canonical single-spelling set).
const (
	SeverityError   = finding.SeverityError
	SeverityWarning = finding.SeverityWarning
)

// Result holds all findings from a lint run. Distinct type (not an
// alias) so scaffolds keeps its own FormatText.
type Result struct {
	Findings []Finding `json:"findings"`
}

// HasErrors reports whether any finding is at error severity.
func (r Result) HasErrors() bool {
	for _, f := range r.Findings {
		if f.Severity == SeverityError {
			return true
		}
	}
	return false
}

// FormatText renders the findings as human-readable output.
func (r Result) FormatText() string {
	if len(r.Findings) == 0 {
		return "No scaffold ownership issues found.\n"
	}

	var sb strings.Builder
	fmt.Fprintf(&sb, "Found %d scaffold ownership issue(s):\n\n", len(r.Findings))

	for _, f := range r.Findings {
		icon := "❌"
		if f.Severity == SeverityWarning {
			icon = "⚠️ "
		}
		fmt.Fprintf(&sb, "  %s [%s] %s: %s\n", icon, f.Rule, f.Path, f.Message)
	}
	sb.WriteString("\n")
	return sb.String()
}

// LintResult bundles findings and any walk error.
type LintResult = Result

// scaffoldMarker is the literal marker comment forge templates emit.
// Matching the leading "// " (Go line-comment prefix) avoids firing on
// references to the marker name in string literals, doc comments, or
// imports — only the comment form is the actual scaffold placeholder.
const scaffoldMarker = "// FORGE_SCAFFOLD:"

// generatedHeader is the canonical header forge codegen emits.
const generatedHeader = "// Code generated by forge. DO NOT EDIT."

// generatedHeaderRE matches forge-emitted generated-file headers. The
// canonical form is `// Code generated by forge. DO NOT EDIT.`; the
// relaxed tail also accepts legacy variants still on disk in older
// projects (`by forge generate.`, and suffixed forms).
// The "by forge" segment is required so that an `_gen.go` file claiming
// a non-forge origin still trips the lint — forge owns the regen story
// for files in its space.
var generatedHeaderRE = regexp.MustCompile(`(?m)^// Code generated by forge[^\n]* DO NOT EDIT\.$`)

// sourceHeader is the second line every pure-generated forge file must carry,
// pointing at the input that drove the file (a proto file, a contract.go,
// forge.yaml, etc).
const sourceHeader = "// Source:"

// LintRoot walks root and applies both rules. Files matching skipDir paths
// (".git", "node_modules", "gen", "vendor") are skipped to avoid heavy
// directories that never contain forge-managed source.
func LintRoot(root string) (Result, error) {
	var result Result

	err := filepath.WalkDir(root, func(path string, d fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if d.IsDir() {
			if shouldSkipDir(d.Name()) {
				return filepath.SkipDir
			}
			return nil
		}
		if !isGoFile(path) {
			return nil
		}
		findings, ferr := lintFile(path, root)
		if ferr != nil {
			// Read errors are fatal — surface them rather than silently skip.
			return ferr
		}
		result.Findings = append(result.Findings, findings...)
		return nil
	})
	if err != nil {
		return result, err
	}
	return result, nil
}

func shouldSkipDir(name string) bool {
	switch name {
	case ".git", "node_modules", "gen", "vendor", "bin", "dist", ".forge", ".next", ".next-prod", ".scratch":
		// `.scratch/` is forge's gitignored throwaway workspace (smoke-test
		// scaffolds, fixture renders). It is never committed source, so the
		// scaffold linters must not replay FORGE_SCAFFOLD/banner findings
		// against it — doing so made `forge lint` fail on forge's own repo.
		return true
	case "testdata":
		// `testdata/` is the canonical home for analyzer fixtures and
		// expected-fail files; the surrounding test suite asserts the
		// linter fires on them, so a top-level `forge lint --scaffolds`
		// must NOT replay those errors against the project itself.
		return true
	}
	return false
}

func isGoFile(path string) bool {
	return strings.HasSuffix(path, ".go")
}

// lintFile applies both rules to a single file. The relRoot is used to
// produce relative paths in findings.
func lintFile(path, relRoot string) ([]Finding, error) {
	data, err := os.ReadFile(path)
	if err != nil {
		return nil, fmt.Errorf("read %s: %w", path, err)
	}

	rel := relPath(path, relRoot)
	var findings []Finding

	// Rule 1: surviving scaffold markers are pending work. We require the
	// marker to appear at the start of a line (after optional whitespace)
	// so string literals like
	//
	//	mustWriteFile(t, ..., "...\n// FORGE_SCAFFOLD: replace me\n")
	//
	// in test sources don't trip the rule. A real scaffold placeholder
	// always lives on its own line as a Go line comment.
	//
	// WARNING severity, deliberately: a fresh scaffold ALWAYS carries
	// these markers, so an uncustomized scaffold is the expected state of
	// the scaffold phase — pending work, not a defect. Error severity
	// here made `forge lint` structurally unable to pass on forge's own
	// freshly-scaffolded output (and gated workflow phases that lint
	// between scaffold and implementation).
	if count := countScaffoldMarkers(data); count > 0 {
		findings = append(findings, Finding{
			Rule:     "scaffold-not-customized",
			Severity: SeverityWarning,
			Path:     rel,
			Message: fmt.Sprintf(
				"file still contains %d FORGE_SCAFFOLD marker(s); fill in the placeholders and remove the comments before shipping",
				count,
			),
		})
	}

	findings = append(findings, LintGeneratedHeader(rel, data)...)

	return findings, nil
}

// LintGeneratedHeader applies rule 2 to one file's content: a "_gen.go"
// file that claims to be generated must carry the canonical header AND a
// "Source:" pointer. rel is the project-relative path, used both to
// recognize the _gen suffix and as the finding's Path.
//
// The "claims to be generated" gate is important because forge's own
// internal codebase has hand-written generators (e.g.
// internal/codegen/crud_gen.go and its test) that legitimately use the
// _gen naming idiom for "this file generates code with _gen.go suffix" —
// they don't claim to be machine-generated themselves.
//
// Exported so forge's own render guard (internal/tierguard) holds every
// Tier-1 file forge emits to the exact rule `forge lint` holds the user's
// tree to. A forge emitter that omits the Source line otherwise surfaces as
// a warning in every freshly scaffolded project — on a file the user is
// told not to edit, so the "add one" remedy is one they cannot apply.
func LintGeneratedHeader(rel string, data []byte) []Finding {
	if !isGenFilename(rel) || !claimsGenerated(data) {
		return nil
	}
	var findings []Finding
	head := firstLines(data, 16)
	headBytes := []byte(head)
	hasCanonical := bytesContains(headBytes, []byte(generatedHeader)) ||
		generatedHeaderRE.Match(headBytes)
	if !hasCanonical {
		findings = append(findings, Finding{
			Rule:     "gen-missing-header",
			Severity: SeverityError,
			Path:     rel,
			Message:  `_gen file claims to be generated but lacks a canonical "// Code generated ... DO NOT EDIT." header`,
		})
	}
	if !bytesContains(headBytes, []byte(sourceHeader)) {
		msg := `_gen file is missing a "// Source: <input>" line; add one so users know what drives the regeneration`
		if hasCanonical {
			// forge wrote this file and the user may not edit it, so "add
			// one" is not a remedy they can apply. Every forge emitter
			// stamps the line now (pinned by internal/tierguard), so a
			// regenerate with a current forge is the fix.
			msg = `forge-generated _gen file is missing its "// Source: <input>" line — an older forge omitted it; ` +
				"re-run `forge generate` with a current forge to restamp it (do not hand-edit the file)"
		}
		findings = append(findings, Finding{
			Rule:     "gen-missing-source",
			Severity: SeverityWarning,
			Path:     rel,
			Message:  msg,
		})
	}
	return findings
}

// isGenFilename returns true for paths whose final basename ends in
// "_gen.go" or "_gen_test.go" — the suffix is the ownership statement, so
// a generated test file is covered by the same rule as generated code.
func isGenFilename(path string) bool {
	base := filepath.Base(path)
	return strings.HasSuffix(base, "_gen.go") || strings.HasSuffix(base, "_gen_test.go")
}

// claimsGenerated returns true when the file's leading comments contain
// the substring "Code generated" — the conventional signal that a file
// is machine-generated (matches the Go convention from
// https://golang.org/s/generatedcode). Hand-written files that happen to
// share a "_gen" naming convention (e.g. forge's own internal/codegen
// generators) won't include this phrase and are therefore skipped.
func claimsGenerated(data []byte) bool {
	head := firstLines(data, 16)
	return strings.Contains(head, "Code generated")
}

// firstLines returns the first n lines of data as a single string, with
// trailing whitespace per line preserved. Used to bound the header scan.
func firstLines(data []byte, n int) string {
	lines := strings.SplitN(string(data), "\n", n+1)
	if len(lines) > n {
		lines = lines[:n]
	}
	return strings.Join(lines, "\n")
}

// relPath returns path relative to root, slash-separated, falling back to
// path if Rel fails.
//
// Slash-separated because it is not only finding output: the banner
// classifier matches it against "internal/templates/<dir>/" prefixes, which a
// backslashed Windows path never contained — so every directory-scoped rule
// missed, and templates fell through to banner-unclassified there.
func relPath(path, root string) string {
	rel, err := filepath.Rel(root, path)
	if err != nil {
		return path
	}
	return filepath.ToSlash(rel)
}

// bytesContains is a wrapper around strings.Contains that operates on
// byte slices without allocating a string copy of the entire haystack.
func bytesContains(haystack, needle []byte) bool {
	return strings.Contains(string(haystack), string(needle))
}

// countScaffoldMarkers counts lines whose first non-whitespace content
// is the scaffoldMarker prefix. Restricting to line starts dodges the
// false-positive case of fixture writers that build scaffold-marker
// strings inside Go test sources via concatenation:
//
//	mustWriteFile(t, path, "package x\n// FORGE_SCAFFOLD: ...\n")
//
// The marker substring is real in the file's text but the line layout
// of the marker is broken by the escape sequences, so it doesn't appear
// at a line start.
func countScaffoldMarkers(data []byte) int {
	// Prefer the Go parser: it is the only thing that can tell a real
	// line COMMENT from the same characters inside a string literal.
	// Tests legitimately embed scaffold-shaped source as fixture data in
	// raw (backtick) literals, where the marker does start its line — a
	// line-prefix scan counts those as pending work that nobody can ever
	// clear (it fired on internal/cli/scaffold/fixtures_test.go).
	if n, ok := countScaffoldMarkerComments(data); ok {
		return n
	}
	// Unparseable file (a template, or Go that does not compile): fall
	// back to the line-prefix scan rather than silently reporting zero.
	count := 0
	for _, line := range strings.Split(string(data), "\n") {
		trimmed := strings.TrimLeft(line, " \t")
		if strings.HasPrefix(trimmed, scaffoldMarker) {
			count++
		}
	}
	return count
}

// countScaffoldMarkerComments counts scaffold markers that the Go parser
// reports as comments. ok=false when data does not parse as Go, so the
// caller can fall back.
func countScaffoldMarkerComments(data []byte) (int, bool) {
	fset := token.NewFileSet()
	file, err := parser.ParseFile(fset, "src.go", data, parser.ParseComments)
	if err != nil {
		return 0, false
	}
	count := 0
	for _, group := range file.Comments {
		for _, c := range group.List {
			if strings.HasPrefix(strings.TrimLeft(c.Text, " \t"), scaffoldMarker) {
				count++
			}
		}
	}
	return count, true
}
