package forgeconv

import (
	"os"
	"path/filepath"
	"strings"
	"testing"
)

// orderProto declares an OrderService with the CRUD quintet over the Order
// entity, two custom rpcs, and a CRUD-named rpc marked forge:custom (custom
// by declaration, so it counts).
const orderProto = `syntax = "proto3";

package services.orders.v1;

message Order {
  string id = 1;
}

service OrderService {
  rpc CreateOrder(CreateOrderRequest) returns (CreateOrderResponse);
  rpc GetOrder(GetOrderRequest) returns (GetOrderResponse);
  rpc ListOrders(ListOrdersRequest) returns (ListOrdersResponse);
  rpc ShipOrder(ShipOrderRequest) returns (ShipOrderResponse);
  rpc CancelOrder(CancelOrderRequest) returns (CancelOrderResponse);
  // forge:custom
  rpc UpdateOrder(UpdateOrderRequest) returns (UpdateOrderResponse);
}
`

// rpcMethodSrc renders one pb-through handler method on *Service.
func rpcMethodSrc(name string) string {
	return "func (s *Service) " + name + "(ctx context.Context, req *pb." + name + "Request) (*pb." + name +
		"Response, error) {\n\treturn nil, nil\n}\n\n"
}

// writeOrderProject lays out a project with orderProto and the given
// handler files under internal/handlers/order/.
func writeOrderProject(t *testing.T, files map[string]string) string {
	t.Helper()
	root := t.TempDir()
	write := func(rel, content string) {
		p := filepath.Join(root, rel)
		if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(p, []byte(content), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	write("proto/services/orders/v1/orders.proto", orderProto)
	write("internal/handlers/order/service.go", "package order\n\ntype Service struct{}\n")
	for name, body := range files {
		// A generated-code header must precede the package clause.
		header, rest := "", body
		if strings.HasPrefix(body, "// Code generated") {
			header, rest, _ = strings.Cut(body, "\n\n")
			header += "\n\n"
		}
		write(filepath.Join("internal/handlers/order", name), header+"package order\n\n"+rest)
	}
	return root
}

func TestLintOneRPCPerFile(t *testing.T) {
	t.Parallel()
	cases := []struct {
		name  string
		files map[string]string
		// want is the finding's file, "" for none.
		want     string
		wantRPCs []string
		wantMove []string
		wantKeep string
	}{
		{
			name:     "two custom rpcs in one file",
			files:    map[string]string{"orders.go": rpcMethodSrc("ShipOrder") + rpcMethodSrc("CancelOrder")},
			want:     "internal/handlers/order/orders.go",
			wantRPCs: []string{"ShipOrder", "CancelOrder"},
			wantMove: []string{"ShipOrder → rpc_ship_order.go", "CancelOrder → rpc_cancel_order.go"},
		},
		{
			name:     "the rpc whose own file it is stays",
			files:    map[string]string{"rpc_ship_order.go": rpcMethodSrc("ShipOrder") + rpcMethodSrc("CancelOrder")},
			want:     "internal/handlers/order/rpc_ship_order.go",
			wantRPCs: []string{"ShipOrder", "CancelOrder"},
			wantMove: []string{"CancelOrder → rpc_cancel_order.go"},
			wantKeep: "ShipOrder → ",
		},
		{
			name:     "a forge:custom CRUD-named rpc counts",
			files:    map[string]string{"orders.go": rpcMethodSrc("UpdateOrder") + rpcMethodSrc("ShipOrder")},
			want:     "internal/handlers/order/orders.go",
			wantRPCs: []string{"UpdateOrder", "ShipOrder"},
		},
		{
			name: "one rpc per file",
			files: map[string]string{
				"rpc_ship_order.go":   rpcMethodSrc("ShipOrder"),
				"rpc_cancel_order.go": rpcMethodSrc("CancelOrder"),
			},
		},
		{
			name: "CRUD shims share handlers_crud.go",
			files: map[string]string{
				"handlers_crud.go": rpcMethodSrc("CreateOrder") + rpcMethodSrc("GetOrder") + rpcMethodSrc("ListOrders"),
			},
		},
		{
			name: "CRUD rpcs outside handlers_crud.go are not counted",
			files: map[string]string{
				"orders.go": rpcMethodSrc("CreateOrder") + rpcMethodSrc("GetOrder") + rpcMethodSrc("ShipOrder"),
			},
		},
		{
			name: "helper methods are not rpcs",
			files: map[string]string{
				"rpc_ship_order.go": rpcMethodSrc("ShipOrder") +
					"func (s *Service) validate() error { return nil }\n\n" +
					"func (s *Service) Name() string { return \"orders\" }\n\n" +
					"func shipHelper() {}\n",
			},
		},
		{
			name: "generated and test files are skipped",
			files: map[string]string{
				"stubs_gen.go": rpcMethodSrc("ShipOrder") + rpcMethodSrc("CancelOrder"),
				"marked.go": "// Code generated by forge. DO NOT EDIT.\n\n" +
					rpcMethodSrc("ShipOrder") + rpcMethodSrc("CancelOrder"),
				"orders_test.go": rpcMethodSrc("ShipOrder") + rpcMethodSrc("CancelOrder"),
			},
		},
		{
			name: "same-named methods on another type are counted per receiver",
			files: map[string]string{
				"orders.go": rpcMethodSrc("ShipOrder") +
					"type client struct{}\n\nfunc (c *client) CancelOrder() {}\n",
			},
		},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			t.Parallel()
			root := writeOrderProject(t, tc.files)
			res, err := LintOneRPCPerFile(root)
			if err != nil {
				t.Fatal(err)
			}
			if tc.want == "" {
				if len(res.Findings) != 0 {
					t.Fatalf("want no findings, got %+v", res.Findings)
				}
				return
			}
			if len(res.Findings) != 1 {
				t.Fatalf("want 1 finding, got %+v", res.Findings)
			}
			f := res.Findings[0]
			if f.Rule != "forgeconv-one-rpc-per-file" || f.Severity != SeverityWarning || f.File != tc.want {
				t.Errorf("finding = %+v, want a forgeconv-one-rpc-per-file warning on %s", f, tc.want)
			}
			if !strings.Contains(f.Message, strings.Join(tc.wantRPCs, ", ")) {
				t.Errorf("message %q does not name %v", f.Message, tc.wantRPCs)
			}
			for _, m := range tc.wantMove {
				if !strings.Contains(f.Remediation, m) {
					t.Errorf("remediation %q does not say %q", f.Remediation, m)
				}
			}
			if tc.wantKeep != "" && strings.Contains(f.Remediation, tc.wantKeep) {
				t.Errorf("remediation %q moves the rpc whose file it is (%q)", f.Remediation, tc.wantKeep)
			}
			if f.Line == 0 {
				t.Errorf("finding has no line: %+v", f)
			}
		})
	}
}

func TestLintOneRPCPerFileScopesCRUDToTheProtoPackage(t *testing.T) {
	t.Parallel()
	for _, tc := range []struct {
		pkg      string
		wantLint bool
	}{
		{"services.other.v1", true},
		{"services.orders.v1", false},
	} {
		t.Run(tc.pkg, func(t *testing.T) {
			t.Parallel()
			root := writeOrderProject(t, map[string]string{"orders.go": rpcMethodSrc("GetOrder") + rpcMethodSrc("ShipOrder")})
			original := strings.Replace(orderProto, "message Order {\n  string id = 1;\n}\n\n", "", 1)
			if err := os.WriteFile(filepath.Join(root, "proto/services/orders/v1/orders.proto"), []byte(original), 0o644); err != nil {
				t.Fatal(err)
			}
			// Even in the same directory, an unrelated package is not
			// local. The declaration may also be split across files.
			dir := filepath.Join(root, "proto/services/orders/v1")
			types := "syntax = \"proto3\";\npackage " + tc.pkg + ";\nmessage Order { string id = 1; }\n"
			if err := os.WriteFile(filepath.Join(dir, "types.proto"), []byte(types), 0o644); err != nil {
				t.Fatal(err)
			}
			res, err := LintOneRPCPerFile(root)
			if err != nil {
				t.Fatal(err)
			}
			if tc.wantLint {
				if len(res.Findings) != 1 || !strings.Contains(res.Findings[0].Message, "GetOrder, ShipOrder") {
					t.Fatalf("want both custom RPCs in the filing warning, got %+v", res.Findings)
				}
			} else if len(res.Findings) != 0 {
				t.Fatalf("GetOrder names a local CRUD message, got %+v", res.Findings)
			}
		})
	}
}

// A service marked forge:unmanaged owns its handler layout; a project with
// no handler tree, or no proto, has nothing to lint.
func TestLintOneRPCPerFile_NothingToJudge(t *testing.T) {
	t.Parallel()

	unmanaged := writeOrderProject(t, map[string]string{"orders.go": rpcMethodSrc("ShipOrder") + rpcMethodSrc("CancelOrder")})
	p := filepath.Join(unmanaged, "proto/services/orders/v1/orders.proto")
	if err := os.WriteFile(p, []byte(strings.Replace(orderProto, "service OrderService", "// forge:unmanaged\nservice OrderService", 1)), 0o644); err != nil {
		t.Fatal(err)
	}
	noProto := writeOrderProject(t, map[string]string{"orders.go": rpcMethodSrc("ShipOrder") + rpcMethodSrc("CancelOrder")})
	if err := os.RemoveAll(filepath.Join(noProto, "proto")); err != nil {
		t.Fatal(err)
	}

	for name, root := range map[string]string{"unmanaged": unmanaged, "no proto": noProto, "no handlers": t.TempDir()} {
		res, err := LintOneRPCPerFile(root)
		if err != nil {
			t.Fatalf("%s: %v", name, err)
		}
		if len(res.Findings) != 0 {
			t.Errorf("%s: want no findings, got %+v", name, res.Findings)
		}
	}
}
