// TestLintFrontendProcessEnv_PerLineOptOut — the escape hatch. Both the
// forge-native spelling and the borrowed //nolint one must silence the
// rule on the line they annotate, and only that line.
func TestLintFrontendProcessEnv_PerLineOptOut(t *testing.T) {
	t.Parallel()
	root, feDir := newFrontendWithConfig(t)
	writeFE(t, feDir, "src/lib/a.ts",
		"// forge:lint-disable-next-line "+RuleFrontendProcessEnv+": SSR-only bootstrap\n"+
			"const a = process.env.NEXT_PUBLIC_ONE;\n")
	writeFE(t, feDir, "src/lib/b.ts",
		"const b = process.env.NEXT_PUBLIC_TWO; //nolint:"+RuleFrontendProcessEnv+"\n")
	writeFE(t, feDir, "src/lib/c.ts",
		"const c = process.env.NEXT_PUBLIC_THREE;\n")

	res := LintFrontendProcessEnv(root, []string{feDir}, finding.SeverityWarning)
	if len(res.Findings) != 1 {
		t.Fatalf("expected only the un-annotated read to survive, got %d: %+v",
			len(res.Findings), res.Findings)
	}
	if !strings.Contains(res.Findings[0].Message, "NEXT_PUBLIC_THREE") {
		t.Errorf("wrong finding survived: %q", res.Findings[0].Message)
	}
}

// TestLintFrontendProcessEnv_SeverityIsCallerControlled mirrors the
// forge-owned-dotenv rule: ONE analyzer, caller-chosen severity, so the
// advisory and gating verdicts can never diverge.
func TestLintFrontendProcessEnv_SeverityIsCallerControlled(t *testing.T) {
	t.Parallel()
	root, feDir := newFrontendWithConfig(t)
	writeFE(t, feDir, "src/lib/a.ts", `const a = process.env.NEXT_PUBLIC_ONE;`)

	for _, sev := range []finding.Severity{finding.SeverityWarning, finding.SeverityError} {
		res := LintFrontendProcessEnv(root, []string{feDir}, sev)
		if len(res.Findings) != 1 {
			t.Fatalf("expected 1 finding at %v, got %d", sev, len(res.Findings))
		}
		if res.Findings[0].Severity != sev {
			t.Errorf("severity = %v, want %v", res.Findings[0].Severity, sev)
		}
	}
}

// TestStripComments pins the comment/string scanner directly. It is the
// piece standing between this rule and its most embarrassing possible
// false positive — flagging the scaffold's own prose, several files of
// which explain in comments why their process.env reads cannot move.
func TestStripComments(t *testing.T) {
	t.Parallel()
	cases := []struct {
		name           string
		in             string
		inBlock        bool
		want           string
		wantStillBlock bool
	}{
		{"plain code", `const a = process.env.X;`, false, `const a = process.env.X;`, false},
		{"line comment", `// process.env.X in prose`, false, ``, false},
		{"trailing line comment", `const a = 1; // process.env.X`, false, `const a = 1; `, false},
		{"inline block", `/* process.env.X */ const b = 1;`, false, ` const b = 1;`, false},
		{"double-quoted string", `const s = "process.env.X";`, false, `const s = ;`, false},
		{"escaped quote", `const s = 'a\'b'; const c = process.env.Y;`, false, `const s = ; const c = process.env.Y;`, false},
		{"continuing block", `still inside process.env.X`, true, ``, true},
		{"block ends mid-line", `end */ const d = process.env.Z;`, true, ` const d = process.env.Z;`, false},
		{"template literal", "const t = `tpl ${process.env.Q}`;", false, `const t = ;`, false},
		{"block opens mid-line", `const a = 1; /* trailing`, false, `const a = 1; `, true},
	}
	for _, c := range cases {
		t.Run(c.name, func(t *testing.T) {
			got, stillBlock := stripComments(c.in, c.inBlock)
			if got != c.want || stillBlock != c.wantStillBlock {
				t.Errorf("stripComments(%q, %v) = (%q, %v), want (%q, %v)",
					c.in, c.inBlock, got, stillBlock, c.want, c.wantStillBlock)
			}
		})
	}
}

