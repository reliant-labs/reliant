// writeFE is a small helper: writes body to <feDir>/<rel>, creating
// parents. Paths are slash-separated regardless of platform.
func writeFE(t *testing.T, feDir, rel, body string) {
	t.Helper()
	full := filepath.Join(feDir, filepath.FromSlash(rel))
	if err := os.MkdirAll(filepath.Dir(full), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(full, []byte(body), 0o644); err != nil {
		t.Fatal(err)
	}
}

// configGenFixture is a trimmed copy of the real generated module's
// shape — the banner, the zod schema whose keys are the DECLARED fields,
// and the SSR branch that reads process.env by design.
const configGenFixture = `// Code generated by forge. DO NOT EDIT.
// forge-owned: regenerated every run — do not edit (forge project disown to take ownership)

import { z } from "zod";

export const configSchema = z.object({
  NEXT_PUBLIC_API_URL: z.string().default("http://localhost:8090"),
  NEXT_PUBLIC_MOCK_API: z.string().default(""),
});

function rawConfig(): Record<string, unknown> {
  if (typeof window !== "undefined" && window.__FORGE_CONFIG__) {
    return window.__FORGE_CONFIG__;
  }
  if (typeof process !== "undefined" && process.env) {
    const fromEnv: Record<string, unknown> = {};
    if (process.env["NEXT_PUBLIC_API_URL"] !== undefined) fromEnv["NEXT_PUBLIC_API_URL"] = process.env["NEXT_PUBLIC_API_URL"];
    return fromEnv;
  }
  return {};
}
`

// newFrontendWithConfig lays out a frontend that HAS the generated typed
// config module — the precondition for the rule to run at all.
func newFrontendWithConfig(t *testing.T) (root, feDir string) {
	t.Helper()
	root = t.TempDir()
	feDir = filepath.Join(root, "frontends", "web")
	writeFE(t, feDir, "src/lib/config_gen.ts", configGenFixture)
	return root, feDir
}

// TestLintFrontendProcessEnv_FlagsRawRead is the core case: a
// hand-written source file that reads process.env is reported, and the
// finding names the file, the variable, and the typed replacement.
func TestLintFrontendProcessEnv_FlagsRawRead(t *testing.T) {
	t.Parallel()
	root, feDir := newFrontendWithConfig(t)
	writeFE(t, feDir, "src/lib/basepath.ts", `
function readBasePath(): string {
  const raw = process.env.NEXT_PUBLIC_BASE_PATH || "";
  return raw;
}
`)

	res := LintFrontendProcessEnv(root, []string{feDir}, finding.SeverityWarning)
	if len(res.Findings) != 1 {
		t.Fatalf("expected 1 finding, got %d: %+v", len(res.Findings), res.Findings)
	}
	f := res.Findings[0]
	if f.Rule != RuleFrontendProcessEnv {
		t.Errorf("rule = %q, want %q", f.Rule, RuleFrontendProcessEnv)
	}
	if f.Severity != finding.SeverityWarning {
		t.Errorf("severity = %v, want warning", f.Severity)
	}
	if f.Line != 3 {
		t.Errorf("line = %d, want 3", f.Line)
	}
	if filepath.IsAbs(f.File) {
		t.Errorf("File should be root-relative, got %q", f.File)
	}
	// The finding must be a runbook: it names the variable and the
	// literal fix.
	if !strings.Contains(f.Message, "NEXT_PUBLIC_BASE_PATH") {
		t.Errorf("message must name the env var; got %q", f.Message)
	}
	if !strings.Contains(f.Remediation, "config_gen") {
		t.Errorf("remediation must point at the generated module; got %q", f.Remediation)
	}
	// NEXT_PUBLIC_BASE_PATH is NOT in the fixture's schema, so the
	// remediation must include the "declare it in the config proto" arm.
	if !strings.Contains(f.Remediation, "config.proto") {
		t.Errorf("undeclared var must be told to declare it in the proto; got %q", f.Remediation)
	}
}

// TestLintFrontendProcessEnv_DeclaredVarGetsDirectFix — when the variable
// IS already declared in the generated schema, the fix is a one-liner
// (read it from the module) with no proto edit required, and the message
// must say so rather than sending the author to the proto for a field
// that already exists.
func TestLintFrontendProcessEnv_DeclaredVarGetsDirectFix(t *testing.T) {
	t.Parallel()
	root, feDir := newFrontendWithConfig(t)
	writeFE(t, feDir, "src/lib/api.ts", `const u = process.env.NEXT_PUBLIC_API_URL;`)

	res := LintFrontendProcessEnv(root, []string{feDir}, finding.SeverityWarning)
	if len(res.Findings) != 1 {
		t.Fatalf("expected 1 finding, got %d: %+v", len(res.Findings), res.Findings)
	}
	rem := res.Findings[0].Remediation
	if !strings.Contains(rem, "loadConfig()") {
		t.Errorf("remediation must show the literal typed read; got %q", rem)
	}
	if strings.Contains(rem, "config.proto") {
		t.Errorf("an ALREADY-DECLARED var must not be sent to the proto; got %q", rem)
	}
}

// TestLintFrontendProcessEnv_NoConfigModuleIsSilent is the false-positive
// guard that matters most. A frontend that has not adopted proto-declared
// config has NO typed door to point at, so the rule must say nothing —
// otherwise every project scaffolded before the config system starts red
// with advice it cannot follow.
func TestLintFrontendProcessEnv_NoConfigModuleIsSilent(t *testing.T) {
	t.Parallel()
	root := t.TempDir()
	feDir := filepath.Join(root, "frontends", "web")
	writeFE(t, feDir, "src/lib/connect.ts", `const b = process.env.NEXT_PUBLIC_API_URL;`)
	writeFE(t, feDir, "src/lib/auth.ts", `const i = process.env.NEXT_PUBLIC_OIDC_ISSUER;`)

	res := LintFrontendProcessEnv(root, []string{feDir}, finding.SeverityWarning)
	if len(res.Findings) != 0 {
		t.Fatalf("a frontend with no config_gen.ts must produce NO findings, got %d: %+v",
			len(res.Findings), res.Findings)
	}
}

// TestLintFrontendProcessEnv_Allowlist pins every exemption, each of which
// was derived from a real file in a forge scaffold or in the control-plane
// corpus. A regression here is the check becoming noise.
func TestLintFrontendProcessEnv_Allowlist(t *testing.T) {
	t.Parallel()
	root, feDir := newFrontendWithConfig(t)

	// 1. Build-time config scripts genuinely run in Node.
	writeFE(t, feDir, "next.config.ts", `const bp = process.env.NEXT_PUBLIC_BASE_PATH ?? "";`)
	writeFE(t, feDir, "vite.config.ts", `const o = process.env.IDP_UPSTREAM_ORIGIN;`)
	writeFE(t, feDir, "vitest.config.ts", `const x = process.env.CI;`)
	// 2. Forge-generated files — flagging them tells the author to edit a
	//    file that is overwritten on the next generate.
	writeFE(t, feDir, "src/lib/basepath_gen.ts",
		"// Code generated by forge. DO NOT EDIT.\n"+
			`export const B = process.env.NEXT_PUBLIC_BASE_PATH ?? "";`)
	writeFE(t, feDir, "src/lib/otel_gen.ts",
		"// Code generated by forge. DO NOT EDIT.\n"+
			`const e = process.env.NEXT_PUBLIC_OTEL_ENDPOINT || '';`)
	// 3. Tests and mock/dev harnesses.
	writeFE(t, feDir, "src/lib/thing.test.ts", `process.env.NEXT_PUBLIC_API_URL = "x";`)
	writeFE(t, feDir, "src/lib/thing.spec.tsx", `process.env.NEXT_PUBLIC_API_URL = "x";`)
	writeFE(t, feDir, "src/__tests__/helper.ts", `process.env.NEXT_PUBLIC_API_URL = "x";`)
	writeFE(t, feDir, "src/mocks/handlers.ts", `const m = process.env.NEXT_PUBLIC_MOCK_API;`)
	// 4. Bundler build-mode discriminators. NODE_ENV can never come from
	//    KCL — both bundlers define it statically — so it is not a config
	//    value and there is nowhere else to read it from.
	writeFE(t, feDir, "src/app/providers.tsx", `const isDev = process.env.NODE_ENV === "development";`)
	writeFE(t, feDir, "src/lib/telemetry.ts", `const d = process.env?.NODE_ENV === "development";`)
	writeFE(t, feDir, "src/main.tsx", `const dev = import.meta.env.DEV;`)
	//    The dev-server API proxy switch the frontend's own bundler config
	//    defines (src/lib/api-base.ts, in both web scaffolds).
	writeFE(t, feDir, "src/lib/api-base.ts",
		`const p = process.env.NODE_ENV === "development" ? (process.env.FORGE_DEV_API_PROXY ?? "") : "";`+"\n"+
			`const v = import.meta.env.DEV ? (import.meta.env.FORGE_DEV_API_PROXY ?? "") : "";`)
	// 5. Vendored / generated protobuf output and build artefacts.
	writeFE(t, feDir, "src/gen/thing_pb.ts", `const z = process.env.NEXT_PUBLIC_API_URL;`)
	writeFE(t, feDir, "node_modules/pkg/index.js", `const z = process.env.NEXT_PUBLIC_API_URL;`)
	writeFE(t, feDir, ".next/static/chunk.js", `const z = process.env.NEXT_PUBLIC_API_URL;`)
	writeFE(t, feDir, "dist/bundle.js", `const z = process.env.NEXT_PUBLIC_API_URL;`)
	// 6. Type declarations, and prose that merely MENTIONS the door.
	writeFE(t, feDir, "src/env.d.ts", `declare const x: typeof process.env.NEXT_PUBLIC_API_URL;`)
	writeFE(t, feDir, "src/lib/notes.ts",
		"// These no longer read `process.env`. Values arrive from config.js.\n"+
			"/* a library reading process.env at runtime finds nothing */\n"+
			"export const ok = 1;\n")

	res := LintFrontendProcessEnv(root, []string{feDir}, finding.SeverityWarning)
	if len(res.Findings) != 0 {
		t.Fatalf("allowlisted files must produce NO findings, got %d:\n%s",
			len(res.Findings), res.FormatText())
	}
}

