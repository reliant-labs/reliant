// The fixtures below are the two halves of the seam this rule watches: a
// Tier-1 hooks file forge rewrites on every generate, and a scaffold-once
// test beside it that forge writes once and never touches again.

const queryHookFixture = `// Code generated by forge. DO NOT EDIT.
export const useGetKey = createQueryHook<typeof GetKeyRequestSchema, GetKeyResponse>(
  keyServiceKeys.getKey,
  (req) => client.getKey(req),
);
`

const mutationHookFixture = `// Code generated by forge. DO NOT EDIT.
export const useIssueMyAPIKey = createMutationHook<typeof IssueMyAPIKeyRequestSchema, IssueMyAPIKeyResponse>(
  keyServiceKeys.all,
  (req) => client.issueMyAPIKey(req),
);
`

// queryShapedTest asserts isSuccess without ever firing anything — the
// shape that only makes sense against a useQuery hook.
func queryShapedTest(hookName string) string {
	return `import { ` + hookName + ` } from "./key-service-hooks_gen";

describe("KeyService hooks", () => {
  it("` + hookName + ` resolves a happy-path response", async () => {
    const { result } = renderHook(() => ` + hookName + `({} as never), { wrapper });
    await waitFor(() => expect(result.current.isSuccess).toBe(true));
    expect(result.current.data).toBeDefined();
  });
});
`
}

// mutationShapedTest fires the mutation — the shape that only makes sense
// against a useMutation hook.
func mutationShapedTest(hookName string) string {
	return `import { ` + hookName + ` } from "./key-service-hooks_gen";

describe("KeyService hooks", () => {
  it("` + hookName + ` resolves a happy-path response", async () => {
    const { result } = renderHook(() => ` + hookName + `(), { wrapper });
    await result.current.mutateAsync({} as never).catch(() => {});
    expect(result.current).toBeDefined();
  });
});
`
}

// writeHookPair lays down a hooks file and its sibling test in a frontend
// tree, returning the project root.
func writeHookPair(t *testing.T, hookBody, testBody string) string {
	t.Helper()
	dir := t.TempDir()
	hooksDir := filepath.Join(dir, "frontends", "web", "src", "hooks")
	if err := os.MkdirAll(hooksDir, 0o755); err != nil {
		t.Fatal(err)
	}
	mustWrite(t, filepath.Join(hooksDir, "key-service-hooks_gen.ts"), hookBody)
	if testBody != "" {
		mustWrite(t, filepath.Join(hooksDir, "key-service-hooks.test.tsx"), testBody)
	}
	return dir
}

// TestLintFrontendHookTestShape_FlagsQueryTestAgainstMutationHook is the
// regression this rule exists for.
//
// The scaffolded test and the hook it exercises are written from ONE
// classification, so they agree the day they are generated. But the hooks
// file is Tier-1 (rewritten every generate, and gitignored in the default
// scaffold) while the test is scaffold-once (written once, never
// overwritten). So the two are only pinned together in TIME: the moment
// the classification for an RPC changes — forge sharpening the name
// heuristic, or an author adding `// forge:mutation` — the hook moves and
// the frozen test does not.
//
// The result is a test that can never pass: a useMutation hook never sets
// isSuccess on its own, because nothing fired it. That is exactly what
// shipped in the control-plane dogfood for IssueMyReliantAPIKey, where a
// character-prefix match on "Is" had classified the RPC as a read.
func TestLintFrontendHookTestShape_FlagsQueryTestAgainstMutationHook(t *testing.T) {
	dir := writeHookPair(t, mutationHookFixture, queryShapedTest("useIssueMyAPIKey"))

	res, err := LintFrontendHookTestShape(dir)
	if err != nil {
		t.Fatalf("LintFrontendHookTestShape: %v", err)
	}
	if len(res.Findings) != 1 {
		t.Fatalf("expected 1 finding for a query-shaped test against a mutation hook, got %d: %+v",
			len(res.Findings), res.Findings)
	}
	f := res.Findings[0]
	if f.Rule != "forgeconv-frontend-hook-test-shape" {
		t.Errorf("rule = %q", f.Rule)
	}
	if f.Severity != SeverityError {
		t.Errorf("severity = %q, want error — the test cannot pass, so it is not a warning", f.Severity)
	}
	if !strings.Contains(f.Message, "useIssueMyAPIKey") {
		t.Errorf("message must name the drifted hook, got: %q", f.Message)
	}
	if !strings.Contains(f.File, "key-service-hooks.test.tsx") {
		t.Errorf("finding must point at the TEST (the editable half), got file %q", f.File)
	}
}

