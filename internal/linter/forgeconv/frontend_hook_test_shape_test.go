// reliantRunServiceStarter is the starter forge scaffolded for reliant's
// RunService while LastRunPerWorkflow was still a mutation (trimmed to three
// rows). After `option idempotency_level = NO_SIDE_EFFECTS` its hook became a
// useQuery and this test kept calling mutateAsync on it (#1508).
const reliantRunServiceStarter = `import { useGetRun } from "./run-service-hooks_gen";
import { useLastRunPerWorkflow } from "./run-service-hooks_gen";
import { usePauseRun } from "./run-service-hooks_gen";

async function waitForSettled(result: { current: { status: string } }) {
  await waitFor(() => expect(["success", "error"]).toContain(result.current.status));
}

describe("RunService hooks", () => {
  it("useGetRun resolves a happy-path response", async () => {
    const { result } = renderHook(() => useGetRun({} as never), { wrapper });
    await waitFor(() => expect(result.current.isSuccess).toBe(true));
  });

  it("useLastRunPerWorkflow resolves a happy-path response", async () => {
    const { result } = renderHook(() => useLastRunPerWorkflow(), { wrapper });
    await result.current.mutateAsync({} as never).catch(() => {});
    await waitForSettled(result);
  });

  it("usePauseRun resolves a happy-path response", async () => {
    const { result } = renderHook(() => usePauseRun(), { wrapper });
    await result.current.mutateAsync({} as never).catch(() => {});
    await waitForSettled(result);
  });
});
`

const reliantRunServiceHooks = `// Code generated by forge. DO NOT EDIT.
export const useGetRun = createQueryHook<typeof GetRunRequestSchema, GetRunResponse>(
export const useLastRunPerWorkflow = createQueryHook<typeof LastRunPerWorkflowRequestSchema, LastRunPerWorkflowResponse>(
export const usePauseRun = createMutationHook<typeof PauseRunRequestSchema, PauseRunResponse>(
`

// TestLintFrontendHookTestShape_ReliantRunServiceRowAtItsLine replays #1508:
// one stale row among fresh ones is reported, at the row's own line (it
// used to be line 1 of the file), with the replacement body.
func TestLintFrontendHookTestShape_ReliantRunServiceRowAtItsLine(t *testing.T) {
	dir := t.TempDir()
	hooksDir := filepath.Join(dir, "frontends", "web", "src", "hooks")
	if err := os.MkdirAll(hooksDir, 0o755); err != nil {
		t.Fatal(err)
	}
	mustWrite(t, filepath.Join(hooksDir, "run-service-hooks_gen.ts"), reliantRunServiceHooks)
	mustWrite(t, filepath.Join(hooksDir, "run-service-hooks.test.tsx"), reliantRunServiceStarter)

	res, err := LintFrontendHookTestShape(dir)
	if err != nil {
		t.Fatal(err)
	}
	if len(res.Findings) != 1 {
		t.Fatalf("want exactly the LastRunPerWorkflow row, got %+v", res.Findings)
	}
	f := res.Findings[0]
	wantLine := strings.Count(reliantRunServiceStarter[:strings.Index(reliantRunServiceStarter, `it("useLastRunPerWorkflow`)], "\n") + 1
	if f.Line != wantLine {
		t.Errorf("line = %d, want %d (the row's own `it(` line)", f.Line, wantLine)
	}
	if f.File != "frontends/web/src/hooks/run-service-hooks.test.tsx" {
		t.Errorf("file = %q", f.File)
	}
	if !strings.Contains(f.Remediation, "renderHook(() => useLastRunPerWorkflow({} as never), { wrapper });") {
		t.Errorf("remediation must carry the query row's body, got:\n%s", f.Remediation)
	}
}

// TestStaleHookTestRows_SharedComparison pins the comparison `forge
// generate` makes from in-memory kinds: a hook absent from the map is
// skipped, and a hand-written row is never stale.
func TestStaleHookTestRows_SharedComparison(t *testing.T) {
	kinds := map[string]bool{"useGetRun": true, "useLastRunPerWorkflow": true, "usePauseRun": false}
	stale := StaleHookTestRows(reliantRunServiceStarter, kinds)
	if len(stale) != 1 || stale[0].Hook != "useLastRunPerWorkflow" || stale[0].Query {
		t.Fatalf("want the one mutation-shaped LastRunPerWorkflow row, got %+v", stale)
	}
	if got := StaleHookTestRows(reliantRunServiceStarter, map[string]bool{"useOther": true}); len(got) != 0 {
		t.Errorf("rows about hooks outside the map must be skipped, got %+v", got)
	}
	hand := `it("useGetRun is wired", () => { expect(useGetRun).toBeTypeOf("function"); });`
	if got := StaleHookTestRows(hand, map[string]bool{"useGetRun": false}); len(got) != 0 {
		t.Errorf("a hand-written row is not a starter row, got %+v", got)
	}
}

// TestStaleRowsOrphanSettleHelper: waitForSettled has callers only in
// mutation rows, so flipping the last one leaves it unused.
func TestStaleRowsOrphanSettleHelper(t *testing.T) {
	stillMutating := map[string]bool{"useGetRun": true, "useLastRunPerWorkflow": true, "usePauseRun": false}
	if StaleRowsOrphanSettleHelper(reliantRunServiceStarter, stillMutating) {
		t.Error("usePauseRun still calls waitForSettled; the helper is not orphaned")
	}
	allQueries := map[string]bool{"useGetRun": true, "useLastRunPerWorkflow": true, "usePauseRun": true}
	if !StaleRowsOrphanSettleHelper(reliantRunServiceStarter, allQueries) {
		t.Error("with every row a query row, waitForSettled has no caller left")
	}
}

// TestHookTestRowFix_MutationBodyNeedsNoHelper: a query-only service's
// starter declares no waitForSettled, so the mutation fix must not call it.
func TestHookTestRowFix_MutationBodyNeedsNoHelper(t *testing.T) {
	fix := HookTestRowFix("useIssueKey", false)
	if strings.Contains(fix, "waitForSettled") || !strings.Contains(fix, "mutateAsync(") {
		t.Errorf("mutation fix must fire the mutation and wait inline:\n%s", fix)
	}
	if fix := HookTestRowFix("useGetKey", true); !strings.Contains(fix, "isSuccess") {
		t.Errorf("query fix must await isSuccess:\n%s", fix)
	}
}
