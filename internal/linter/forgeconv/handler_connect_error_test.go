const handlerConnectErrorFixture = `package thing

import (
	"context"
	"errors"
	"fmt"

	"connectrpc.com/connect"
)

func fixed() error {
	return connect.NewError(connect.CodeInvalidArgument, errors.New("id is required"))
}

func fixedFormat(name string) error {
	return connect.NewError(connect.CodeAlreadyExists, fmt.Errorf("name %q is taken", name))
}

func wrapped(err error) error {
	return connect.NewError(connect.CodeInternal, fmt.Errorf("failed to push: %w", err))
}

func bare(ctx context.Context, err error) error {
	return connect.NewError(connect.CodeNotFound, err)
}

func formatted(err error) error {
	return connect.NewError(connect.CodeInternal, fmt.Errorf("list: %v", err))
}

func text(err error) error {
	return connect.NewError(connect.CodeUnavailable, errors.New(err.Error()))
}

func none() error {
	return connect.NewError(connect.CodeUnauthenticated, nil)
}
`

// TestHandlerConnectError_FlagsEveryCallAndNamesItsKind: one warning per
// connect.NewError, phrased for its shape — a fixed message (the codemod
// rewrites it), an error value (it leaks; WrapOr), and nil.
func TestHandlerConnectError_FlagsEveryCallAndNamesItsKind(t *testing.T) {
	tmp := t.TempDir()
	pkgDir := filepath.Join(tmp, "internal", "handlers", "thing")
	must(t, mkdirAll(pkgDir))
	must(t, writeFile(filepath.Join(pkgDir, "thing.go"), handlerConnectErrorFixture))

	res, err := LintHandlerErrorMapping(tmp)
	if err != nil {
		t.Fatalf("LintHandlerErrorMapping: %v", err)
	}
	got := findingsForRule(res.Findings, handlerConnectErrorRule)
	if len(got) != 7 {
		t.Fatalf("expected 7 findings (one per connect.NewError), got %d:\n%s", len(got), res.FormatText())
	}
	want := []struct {
		line        int
		message     string
		remediation string
	}{
		{12, "fixed message", "svcerr.InvalidArgument(\"<message>\")"},
		{16, "fixed message", "svcerr.AlreadyExists("},
		{20, "publishes its Error() text", "svcerr.WrapOr(err, svcerr.Internal("},
		{24, "publishes its Error() text", "svcerr.WrapOr(err, svcerr.NotFound("},
		{28, "publishes its Error() text", "svcerr.WrapOr(err, svcerr.Internal("},
		{32, "publishes its Error() text", "svcerr.WrapOr(err, svcerr.Unavailable("},
		{36, "nil error", "svcerr.ErrUnauthenticated"},
	}
	for i, w := range want {
		f := got[i]
		if f.Line != w.line || !strings.Contains(f.Message, w.message) || !strings.Contains(f.Remediation, w.remediation) {
			t.Errorf("finding %d = line %d %q → %q; want line %d containing %q → %q", i, f.Line, f.Message, f.Remediation, w.line, w.message, w.remediation)
		}
		if f.Severity != SeverityWarning {
			t.Errorf("finding %d severity = %s, want warning (a project flips it to error once migrated)", i, f.Severity)
		}
	}
	if !strings.Contains(got[0].Remediation, "forge fix connect-errors") {
		t.Errorf("a fixed-message finding should point at the codemod: %s", got[0].Remediation)
	}
}

// TestHandlerConnectError_SkipsGeneratedTestAndNonHandlerFiles: a generated
// file is the generator's to fix, a test may build a connect error as a
// fixture, and the rule covers handler packages only.
func TestHandlerConnectError_SkipsGeneratedTestAndNonHandlerFiles(t *testing.T) {
	tmp := t.TempDir()
	call := "\nfunc f() error { return connect.NewError(connect.CodeInternal, errors.New(\"x\")) }\n"
	imports := "import (\n\t\"errors\"\n\n\t\"connectrpc.com/connect\"\n)\n"
	files := map[string]string{
		"internal/handlers/mocks/thing_mock_gen.go": "// Code generated by forge. DO NOT EDIT.\n\npackage mocks\n\n" + imports + call,
		"internal/handlers/thing/thing_test.go":     "package thing\n\n" + imports + call,
		"internal/interceptors/auth.go":             "package interceptors\n\n" + imports + call,
	}
	for rel, body := range files {
		path := filepath.Join(tmp, filepath.FromSlash(rel))
		must(t, mkdirAll(filepath.Dir(path)))
		must(t, writeFile(path, body))
	}
	res, err := LintHandlerErrorMapping(tmp)
	if err != nil {
		t.Fatalf("LintHandlerErrorMapping: %v", err)
	}
	if got := findingsForRule(res.Findings, handlerConnectErrorRule); len(got) != 0 {
		t.Fatalf("expected no findings, got %d:\n%s", len(got), res.FormatText())
	}
}

func TestConnectErrorArgShape(t *testing.T) {
	cases := map[string]connectErrorArg{
		`errors.New("x")`:                     argFixedMessage,
		"errors.New(`x`)":                     argFixedMessage,
		`fmt.Errorf("x %s", req.GetName())`:   argFixedMessage,
		`fmt.Errorf("x %d", n)`:               argFixedMessage,
		`nil`:                                 argNil,
		`err`:                                 argErrorValue,
		`fmt.Errorf("x: %w", err)`:            argErrorValue,
		`fmt.Errorf("x: %s", err)`:            argErrorValue,
		`fmt.Errorf("x: %s", dbErr)`:          argErrorValue,
		`fmt.Errorf("x: %s", res.Error())`:    argErrorValue,
		`errors.New(msg)`:                     argErrorValue,
		`fmt.Errorf(format, a)`:               argErrorValue,
		`svcerr.Draining("gateway draining")`: argErrorValue,
	}
	for src, want := range cases {
		e, err := parser.ParseExpr(src)
		if err != nil {
			t.Fatalf("parse %s: %v", src, err)
		}
		if got := connectErrorArgShape(e); got != want {
			t.Errorf("connectErrorArgShape(%s) = %d, want %d", src, got, want)
		}
	}
}
