-- +goose Up
-- When a gateway last heard from this daemon on a stream that has since ended:
-- the released lease's last_stream_activity, written by
-- ReleaseDaemonAttachment as the session tears down.
--
-- The lease itself is deleted on release, so before this column a daemon that
-- dropped a second ago and one whose laptop was closed last week read exactly
-- alike: no lease, no NATS responder. A tool call needs to tell them apart. A
-- daemon-gateway rollout drains every stream and each daemon redials within
-- 15-25s (prod 2026-10-10); a tool call that finds such a daemon gone waits
-- for it to come back, while one whose machine has been away for long keeps
-- failing at once (toolexec's reconnect wait reads this through
-- DaemonLastSeenAt).
--
-- NULL until a session of the daemon ends after this migration: nothing to
-- backfill, since a daemon with no recent release is exactly one a tool call
-- should not wait for.
--
-- IF NOT EXISTS: migrations are replayed against databases built from
-- schema.sql (see 20261004201053_add_local_models_to_daemons.sql).
ALTER TABLE daemons ADD COLUMN IF NOT EXISTS last_seen_at TIMESTAMPTZ;
