// Package codegen — config_schema_gen.go emits a typed KCL
// `schema AppConfig` projected from the proto config fields
// (the `(forge.v1.config)`-annotated fields of proto/<project>/config/v1/config.proto).
//
// This is the TYPE half of the config-as-KCL story: it projects the SHAPE —
// one KCL schema whose fields mirror the proto config fields, so an env authors
// its config as a typed `AppConfig { ... }` instance in
// `deploy/kcl/<env>/config.k` and KCL type-checks it against the proto's own
// contract (required fields, types, defaults) at load time.
//
// The runtime Go loader (pkg/config/loader.go), which binds env by each field's
// `env_var` annotation via descriptor reflection, describes the same fields, so
// the two stay coherent by construction.
package codegen

import (
	"fmt"
	"strconv"
	"strings"

	"github.com/reliant-labs/forge/internal/configproto"
	"github.com/reliant-labs/forge/internal/naming"
)

// ConfigSchemaModule is the KCL module name (and filename stem) the config
// projection is emitted under: deploy/kcl/config_gen.k. It carries BOTH
// halves — the TYPE (`schema AppConfig` / `schema ConfigSecretRef`, emitted
// here) and the BEHAVIOR (`appConfigEnvMap`, emitted by
// config_projection_gen.go) — because both are projected from the same
// proto by the same generate run and are only ever correct together.
//
// Each per-env values file (config.k) and each env's main.k import it by
// THIS name and qualify the symbols as `config_gen.AppConfig`,
// `config_gen.appConfigEnvMap` etc. — KCL does not share top-level symbols
// across separately-imported modules, so the reference must be qualified.
//
// The `_gen` suffix is forge's Tier-1 naming convention: a file forge
// rewrites on every run says so in its own name.
const ConfigSchemaModule = "config_gen"

// LegacyConfigModules names the pre-merge KCL modules that config_gen.k
// replaced: the TYPE half (config_schema.k) and the BEHAVIOR half
// (config_projection.k), which were two Tier-1 files, two hash guards and
// two diff entries for one projection. Existing projects have them on
// disk; RemoveLegacyConfigModules withdraws forge's own copies once the
// merged file is in place.
func LegacyConfigModules() []string { return []string{"config_schema", "config_projection"} }

// GenerateConfigSchemaKCL emits a KCL file declaring `schema AppConfig`,
// one field per proto config field in proto order. Each field's KCL type
// is mapped from its proto type (see kclTypeForProtoConfig) and its
// default is projected from the proto annotation (see
// kclConfigDefaultLiteral). Fields with a description get a leading `#`
// doc comment.
//
// Component config-block references — a message-typed field whose target
// message carries its OWN config fields — arrive from forge's descriptor
// extractor as ProtoType == "message" WITH MessageType set to the block's
// name (e.g. "TraderConfig") and NO env_var of their own. They carry no
// scalar KCL type and env binds on the referenced message's leaves, so
// they are skipped with a comment marking the omission.
//
// NOTE the discriminator is MessageType, not ProtoType == "message":
// forge's extractor (internal/cli/forge_descriptor.go) collapses EVERY
// message kind to ProtoType "message", so a `google.protobuf.Duration`
// LEAF field also has ProtoType "message" (with GoType "string",
// MessageType unset, env_var set). Those are real scalar-carried config
// leaves and MUST be emitted (as `str`), not skipped — keying the skip on
// MessageType is what tells the two apart.
func GenerateConfigSchemaKCL(fields []ConfigField, projectName string) (string, error) {
	var b strings.Builder

	// 2-line generated-file header. Line 1 is the standard forge stamp;
	// line 2 tells the reader where to author values and where to add
	// fields (the proto, never this generated file).
	b.WriteString("# Code generated by forge. DO NOT EDIT.\n")
	b.WriteString("# Typed config schema projected from " + configProtoDir(projectName) + "/config.proto — author per-env values in deploy/kcl/<env>/config.k as an `AppConfig { ... }` instance; add or change fields in the PROTO, never here.\n\n")

	body, err := renderAppConfigSchema(fields, projectName)
	if err != nil {
		return "", err
	}
	b.WriteString(body)
	return b.String(), nil
}

// renderAppConfigSchema emits the TYPE half — `schema ConfigSecretRef` +
// `schema AppConfig` — with no file header or imports, so it can be
// concatenated with the projection half into the single generated
// config_gen.k (see GenerateConfigKCL).
func renderAppConfigSchema(fields []ConfigField, projectName string) (string, error) {
	return renderConfigSchemaNamed(fields, projectName, "AppConfig", true)
}

// renderConfigSchemaNamed emits one typed config schema under schemaName.
// It is the per-binary generalization of renderAppConfigSchema: a project
// with per-binary configs emits one schema per binary (AdminConfig,
// GatewayConfig, …), each carrying ONLY that binary's fields, so an env
// authoring a value for a field the binary does not read is a KCL type
// error rather than a silently ignored line.
//
// withSecretRef emits the shared `schema ConfigSecretRef` alongside. It is
// declared exactly once per module, so only the first schema in a file asks
// for it.
func renderConfigSchemaNamed(fields []ConfigField, projectName, schemaName string, withSecretRef bool) (string, error) {
	root, blocks := partitionConfigBlocks(fields)
	if err := CheckDuplicateConfigFields(root, ConfigSchemaModule, schemaName); err != nil {
		return "", err
	}
	// Each block is its own KCL namespace, so a leaf name is only a duplicate
	// WITHIN one block — two blocks may both declare `base_domain`.
	for _, blk := range blocks {
		if err := CheckDuplicateConfigFields(blk.Fields, ConfigSchemaModule, blk.schemaName(schemaName)); err != nil {
			return "", err
		}
	}
	// A block field and a root scalar of the same name would be two schema
	// members fighting over one key; exactly one would survive.
	for _, blk := range blocks {
		for _, f := range root {
			if f.Name == blk.Field {
				return "", fmt.Errorf("%s.k: %q is both a field of %s and the config block %s — rename one in the proto",
					ConfigSchemaModule, blk.Field, schemaName, blk.Type)
			}
		}
	}

	var b strings.Builder

	// ConfigSecretRef is the typed model for a SENSITIVE config field: a
	// reference to the Secret NAME + KEY that backs it, never the secret
	// VALUE. It is named ConfigSecretRef (not SecretRef) to avoid clashing
	// with the forge module's own secret schemas (RenderedSecretKey et al.).
	// Every sensitive field defaults to `{ name = "<project>-secrets", key =
	// "<lower(env_var)>" }` — the same default backend the Go projector wires
	// — so an AppConfig instance need only spell a ConfigSecretRef for fields
	// that point at a DIFFERENT Secret/key (the ${NAME#KEY} override case).
	if withSecretRef {
		b.WriteString("schema ConfigSecretRef:\n")
		b.WriteString("    name: str\n")
		b.WriteString("    key: str\n\n")
	}

	// One nested schema per composed block, declared BEFORE the root schema
	// that instantiates it. Its name is scoped by the root schema
	// (AppConfigStripe) so per-binary configs composing the same block each
	// get their own, and a block message name can never shadow a root schema.
	for _, blk := range blocks {
		name := blk.schemaName(schemaName)
		fmt.Fprintf(&b, "# %s is the %s block (%s) — author its values in config.k as `%s.<field> = ...`.\n", name, blk.Field, blk.Type, blk.Field)
		b.WriteString("schema " + name + ":\n")
		blockBody, emitted := renderConfigSchemaFields(blk.Fields, projectName)
		if emitted == 0 {
			b.WriteString("    \"\"\"No config fields.\"\"\"\n\n")
			continue
		}
		b.WriteString(blockBody)
		b.WriteString(renderEmptyEnvChecks(blk.Fields))
		b.WriteString("\n")
	}

	b.WriteString("schema " + schemaName + ":\n")

	rootBody, emitted := renderConfigSchemaFields(root, projectName)
	var body strings.Builder
	body.WriteString(rootBody)
	for _, blk := range blocks {
		name := blk.schemaName(schemaName)
		fmt.Fprintf(&body, "    # %s config block (%s). Set its fields as `%s.<field> = ...`.\n", blk.Field, blk.Type, blk.Field)
		fmt.Fprintf(&body, "    %s: %s = %s {}\n", blk.Field, name, name)
		emitted++
	}

	if emitted == 0 {
		// A KCL schema suite must be non-empty. A docstring-only suite is
		// valid KCL and doubles as the placeholder note.
		b.WriteString("    # No (forge.v1.config)-annotated config fields were found.\n")
		b.WriteString("    \"\"\"No config fields projected from " + configProtoDir(projectName) + "/config.proto yet — add `(forge.v1.config)`-annotated fields to the proto to populate this schema.\"\"\"\n")
		return b.String(), nil
	}

	b.WriteString(body.String())
	// The check block closes the suite: KCL wants it after every member,
	// the composed blocks included.
	b.WriteString(renderEmptyEnvChecks(root))
	return b.String(), nil
}

// renderEmptyEnvChecks emits the schema `check:` block refusing an empty
// string for each field that has a non-empty default, or "" when no field
// needs one.
//
// The runtime loader reads an env var set to "" as unset (pkg/config's
// lookupEnv), so the env map can carry an empty value but the process never
// sees it: `pprof_addr = ""` in config.k would render `PPROF_ADDR: ""` and
// the process would load the default 127.0.0.1:6060. An env value that
// renders cleanly and is then ignored is the silent fallback the loader
// refuses everywhere else, so the render fails instead, naming the flag that
// does carry an empty value. A field whose default is empty needs no check:
// "" and unset load the same value.
//
// Sensitive fields are references, not values, and a str with an empty
// default has nothing to fall back to, so neither gets a check.
func renderEmptyEnvChecks(fields []ConfigField) string {
	var conds []string
	for _, f := range fields {
		if f.MessageType != "" || f.Sensitive || f.EnvVar == "" || f.DefaultValue == "" || kclTypeForProtoConfig(f) != "str" {
			continue
		}
		// Only a string (or bytes) field has an empty VALUE to offer. A
		// duration or an enum, also a str here, has none: "" fails to parse.
		how := "set a value"
		if f.ProtoType == "string" || f.ProtoType == "bytes" {
			how = "set a value, or change its default in the proto"
			if f.Flag != "" {
				how = fmt.Sprintf("set a value, or pass --%s= in the workload's args to make it empty", f.Flag)
			}
		}
		msg := fmt.Sprintf("%s = \"\" cannot reach the process: an empty %s counts as unset, so it would load the default %q — %s",
			f.Name, f.EnvVar, f.DefaultValue, how)
		conds = append(conds, fmt.Sprintf("        %s != \"\", %s\n", f.Name, strconv.Quote(msg)))
	}
	if len(conds) == 0 {
		return ""
	}
	return "\n    check:\n" + strings.Join(conds, "")
}

// configBlock is one composed config block in a schema's field list.
type configBlock struct {
	Field  string // the composing field on the root message, e.g. "stripe"
	Type   string // the block message, e.g. "StripeConfig"
	Fields []ConfigField
}

// schemaName is the nested KCL schema this block projects to, scoped by the
// schema that composes it: AppConfig + stripe -> AppConfigStripe.
func (c configBlock) schemaName(parent string) string {
	return parent + naming.ToPascalCase(c.Field)
}

// partitionConfigBlocks splits a flattened field list into its root fields and
// its composed blocks (ConfigField.KCLBlock), preserving first-appearance order
// for both so the emitted module is byte-stable.
func partitionConfigBlocks(fields []ConfigField) (root []ConfigField, blocks []configBlock) {
	idx := map[string]int{}
	for _, f := range fields {
		if f.KCLBlock == "" {
			root = append(root, f)
			continue
		}
		i, ok := idx[f.KCLBlock]
		if !ok {
			i = len(blocks)
			idx[f.KCLBlock] = i
			blocks = append(blocks, configBlock{Field: f.KCLBlock, Type: f.KCLBlockType})
		}
		blocks[i].Fields = append(blocks[i].Fields, f)
	}
	return root, blocks
}

// renderConfigSchemaFields renders the member lines of one schema suite and
// how many members it declared.
func renderConfigSchemaFields(fields []ConfigField, projectName string) (string, int) {
	var body strings.Builder
	emitted := 0
	for _, f := range fields {
		if f.MessageType != "" {
			// Block-reference to a config message that the flattener did not
			// expand (an unknown message). A duration/WKT leaf has ProtoType
			// "message" too but NO MessageType — it is emitted below as a str.
			fmt.Fprintf(&body, "    # (omitted) %s references config message %q, which is not a known config message.\n", f.Name, f.MessageType)
			continue
		}
		if d := strings.TrimSpace(f.Description); d != "" {
			// Collapse embedded newlines so the doc comment stays a single
			// KCL comment line.
			d = strings.Join(strings.Fields(d), " ")
			fmt.Fprintf(&body, "    # %s\n", d)
		}
		if f.Sensitive {
			// A sensitive field is typed as a ConfigSecretRef, not a str: its
			// value is a Secret name+key reference, never an inline value. It
			// ALWAYS carries the default-backend literal (even when required),
			// so the author only spells a ConfigSecretRef to override the
			// backing Secret/key. This mirrors the Go projector, which wires a
			// default secret_ref for every sensitive field regardless of
			// per-env value.
			secretName := fmt.Sprintf("%s-secrets", projectName)
			secretKey := strings.ToLower(f.EnvVar)
			fmt.Fprintf(&body, "    %s: ConfigSecretRef = ConfigSecretRef { name = %q, key = %q }\n",
				f.Name, secretName, secretKey)
			emitted++
			continue
		}
		kt := kclTypeForProtoConfig(f)
		if lit, ok := kclConfigDefaultLiteral(f); ok {
			fmt.Fprintf(&body, "    %s: %s = %s\n", f.Name, kt, lit)
		} else {
			// Required field with no default: no `= ...` means KCL requires
			// the author to set it in their AppConfig instance.
			fmt.Fprintf(&body, "    %s: %s\n", f.Name, kt)
		}
		emitted++
	}
	return body.String(), emitted
}

// CheckDuplicateConfigFields refuses a field set that would declare the same
// field name twice inside ONE generated KCL schema.
//
// KCL accepts a repeated field in a schema suite silently and the LAST
// declaration wins, so the first field's default is discarded with no
// diagnostic. That is not a style problem — it is a value the operator never
// wrote appearing in a rendered manifest. Observed in production: a config
// proto declared `app_url = "http://localhost:3000"` and a second config
// proto, flattened into the same AppConfig, declared `app_url = ""`. The
// empty string won, three prod workloads shipped `APP_URL: ”`, and the
// consumer gated a browser auth redirect on the value being non-empty — so
// the collision silently downgraded that redirect to a bare 401. Nothing in
// any diff showed it, because config_gen.k is generated and nobody reads it.
//
// The refusal is per SCHEMA, never across schemas. A project with per-binary
// configs emits AdminConfig, GatewayConfig and so on into the same module,
// and those legitimately share field names — `port` on both binaries is two
// separate declarations in two separate suites, which is the whole point of
// splitting them. Only a repeat WITHIN one suite shadows anything.
//
// Block-reference fields (MessageType set) are exempt: they project to a
// comment rather than a schema field, so two of them cannot shadow each
// other. They are still checked against SCALAR fields of the same name,
// because that pair does produce one real declaration plus a confusing
// comment, and it means the proto author has two different fields fighting
// over one name.
//
// module names the KCL module the schema lands in (ConfigSchemaModule,
// FrontendConfigModule, …) so the message points at the file that would
// actually have carried the shadowed field.
func CheckDuplicateConfigFields(fields []ConfigField, module, schemaName string) error {
	firstSeen := make(map[string]ConfigField, len(fields))
	for _, f := range fields {
		prior, dup := firstSeen[f.Name]
		if !dup {
			firstSeen[f.Name] = f
			continue
		}
		return fmt.Errorf(
			"%s.k: field %q is declared twice in schema %s%s\n"+
				"  — KCL silently keeps the LAST declaration, so the first field's default is discarded.\n"+
				"  Rename one field or remove the duplicate.",
			module, f.Name, schemaName, duplicateFieldSources(prior, f))
	}
	return nil
}

// duplicateFieldSources renders the provenance clause naming where the two
// colliding declarations came from. It degrades rather than lying: a
// descriptor written by an older forge carries no ProtoFile, and a made-up
// path would send the author to the wrong file, so an unknown source is
// simply omitted and a collision with no known source at all renders nothing.
func duplicateFieldSources(first, second ConfigField) string {
	switch {
	case first.ProtoFile != "" && second.ProtoFile != "" && first.ProtoFile != second.ProtoFile:
		return fmt.Sprintf("\n  (declared by both %s and %s)", first.ProtoFile, second.ProtoFile)
	case first.ProtoFile != "" && second.ProtoFile != "":
		// Same file twice — the proto itself repeats the name, or one
		// message composes another from the same file.
		return fmt.Sprintf("\n  (both declarations are in %s)", first.ProtoFile)
	case first.ProtoFile != "":
		return fmt.Sprintf("\n  (one declaration is in %s)", first.ProtoFile)
	case second.ProtoFile != "":
		return fmt.Sprintf("\n  (one declaration is in %s)", second.ProtoFile)
	default:
		return ""
	}
}

// kclTypeForProtoConfig maps a config field's proto type to its KCL type.
//
//	string, bytes             -> str  (bytes is base64, as protojson sends it)
//	every integer kind        -> int
//	float/double              -> float
//	bool                      -> bool
//	google.protobuf.Duration  -> str  (forge carries durations as strings
//	                                    like "30m"/"5s")
//	enum                      -> str  (protojson encodes the value NAME)
//
// The scalar half routes through the closed table by way of the Go type,
// not through a list of proto kind names. The Go type is the right key
// because it is the one that separates `int` from `float`, which the
// TypeScript projection does not: int32 and double are both `number` there
// and must not be the same KCL type here.
//
// Naming a subset of the kinds is what this used to do — "int32", "int64",
// "uint32", "uint64" and no others — so the eight remaining integer kinds
// took the `str` fallback. A `sint64 max_retries` config field was typed
// `int` on the Go struct and `str` in the emitted KCL schema, and the KCL
// schema is what validates the operator's values: the fallback did not
// report a kind it did not know, it answered `str` and looked right.
func kclTypeForProtoConfig(f ConfigField) string {
	// Durations render as strings regardless of how the descriptor spells
	// them (proto message name or the Go time.Duration alias).
	if f.ProtoType == "google.protobuf.Duration" || f.GoType == "time.Duration" || f.GoType == "*durationpb.Duration" {
		return "str"
	}
	if goType, ok := ProtoScalarGoType(f.ProtoType); ok {
		return kclTypeForGoScalar(goType)
	}
	switch f.ProtoType {
	case "message":
		// A message-typed LEAF that reached here (MessageType unset, so
		// it's not a block reference) is a well-known scalar-carried type —
		// today only google.protobuf.Duration, which forge carries as a
		// string ("30m"/"5s"). GoType confirms it ("string").
		return "str"
	default:
		// enum, and any non-scalar a descriptor spells by type name.
		return "str"
	}
}

// kclTypeForGoScalar names the KCL type for one Go type in the closed proto
// scalar projection. It is total over that projection's nine values —
// TestKCLType_IsTotalOverTheClosedVocabulary pins that every kind in the
// table lands on a named arm — so the tail is a programming error rather
// than a config field shape.
func kclTypeForGoScalar(goType string) string {
	switch goType {
	case "string":
		return "str"
	case "bool":
		return "bool"
	case "float32", "float64":
		return "float"
	case "int32", "int64", "uint32", "uint64":
		return "int"
	case "[]byte":
		// No KCL scalar holds bytes; base64 is the encoding the field
		// already has on the wire.
		return "str"
	}
	panic("codegen: no KCL type for Go scalar type " + goType)
}

// kclConfigDefaultLiteral returns the KCL default literal for a config
// field and whether one should be emitted.
//
//   - DefaultValue set  -> the literal in the field's KCL type
//     (str/duration quoted, int/float bare, bool True/False).
//   - Required, no default -> ("", false): emit no default so KCL requires
//     the author to set the field.
//   - Neither required nor default -> the type-zero literal ("" / 0 /
//     False / 0.0) so an AppConfig instance is easy to construct.
func kclConfigDefaultLiteral(f ConfigField) (string, bool) {
	kt := kclTypeForProtoConfig(f)

	if f.DefaultValue != "" {
		switch kt {
		case "str":
			// Covers plain strings AND durations (carried as strings).
			return strconv.Quote(f.DefaultValue), true
		case "int", "float":
			// Numeric literals are emitted bare, straight from the proto.
			return f.DefaultValue, true
		case "bool":
			if isKCLTruthy(f.DefaultValue) {
				return "True", true
			}
			return "False", true
		}
	}

	if f.Required {
		// No default + required: KCL makes an undefaulted field mandatory.
		return "", false
	}

	// Neither required nor default: emit the type-zero so callers can
	// instantiate AppConfig without spelling every field.
	switch kt {
	case "str":
		return `""`, true
	case "int":
		return "0", true
	case "bool":
		return "False", true
	case "float":
		return "0.0", true
	default:
		return `""`, true
	}
}

// isKCLTruthy interprets a proto default_value string as a bool.
func isKCLTruthy(v string) bool {
	switch strings.ToLower(strings.TrimSpace(v)) {
	case "true", "1", "yes", "t":
		return true
	default:
		return false
	}
}

// configProtoDir is the directory declaring the project's config protos
// (internal/configproto), as the generated files' comments name it.
func configProtoDir(projectName string) string {
	return configproto.For(projectName).Dir()
}
