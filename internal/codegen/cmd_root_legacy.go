// Backwards compatibility for the retired cmd/<bin>/cmd/root_gen.go.
//
// THE PROBLEM THIS SOLVES. root_gen.go held ServiceName, the migration source,
// and generatedCommands, and forge no longer emits it: a new project gets those
// facts from its own scaffold-once root.go (ServiceName as a const, `db migrate`
// self-registered from db.go) and from db.Source().
//
// But root.go and serve.go are SCAFFOLD-ONCE. A project created before this
// change keeps the copies it was born with — forever, by design — and those
// copies call generatedCommands(), migrationSource(), migrationSourceDir and
// ServiceName. Forge cannot rewrite them to the new shape without destroying
// whatever the user has done to files it promised never to touch. So simply
// deleting root_gen.go leaves every existing project failing to build with five
// `undefined:` errors, and no `forge generate` run able to recover it.
//
// The shape of the fix is therefore: KEEP EMITTING root_gen.go for a project
// whose root.go still needs it, and emit nothing for a project whose root.go
// does not. The on-disk root.go is the evidence, read every run, so a project
// migrates the moment its root.go stops asking — including by the user porting
// it themselves, at which point the next run reclaims the file.
//
// The legacy file is rendered from Go rather than from a template because it is
// frozen: it exists to keep old call sites compiling, it gains no features, and
// keeping a template for it invites edits that would only ever reach projects
// on their way out of this shape.

// legacyRootGenRelPath is the retired file's project-relative path.
func legacyRootGenRelPath(bin string) string {
	return filepath.Join("cmd", bin, "cmd", "root_gen.go")
}

// rootGoNeedsLegacyGen reports whether cmd/<bin>/cmd/root.go is a pre-retirement
// copy — one that calls generatedCommands() and therefore cannot compile without
// root_gen.go beside it.
//
// generatedCommands is the discriminator rather than ServiceName because it is
// the symbol ONLY the old root.go used: the new root.go declares ServiceName
// itself, so keying on that name would misread every new project as legacy.
//
// An unreadable root.go answers false. A project with no command tree has no
// legacy call site to keep compiling, and inventing one would create a file
// nothing references.
func rootGoNeedsLegacyGen(projectDir, bin string) bool {
	body, err := os.ReadFile(filepath.Join(projectDir, "cmd", bin, "cmd", "root.go"))
	if err != nil {
		return false
	}
	return strings.Contains(string(body), "generatedCommands(")
}

// SyncLegacyRootGen keeps a pre-retirement command tree compiling, and reclaims
// root_gen.go once the tree no longer needs it.
//
// Both directions run on every generate, so the file tracks the project's real
// state: a legacy project keeps a correct root_gen.go (including the migration
// source flipping to the embedded set when it writes its first .sql), and a
// project whose root.go has moved to the new shape loses the file on the next
// run rather than carrying a stale copy that redeclares ServiceName.
func SyncLegacyRootGen(projectDir, modulePath, bin string, cs *checksums.FileChecksums) error {
	rel := legacyRootGenRelPath(bin)
	if !rootGoNeedsLegacyGen(projectDir, bin) {
		// New-shape root.go declares ServiceName itself, so a leftover
		// root_gen.go would be a redeclaration in the same package — this
		// removal is what makes the retirement safe, not merely tidy.
		RetireGenerated(projectDir, rel, cs)
		return nil
	}

	// The two facts the legacy file carries that are NOT constant.
	hasMigrations := ProjectHasSQLMigrations(projectDir)
	// `db migrate` exists exactly when db.go was scaffolded. Reading disk
	// rather than re-deriving from config keeps this agreeing with the file
	// that actually declares newDBCmd.
	_, dbErr := os.Stat(filepath.Join(projectDir, "cmd", bin, "cmd", "db.go"))
	hasDBCmd := dbErr == nil

	content := renderLegacyRootGen(modulePath, projectDir, bin, hasMigrations, hasDBCmd)
	if err := writeForgeOwned(projectDir, rel, content, cs); err != nil {
		return fmt.Errorf("write %s: %w", rel, err)
	}
	return nil
}

// renderLegacyRootGen builds the retired file for a project still on the old
// command-tree shape.
func renderLegacyRootGen(modulePath, projectDir, bin string, hasMigrations, hasDBCmd bool) []byte {
	var b strings.Builder
	b.WriteString("// Code generated by forge. DO NOT EDIT.\n")
	b.WriteString("// forge-owned: regenerated every run — do not edit (forge project disown to take ownership)\n")
	b.WriteString("//\n")
	b.WriteString("// COMPATIBILITY FILE — forge does not emit this for new projects.\n")
	b.WriteString("//\n")
	b.WriteString("// Your cmd/" + bin + "/cmd/root.go calls generatedCommands(), which means it\n")
	b.WriteString("// predates the change that moved these facts into root.go itself. root.go is\n")
	b.WriteString("// scaffold-once and yours, so forge will not rewrite it — it keeps emitting\n")
	b.WriteString("// this file instead, and your project keeps building.\n")
	b.WriteString("//\n")
	b.WriteString("// TO RETIRE THIS FILE, edit root.go (and serve.go) to the current shape:\n")
	b.WriteString("//\n")
	b.WriteString("//   1. Add `const ServiceName = \"" + projectNameFromBin(bin) + "\"` to root.go.\n")
	if hasDBCmd {
		b.WriteString("//   2. Replace the `for _, c := range generatedCommands(deps)` loop in root.go\n")
		b.WriteString("//      with a `registeredCommands` slice + `registerCommand` helper, and add\n")
		b.WriteString("//      `func init() { registerCommand(newDBCmd) }` to db.go.\n")
	} else {
		b.WriteString("//   2. Delete the `for _, c := range generatedCommands(deps)` loop from\n")
		b.WriteString("//      root.go — this project has no db.go, so it adds nothing.\n")
	}
	b.WriteString("//   3. Point serve.go's AutoMigrate at db.Source() / db.SourceDir instead of\n")
	b.WriteString("//      migrationSource() / migrationSourceDir (same for db.go's openMigrator).\n")
	b.WriteString("//\n")
	b.WriteString("// The next `forge generate` then deletes this file on its own.\n")
	b.WriteString("package cmd\n\n")

	// cobra is imported in BOTH branches: generatedCommands returns
	// []*cobra.Command either way, so the no-db branch names the type too.
	b.WriteString("import (\n")
	b.WriteString("\t\"io/fs\"\n")
	b.WriteString("\n\t\"github.com/spf13/cobra\"\n")
	if hasMigrations {
		b.WriteString("\n\tforgedb \"" + modulePath + "/db\"\n")
	}
	b.WriteString(")\n\n")

	b.WriteString("// ServiceName is this binary's app identity (semconv service.name).\n")
	b.WriteString("const ServiceName = \"" + projectNameFromBin(bin) + "\"\n\n")

	b.WriteString("// migrationSourceDir is the directory inside the embedded filesystem\n")
	b.WriteString("// that holds the SQL.\n")
	b.WriteString("const migrationSourceDir = \"migrations\"\n\n")

	if hasMigrations {
		b.WriteString("// migrationSource returns the embedded migration set.\n")
		b.WriteString("func migrationSource() fs.FS { return forgedb.MigrationsFS }\n")
	} else {
		b.WriteString("// migrationSource returns nil: db/migrations/ holds no .sql, so\n")
		b.WriteString("// db/embed_gen.go does not exist and naming it would not compile.\n")
		b.WriteString("func migrationSource() fs.FS { return nil }\n")
	}

	// The command registry, which the MODERN root.go declares itself.
	//
	// Scaffold-once files written after the retirement (auth.go, and db.go as
	// of the same change) self-register with `func init() {
	// registerCommand(newXCmd) }`, because the file that defines a
	// conditionally-scaffolded command is the file that should add it. A legacy
	// root.go has no such helper and never will — it is scaffold-once and
	// predates it — so a project that receives one of those files stops
	// compiling with `undefined: registerCommand` unless the compatibility file
	// supplies it. generatedCommands then returns what was registered, since
	// that is the only hook the legacy root.go ranges over.
	b.WriteString("\n// registeredCommands holds subcommands contributed by files that register\n")
	b.WriteString("// themselves from an init() — the shape forge scaffolds today.\n")
	b.WriteString("var registeredCommands []func(Deps) *cobra.Command\n\n")
	b.WriteString("// registerCommand adds a subcommand constructor to the tree. A file\n")
	b.WriteString("// scaffolded by current forge calls this from its own init().\n")
	b.WriteString("func registerCommand(f func(Deps) *cobra.Command) {\n")
	b.WriteString("\tregisteredCommands = append(registeredCommands, f)\n")
	b.WriteString("}\n")

	b.WriteString("\n// generatedCommands returns the subcommands forge derives for this project,\n")
	b.WriteString("// plus everything a self-registering file contributed.\n")
	b.WriteString("func generatedCommands(deps Deps) []*cobra.Command {\n")
	if hasDBCmd {
		// db.go predating the self-registering template names newDBCmd here.
		// A db.go that DOES self-register would then be added twice, so the
		// direct wiring is conditional on the file not already doing it.
		b.WriteString("\tvar cmds []*cobra.Command\n")
		b.WriteString(dbCmdWiring(projectDir, bin))
	} else {
		b.WriteString("\t// No db.go in this project, so nothing is derived directly.\n")
		b.WriteString("\tvar cmds []*cobra.Command\n")
	}
	b.WriteString("\tfor _, f := range registeredCommands {\n")
	b.WriteString("\t\tcmds = append(cmds, f(deps))\n")
	b.WriteString("\t}\n")
	b.WriteString("\treturn cmds\n")
	b.WriteString("}\n")
	return []byte(b.String())
}

// dbCmdWiring returns the generatedCommands body line that adds `db migrate`.
//
// db.go is scaffold-once, so a project holds whichever version it was born
// with: an older copy just declares newDBCmd and expects the caller to wire it,
// while the current template self-registers from an init(). Wiring it directly
// in both cases would add the command twice for the newer shape, and cobra
// would render a duplicate. The file on disk is the evidence, read the same way
// rootGoNeedsLegacyGen reads root.go.
func dbCmdWiring(projectDir, bin string) string {
	body, err := os.ReadFile(filepath.Join(projectDir, "cmd", bin, "cmd", "db.go"))
	if err == nil && strings.Contains(string(body), "registerCommand(newDBCmd)") {
		return "\t// db.go registers itself from its own init(); wiring it here too\n" +
			"\t// would add the command twice.\n"
	}
	return "\tcmds = append(cmds, newDBCmd(deps))\n"
}

// projectNameFromBin returns the binary name, which is the forge.yaml project
// name for the primary binary — the same string the retired template baked in.
func projectNameFromBin(bin string) string { return bin }
