// Package codegen — crd_kcl_gen.go projects a project's Kubernetes CRD Go
// types (api/<version>/*_types.go) into the KCL manifest module that actually
// installs those CRDs on a cluster, deploy/kcl/lib/crd_gen.k.
//
// # WHY THIS EXISTS, AND WHAT IT REPLACES
//
// A CRD used to be declared twice in a forge project: once as the Go types the
// controller reads and writes, and once as a hand-authored KCL dict that is
// what actually reaches the cluster (via Environment.additional_manifests).
// Keeping those two in agreement was a manual, unaided job, and the failure
// mode is SILENT and unbounded in time:
//
//	The API server prunes any field of a custom resource that the installed
//	structural schema does not declare. A field present in the Go type but
//	missing from the installed schema does not error anywhere — the CR
//	applies cleanly, kubectl reports success, and the controller reads a ZERO
//	VALUE forever. No build, lint or deploy notices.
//
// A test that walks both halves and reports drift is the usual mitigation, and
// it is strictly worse than not having two halves: it converts a silent
// corruption into a loud chore, but the chore still has to be done by hand on
// every field, and the test can only police the keywords someone taught it.
// Generating the KCL from the Go types removes the second declaration, so
// there is nothing left to drift and no gate to maintain.
//
// # WHY controller-tools, RATHER THAN OUR OWN AST WALK
//
// The schema semantics here are not ours to invent: which fields are required
// (the omitempty/+optional rule), how a pointer differs from a value, how
// metav1.Time and metav1.Condition project, how +kubebuilder:validation:*
// markers lower to OpenAPI keywords, how +listType=map becomes
// x-kubernetes-list-type. controller-tools IS that specification, and every
// kubebuilder project in existence agrees with it.
//
// Re-deriving those rules with a hand-rolled reflect/AST walk means owning a
// forever-incomplete reimplementation of someone else's spec, where each gap
// is a silently pruned field. So this drives controller-tools as a LIBRARY and
// lowers its output to KCL — the projection here is purely syntactic
// (OpenAPI JSON -> KCL dict literal), carrying no schema opinions of its own.
//
// Driving the library rather than shelling out to the controller-gen BINARY is
// what makes `forge generate` hermetic: no PATH dependency, no separately
// installed tool whose version can disagree with the schema it produced, and
// no "works on my machine" gap between a developer's checkout and CI.
package codegen

import (
	"fmt"
	"sort"
	"strconv"
	"strings"

	apiext "k8s.io/apiextensions-apiserver/pkg/apis/apiextensions/v1"
)

// CRDKCLModule is the basename (no extension) of the generated KCL module.
// Consumers do `import lib.crd_gen` and call `crd_gen.<lower>_crd()`.
const CRDKCLModule = "crd_gen"

// CRDDoc is one CRD's projected form: the kind it declares and the fully
// rendered apiextensions.k8s.io/v1 object, ready to lower into KCL.
type CRDDoc struct {
	// Kind is the CR kind ("Workload"), used for the lambda name and
	// for deterministic ordering.
	Kind string
	// Lambda is the generated KCL lambda name ("simplebackend_crd"). It
	// matches the historical hand-authored spelling so a project migrating
	// off the hand-written module only changes its import line.
	Lambda string
	// CRD is controller-tools' projection of the Go types.
	CRD apiext.CustomResourceDefinition
}

// GenerateCRDKCL renders the complete deploy/kcl/lib/crd_gen.k module: one
// `<lower>_crd = lambda -> any { ... }` per CRD, in deterministic kind order.
//
// The generated lambdas take no arguments and close over nothing, exactly like
// the hand-authored module they replace, so every call site keeps its shape.
//
// controllerGenVersion is stamped into each CRD's
// controller-gen.kubebuilder.io/version annotation. It names the schema
// SEMANTICS the output was produced under, which is the one piece of
// provenance that matters when a future controller-tools bump changes how some
// Go construct projects.
func GenerateCRDKCL(docs []CRDDoc, controllerGenVersion string) (string, error) {
	if len(docs) == 0 {
		return "", fmt.Errorf("no CRDs to generate")
	}

	// Deterministic output is a hard requirement, not a nicety: this file is
	// checksum-tracked, so a map-ordering wobble would show up as spurious
	// drift on every run and train people to ignore the guard.
	ordered := append([]CRDDoc(nil), docs...)
	sort.Slice(ordered, func(i, j int) bool { return ordered[i].Kind < ordered[j].Kind })

	var b strings.Builder
	b.WriteString("# Code generated by forge. DO NOT EDIT.\n")
	b.WriteString("#\n")
	b.WriteString("# Kubernetes CRD manifests, projected from the Go types in api/<version>/*_types.go\n")
	b.WriteString("# by controller-tools " + controllerGenVersion + ".\n")
	b.WriteString("#\n")
	b.WriteString("# The Go types are the SINGLE SOURCE OF TRUTH. To change a CRD's schema, edit the\n")
	b.WriteString("# Go struct (and its +kubebuilder:validation: markers) and re-run `forge generate`.\n")
	b.WriteString("# Editing this file by hand is pointless — it is overwritten — and dangerous: the\n")
	b.WriteString("# API server PRUNES any CR field the installed schema does not declare, silently,\n")
	b.WriteString("# so a schema that disagrees with the Go type makes the controller read zero\n")
	b.WriteString("# values forever with no error anywhere.\n")
	b.WriteString("#\n")
	b.WriteString("# Install these by listing them in an Environment's `additional_manifests`.\n")
	b.WriteString("\n")

	for i, doc := range ordered {
		if i > 0 {
			b.WriteString("\n")
		}
		obj, err := crdToKCLValue(doc, controllerGenVersion)
		if err != nil {
			return "", fmt.Errorf("project CRD %s: %w", doc.Kind, err)
		}
		fmt.Fprintf(&b, "%s = lambda -> any {\n", doc.Lambda)
		b.WriteString(indentKCL(renderKCLValue(obj, 0), 1))
		b.WriteString("\n}\n")
	}

	return b.String(), nil
}

// crdToKCLValue converts the typed CRD into the generic map/slice tree the KCL
// renderer walks.
//
// It round-trips through the apiextensions JSON encoding on purpose. That
// encoding is the SAME one the API server reads, so every field-level decision
// about what appears in the manifest (omitempty, the JSONSchemaProps union
// members, how x-kubernetes-* keys spell out) is made by the upstream type's
// own json tags rather than by a hand-written switch here that would drift from
// them. A manual walk of JSONSchemaProps's ~40 fields is precisely the kind of
// second declaration this generator exists to delete.
func crdToKCLValue(doc CRDDoc, controllerGenVersion string) (map[string]any, error) {
	c := doc.CRD

	// TypeMeta is empty on controller-tools' output (it builds the object, it
	// does not serialize it), but a manifest that reaches a cluster must name
	// its own apiVersion/kind.
	c.APIVersion = apiext.SchemeGroupVersion.String()
	c.Kind = "CustomResourceDefinition"

	if c.Annotations == nil {
		c.Annotations = map[string]string{}
	}
	c.Annotations["controller-gen.kubebuilder.io/version"] = controllerGenVersion

	raw, err := toGenericJSON(c)
	if err != nil {
		return nil, err
	}
	obj, ok := raw.(map[string]any)
	if !ok {
		return nil, fmt.Errorf("CRD did not encode to an object, got %T", raw)
	}

	// `status` on a CustomResourceDefinition is the API server's own
	// bookkeeping (acceptedNames, storedVersions, conditions). It is written
	// BY the server, never by an applier, and the zero value that falls out of
	// the encoding here declares an empty acceptedNames — which a strict
	// apply can reject and which is meaningless in a manifest either way.
	delete(obj, "status")

	// metadata.creationTimestamp is likewise server-owned; the zero
	// metav1.Time encodes as an explicit `null`, which is noise in a manifest
	// and is rejected by some validating admission paths.
	if md, ok := obj["metadata"].(map[string]any); ok {
		delete(md, "creationTimestamp")
	}

	return obj, nil
}

// renderKCLValue renders a generic JSON value as a KCL literal.
//
// KCL's dict and list syntax is close enough to JSON that this is a
// straightforward structural walk, with three deliberate differences:
//
//   - booleans are True/False, not true/false;
//   - a key that is not a bare KCL identifier is quoted (the x-kubernetes-*
//     keys carry hyphens, so they must be);
//   - dict entries are newline-separated rather than comma-separated, which is
//     idiomatic KCL and keeps diffs one-field-per-line.
//
// Keys are emitted in sorted order for determinism.
func renderKCLValue(v any, depth int) string {
	switch t := v.(type) {
	case nil:
		return "None"
	case bool:
		if t {
			return "True"
		}
		return "False"
	case string:
		return quoteKCLString(t)
	case float64:
		// JSON has one number type. Render integral values without a
		// decimal point so `minimum = 1` does not become `minimum = 1.0` —
		// the latter is a valid schema but a gratuitous diff against every
		// existing manifest, and reads as a float where the API means a
		// count.
		if t == float64(int64(t)) {
			return strconv.FormatInt(int64(t), 10)
		}
		return strconv.FormatFloat(t, 'g', -1, 64)
	case int64:
		return strconv.FormatInt(t, 10)
	case int:
		return strconv.Itoa(t)

	case []any:
		if len(t) == 0 {
			return "[]"
		}
		var b strings.Builder
		b.WriteString("[\n")
		for _, item := range t {
			b.WriteString(indentKCL(renderKCLValue(item, depth+1), 1))
			b.WriteString("\n")
		}
		b.WriteString("]")
		return b.String()

	case map[string]any:
		if len(t) == 0 {
			return "{}"
		}
		keys := make([]string, 0, len(t))
		for k := range t {
			keys = append(keys, k)
		}
		sort.Strings(keys)

		var b strings.Builder
		b.WriteString("{\n")
		for _, k := range keys {
			entry := fmt.Sprintf("%s = %s", kclKey(k), renderKCLValue(t[k], depth+1))
			b.WriteString(indentKCL(entry, 1))
			b.WriteString("\n")
		}
		b.WriteString("}")
		return b.String()

	default:
		return quoteKCLString(fmt.Sprint(t))
	}
}

// kclKey renders a dict key, quoting it when it is not a bare identifier.
// The x-kubernetes-* schema keys contain hyphens and MUST be quoted; an
// unquoted one is a syntax error, not a silent mis-render.
func kclKey(k string) string {
	if isBareKCLIdent(k) {
		return k
	}
	return quoteKCLString(k)
}

func isBareKCLIdent(s string) bool {
	if s == "" {
		return false
	}
	for i, r := range s {
		switch {
		case r >= 'a' && r <= 'z', r >= 'A' && r <= 'Z', r == '_':
		case r >= '0' && r <= '9' && i > 0:
		default:
			return false
		}
	}
	return true
}

// quoteKCLString renders a Go string as a KCL string literal.
//
// strconv.Quote is the right tool and the choice deserves a note, because
// regex patterns are the dominant string here and they are backslash-dense:
// a pattern like `^[a-z0-9]([-a-z0-9]*[a-z0-9])?(\.[a-z0-9]...)*$` must reach
// the API server with its backslashes INTACT. strconv.Quote escapes them
// correctly for a double-quoted literal, which KCL parses with the same rules
// Go does.
func quoteKCLString(s string) string {
	return strconv.Quote(s)
}

// indentKCL indents every non-empty line of s by n levels of four spaces.
func indentKCL(s string, n int) string {
	if n <= 0 {
		return s
	}
	pad := strings.Repeat("    ", n)
	lines := strings.Split(s, "\n")
	for i, line := range lines {
		if line == "" {
			continue
		}
		lines[i] = pad + line
	}
	return strings.Join(lines, "\n")
}
