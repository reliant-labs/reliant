// sampleFrontendConfig is a realistic public web config: an API URL with a
// default, a required issuer, and an optional endpoint.
func sampleFrontendConfig() FrontendConfig {
	return FrontendConfig{
		Frontend:    "web",
		MessageName: "WebConfig",
		Fields: []ConfigField{
			{
				Name: "api_url", GoName: "ApiUrl", GoType: "string", ProtoType: "string",
				EnvVar: "API_URL", DefaultValue: "http://localhost:8080",
				Description: "Base URL the transport targets.",
			},
			{
				Name: "oidc_issuer", GoName: "OidcIssuer", GoType: "string", ProtoType: "string",
				EnvVar: "OIDC_ISSUER", Required: true,
			},
			{
				Name: "otel_endpoint", GoName: "OtelEndpoint", GoType: "string", ProtoType: "string",
				EnvVar: "OTEL_ENDPOINT",
			},
		},
	}
}

func TestGenerateFrontendConfigKCL_Shape(t *testing.T) {
	out, err := GenerateFrontendConfigKCL([]FrontendConfig{sampleFrontendConfig()}, "demo")
	if err != nil {
		t.Fatalf("generate: %v", err)
	}

	for _, want := range []string{
		"schema WebConfig:",
		"webConfigRuntime = lambda c: WebConfig -> any {",
		`api_url: str = "http://localhost:8080"`,
		"oidc_issuer: str\n", // required, no default => mandatory in KCL
		// Optional with no default takes its type-zero, exactly as the
		// backend schema does, so an env can instantiate the schema without
		// spelling every field.
		`otel_endpoint: str = ""`,
		`"API_URL" = c.api_url`, // projection keyed by env_var
		"Code generated by forge. DO NOT EDIT.",
	} {
		if !strings.Contains(out, want) {
			t.Errorf("generated KCL missing %q:\n%s", want, out)
		}
	}

	// The public-by-construction claim must be stated in the artifact, and
	// no secret machinery may appear.
	if !strings.Contains(out, "PUBLIC") {
		t.Errorf("generated KCL should state that its contents are public:\n%s", out)
	}
	if strings.Contains(out, "ConfigSecretRef") {
		t.Errorf("frontend config must never emit secret references:\n%s", out)
	}
}

// The generated module has to be real KCL, not merely plausible text.
func TestGenerateFrontendConfigKCL_Compiles(t *testing.T) {
	if testing.Short() {
		t.Skip("compiles KCL with the kcl binary; skipped under -short")
	}
	kclBin, err := exec.LookPath("kcl")
	if err != nil {
		t.Skip("kcl binary not installed")
	}

	mod, err := GenerateFrontendConfigKCL([]FrontendConfig{sampleFrontendConfig()}, "demo")
	if err != nil {
		t.Fatalf("generate: %v", err)
	}

	dir := t.TempDir()
	if err := os.WriteFile(filepath.Join(dir, "kcl.mod"), []byte("[package]\nname = \"t\"\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(dir, FrontendConfigModule+".k"), []byte(mod), 0o644); err != nil {
		t.Fatal(err)
	}
	// An instance + a projection call, which is exactly how a per-env
	// config.k consumes the module.
	main := "import " + FrontendConfigModule + " as fc\n\n" +
		"cfg = fc.WebConfig {\n" +
		"    oidc_issuer = \"https://idp.example.com\"\n" +
		"    otel_endpoint = \"https://otel.example.com\"\n" +
		"}\n" +
		"runtime_config = fc.webConfigRuntime(cfg)\n"
	if err := os.WriteFile(filepath.Join(dir, "main.k"), []byte(main), 0o644); err != nil {
		t.Fatal(err)
	}

	cmd := exec.Command(kclBin, "run", "main.k")
	cmd.Dir = dir
	got, err := cmd.CombinedOutput()
	if err != nil {
		t.Fatalf("kcl run failed: %v\n%s\n--- module ---\n%s", err, got, mod)
	}

	rendered := string(got)
	// The default flows through, the required value is the author's, and
	// the keys are the env_var spellings the TypeScript module reads.
	for _, want := range []string{
		"API_URL: http://localhost:8080",
		"OIDC_ISSUER: https://idp.example.com",
		"OTEL_ENDPOINT: https://otel.example.com",
	} {
		if !strings.Contains(rendered, want) {
			t.Errorf("rendered runtime config missing %q:\n%s", want, rendered)
		}
	}
}

// KCL must enforce the proto's required-ness: omitting a required field is
// an error at render time, not an undefined value in the browser.
func TestGenerateFrontendConfigKCL_RequiredFieldEnforced(t *testing.T) {
	if testing.Short() {
		t.Skip("compiles KCL with the kcl binary; skipped under -short")
	}
	kclBin, err := exec.LookPath("kcl")
	if err != nil {
		t.Skip("kcl binary not installed")
	}

	mod, err := GenerateFrontendConfigKCL([]FrontendConfig{sampleFrontendConfig()}, "demo")
	if err != nil {
		t.Fatalf("generate: %v", err)
	}

	dir := t.TempDir()
	if err := os.WriteFile(filepath.Join(dir, "kcl.mod"), []byte("[package]\nname = \"t\"\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(dir, FrontendConfigModule+".k"), []byte(mod), 0o644); err != nil {
		t.Fatal(err)
	}
	// oidc_issuer omitted on purpose.
	main := "import " + FrontendConfigModule + " as fc\n\ncfg = fc.WebConfig {}\n"
	if err := os.WriteFile(filepath.Join(dir, "main.k"), []byte(main), 0o644); err != nil {
		t.Fatal(err)
	}

	cmd := exec.Command(kclBin, "run", "main.k")
	cmd.Dir = dir
	out, err := cmd.CombinedOutput()
	if err == nil {
		t.Fatalf("omitting a required frontend config field should fail KCL rendering, got:\n%s", out)
	}
}
