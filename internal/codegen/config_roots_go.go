// File: internal/codegen/config_roots_go.go
//
// The Go half of per-root config (roots plan F9): pkg/config/roots_gen.go,
// each root of the composition graph as data another module can import —
// the same reach deploy/kcl/config_gen.k's ROOTS projects, written from the
// same []GraphRoot in the same generate step, plus the configs each root's
// process loads, so pkg/config.Root.Validate runs exactly the boot load over
// a rendered env. The repo that keeps a deployment's values validates them
// against the schema of the binary it deploys, at its pinned version.

package codegen

import (
	"fmt"
	"go/format"
	"path/filepath"
	"sort"
	"strconv"
	"strings"

	"github.com/reliant-labs/forge/internal/checksums"
)

// rootsGoFile is the generated file, in the project's pkg/config.
var rootsGoFile = filepath.Join("pkg", "config", "roots_gen.go")

// GenerateRootsGo writes pkg/config/roots_gen.go for a graph-mode project's
// roots — the ones its composition step assembled, which deploy config's
// ROOTS projects too — whether or not the project deploys with forge's KCL:
// the binary's env schema is the binary's, and the repo that deploys it may
// be another. A legacy project, or a graph whose reach is unknown (nil
// roots), gets none.
func GenerateRootsGo(projectDir string, roots []GraphRoot, cs *checksums.FileChecksums) error {
	if !GraphComposition(projectDir) {
		roots = nil
	}
	return emitRootsGo(projectDir, roots, projectRootConfigMessage(projectDir), cs)
}

// projectRootConfigMessage is the message config.Config aliases, read off
// proto/<project>/config/v1; "" when there is none.
func projectRootConfigMessage(projectDir string) string {
	messages, err := ParseConfigProtosFromDir(filepath.Join(projectDir, "proto", "config"))
	if err != nil {
		return ""
	}
	return rootConfigMessageName(messages, primaryBinaryName(projectDir))
}

// emitRootsGo writes pkg/config/roots_gen.go for roots — the roots ROOTS was
// just rendered from — or retires it when ROOTS is not projected (no roots,
// or no reach to read them against). rootMessage is the root config's message
// name, which config.Config aliases.
func emitRootsGo(projectDir string, roots []GraphRoot, rootMessage string, cs *checksums.FileChecksums) error {
	src, ok, err := rootsGoSource(roots, rootMessage)
	if err != nil {
		return err
	}
	if !ok {
		RetireGenerated(projectDir, rootsGoFile, cs)
		return nil
	}
	if err := writeForgeOwned(projectDir, rootsGoFile, src, cs); err != nil {
		return fmt.Errorf("write %s: %w", rootsGoFile, err)
	}
	return nil
}

// rootsGoSource renders roots_gen.go; ok is false when the roots' reach is
// unknown — as RootsKCLFor renders no ROOTS for them.
func rootsGoSource(roots []GraphRoot, rootMessage string) (src []byte, ok bool, err error) {
	if len(roots) == 0 || rootMessage == "" {
		return nil, false, nil
	}
	for _, r := range roots {
		if r.Config == nil {
			return nil, false, nil
		}
	}
	q := strconv.Quote
	list := func(ss []string) string {
		parts := make([]string, len(ss))
		for i, s := range ss {
			parts[i] = q(s)
		}
		return "[]string{" + strings.Join(parts, ", ") + "}"
	}
	var b strings.Builder
	b.WriteString(`// Code generated by forge. DO NOT EDIT.
// forge-owned: regenerated every run — do not edit (forge project disown to take ownership)
// Source: the composition graph's roots (internal/app) and proto/<project>/config/v1 — the
// reach deploy/kcl/config_gen.k's ROOTS projects, as Go.

package config

import (
	"fmt"
	"strings"

	forgeconfig "github.com/reliant-labs/forge/pkg/config"
)

// Roots is every root of this binary's composition graph as a process: the
// command that runs it, every environment variable it reaches (each with its
// config, path, type, and whether it is required or a secret), the env
// families it reaches, and the configs its process loads with the fields of
// each it demands. Env, Secrets and RequiredSecrets of each are
// deploy/kcl/config_gen.k's ROOTS, generated from the same reach.
//
// It is for the repo that keeps a deployment's values: import this package at
// the pinned version and check each workload's rendered env against the root
// it runs (forgeconfig.Root.Validate, or ValidateRootEnv).
func Roots() []forgeconfig.Root {
	return []forgeconfig.Root{
`)
	for _, r := range sortedRoots(roots) {
		fmt.Fprintf(&b, "\t\t{\n\t\t\tName: %s,\n\t\t\tArgs: %s,\n", q(r.Name), list(r.Args))
		var vars, fams []string
		add := func(message string, ls []ConfigLeaf) {
			for _, l := range ls {
				switch {
				case l.EnvVar != "":
					v := fmt.Sprintf("{Name: %s, Config: %s, Path: %s, Type: %s", q(l.EnvVar), q(message), q(l.Path), q(l.Type))
					if len(l.Aliases) > 0 {
						v += ", Aliases: " + list(l.Aliases)
					}
					if l.Required {
						v += ", Required: true"
					}
					if l.Sensitive {
						v += ", Sensitive: true"
					}
					vars = append(vars, v+"}")
				case l.EnvPrefix != "":
					fams = append(fams, fmt.Sprintf("{Prefix: %s, Suffix: %s, Config: %s, Path: %s}", q(l.EnvPrefix), q(l.EnvSuffix), q(message), q(l.Path)))
				}
			}
		}
		add(rootMessage, r.Config)
		for _, l := range r.Loads {
			add(l.Message, l.Config)
		}
		b.WriteString("\t\t\tVars: []forgeconfig.RootVar{\n")
		for _, v := range vars {
			b.WriteString("\t\t\t\t" + v + ",\n")
		}
		b.WriteString("\t\t\t},\n")
		if len(fams) > 0 {
			b.WriteString("\t\t\tFamilies: []forgeconfig.RootFamily{\n")
			for _, f := range fams {
				b.WriteString("\t\t\t\t" + f + ",\n")
			}
			b.WriteString("\t\t\t},\n")
		}
		b.WriteString("\t\t\tConfigs: []forgeconfig.RootConfig{\n")
		fmt.Fprintf(&b, "\t\t\t\t{Message: &Config{}, Reach: %s},\n", list(leafPaths(r.Config)))
		for _, l := range r.Loads {
			fmt.Fprintf(&b, "\t\t\t\t{Message: &%s{}, Reach: %s},\n", l.Message, list(leafPaths(l.Config)))
		}
		b.WriteString("\t\t\t},\n\t\t},\n")
	}
	b.WriteString(`	}
}

// RootNamed is the root named name, as Roots has it.
func RootNamed(name string) (forgeconfig.Root, bool) {
	for _, r := range Roots() {
		if r.Name == name {
			return r, true
		}
	}
	return forgeconfig.Root{}, false
}

// ValidateRootEnv runs what the process running root name runs at boot —
// each config it loads, demanding the fields the root reaches — over env
// instead of the process environment, with no flags, and returns every
// problem it finds: a required variable missing, a value the process would
// refuse, a misspelt env-family entry, and every variable of env the root
// never reads (a *forgeconfig.UnreachedVarError each). nil: the process would
// start on env.
func ValidateRootEnv(name string, env map[string]string) []error {
	r, ok := RootNamed(name)
	if !ok {
		var names []string
		for _, r := range Roots() {
			names = append(names, r.Name)
		}
		return []error{fmt.Errorf("no root named %q: the roots are %s", name, strings.Join(names, ", "))}
	}
	return r.Validate(env)
}
`)
	out, err := format.Source([]byte(b.String()))
	if err != nil {
		return nil, false, fmt.Errorf("format %s (a forge bug — please report it): %w\n%s", rootsGoFile, err, b.String())
	}
	return out, true, nil
}

// sortedRoots is roots by name, as ROOTS lists them.
func sortedRoots(roots []GraphRoot) []GraphRoot {
	out := append([]GraphRoot(nil), roots...)
	sort.Slice(out, func(i, j int) bool { return out[i].Name < out[j].Name })
	return out
}

// leafPaths is ls' paths, never nil.
func leafPaths(ls []ConfigLeaf) []string {
	out := make([]string, 0, len(ls))
	for _, l := range ls {
		out = append(out, l.Path)
	}
	return out
}
