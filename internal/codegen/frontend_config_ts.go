package codegen

import (
	"fmt"
	"strings"
)

// FrontendConfigTSFile is the generated module's path inside a frontend,
// relative to the frontend root.
const FrontendConfigTSFile = "src/lib/config_gen.ts"

// FrontendConfigJSFile is the runtime config document's path inside a
// frontend, relative to the frontend root. It lands in the framework's
// static-asset directory so it is served verbatim at <basePath>/config.js.
const FrontendConfigJSFile = "config.js"

// FrontendConfigGlobal is the browser global the runtime document assigns
// and the generated module reads.
const FrontendConfigGlobal = "__FORGE_CONFIG__"

// GenerateFrontendConfigTS emits the typed TypeScript module a frontend
// imports INSTEAD of touching process.env / import.meta.env.
//
// ── Why a runtime document rather than build-time inlining ──────────────
//
// Next.js and Vite both inline NEXT_PUBLIC_* / VITE_* at BUILD time: the
// value becomes a string literal in the bundle. That makes a built artifact
// environment-SPECIFIC — it carries staging's issuer forever — which is
// exactly what `forge env deploy` exists to avoid. Promoting a bundle
// built against staging into production would point real users at the
// staging IdP.
//
// So the values arrive at RUNTIME instead, as a small JS document
// (config.js) that assigns a global before any bundle code runs. The
// document is a static asset: KCL renders one per environment, and
// promoting an artifact means shipping the same bundle beside a different
// config.js. Nothing is rebuilt.
//
// A blocking classic <script src> is what makes this safe to depend on at
// module scope. The alternative — fetch("/config.json") at boot — is
// asynchronous, so every consumer would have to await it, and the OIDC
// provider needs its issuer during module initialization to decide whether
// auth is even configured. A synchronous global removes that ordering
// problem entirely.
//
// ── Server rendering ────────────────────────────────────────────────────
//
// A Next.js `standalone` build also renders on the server, where there is
// no window. There the module reads process.env, which in a deployed
// workload is populated from the SAME KCL config — so both paths have one
// source and cannot disagree. This is not a dotenv fallback: no .env file
// is read, written, or consulted.
func GenerateFrontendConfigTS(fc FrontendConfig, projectName, platform string) (string, error) {
	var b strings.Builder

	b.WriteString("// Code generated by forge. DO NOT EDIT.\n")
	b.WriteString("// forge-owned: regenerated every run — do not edit (forge project disown to take ownership)\n")
	b.WriteString("// Source: " + configProtoDir(projectName) + "/config.proto — the message annotated\n")
	fmt.Fprintf(&b, "// (forge.v1.frontend_config) = {frontend: %q}.\n", fc.Frontend)
	b.WriteString("//\n")
	b.WriteString("// This module is the ONLY supported way for this frontend to read its\n")
	b.WriteString("// configuration. Do not reach for process.env / import.meta.env: a value\n")
	b.WriteString("// read there is untyped, undefaulted, unvalidated, and — because both\n")
	b.WriteString("// bundlers inline it at BUILD time — frozen into the artifact, so the\n")
	b.WriteString("// bundle can never be promoted between environments.\n")
	b.WriteString("//\n")
	b.WriteString("// Values arrive at RUNTIME from config.js, which KCL renders per\n")
	fmt.Fprintf(&b, "// environment and which assigns window.%s before this\n", FrontendConfigGlobal)
	b.WriteString("// bundle executes. Promoting a build means shipping the same bundle\n")
	b.WriteString("// beside a different config.js — nothing is rebuilt.\n")
	b.WriteString("//\n")
	b.WriteString("// EVERY VALUE HERE IS PUBLIC. It is delivered to the browser. A field\n")
	b.WriteString("// marked `sensitive` in the proto is refused at generate time and can\n")
	b.WriteString("// never appear in this file.\n\n")

	b.WriteString(`import { z } from "zod";` + "\n\n")
	if frontendConfigHasBool(fc) {
		b.WriteString(configBoolHelper)
	}

	// ── The schema ──────────────────────────────────────────────────────
	fmt.Fprintf(&b, "/** Typed, validated config for frontend %q (project %s). */\n", fc.Frontend, projectName)
	b.WriteString("export const configSchema = z.object({\n")
	for _, f := range fc.Fields {
		if f.MessageType != "" {
			continue
		}
		if d := strings.TrimSpace(f.Description); d != "" {
			d = strings.Join(strings.Fields(d), " ")
			fmt.Fprintf(&b, "  /** %s */\n", escapeJSDoc(d))
		}
		fmt.Fprintf(&b, "  %s: %s,\n", tsConfigKey(f), zodExprForConfigField(f))
	}
	b.WriteString("});\n\n")

	fmt.Fprintf(&b, "export type %s = z.infer<typeof configSchema>;\n\n", tsConfigTypeName(fc))

	// ── The runtime source ──────────────────────────────────────────────
	b.WriteString("declare global {\n")
	b.WriteString("  interface Window {\n")
	fmt.Fprintf(&b, "    %s?: Record<string, unknown>;\n", FrontendConfigGlobal)
	b.WriteString("  }\n")
	b.WriteString("}\n\n")

	b.WriteString("/**\n")
	b.WriteString(" * Raw values, before validation.\n")
	b.WriteString(" *\n")
	b.WriteString(" * In the BROWSER they come from config.js (rendered by KCL for this\n")
	b.WriteString(" * environment). During SERVER rendering there is no window, so they come\n")
	b.WriteString(" * from the process environment — which a deployed workload receives from\n")
	b.WriteString(" * the SAME KCL config, so the two cannot disagree. No .env file is read.\n")
	b.WriteString(" */\n")
	b.WriteString("function rawConfig(): Record<string, unknown> {\n")
	fmt.Fprintf(&b, "  if (typeof window !== \"undefined\" && window.%s) {\n", FrontendConfigGlobal)
	fmt.Fprintf(&b, "    return window.%s;\n", FrontendConfigGlobal)
	b.WriteString("  }\n")
	b.WriteString(serverSideRawConfig(fc, platform))
	b.WriteString("}\n\n")

	// ── Mode-dependent required keys ────────────────────────────────────
	b.WriteString(requiredWhenTS(fc))

	// ── Validation ──────────────────────────────────────────────────────
	b.WriteString(configLoaderBody(fc, projectName))

	return b.String(), nil
}

// serverSideRawConfig emits the non-browser branch. React Native has no
// server render and no window during tests, so it simply yields an empty
// object and lets defaults apply.
func serverSideRawConfig(fc FrontendConfig, platform string) string {
	if platform == "react-native" {
		return "  return {};\n"
	}

	var b strings.Builder
	b.WriteString("  if (typeof process !== \"undefined\" && process.env) {\n")
	b.WriteString("    const fromEnv: Record<string, unknown> = {};\n")
	for _, f := range fc.Fields {
		if f.MessageType != "" {
			continue
		}
		key := tsConfigKeyRaw(f)
		// The server reads the UNPREFIXED name: a deployed workload's env
		// is projected from the same KCL config the browser document is,
		// and that projection uses the proto's env_var spelling.
		fmt.Fprintf(&b, "    if (process.env[%q] !== undefined) fromEnv[%q] = process.env[%q];\n", key, key, key)
	}
	b.WriteString("    return fromEnv;\n")
	b.WriteString("  }\n")
	b.WriteString("  return {};\n")
	return b.String()
}

// configLoaderBody emits the validating accessor. It fails LOUD and once,
// at boot, rather than letting a missing value surface as `undefined` three
// components deep.
func configLoaderBody(fc FrontendConfig, projectName string) string {
	typeName := tsConfigTypeName(fc)

	var b strings.Builder
	fmt.Fprintf(&b, "let cached: %s | null = null;\n\n", typeName)

	b.WriteString("/**\n")
	b.WriteString(" * Validated config for this frontend.\n")
	b.WriteString(" *\n")
	b.WriteString(" * Throws at first use when a required value is missing or malformed.\n")
	b.WriteString(" * That is deliberate: a config error should stop the app at boot with a\n")
	b.WriteString(" * message naming the field, not travel as `undefined` into a component\n")
	b.WriteString(" * that renders a blank screen or a request to \"undefined/api\".\n")
	b.WriteString(" */\n")
	fmt.Fprintf(&b, "export function loadConfig(): %s {\n", typeName)
	b.WriteString("  if (cached) return cached;\n\n")
	if frontendConfigHasRequiredWhen(fc) {
		// The mode-dependent keys are judged on the RAW document: a default
		// does not satisfy them (see missingRequiredConfig).
		b.WriteString("  const raw = rawConfig();\n")
		b.WriteString("  const parsed = configSchema.safeParse(raw);\n")
		b.WriteString("  const missing = missingRequiredConfig(raw);\n")
		b.WriteString("  if (!parsed.success || missing.length > 0) {\n")
		b.WriteString("    const problems = [\n")
		b.WriteString("      ...(parsed.success ? [] : parsed.error.issues.map((i) => `  • ${i.path.join(\".\") || \"(root)\"}: ${i.message}`)),\n")
		b.WriteString("      ...missing.map((m) => `  • ${m.key}: required when ${m.when.key} is \"${m.when.equals}\"`),\n")
		b.WriteString("    ].join(\"\\n\");\n")
	} else {
		b.WriteString("  const parsed = configSchema.safeParse(rawConfig());\n")
		b.WriteString("  if (!parsed.success) {\n")
		b.WriteString("    const problems = parsed.error.issues\n")
		b.WriteString("      .map((i) => `  • ${i.path.join(\".\") || \"(root)\"}: ${i.message}`)\n")
		b.WriteString("      .join(\"\\n\");\n")
	}
	b.WriteString("    throw new Error(\n")
	fmt.Fprintf(&b, "      `frontend %q: invalid runtime configuration\\n\\n${problems}\\n\\n` +\n", fc.Frontend)
	fmt.Fprintf(&b, "        `These values are rendered by KCL into config.js. Fix them in\\n` +\n")
	fmt.Fprintf(&b, "        `deploy/kcl/<env>/config.k (the %s instance) and re-run\\n` +\n", fc.MessageName)
	fmt.Fprintf(&b, "        `\\`forge generate\\`. To add or remove a FIELD, edit\\n` +\n")
	b.WriteString("        `" + configProtoDir(projectName) + "/config.proto — never this file.\\n\\n` +\n")
	fmt.Fprintf(&b, "        `If config.js did not load at all, check that it is present in\\n` +\n")
	fmt.Fprintf(&b, "        `this frontend's static assets and referenced from the document\\n` +\n")
	fmt.Fprintf(&b, "        `head (project %s).`,\n", projectName)
	b.WriteString("    );\n")
	b.WriteString("  }\n\n")
	b.WriteString("  cached = parsed.data;\n")
	b.WriteString("  return cached;\n")
	b.WriteString("}\n\n")

	b.WriteString("/**\n")
	b.WriteString(" * Resets the memoized config. Tests only — a running app reads one\n")
	b.WriteString(" * environment's values for its whole lifetime.\n")
	b.WriteString(" */\n")
	b.WriteString("export function resetConfigForTests(): void {\n")
	b.WriteString("  cached = null;\n")
	b.WriteString("}\n")

	return b.String()
}

// tsConfigKey is the object key for a field, quoted when needed. The key is
// the env_var spelling so ONE name identifies the fact across the proto,
// the KCL projection, the runtime document and this module.
func tsConfigKey(f ConfigField) string {
	return tsConfigKeyRaw(f)
}

func tsConfigKeyRaw(f ConfigField) string {
	if f.EnvVar != "" {
		return f.EnvVar
	}
	return f.Name
}

// tsConfigTypeName names the exported type after the proto message, so the
// TypeScript type and the KCL schema an operator edits share a name.
func tsConfigTypeName(fc FrontendConfig) string {
	if fc.MessageName == "" {
		return "FrontendConfig"
	}
	return fc.MessageName
}

// zodExprForConfigField maps a config field to its zod validator, carrying
// the proto's type, default and required-ness into runtime validation.
func zodExprForConfigField(f ConfigField) string {
	if kclTypeForProtoConfig(f) == "bool" {
		// The default sits INSIDE the preprocess: configBool maps "" to
		// undefined, and an outer .default() only sees the raw input, so
		// a present-but-empty value would fail instead of defaulting.
		inner := "z.boolean()"
		switch {
		case f.DefaultValue != "":
			inner += ".default(" + zodDefaultLiteral(f) + ")"
		case !f.Required:
			inner += ".default(false)"
		}
		return "z.preprocess(configBool, " + inner + ")"
	}
	base := zodBaseForConfigField(f)

	if f.DefaultValue != "" {
		return base + ".default(" + zodDefaultLiteral(f) + ")"
	}
	if f.Required {
		// Required with no default: a present-but-empty string is the
		// failure this catches — an unset KCL value projects as "" and
		// would otherwise validate as a perfectly good string.
		if zodBaseForConfigField(f) == "z.string()" {
			return base + `.min(1, "required but empty")`
		}
		return base
	}
	// Optional with no default takes the type-zero, matching the KCL
	// schema's type-zero so the two layers agree.
	return base + ".default(" + zodZeroLiteral(f) + ")"
}

func zodBaseForConfigField(f ConfigField) string {
	switch kclTypeForProtoConfig(f) {
	case "int", "float":
		// KCL emits a JSON number; a server-side process.env read yields a
		// string. coerce accepts both without the call sites caring.
		return "z.coerce.number()"
	case "bool":
		// NOT z.coerce.boolean(): that is Boolean(v), so the STRING
		// "false" — the only spelling a runtime_config value, a KCL str or
		// a server-side process.env read can carry — validates as true.
		// configBool reads the spellings both layers write and leaves any
		// other string for z.boolean() to refuse. zodExprForConfigField
		// places the default inside it.
		return "z.preprocess(configBool, z.boolean())"
	default:
		return "z.string()"
	}
}

// configBoolHelper is emitted once, ahead of the schema, when a field is a
// bool. It maps the text forms of a boolean onto one, and "" onto undefined
// so a present-but-empty value takes the field's default like an absent one.
// Any other string passes through unchanged, so a typo ("yes", "ture") fails
// validation at boot, naming the field, instead of reading as off.
const configBoolHelper = `/** A boolean from config.js (JSON) or its text forms ("true"/"false", "1"/"0"). */
function configBool(v: unknown): unknown {
  if (typeof v !== "string") return v;
  const s = v.trim().toLowerCase();
  if (s === "") return undefined;
  if (s === "true" || s === "1") return true;
  if (s === "false" || s === "0") return false;
  return v;
}

`

// frontendConfigHasBool reports whether any leaf field of fc is a bool, i.e.
// whether the generated module needs configBoolHelper.
func frontendConfigHasBool(fc FrontendConfig) bool {
	for _, f := range fc.Fields {
		if f.MessageType == "" && kclTypeForProtoConfig(f) == "bool" {
			return true
		}
	}
	return false
}

func zodDefaultLiteral(f ConfigField) string {
	switch kclTypeForProtoConfig(f) {
	case "int", "float":
		return f.DefaultValue
	case "bool":
		if isKCLTruthy(f.DefaultValue) {
			return "true"
		}
		return "false"
	default:
		return fmt.Sprintf("%q", f.DefaultValue)
	}
}

func zodZeroLiteral(f ConfigField) string {
	switch kclTypeForProtoConfig(f) {
	case "int", "float":
		return "0"
	case "bool":
		return "false"
	default:
		return `""`
	}
}

// GenerateFrontendConfigJS renders the runtime config document for ONE
// environment — the artifact KCL's projection feeds and the browser loads.
//
// It is a classic script (not a module) assigning a global, so a blocking
// <script src> in the document head guarantees the value exists before any
// bundle code runs. values is the rendered projection: env_var name -> value.
func GenerateFrontendConfigJS(frontend, env string, valuesJSON string) string {
	var b strings.Builder
	b.WriteString("// Code generated by forge. DO NOT EDIT.\n")
	fmt.Fprintf(&b, "// Runtime configuration for frontend %q, environment %q.\n", frontend, env)
	b.WriteString("//\n")
	b.WriteString("// Rendered from deploy/kcl/<env>/config.k. This file is the ONLY\n")
	b.WriteString("// environment-specific part of a built frontend: the same bundle can be\n")
	b.WriteString("// promoted between environments by shipping it beside a different copy\n")
	b.WriteString("// of this file. Nothing is rebuilt.\n")
	b.WriteString("//\n")
	b.WriteString("// Everything here is PUBLIC — it is served to the browser.\n")
	fmt.Fprintf(&b, "window.%s = %s;\n", FrontendConfigGlobal, valuesJSON)
	return b.String()
}

// escapeJSDoc makes a proto description safe to interpolate into a
// /** ... */ block.
//
// Descriptions are prose written by humans, and prose about URLs routinely
// contains a glob — forge's own scaffolded config.proto describes the OIDC
// redirect URI as "http://localhost:*/auth/callback". Emitted raw, the `*/`
// in that URL closes the comment and the remainder of the sentence is parsed
// as TypeScript, which is a syntax error in a file the user is forbidden to
// edit.
//
// The escape is `*\/`: TypeScript reads the backslash as an ordinary
// character inside a comment, so the text still reads as the original URL,
// while the two-character comment terminator no longer appears.
func escapeJSDoc(s string) string {
	return strings.ReplaceAll(s, "*/", `*\/`)
}
