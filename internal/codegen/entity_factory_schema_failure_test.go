// TestEntityFactories_AnUnreadableSchemaIsAnError is forge bug df26c327 at
// the emitter. When the applied schema cannot be read, the factories emitter
// writes nothing — and it must SAY so. It used to return nil (and its caller
// printed a warning and reported success), so a run that could not look at
// the schema was indistinguishable from a project with no factories, and the
// stale-file sweep deleted every committed factories_gen_test.go.
//
// Asserted at both layers: GenerateEntityFactories returns the schema error,
// GenerateBootstrapTesting returns it as an *EntityFactoriesError (so the
// pipeline can fail that one emitter), and the factories file on disk is left
// exactly as it was.
func TestEntityFactories_AnUnreadableSchemaIsAnError(t *testing.T) {
	cause := errors.New("pgtest: connect to postgres://127.0.0.1:1/postgres: connection refused")
	orig := openAppliedSchema
	openAppliedSchema = func(string, string) ([]schemadef.Table, *schemadef.Shadow, error) {
		return nil, nil, cause
	}
	t.Cleanup(func() { openAppliedSchema = orig })

	projectDir := t.TempDir()
	handlerDir := filepath.Join(projectDir, "internal", "handlers", "shop")
	if err := os.MkdirAll(handlerDir, 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(handlerDir, "service.go"), []byte("package shop\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	factoryPath := filepath.Join(handlerDir, entityFactoryFile)
	committed := []byte("// Code generated by forge. DO NOT EDIT.\npackage shop\n\nfunc NewProduct() {}\n")
	if err := os.WriteFile(factoryPath, committed, 0o644); err != nil {
		t.Fatal(err)
	}
	services := []ServiceDef{{
		Name: "ShopService",
		Methods: []Method{
			{Name: "CreateProduct", InputType: "CreateProductRequest", OutputType: "CreateProductResponse"},
		},
	}}

	err := GenerateEntityFactories(projectDir, "example.com/proj", services, nil)
	if !errors.Is(err, cause) {
		t.Fatalf("GenerateEntityFactories() = %v, want the schema-read error: writing nothing without an error reads as \"no factories any more\"", err)
	}
	if !strings.Contains(err.Error(), "shadow database") {
		t.Errorf("error %q does not say what could not be read", err)
	}

	err = GenerateBootstrapTesting(BootstrapTestingGenInput{
		GenContext: GenContext{ProjectDir: projectDir, ModulePath: "example.com/proj"},
		Services:   services,
	})
	var factoriesErr *EntityFactoriesError
	if !errors.As(err, &factoriesErr) || !errors.Is(err, cause) {
		t.Fatalf("GenerateBootstrapTesting() = %v, want an *EntityFactoriesError wrapping the schema-read error", err)
	}

	got, rerr := os.ReadFile(factoryPath)
	if rerr != nil {
		t.Fatalf("%s is gone after a failed schema read: %v", entityFactoryFile, rerr)
	}
	if string(got) != string(committed) {
		t.Errorf("%s was rewritten from no schema:\n%s", entityFactoryFile, got)
	}
}

// TestEntityFactories_NoSchemaIsNotAnError: a project with no migrations has
// no factories to write, and that is a success — the failure path above must
// not swallow this one.
func TestEntityFactories_NoSchemaIsNotAnError(t *testing.T) {
	if err := GenerateEntityFactories(t.TempDir(), "example.com/proj", nil, nil); err != nil {
		t.Fatalf("GenerateEntityFactories() on a project with no migrations = %v, want nil", err)
	}
}
