package codegen

import (
	"go/ast"
	"go/parser"
	"go/token"
	"os"
	"path/filepath"
	"strings"
	"testing"
)

// noGraphTree writes a command tree with no composition graph — the shape
// `forge project new --disable codegen` scaffolds — holding root.go and, when
// non-empty, serve.go.
func noGraphTree(t *testing.T, root, serve string) (dir, rootsGen string) {
	t.Helper()
	dir = t.TempDir()
	tree := filepath.Join(dir, "cmd", "demo", "cmd")
	if err := os.MkdirAll(tree, 0o755); err != nil {
		t.Fatal(err)
	}
	files := map[string]string{"root.go": root}
	if serve != "" {
		files["serve.go"] = serve
	}
	for name, src := range files {
		if err := os.WriteFile(filepath.Join(tree, name), []byte(src), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	return dir, filepath.Join(tree, "roots_gen.go")
}

const rootCallingRootCommands = "package cmd\n\nfunc newRootCmd(deps Deps) { _ = rootCommands(deps) }\n"

// root.go is the same file in every shape and calls rootCommands. With no
// graph there are no roots, so the projection is an empty rootCommands —
// what makes the tree compile without a hand edit.
func TestEmitRootCommandsWithoutGraph_DefinesAnEmptyRootCommands(t *testing.T) {
	dir, rootsGen := noGraphTree(t, rootCallingRootCommands, "")
	if err := EmitRootCommandsWithoutGraph(dir, nil); err != nil {
		t.Fatal(err)
	}
	src, err := os.ReadFile(rootsGen)
	if err != nil {
		t.Fatalf("roots_gen.go not written: %v", err)
	}
	file, err := parser.ParseFile(token.NewFileSet(), rootsGen, src, 0)
	if err != nil {
		t.Fatalf("roots_gen.go does not parse: %v\n%s", err, src)
	}
	declared := false
	for _, d := range file.Decls {
		if fn, ok := d.(*ast.FuncDecl); ok && fn.Recv == nil && fn.Name.Name == "rootCommands" {
			declared = true
		}
	}
	if file.Name.Name != "cmd" || !declared {
		t.Fatalf("roots_gen.go does not declare cmd.rootCommands:\n%s", src)
	}
	if !strings.Contains(string(src), "return nil") {
		t.Fatalf("a project with no graph has no roots, so rootCommands returns none:\n%s", src)
	}
	// Nothing a graph-less project lacks may be imported.
	for _, missing := range []string{"/internal/app", "/pkg/config", "lifecyclekit"} {
		if strings.Contains(string(src), missing) {
			t.Errorf("roots_gen.go imports %s, which a project without codegen does not have:\n%s", missing, src)
		}
	}
}

// A tree that declares runRoot has the graph's own roots_gen.go; replacing it
// with the empty one would leave serve.go calling a rootSpec nothing defines.
func TestEmitRootCommandsWithoutGraph_LeavesAGraphTreeAlone(t *testing.T) {
	dir, rootsGen := noGraphTree(t, rootCallingRootCommands,
		"package cmd\n\nfunc runRoot(ctx context.Context, deps Deps, root rootSpec) error { return nil }\n")
	const graphs = "// Code generated by forge. DO NOT EDIT.\npackage cmd\n\ntype rootSpec struct{}\n"
	if err := os.WriteFile(rootsGen, []byte(graphs), 0o644); err != nil {
		t.Fatal(err)
	}
	if err := EmitRootCommandsWithoutGraph(dir, nil); err != nil {
		t.Fatal(err)
	}
	got, err := os.ReadFile(rootsGen)
	if err != nil {
		t.Fatal(err)
	}
	if string(got) != graphs {
		t.Fatalf("the graph's roots_gen.go was replaced:\n%s", got)
	}
}

// A root.go that no longer calls rootCommands needs none; an empty function
// nothing calls is dead code the project's lint reports.
func TestEmitRootCommandsWithoutGraph_WritesNothingNobodyCalls(t *testing.T) {
	dir, rootsGen := noGraphTree(t, "package cmd\n\nfunc newRootCmd(deps Deps) {}\n", "")
	if err := EmitRootCommandsWithoutGraph(dir, nil); err != nil {
		t.Fatal(err)
	}
	if _, err := os.Stat(rootsGen); !os.IsNotExist(err) {
		t.Fatalf("roots_gen.go written for a root.go that does not call rootCommands (%v)", err)
	}
}

// No command tree (a CLI or library kind) is no work.
func TestEmitRootCommandsWithoutGraph_NoTreeIsANoOp(t *testing.T) {
	dir := t.TempDir()
	if err := EmitRootCommandsWithoutGraph(dir, nil); err != nil {
		t.Fatal(err)
	}
	entries, err := os.ReadDir(dir)
	if err != nil {
		t.Fatal(err)
	}
	if len(entries) != 0 {
		t.Fatalf("wrote into a project with no command tree: %v", entries)
	}
}
