// changesFixture declares one change of every type, with a description that
// spans lines and a JSON default holding a quote and a backquote.
const changesFixture = `version: 1
changes:
  new-checkout:
    description: Shorter checkout flow
    type: bool
    default: control
    variants:
      control: false
      treatment: true
  hero.copy:
    description: |
      The hero's headline.
      Copy is tested by marketing.
    type: string
    default: a
    variants:
      a: Ship faster
      b: "Deploy in \"one\" command"
  max_items:
    type: number
    default: low
    variants:
      low: 10
      high: 2.5e2
  theme:
    type: json
    default: v1
    variants:
      v1: {accent: blue, note: "it's ` + "`new`" + `"}
      v2: [1, "x"]
  delete:
    type: bool
    default: off
    variants:
      off: false
      on: true
`

// The goldens pin both files whole. FORGE_UPDATE_GOLDEN=1 rewrites them.
func TestGenerateChangesGolden(t *testing.T) {
	d, err := changesdecl.Parse(changesdecl.FileName, []byte(changesFixture))
	if err != nil {
		t.Fatal(err)
	}
	goSrc, err := GenerateChangesGo(d)
	if err != nil {
		t.Fatal(err)
	}
	tsSrc, err := GenerateChangesTS(d)
	if err != nil {
		t.Fatal(err)
	}
	checkGolden(t, "testdata/changes_gen.golden.go.txt", goSrc)
	checkGolden(t, "testdata/changes_gen.golden.ts", tsSrc)

	// The load-bearing lines, spelled out so a regenerated golden cannot
	// quietly drop the SDK contract.
	for _, want := range []string{
		"package changes\n",
		`"github.com/reliant-labs/forge/pkg/changes"`,
		`const KeyNewCheckout = "new-checkout"`,
		"// forge:section new-checkout\n",
		"func NewCheckout(ctx context.Context, s *changes.Store, ec changes.EvalContext) bool {\n\treturn changes.Bool(s.Evaluate(ctx, KeyNewCheckout, ec), false)\n}",
		"func HeroCopy(ctx context.Context, s *changes.Store, ec changes.EvalContext) string {\n\treturn changes.String(s.Evaluate(ctx, KeyHeroCopy, ec), \"Ship faster\")\n}",
		"func MaxItems(ctx context.Context, s *changes.Store, ec changes.EvalContext) float64 {\n\treturn changes.Float64(s.Evaluate(ctx, KeyMaxItems, ec), 10)\n}",
		"func Theme(ctx context.Context, s *changes.Store, ec changes.EvalContext, v any) bool {\n\tif changes.Decode(s.Evaluate(ctx, KeyTheme, ec), v) {",
		"// NewCheckout evaluates the change \"new-checkout\":\n// Shorter checkout flow\n",
		"// Code generated by forge. DO NOT EDIT.\n",
	} {
		if !strings.Contains(string(goSrc), want) {
			t.Errorf("changes_gen.go lacks %q", want)
		}
	}
	for _, want := range []string{
		`import * as forge from "@reliantlabs/forge-web-runtime";`,
		"// forge:section new-checkout\n",
		`export const newCheckoutKey = "new-checkout";`,
		"export function newCheckout(store: forge.ChangesStore, ctx?: forge.ChangeEvalContext): boolean {",
		"  const r = store.evaluate(newCheckoutKey, ctx);\n  return forge.changeBool(r, false);",
		"export function deleteChange(store: forge.ChangesStore, ctx?: forge.ChangeEvalContext): boolean {",
		"export function theme<T = unknown>(store: forge.ChangesStore, ctx?: forge.ChangeEvalContext): T {",
		`return forge.changeString(r, "Ship faster");`,
		"// Code generated by forge. DO NOT EDIT.\n",
	} {
		if !strings.Contains(string(tsSrc), want) {
			t.Errorf("changes_gen.ts lacks %q", want)
		}
	}

	// The Go output parses as Go: format.Source would have refused it
	// otherwise, but the backquoted JSON default is the case to prove.
	if _, err := parser.ParseFile(token.NewFileSet(), "changes_gen.go", goSrc, parser.ParseComments); err != nil {
		t.Fatalf("changes_gen.go does not parse: %v", err)
	}
	if !strings.Contains(string(goSrc), `changes.Decode(changes.Result{Value: []byte("{\"accent\":\"blue\",\"note\":\"it's `+"`new`"+`\"}")}, v)`) {
		t.Errorf("a JSON default holding a backquote is not an interpreted string literal:\n%s", goSrc)
	}
}

// The preamble does not depend on which changes exist: a declaration of one
// bool change and one of every type open the same way, so a branch adding a
// change of a new type touches no line another branch could also edit.
func TestGenerateChangesPreambleIsFixed(t *testing.T) {
	one, err := changesdecl.Parse(changesdecl.FileName, []byte("version: 1\nchanges:\n  a: {type: bool, default: x, variants: {x: true}}\n"))
	if err != nil {
		t.Fatal(err)
	}
	all, err := changesdecl.Parse(changesdecl.FileName, []byte(changesFixture))
	if err != nil {
		t.Fatal(err)
	}
	preamble := func(src []byte) string { return string(src[:strings.Index(string(src), "// forge:section")]) }
	for lang, gen := range map[string]func(*changesdecl.Decl) ([]byte, error){"go": GenerateChangesGo, "ts": GenerateChangesTS} {
		a, err := gen(one)
		if err != nil {
			t.Fatal(err)
		}
		b, err := gen(all)
		if err != nil {
			t.Fatal(err)
		}
		if preamble(a) != preamble(b) {
			t.Errorf("%s: the preamble depends on the declared changes:\n%s\n---\n%s", lang, preamble(a), preamble(b))
		}
		if lang == "go" && !strings.Contains(string(a), "x (true, the default)") {
			t.Errorf("a lone variant is not described:\n%s", a)
		}
	}
}

// Two branches that change different changes merge with plain git into what
// generate writes for the merged declaration: each change is its own section.
func TestMergeProperty_ChangesAccessors(t *testing.T) {
	testkit.Slow(t, "execs git")
	decl := func(variant string) *changesdecl.Decl {
		src := "version: 1\nchanges:\n  a: {type: bool, default: x, variants: {x: true}}\n"
		if variant == "theirs" || variant == "merged" {
			src += "  b: {type: string, default: x, variants: {x: hi}}\n"
		}
		src += "  c: {type: number, default: x, variants: {x: 1}}\n"
		if variant == "ours" || variant == "merged" {
			src = strings.Replace(src, "variants: {x: 1}", "variants: {x: 2, y: 3}", 1)
		}
		d, err := changesdecl.Parse(changesdecl.FileName, []byte(src))
		if err != nil {
			t.Fatal(err)
		}
		return d
	}
	for rel, gen := range map[string]func(*changesdecl.Decl) ([]byte, error){ChangesGoFile: GenerateChangesGo, "frontends/web/" + ChangesTSFile: GenerateChangesTS} {
		mergeproperty.AssertPlainMergeIsRender(t, rel, func(variant string) []byte {
			out, err := gen(decl(variant))
			if err != nil {
				t.Fatal(err)
			}
			return out
		})
	}
}

func checkGolden(t *testing.T, path string, got []byte) {
	t.Helper()
	if os.Getenv("FORGE_UPDATE_GOLDEN") == "1" {
		if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(path, got, 0o644); err != nil {
			t.Fatal(err)
		}
	}
	want, err := os.ReadFile(path)
	if err != nil {
		t.Fatalf("read golden (FORGE_UPDATE_GOLDEN=1 writes it): %v", err)
	}
	if string(want) != string(got) {
		t.Errorf("%s differs from the render (FORGE_UPDATE_GOLDEN=1 rewrites it):\n--- got ---\n%s", path, got)
	}
}
