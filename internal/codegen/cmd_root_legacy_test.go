package codegen

import (
	"os"
	"path/filepath"
	"testing"
)

// TestSyncLegacyRootGen_ReclaimsALeftoverFile pins the retirement: a pristine
// root_gen.go forge rendered earlier is removed, because the current root.go
// declares ServiceName itself and a stale copy is a redeclaration.
func TestSyncLegacyRootGen_ReclaimsALeftoverFile(t *testing.T) {
	dir := t.TempDir()
	rel := legacyRootGenRelPath("demo")
	if err := os.MkdirAll(filepath.Join(dir, filepath.Dir(rel)), 0o755); err != nil {
		t.Fatal(err)
	}
	body := []byte("// Code generated by forge. DO NOT EDIT.\npackage cmd\n\nconst ServiceName = \"demo\"\n")
	if err := writeForgeOwned(dir, rel, body, nil); err != nil {
		t.Fatal(err)
	}

	if err := SyncLegacyRootGen(dir, "example.com/demo", "demo", nil); err != nil {
		t.Fatal(err)
	}
	if _, err := os.Stat(filepath.Join(dir, rel)); !os.IsNotExist(err) {
		t.Errorf("root_gen.go survived its retirement (stat err: %v)", err)
	}
}

// TestSyncLegacyRootGen_NeverEmits: forge writes no root_gen.go, whatever
// shape root.go has.
func TestSyncLegacyRootGen_NeverEmits(t *testing.T) {
	dir := t.TempDir()
	treeDir := filepath.Join(dir, "cmd", "demo", "cmd")
	if err := os.MkdirAll(treeDir, 0o755); err != nil {
		t.Fatal(err)
	}
	legacy := "package cmd\n\nfunc newRootCmd(deps Deps) {\n\tfor _, c := range generatedCommands(deps) {\n\t\t_ = c\n\t}\n}\n"
	if err := os.WriteFile(filepath.Join(treeDir, "root.go"), []byte(legacy), 0o644); err != nil {
		t.Fatal(err)
	}

	if err := SyncLegacyRootGen(dir, "example.com/demo", "demo", nil); err != nil {
		t.Fatal(err)
	}
	if _, err := os.Stat(filepath.Join(dir, legacyRootGenRelPath("demo"))); !os.IsNotExist(err) {
		t.Errorf("root_gen.go must not be emitted (stat err: %v)", err)
	}
}
