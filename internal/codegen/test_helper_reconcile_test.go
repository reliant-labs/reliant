package codegen

import (
	"os"
	"path/filepath"
	"strings"
	"testing"
)

func TestReconcileScaffoldTestHelperName_UpdatesAllHandlerTests(t *testing.T) {
	root := t.TempDir()
	// The handler's package clause doesn't have to match its directory.
	dir := filepath.Join(root, "internal", "handlers", "billing_ops")
	if err := os.MkdirAll(dir, 0o755); err != nil {
		t.Fatal(err)
	}
	writeReconcileFixture(t, filepath.Join(root, "go.mod"), "module example.com/demo\n")

	// @ marks the exact insertion point for the Svc prefix. The user test
	// uses an explicit alias; the other tests use the default package name.
	const selectors = `package billing_test

import "example.com/demo/internal/handlers/billing_ops"

var _ = billing.NewTest@Billing
var _ = billing.NewTest@BillingServer
var _ = billing.With@BillingDeps
`
	const custom = `package billing_test

import (
	acct "example.com/demo/internal/handlers/billing_ops"
	other "example.net/other/internal/handlers/billing_ops"
)

var _ = acct.NewTest@Billing
var _ = acct.NewTest@BillingServer
var _ = acct.With@BillingDeps

var _ = acct.NewTestBillingFixture
var _ = acct.WithBillingDepsFixture
var _ = other.NewTestBilling
var _ = "acct.NewTestBilling"

// acct.NewTestBilling must be left alone in comments.
func NewTestBillingFixture() {}

func shadow() {
	acct := struct{ NewTestBilling int }{}
	_ = acct.NewTestBilling
}
`
	files := map[string]string{
		"handlers_test.go":                custom,
		"handlers_crud_test.go":           selectors,
		"rpc_run_test.go":                 selectors,
		"handlers_scaffold_other_test.go": custom,
		"helpers_gen_test.go":             "// Code generated by forge. DO NOT EDIT.\n\n" + strings.ReplaceAll(selectors, "@", ""),
		"not_a_test_file.go":              strings.ReplaceAll(selectors, "@", ""),
	}
	for name, fixture := range files {
		writeReconcileFixture(t, filepath.Join(dir, name), strings.ReplaceAll(fixture, "@", ""))
	}
	writeWiredPkg(t, root, "billing")
	assertHelperReconcile(t, root, dir, files, "Svc")

	if changed, err := ReconcileScaffoldTestHelperName(root, "billing", dir); err != nil || changed {
		t.Fatalf("second reconcile: changed=%t, err=%v; want a no-op", changed, err)
	}
	if err := os.Remove(filepath.Join(root, "internal", "billing", "contract.go")); err != nil {
		t.Fatal(err)
	}
	assertHelperReconcile(t, root, dir, files, "")
}

func assertHelperReconcile(t *testing.T, root, dir string, files map[string]string, prefix string) {
	t.Helper()
	changed, err := ReconcileScaffoldTestHelperName(root, "billing", dir)
	if err != nil || !changed {
		t.Fatalf("reconcile (prefix %q): changed=%t, err=%v", prefix, changed, err)
	}
	for name, fixture := range files {
		want := strings.ReplaceAll(fixture, "@", prefix)
		got, err := os.ReadFile(filepath.Join(dir, name))
		if err != nil {
			t.Fatal(err)
		}
		if string(got) != want {
			t.Errorf("%s (prefix %q):\n--- got ---\n%s\n--- want ---\n%s", name, prefix, got, want)
		}
	}
}

func writeReconcileFixture(t *testing.T, path, content string) {
	t.Helper()
	if err := os.WriteFile(path, []byte(content), 0o644); err != nil {
		t.Fatal(err)
	}
}
