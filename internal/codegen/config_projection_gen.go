// Package codegen — config_projection_gen.go emits the VALUE-projection
// half, and assembles it with the TYPE half from config_schema_gen.go into
// the single generated module deploy/kcl/config_gen.k (GenerateConfigKCL,
// the one entrypoint the pipeline calls).
//
// Where config_schema_gen.go projects the SHAPE (`schema AppConfig`), this
// emitter projects the BEHAVIOR: one generated KCL function that turns a
// typed `AppConfig` value into entries of a workload's env map
// (fw.Workload.env, kcl/workload.k) —
//
//   - appConfigEnvMap(c, config_secrets) -> {str: str | forge.SecretRef}
//     keyed by ENV_VAR name, one entry per config field with a non-empty
//     env_var:
//   - non-sensitive -> the value read off c, as a string (INLINE: no
//     ConfigMap object or reference). Projected for EVERY caller: no
//     credential, no start-time dependency, so broadcasting it is free.
//   - sensitive     -> forge.SecretRef {name = c.<field>.name, key =
//     c.<field>.key, store_key = "<ENV_VAR>", optional?}
//     (reads the typed ConfigSecretRef off the value. Projected ONLY when
//     `config_secrets` names it — see renderConfigEnvMapNamed for the
//     outage that rule exists to prevent.)
//   - env family    -> one entry per KEY of the field's map, each projected
//     as its family's sensitivity says; a sensitive family is selected by
//     its pattern in `config_secrets` (config_env_family_kcl.go).
//
// A workload consumes it the native way:
//
//	env = appConfigEnvMap(app_config, config_secrets) | { <workload extras> }
//
// — config first, composed with map-merge `|` (last-wins), so a workload
// extra of the same NAME overrides the config entry, and a duplicate name
// is structurally impossible.
//
// ONE entry serves every runtime. forge.render lowers a SecretRef to the
// wire's `secretRef` for a cluster or host workload, and — via `store_key`,
// the key the env's secret store holds the value under — to a
// `managedSecret {name = store_key}` for a HOSTED one, carrying `optional`
// through both. So an author never re-states a credential per runtime.
//
// The per-field metadata (env-var name, sensitive flag, value expression) is
// BAKED into the generated code from the proto, so the emitted KCL is a
// straight-line map literal. The runtime Go loader (pkg/config/loader.go,
// which binds env by each field's env_var) reads the SAME projected env vars,
// so the two stay coherent by construction.
//
// The default Secret backend (name = "<project>-secrets", key =
// lower(env_var)) is supplied by the AppConfig field's SCHEMA DEFAULT (see
// config_schema_gen.go), and a per-env override flows through as a
// ConfigSecretRef the author writes into config.k.
package codegen

import (
	"fmt"
	"sort"
	"strconv"
	"strings"

	"github.com/reliant-labs/forge/internal/naming"
)

// GenerateConfigKCL emits the ONE generated config module —
// deploy/kcl/config_gen.k — carrying both halves of the projection: the
// TYPE (`schema ConfigSecretRef` + `schema AppConfig`) and the BEHAVIOR
// (`appConfigEnvMap`).
//
// They were two files (config_schema.k + config_projection.k) on the
// premise that a KCL module cannot hold a schema and a lambda together.
// It can — forge's own kcl/workload.k interleaves schemas and lambdas in
// one file. Since both
// halves are projected from the same proto by the same run and are only
// ever valid as a pair, splitting them bought nothing and cost a second
// Tier-1 file, a second hash guard and a second diff entry in every
// change. Merging also removes the cross-module import: the lambda now
// names `AppConfig` directly instead of `config_schema.AppConfig`.
//
// Layout is TYPE first, then BEHAVIOR — the lambda's signature references
// AppConfig, and reading the shape before the projection over it is the
// order that explains itself.
//
// Fields are visited in proto order by both halves. A field with an empty
// env_var (a component config-block reference, or any field with no env
// binding) is skipped by the projection — mirroring the runtime loader,
// which binds env only for fields that declare an env_var.
func GenerateConfigKCL(fields []ConfigField, projectName string) (string, error) {
	var b strings.Builder

	b.WriteString("# Code generated by forge. DO NOT EDIT.\n")
	b.WriteString("# Typed config schema + env projection, both projected from " + configProtoDir(projectName) + "/config.proto — author per-env values in deploy/kcl/<env>/config.k as an `AppConfig { ... }` instance; add or change fields in the PROTO, never here.\n\n")

	// forge.SecretRef is in the projection's return type; the schemas below
	// need no import (they are declared here).
	b.WriteString(configModuleImports(fields))

	schema, err := renderAppConfigSchema(fields, projectName)
	if err != nil {
		return "", fmt.Errorf("render config schema: %w", err)
	}
	b.WriteString(schema)
	b.WriteString("\n")
	b.WriteString(kclSection("env-map appConfigEnvMap"))
	b.WriteString(renderAppConfigEnvMap(fields))

	return b.String(), nil
}

// KCLConfigName maps a config MESSAGE name to the KCL schema and lambda it
// projects to: `AdminConfig` -> schema `AdminConfig`, lambda
// `adminConfigEnvMap`. The lambda name is the schema name lower-camelled
// with the `EnvMap` suffix, matching the existing appConfigEnvMap spelling
// so the per-binary names read as the same family.
func KCLConfigName(messageName string) (schema, lambda string) {
	if messageName == "" {
		return "AppConfig", "appConfigEnvMap"
	}
	lower := strings.ToLower(messageName[:1]) + messageName[1:]
	return messageName, lower + "EnvMap"
}

// KCLAllSensitiveName maps a config SCHEMA name to the generated constant
// listing every sensitive ENV_VAR that schema declares: `AppConfig` ->
// `APP_CONFIG_SENSITIVE_ENV`.
//
// It exists so the one caller that legitimately wants EVERY credential —
// forge's own host-mode config probe, which resolves what the env's config
// evaluates to for `forge env up`, the parity report and the seed gate — can say
// so by name instead of hand-listing vars that would go stale the moment a
// field is added. A cluster WORKLOAD must never use it: naming the whole set
// is precisely the broadcast this design removed.
func KCLAllSensitiveName(schemaName string) string {
	if schemaName == "" {
		schemaName = "AppConfig"
	}
	var b strings.Builder
	for i, r := range schemaName {
		if i > 0 && r >= 'A' && r <= 'Z' {
			b.WriteByte('_')
		}
		b.WriteRune(r)
	}
	return strings.ToUpper(b.String()) + "_SENSITIVE_ENV"
}

// KCLOptionalSecretsName maps a config SCHEMA name to the generated constant
// listing every sensitive ENV_VAR that schema marks `optional: true`:
// `AppConfig` -> `APP_CONFIG_OPTIONAL_SECRET_ENV`.
//
// It is the seam the secret PRE-FLIGHT reads. `forge env up` validates every
// declared secret_ref against the store before anything starts, and it works
// from the rendered entities — it has no proto and no descriptor in hand. So
// the proto's `optional` annotation is projected to KCL here and travels with
// the render, which keeps the dependency running one way: the secrets package
// never learns what a config message is.
//
// Emitted even when empty so a reference resolves in a project that marks
// nothing optional.
func KCLOptionalSecretsName(schemaName string) string {
	if schemaName == "" {
		schemaName = "AppConfig"
	}
	var b strings.Builder
	for i, r := range schemaName {
		if i > 0 && r >= 'A' && r <= 'Z' {
			b.WriteByte('_')
		}
		b.WriteRune(r)
	}
	return strings.ToUpper(b.String()) + "_OPTIONAL_SECRET_ENV"
}

// GenerateConfigKCLPerBinary emits the config module for a project that
// declares PER-BINARY configs: one typed schema plus one env-projection
// lambda per binary, all in the single generated config_gen.k.
//
// Each pair is projected from ONLY that binary's fields, which is what makes
// the deploy story disjoint: an env authoring `AdminConfig { ... }` can set
// only fields admin reads (anything else is a KCL type error), and the
// workload env built from adminConfigEnvMap carries only admin's env vars —
// so gateway's Deployment does not carry admin's credentials.
//
// rootFields is the project-global AppConfig's field set. It is still
// emitted when non-empty, because a project mid-migration (or one that keeps
// a shared AppConfig alongside per-binary ones) has env files and main.k
// modules that reference AppConfig/appConfigEnvMap, and those are user-owned
// scaffold-once files forge does not rewrite.
func GenerateConfigKCLPerBinary(rootFields []ConfigField, perBinary []BinaryConfigFields, projectName string) (string, error) {
	var b strings.Builder

	b.WriteString("# Code generated by forge. DO NOT EDIT.\n")
	b.WriteString("# Typed config schemas + env projections, one per BINARY, projected from " + configProtoDir(projectName) + "/config.proto — author per-env values in deploy/kcl/<env>/config.k as `<Binary>Config { ... }` instances; add or change fields in the PROTO, never here.\n\n")
	fieldSets := [][]ConfigField{rootFields}
	for _, bc := range perBinary {
		fieldSets = append(fieldSets, bc.Fields)
	}
	b.WriteString(configModuleImports(fieldSets...))

	// ConfigSecretRef is declared once for the whole module, by whichever
	// schema is emitted first.
	first := true
	emit := func(fields []ConfigField, messageName string) error {
		schemaName, lambdaName := KCLConfigName(messageName)
		schema, err := renderConfigSchemaNamed(fields, projectName, schemaName, first)
		if err != nil {
			return fmt.Errorf("render %s schema: %w", schemaName, err)
		}
		first = false
		b.WriteString(schema)
		b.WriteString("\n")
		b.WriteString(kclSection("env-map " + lambdaName))
		b.WriteString(renderConfigEnvMapNamed(fields, schemaName, lambdaName))
		b.WriteString("\n")
		return nil
	}

	if len(rootFields) > 0 {
		if err := emit(rootFields, "AppConfig"); err != nil {
			return "", err
		}
	}
	for _, bc := range perBinary {
		if err := emit(bc.Fields, bc.MessageName); err != nil {
			return "", err
		}
	}

	declared := map[string]bool{"AppConfig": true, "ConfigSecretRef": true}
	for _, bc := range perBinary {
		declared[bc.MessageName] = true
	}
	for _, ps := range ProcessSelectorsFrom(perBinary) {
		if declared[ps.SchemaName()] {
			return "", fmt.Errorf(
				"binary %q binds a config per subcommand, so forge generates the KCL schema %s for its processes — "+
					"and a config message of that name already exists. Rename the message",
				ps.Binary, ps.SchemaName())
		}
		b.WriteString(kclSection("process-selector " + ps.SchemaName()))
		b.WriteString(renderProcessSelector(ps))
		b.WriteString("\n")
	}

	return strings.TrimRight(b.String(), "\n") + "\n", nil
}

// ProcessSelector is one binary that scopes config to its subcommands: its
// root config (the binary-wide surface, nil when it declares none) and its
// command configs, ordered LONGEST command first so the first prefix match
// is the most specific one.
//
// It exists because, for such a binary, no single per-message env map is a
// workload's env: the process running `reliant server api` reads the root
// config AND the api config. The generated selector composes the two, picks
// the command config from the workload's own argv — so which workload gets
// which env is derived from the command it runs, not hand-filtered per
// workload — and splits the workload's config_secrets between them.
type ProcessSelector struct {
	Binary   string
	Root     *BinaryConfigFields
	Commands []BinaryConfigFields
	// Subtrees are the binary's subtree configs, in declaration order: each
	// one a process loads when one of its paths prefixes the process's path.
	Subtrees []BinaryConfigFields
}

// ProcessSelectorsFrom groups per-binary configs into one ProcessSelector per
// binary that declares at least one command or subtree config, in
// first-declaration order. A binary with only a root config needs no
// selector: its one env map is the process's env.
func ProcessSelectorsFrom(perBinary []BinaryConfigFields) []ProcessSelector {
	var order []string
	byBinary := map[string]*ProcessSelector{}
	for i := range perBinary {
		bc := perBinary[i]
		ps, ok := byBinary[bc.Binary]
		if !ok {
			ps = &ProcessSelector{Binary: bc.Binary}
			byBinary[bc.Binary] = ps
			order = append(order, bc.Binary)
		}
		if len(bc.Subtrees) > 0 {
			ps.Subtrees = append(ps.Subtrees, bc)
			continue
		}
		if len(bc.Command) == 0 {
			if ps.Root == nil {
				ps.Root = &perBinary[i]
			}
			continue
		}
		ps.Commands = append(ps.Commands, bc)
	}
	var out []ProcessSelector
	for _, b := range order {
		ps := byBinary[b]
		if len(ps.Commands) == 0 && len(ps.Subtrees) == 0 {
			continue
		}
		sort.SliceStable(ps.Commands, func(i, j int) bool {
			return len(ps.Commands[i].Command) > len(ps.Commands[j].Command)
		})
		out = append(out, *ps)
	}
	return out
}

// SchemaName is the generated KCL schema bundling the binary's config
// instances: `reliant` -> `ReliantProcess`.
func (ps ProcessSelector) SchemaName() string { return kclPascal(ps.Binary) + "Process" }

// LambdaName is the generated selector: `reliant` -> `reliantProcessEnvMap`.
func (ps ProcessSelector) LambdaName() string {
	s := ps.SchemaName()
	return strings.ToLower(s[:1]) + s[1:] + "EnvMap"
}

// InstanceName is the member a config's instance takes on the bundle, and the
// name the per-env config.k scaffold declares it under: `ApiServerConfig` ->
// `api_server_config`.
func InstanceName(messageName string) string { return naming.ToSnakeCase(messageName) }

// kclPascal PascalCases a binary name for a KCL identifier: `api-gateway` ->
// `ApiGateway`. Unlike naming.ToPascalCase it applies no Go initialisms, which
// would make the lower-camelled lambda read `aPIGatewayProcessEnvMap`.
func kclPascal(s string) string {
	var b strings.Builder
	for _, w := range strings.FieldsFunc(s, func(r rune) bool { return r == '-' || r == '_' || r == '.' }) {
		b.WriteString(strings.ToUpper(w[:1]) + w[1:])
	}
	return b.String()
}

// renderProcessSelector emits a binary's process bundle schema and its
// selector lambda. See ProcessSelector for why it exists; the comment it
// emits is the user-facing contract.
func renderProcessSelector(ps ProcessSelector) string {
	var b strings.Builder
	schema, lambda := ps.SchemaName(), ps.LambdaName()
	process := func(bc BinaryConfigFields) string {
		return strings.TrimSpace(ps.Binary + " " + strings.Join(bc.Command, " "))
	}

	fmt.Fprintf(&b, "# The `%s` binary binds a config per subcommand, so a workload's env is the\n", ps.Binary)
	b.WriteString("# binary's root config PLUS the config of the subcommand its process runs.\n")
	fmt.Fprintf(&b, "# %s carries the instances (config.k declares one); %s\n", schema, lambda)
	b.WriteString("# picks the subcommand's from the workload's own command line.\n")
	fmt.Fprintf(&b, "schema %s:\n", schema)
	if ps.Root != nil {
		fmt.Fprintf(&b, "    # Every `%s` process: the binary-wide root config.\n", ps.Binary)
		fmt.Fprintf(&b, "    %s?: %s\n", InstanceName(ps.Root.MessageName), ps.Root.MessageName)
	}
	for _, c := range ps.Subtrees {
		fmt.Fprintf(&b, "    # Every process at or below %s.\n", subtreeList(ps.Binary, c.Subtrees))
		fmt.Fprintf(&b, "    %s?: %s\n", InstanceName(c.MessageName), c.MessageName)
	}
	for _, c := range ps.Commands {
		fmt.Fprintf(&b, "    # `%s`\n", process(c))
		fmt.Fprintf(&b, "    %s?: %s\n", InstanceName(c.MessageName), c.MessageName)
	}
	b.WriteString("\n")

	fmt.Fprintf(&b, "# %s projects ONE `%s` process's config into a workload's env\n", lambda, ps.Binary)
	b.WriteString("# map: the root config, plus the config of the subcommand argv runs.\n")
	b.WriteString("#\n")
	b.WriteString("# argv is the process's command line, a workload's `command + args`. The\n")
	fmt.Fprintf(&b, "# subcommand path is what follows the token naming the binary (`%s`, or one\n", ps.Binary)
	fmt.Fprintf(&b, "# ending in `/%s`: `./cmd/%s`, `/app/%s`), or all of argv when no token\n", ps.Binary, ps.Binary, ps.Binary)
	b.WriteString("# names it (an image whose ENTRYPOINT is the binary, run with `args`). The\n")
	b.WriteString("# path ends at the first flag, so put flags after the subcommand. The\n")
	b.WriteString("# LONGEST declared command that prefixes the path wins; a process running\n")
	b.WriteString("# none of them gets the root config alone. Every subtree config one of whose\n")
	b.WriteString("# paths prefixes the path is added too.\n")
	b.WriteString("#\n")
	b.WriteString("# config_secrets names the sensitive fields the workload reads, across both\n")
	b.WriteString("# configs; each is routed to the config that declares it.\n")
	b.WriteString("#\n")
	fmt.Fprintf(&b, "#     env = config_gen.%s(appcfg.%s, (w.command or []) + (w.args or []), w.config_secrets) | w.env\n",
		lambda, naming.ToSnakeCase(schema))
	fmt.Fprintf(&b, "%s = lambda p: %s, argv: [str], config_secrets: [str] -> {str: str | forge.SecretRef} {\n", lambda, schema)
	fmt.Fprintf(&b, "    _at = [_i for _i, _a in argv if _a == %q or _a.endswith(%q)]\n", ps.Binary, "/"+ps.Binary)
	b.WriteString("    _rest = argv[_at[0] + 1:] if _at else argv\n")
	b.WriteString("    _flags = [_i for _i, _a in _rest if _a.startswith(\"-\")]\n")
	b.WriteString("    _path = _rest[:_flags[0]] if _flags else _rest\n")

	// The matched command config, by instance name; "" for none. Longest
	// first (ProcessSelectorsFrom), so a chain of conditionals is a
	// longest-prefix match.
	b.WriteString("    _cmd = ")
	for _, c := range ps.Commands {
		fmt.Fprintf(&b, "%q if _path[:%d] == %s else ", InstanceName(c.MessageName), len(c.Command), kclStrList(c.Command))
	}
	b.WriteString("\"\"\n")

	rootSensitive := "[]"
	if ps.Root != nil {
		rootSensitive = KCLAllSensitiveName(ps.Root.MessageName)
	}
	fmt.Fprintf(&b, "    _root_sensitive: [str] = %s\n", rootSensitive)
	for _, c := range ps.Subtrees {
		inst := InstanceName(c.MessageName)
		fmt.Fprintf(&b, "    _in_%s = any _p in %s { _path[:len(_p)] == _p }\n", inst, kclPathList(c.Subtrees))
	}
	b.WriteString("    _sub_sensitive: [str] = []")
	for _, c := range ps.Subtrees {
		fmt.Fprintf(&b, " + (%s if _in_%s else [])", KCLAllSensitiveName(c.MessageName), InstanceName(c.MessageName))
	}
	b.WriteString("\n")
	b.WriteString("    _cmd_sensitive: [str] = ")
	for _, c := range ps.Commands {
		fmt.Fprintf(&b, "%s if _cmd == %q else ", KCLAllSensitiveName(c.MessageName), InstanceName(c.MessageName))
	}
	b.WriteString("[]\n")

	b.WriteString("    assert all _n in config_secrets { _n in _root_sensitive or _n in _sub_sensitive or _n in _cmd_sensitive }, \\\n")
	fmt.Fprintf(&b, "        \"%s: config_secrets names ${[_n for _n in config_secrets if _n not in _root_sensitive and _n not in _sub_sensitive and _n not in _cmd_sensitive]}, which is not a `sensitive` field of the config(s) a `%s` process running ${_path} loads. Sensitive fields: ${sorted(_root_sensitive + _sub_sensitive + _cmd_sensitive)}.\"\n", lambda, ps.Binary)

	rootEnv := "{}"
	if ps.Root != nil {
		inst := InstanceName(ps.Root.MessageName)
		_, rootLambda := KCLConfigName(ps.Root.MessageName)
		fmt.Fprintf(&b, "    assert p.%s not in [None, Undefined], \"%s: every `%s` process loads %s — set `%s` on the %s.\"\n",
			inst, lambda, ps.Binary, ps.Root.MessageName, inst, schema)
		rootEnv = fmt.Sprintf("%s(p.%s, [_n for _n in config_secrets if _n in _root_sensitive])", rootLambda, inst)
	}
	for _, c := range ps.Subtrees {
		inst := InstanceName(c.MessageName)
		fmt.Fprintf(&b, "    assert not _in_%s or p.%s not in [None, Undefined], \"%s: this workload runs `%s ${' '.join(_path)}`, at or below %s, which loads %s — set `%s` on the %s.\"\n",
			inst, inst, lambda, ps.Binary, subtreeList(ps.Binary, c.Subtrees), c.MessageName, inst, schema)
	}
	for _, c := range ps.Commands {
		inst := InstanceName(c.MessageName)
		fmt.Fprintf(&b, "    assert _cmd != %q or p.%s not in [None, Undefined], \"%s: this workload runs `%s`, which loads %s — set `%s` on the %s.\"\n",
			inst, inst, lambda, process(c), c.MessageName, inst, schema)
	}
	fmt.Fprintf(&b, "    _root_env = %s\n", rootEnv)
	b.WriteString("    _sub_env = {}")
	for _, c := range ps.Subtrees {
		inst := InstanceName(c.MessageName)
		_, subLambda := KCLConfigName(c.MessageName)
		fmt.Fprintf(&b, " | (%s(p.%s, [_n for _n in config_secrets if _n in %s]) if _in_%s else {})",
			subLambda, inst, KCLAllSensitiveName(c.MessageName), inst)
	}
	b.WriteString("\n")
	b.WriteString("    _cmd_env = ")
	for _, c := range ps.Commands {
		inst := InstanceName(c.MessageName)
		_, cmdLambda := KCLConfigName(c.MessageName)
		fmt.Fprintf(&b, "%s(p.%s, [_n for _n in config_secrets if _n in _cmd_sensitive]) if _cmd == %q else ", cmdLambda, inst, inst)
	}
	b.WriteString("{}\n")
	// Root first, then the subtree configs, then the command config. Their
	// keys are disjoint — generate refuses a leaf two configs one process
	// loads both declare (ValidateBinaryConfigBindings) — so `|` only adds
	// keys and keeps insertion order.
	b.WriteString("    _root_env | _sub_env | _cmd_env\n")
	b.WriteString("}\n")
	return b.String()
}

// kclPathList renders command paths as a KCL list of string lists.
func kclPathList(paths [][]string) string {
	q := make([]string, len(paths))
	for i, p := range paths {
		q[i] = kclStrList(p)
	}
	return "[" + strings.Join(q, ", ") + "]"
}

// subtreeList renders subtree paths as shell commands for a comment:
// "`reliant daemon`, `reliant open`".
func subtreeList(binary string, paths [][]string) string {
	q := make([]string, len(paths))
	for i, p := range paths {
		q[i] = "`" + strings.TrimSpace(binary+" "+strings.Join(p, " ")) + "`"
	}
	return strings.Join(q, ", ")
}

// kclStrList renders a string list as a KCL list literal.
func kclStrList(items []string) string {
	q := make([]string, len(items))
	for i, s := range items {
		q[i] = strconv.Quote(s)
	}
	return "[" + strings.Join(q, ", ") + "]"
}

// BinaryConfigFields is one binary-bound config's KCL projection input: the
// config message name (which names the schema and lambda), the process that
// loads it, and the ConfigFields it resolves — its own leaves plus the
// leaves of every block it composes.
type BinaryConfigFields struct {
	Binary string
	// Command is the subcommand path whose process loads this config; empty
	// for the binary's root config. See ConfigMessage.Command.
	Command []string
	// Subtrees are the command paths at or below which this config is
	// loaded; empty unless it is a subtree config. See ConfigMessage.Subtrees.
	Subtrees    [][]string
	MessageName string
	Fields      []ConfigField
}

// BinaryConfigFieldsFrom resolves the per-binary KCL projection inputs from
// parsed config messages, in declaration order. Empty for a project that
// declares no per-binary configs.
func BinaryConfigFieldsFrom(messages []ConfigMessage) []BinaryConfigFields {
	var out []BinaryConfigFields
	for _, m := range messages {
		if m.Binary == "" {
			continue
		}
		out = append(out, BinaryConfigFields{
			Binary:      m.Binary,
			Command:     m.Command,
			Subtrees:    m.Subtrees,
			MessageName: m.Name,
			Fields:      ConfigFieldsForMessage(messages, m.Name),
		})
	}
	return out
}

// renderAppConfigEnvMap emits the appConfigEnvMap lambda: env-map entries
// `{str: str | forge.SecretRef}` keyed by ENV_VAR name, one per field with a
// non-empty env_var (see the file comment).
//
//	env = appConfigEnvMap(app_config, config_secrets) | {EXTRA = "x"}
func renderAppConfigEnvMap(fields []ConfigField) string {
	return renderConfigEnvMapNamed(fields, "AppConfig", "appConfigEnvMap")
}

// renderConfigEnvMapNamed emits one env-projection lambda over one config
// schema. It is the per-binary generalization of renderAppConfigEnvMap: a
// project with per-binary configs emits one lambda per binary, each closing
// over ONLY that binary's fields.
//
// The lambda takes TWO arguments, and the second is the fix for the defect
// described below:
//
//		<lambda>(cfg, config_secrets)
//
//	  - NON-SENSITIVE fields are projected UNCONDITIONALLY, for every caller.
//	    They lower to an inline `{value = ...}` read straight off the typed
//	    config, so they carry no credential and — crucially — no start-time
//	    dependency on anything existing in the cluster. Broadcasting them is
//	    free, and keeping it free is what stops this design from taxing the
//	    ordinary act of adding a config value: declare `env_var` in the proto
//	    and every workload has it, exactly as before.
//	  - SENSITIVE fields are projected ONLY when the caller NAMES them in
//	    `config_secrets`. A workload's rendered manifest therefore carries the
//	    secretKeyRefs that workload declared it reads, and no others.
//
// WHY, and what broke. Every env's main.k layers ONE projected map under
// EVERY workload, so while the sensitive branch was unconditional, adding a
// single `sensitive` field to a shared AppConfig added a secretKeyRef to
// every Deployment, CronJob and Job in the project. In control-plane a new
// `zitadel_broker_token` field landed in 7 Deployments plus a Job that never
// read it. That is not cosmetic: a pod whose secretKeyRef names a key that
// does not exist NEVER STARTS — it stalls in CreateContainerConfigError,
// emitting no application log, so the failure looks nothing like its cause.
// The first deploy of one feature's credential would have taken the whole
// namespace down rather than that one feature (see
// control-plane/docs/zitadel-prod-recovery.md). It was a least-privilege
// failure on its own terms too: the LLM-proxy pod has no business carrying
// the IdP broker credential.
//
// The ARITY change is deliberate and is the migration story. A one-arg call
// against the new lambda is a KCL CompileError naming the file and line
// ("expected 2 positional arguments, found 1"), so every existing call site
// is found mechanically at render time. The rejected alternative — defaulting
// `config_secrets = []` — is what makes this dangerous: an unmigrated env would
// render green while SILENTLY DROPPING every credential from every pod, and
// the app would fail at runtime, far from the edit, exactly the class of
// failure this change exists to remove.
//
// Naming a field that is not a sensitive field of this config is a render
// FAILURE, not a silent no-op. A `config_secrets` entry that is quietly ignored
// (a typo, or a field renamed in the proto) is a workload that believes it
// declared a credential and does not have one — the CreateContainerConfigError
// story again, one layer up. The assert names the unknown entry and lists
// every sensitive var this config actually has.
func renderConfigEnvMapNamed(fields []ConfigField, schemaName, lambdaName string) string {
	type kv struct {
		key, expr string
		optional  bool
		// block is the config block the field belongs to ("" for a root
		// field): each block's entries are their own forge:section (see
		// writeGrouped).
		block string
		// omitWhen, on an inline entry, is the KCL condition under which the
		// entry is projected at all ("" = always). See the Optional branch
		// below.
		omitWhen string
	}
	var inline, secrets []kv
	// Env families (config_env_family_kcl.go): a non-sensitive family's
	// entries are inline, for every caller; a sensitive family's are keyed
	// by its pattern and selected by config_secrets like a scalar secret.
	var familyInline []string
	var familySecrets []kv
	for _, f := range fields {
		if f.EnvPrefix != "" {
			if !f.Sensitive {
				familyInline = append(familyInline, kclFamilyEntries(f, "c"))
				continue
			}
			familySecrets = append(familySecrets, kv{
				key:      familySecretName(f),
				expr:     kclFamilyEntries(f, "c"),
				optional: f.Optional,
			})
			continue
		}
		// Empty env_var == no env binding (block-reference messages and any
		// unbound field). Matches the runtime loader, which binds env only for
		// fields that declare an env_var.
		if f.EnvVar == "" {
			continue
		}
		if f.Sensitive {
			// Read the typed ConfigSecretRef off the AppConfig value: its
			// name/key ARE the SecretRef name/key. The AppConfig field's
			// SCHEMA DEFAULT supplies the default backend (<project>-secrets /
			// lower(env_var)); an author who set a ConfigSecretRef override
			// (the ${NAME#KEY} case) flows through here unchanged.
			// `optional` rides ON the SecretRef so it reaches the wire
			// (secretRef.optional / managedSecret.optional) and the store
			// pre-flight. Emitted only when true.
			//
			// `store_key` is the ENV_VAR name, which is the key the env's
			// secret store holds the value under. It is what lets ONE entry
			// serve every runtime: a cluster or host workload reads the
			// Secret key (secretRef), and a hosted workload reads the stored
			// value by that name (managedSecret) — forge.render picks.
			opt := ""
			if f.Optional {
				opt = ", optional = True"
			}
			expr := fmt.Sprintf(`forge.SecretRef {name = c.%s.name, key = c.%s.key, store_key = %q%s}`, f.KCLPath(), f.KCLPath(), f.EnvVar, opt)
			secrets = append(secrets, kv{
				key:      f.EnvVar,
				expr:     expr,
				optional: f.Optional,
				block:    f.KCLBlock,
			})
			continue
		}
		// Non-sensitive -> an INLINE value: the typed field read off `c` and
		// converted to a string via kclConfigValueExpr — no ConfigMap object,
		// no reference.
		//
		// An OPTIONAL non-sensitive field is projected only when its value
		// differs from its schema default. This is lossless — the runtime
		// loader resolves an absent env var to that same default — and it is
		// what lets a project add a knob that only some environments set
		// without touching every other environment's manifests. Before this,
		// adding one tier-specific string (say, an e2e-only storage endpoint)
		// put `value: ""` into every Deployment of every env, so an env that
		// never heard of the feature still churned on each field added. A
		// REQUIRED or unannotated field keeps the old always-projected shape:
		// its presence in the manifest is part of what an operator audits.
		entry := kv{
			key:   f.EnvVar,
			expr:  kclConfigValueExpr(f, "c"),
			block: f.KCLBlock,
		}
		if f.Optional {
			if def, ok := kclConfigDefaultLiteral(f); ok {
				entry.omitWhen = fmt.Sprintf("c.%s != %s", f.KCLPath(), def)
			}
		}
		inline = append(inline, entry)
	}

	var b strings.Builder

	// writeGrouped writes entries with each config block's run of entries
	// in its own forge:section (named "<group> <block>"), closed by a blank
	// line, so two branches that add fields to different blocks change
	// different sections (and never adjacent lines) and merge with plain
	// git. A closing "<group> (end)" section then holds whatever follows the
	// group, so a block appended at the end does not move that tail out of
	// the previous block's section (which would rehash it).
	writeGrouped := func(indent, group string, entries []kv, write func(kv)) {
		// Root fields declared on both sides of a block form two runs; the
		// second takes an ordinal, so every header in the module stays unique.
		runs := map[string]int{}
		for i, e := range entries {
			if i == 0 || e.block != entries[i-1].block {
				if i > 0 {
					b.WriteString("\n")
				}
				block := e.block
				if block == "" {
					block = "(root)"
				}
				if runs[block]++; runs[block] > 1 {
					block += fmt.Sprintf(" #%d", runs[block])
				}
				b.WriteString(indent + kclSection(group+" "+block))
			}
			write(e)
		}
		if len(entries) > 0 {
			b.WriteString("\n")
		}
		b.WriteString(indent + kclSection(group+" (end)"))
	}

	// The full sensitive-var list, as a module-level constant emitted BEFORE
	// the lambda (KCL binds top-level names; it cannot live in the body).
	// Only forge's own host-mode probe uses it (see KCLAllSensitiveName); a
	// workload that named it would reinstate the broadcast. It is emitted
	// even when empty so the probe's reference resolves in a project that
	// declares no credentials at all.
	fmt.Fprintf(&b, "# Every ENV_VAR %s declares `sensitive: true` for. Used by forge's\n", schemaName)
	b.WriteString("# host-mode config probe, which resolves the whole config for `forge env up`\n")
	b.WriteString("# and the parity report. A WORKLOAD must not use it: naming every\n")
	b.WriteString("# credential is the broadcast that put one feature's secretKeyRef on\n")
	b.WriteString("# every pod. Declare what a workload reads in its `config_secrets` instead.\n")
	// A sensitive env family is listed by its pattern
	// (APP_OAUTH_<KEY>_CLIENT_SECRET), the name config_secrets selects it by.
	//
	// One entry per line, grouped by config block like the env map below:
	// two branches that add credentials to different blocks change
	// different sections of the list, not its one line.
	allSecrets := append(append([]kv(nil), secrets...), familySecrets...)
	writeKeys := func(e kv) { fmt.Fprintf(&b, "    %q\n", e.key) }
	fmt.Fprintf(&b, "%s: [str] = [\n", KCLAllSensitiveName(schemaName))
	writeGrouped("    ", KCLAllSensitiveName(schemaName), allSecrets, writeKeys)
	b.WriteString("]\n\n")

	// The OPTIONAL subset of the above. Read by forge's secret pre-flight to
	// tell a credential this environment deliberately leaves unset from one
	// nobody has configured yet — the two are indistinguishable in the store,
	// so the annotation is the only thing that can say which.
	fmt.Fprintf(&b, "# Every ENV_VAR %s declares BOTH `sensitive: true` and\n", schemaName)
	b.WriteString("# `optional: true` for. The secret pre-flight skips these: a declared\n")
	b.WriteString("# secret with no value is an error by default, and this is the author\n")
	b.WriteString("# stating that THIS one's absence is intended (a tier's off-switch, a\n")
	b.WriteString("# credential only some environments own).\n")
	var optionalSecrets []kv
	for _, e := range allSecrets {
		if e.optional {
			optionalSecrets = append(optionalSecrets, e)
		}
	}
	fmt.Fprintf(&b, "%s: [str] = [\n", KCLOptionalSecretsName(schemaName))
	writeGrouped("    ", KCLOptionalSecretsName(schemaName), optionalSecrets, writeKeys)
	b.WriteString("]\n\n")

	fmt.Fprintf(&b, "# %s projects a typed %s into a workload's env MAP (fw.Workload.env):\n", lambdaName, schemaName)
	b.WriteString("# one entry per field that declares an env_var, keyed by ENV_VAR name — a\n")
	b.WriteString("# string for an ordinary field, a forge.SecretRef for a sensitive one.\n")
	b.WriteString("#\n")
	b.WriteString("# Non-sensitive fields are projected for EVERY caller: they are inline\n")
	b.WriteString("# values, so they carry no credential and no start-time dependency.\n")
	b.WriteString("# Sensitive fields are projected ONLY when `config_secrets` NAMES them, so a\n")
	b.WriteString("# workload's manifest carries the secretKeyRefs it declared and no others.\n")
	b.WriteString("# A pod whose secretKeyRef names a missing key does not start — it stalls\n")
	b.WriteString("# in CreateContainerConfigError with no application log — so a credential\n")
	b.WriteString("# broadcast to workloads that never read it turns one feature's missing\n")
	b.WriteString("# secret into a whole namespace outage.\n")
	fmt.Fprintf(&b, "#\n#     env = %s(cfg, config_secrets) | {EXTRA = \"value\"}\n", lambdaName)
	// The schema is declared above in this same file, so the parameter type
	// is the bare name — no module qualifier.
	//
	// `config_secrets` has NO default. A one-arg call is a compile error that
	// names the file and line; a default would render green and silently
	// ship pods with no credentials.
	fmt.Fprintf(&b, "%s = lambda c: %s, config_secrets: [str] -> {str: str | forge.SecretRef} {\n", lambdaName, schemaName)

	// The sensitive half is bound first so the assert can name what IS
	// available when an entry does not resolve.
	b.WriteString("    _sensitive: {str: forge.SecretRef} = {\n")
	writeGrouped("        ", lambdaName+" secrets", secrets, func(e kv) { fmt.Fprintf(&b, "        %q = %s\n", e.key, e.expr) })
	b.WriteString("    }\n")
	if len(familySecrets) == 0 {
		b.WriteString("    assert all _n in config_secrets { _n in _sensitive }, \\\n")
		fmt.Fprintf(&b, "        \"%s: config_secrets names ${[_n for _n in config_secrets if _n not in _sensitive]}, which is not a `sensitive` field of %s. Sensitive fields: ${sorted([_k for _k in _sensitive])}. Add `sensitive: true` to the field's (forge.v1.config) annotation in its config proto, or drop the name from this workload's config_secrets.\"\n", lambdaName, schemaName)
	} else {
		// Each sensitive family, by its pattern: the entries it expands to
		// in this config value, one SecretRef per KEY.
		b.WriteString("    _families: {str: {str: forge.SecretRef}} = {\n")
		for _, e := range familySecrets {
			fmt.Fprintf(&b, "        %q = %s\n", e.key, e.expr)
		}
		b.WriteString("    }\n")
		b.WriteString("    assert all _n in config_secrets { _n in _sensitive or _n in _families }, \\\n")
		fmt.Fprintf(&b, "        \"%s: config_secrets names ${[_n for _n in config_secrets if _n not in _sensitive and _n not in _families]}, which is not a `sensitive` field or env family of %s. Sensitive fields: ${sorted([_k for _k in _sensitive] + [_k for _k in _families])}. Add `sensitive: true` to the field's (forge.v1.config) annotation in its config proto, or drop the name from this workload's config_secrets.\"\n", lambdaName, schemaName)
	}

	// Inline half first, then the non-sensitive families, then the selected
	// secrets and sensitive families. `|` on disjoint key sets only ADDS
	// keys, so no entry is ever merged into another, and insertion order is
	// preserved (Kubernetes `$(VAR)` expansion reads only EARLIER entries).
	// Keys are disjoint by construction: generate refuses a family that
	// could claim another field's variable (ValidateConfigEnvFamilies).
	tail := append([]string(nil), familyInline...)
	tail = append(tail, "{_k: _sensitive[_k] for _k in _sensitive if _k in config_secrets}")
	if len(familySecrets) > 0 {
		tail = append(tail, "{_k: _v for _n in config_secrets if _n in _families for _k, _v in _families[_n]}")
	}
	rest := " | " + strings.Join(tail, " | ") + "\n"
	if len(inline) == 0 {
		b.WriteString("    {}" + rest)
	} else {
		b.WriteString("    {\n")
		writeGrouped("        ", lambdaName+" values", inline, func(e kv) {
			if e.omitWhen != "" {
				fmt.Fprintf(&b, "        if %s:\n", e.omitWhen)
				fmt.Fprintf(&b, "            %q = %s\n", e.key, e.expr)
				return
			}
			fmt.Fprintf(&b, "        %q = %s\n", e.key, e.expr)
		})
		b.WriteString("    }" + rest)
	}
	b.WriteString("}\n")
	return b.String()
}

// kclConfigValueExpr renders the KCL expression that reads field f off the
// typed AppConfig receiver `recv` as a STRING (env values are strings).
// String-typed fields — including durations, which forge carries as strings
// ("30s") — inline directly; int/float scalars are wrapped in KCL's str(...)
// builtin.
//
// Bools are the exception: KCL's str(True) yields "True"/"False"
// (capitalized), but the runtime Go loader parses env values with
// strconv.ParseBool and the canonical lowercase form is "true"/"false". So a
// bool is projected as an explicit `"true" if c.<field> else "false"`
// conditional to emit the lowercase form, NOT str(...).
//
// This reuses kclTypeForProtoConfig so the str/non-str decision stays
// identical to the schema emitter's type mapping.
func kclConfigValueExpr(f ConfigField, recv string) string {
	return kclValueExpr(f, recv+"."+f.KCLPath())
}

// kclValueExpr renders ref, a KCL expression holding a value of f's type, as
// the STRING an env var carries (see kclConfigValueExpr).
func kclValueExpr(f ConfigField, ref string) string {
	switch kclTypeForProtoConfig(f) {
	case "str":
		return ref
	case "bool":
		return `"true" if ` + ref + ` else "false"`
	default:
		return "str(" + ref + ")"
	}
}
