package codegen

import (
	"os"
	"path/filepath"
	"strings"
	"testing"
)

// TestGenerateMigrateRetiresPkgAppMigrate pins the RECLAMATION half of moving
// the migration logic into pkg/migratekit.
//
// The 86-line pkg/app/migrate.go this replaced was Tier-1, so every project
// scaffolded before the move has a pristine copy on disk carrying forge's "DO
// NOT EDIT — regenerated every run" marker. Nothing regenerates it anymore. A
// certified file that no emitter owns is exactly what the stale sweep deletes
// with --force-cleanup, and leaving it would also keep a second, diverging
// AutoMigrate in the user's tree. So the emitter reclaims its own render.
func TestGenerateMigrateRetiresPkgAppMigrate(t *testing.T) {
	dir := t.TempDir()
	rel := filepath.Join("pkg", "app", "migrate.go")
	abs := filepath.Join(dir, rel)
	if err := os.MkdirAll(filepath.Dir(abs), 0o755); err != nil {
		t.Fatal(err)
	}

	// A PRISTINE forge render: the banner plus a hash marker that verifies.
	body := []byte("// Code generated by forge. DO NOT EDIT.\npackage app\n")
	if err := os.WriteFile(abs, body, 0o644); err != nil {
		t.Fatal(err)
	}

	if err := GenerateMigrate(dir, "example.com/proj", false, nil); err != nil {
		t.Fatalf("GenerateMigrate: %v", err)
	}
	if _, err := os.Stat(abs); !os.IsNotExist(err) {
		t.Errorf("pkg/app/migrate.go survived; a forge-certified file that no emitter "+
			"writes anymore is what --force-cleanup deletes, and it shadows "+
			"migratekit.AutoMigrate (stat err = %v)", err)
	}
}

// TestGenerateMigrateKeepsUserOwnedMigrate is the other half, and the more
// important one: forge does not delete a file the user has made their own.
//
// A hand-edited migrate.go no longer verifies as forge's render, so it is the
// user's work — possibly a deliberately customized migration path — and
// removing it would destroy code forge did not write.
func TestGenerateMigrateKeepsUserOwnedMigrate(t *testing.T) {
	dir := t.TempDir()
	rel := filepath.Join("pkg", "app", "migrate.go")
	abs := filepath.Join(dir, rel)
	if err := os.MkdirAll(filepath.Dir(abs), 0o755); err != nil {
		t.Fatal(err)
	}
	// No forge banner at all: this is the user's file.
	body := []byte("package app\n\n// hand-written by the user\nfunc AutoMigrate() {}\n")
	if err := os.WriteFile(abs, body, 0o644); err != nil {
		t.Fatal(err)
	}

	if err := GenerateMigrate(dir, "example.com/proj", false, nil); err != nil {
		t.Fatalf("GenerateMigrate: %v", err)
	}
	got, err := os.ReadFile(abs)
	if err != nil {
		t.Fatalf("user-owned migrate.go was deleted: %v", err)
	}
	if !strings.Contains(string(got), "hand-written by the user") {
		t.Errorf("user-owned migrate.go was rewritten; forge must not touch a file it does not own:\n%s", got)
	}
}

// TestGenerateMigrateEmbedsOnlyWithSQL pins the one thing this emitter still
// derives: `//go:embed migrations/*.sql` does not compile against an empty
// match, so db/embed.go may exist only once the project has written SQL.
func TestGenerateMigrateEmbedsOnlyWithSQL(t *testing.T) {
	for _, tc := range []struct {
		name          string
		hasMigrations bool
		wantEmbed     bool
	}{
		{"no SQL yet", false, false},
		{"has SQL", true, true},
	} {
		t.Run(tc.name, func(t *testing.T) {
			dir := t.TempDir()
			if err := GenerateMigrate(dir, "example.com/proj", tc.hasMigrations, nil); err != nil {
				t.Fatalf("GenerateMigrate: %v", err)
			}
			_, err := os.Stat(filepath.Join(dir, "db", "embed_gen.go"))
			if got := err == nil; got != tc.wantEmbed {
				t.Errorf("db/embed.go present = %v, want %v", got, tc.wantEmbed)
			}
		})
	}
}
