// The harness's doubles come from ONE generator.
//
// A Deps field's interface used to get two same-shape fakes: a Mock<Role>
// in the declaring package's mock_gen.go, and a Stub<Field> synthesized
// into the handler's helpers_gen_test.go. Each had a <Method>Func field per
// method and an embedded contractkit.Recorder, and they differed only in
// which error an unprogrammed method returned — so a test author met two
// names for one collaborator, and a test written against one could not be
// handed the other.
//
// Now, whenever forge already writes a mock for the field's interface, the
// harness installs that mock and synthesizes nothing. The mock is found in
// one of two places:
//
//   - the handler package's own mock_gen.go — a deps.go marked by `forge
//     fix narrow-deps` mocks its local roles there, and the Deps-discovered
//     mocks of other packages' interfaces (MockEstimateStore for a
//     db.EstimateStore field) land there too;
//   - the mock_gen.go of the package that DECLARES the interface (its
//     contract.go or marked deps.go), imported by the harness.
//
// Stub<Field> remains only for an interface forge mocks nowhere — the
// standard library's, a third-party module's, or a handler-local one
// declared outside a marked deps.go.

// forgeMockFile is the file the contract generator writes a package's mocks
// into (internal/generator/contract).
const forgeMockFile = "mock_gen.go"

// forgeMockIndex is what one directory's forge-generated mock_gen.go
// mocks, read from the compile-time check the generator writes beside every
// mock: `var _ <Interface> = (*<Mock>)(nil)`. The check is the generator's
// own statement of which interface each mock satisfies, so the index needs
// no knowledge of how mocks are named (MockStore, MockDbEstimateStore on a
// collision, ...).
type forgeMockIndex struct {
	// local maps an interface declared in this package to its mock.
	local map[string]string
	// foreign maps "<import path>.<Name>" — an interface declared in
	// another package and mocked here — to its mock.
	foreign map[string]string
}

// readForgeMocks indexes dir's mock_gen.go. A missing file, one that does
// not parse, or one forge did not generate (a hand-written mock_gen.go has
// no forge header) indexes nothing: the harness then falls back to a stub,
// which is always correct.
func readForgeMocks(dir string) forgeMockIndex {
	idx := forgeMockIndex{local: map[string]string{}, foreign: map[string]string{}}
	path := filepath.Join(dir, forgeMockFile)
	src, err := os.ReadFile(path)
	if err != nil {
		return idx
	}
	f, err := parser.ParseFile(token.NewFileSet(), path, src, parser.ParseComments|parser.SkipObjectResolution)
	if err != nil || !generatedByForge(f) {
		return idx
	}
	imports := map[string]string{}
	for _, imp := range f.Imports {
		p, perr := importPathFromSpec(imp)
		if perr != nil {
			continue
		}
		imports[aliasForImport(imp, p)] = p
	}
	for _, decl := range f.Decls {
		gd, ok := decl.(*ast.GenDecl)
		if !ok || gd.Tok != token.VAR {
			continue
		}
		for _, spec := range gd.Specs {
			vs, ok := spec.(*ast.ValueSpec)
			if !ok || len(vs.Names) != 1 || vs.Names[0].Name != "_" || len(vs.Values) != 1 {
				continue
			}
			mock, ok := nilPointerConversion(vs.Values[0])
			if !ok {
				continue
			}
			switch t := vs.Type.(type) {
			case *ast.Ident:
				idx.local[t.Name] = mock
			case *ast.SelectorExpr:
				q, ok := t.X.(*ast.Ident)
				if !ok {
					continue
				}
				if p, ok := imports[q.Name]; ok {
					idx.foreign[p+"."+t.Sel.Name] = mock
				}
			}
		}
	}
	return idx
}

// generatedByForge reports whether f carries the contract generator's
// header, so a hand-written file that happens to be called mock_gen.go is
// never mistaken for forge's.
func generatedByForge(f *ast.File) bool {
	for _, cg := range f.Comments {
		if cg.Pos() >= f.Package {
			break
		}
		for _, c := range cg.List {
			if strings.HasPrefix(c.Text, "// Code generated by forge.") {
				return true
			}
		}
	}
	return false
}

// nilPointerConversion matches `(*Mock)(nil)` and returns Mock.
func nilPointerConversion(e ast.Expr) (string, bool) {
	call, ok := e.(*ast.CallExpr)
	if !ok || len(call.Args) != 1 {
		return "", false
	}
	if arg, ok := call.Args[0].(*ast.Ident); !ok || arg.Name != "nil" {
		return "", false
	}
	paren, ok := call.Fun.(*ast.ParenExpr)
	if !ok {
		return "", false
	}
	star, ok := paren.X.(*ast.StarExpr)
	if !ok {
		return "", false
	}
	id, ok := star.X.(*ast.Ident)
	if !ok {
		return "", false
	}
	return id.Name, true
}

// mocksIn is readForgeMocks, cached for the run.
func (r *typesResolver) mocksIn(dir string) forgeMockIndex {
	if idx, ok := r.mocks[dir]; ok {
		return idx
	}
	idx := readForgeMocks(dir)
	r.mocks[dir] = idx
	return idx
}

// forgeMock returns the mock forge generated for importPath's typeName in
// that package's own mock_gen.go.
//
// Only a package that type-checked cleanly is asked (r.pkg is nil
// otherwise), and its mock_gen.go's compile-time check is part of that
// package: a mock that did not satisfy the interface would have failed it.
// So a mock found here is one the harness can install.
func (r *typesResolver) forgeMock(importPath, typeName string) (string, bool) {
	pkg := r.pkg(importPath)
	dir := r.dirs[importPath]
	if pkg == nil || dir == "" {
		return "", false
	}
	mock, ok := r.mocksIn(dir).local[typeName]
	if !ok {
		return "", false
	}
	if _, ok := pkg.Scope().Lookup(mock).(*types.TypeName); !ok {
		return "", false
	}
	return mock, true
}

// DepsAutoMock is one Deps field the harness fills with the mock forge
// already generates for its interface, instead of synthesizing a stub.
type DepsAutoMock struct {
	// FieldName is the Deps field name as declared (e.g. "Pause").
	FieldName string
	// Interface is the field's type as the Deps struct spells it
	// ("runs.PauseController", "Repository"). It is for the generated
	// comment only.
	Interface string
	// MockType is the mock's type as the harness spells it: bare for a
	// mock in the handler's own package ("MockRepository"), qualified by
	// ExtraImports' alias for one in the declaring package
	// ("runs.MockPauseController").
	MockType string
	// ExtraImports is the declaring package's import, for a qualified
	// MockType; empty for a mock in the handler's own package.
	ExtraImports []ExtraImport
	// Optional marks a `// forge:optional-dep` field: NewTest<Svc>
	// leaves it nil, as it does for a stubbed optional field.
	Optional bool
	// StubType is the Stub<Field> this field was given before forge
	// filled it with its mock — the name `forge fix harness-mocks`
	// rewrites in the package's tests.
	StubType string
}

// mockForField decides whether the Deps field f — of type t, in the
// handler at handlerDir — gets a forge mock, and which. imports is the
// handler's alias -> import path map (collectImports).
//
// A mock in the handler's own mock_gen.go needs no type check of its own:
// the file's compile-time checks are part of the handler package, so a
// mock that no longer satisfied its interface fails the package's build
// before it could fail the harness's.
//
// For an interface of another package, the declaring package's own mock
// wins over a Deps-discovered copy in the handler's mock_gen.go, so one
// interface has one mock type — runs.MockPauseController — in every
// consumer's tests.
func mockForField(handlerDir string, f DepsField, t string, imports map[string]string, resolver *typesResolver) (DepsAutoMock, bool) {
	m := DepsAutoMock{FieldName: f.Name, Interface: t, Optional: f.Optional, StubType: "Stub" + f.Name}
	own := resolver.mocksIn(handlerDir)

	// A bare identifier: an interface declared in this package, mocked by
	// this package's mock_gen.go.
	if !strings.ContainsAny(t, ".*[]<>(){} ") {
		mock, ok := own.local[t]
		if !ok {
			return m, false
		}
		m.MockType = mock
		return m, true
	}

	// `<pkg>.<Type>` only — a pointer, slice or generic instantiation of an
	// interface is no Deps shape forge mocks.
	dot := strings.IndexByte(t, '.')
	if dot <= 0 || strings.ContainsAny(t, "*[]<>(){} ") {
		return m, false
	}
	alias, typeName := t[:dot], t[dot+1:]
	importPath, ok := imports[alias]
	if !ok {
		return m, false
	}
	// The declaring package's mock, imported under the package's declared
	// name — the qualifier the stubs use, so the alias reconciliation that
	// keeps stub imports apart applies unchanged.
	if mock, ok := resolver.forgeMock(importPath, typeName); ok {
		name := resolver.pkg(importPath).Name()
		m.MockType = name + "." + mock
		m.ExtraImports = []ExtraImport{{Alias: name, Path: importPath}}
		return m, true
	}
	// Else this package's own, Deps-discovered mock of the interface (the
	// db.EstimateStore case: internal/db mocks nothing): no import.
	mock, ok := own.foreign[importPath+"."+typeName]
	if !ok {
		return m, false
	}
	m.MockType = mock
	return m, true
}

// HarnessMockRename is one Stub<Field> the harness of the component in Dir
// synthesized before forge filled the field with its interface's mock —
// what `forge fix harness-mocks` rewrites in that component's tests.
type HarnessMockRename struct {
	// Dir is the component's directory, relative to the project root,
	// slash-separated ("internal/handlers/chat").
	Dir string
	// StubType is the retired double ("StubPause").
	StubType string
	// MockType is what the harness installs now, spelled from inside the
	// component's package: bare for its own mock ("MockNarrow"), qualified
	// for the declaring package's ("runs.MockPauseController").
	MockType string
	// Import is the package a qualified MockType is reached through; nil
	// for a bare one.
	Import *ExtraImport
}

// HarnessMockRenames reports, for every handler under
// projectDir/internal/handlers, each Deps field whose harness double is now
// a forge mock rather than a Stub<Field>. It reads the same inputs, through
// the same decision (computeDepsDoubles), as the harness generator — so the
// codemod renames exactly the stubs a regenerated harness no longer
// declares, and nothing else.
func HarnessMockRenames(projectDir string) ([]HarnessMockRename, error) {
	root := filepath.Join(projectDir, "internal", "handlers")
	var dirs []string
	err := filepath.WalkDir(root, func(path string, d os.DirEntry, err error) error {
		if err != nil {
			if os.IsNotExist(err) && path == root {
				return filepath.SkipDir
			}
			return err
		}
		if !d.IsDir() {
			return nil
		}
		if name := d.Name(); path != root && (name == "testdata" || strings.HasPrefix(name, ".")) {
			return filepath.SkipDir
		}
		if fields, ferr := ParseServiceDeps(path); ferr == nil && len(fields) > 0 {
			dirs = append(dirs, path)
		}
		return nil
	})
	if err != nil {
		return nil, err
	}
	if len(dirs) == 0 {
		return nil, nil
	}
	resolver := newTypesResolver(projectDir, depsSelectorImports(dirs))
	var out []HarnessMockRename
	for _, dir := range dirs {
		rel, rerr := filepath.Rel(projectDir, dir)
		if rerr != nil {
			return nil, rerr
		}
		_, mocks, _ := computeDepsDoubles(dir, resolver)
		for _, m := range mocks {
			r := HarnessMockRename{Dir: filepath.ToSlash(rel), StubType: m.StubType, MockType: m.MockType}
			if len(m.ExtraImports) > 0 {
				imp := m.ExtraImports[0]
				r.Import = &imp
			}
			out = append(out, r)
		}
	}
	return out, nil
}
