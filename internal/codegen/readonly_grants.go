// GenerateReadOnlyGrants writes db/grants/readonly_gen.sql and one row file
// per table under db/grants/readonly/ (pkg/dbgrants.Files): the grants that
// bound what the database's read-only role (pkg/dbgrants) can select.
//
// It projects the APPLIED schema (every base table, not only the ones a service
// has CRUD rpcs for) and the proto `forge:secret` markers, and the migrator
// applies the file after every run, so a new table or column is covered by the
// migration that creates it.
//
// A column is withheld when it is declared secret (proto field or SQL
// `forge:secret` comment) and also when it is credential-shaped and nobody
// decided (pkg/dbgrants.CredentialShaped): a `forge:readable <reason>` comment
// is the only way to grant such a column. The role holds no table-level SELECT,
// so a column added later is NOT readable until the next generate has seen
// whether it is secret. That is the safe direction to be wrong in.
//
// The dashboard role (pkg/dbgrants.DashboardRoleName) gets no generated
// grants: the project grants it with its own migrations. The files forge used
// to write for it (db/grants/dashboard_gen.sql and db/grants/dashboard/) are
// removed here when they are still forge's pristine output.
//
// cs is the project's checksum tracker. The files are only written when the
// project has migrations: the grants ride in the migrations' embed.
func GenerateReadOnlyGrants(projectDir string, services []ServiceDef, cs *checksums.FileChecksums) (written bool, err error) {
	if !projectHasSQLMigrations(projectDir) {
		return false, nil
	}
	migDir := filepath.Join(projectDir, "db", "migrations")
	tables, err := shadowdb.Tables(projectDir, migDir)
	if err != nil {
		return false, fmt.Errorf("introspect schema for read-only grants: %w", err)
	}
	if err := schemadef.CheckMarkers(tables); err != nil {
		return false, err
	}
	grantTables := ReadOnlyGrantTables(tables, services)
	files, err := GrantsFileSet(grantTables)
	if err != nil {
		return false, err
	}
	for _, rel := range sortedGrantPaths(files) {
		if err := writeForgeOwned(projectDir, rel, files[rel], cs); err != nil {
			return false, fmt.Errorf("write %s: %w", rel, err)
		}
	}
	// A table that is gone takes its row with it, and the retired dashboard
	// grants go whole. Only forge's own pristine file is removed: a
	// hand-edited or disowned one is reported by the drift lanes, never
	// deleted.
	for _, dir := range []string{dbgrants.GrantsRowsDir, retiredDashboardGrantsRowsDir} {
		entries, _ := os.ReadDir(filepath.Join(projectDir, filepath.FromSlash(dir)))
		for _, e := range entries {
			rel := dir + "/" + e.Name()
			if e.IsDir() || !strings.HasSuffix(e.Name(), "_gen.sql") || files[rel] != nil {
				continue
			}
			removeRetiredForgeFile(projectDir, filepath.FromSlash(rel), cs)
		}
	}
	removeRetiredForgeFile(projectDir, filepath.FromSlash(retiredDashboardGrantsPath), cs)
	// Gone once it is empty; a directory still holding a kept file stays.
	_ = os.Remove(filepath.Join(projectDir, filepath.FromSlash(retiredDashboardGrantsRowsDir)))
	return true, nil
}

// The dashboard role's generated grants, retired when its access moved to the
// project's own migrations (migrations/v1.0.13).
const (
	retiredDashboardGrantsPath    = "db/grants/dashboard_gen.sql"
	retiredDashboardGrantsRowsDir = "db/grants/dashboard"
)

// GrantsFileSet is every grants file `forge generate` writes for tables, keyed
// by project-relative path: the read-only role's script and one row per table
// (pkg/dbgrants.Files).
func GrantsFileSet(tables []dbgrants.Table) (map[string][]byte, error) {
	out := map[string][]byte{}
	ro, err := dbgrants.RenderFiles(tables)
	if err != nil {
		return nil, err
	}
	addGrantsFiles(out, dbgrants.GrantsPath, dbgrants.GrantsRowsDir, dbgrants.RoleName, ReadOnlyGrantsFile(ro.Main), ro)
	return out, nil
}

func addGrantsFiles(out map[string][]byte, mainPath, rowsDir, role string, main []byte, f dbgrants.Files) {
	out[mainPath] = main
	for _, t := range f.Tables {
		out[rowsDir+"/"+dbgrants.FileName(t.Schema, t.Name)] = GrantsRowFile(role, mainPath, t)
	}
}

// GrantsRowFile is the bytes of one table's row file: what role may read of
// the table, applied by the script at mainPath.
func GrantsRowFile(role, mainPath string, t dbgrants.TableFile) []byte {
	return []byte("-- Code generated by forge. DO NOT EDIT.\n" +
		"-- forge-owned: regenerated every run — do not edit (forge project disown to take ownership)\n" +
		"-- Source: the applied db/migrations schema and the proto forge:secret markers.\n" +
		"--\n" +
		"-- What the " + role + " role may read of " + t.Schema + "." + t.Name + ": one row of " + mainPath + ",\n" +
		"-- which the migrator splices in and applies (pkg/dbgrants.Files). A table per file, so\n" +
		"-- tables born on different branches merge as new files.\n" +
		t.Row)
}

func sortedGrantPaths(m map[string][]byte) []string {
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	return keys
}

// ReadOnlyGrantsFile is the bytes of db/grants/readonly_gen.sql around the
// script dbgrants.RenderFiles returned as Main.
func ReadOnlyGrantsFile(script string) []byte {
	return []byte("-- Code generated by forge. DO NOT EDIT.\n" +
		"-- forge-owned: regenerated every run — do not edit (forge project disown to take ownership)\n" +
		"-- Source: pkg/dbgrants; the per-table rows are db/grants/readonly/<schema>.<table>_gen.sql.\n" +
		"--\n" +
		"-- The grants of the " + dbgrants.RoleName + " role, which `forge db query` and the control plane read\n" +
		"-- through. The migrator applies this file, with the rows spliced in, after every\n" +
		"-- `db migrate up`, so a new table is covered by the migration that creates it. A column\n" +
		"-- marked forge:secret is not listed: Postgres refuses it, whatever the SQL.\n" +
		script)
}

// projectHasSQLMigrations is the predicate GenerateMigrate's caller uses for
// db/embed_gen.go, here on the path alone.
func projectHasSQLMigrations(projectDir string) bool {
	entries, err := os.ReadDir(filepath.Join(projectDir, "db", "migrations"))
	if err != nil {
		return false
	}
	for _, e := range entries {
		if !e.IsDir() && filepath.Ext(e.Name()) == ".sql" {
			return true
		}
	}
	return false
}

// ReadOnlyGrantTables is the pure half of GenerateReadOnlyGrants: every applied
// base table, each column secret or not.
//
// A column is secret when its table's entity wire message marks the same-named
// field `forge:secret`. The entity is the CRUD join's where a service claims
// the table, and otherwise the message named for the table's entity
// (TableEntityName) in ANY service: a table with no CRUD rpcs, or a
// `forge:custom` one, has no store-side entity to carry the marker, and its
// secrets must be withheld all the same.
//
// A table no wire message names has no proto field to carry forge:secret, so
// its secrets are declared in SQL (`COMMENT ON COLUMN t.c IS 'forge:secret'`),
// and what is not declared is judged by the column's name and type.
func ReadOnlyGrantTables(tables []schemadef.Table, services []ServiceDef) []dbgrants.Table {
	var base []schemadef.Table
	for _, t := range tables {
		if !t.IsView {
			base = append(base, t)
		}
	}
	secretCols := map[string]map[string]bool{} // table → secret column names
	mark := func(table string, fields []EntityField) {
		for _, f := range fields {
			if !f.Secret {
				continue
			}
			if secretCols[table] == nil {
				secretCols[table] = map[string]bool{}
			}
			secretCols[table][f.Name] = true
		}
	}
	joined := map[string]bool{}
	for _, e := range entitiesForTables(base, ManagedServices(services)) {
		joined[e.TableName] = true
		mark(e.TableName, e.Fields)
	}
	for _, t := range base {
		if joined[t.Name] {
			continue
		}
		name := TableEntityName(t)
		for _, svc := range services {
			mark(t.Name, WireEntityFields(svc, name))
		}
	}

	out := make([]dbgrants.Table, 0, len(base))
	for _, t := range base {
		schema := t.Schema
		if schema == "" {
			schema = "public"
		}
		dt := dbgrants.Table{Schema: schema, Name: t.Name}
		for _, c := range t.Columns {
			_, readable := c.ReadableReason()
			dt.Columns = append(dt.Columns, dbgrants.Column{
				Name:     c.Name,
				Secret:   secretCols[t.Name][c.Name] || c.DeclaresSecret(),
				Readable: readable,
				Kind:     grantColumnKind(c),
			})
		}
		out = append(out, dt)
	}
	sort.Slice(out, func(i, j int) bool {
		if out[i].Schema != out[j].Schema {
			return out[i].Schema < out[j].Schema
		}
		return out[i].Name < out[j].Name
	})
	return out
}

// grantColumnKind classifies a column's type for the role's name check. A type
// forge cannot place is text: the stricter reading.
func grantColumnKind(c schemadef.Column) dbgrants.ColumnKind {
	if c.IsArray || !c.TypeKnown {
		return dbgrants.KindText
	}
	switch c.Type {
	case schemadef.TypeInt, schemadef.TypeFloat, schemadef.TypeBool, schemadef.TypeTime:
		return dbgrants.KindScalar
	case schemadef.TypeBytes:
		return dbgrants.KindBinary
	}
	return dbgrants.KindText
}

// UndecidedReadOnlyColumns is what `forge lint --db-grants` reports: the
// credential-shaped columns of the applied schema that carry neither
// forge:secret (proto field or SQL comment) nor forge:readable. The grants
// withhold them all the same; this is the half that makes the omission loud.
func UndecidedReadOnlyColumns(tables []schemadef.Table, services []ServiceDef) []dbgrants.Finding {
	return dbgrants.Undecided(ReadOnlyGrantTables(tables, services))
}

// ParseReadOnlyGrantsServices returns the services whose messages can carry a
// `forge:secret` marker: every service in the descriptor, managed or not. nil
// when the project has no compiled descriptor yet.
func ParseReadOnlyGrantsServices(projectDir string) ([]ServiceDef, error) {
	desc, err := LoadDescriptor(projectDir)
	if err != nil || desc == nil {
		return nil, err
	}
	return desc.Services, nil
}
