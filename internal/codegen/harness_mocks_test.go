// TestReadForgeMocks_IndexesCompileTimeChecks pins the index: each
// `var _ I = (*M)(nil)` in a forge-generated mock_gen.go maps I to M, a
// qualified I is keyed by its import path, and a mock_gen.go forge did not
// write indexes nothing.
func TestReadForgeMocks_IndexesCompileTimeChecks(t *testing.T) {
	dir := t.TempDir()
	write := func(src string) {
		t.Helper()
		if err := os.WriteFile(filepath.Join(dir, forgeMockFile), []byte(src), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	write(`// Code generated by forge. DO NOT EDIT.
package chat

import (
	estore "example.com/proj/internal/db"
	"example.com/proj/internal/runs"
)

type MockNarrow struct{}
type MockEstimateStore struct{}
type MockPauseController struct{}

// Compile-time check.
var _ Narrow = (*MockNarrow)(nil)

// Compile-time check.
var _ estore.EstimateStore = (*MockEstimateStore)(nil)

var _ runs.PauseController = (*MockPauseController)(nil)

var notACheck = 1
`)
	idx := readForgeMocks(dir)
	if got := idx.local["Narrow"]; got != "MockNarrow" {
		t.Errorf("local[Narrow] = %q, want MockNarrow (all: %v)", got, idx.local)
	}
	if got := idx.foreign["example.com/proj/internal/db.EstimateStore"]; got != "MockEstimateStore" {
		t.Errorf("an aliased import is keyed by its path: foreign = %v", idx.foreign)
	}
	if got := idx.foreign["example.com/proj/internal/runs.PauseController"]; got != "MockPauseController" {
		t.Errorf("foreign = %v, want runs.PauseController keyed by path", idx.foreign)
	}

	write(`package chat

type MockNarrow struct{}

var _ Narrow = (*MockNarrow)(nil)
`)
	if idx := readForgeMocks(dir); len(idx.local)+len(idx.foreign) != 0 {
		t.Errorf("a mock_gen.go without forge's header is not forge's: indexed %+v", idx)
	}
}

// mockFixtureFiles is a module whose chat handler names one collaborator of
// each kind:
//
//   - Pause runs.PauseController — declared and mocked in internal/runs;
//   - Narrow Narrow — a role in the handler's own marked deps.go, mocked in
//     the handler's mock_gen.go;
//   - Estimates db.EstimateStore — internal/db mocks nothing, so the
//     handler's mock_gen.go carries a Deps-discovered MockEstimateStore;
//   - Repo Repository — declared in service.go, which nothing mocks;
//   - Sink runs.Sink, optional — mocked in internal/runs.
func mockFixtureFiles() map[string]string {
	return map[string]string{
		"internal/runs/contract.go": `package runs

import "context"

type PauseController interface {
	Pause(ctx context.Context, runID string) error
	Paused(runID string) bool
}

type Sink interface {
	Emit(ctx context.Context, event string) error
}

type Service interface {
	Start(ctx context.Context) error
}
`,
		"internal/db/store.go": `package db

import "context"

type EstimateStore interface {
	GetEstimate(ctx context.Context, id string) (string, error)
}
`,
		"internal/handlers/chat/deps.go": depsurface.DepsFileMarker + `

package chat

import "context"

type Narrow interface {
	Lookup(ctx context.Context, id string) (string, error)
}
`,
		"internal/handlers/chat/service.go": `package chat

import (
	"context"
	"errors"
	"log/slog"
	"net/http"

	"connectrpc.com/connect"

	"example.com/proj/internal/db"
	"example.com/proj/internal/runs"
)

type Repository interface {
	GetChat(ctx context.Context, id string) (string, error)
}

type Deps struct {
	Logger *slog.Logger
	Pause  runs.PauseController
	Narrow Narrow
	Estimates db.EstimateStore
	Repo   Repository
	// forge:optional-dep
	Sink runs.Sink
}

type Service struct{ deps Deps }

func New(deps Deps) (*Service, error) {
	if deps.Pause == nil || deps.Narrow == nil || deps.Repo == nil {
		return nil, errors.New("chat: Pause, Narrow and Repo are required")
	}
	return &Service{deps: deps}, nil
}

func (s *Service) Register(*http.ServeMux, ...connect.HandlerOption) {}

func (s *Service) Pause(ctx context.Context, id string) error { return s.deps.Pause.Pause(ctx, id) }

func (s *Service) Sink() runs.Sink { return s.deps.Sink }
`,
	}
}

// writeMockFixtureModule writes files as a module that requires this
// forge checkout, generates its mock_gen.go files with forge's real
// contract generator, and tidies it — the resolver loads packages the way
// a real project's are, under -mod=readonly, so a package whose mock_gen.go
// imports forge/pkg/contractkit type-checks only in a tidy module. Every
// module the fixture needs is in forge's build list, so the tidy runs
// offline. It returns the module root.
//
// GOFLAGS=-mod=mod is for the go test the compile test runs afterwards,
// which also compiles the harness's own imports.
func writeMockFixtureModule(t *testing.T, files map[string]string) string {
	t.Helper()
	forgeRoot, err := filepath.Abs("../..")
	if err != nil {
		t.Fatalf("resolve forge root: %v", err)
	}
	sum, err := os.ReadFile(filepath.Join(forgeRoot, "go.sum"))
	if err != nil {
		t.Fatalf("read forge go.sum: %v", err)
	}
	files["go.mod"] = "module example.com/proj\n\ngo " + pkgGoVersion(t, forgeRoot) + "\n\n" +
		"require github.com/reliant-labs/forge v0.0.0\n\n" +
		"replace github.com/reliant-labs/forge => " + filepath.ToSlash(forgeRoot) + "\n"
	files["go.sum"] = string(sum)
	t.Setenv("GOFLAGS", "-mod=mod")
	t.Setenv("GOWORK", "off")
	root := writeHarnessFixture(t, files)
	generateFixtureMocks(t, root)
	tidy := exec.Command("go", "mod", "tidy")
	tidy.Dir = root
	tidy.Env = append(os.Environ(), "GOPROXY=off")
	if out, err := tidy.CombinedOutput(); err != nil {
		t.Fatalf("go mod tidy (offline) the fixture: %v\n%s", err, out)
	}
	return root
}

// generateFixtureMocks writes the mock_gen.go files forge's contract step
// would, with the real generator.
func generateFixtureMocks(t *testing.T, root string) {
	t.Helper()
	for _, src := range []string{"internal/runs/contract.go", "internal/handlers/chat/deps.go"} {
		if err := contract.Generate(filepath.Join(root, filepath.FromSlash(src))); err != nil {
			t.Fatalf("contract.Generate(%s): %v", src, err)
		}
	}
}

// TestComputeDepsDoubles_PrefersForgeMocks: each mocked interface gets its
// mock — the declaring package's, imported, or the handler's own — and only
// the unmocked one is stubbed. The declaring package's mock wins over the
// handler's Deps-discovered copy of it (both exist for runs.PauseController
// here), so one interface has one mock name in every consumer.
func TestComputeDepsDoubles_PrefersForgeMocks(t *testing.T) {
	if testing.Short() {
		t.Skip("type-checks the fixture module via the go toolchain; runs in task test")
	}
	root := writeMockFixtureModule(t, mockFixtureFiles())
	handlerDir := filepath.Join(root, "internal", "handlers", "chat")

	stubs, mocks, unresolved := computeDepsDoubles(handlerDir, newTypesResolver(handlerDir, nil))
	if len(unresolved) != 0 {
		t.Fatalf("unresolved = %+v, want none", unresolved)
	}
	if len(stubs) != 1 || stubs[0].FieldName != "Repo" || stubs[0].StubType != "StubRepo" {
		t.Fatalf("stubs = %+v, want only StubRepo (Repository is mocked nowhere)", stubs)
	}
	got := map[string]DepsAutoMock{}
	for _, m := range mocks {
		got[m.FieldName] = m
	}
	if m := got["Pause"]; m.MockType != "runs.MockPauseController" ||
		len(m.ExtraImports) != 1 || m.ExtraImports[0] != (ExtraImport{Alias: "runs", Path: "example.com/proj/internal/runs"}) {
		t.Errorf("Pause = %+v, want runs.MockPauseController importing internal/runs", m)
	}
	if m := got["Narrow"]; m.MockType != "MockNarrow" || len(m.ExtraImports) != 0 {
		t.Errorf("Narrow = %+v, want the handler's own MockNarrow, no import", m)
	}
	if m := got["Estimates"]; m.MockType != "MockEstimateStore" || len(m.ExtraImports) != 0 {
		t.Errorf("Estimates = %+v, want the handler's Deps-discovered MockEstimateStore (internal/db mocks nothing)", m)
	}
	if m := got["Sink"]; m.MockType != "runs.MockSink" || !m.Optional {
		t.Errorf("Sink = %+v, want an optional runs.MockSink", m)
	}
	if m := got["Pause"]; m.StubType != "StubPause" {
		t.Errorf("Pause.StubType = %q, want StubPause (the name forge fix harness-mocks rewrites)", m.StubType)
	}
}

// TestGenerateBootstrapTesting_InstallsForgeMocks generates the REAL
// helpers_gen_test.go for the fixture and runs a test against it: the
// harness installs runs.MockPauseController and MockNarrow, synthesizes only
// StubRepo, leaves the optional Sink nil, and an unset mock method answers
// contractkit.MockNotSet.
func TestGenerateBootstrapTesting_InstallsForgeMocks(t *testing.T) {
	if testing.Short() {
		t.Skip("-short: builds and runs a fixture module with go test; runs in task test")
	}
	files := mockFixtureFiles()
	files["pkg/middleware/claims.go"] = `package middleware

import (
	"context"

	"github.com/reliant-labs/forge/pkg/auth"
)

type claimsKey struct{}

func ContextWithClaims(ctx context.Context, c *auth.Claims) context.Context {
	return context.WithValue(ctx, claimsKey{}, c)
}
`
	files["gen/services/chat/v1/chatv1connect/chat.connect.go"] = `package chatv1connect

import "connectrpc.com/connect"

type ChatServiceClient interface{}

func NewChatServiceClient(connect.HTTPClient, string, ...connect.ClientOption) ChatServiceClient {
	return nil
}
`
	files["internal/handlers/chat/mocks_use_test.go"] = `package chat_test

import (
	"context"
	"strings"
	"testing"

	"example.com/proj/internal/handlers/chat"
	"example.com/proj/internal/runs"
)

func TestHarnessInstallsForgeMocks(t *testing.T) {
	svc := chat.NewTestChat(t)
	err := svc.Pause(context.Background(), "r1")
	if err == nil || !strings.Contains(err.Error(), "MockPauseController.PauseFunc not set") {
		t.Fatalf("an unset mock method must answer MockNotSet, got %v", err)
	}
	if svc.Sink() != nil {
		t.Fatal("an optional dep stays nil")
	}

	var paused string
	pause := &runs.MockPauseController{PauseFunc: func(_ context.Context, id string) error {
		paused = id
		return nil
	}}
	svc = chat.NewTestChat(t, chat.WithChatDeps(chat.Deps{Pause: pause}))
	if err := svc.Pause(context.Background(), "r2"); err != nil || paused != "r2" || pause.CallCount("Pause") != 1 {
		t.Fatalf("Pause = %v, paused %q, calls %d; want the programmed mock", err, paused, pause.CallCount("Pause"))
	}
	_ = &chat.StubRepo{}
	_ = &chat.MockNarrow{}
}
`
	root := writeMockFixtureModule(t, files)
	helpers := readHarness(t, root, "internal/handlers/chat",
		[]ServiceDef{{Name: "ChatService", ModulePath: "example.com/proj"}}, nil)

	for _, want := range []string{
		"deps.Pause = &runs.MockPauseController{}",
		"deps.Narrow = &MockNarrow{}",
		"deps.Estimates = &MockEstimateStore{}",
		"deps.Repo = &StubRepo{}",
	} {
		if !strings.Contains(helpers, want) {
			t.Errorf("harness lacks %q", want)
		}
	}
	for _, gone := range []string{"StubPause", "StubNarrow", "StubEstimates", "StubSink", "deps.Sink ="} {
		if strings.Contains(helpers, gone) {
			t.Errorf("harness still has %q: a mocked interface gets no stub, an optional dep no default", gone)
		}
	}
	cmd := exec.Command("go", "test", "-count=1", "./internal/handlers/chat/")
	cmd.Dir = root
	cmd.Env = goexec.WithTrimpath(os.Environ())
	if out, terr := cmd.CombinedOutput(); terr != nil {
		t.Fatalf("the generated harness does not compile or install the mocks: %v\n%s\n---- %s ----\n%s",
			terr, out, componentTestHelperFile, helpers)
	}
}
