// compose_ownership_prose_test.go — guards what shipped prose CLAIMS about
// the ownership of internal/app/compose.go and internal/app/lifecycle.go.
//
// Both files are USER-OWNED and RECONCILED, and their own template headers
// say so: forge writes each one ONCE (write-if-absent), then keeps only a
// projection in sync — for compose.go, the discovered component set and the
// Deps literal's KEY set; for lifecycle.go, the Worker<X>()/Operator<X>()
// accessors and the All* aggregates. The EXPRESSION filling a Deps field,
// the construction order, carved cross-edges and a rewritten All* body all
// stay the user's, and `forge project disown <path>` stops reconciliation.
//
// Prose that calls either file "generated", "regenerated every run",
// "forge-owned" or "overwritten by generate" is therefore not a harmless
// simplification — it tells an agent its hand-wiring will be destroyed, so
// the agent routes around the one file it is supposed to edit, or invents a
// parallel hook system to avoid touching it. That is worse than silence: the
// user loses a seam that exists and works.
//
// Only internal/app/mounts_services_gen.go is genuinely generated, and only
// it carries the "Code generated by forge. DO NOT EDIT." banner.
//
// The guard matches a claim ATTACHED to the filename — within a short
// character window, in either direction — rather than merely co-occurring on
// the line. That distinction is the whole design: these skills legitimately
// say "not by a generated `wire_gen.go`" and "the generated test harness" on
// the same line as compose.go, and a co-occurrence guard would flag those
// true statements. A guard that cries wolf on correct prose gets negotiated
// away, so this one is deliberately narrow: it is a ratchet against the
// regression that already happened, not a proof of global correctness.
package templates_test

import (
	"os"
	"path/filepath"
	"regexp"
	"strings"
	"testing"
)

// reconciledUserOwnedAppFiles are the app-layer files forge reconciles but
// does not own. Naming one is fine; calling it generated is the defect.
var reconciledUserOwnedAppFiles = []string{"compose.go", "lifecycle.go"}

// generatedClaimRE matches the phrases that tell a reader "your edits here
// will be destroyed".
var generatedClaimRE = regexp.MustCompile(`(?i)generated|forge-owned|overwritten|do not edit|never edit`)

// whitespaceRunRE collapses alignment padding so claimAttachWindow measures
// reading distance rather than column layout.
var whitespaceRunRE = regexp.MustCompile(`\s+`)

// claimAttachWindow is how close a claim must sit to the filename to count
// as describing it, measured AFTER runs of whitespace collapse to a single
// space. Collapsing first is what makes the window meaningful in an aligned
// tree listing, where `compose.go` and its `# generated:` comment are
// adjacent in meaning but twenty spaces apart on the line.
//
// Measured against the real corpus: every true defect attaches within this
// window, while the legitimate same-line uses — "not by a generated
// `wire_gen.go`", "the generated test harness", "`pkg/` is the generated
// substrate the app imports" — sit well outside it. Widening this is how
// the guard starts flagging true statements, which is how it gets deleted.
const claimAttachWindow = 24

// TestNoShippedTemplateCallsComposeGenerated walks every template forge
// ships and fails on a generated-ness claim attached to a reconciled
// user-owned app file.
func TestNoShippedTemplateCallsComposeGenerated(t *testing.T) {
	t.Parallel()

	type offender struct {
		where string
		file  string
		claim string
		line  string
	}
	var offenders []offender

	err := filepath.WalkDir("project", func(path string, d os.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if d.IsDir() {
			return nil
		}
		body, readErr := os.ReadFile(path)
		if readErr != nil {
			return readErr
		}
		for i, raw := range strings.Split(string(body), "\n") {
			line := whitespaceRunRE.ReplaceAllString(raw, " ")
			for _, name := range reconciledUserOwnedAppFiles {
				for _, at := range indexAll(strings.ToLower(line), name) {
					lo := max(0, at-claimAttachWindow)
					hi := min(len(line), at+len(name)+claimAttachWindow)
					if m := generatedClaimRE.FindString(line[lo:hi]); m != "" {
						offenders = append(offenders, offender{
							where: path + ":" + itoa(i+1),
							file:  name,
							claim: m,
							line:  strings.TrimSpace(line),
						})
					}
				}
			}
		}
		return nil
	})
	if err != nil {
		t.Fatalf("walk project templates: %v", err)
	}

	for _, o := range offenders {
		t.Errorf("%s calls %s %q\n  %s\n\n  %s is USER-OWNED and RECONCILED — see the header of its own "+
			"template (project/%s.tmpl): forge writes it once, keeps the component set and Deps keys in "+
			"sync, and never touches the value expressions. Describe it accurately instead: \"yours; forge "+
			"reconciles the component set and Deps keys; hand-edits to values are kept; `forge project "+
			"disown internal/app/%s` to opt out\".",
			o.where, o.file, o.claim, o.line, o.file, o.file, o.file)
	}
}

// indexAll returns every start offset of sub in s.
func indexAll(s, sub string) []int {
	var out []int
	for off := 0; ; {
		i := strings.Index(s[off:], sub)
		if i < 0 {
			return out
		}
		out = append(out, off+i)
		off += i + len(sub)
	}
}
