//go:build unix

package storage

import (
	"os"
	"path/filepath"
	"testing"
	"time"

	"golang.org/x/sys/unix"
)

// ageLink backdates a symlink itself. ageDir skips symlinks (os.Chtimes would
// age the target), and a fresh link is recent activity that holds the worktree.
func ageLink(t *testing.T, link string) {
	t.Helper()
	stamp := unix.NsecToTimespec(time.Now().Add(-60 * 24 * time.Hour).UnixNano())
	if err := unix.UtimesNanoAt(unix.AT_FDCWD, link, []unix.Timespec{stamp, stamp}, unix.AT_SYMLINK_NOFOLLOW); err != nil {
		t.Fatal(err)
	}
}

// A symlink inside a checkout belongs to that checkout, wherever it points. A
// venv's bin/python3 -> /usr/bin/python3.12, or a node_modules link into a
// sibling checkout, must not hold the worktree, and removing the worktree
// unlinks the link without touching its target. (reliant#1208 fixed this in
// reliant's copy of the policy; forge's walk never resolved a link, and this
// pins that.)
func TestWorktreeSymlinkOutOfCheckoutIsInsideIt(t *testing.T) {
	if testing.Short() {
		t.Skip("builds real git repositories and worktrees; runs in task test")
	}
	repo, worktree := gitRepoWithWorktree(t)
	excludeInRepo(t, repo, ".tools/\nnode_modules/\n")
	outside := t.TempDir()
	interpreter := filepath.Join(outside, "python3.12")
	sibling := filepath.Join(outside, "sibling-checkout")
	writeFile(t, interpreter, "#!/bin/true\n")
	writeFile(t, filepath.Join(sibling, "pkg", "index.js"), "x\n")
	links := map[string]string{
		filepath.Join(worktree, ".tools", "venv", "bin", "python3"): interpreter,
		filepath.Join(worktree, "node_modules", "pkg"):              filepath.Join(sibling, "pkg"),
		filepath.Join(worktree, ".tools", "dangling"):               filepath.Join(outside, "gone"),
	}
	for link, target := range links {
		if err := os.MkdirAll(filepath.Dir(link), 0o700); err != nil {
			t.Fatal(err)
		}
		if err := os.Symlink(target, link); err != nil {
			t.Skipf("symlinks unavailable: %v", err)
		}
	}
	ageDir(t, worktree)
	for link := range links {
		ageLink(t, link)
	}
	fakeLsof(t, unrelatedOpenFile, "exit 0")
	wantRemoved(t, reapOnce(t, Runner{}, repo, true), worktree)
	for _, target := range []string{interpreter, filepath.Join(sibling, "pkg", "index.js")} {
		if _, err := os.Stat(target); err != nil {
			t.Fatalf("the symlink's target %s was deleted: %v", target, err)
		}
	}
}

// A symlink in an ignored path nothing recognizes is judged as an entry, never
// followed: a link to a directory is one entry (not a walk of the target), and
// the target is not read for the generated marker or compared as a copy.
func TestWorktreeIgnoredSymlinkIsNotFollowed(t *testing.T) {
	if testing.Short() {
		t.Skip("builds real git repositories and worktrees; runs in task test")
	}
	repo, worktree := gitRepoWithWorktree(t)
	excludeInRepo(t, repo, "linked\n")
	outside := t.TempDir()
	writeFile(t, filepath.Join(outside, "config.js"), "// Code generated by forge. DO NOT EDIT.\n")
	link := filepath.Join(worktree, "linked")
	if err := os.Symlink(outside, link); err != nil {
		t.Skipf("symlinks unavailable: %v", err)
	}
	ageDir(t, worktree)
	ageLink(t, link)
	fakeLsof(t, unrelatedOpenFile, "exit 0")
	hold := wantHeldData(t, reapOnce(t, Runner{}, repo, true), worktree)
	if hold.Detail == "" {
		t.Fatal("hold has no detail")
	}
	if _, err := os.Stat(filepath.Join(outside, "config.js")); err != nil {
		t.Fatalf("the target was touched: %v", err)
	}
}
