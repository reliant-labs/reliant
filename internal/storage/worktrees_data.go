package storage

import (
	"bytes"
	"io"
	"os"
	"path/filepath"
	"regexp"
	"strings"
)

// maxDataNames bounds how many data paths a walk lists (and so a hold's
// detail). Only data counts toward it: entries that are not data are dropped
// during the walk, so they can never fill the cap and hide a real data file.
const maxDataNames = 20

// maxCompareBytes bounds the size of an ignored file compared byte for byte
// with its copy in the main checkout. A larger one holds the worktree.
const maxCompareBytes int64 = 64 << 20

// dataJudge finds the ignored paths of one checkout that are the user's data:
// what removing the checkout would lose. An ignored path is NOT data when
//
//   - a build recreates it (rebuildablePath);
//   - it is a regular file whose first line carries the generated-code marker
//     ("Code generated ... DO NOT EDIT."), and the never-list does not name
//     it: a tool wrote it from inputs that outlive the worktree;
//   - it is a regular file byte-identical to the same path in the main
//     checkout: a copy of a file that exists elsewhere, which is how a
//     worktree gets its .env or dev secrets. This one applies to
//     never-listed paths too, because nothing is lost. A file that differs
//     from the main checkout's, even only by being older, is data: it may
//     hold a credential the main checkout no longer has.
//
// Symlinks are never followed. A symlink in an ignored path is judged by its
// own entry (Lstat), never its target: removing the worktree unlinks it and
// leaves the target alone, so where it points is irrelevant.
type dataJudge struct {
	checkout string
	// source is the repository's main checkout ("" when there is none). The
	// reaper already has it from the pass's `git worktree list`, so judging a
	// copy costs no further git process.
	source string
	allow  []string
	out    []string
}

// visit judges one ignored path and appends the data under it to j.out. git
// collapses a directory holding only ignored files into one entry (web/ for
// web/node_modules/), which would hide an allowlisted child, so an unmatched
// directory is judged by its contents. Walking stops at every allowlisted
// directory, so node_modules is never traversed.
func (j *dataJudge) visit(rel string) []string {
	j.walk(rel)
	return j.out
}

func (j *dataJudge) walk(rel string) {
	if len(j.out) >= maxDataNames || rebuildablePath(rel, j.allow) {
		return
	}
	full := filepath.Join(j.checkout, filepath.FromSlash(rel))
	info, err := os.Lstat(full)
	if err != nil {
		j.out = append(j.out, rel)
		return
	}
	if !info.IsDir() {
		if info.Mode().IsRegular() && ((!neverRebuildablePath(rel) && generatedFile(full)) || j.copyInSource(rel, full, info)) {
			return
		}
		j.out = append(j.out, rel)
		return
	}
	children, err := os.ReadDir(full)
	if err != nil || len(children) == 0 {
		j.out = append(j.out, rel)
		return
	}
	for _, child := range children {
		name := strings.TrimSuffix(rel, "/") + "/" + child.Name()
		if child.IsDir() {
			name += "/"
		}
		j.walk(name)
	}
}

// copyInSource reports whether the main checkout holds a separate,
// byte-identical copy of this file at the same path. The copy must resolve to
// a path inside the main checkout (a symlinked directory there could lead back
// into this worktree, or into another one being removed) and must not be this
// very file reached another way.
func (j *dataJudge) copyInSource(rel, full string, info os.FileInfo) bool {
	if j.source == "" || info.Size() > maxCompareBytes {
		return false
	}
	src := filepath.Join(j.source, filepath.FromSlash(rel))
	si, err := os.Lstat(src)
	if err != nil || !si.Mode().IsRegular() || si.Size() != info.Size() || os.SameFile(si, info) {
		return false
	}
	real := canonicalPath(src)
	if !within(canonicalPath(j.source), real) || within(canonicalPath(j.checkout), real) {
		return false
	}
	return sameBytes(full, src)
}

// sameBytes reports whether two files have identical contents. Any read error
// is "not the same".
func sameBytes(a, b string) bool {
	fa, err := os.Open(a)
	if err != nil {
		return false
	}
	defer func() { _ = fa.Close() }()
	fb, err := os.Open(b)
	if err != nil {
		return false
	}
	defer func() { _ = fb.Close() }()
	ba, bb := make([]byte, 64<<10), make([]byte, 64<<10)
	for {
		na, ea := io.ReadFull(fa, ba)
		nb, eb := io.ReadFull(fb, bb)
		if na != nb || !bytes.Equal(ba[:na], bb[:nb]) {
			return false
		}
		if ea != nil || eb != nil {
			return atEOF(ea) && atEOF(eb)
		}
	}
}

func atEOF(err error) bool { return err == io.EOF || err == io.ErrUnexpectedEOF }

// generatedMarker is the first line of a file a tool generated, in any comment
// syntax: the convention of https://go.dev/s/generatedcode, which forge and
// most code generators follow ("// Code generated by forge. DO NOT EDIT.").
var generatedMarker = regexp.MustCompile(`^\s*(//|#|--|;|/\*|<!--)\s*Code generated .*DO NOT EDIT\.`)

// generatedFile reports whether the file's first line is the generated-code
// marker.
func generatedFile(full string) bool {
	f, err := os.Open(full)
	if err != nil {
		return false
	}
	defer func() { _ = f.Close() }()
	head := make([]byte, 512)
	n, _ := io.ReadFull(f, head)
	line, _, _ := strings.Cut(string(head[:n]), "\n")
	return generatedMarker.MatchString(line)
}

// neverRebuildablePath reports whether the never-list names an ignored path.
func neverRebuildablePath(p string) bool {
	segments := splitSegments(p)
	for _, deny := range worktreeNeverRebuildable {
		if matchesRun(segments, deny) {
			return true
		}
	}
	return false
}
