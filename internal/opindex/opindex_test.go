func TestParseProtoSpans(t *testing.T) {
	pf := parseProto([]byte(fixture["proto/todo/v1/todo.proto"]))
	if pf.Package != "todo.v1" {
		t.Errorf("package = %q", pf.Package)
	}
	var rpcs []string
	for _, r := range pf.RPCs {
		rpcs = append(rpcs, r.Name+" "+r.In+" "+r.Out)
	}
	if want := []string{"CreateTodo CreateTodoRequest CreateTodoResponse", "ListTodos ListTodosRequest shared.v1.Page"}; !reflect.DeepEqual(rpcs, want) {
		t.Errorf("rpcs = %v", rpcs)
	}
	if r := pf.RPCs[1]; r.End != r.Line+2 {
		t.Errorf("ListTodos spans %d-%d, want its option block", r.Line, r.End)
	}
	var msgs []string
	for _, m := range pf.Messages {
		msgs = append(msgs, m.Name)
	}
	sort.Strings(msgs)
	if want := []string{"CreateTodoRequest", "CreateTodoResponse", "ListTodosRequest"}; !reflect.DeepEqual(msgs, want) {
		t.Errorf("messages = %v", msgs)
	}
}

