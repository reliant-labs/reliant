func TestMappingJSONShape(t *testing.T) {
	ix := buildFixture(t)
	m := mapOf(t, ix, nil, nil, nil)
	b, err := json.Marshal(m)
	if err != nil {
		t.Fatal(err)
	}
	// Empty lists are [] (never null), so a consumer can range without a
	// nil check.
	if got, want := string(b), `{"base":"","head":"","commits":[],"total":0,"ops":[],"unattributed":[]}`; got != want {
		t.Errorf("empty mapping JSON = %s, want %s", got, want)
	}
	op, _ := ix.Lookup("todo.v1.TodoService/CreateTodo")
	b, _ = json.Marshal(MappedOp{Op: op, Reasons: []Reason{{Via: ViaProto, File: "x.proto", Line: 1}}})
	for _, key := range []string{`"name":`, `"rpc_service":`, `"rpc_method":`, `"proto_file":`, `"proto_line":`, `"reasons":`, `"via":"proto"`} {
		if !strings.Contains(string(b), key) {
			t.Errorf("MappedOp JSON %s lacks %s", b, key)
		}
	}
}

