func TestCallGraphReach(t *testing.T) {
	ix := buildFixture(t)
	p := ix.pkgs["internal/billing"]
	cases := map[string][]string{
		"service.Charge":   {"billing.Charge"},
		"service.validate": {"billing.Charge"},
		"limit":            {"billing.Charge"},
		"errTooBig":        {"billing.Charge"},
		"format":           {"billing.Refund"},
		"service":          {"billing.Charge", "billing.Refund"}, // the receiver type
		"unused":           nil,
		"New":              nil,
		"cache.Charge":     nil, // only `s.validate` and friends are called; nothing names cache
	}
	for node, want := range cases {
		if got := p.reach[node]; !reflect.DeepEqual(got, want) {
			t.Errorf("reach[%s] = %v, want %v", node, got, want)
		}
	}
	h := ix.pkgs["internal/handlers/todo"]
	if got := h.reach["Service.save"]; !reflect.DeepEqual(got, []string{"todo.v1.TodoService/CreateTodo"}) {
		t.Errorf("reach[Service.save] = %v", got)
	}
}

// mapOf maps changes against in-memory head/base trees.
func mapOf(t *testing.T, ix *Index, changes []FileChange, head, base map[string]string) Mapping {
	t.Helper()
	read := func(tree map[string]string) ReadFunc {
		return func(p string) ([]byte, error) {
			s, ok := tree[p]
			if !ok {
				return nil, nil
			}
			return []byte(s), nil
		}
	}
	m, err := ix.MapChanges(changes, read(head), read(base))
	if err != nil {
		t.Fatal(err)
	}
	return m
}

