func writeTree(t *testing.T, root string, files map[string]string) {
	t.Helper()
	for rel, content := range files {
		p := filepath.Join(root, filepath.FromSlash(rel))
		if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(p, []byte(content), 0o644); err != nil {
			t.Fatal(err)
		}
	}
}

func buildFixture(t *testing.T) *Index {
	t.Helper()
	dir := t.TempDir()
	writeTree(t, dir, fixture)
	ix, err := Build(dir)
	if err != nil {
		t.Fatal(err)
	}
	if w := ix.Warnings(); len(w) > 0 {
		t.Fatalf("warnings: %v", w)
	}
	return ix
}

func lineOf(t *testing.T, file, needle string) int {
	t.Helper()
	for i, l := range strings.Split(fixture[file], "\n") {
		if strings.Contains(l, needle) {
			return i + 1
		}
	}
	t.Fatalf("%q not in %s", needle, file)
	return 0
}

