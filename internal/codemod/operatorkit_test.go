package codemod

import (
	"os"
	"path/filepath"
	"strings"
	"testing"
)

func writeTree(t *testing.T, files map[string]string) string {
	t.Helper()
	dir := t.TempDir()
	for rel, body := range files {
		path := filepath.Join(dir, filepath.FromSlash(rel))
		if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(path, []byte(body), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	return dir
}

func readFile(t *testing.T, dir, rel string) string {
	t.Helper()
	b, err := os.ReadFile(filepath.Join(dir, filepath.FromSlash(rel)))
	if err != nil {
		t.Fatal(err)
	}
	return string(b)
}

// The shape control-plane's owned lifecycle.go has: lifecyclekit used for
// WrapWorker (stays) AND for the operator bridge (moves).
const lifecycleUsingBoth = `package app

import (
	"context"
	"log/slog"

	"github.com/reliant-labs/forge/pkg/lifecyclekit"
)

func wrap(w lifecyclekit.WorkerLifecycle) any { return lifecyclekit.WrapWorker("x", w) }

// RunOperators runs the controllers (lifecyclekit.Run, over operatorkit).
func RunOperators(ctx context.Context, logger *slog.Logger) error {
	controllers := make([]lifecyclekit.Controller, 0, 1)
	controllers = append(controllers, lifecyclekit.Controller{Name: "workspace"})
	return lifecyclekit.Run(ctx, logger, lifecyclekit.Options{HealthProbeAddr: ":8081"}, controllers)
}
`

const lifecycleUsingBothWant = `package app

import (
	"context"
	"log/slog"

	"github.com/reliant-labs/forge/pkg/appkit/operatorkit"
	"github.com/reliant-labs/forge/pkg/lifecyclekit"
)

func wrap(w lifecyclekit.WorkerLifecycle) any { return lifecyclekit.WrapWorker("x", w) }

// RunOperators runs the controllers (lifecyclekit.Run, over operatorkit).
func RunOperators(ctx context.Context, logger *slog.Logger) error {
	controllers := make([]operatorkit.Controller, 0, 1)
	controllers = append(controllers, operatorkit.Controller{Name: "workspace"})
	return operatorkit.Run(ctx, logger, operatorkit.Options{HealthProbeAddr: ":8081"}, controllers)
}
`

func TestOperatorkit_RenamesAndKeepsLifecyclekitWhenStillUsed(t *testing.T) {
	dir := writeTree(t, map[string]string{"internal/app/lifecycle.go": lifecycleUsingBoth})
	rep, err := runOperatorkit(dir, Options{Write: true})
	if err != nil {
		t.Fatal(err)
	}
	if got := readFile(t, dir, "internal/app/lifecycle.go"); got != lifecycleUsingBothWant {
		t.Errorf("rewrite mismatch:\n--- got\n%s\n--- want\n%s", got, lifecycleUsingBothWant)
	}
	want := "internal/app/lifecycle.go: lifecyclekit.Controller, lifecyclekit.Options, lifecyclekit.Run → operatorkit"
	if len(rep.Rewrites) != 1 || rep.Rewrites[0] != want {
		t.Errorf("Rewrites = %q, want [%q]", rep.Rewrites, want)
	}

	// Idempotent: the second run finds nothing.
	again, err := runOperatorkit(dir, Options{Write: true})
	if err != nil {
		t.Fatal(err)
	}
	if again.Changed() {
		t.Errorf("second run rewrote %q", again.Rewrites)
	}
}

func TestOperatorkit_DropsLifecyclekitImportWhenUnused(t *testing.T) {
	const src = `package app

import (
	"context"
	"log/slog"

	lk "github.com/reliant-labs/forge/pkg/lifecyclekit"
)

func run(ctx context.Context, l *slog.Logger) error {
	return lk.Run(ctx, l, lk.Options{}, nil)
}
`
	const want = `package app

import (
	"context"
	"log/slog"

	"github.com/reliant-labs/forge/pkg/appkit/operatorkit"
)

func run(ctx context.Context, l *slog.Logger) error {
	return operatorkit.Run(ctx, l, operatorkit.Options{}, nil)
}
`
	dir := writeTree(t, map[string]string{"cmd/app/run.go": src})
	if _, err := runOperatorkit(dir, Options{Write: true}); err != nil {
		t.Fatal(err)
	}
	if got := readFile(t, dir, "cmd/app/run.go"); got != want {
		t.Errorf("rewrite mismatch:\n--- got\n%s\n--- want\n%s", got, want)
	}
}

func TestOperatorkit_UsesAnExistingOperatorkitImport(t *testing.T) {
	const src = `package app

import (
	ok "github.com/reliant-labs/forge/pkg/appkit/operatorkit"
	"github.com/reliant-labs/forge/pkg/lifecyclekit"
)

var _ ok.Controller
var _ = lifecyclekit.Options{}
`
	dir := writeTree(t, map[string]string{"a.go": src})
	if _, err := runOperatorkit(dir, Options{Write: true}); err != nil {
		t.Fatal(err)
	}
	got := readFile(t, dir, "a.go")
	if !strings.Contains(got, "var _ = ok.Options{}") || strings.Contains(got, "lifecyclekit") {
		t.Errorf("expected the existing `ok` import reused and lifecyclekit dropped:\n%s", got)
	}
}

func TestOperatorkit_LeavesShadowsGeneratedFilesAndDryRunAlone(t *testing.T) {
	// A local named lifecyclekit is not the package.
	const shadow = `package app

import "github.com/reliant-labs/forge/pkg/lifecyclekit"

type opts struct{ Run func() }

var _ lifecyclekit.WorkerLifecycle

func f() {
	lifecyclekit := opts{}
	lifecyclekit.Run()
}
`
	const generated = `// Code generated by forge. DO NOT EDIT.

package app

import "github.com/reliant-labs/forge/pkg/lifecyclekit"

var _ lifecyclekit.Options
`
	const moves = `package app

import "github.com/reliant-labs/forge/pkg/lifecyclekit"

var _ lifecyclekit.Options
`
	dir := writeTree(t, map[string]string{
		"shadow.go":             shadow,
		"generated.go":          generated,
		"testdata/fixture.go":   moves,
		"internal/app/moves.go": moves,
	})
	rep, err := runOperatorkit(dir, Options{})
	if err != nil {
		t.Fatal(err)
	}
	if len(rep.Rewrites) != 1 || !strings.HasPrefix(rep.Rewrites[0], "internal/app/moves.go:") {
		t.Errorf("dry run reported %q, want only internal/app/moves.go", rep.Rewrites)
	}
	for rel, want := range map[string]string{"shadow.go": shadow, "generated.go": generated, "testdata/fixture.go": moves, "internal/app/moves.go": moves} {
		if got := readFile(t, dir, rel); got != want {
			t.Errorf("%s changed (dry run, or a file the codemod must leave alone):\n%s", rel, got)
		}
	}
}

func TestRegistry_OperatorkitIsAnUpgradeCodemod(t *testing.T) {
	c, ok := Lookup("operatorkit")
	if !ok {
		t.Fatal("operatorkit codemod not registered")
	}
	if !c.Upgrade || c.Version != "v0.1.46" {
		t.Errorf("operatorkit: Upgrade=%v Version=%q, want an upgrade codemod for v0.1.46", c.Upgrade, c.Version)
	}
}
