package codemod

import (
	"bytes"
	"crypto/sha256"
	"errors"
	"io/fs"
	"os"
	"path/filepath"
	"strings"

	"github.com/reliant-labs/forge/internal/checksums"
)

// Every codemod's output is formatted the way the project's linters expect, in
// ONE place, so a rewrite never hands a person formatting findings forge
// produced itself.
//
// Incident (control-plane, the pin bot's first live run): `forge project
// upgrade` applied the connect-errors codemod (209 rewrites) and then reported
// 39 gofmt and 39 goimports findings as needs_human. The codemods format with
// whatever their own printer yields — go/format, or goimports with no local
// prefix — and the project's gate is goimports with its own local-prefixes.
// forge#1198 fixed that for narrow-deps by formatting its output to the
// project's gate; every other codemod kept its own printer.
//
// register wraps each codemod's Run with formatAfter, so the guarantee holds for
// every codemod there is and every one added later, and `forge fix <name>`,
// upgrade's codemod phase and a playbook's automation step all get it: none of
// them can reach a Run that skips it.
//
// WHICH files: the Go files whose bytes changed during the run, found by
// comparing two walks — not a list the codemod reports, which is a second
// answer to "what did you write?" for a codemod to get wrong. That covers a
// moved file (configproto) and a file written through any writer. Content, not
// mtime: a coarse-grained filesystem timestamps two writes in one second alike.
//
// A codemod whose report quotes positions in the files it wrote (connect-errors)
// formats its own output first (formatForProject), so those positions are the
// formatted file's; this pass then finds nothing left to do.
// WHAT to: checksums.RewriteGoFormat, the same reading of the project's
// golangci-lint config `forge lint --fix` and narrow-deps use.

type runFunc = func(dir string, opts Options) (Report, error)

// formatAfter wraps run so the Go files it wrote are left formatted to the
// project's standard. A dry run writes nothing and formats nothing.
func formatAfter(run runFunc) runFunc {
	return func(dir string, opts Options) (Report, error) {
		if !opts.Write {
			return run(dir, opts)
		}
		before := stampGoFiles(dir)
		rep, err := run(dir, opts)
		if err != nil {
			return rep, err
		}
		return rep, formatChangedGo(dir, before)
	}
}

// stampGoFiles hashes the project's own Go files (see walkOwnedGo), keyed by
// slash-separated path relative to dir.
func stampGoFiles(dir string) map[string][sha256.Size]byte {
	out := map[string][sha256.Size]byte{}
	_ = walkOwnedGo(dir, func(rel string) error {
		if src, err := os.ReadFile(filepath.Join(dir, filepath.FromSlash(rel))); err == nil {
			out[rel] = sha256.Sum256(src)
		}
		return nil
	})
	return out
}

// formatChangedGo formats every owned Go file that is new or changed since
// before was taken. A file that does not parse is left as the codemod wrote it:
// the compiler reports that with a real error, and formatting is not the pass
// that should hide it.
func formatChangedGo(dir string, before map[string][sha256.Size]byte) error {
	var std *checksums.GoFormatStandard
	return walkOwnedGo(dir, func(rel string) error {
		abs := filepath.Join(dir, filepath.FromSlash(rel))
		src, err := os.ReadFile(abs)
		if err != nil {
			return err
		}
		if was, ok := before[rel]; ok && was == sha256.Sum256(src) {
			return nil
		}
		if isGenerated(src) {
			return nil
		}
		if std == nil {
			s := checksums.RewriteGoFormat(dir)
			std = &s
		}
		formatted, err := std.Format(abs, src)
		if err != nil || bytes.Equal(src, formatted) {
			return nil //nolint:nilerr // unparseable: leave it for the compiler to report
		}
		return writeFile(abs, formatted)
	})
}

// formatForProject formats src, a Go file about to be written at path in the
// project at dir, to the project's standard. Source that does not parse is
// returned as it is.
func formatForProject(dir, path string, src []byte) []byte {
	formatted, err := checksums.RewriteGoFormat(dir).Format(path, src)
	if err != nil {
		return src
	}
	return formatted
}

// walkOwnedGo visits the project's own Go files: not generated by name, not in
// a dependency, fixture or tool-state tree, not in a nested module. (A file
// generated by header is checked by the caller, which has its bytes.)
func walkOwnedGo(dir string, fn func(rel string) error) error {
	return filepath.WalkDir(dir, func(path string, d fs.DirEntry, err error) error {
		if err != nil {
			if errors.Is(err, fs.ErrPermission) {
				return nil
			}
			return err
		}
		if d.IsDir() {
			if path == dir {
				return nil
			}
			if skipDir(d.Name()) {
				return filepath.SkipDir
			}
			if _, statErr := os.Stat(filepath.Join(path, "go.mod")); statErr == nil {
				return filepath.SkipDir
			}
			return nil
		}
		name := d.Name()
		if !strings.HasSuffix(name, ".go") || strings.HasSuffix(name, "_gen.go") ||
			strings.HasSuffix(name, ".pb.go") || strings.HasSuffix(name, ".connect.go") {
			return nil
		}
		rel, err := filepath.Rel(dir, path)
		if err != nil {
			return err
		}
		return fn(filepath.ToSlash(rel))
	})
}
