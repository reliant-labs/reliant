// legacyConfigProject is a project on the shared config.v1 layout: the
// root and a frontend config, a service proto that imports and names one,
// an owned Go importer, a frontend source importing the TS stub, the stale
// generated output, and a doc naming the old path.
var legacyConfigProject = map[string]string{
	"go.mod":     "module example.com/acme-app\n\ngo 1.25\n",
	"forge.yaml": "name: acme-app\n",
	"proto/config/v1/config.proto": `syntax = "proto3";

package config.v1;

import "forge/v1/forge.proto";

option go_package = "example.com/acme-app/gen/config/v1;configv1";

// Declared in proto/config/v1/config.proto; forge.v1.config annotates it.
message AppConfig {
  string region = 1 [(forge.v1.config) = {env_var: "REGION"}];
  WebConfig web = 2;
}
`,
	"proto/config/v1/web_config.proto": `syntax = "proto3";

package config.v1;

option go_package = "example.com/acme-app/gen/config/v1;configv1";

message WebConfig {
  string api_url = 1 [(forge.v1.config) = {env_var: "API_URL"}];
}
`,
	"proto/services/things/v1/things.proto": `syntax = "proto3";

package things.v1;

import "config/v1/config.proto";

message Snapshot {
  config.v1.AppConfig app = 1;
  .config.v1.WebConfig web = 2;
  acme.config.v1.Other other = 3;
}
`,
	"internal/app/settings.go": `package app

import (
	configv1 "example.com/acme-app/gen/config/v1"
)

// Region reads proto/config/v1/config.proto's region.
func Region(c *configv1.AppConfig) string { return c.GetRegion() }
`,
	"pkg/config/config_gen.go":           "// Code generated by forge. DO NOT EDIT.\npackage config\n\nimport configv1 \"example.com/acme-app/gen/config/v1\"\n\ntype Config = configv1.AppConfig\n",
	"gen/config/v1/config.pb.go":         "// Code generated by protoc-gen-go. DO NOT EDIT.\npackage configv1\n",
	"web/src/gen/config/v1/config_pb.ts": "// @generated by protoc-gen-es v2\nexport {};\n",
	"web/src/lib/settings.ts":            "import { AppConfigSchema } from \"@/gen/config/v1/config_pb\";\nexport const s = AppConfigSchema;\n",
	"README.md":                          "Config lives in proto/config/v1/config.proto.\n",
	// buf exempts the config tree from breaking; proto/configs is another
	// directory, which must not move.
	"buf.yaml": "version: v2\nbreaking:\n  ignore:\n    - proto/config\n    - proto/config/\n    - proto/configs\n",
}

func TestConfigProtoPackage_MovesTheLegacyLayout(t *testing.T) {
	dir := writeTree(t, legacyConfigProject)

	dry, err := runConfigProtoPackage(dir, Options{})
	if err != nil {
		t.Fatalf("dry run: %v", err)
	}
	if !dry.Changed() || len(dry.Blocked) > 0 {
		t.Fatalf("dry run: changed=%v blocked=%v", dry.Changed(), dry.Blocked)
	}
	if _, err := os.Stat(filepath.Join(dir, "proto/config/v1/config.proto")); err != nil {
		t.Fatal("--dry-run moved a file")
	}

	rep, err := runConfigProtoPackage(dir, Options{Write: true})
	if err != nil {
		t.Fatalf("codemod: %v", err)
	}
	t.Logf("rewrites:\n%s\nnext:\n%s", strings.Join(rep.Rewrites, "\n"), strings.Join(rep.Next, "\n"))
	if strings.Join(rep.Rewrites, "\n") != strings.Join(dry.Rewrites, "\n") {
		t.Errorf("dry run and run disagree:\n%s\n---\n%s", strings.Join(dry.Rewrites, "\n"), strings.Join(rep.Rewrites, "\n"))
	}

	root := readFile(t, dir, "proto/acme_app/config/v1/config.proto")
	for _, want := range []string{
		"package acme_app.config.v1;",
		`option go_package = "example.com/acme-app/gen/acme_app/config/v1;configv1";`,
		"// Declared in proto/acme_app/config/v1/config.proto; forge.v1.config annotates it.",
		`[(forge.v1.config) = {env_var: "REGION"}]`, // env names never move
	} {
		if !strings.Contains(root, want) {
			t.Errorf("moved config.proto lacks %q:\n%s", want, root)
		}
	}
	if web := readFile(t, dir, "proto/acme_app/config/v1/web_config.proto"); !strings.Contains(web, "package acme_app.config.v1;") {
		t.Errorf("web_config.proto not re-packaged:\n%s", web)
	}

	svc := readFile(t, dir, "proto/services/things/v1/things.proto")
	for _, want := range []string{
		`import "acme_app/config/v1/config.proto";`,
		"  acme_app.config.v1.AppConfig app = 1;",
		"  .acme_app.config.v1.WebConfig web = 2;",
		"  acme.config.v1.Other other = 3;", // another package that merely ends in config.v1
	} {
		if !strings.Contains(svc, want) {
			t.Errorf("things.proto lacks %q:\n%s", want, svc)
		}
	}

	goSrc := readFile(t, dir, "internal/app/settings.go")
	if !strings.Contains(goSrc, `configv1 "example.com/acme-app/gen/acme_app/config/v1"`) ||
		!strings.Contains(goSrc, "proto/acme_app/config/v1/config.proto") {
		t.Errorf("settings.go not rewritten:\n%s", goSrc)
	}
	if got := readFile(t, dir, "pkg/config/config_gen.go"); got != legacyConfigProject["pkg/config/config_gen.go"] {
		t.Error("rewrote a generated file; forge generate owns it")
	}
	if ts := readFile(t, dir, "web/src/lib/settings.ts"); !strings.Contains(ts, `"@/gen/acme_app/config/v1/config_pb"`) {
		t.Errorf("settings.ts not rewritten:\n%s", ts)
	}

	if buf := readFile(t, dir, "buf.yaml"); buf != "version: v2\nbreaking:\n  ignore:\n    - proto/acme_app/config\n    - proto/acme_app/config/\n    - proto/configs\n" {
		t.Errorf("buf.yaml's ignore of the config tree not moved:\n%s", buf)
	}

	for _, gone := range []string{"proto/config", "gen/config", "web/src/gen/config"} {
		if _, err := os.Stat(filepath.Join(dir, gone)); !os.IsNotExist(err) {
			t.Errorf("%s still exists after the move", gone)
		}
	}
	if len(configproto.LegacyFiles(dir)) != 0 {
		t.Error("LegacyFiles still finds the legacy layout")
	}
	if !strings.Contains(strings.Join(rep.Next, "\n"), "README.md:1") {
		t.Errorf("the README's mention of the old path is not listed: %v", rep.Next)
	}

	again, err := runConfigProtoPackage(dir, Options{Write: true})
	if err != nil || again.Changed() || len(again.Next) > 0 {
		t.Errorf("second run is not a no-op: %+v, %v", again, err)
	}
}

// A destination that already exists is a merge only a person can do.
func TestConfigProtoPackage_RefusesToOverwrite(t *testing.T) {
	files := map[string]string{"proto/acme_app/config/v1/config.proto": "syntax = \"proto3\";\n"}
	for rel, body := range legacyConfigProject {
		files[rel] = body
	}
	dir := writeTree(t, files)
	rep, err := runConfigProtoPackage(dir, Options{Write: true})
	if err != nil {
		t.Fatal(err)
	}
	if len(rep.Blocked) != 1 || !strings.Contains(rep.Blocked[0], "proto/acme_app/config/v1/config.proto") {
		t.Fatalf("Blocked = %v", rep.Blocked)
	}
	if _, err := os.Stat(filepath.Join(dir, "proto/config/v1/web_config.proto")); err != nil {
		t.Error("a blocked run moved a file")
	}
}
