// harnessMocksProject is a handler whose Deps names a collaborator of each
// kind: Pause runs.PauseController (mocked in internal/runs), Narrow (a
// deps.go role, mocked in the handler's own mock_gen.go) and Repo (mocked
// nowhere, so StubRepo stays). Its tests reach the retired stubs both from
// inside the package and from chat_test.
//
// The mock_gen.go files carry forge's header and compile-time checks — all
// the codemod reads — and no contractkit import, so the fixture type-checks
// with the standard library alone.
var harnessMocksProject = map[string]string{
	"go.mod": "module example.com/proj\n\ngo 1.22\n",
	"internal/runs/contract.go": `package runs

import "context"

type PauseController interface {
	Pause(ctx context.Context, runID string) error
}
`,
	"internal/runs/mock_gen.go": `// Code generated by forge. DO NOT EDIT.
package runs

import "context"

type MockPauseController struct {
	PauseFunc func(ctx context.Context, runID string) error
}

func (m *MockPauseController) Pause(ctx context.Context, runID string) error {
	return m.PauseFunc(ctx, runID)
}

// Compile-time check.
var _ PauseController = (*MockPauseController)(nil)
`,
	"internal/handlers/chat/deps.go": `// forge:deps — consumer-declared interfaces for this package's Deps.

package chat

type Narrow interface{ Lookup(id string) string }
`,
	"internal/handlers/chat/mock_gen.go": `// Code generated by forge. DO NOT EDIT.
package chat

type MockNarrow struct{ LookupFunc func(id string) string }

func (m *MockNarrow) Lookup(id string) string { return m.LookupFunc(id) }

var _ Narrow = (*MockNarrow)(nil)
`,
	"internal/handlers/chat/service.go": `package chat

import (
	"log/slog"

	"example.com/proj/internal/runs"
)

type Repository interface{ Get(id string) (string, error) }

type Deps struct {
	Logger *slog.Logger
	Pause  runs.PauseController
	Narrow Narrow
	Repo   Repository
}
`,
	// The retired harness, as forge v0.1.46 wrote it: never rewritten.
	"internal/handlers/chat/helpers_gen_test.go": `// Code generated by forge. DO NOT EDIT.
package chat

type StubPause struct{}
type StubNarrow struct{}
type StubRepo struct{}
`,
	"internal/handlers/chat/internal_test.go": `package chat

import "testing"

func TestInternal(t *testing.T) {
	p := &StubPause{}
	n := StubNarrow{}
	r := &StubRepo{}
	_, _, _ = p, n, r
	var stubs []*StubPause
	_ = stubs
	if msg := "StubPause.PauseFunc not set"; msg == "" {
		t.Fatal()
	}
}
`,
	// A struct embedding a stub in one file, used from another: the
	// embedded field is named after the type.
	"internal/handlers/chat/wrapped_test.go": `package chat_test

import "example.com/proj/internal/handlers/chat"

type wrapped struct {
	*chat.StubPause
	calls int
}
`,
	"internal/handlers/chat/external_test.go": `package chat_test

import (
	"testing"

	"example.com/proj/internal/handlers/chat"
	rr "example.com/proj/internal/runs"
)

var _ rr.PauseController = (*chat.StubPause)(nil)

func TestExternal(t *testing.T) {
	_ = chat.Deps{Pause: &chat.StubPause{}, Narrow: &chat.StubNarrow{}, Repo: &chat.StubRepo{}}
	other := struct{ StubNarrow int }{}
	_ = other.StubNarrow
	w := &wrapped{StubPause: &chat.StubPause{}}
	w.StubPause.PauseFunc = nil
}
`,
}

func TestHarnessMocks_RenamesRetiredStubs(t *testing.T) {
	dir := writeTree(t, harnessMocksProject)
	c, ok := Lookup("harness-mocks")
	if !ok {
		t.Fatal("harness-mocks is not registered")
	}

	dry, err := c.Run(dir, Options{})
	if err != nil {
		t.Fatalf("dry run: %v", err)
	}
	if !dry.Changed() {
		t.Fatal("dry run reports nothing to rewrite")
	}
	if got := readFile(t, dir, "internal/handlers/chat/internal_test.go"); got != harnessMocksProject["internal/handlers/chat/internal_test.go"] {
		t.Fatalf("a dry run wrote:\n%s", got)
	}

	rep, err := c.Run(dir, Options{Write: true})
	if err != nil {
		t.Fatalf("run: %v", err)
	}
	internal := readFile(t, dir, "internal/handlers/chat/internal_test.go")
	for _, want := range []string{
		"p := &runs.MockPauseController{}",
		"n := MockNarrow{}",
		"r := &StubRepo{}", // Repository is mocked nowhere: its stub stays
		"var stubs []*runs.MockPauseController",
		`"example.com/proj/internal/runs"`,
	} {
		if !strings.Contains(internal, want) {
			t.Errorf("internal_test.go lacks %q:\n%s", want, internal)
		}
	}
	external := readFile(t, dir, "internal/handlers/chat/external_test.go")
	for _, want := range []string{
		"var _ rr.PauseController = (*rr.MockPauseController)(nil)", // the file's own alias
		"Pause: &rr.MockPauseController{}",
		"Narrow: &chat.MockNarrow{}",
		"Repo: &chat.StubRepo{}",
		"other := struct{ StubNarrow int }{}", // a field of the same name is not the stub
		"_ = other.StubNarrow",
		"w := &wrapped{MockPauseController: &rr.MockPauseController{}}", // the embedded field's key
		"w.MockPauseController.PauseFunc = nil",
	} {
		if !strings.Contains(external, want) {
			t.Errorf("external_test.go lacks %q:\n%s", want, external)
		}
	}
	if strings.Count(external, `"example.com/proj/internal/runs"`) != 1 {
		t.Errorf("external_test.go already imported internal/runs; it must not gain a second import:\n%s", external)
	}
	if wrapped := readFile(t, dir, "internal/handlers/chat/wrapped_test.go"); !strings.Contains(wrapped, "*runs.MockPauseController") {
		t.Errorf("wrapped_test.go must embed the mock, importing internal/runs:\n%s", wrapped)
	}
	if got := readFile(t, dir, "internal/handlers/chat/helpers_gen_test.go"); got != harnessMocksProject["internal/handlers/chat/helpers_gen_test.go"] {
		t.Errorf("the generated harness was rewritten:\n%s", got)
	}
	if len(rep.Next) != 1 || !strings.Contains(rep.Next[0], "internal_test.go: line") ||
		!strings.Contains(rep.Next[0], "MockPauseController.<Method>Func not set") {
		t.Errorf("Next = %q, want the one assertion on StubPause's error text", rep.Next)
	}

	again, err := c.Run(dir, Options{Write: true})
	if err != nil {
		t.Fatalf("second run: %v", err)
	}
	if again.Changed() {
		t.Errorf("a second run rewrote %v: the codemod is not idempotent", again.Rewrites)
	}
}

func TestHarnessMocks_ScopeRewritesOnlyItsSlice(t *testing.T) {
	dir := writeTree(t, harnessMocksProject)
	c, _ := Lookup("harness-mocks")
	scope, err := ParseScope(dir, []string{"internal/handlers/chat/external_test.go"})
	if err != nil {
		t.Fatal(err)
	}
	if _, err := c.Run(dir, Options{Write: true, Scope: scope}); err != nil {
		t.Fatal(err)
	}
	if got := readFile(t, dir, "internal/handlers/chat/internal_test.go"); got != harnessMocksProject["internal/handlers/chat/internal_test.go"] {
		t.Errorf("a file outside --scope was rewritten:\n%s", got)
	}
	if !strings.Contains(readFile(t, dir, "internal/handlers/chat/external_test.go"), "chat.MockNarrow") {
		t.Error("the scoped file was not rewritten")
	}
}

func TestHarnessMocks_NothingToDoWithoutHandlers(t *testing.T) {
	dir := writeTree(t, map[string]string{"go.mod": "module example.com/proj\n\ngo 1.22\n"})
	c, _ := Lookup("harness-mocks")
	rep, err := c.Run(dir, Options{Write: true})
	if err != nil || rep.Changed() || len(rep.Next) > 0 {
		t.Fatalf("a project with no handlers: rep %+v, err %v", rep, err)
	}
}
