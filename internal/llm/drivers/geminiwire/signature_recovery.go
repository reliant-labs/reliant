// Thought-signature recovery: the Gemini counterpart of the Anthropic
// driver's signature_recovery.go.
//
// Gemini 3 validates the thought signature on the first functionCall of every
// step of the current turn, and rejects the request when one is missing or is
// not a signature it issued. History can hold either for reasons the user
// cannot undo: calls made by another model before a mid-chat switch, a row
// persisted before signature capture, a signature issued to a different
// model, key or transport (Gemini API vs Vertex vs Antigravity). Stand-in
// stamping (StepNeedsSignatureStandIn) prevents the missing case it can see;
// a signature that is present but rejected cannot be seen until the server
// says so. Without recovery, that one row fails every later request of the
// chat.
//
// So a rejected request is sent once more with every signature in it replaced
// by Google's documented stand-in (SkipThoughtSignatureValidator), which the
// server accepts "for function call parts that were not generated by the
// API". The stand-in costs some reasoning quality on that one request
// (Google: "should be a last resort"), which beats a wedged chat. Once, never
// more: a request still rejected with stand-ins is not a signature problem.

// ErrThoughtSignatureRejected matches a request Gemini refused because of a
// thought signature: a StopError with MISSING_THOUGHT_SIGNATURE, or (by
// IsThoughtSignatureRejection) the 400 the server answers with.
var ErrThoughtSignatureRejected = errors.New("gemini rejected a thought signature")

// signatureRejectionText matches the server's wording. The exact strings
// seen, as reproduced by hermes-agent's provider fakes
// (tests/fakes/providers/vertex.py, gemini_native.py), are:
//
//	Corrupted thought signature.
//	Function call is missing a thought_signature in functionCall parts. …
//	Function call `x` in the `3.` content block is missing a `thought_signature`.
//	….thought_signature: invalid bytes value
//
// Google does not document an error code for these, so the match is on text:
// the phrase "thought signature" / "thought_signature" together with a word
// saying it is wrong. A 400 about anything else is left alone. This is a
// conservative match by design; a wording it misses only means that request
// fails as it did before recovery existed.
var signatureRejectionText = regexp.MustCompile(`(?i)thought[_ ]signature`)

var signatureRejectionVerdicts = []string{"corrupt", "missing", "invalid", "not valid"}

// IsThoughtSignatureRejection reports whether err is Gemini refusing a request
// because of a thought signature.
func IsThoughtSignatureRejection(err error) bool {
	if err == nil {
		return false
	}
	if errors.Is(err, ErrThoughtSignatureRejected) {
		return true
	}
	msg := err.Error()
	if !signatureRejectionText.MatchString(msg) {
		return false
	}
	lower := strings.ToLower(msg)
	for _, verdict := range signatureRejectionVerdicts {
		if strings.Contains(lower, verdict) {
			return true
		}
	}
	return false
}

// skipThoughtSignatureValidatorBytes is SkipThoughtSignatureValidator as the
// genai SDK must hold it.
//
// genai.Part.ThoughtSignature is []byte, and the SDK base64-encodes it on the
// way out, because on the wire the field is a protobuf bytes field in JSON.
// The documented stand-in is that JSON string, which is itself base64 (its
// underscores are the URL-safe alphabet). So the bytes to hold are its
// decoding: the SDK re-encodes them as the same text in the standard
// alphabet ("skip/thought/…"), and protobuf JSON accepts either alphabet, so
// the server decodes exactly the bytes it decodes from the literal.
// []byte("skip_thought_signature_validator") — the ASCII of the literal — is
// what the warning on SkipThoughtSignatureValidator is about: the server
// would see a different, invalid signature.
var skipThoughtSignatureValidatorBytes = mustDecodeStandIn()

func mustDecodeStandIn() []byte {
	b, err := base64.RawURLEncoding.DecodeString(SkipThoughtSignatureValidator)
	if err != nil {
		panic("geminiwire: the thought-signature stand-in is not base64: " + err.Error())
	}
	return b
}

// SkipThoughtSignatureValidatorBytes returns the stand-in for a genai.Part's
// ThoughtSignature. See skipThoughtSignatureValidatorBytes.
func SkipThoughtSignatureValidatorBytes() []byte {
	return append([]byte(nil), skipThoughtSignatureValidatorBytes...)
}

// legacySignatureModel matches the Gemini 1.x and 2.x model ids, which do not
// validate thought signatures on replayed calls.
var legacySignatureModel = regexp.MustCompile(`(?i)(^|/)gemini-[12](\.|-)`)

// ValidatesThoughtSignatures reports whether model checks the signatures of
// replayed function calls, so unsigned steps need the stand-in. Gemini 3 and
// later do; 1.x and 2.x do not, and are left exactly as they were.
func ValidatesThoughtSignatures(model string) bool {
	return !legacySignatureModel.MatchString(model)
}

// StampUnsignedSteps sets the stand-in on the first functionCall of every
// model step whose calls carry no signature at all, and returns how many it
// stamped. The genai-typed twin of antigravity's stampUnsignedCallSteps; the
// rule (StepNeedsSignatureStandIn) is shared.
func StampUnsignedSteps(contents []*genai.Content) int {
	stamped := 0
	for _, c := range contents {
		if c == nil || c.Role != string(genai.RoleModel) {
			continue
		}
		var calls []*genai.Part
		var callSigned []bool
		for _, p := range c.Parts {
			if p == nil || p.FunctionCall == nil {
				continue
			}
			calls = append(calls, p)
			callSigned = append(callSigned, len(p.ThoughtSignature) > 0)
		}
		if StepNeedsSignatureStandIn(callSigned) {
			calls[0].ThoughtSignature = SkipThoughtSignatureValidatorBytes()
			stamped++
		}
	}
	return stamped
}

// ReplaceSignaturesWithStandIns removes every thought signature from
// contents and stamps the stand-in on the first call of every step: the
// request signature recovery sends. It returns how many signatures it
// removed.
func ReplaceSignaturesWithStandIns(contents []*genai.Content) int {
	removed := 0
	for _, c := range contents {
		if c == nil {
			continue
		}
		for _, p := range c.Parts {
			if p != nil && len(p.ThoughtSignature) > 0 {
				p.ThoughtSignature = nil
				removed++
			}
		}
	}
	StampUnsignedSteps(contents)
	return removed
}

// RecoverSignatureRejection runs a streamed request, and when it fails with a
// thought-signature rejection before producing any output, runs it once more
// with stand-in signatures.
//
// attempt(false) is the request as built; attempt(true) is the same request
// with every signature replaced by the stand-in (ReplaceSignaturesWithStandIns
// for a genai driver). The first attempt's events are forwarded as they
// arrive. On a rejection the rest of that attempt (a driver's fallback
// complete event, typically) is drained and dropped, and the second attempt's
// events are forwarded instead. A rejection after output was produced is not
// retried: the request was evidently accepted, and the output is already the
// caller's.
func RecoverSignatureRejection(ctx context.Context, src Source, attempt func(standIns bool) <-chan llm.DriverEvent) <-chan llm.DriverEvent {
	out := make(chan llm.DriverEvent)
	go func() {
		defer close(out)
		first := attempt(false)
		produced := false
		for event := range first {
			if event.Type == llm.EventError && !produced && IsThoughtSignatureRejection(event.Error) {
				for range first {
					// Drain: the first attempt's goroutine must finish, and
					// nothing it still sends belongs to the caller.
				}
				logging.WarnContext(ctx, "Gemini rejected a thought signature; retrying once with stand-in signatures",
					"source", string(src), "error", event.Error)
				for retried := range attempt(true) {
					out <- retried
				}
				return
			}
			if producesOutput(event.Type) {
				produced = true
			}
			out <- event
		}
	}()
	return out
}

// RecoverSignatureRejectionSync is RecoverSignatureRejection for a request
// that is not streamed.
func RecoverSignatureRejectionSync[T any](ctx context.Context, src Source, attempt func(standIns bool) (T, error)) (T, error) {
	result, err := attempt(false)
	if err == nil || !IsThoughtSignatureRejection(err) {
		return result, err
	}
	logging.WarnContext(ctx, "Gemini rejected a thought signature; retrying once with stand-in signatures",
		"source", string(src), "error", err)
	return attempt(true)
}

func producesOutput(t llm.EventType) bool {
	switch t {
	case llm.EventContentStart, llm.EventContentDelta,
		llm.EventThinkingStart, llm.EventThinkingDelta,
		llm.EventToolUseStart, llm.EventToolUseDelta, llm.EventToolUseStop:
		return true
	}
	return false
}
