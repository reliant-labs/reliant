// unreachableShadowServer is a postgres server nothing listens on. Port 1 is
// refused at once on every host, so the shadow-database apply fails without a
// timeout. FORGE_TEST_POSTGRES_URL is honored verbatim and unprobed
// (shadowdb.Resolve), which is what makes the failure deterministic.
const unreachableShadowServer = "postgres://postgres:postgres@127.0.0.1:1/postgres?sslmode=disable"

// TestGenerate_AnUnreadableSchemaKeepsTheEntityFactories is forge bug
// df26c327. On one machine the entity-factories emitter could not read the
// applied schema; it printed "Warning: skipped entity factories" and reported
// success, and the stale-file sweep then deleted every committed
// factories_gen_test.go as "no emitter writes them any more".
//
// The sweep may delete only what an emitter that RAN no longer claims. So a
// schema-read failure must fail the factories step — named, with its cause,
// recorded so the run exits non-zero — and the sweep must leave the
// factories it did not rewrite alone.
func TestGenerate_AnUnreadableSchemaKeepsTheEntityFactories(t *testing.T) {
	if testing.Short() {
		t.Skip("waits out pgtest's 15s connect retry against a refused port; runs in task test (codegen's TestEntityFactories_AnUnreadableSchemaIsAnError covers the emitter under -short)")
	}
	resetCleanupRunState(t)
	t.Setenv(pgtest.EnvBaseURL, unreachableShadowServer)
	dir := t.TempDir()

	mustMkdir(t, filepath.Join(dir, "db", "migrations"))
	mustWrite(t, filepath.Join(dir, "db", "migrations", "00001_init.up.sql"),
		"CREATE TABLE products (id TEXT PRIMARY KEY, name TEXT NOT NULL);\n")
	mustMkdir(t, filepath.Join(dir, "internal", "handlers", "shop"))
	mustWrite(t, filepath.Join(dir, "internal", "handlers", "shop", "service.go"), "package shop\n")

	// A factories file a previous run wrote and the project committed.
	rel := "internal/handlers/shop/factories_gen_test.go"
	factories := filepath.Join(dir, filepath.FromSlash(rel))
	mustWriteStamped(t, factories, rel, "// Code generated by forge. DO NOT EDIT.\npackage shop\n")
	before, err := os.ReadFile(factories)
	if err != nil {
		t.Fatal(err)
	}

	ctx := newCleanupCtx(dir, &checksums.FileChecksums{}, []codegen.ServiceDef{{
		Name: "ShopService",
		Methods: []codegen.Method{
			{Name: "CreateProduct", InputType: "CreateProductRequest", OutputType: "CreateProductResponse"},
			{Name: "GetProduct", InputType: "GetProductRequest", OutputType: "GetProductResponse"},
		},
	}}, nil)

	buf, restore := captureStderr(t)
	stepErr := stepBootstrapTesting(ctx)
	var cleanupErr error
	if stepErr == nil {
		cleanupErr = stepCleanupStale(ctx)
	}
	restore()
	stderr := buf.String()

	if stepErr != nil {
		t.Fatalf("stepBootstrapTesting returned %v; without --strict a factories failure is a recorded step failure, not an abort", stepErr)
	}
	if cleanupErr != nil {
		t.Fatalf("stepCleanupStale: %v", cleanupErr)
	}
	if !slices.Contains(ctx.SoftFailures, entityFactoriesStep) {
		t.Errorf("SoftFailures = %v, want %q: an emitter that wrote nothing because it could not read the schema did not succeed, and the run must exit non-zero", ctx.SoftFailures, entityFactoriesStep)
	}
	for _, want := range []string{entityFactoriesStep + " failed", "shadow database", "127.0.0.1"} {
		if !strings.Contains(stderr, want) {
			t.Errorf("stderr does not name the failure and its cause (missing %q):\n%s", want, stderr)
		}
	}
	after, err := os.ReadFile(factories)
	if err != nil {
		t.Fatalf("%s was deleted after its emitter failed to read the schema: %v\nstderr:\n%s", rel, err, stderr)
	}
	if string(after) != string(before) {
		t.Errorf("%s was rewritten from no schema:\n%s", rel, after)
	}
}

// TestGenerate_AnUnreadableSchemaStopsAStrictRun: under --strict (what a gate
// wants) the same failure stops the run with the shadow database's error,
// rather than surfacing later as generated-code drift.
func TestGenerate_AnUnreadableSchemaStopsAStrictRun(t *testing.T) {
	if testing.Short() {
		t.Skip("waits out pgtest's 15s connect retry against a refused port; runs in task test")
	}
	resetCleanupRunState(t)
	t.Setenv(pgtest.EnvBaseURL, unreachableShadowServer)
	dir := t.TempDir()

	mustMkdir(t, filepath.Join(dir, "db", "migrations"))
	mustWrite(t, filepath.Join(dir, "db", "migrations", "00001_init.up.sql"),
		"CREATE TABLE products (id TEXT PRIMARY KEY);\n")
	mustMkdir(t, filepath.Join(dir, "internal", "handlers", "shop"))
	mustWrite(t, filepath.Join(dir, "internal", "handlers", "shop", "service.go"), "package shop\n")

	ctx := newCleanupCtx(dir, &checksums.FileChecksums{}, []codegen.ServiceDef{{Name: "ShopService"}}, nil)
	ctx.Strict = true
	_, restore := captureStderr(t)
	err := stepBootstrapTesting(ctx)
	restore()
	if err == nil {
		t.Fatal("stepBootstrapTesting succeeded under --strict with an unreachable shadow database")
	}
	for _, want := range []string{entityFactoriesStep, "shadow database", "127.0.0.1"} {
		if !strings.Contains(err.Error(), want) {
			t.Errorf("error does not name %q: %v", want, err)
		}
	}
}
