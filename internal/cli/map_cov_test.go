func TestRunMapPrintsTreeAndJSON(t *testing.T) {
	covBMapProject(t)

	text := captureStdout(t, func() {
		if err := runMap(0, "", false); err != nil {
			t.Errorf("runMap: %v", err)
		}
	})
	for _, want := range []string{"└── ", "├── ", "svc.go    [" + OwnershipScaffold + ", ⚠ FORGE_SCAFFOLD]", "forge.yaml    [" + OwnershipUser + "]"} {
		if !strings.Contains(text, want) {
			t.Errorf("tree missing %q:\n%s", want, text)
		}
	}

	js := captureStdout(t, func() {
		if err := runMap(0, "internal", true); err != nil {
			t.Errorf("runMap --json: %v", err)
		}
	})
	var root MapNode
	if err := json.NewDecoder(bytes.NewBufferString(js)).Decode(&root); err != nil {
		t.Fatalf("--json is not a MapNode: %v\n%s", err, js)
	}
	if len(root.Children) != 1 || root.Children[0].Path != "internal" {
		t.Errorf("--filter internal must keep only that subtree, got %+v", root.Children)
	}
}

func TestMapCmdWiresFlagsToRunMap(t *testing.T) {
	covBMapProject(t)
	cmd := newMapCmd()
	var buf bytes.Buffer
	cmd.SetOut(&buf)
	cmd.SetErr(&buf)
	cmd.SetArgs([]string{"--depth", "1", "--json"})
	out := captureStdout(t, func() {
		if err := cmd.Execute(); err != nil {
			t.Errorf("map: %v", err)
		}
	})
	var root MapNode
	if err := json.Unmarshal([]byte(out), &root); err != nil {
		t.Fatalf("not JSON: %v\n%s", err, out)
	}
	for _, c := range root.Children {
		if len(c.Children) != 0 {
			t.Errorf("--depth 1 must not descend into %s", c.Path)
		}
	}
}

