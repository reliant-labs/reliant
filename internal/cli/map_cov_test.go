func TestMapPathFilters(t *testing.T) {
	for _, tc := range []struct {
		name         string
		rel, filter  string
		wantMatch    bool
		wantDescends bool
	}{
		{"exact path", "internal/handlers", "internal/handlers", true, true},
		{"trailing slash on the filter", "internal/handlers/billing", "internal/handlers/", true, false},
		{"below the filter", "internal/handlers/billing/svc.go", "internal/handlers", true, false},
		{"a sibling sharing a name prefix is not below", "internal/handlers2", "internal/handlers", false, false},
		{"a parent of the filter is descended into, not matched", "internal", "internal/handlers/billing", false, true},
		{"unrelated path", "cmd", "internal/handlers", false, false},
	} {
		t.Run(tc.name, func(t *testing.T) {
			if got := pathMatchesFilter(tc.rel, tc.filter); got != tc.wantMatch {
				t.Errorf("pathMatchesFilter(%q, %q) = %v, want %v", tc.rel, tc.filter, got, tc.wantMatch)
			}
			if got := filterStartsWith(tc.filter, tc.rel); got != tc.wantDescends {
				t.Errorf("filterStartsWith(%q, %q) = %v, want %v", tc.filter, tc.rel, got, tc.wantDescends)
			}
		})
	}
}

func TestProtoEntityMissingFromMigrations(t *testing.T) {
	dir := t.TempDir()
	proto := filepath.Join(dir, "db.proto")
	mustWriteFile(t, proto, `syntax = "proto3";
message User {
  option (forge.v1.entity) = { table_name: "Users" };
}
message Invoice {
  option (forge.v1.entity) = { table_name: "invoices" };
}
message Broken {
  option (forge.v1.entity) = { table_name: "unterminated };
}
`)
	mig := map[string]struct{}{"users": {}}
	got := protoEntityMissingFromMigrations(proto, mig)
	if want := []string{"invoices"}; !reflect.DeepEqual(got, want) {
		t.Errorf("missing = %v, want %v (table names compare case-insensitively; an unterminated literal is ignored)", got, want)
	}
	if got := protoEntityMissingFromMigrations(filepath.Join(dir, "absent.proto"), mig); got != nil {
		t.Errorf("an unreadable proto reports no tables, got %v", got)
	}
}

func TestContainsScaffoldMarker(t *testing.T) {
	dir := t.TempDir()
	write := func(name, body string) string {
		p := filepath.Join(dir, name)
		mustWriteFile(t, p, body)
		return p
	}
	for _, tc := range []struct {
		name string
		path string
		want bool
	}{
		{"go line-start marker", write("a.go", "package a\n// FORGE_SCAFFOLD: fill in\n"), true},
		{"indented yaml marker", write("a.yaml", "x: 1\n  # FORGE_SCAFFOLD: fill in\n"), true},
		{"marker named in a string literal", write("b.go", "package b\nvar s = \"// FORGE_SCAFFOLD: x\"\n"), false},
		{"markdown documents the marker, never carries one", write("README.md", "// FORGE_SCAFFOLD: x\n"), false},
		{"unreadable file", filepath.Join(dir, "missing.go"), false},
	} {
		if got := containsScaffoldMarker(tc.path); got != tc.want {
			t.Errorf("%s: containsScaffoldMarker = %v, want %v", tc.name, got, tc.want)
		}
	}
}

func TestAnnotateFileNodeOwnership(t *testing.T) {
	dir := t.TempDir()
	stamped, _ := checksums.Stamp("internal/a/mock_gen.go", []byte("package a\n"))
	mustWriteFile(t, filepath.Join(dir, "internal/a/mock_gen.go"), string(stamped))
	mustWriteFile(t, filepath.Join(dir, "internal/a/drifted_gen.go"), strings.Replace(string(stamped), "package a", "package a // hand edit", 1))
	mustWriteFile(t, filepath.Join(dir, "internal/a/legacy_gen.go"), "package a\n")
	mustWriteFile(t, filepath.Join(dir, "internal/a/banner.go"), "// Code generated by forge. DO NOT EDIT.\npackage a\n")
	mustWriteFile(t, filepath.Join(dir, "internal/a/mine.go"), "package a\n")
	mustWriteFile(t, filepath.Join(dir, "deploy/ci.json"), `{"a":1}`)
	mustWriteFile(t, filepath.Join(dir, "deploy/edited.json"), `{"a":2}`)
	mustWriteFile(t, filepath.Join(dir, "proto/db/user.proto"), "message U { option (forge.v1.entity) = { table_name: \"ghosts\" }; }\n")
	mustWriteFile(t, filepath.Join(dir, "proto/db/ok.proto"), "message U { option (forge.v1.entity) = { table_name: \"users\" }; }\n")

	cs := &generator.FileChecksums{Unstampable: map[string]string{
		"deploy/ci.json":     checksums.BodyHash([]byte(`{"a":1}`)),
		"deploy/edited.json": checksums.BodyHash([]byte(`{"a":1}`)),
	}}
	mig := map[string]struct{}{"users": {}}

	for _, tc := range []struct {
		rel       string
		wantOwner string
		wantFlags []string
	}{
		{"internal/a/mock_gen.go", OwnershipForgeSpace, nil},
		{"internal/a/drifted_gen.go", OwnershipForgeDrifted, []string{"drift"}},
		{"deploy/ci.json", OwnershipForgeSpace, nil},
		{"deploy/edited.json", OwnershipForgeDrifted, []string{"drift"}},
		{"internal/a/legacy_gen.go", OwnershipForgeSpace, nil},
		{"internal/a/banner.go", OwnershipForgeSpace, nil},
		{"internal/a/mine.go", OwnershipUser, nil},
		{"proto/db/user.proto", OwnershipUser, []string{"diverged-from-migrations"}},
		{"proto/db/ok.proto", OwnershipUser, nil},
	} {
		node := &MapNode{Path: tc.rel}
		annotateFileNode(dir, filepath.FromSlash(tc.rel), node, cs, mig, nil)
		if node.Ownership != tc.wantOwner || !reflect.DeepEqual(node.Flags, tc.wantFlags) {
			t.Errorf("%s: ownership %q flags %v, want %q %v", tc.rel, node.Ownership, node.Flags, tc.wantOwner, tc.wantFlags)
		}
	}
}

func TestBuildMapTreeFilterDepthAndSkips(t *testing.T) {
	dir := t.TempDir()
	for _, f := range []string{
		"internal/handlers/billing/svc.go",
		"internal/handlers/auth/svc.go",
		"internal/db/db.go",
		"cmd/main.go",
		"node_modules/dep/index.js",
		".hidden/x.go",
		".github/workflows/ci.yml",
		"README.md",
	} {
		mustWriteFile(t, filepath.Join(dir, f), "x\n")
	}
	paths := func(n *MapNode) []string {
		var out []string
		var walk func(*MapNode)
		walk = func(n *MapNode) {
			for _, c := range n.Children {
				out = append(out, c.Path)
				walk(c)
			}
		}
		walk(n)
		return out
	}

	root, err := buildMapTree(dir, nil, "", 0, nil, nil)
	if err != nil {
		t.Fatal(err)
	}
	if want := filepath.Base(dir) + "/"; root.Name != want {
		t.Errorf("root name = %q, want %q", root.Name, want)
	}
	all := strings.Join(paths(root), " ")
	if strings.Contains(all, "node_modules") || strings.Contains(all, ".hidden") {
		t.Errorf("noise dirs and dotfiles must be skipped: %s", all)
	}
	if !strings.Contains(all, ".github/workflows/ci.yml") {
		t.Errorf(".github is the one dot-dir that is kept: %s", all)
	}
	// Directories sort before files at every level.
	if first := root.Children[0]; !first.IsDir || root.Children[len(root.Children)-1].IsDir {
		t.Errorf("dirs must come first, files last: %v", paths(root))
	}

	shallow, _ := buildMapTree(dir, nil, "", 1, nil, nil)
	for _, p := range paths(shallow) {
		if strings.Count(p, "/") > 0 {
			t.Errorf("--depth 1 must not descend: %s", p)
		}
	}

	filtered, _ := buildMapTree(dir, nil, "internal/handlers/billing", 0, nil, nil)
	if got, want := paths(filtered), []string{"internal", "internal/handlers", "internal/handlers/billing", "internal/handlers/billing/svc.go"}; !reflect.DeepEqual(got, want) {
		t.Errorf("filtered tree = %v, want %v", got, want)
	}
}

