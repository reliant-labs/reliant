// A --dry-run writes NOTHING: not the project, not .forge/forge.lock, and not
// git configuration — the project's or an enclosing repository's. `forge
// scaffold --dry-run` run inside a scratch directory of another checkout
// enabled extensions.worktreeConfig in THAT checkout's .git/config, wrote the
// merge driver and a versioned command into it, and then printed "(dry run —
// nothing written)".
//
// Each case runs the dry run in a project that is its own repository and in a
// project inside a parent repository, and compares every file, directory and
// mode under the outermost directory — .git included — before and after.
func TestDryRunWritesNothing(t *testing.T) {
	if testing.Short() {
		t.Skip("builds real git repositories; runs in task test")
	}
	for _, args := range [][]string{
		{"scaffold", "--dry-run"},
		{"scaffold", "package", "billing", "--dry-run"},
		{"package", "new", "billing", "--dry-run"},
		{"project", "disown", "no-such-file_gen.go", "--reason", "test", "--dry-run"},
		{"project", "disown", "internal/nothing.go", "--absent", "--reason", "test", "--dry-run"},
		{"project", "delete", "service", "notes", "--dry-run", "--yes"},
		{"generate", "--dry-run"},
	} {
		for _, layout := range []string{"own repository", "inside a parent repository"} {
			t.Run(strings.Join(args, " ")+"/"+layout, func(t *testing.T) {
				outer, project := dryRunFixture(t, layout == "inside a parent repository")
				clearProjectDir(t)
				before := treeSnapshot(t, outer)

				out, err := runForge(t, append([]string{"-C", project}, args...)...)
				if args[0] == "scaffold" && len(args) == 2 && !strings.Contains(out, "would birth") {
					t.Fatalf("the dry run never planned the marked entity (err=%v), so it proves nothing:\n%s", err, out)
				}

				after := treeSnapshot(t, outer)
				for _, d := range diffSnapshots(before, after) {
					t.Errorf("forge %s wrote %s", strings.Join(args, " "), d)
				}
			})
		}
	}
}

// dryRunFixture is a forge project with one marked entity, a forge-managed
// pre-commit hook, and a merge-driver binary forge would happily name: every
// piece of per-clone setup a writing command performs has something to act
// on. nested puts the project in a subdirectory of a parent repository that
// has no idea it is there.
func dryRunFixture(t *testing.T, nested bool) (outer, project string) {
	t.Helper()
	isolateGit(t)
	for _, e := range []string{mergeDriverOptOutEnv, "FORGE_NO_GIT_HOOKS", "FORGE_NO_HOOKS"} {
		t.Setenv(e, "")
	}
	outer, err := filepath.EvalSymlinks(t.TempDir())
	if err != nil {
		t.Fatal(err)
	}
	gitOut(t, outer, "init", "-q")
	project = outer
	if nested {
		project = filepath.Join(outer, "temp", "launch-notes")
	}
	writeTestFile(t, filepath.Join(project, "forge.yaml"), "name: svc\nmodule_path: example.com/svc\n")
	writeTestFile(t, filepath.Join(project, ".githooks", "pre-commit"),
		"#!/bin/sh\n# forge-managed git pre-commit hook — regenerated by `forge generate`.\nexit 0\n")
	writeTestFile(t, filepath.Join(project, "proto", "services", "notes", "v1", "notes.proto"),
		"syntax = \"proto3\";\n\npackage notes.v1;\n\n// forge:entity\nmessage Note {\n  string body = 2;\n}\n\nservice NotesService {}\n")

	// A durable forge binary outside the temp directory, and a project that
	// pins this forge: the conditions under which the wiring writes the most.
	bin := filepath.Join(t.TempDir(), "bin", "forge")
	writeTestFile(t, bin, "#!/bin/sh\n")
	if err := os.Chmod(bin, 0o755); err != nil {
		t.Fatal(err)
	}
	t.Setenv("TMPDIR", t.TempDir())
	prevExe, prevCheck := mergeDriverExecutable, mergeDriverPinCheck
	t.Cleanup(func() { mergeDriverExecutable, mergeDriverPinCheck = prevExe, prevCheck })
	mergeDriverExecutable = func() (string, error) { return bin, nil }
	mergeDriverPinCheck = func(string) (string, string, bool) { return "", "", false }
	return outer, project
}

// treeSnapshot is every path under root with its type, mode and content.
func treeSnapshot(t *testing.T, root string) map[string]string {
	t.Helper()
	snap := map[string]string{}
	err := filepath.WalkDir(root, func(path string, d fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		rel, _ := filepath.Rel(root, path)
		info, err := d.Info()
		if err != nil {
			return err
		}
		switch {
		case d.IsDir():
			snap[rel] = fmt.Sprintf("dir %v", info.Mode())
		case d.Type()&fs.ModeSymlink != 0:
			target, _ := os.Readlink(path)
			snap[rel] = "symlink -> " + target
		default:
			body, err := os.ReadFile(path)
			if err != nil {
				return err
			}
			snap[rel] = fmt.Sprintf("file %v\n%s", info.Mode(), body)
		}
		return nil
	})
	if err != nil {
		t.Fatal(err)
	}
	return snap
}

func diffSnapshots(before, after map[string]string) []string {
	var diffs []string
	for p, a := range after {
		b, ok := before[p]
		switch {
		case !ok:
			diffs = append(diffs, fmt.Sprintf("%s (created):\n%s", p, a))
		case a != b:
			diffs = append(diffs, fmt.Sprintf("%s:\n--- before\n%s\n--- after\n%s", p, b, a))
		}
	}
	for p := range before {
		if _, ok := after[p]; !ok {
			diffs = append(diffs, p+" (removed)")
		}
	}
	sort.Strings(diffs)
	return diffs
}
