package cli

import (
	"bytes"
	"encoding/json"
	"strings"
	"testing"
)

func capabilitiesJSON(t *testing.T) CapabilitiesSpec {
	t.Helper()
	var buf bytes.Buffer
	if err := runCapabilities(&buf, true); err != nil {
		t.Fatalf("runCapabilities: %v", err)
	}
	var spec CapabilitiesSpec
	if err := json.Unmarshal(buf.Bytes(), &spec); err != nil {
		t.Fatalf("output is not valid JSON: %v\n%s", err, buf.String())
	}
	return spec
}

// TestCapabilities_EnumeratesTheRealTree is the whole contract: the dump is
// the command tree, not a copy of it. A verb that exists must appear; a
// spelling forge retired must not; and the walk must reach past the first
// level, since the leaf verbs are exactly what an agent fails to discover.
func TestCapabilities_EnumeratesTheRealTree(t *testing.T) {
	spec := capabilitiesJSON(t)

	paths := map[string]CommandSpec{}
	for _, c := range spec.Commands {
		paths[c.Path] = c
	}
	if len(spec.Commands) < 80 {
		t.Fatalf("only %d commands enumerated — the tree walk has broken", len(spec.Commands))
	}
	for _, want := range []string{
		"forge scaffold", "forge scaffold entity", "forge scaffold rpc", "forge scaffold worker",
		"forge generate", "forge project annotations", "forge project capabilities",
		"forge skill load", "forge db seed apply", "forge env up",
	} {
		if _, ok := paths[want]; !ok {
			t.Errorf("capabilities omit %q, which the command tree has", want)
		}
	}
	// A retired spelling can never reappear here, because every path is the
	// cobra tree's own CommandPath() — internal/removalguard owns the
	// negative assertion, and repeating the dead verbs in this file would
	// itself be a surviving reference to them.
	//
	// Depth: a group is marked as one, a leaf is not.
	if !paths["forge scaffold"].Group {
		t.Error("`forge scaffold` is not marked as a group, but it has subcommands")
	}
	if paths["forge generate"].Group {
		t.Error("`forge generate` is marked as a group, but it has no subcommands")
	}
	for _, c := range spec.Commands {
		if c.Short == "" {
			t.Errorf("command %q has no Short — it would list as a bare path", c.Path)
		}
	}
}

// TestCapabilities_ListsHiddenAnalyzers pins the reason analyzers are in the
// dump at all: the maintainer flags are functional capabilities that
// `forge lint --help` deliberately hides, so nothing else an agent reads
// mentions them.
func TestCapabilities_ListsHiddenAnalyzers(t *testing.T) {
	spec := capabilitiesJSON(t)

	byFlag := map[string]AnalyzerSpec{}
	for _, a := range spec.Analyzers {
		byFlag[a.Flag] = a
	}
	if len(spec.Analyzers) < 10 {
		t.Fatalf("only %d lint analyzers enumerated — the flag walk has broken", len(spec.Analyzers))
	}
	for _, want := range []string{"--conventions", "--contract", "--migration-safety"} {
		if _, ok := byFlag[want]; !ok {
			t.Errorf("analyzers omit %q", want)
		}
	}
	scaffolds, ok := byFlag["--scaffolds"]
	if !ok {
		t.Fatal("analyzers omit --scaffolds, a hidden analyzer no other surface names")
	}
	if !scaffolds.Hidden {
		t.Error("--scaffolds is no longer hidden; the ✱ marking is now wrong")
	}
	if _, ok := byFlag["--help"]; ok {
		t.Error("--help is listed as a lint analyzer")
	}
	for _, a := range spec.Analyzers {
		if a.Usage == "" {
			t.Errorf("analyzer %q has no usage text", a.Flag)
		}
	}
}

// TestCapabilities_MarkersMatchTheAnnotationDump keeps the two dumps from
// disagreeing: both project markerSpecs(), which a sibling test pins against
// the real recognizers.
func TestCapabilities_MarkersMatchTheAnnotationDump(t *testing.T) {
	spec := capabilitiesJSON(t)
	if len(spec.Markers) != len(markerSpecs()) {
		t.Fatalf("capabilities list %d markers, markerSpecs has %d", len(spec.Markers), len(markerSpecs()))
	}
	names := map[string]bool{}
	for _, m := range spec.Markers {
		names[m.Name] = true
	}
	for _, m := range markerSpecs() {
		if !names[m.Name] {
			t.Errorf("capabilities omit marker %q", m.Name)
		}
	}
}

// TestFirstSentence_KeepsQuotedPeriods guards the one truncation rule. The
// --generated-drift usage quotes the literal banner "Code generated by
// forge. DO NOT EDIT.", and a naive split on ". " cut the description in
// half — advertising an analyzer by a fragment of someone else's sentence.
func TestFirstSentence_KeepsQuotedPeriods(t *testing.T) {
	cases := []struct{ in, want string }{
		{"Plain claim. Second sentence.", "Plain claim."},
		{
			"Fail when a forge-generated (`Code generated by forge. DO NOT EDIT.`) file was edited",
			"Fail when a forge-generated (`Code generated by forge. DO NOT EDIT.`) file was edited",
		},
		{"Collapses   runs\nof whitespace", "Collapses runs of whitespace"},
		{"No trailing period", "No trailing period"},
	}
	for _, tc := range cases {
		if got := firstSentence(tc.in); got != tc.want {
			t.Errorf("firstSentence(%q) = %q, want %q", tc.in, got, tc.want)
		}
	}
}

// TestCapabilities_TextViewIsUsable is a smoke test on the human/agent view:
// the sections are present and the tree is indented by depth.
func TestCapabilities_TextViewIsUsable(t *testing.T) {
	var buf bytes.Buffer
	if err := runCapabilities(&buf, false); err != nil {
		t.Fatalf("runCapabilities: %v", err)
	}
	out := buf.String()
	for _, want := range []string{
		"COMMANDS", "LINT ANALYZERS", "MARKERS",
		"forge scaffold entity", "forge skill load <name>", "forge project annotations",
	} {
		if !strings.Contains(out, want) {
			t.Errorf("text view is missing %q", want)
		}
	}
	// A second-level verb is indented under its group.
	if !strings.Contains(out, "\n    forge scaffold entity") {
		t.Error("text view does not indent subcommands by depth")
	}
}
