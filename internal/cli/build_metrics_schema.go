package cli

// The metrics schema as a build artifact.
//
// Every service binary can print the declared-metrics registry it links
// (`<bin> metrics schema --json`, forge.metrics/v1). `forge build` runs the
// binary it just built for the host and writes that document to a fixed path in
// the project, so a release bundle can carry it as
// observability/metrics-schema.json beside the dashboards (K4): the bundle
// step copies bin-adjacent files by path, it does not need to run anything.
//
// WHERE: <output dir>/observability/metrics-schema.json — bin/observability/
// metrics-schema.json by default. It is next to the binaries because it
// describes THEM: it is regenerated by every build, is reproducible from the
// binary alone, and so is output, not source (bin/ is gitignored). The bundle
// path inside a release is observability/metrics-schema.json, the same
// relative path under the build output directory.
//
// BEST EFFORT, like every other artifact derived from a built binary here: a
// binary that predates the registry, one built for another OS or architecture,
// or one that fails to run yields a warning and no file — never a failed
// build. A stale file from an earlier build is removed so the path never
// describes a binary it was not produced from.

import (
	"context"
	"fmt"
	"io"
	"os"
	"path/filepath"
	"runtime"
	"time"

	"github.com/reliant-labs/forge/internal/hostlaunch"
	"github.com/reliant-labs/forge/pkg/observe/metrics"

	"github.com/reliant-labs/forge/internal/atomicfile"
)

// MetricsSchemaArtifact is the schema's path relative to the build output
// directory, and its path inside a release bundle.
const MetricsSchemaArtifact = "observability/metrics-schema.json"

// metricsSchemaTimeout bounds running a freshly built binary. The command reads
// no config and starts nothing, so anything slower is a hang.
const metricsSchemaTimeout = 20 * time.Second

// emitMetricsSchema writes the metrics schema for the first of targets that
// yields one. A service's binaries share one registry per project binary, and
// the shared project binary is by far the usual case (server/worker/cron all
// map to ./cmd/<project>), so the first target that runs is the schema.
func emitMetricsSchema(ctx context.Context, w io.Writer, outputDir, crossArch string, targets []goBuildTarget) {
	dest := filepath.Join(outputDir, filepath.FromSlash(MetricsSchemaArtifact))
	_ = os.Remove(dest)

	var lastErr error
	for _, t := range targets {
		if !hostRunnable(t, crossArch) {
			continue
		}
		bin := filepath.Join(outputDir, hostlaunch.ExeName(runtime.GOOS, t.outputName))
		runCtx, cancel := context.WithTimeout(ctx, metricsSchemaTimeout)
		raw, err := binaryMetricsSchema(runCtx, bin)
		cancel()
		if err != nil {
			lastErr = err
			continue
		}
		if _, err := metrics.ParseSchema(raw); err != nil {
			lastErr = err
			continue
		}
		if err := os.MkdirAll(filepath.Dir(dest), 0o755); err != nil {
			fmt.Fprintf(w, "[build] metrics schema not written: %v\n", err)
			return
		}
		if err := atomicfile.WriteFile(dest, raw, 0o644); err != nil {
			fmt.Fprintf(w, "[build] metrics schema not written: %v\n", err)
			return
		}
		fmt.Fprintf(w, "[build] metrics schema: %s\n", dest)
		return
	}
	if lastErr != nil {
		fmt.Fprintf(w, "[build] metrics schema skipped: %v\n", lastErr)
	}
}

// hostRunnable reports whether a built target can be executed on this machine:
// a cross-compiled binary cannot be asked for its schema. crossArch is the
// build-wide arch buildGoTarget used (an explicit GoBuild.goarch wins over it,
// and a non-empty arch means GOOS defaulted to linux).
func hostRunnable(t goBuildTarget, crossArch string) bool {
	arch := crossArch
	if t.goarch != "" {
		arch = t.goarch
	}
	targetOS := t.goos
	if arch != "" && targetOS == "" {
		targetOS = "linux"
	}
	return (targetOS == "" || targetOS == runtime.GOOS) && (arch == "" || arch == runtime.GOARCH)
}

// builtTargets keeps the targets whose go build succeeded.
func builtTargets(targets []goBuildTarget, succeeded []buildResult) []goBuildTarget {
	ok := map[string]bool{}
	for _, r := range succeeded {
		if r.kind == "service" {
			ok[r.name] = true
		}
	}
	var out []goBuildTarget
	for _, t := range targets {
		if ok[t.outputName] {
			out = append(out, t)
		}
	}
	return out
}
