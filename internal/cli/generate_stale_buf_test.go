func TestParseBufOutputHeader(t *testing.T) {
	cases := []struct {
		name, head, want string
		ok               bool
	}{
		{"protoc-gen-go", "// Code generated by protoc-gen-go. DO NOT EDIT.\n// versions:\n// \tprotoc-gen-go v1.36.12\n// \tprotoc        (unknown)\n// source: services/a/v1/a.proto\n\npackage av1\n", "services/a/v1/a.proto", true},
		{"protoc-gen-connect-go", "// Code generated by protoc-gen-connect-go. DO NOT EDIT.\n//\n// Source: services/a/v1/a.proto\n\npackage av1connect\n", "services/a/v1/a.proto", true},
		{"protoc-gen-es", "// @generated by protoc-gen-es v2.16.0 with parameter \"target=ts\"\n// @generated from file services/a/v1/a.proto (package a.v1, syntax proto3)\n/* eslint-disable */\n", "services/a/v1/a.proto", true},
		{"no banner", "// source: services/a/v1/a.proto\npackage x\n", "", false},
		{"other generator", "// Code generated by mockgen. DO NOT EDIT.\n// Source: services/a/v1/a.proto\n", "", false},
		{"forge-certified", "// Code generated by protoc-gen-go. DO NOT EDIT.\n// forge:hash=abc\n// source: services/a/v1/a.proto\n", "", false},
		{"source after the header block", "// Code generated by protoc-gen-go. DO NOT EDIT.\npackage x\n// source: services/a/v1/a.proto\n", "", false},
		{"not a proto", "// Code generated by protoc-gen-go. DO NOT EDIT.\n// source: services/a/v1/a.txt\n", "", false},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			got, ok := parseBufOutputHeader([]byte(tc.head))
			if got != tc.want || ok != tc.ok {
				t.Fatalf("parseBufOutputHeader = (%q, %v), want (%q, %v)", got, ok, tc.want, tc.ok)
			}
		})
	}
}

// Deleting a proto leaves its buf output behind (buf never prunes). The
// sweep removes exactly the plugin output whose source proto is gone, and
// nothing else: not a dependency's output, not a namespace the project does
// not hold, not a forge-certified or hand-written file.
func TestPruneStaleBufOutput(t *testing.T) {
	dir := t.TempDir()
	write := func(rel, body string) {
		t.Helper()
		p := filepath.Join(dir, filepath.FromSlash(rel))
		if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(p, []byte(body), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	goHead := func(src string) string {
		return "// Code generated by protoc-gen-go. DO NOT EDIT.\n// source: " + src + "\n\npackage x\n"
	}
	connectHead := func(src string) string {
		return "// Code generated by protoc-gen-connect-go. DO NOT EDIT.\n//\n// Source: " + src + "\n\npackage x\n"
	}
	esHead := func(src string) string {
		return "// @generated by protoc-gen-es v2.16.0\n// @generated from file " + src + " (package a.v1, syntax proto3)\n"
	}

	write("buf.yaml", "version: v2\nmodules:\n  - path: proto\n")
	write("proto/services/keep/v1/keep.proto", "syntax = \"proto3\";\n")
	write("proto/forge/v1/forge.proto", "syntax = \"proto3\";\n")

	// Live output.
	write("gen/services/keep/v1/keep.pb.go", goHead("services/keep/v1/keep.proto"))
	write("frontends/web/src/gen/services/keep/v1/keep_pb.ts", esHead("services/keep/v1/keep.proto"))
	// Stale output of the deleted services/gone proto.
	write("gen/services/gone/v1/gone.pb.go", goHead("services/gone/v1/gone.proto"))
	write("gen/services/gone/v1/gonev1connect/gone.connect.go", connectHead("services/gone/v1/gone.proto"))
	write("frontends/web/src/gen/services/gone/v1/gone_pb.ts", esHead("services/gone/v1/gone.proto"))
	// Kept: dependencies, a namespace the project does not hold, a
	// forge-certified file, a hand-written file.
	write("frontends/web/src/gen/google/api/annotations_pb.ts", esHead("google/api/annotations.proto"))
	write("frontends/web/src/gen/forge/v2/old_pb.ts", esHead("forge/v2/old.proto"))
	write("gen/acme/v1/acme.pb.go", goHead("acme/v1/acme.proto"))
	write("gen/services/gone/v1/forge_gen.go", "// Code generated by protoc-gen-go. DO NOT EDIT.\n// forge:hash=00\n// source: services/gone/v1/gone.proto\n")
	write("gen/services/gone/v1/notes.go", "// source: services/gone/v1/gone.proto\npackage x\n")

	ctx := &pipelineContext{ProjectDir: dir}
	got := pruneStaleBufOutput(ctx, []string{"gen", "frontends/web/src/gen"})
	want := []string{
		"frontends/web/src/gen/services/gone/v1/gone_pb.ts",
		"gen/services/gone/v1/gone.pb.go",
		"gen/services/gone/v1/gonev1connect/gone.connect.go",
	}
	if !reflect.DeepEqual(got, want) {
		t.Fatalf("removed:\n%v\nwant:\n%v", got, want)
	}
	for _, rel := range want {
		if _, err := os.Stat(filepath.Join(dir, rel)); !os.IsNotExist(err) {
			t.Errorf("%s still exists (err %v)", rel, err)
		}
	}
	for _, rel := range []string{
		"gen/services/keep/v1/keep.pb.go",
		"frontends/web/src/gen/services/keep/v1/keep_pb.ts",
		"frontends/web/src/gen/google/api/annotations_pb.ts",
		"frontends/web/src/gen/forge/v2/old_pb.ts",
		"gen/acme/v1/acme.pb.go",
		"gen/services/gone/v1/forge_gen.go",
		"gen/services/gone/v1/notes.go",
	} {
		if _, err := os.Stat(filepath.Join(dir, rel)); err != nil {
			t.Errorf("%s was removed: %v", rel, err)
		}
	}
	// Emptied directories go, up to (not including) the out directory.
	if _, err := os.Stat(filepath.Join(dir, "frontends/web/src/gen/services/gone")); !os.IsNotExist(err) {
		t.Errorf("emptied frontends/web/src/gen/services/gone kept (err %v)", err)
	}
	if _, err := os.Stat(filepath.Join(dir, "gen/services/gone/v1/gonev1connect")); !os.IsNotExist(err) {
		t.Errorf("emptied gonev1connect kept (err %v)", err)
	}
	if _, err := os.Stat(filepath.Join(dir, "frontends/web/src/gen")); err != nil {
		t.Errorf("out directory removed: %v", err)
	}

	// A second run finds nothing.
	if again := pruneStaleBufOutput(ctx, []string{"gen", "frontends/web/src/gen"}); len(again) != 0 {
		t.Fatalf("second run removed %v", again)
	}
}

// With no local proto at all there is no namespace to prove a source gone
// in, so nothing is swept.
func TestPruneStaleBufOutputWithoutProtosKeepsEverything(t *testing.T) {
	dir := t.TempDir()
	p := filepath.Join(dir, "gen", "services", "a", "v1", "a.pb.go")
	if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(p, []byte("// Code generated by protoc-gen-go. DO NOT EDIT.\n// source: services/a/v1/a.proto\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	if got := pruneStaleBufOutput(&pipelineContext{ProjectDir: dir}, []string{"gen"}); len(got) != 0 {
		t.Fatalf("removed %v", got)
	}
}

// Ownership must be provable before a sweep (review B1): a namespace two
// proto roots share cannot say which root a source path is relative to, and
// a buf.gen.yaml that generates from a remote input names sources this
// project does not hold. Either way the output is kept.
func TestPruneStaleBufOutputNeedsProvableOwnership(t *testing.T) {
	goHead := func(src string) string {
		return "// Code generated by protoc-gen-go. DO NOT EDIT.\n// source: " + src + "\n\npackage x\n"
	}
	project := func(t *testing.T, files map[string]string) string {
		t.Helper()
		dir := t.TempDir()
		for rel, body := range files {
			p := filepath.Join(dir, filepath.FromSlash(rel))
			if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
				t.Fatal(err)
			}
			if err := os.WriteFile(p, []byte(body), 0o644); err != nil {
				t.Fatal(err)
			}
		}
		return dir
	}
	t.Run("two roots share a namespace", func(t *testing.T) {
		dir := project(t, map[string]string{
			"buf.yaml":                        "version: v2\nmodules:\n  - path: proto\n  - path: api\n",
			"proto/services/a/v1/a.proto":     "syntax = \"proto3\";\n",
			"api/services/b/v1/b.proto":       "syntax = \"proto3\";\n",
			"proto/billing/v1/billing.proto":  "syntax = \"proto3\";\n",
			"gen/services/gone/v1/gone.pb.go": goHead("services/gone/v1/gone.proto"),
			"gen/billing/v1/old/old.pb.go":    goHead("billing/v1/old/old.proto"),
		})
		got := pruneStaleBufOutput(&pipelineContext{ProjectDir: dir}, []string{"gen"})
		if !reflect.DeepEqual(got, []string{"gen/billing/v1/old/old.pb.go"}) {
			t.Fatalf("removed %v; want only the output of the namespace one root holds", got)
		}
	})
	t.Run("a remote buf.gen.yaml input", func(t *testing.T) {
		dir := project(t, map[string]string{
			"buf.yaml":                        "version: v2\nmodules:\n  - path: proto\n",
			"buf.gen.yaml":                    "version: v2\ninputs:\n  - directory: proto\n  - module: buf.build/acme/apis\n",
			"proto/services/a/v1/a.proto":     "syntax = \"proto3\";\n",
			"gen/services/gone/v1/gone.pb.go": goHead("services/gone/v1/gone.proto"),
		})
		if got := pruneStaleBufOutput(&pipelineContext{ProjectDir: dir}, []string{"gen"}); len(got) != 0 {
			t.Fatalf("removed %v; a remote input may have produced it", got)
		}
	})
}
