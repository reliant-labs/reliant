package lint

import (
	"os"
	"path/filepath"
	"testing"
)

// Generated Go is not the format pre-pass's to rewrite.
//
// Incident (control-plane, cutting v0.1.9): a bare `forge lint` left the tree
// dirty with 35 modified files under gen/ — every .pb.go and .connect.go
// protoc had emitted. The next `forge generate` reverted all 35, because
// protoc-gen-go rewrites those files from scratch and emits its own import
// grouping. So the two commands ping-pong: whichever ran last decided the
// bytes, and a release checkout was never clean between them.
//
// The pre-pass exists for exactly one reason — to keep mechanical formatting
// from surfacing as a golangci-lint gate. The scaffolded .golangci.yml
// excludes generated files from every linter ("(^|/)gen/", ".*_gen\.go$",
// ".*\.pb\.go$", ".*\.connect\.go$"), so reformatting them pre-empts no
// finding that could ever have fired. It buys nothing, and it costs a dirty
// tree, a fight with the generator, and a red "Verify Generated Code" job for
// whoever's checkout differs.

// protocStyleGo mirrors what protoc-gen-go actually emits: a single import
// block with the stdlib packages last and aliased to their own names.
// goimports regroups it (stdlib hoisted into a leading group), which is
// precisely the diff that appeared in all 35 files.
const protocStyleGo = `// Code generated by protoc-gen-go. DO NOT EDIT.

package auditv1

import (
	_ "example.com/thing/forgepb"
	protoreflect "google.golang.org/protobuf/reflect/protoreflect"
	reflect "reflect"
	sync "sync"
)
`

// generatedPaths are the shapes forge and its toolchain generate, each of
// which the scaffolded .golangci.yml already excludes from linting.
var generatedPaths = []string{
	"gen/audit/v1/audit_log.pb.go",
	"gen/audit/v1/auditv1connect/audit_log.connect.go",
	"internal/billing/mock_gen.go",
	"internal/billing/tracing_gen.go",
	"pkg/thing/thing.pb.go",
	"internal/thing/thing.connect.go",
}

// TestFormatGoTree_LeavesGeneratedFilesAlone is the regression lock on the
// incident above: the pre-pass must not rewrite a single generated file, so
// `forge lint` cannot dirty a clean checkout and cannot disagree with
// `forge generate` about the bytes.
func TestFormatGoTree_LeavesGeneratedFilesAlone(t *testing.T) {
	root := newFormatProject(t)
	for _, rel := range generatedPaths {
		writeFile(t, root, rel, protocStyleGo)
	}

	changed, err := formatGoTree(root)
	if err != nil {
		t.Fatalf("formatGoTree: %v", err)
	}
	if len(changed) != 0 {
		t.Errorf("pre-pass rewrote generated file(s) %v; generated code is regenerated by "+
			"forge generate and excluded from every linter, so formatting it only "+
			"guarantees the two commands disagree", changed)
	}

	for _, rel := range generatedPaths {
		got, rerr := os.ReadFile(filepath.Join(root, rel))
		if rerr != nil {
			t.Fatalf("read back %s: %v", rel, rerr)
		}
		if string(got) != protocStyleGo {
			t.Errorf("%s was modified by the pre-pass:\n--- got ---\n%s", rel, got)
		}
	}
}

// TestFormatGoTree_StillFormatsOwnedFilesBesideGenerated pins the other half
// of the boundary. Skipping generated code must not become "skip the package
// that contains it": a hand-edited file sitting next to a mock_gen.go is
// exactly the drift the pre-pass was built to absorb, and it still must be.
func TestFormatGoTree_StillFormatsOwnedFilesBesideGenerated(t *testing.T) {
	root := newFormatProject(t)
	writeFile(t, root, "internal/billing/mock_gen.go", protocStyleGo)
	writeFile(t, root, "internal/billing/service.go", unformattedGo)

	changed, err := formatGoTree(root)
	if err != nil {
		t.Fatalf("formatGoTree: %v", err)
	}
	want := filepath.Join("internal", "billing", "service.go")
	if len(changed) != 1 || changed[0] != want {
		t.Fatalf("changed = %v, want [%s] — the owned file beside a _gen.go must still be formatted", changed, want)
	}
}
