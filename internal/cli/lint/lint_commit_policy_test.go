// TestCommitPolicyStep_GatesOnIgnoredGeneratedCode: `forge lint` must fail a
// project whose (inherited, pre-fix) .gitignore hides forge-generated code —
// the state that turned a scaffolded project's CI red on every compiling job
// while `forge ci verify-generated` stayed green — and must name the file and
// the fix, in text and JSON.
func TestCommitPolicyStep_GatesOnIgnoredGeneratedCode(t *testing.T) {
	if testing.Short() {
		t.Skip("runs git against a real repository; runs in task test")
	}
	step := findStep(t, "commit-policy lint")
	if !step.gates {
		t.Fatal("commit-policy lint must gate: an ignored generated file breaks every fresh clone")
	}
	if _, err := exec.LookPath("git"); err != nil {
		t.Skip("git not on PATH")
	}
	dir := t.TempDir()
	run := func(args ...string) {
		t.Helper()
		cmd := exec.Command("git", append([]string{"-C", dir}, args...)...)
		cmd.Env = append(os.Environ(), "GIT_AUTHOR_NAME=t", "GIT_AUTHOR_EMAIL=t@t", "GIT_COMMITTER_NAME=t", "GIT_COMMITTER_EMAIL=t@t")
		if out, err := cmd.CombinedOutput(); err != nil {
			t.Fatalf("git %v: %v\n%s", args, err, out)
		}
	}
	for rel, body := range map[string]string{
		".gitignore":                       "pkg/middleware/*_gen.go\n",
		"pkg/middleware/procedures_gen.go": "// Code generated by forge. DO NOT EDIT.\npackage middleware\n",
		"pkg/middleware/auth.go":           "package middleware\n",
	} {
		p := filepath.Join(dir, filepath.FromSlash(rel))
		_ = os.MkdirAll(filepath.Dir(p), 0o755)
		if err := os.WriteFile(p, []byte(body), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	run("init", "-q")
	run("add", "-A")
	run("commit", "-qm", "init")

	fs, gated, err := collectCommitPolicyJSON(dir)
	if err != nil || !gated || len(fs) != 1 || fs[0].Severity != "error" || fs[0].File != "pkg/middleware/procedures_gen.go" {
		t.Fatalf("got (%+v, gated=%v, %v); want one gating error on procedures_gen.go", fs, gated, err)
	}
	if !strings.Contains(fs[0].FixHint, "git add pkg/middleware/procedures_gen.go") {
		t.Errorf("fix hint must name the command that repairs it: %q", fs[0].FixHint)
	}
}

// TestCommitPolicyStep_WarnsOnIgnoredBirthLedger: a `.forge/` ignore line
// keeps .forge/scaffolded/ out of git whatever the scaffold's negations say,
// so deleted scaffolds come back in every fresh clone. `forge lint` names the
// path and the fix; the scaffold's own `.forge/*` + negations pass.
func TestCommitPolicyStep_WarnsOnIgnoredBirthLedger(t *testing.T) {
	if testing.Short() {
		t.Skip("runs git against a real repository; runs in task test")
	}
	if _, err := exec.LookPath("git"); err != nil {
		t.Skip("git not on PATH")
	}
	for _, tc := range []struct {
		name, gitignore string
		want            []string
	}{
		// `git check-ignore` matches a path's leading directories too, so a
		// rule that excludes .forge itself is reported against every probe
		// below it, in each spelling, and wins over the scaffold's negations.
		{"directory ignored", ".forge/\n.forge/*\n!.forge/scaffolded/\n!.forge/disowned.json\n!.forge/hashes/\n",
			[]string{".forge/disowned.json", ".forge/hashes/", ".forge/scaffolded/"}},
		{"directory ignored, no slash", ".forge\n.forge/*\n!.forge/scaffolded/\n!.forge/disowned.json\n!.forge/hashes/\n",
			[]string{".forge/disowned.json", ".forge/hashes/", ".forge/scaffolded/"}},
		{"directory ignored, anchored", "/.forge/\n!.forge/scaffolded/\n!.forge/disowned.json\n!.forge/hashes/\n",
			[]string{".forge/disowned.json", ".forge/hashes/", ".forge/scaffolded/"}},
		{"scaffold's rules", ".forge/*\n!.forge/scaffolded/\n!.forge/disowned.json\n!.forge/hashes/\n", nil},
	} {
		t.Run(tc.name, func(t *testing.T) {
			dir := t.TempDir()
			if out, err := exec.Command("git", "-C", dir, "init", "-q").CombinedOutput(); err != nil {
				t.Fatalf("git init: %v\n%s", err, out)
			}
			if err := os.WriteFile(filepath.Join(dir, ".gitignore"), []byte(tc.gitignore), 0o644); err != nil {
				t.Fatal(err)
			}
			fs, _, err := collectCommitPolicyJSON(dir)
			if err != nil {
				t.Fatal(err)
			}
			var got []string
			for _, f := range fs {
				if f.Rule != "forge-state-ignored" {
					t.Errorf("unexpected finding %+v", f)
					continue
				}
				got = append(got, f.File)
				if !strings.Contains(f.FixHint, "`.forge/*`") {
					t.Errorf("fix hint must say to ignore the children: %q", f.FixHint)
				}
			}
			if strings.Join(got, ",") != strings.Join(tc.want, ",") {
				t.Errorf("findings on %v, want %v", got, tc.want)
			}
		})
	}
}
