// File: internal/cli/lint/lint_unproven_signup.go
//
// forgeconv-unproven-signup — a deployed sign-up that creates accounts whose
// address nobody proves.
//
// Where an environment's identity delivers no mail (`forge.IdentityEmail
// {delivery = "none"}`) or a broker serves the legacy self-sign-up outside
// development (auth_self_signup), a sign-up creates the account WITH its
// password and signs in at once: nothing can mail a code. Its email is then a
// contact field the person typed (devidp.MetaContactOnly). It is never
// proven, and no later proof claims the account — when mail is turned on, the
// address's real owner gets a fresh account and this one is moved aside
// (forge#2121). An app that binds anything to such an address (an
// invitation, a membership, a domain allow-list) binds it to whoever typed
// it.
//
// The lane steers to a sign-up that proves the address: deliver mail
// (`delivery = "platform"`, the default, or `smtp`), so sign-up creates no
// credential until the address is proven.
//
// Textual, like forgeconv-identity-methods: deploy/kcl/**/*.k, comments
// stripped. The dev env (deploy/kcl/dev/) is skipped for auth_self_signup,
// which the broker turns on in development anyway.
//
// A file forge generated (it opens with the `# Code generated by forge. DO
// NOT EDIT.` banner, e.g. deploy/kcl/config_gen.k) declares no environment's
// values: it is a projection of the config proto, a schema and a mapping
// from whatever each env sets onto env vars. So the lane reads only what such
// a file can mean, the schema DEFAULT (ruleUnprovenSignupDefault), and never
// a value: an env var mapping spelled with a literal "true" in a generated
// file is not sign-up turned on (forge bug 90412992). An env's own main.k or
// config.k is where a value is declared, and stays fully read.
//
// ERROR severity, graded by the rollout table: a warning until GatesFrom.
package lint

import (
	"fmt"
	"io/fs"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strings"
)

// ruleUnprovenSignup is the rule ID this lane emits.
const ruleUnprovenSignup = "forgeconv-unproven-signup"

// ruleUnprovenSignupDefault is the lane's second rule: a config schema that
// DEFAULTS auth_self_signup to true (`auth_self_signup: bool = True`, a proto
// default_value of "true" projected into config_gen.k), which turns the
// legacy sign-up on in every environment that does not override it, prod
// included. It has its own ID so projects can grade the two findings separately.
const ruleUnprovenSignupDefault = "forgeconv-unproven-signup-default"

var (
	kclNoMail = regexp.MustCompile(`\bdelivery\s*[:=]\s*"none"`)
	// kclLegacySelfSign matches auth_self_signup SET to true: a config value
	// (`auth_self_signup = True`) or an env var (`"AUTH_SELF_SIGNUP" =
	// "true"`). The value must be the whole expression, ending the line or
	// the entry, so the env projection forge generates into every
	// config_gen.k — `"AUTH_SELF_SIGNUP" = "true" if c.auth_self_signup else
	// "false"` — reads as what it is, a mapping of whatever the env
	// declares, and not as sign-up turned on.
	kclLegacySelfSign = regexp.MustCompile(`(?im)\bauth_self_signup"?\s*[:=]\s*("?true"?|"1")\s*(?:[,;}\]]|$)`)
	// kclSelfSignDefault matches a schema attribute defaulting it to true
	// (ruleUnprovenSignupDefault).
	kclSelfSignDefault = regexp.MustCompile(`(?im)\bauth_self_signup\s*:\s*bool\s*=\s*true\s*$`)
)

// kclGeneratedBanner is the header forge writes on every .k file it
// generates (config_projection_gen.go), the KCL spelling of Go's
// `// Code generated ... DO NOT EDIT.` convention.
var kclGeneratedBanner = regexp.MustCompile(`^#\s*Code generated by forge\b.*\bDO NOT EDIT\.?\s*$`)

// isForgeGeneratedKCL reports whether a .k file carries forge's generated
// banner on one of its first lines (blank lines before it allowed).
func isForgeGeneratedKCL(raw []byte) bool {
	for i, line := range strings.SplitN(string(raw), "\n", 6) {
		line = strings.TrimSpace(line)
		if line == "" && i < 5 {
			continue
		}
		return kclGeneratedBanner.MatchString(line)
	}
	return false
}

// unprovenSignupFinding is one declaration of a sign-up nobody proves.
type unprovenSignupFinding struct {
	Rule  string // ruleUnprovenSignup or ruleUnprovenSignupDefault
	Where string // file:line
	What  string
}

func findUnprovenSignups(root string) ([]unprovenSignupFinding, error) {
	var out []unprovenSignupFinding
	dir := filepath.Join(root, "deploy", "kcl")
	err := filepath.WalkDir(dir, func(path string, d fs.DirEntry, err error) error {
		if err != nil {
			if d != nil && d.IsDir() {
				return filepath.SkipDir
			}
			return nil
		}
		if d.IsDir() || !strings.HasSuffix(path, ".k") || strings.HasSuffix(path, "_test.k") {
			return nil
		}
		raw, rerr := os.ReadFile(path)
		if rerr != nil {
			return nil
		}
		rel, _ := filepath.Rel(root, path)
		rel = filepath.ToSlash(rel)
		generated := isForgeGeneratedKCL(raw)
		lines := strings.Split(string(raw), "\n")
		for i := range lines {
			lines[i] = kclLineComment.ReplaceAllString(lines[i], "")
		}
		text := strings.Join(lines, "\n")
		lineOf := func(off int) int { return strings.Count(text[:off], "\n") + 1 }
		if signup := kclSignup.FindStringSubmatchIndex(text); !generated && signup != nil && kclNoMail.MatchString(text) {
			out = append(out, unprovenSignupFinding{
				Rule:  ruleUnprovenSignup,
				Where: fmt.Sprintf("%s:%d", rel, lineOf(signup[0])),
				What:  fmt.Sprintf("signup %q with email delivery \"none\"", text[signup[2]:signup[3]]),
			})
		}
		if !strings.HasPrefix(rel, "deploy/kcl/dev/") {
			if m := kclLegacySelfSign.FindStringIndex(text); !generated && m != nil {
				out = append(out, unprovenSignupFinding{
					Rule:  ruleUnprovenSignup,
					Where: fmt.Sprintf("%s:%d", rel, lineOf(m[0])),
					What:  "auth_self_signup (the legacy sign-up) outside development",
				})
			}
			if m := kclSelfSignDefault.FindStringIndex(text); m != nil {
				out = append(out, unprovenSignupFinding{
					Rule:  ruleUnprovenSignupDefault,
					Where: fmt.Sprintf("%s:%d", rel, lineOf(m[0])),
					What:  "auth_self_signup defaulting to true (the legacy sign-up in every environment that does not set it)",
				})
			}
		}
		return nil
	})
	if err != nil && !os.IsNotExist(err) {
		return nil, err
	}
	sort.Slice(out, func(i, j int) bool {
		if out[i].Where != out[j].Where {
			return out[i].Where < out[j].Where
		}
		return out[i].Rule < out[j].Rule
	})
	return out, nil
}

// unprovenSignupLane is the lane's name in lintPipeline (and lint.lanes).
const unprovenSignupLane = "unproven-signup lint"

func collectUnprovenSignupJSON(root string) ([]lintJSONFinding, error) {
	if root == "" {
		return nil, nil
	}
	found, err := findUnprovenSignups(root)
	if err != nil {
		return nil, fmt.Errorf("scan identity sign-up: %w", err)
	}
	out := make([]lintJSONFinding, 0, len(found))
	for _, f := range found {
		file, line := f.Where, 0
		if i := strings.LastIndexByte(f.Where, ':'); i > 0 {
			file = f.Where[:i]
			_, _ = fmt.Sscanf(f.Where[i+1:], "%d", &line)
		}
		hint := "deliver mail so sign-up proves the address first: drop `delivery = \"none\"` (platform delivery is the default) " +
			"or declare `smtp`, and serve sign-up through the LOGIN_POLICY rather than auth_self_signup " +
			"(`forge skill load auth/frontend`)"
		if f.Rule == ruleUnprovenSignupDefault {
			hint = "default auth_self_signup to false in the config proto (`default_value: \"false\"`, then `forge generate`), " +
				"and serve sign-up through the LOGIN_POLICY rather than auth_self_signup " +
				"(`forge skill load auth/frontend`)"
		}
		out = append(out, lintJSONFinding{
			Rule:     f.Rule,
			Severity: "error",
			File:     file,
			Line:     line,
			Message: "this environment declares " + f.What + ": a sign-up creates its account with a password and an address " +
				"nobody proves. That address is a contact field the person typed, never proven and never claimed by a later proof",
			FixHint: hint,
		})
	}
	return out, nil
}
