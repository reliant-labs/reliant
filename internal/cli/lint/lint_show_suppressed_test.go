// suppressedProject writes one of every suppression the inventory lists, and
// one of every place it must NOT look.
func suppressedProject(t *testing.T) string {
	t.Helper()
	root := t.TempDir()
	files := map[string]string{
		"forge.yaml": "name: demo\n" +
			"lint:\n" +
			"  rules:\n" +
			"    # a CLI has no handlers\n" +
			"    forgeconv-handler-file-size: off\n" +
			"    forgeconv-list-filter-optional: warn\n" +
			"    forgeconv-one-service-per-file: error\n" +
			"contracts:\n" +
			"  exclude:\n" +
			"    - internal/buildinfo # version stamp only\n",
		"internal/algos/doc.go": "// Package algos is a strategy registry.\n//\n" +
			"//forge:exclude-contract: strategy registry\npackage algos\n",
		"internal/db/doc.go": "//forge:lint-disable-next-line forge-exclude-contract-outbound-io: 40-method DB layer; split tracked in #123\n" +
			"//forge:exclude-contract: hand-written data layer, split pending\npackage db\n",
		"internal/x/x.go":                          "package x\n\nfunc f() {\n\t_ = g() //nolint:errcheck // best effort\n}\n",
		"internal/svc/svc.go":                      "package svc\n\nfunc (s *S) h() {\n\ts.deps.Clock.Now() // forge:optional-checked\n}\n",
		"db/migrations/20260101000000_drop.up.sql": "-- forge:allow-destructive: the legacy table has no readers\nDROP TABLE legacy;\n",
		"frontends/web/src/a.ts":                   "// forge:lint-disable-next-line forge-frontend-process-env: build-time constant\nconst x = process.env.X;\n",
		// Not the project's own hand-written source: none of these count.
		"internal/x/x_gen.go":       "package x\n\n//nolint:errcheck\nfunc gen() {}\n",
		"internal/x/stamped.go":     "// Code generated by forge. DO NOT EDIT.\n\npackage x\n\n//nolint:gosec\nfunc stamped() {}\n",
		"node_modules/dep/index.js": "// forge:lint-disable-file *\n",
		"internal/x/testdata/f.go":  "//nolint:revive\npackage f\n",
		".forge/cache/c.yaml":       "# forge:lint-disable-file *\n",
	}
	for name, body := range files {
		p := filepath.Join(root, filepath.FromSlash(name))
		if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(p, []byte(body), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	return root
}

// The flag exists. The contracts/package-markers skill told users to run
// `forge lint --show-suppressed`, and forge lint answered "unknown flag".
func TestShowSuppressedListsEveryDeclaredSuppression(t *testing.T) {
	t.Chdir(suppressedProject(t))
	cmd := newCmd(testFactory())
	var out bytes.Buffer
	cmd.SetOut(&out)
	cmd.SetArgs([]string{"--show-suppressed", "--json"})
	if err := cmd.Execute(); err != nil {
		t.Fatalf("forge lint --show-suppressed --json: %v", err)
	}
	var got struct {
		Suppressions  []declaredSuppression `json:"suppressions"`
		Total         int                   `json:"total"`
		WithoutReason int                   `json:"without_reason"`
	}
	if err := json.Unmarshal(out.Bytes(), &got); err != nil {
		t.Fatalf("not JSON: %v\n%s", err, out.String())
	}
	want := []declaredSuppression{
		{File: "db/migrations/20260101000000_drop.up.sql", Line: 1, Rule: "destructive-change", Mechanism: "forge:allow-destructive", Covers: "the file", Reason: "the legacy table has no readers"},
		{File: "forge.yaml", Line: 5, Rule: "forgeconv-handler-file-size", Mechanism: "lint.rules: off", Covers: "every finding in the project: not reported", Reason: "a CLI has no handlers"},
		{File: "forge.yaml", Line: 6, Rule: "forgeconv-list-filter-optional", Mechanism: "lint.rules: warn", Covers: "every finding in the project: reported as warning, never gating"},
		{File: "forge.yaml", Line: 10, Rule: "contract", Mechanism: "contracts.exclude", Covers: "packages matching internal/buildinfo, with their mocks and decorators", Reason: "version stamp only"},
		{File: "frontends/web/src/a.ts", Line: 1, Rule: "forge-frontend-process-env", Mechanism: "forge:lint-disable-next-line", Covers: "line 2", Reason: "build-time constant"},
		{File: "internal/algos/doc.go", Line: 3, Rule: "contract", Mechanism: "forge:exclude-contract", Covers: "package internal/algos, with its mock and decorator", Reason: "strategy registry"},
		{File: "internal/db/doc.go", Line: 1, Rule: "forge-exclude-contract-outbound-io", Mechanism: "forge:lint-disable-next-line", Covers: "lines 2-3", Reason: "40-method DB layer; split tracked in #123"},
		{File: "internal/db/doc.go", Line: 2, Rule: "contract", Mechanism: "forge:exclude-contract", Covers: "package internal/db, with its mock and decorator", Reason: "hand-written data layer, split pending"},
		{File: "internal/svc/svc.go", Line: 4, Rule: "forge-optional-deps-guard", Mechanism: "forge:optional-checked", Covers: "lines 4-5"},
		{File: "internal/x/x.go", Line: 4, Rule: "errcheck", Mechanism: "nolint:", Covers: "line 4", Reason: "best effort"},
	}
	if len(got.Suppressions) != len(want) {
		t.Fatalf("got %d suppressions, want %d:\n%s", len(got.Suppressions), len(want), out.String())
	}
	for i := range want {
		if got.Suppressions[i] != want[i] {
			t.Errorf("suppression %d:\n got %+v\nwant %+v", i, got.Suppressions[i], want[i])
		}
	}
	if got.Total != len(want) || got.WithoutReason != 2 {
		t.Errorf("total = %d, without_reason = %d; want %d, 2", got.Total, got.WithoutReason, len(want))
	}
}

func TestShowSuppressedTextAndScope(t *testing.T) {
	t.Chdir(suppressedProject(t))
	cmd := newCmd(testFactory())
	var out bytes.Buffer
	cmd.SetOut(&out)
	cmd.SetArgs([]string{"--show-suppressed", "--scope", "internal/db"})
	if err := cmd.Execute(); err != nil {
		t.Fatalf("forge lint --show-suppressed --scope internal/db: %v", err)
	}
	text := out.String()
	for _, want := range []string{
		"Suppressions declared in internal/db (read-only: nothing was linted)",
		"internal/db/doc.go:1  forge-exclude-contract-outbound-io  [forge:lint-disable-next-line; lines 2-3]",
		"    40-method DB layer; split tracked in #123",
		"internal/db/doc.go:2  contract  [forge:exclude-contract;",
		"2 suppressions, 0 with no reason.",
	} {
		if !strings.Contains(text, want) {
			t.Errorf("output lacks %q:\n%s", want, text)
		}
	}
	if strings.Contains(text, "internal/x/") || strings.Contains(text, "forge.yaml") {
		t.Errorf("--scope internal/db listed suppressions outside it:\n%s", text)
	}
}

// It is an inventory, not a lane: combined with anything that lints it would
// be unclear which ran, so those combinations are refused.
func TestShowSuppressedRefusesLintingFlags(t *testing.T) {
	for _, args := range [][]string{
		{"--show-suppressed", "--contract"},
		{"--show-suppressed", "--quiet"},
		{"--show-suppressed", "--gate-json", "g.json"},
		{"--show-suppressed", "./..."},
	} {
		cmd := newCmd(testFactory())
		cmd.SetOut(&bytes.Buffer{})
		cmd.SetErr(&bytes.Buffer{})
		cmd.SetArgs(args)
		err := cmd.Execute()
		if err == nil || !strings.Contains(err.Error(), "runs no linter") {
			t.Errorf("forge lint %v: err = %v; want a refusal", args, err)
		}
	}
}
