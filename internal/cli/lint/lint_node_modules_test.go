// Third-party Go sources vendored inside an npm package (reliant's
// web/node_modules/flatted/golang/pkg/flatted: no go.mod, so part of the
// enclosing module as far as ./... goes) used to be linted as the project's
// own, and failed govet on every machine with web/node_modules installed.

// nodeModulesProject is a clean module plus a vet-failing, type-broken Go
// package under web/node_modules.
func nodeModulesProject(t *testing.T) string {
	t.Helper()
	dir := t.TempDir()
	files := map[string]string{
		"go.mod":  "module example.com/m\n\ngo 1.24\n",
		"main.go": "package main\n\nfunc main() {}\n",
		"web/node_modules/x/bad.go": `package x

import "fmt"

func F() { fmt.Printf("%d", "not an int") }

func G() int { return undefinedSymbol }
`,
	}
	for name, body := range files {
		p := filepath.Join(dir, name)
		if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(p, []byte(body), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	return dir
}

func TestGolangciLintIgnoresNodeModules(t *testing.T) {
	if testing.Short() {
		t.Skip("runs the real golangci-lint over a temp module; runs in task test")
	}
	if _, err := exec.LookPath("golangci-lint"); err != nil {
		t.Skip("golangci-lint not on PATH")
	}
	dir := nodeModulesProject(t)
	t.Chdir(dir)
	rc := &lintRunCtx{ctx: context.Background(), cwd: dir, paths: []string{"./..."}, golangciMemo: newGolangciMemo(productionGolangciToolchain())}

	// Control: the module really does fail when node_modules is included,
	// so the assertion below is not vacuous.
	raw, err := rc.execGolangci(golangciRunArgs(nil, rc.paths))
	if err != nil {
		t.Fatalf("golangci-lint unavailable: %v", err)
	}
	if raw.err == nil {
		t.Fatalf("control: ./... over a node_modules vet failure should fail, got:\n%s", raw.combined())
	}

	fs, gated := collectGolangciLintJSON(rc)
	if gated || len(fs) != 0 {
		t.Fatalf("golangci-lint linted node_modules: gated=%v findings=%+v", gated, fs)
	}
}

func TestContractLinterIgnoresNodeModules(t *testing.T) {
	if testing.Short() {
		t.Skip("loads a temp module with go/packages; runs in task test")
	}
	dir := nodeModulesProject(t)
	t.Chdir(dir)

	if _, err := runContractAnalysisInProcess(context.Background(), []string{"./..."}, nil, contract.ExcludeGateOptions{}); err != nil {
		if strings.Contains(err.Error(), "node_modules") {
			t.Fatalf("contract linter loaded a node_modules package: %v", err)
		}
		t.Fatalf("contract analysis: %v", err)
	}
}
