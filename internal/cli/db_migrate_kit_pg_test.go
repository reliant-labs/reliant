// File: internal/cli/db_migrate_kit_pg_test.go
//
// `forge db migrate` against a REAL postgres, driven through the root command
// the way an operator runs it. Each test is a case the golang-migrate CLI —
// what the command used to shell out to — got wrong, because it skipped
// everything migratekit adds:
//
//   - a database goose migrated, meeting the baseline that replaced goose's
//     history: the CLI ran the baseline's CREATE TABLEs against goose's schema
//     and left the database dirty, instead of adopting it;
//   - a server booting with AUTO_MIGRATE after `forge db migrate up`: the CLI
//     wrote no applied-record row, so the server refused the version it had
//     applied as MISSING;
//   - the dirty-schema recovery the refusal itself prints (repair, `force`,
//     `up`), which has to keep that record in step to get through.
//
// Gated behind testing.Short(): these need a real postgres (pgtest).

package cli

import (
	"database/sql"
	"os"
	"path/filepath"
	"strings"
	"testing"

	"github.com/reliant-labs/forge/pkg/migratekit"
)

// migrateTestProject lays down a project holding files under db/migrations and
// returns its root.
func migrateTestProject(t *testing.T, files map[string]string) string {
	t.Helper()
	root, err := filepath.EvalSymlinks(t.TempDir())
	if err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(root, "forge.yaml"), []byte("name: migproj\nmodule_path: example.com/migproj\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	addMigrations(t, root, files)
	return root
}

func addMigrations(t *testing.T, root string, files map[string]string) {
	t.Helper()
	dir := filepath.Join(root, "db", "migrations")
	if err := os.MkdirAll(dir, 0o755); err != nil {
		t.Fatal(err)
	}
	for name, body := range files {
		if err := os.WriteFile(filepath.Join(dir, name), []byte(body), 0o644); err != nil {
			t.Fatal(err)
		}
	}
}

func openScratch(t *testing.T, dsn string) *sql.DB {
	t.Helper()
	db, err := sql.Open("postgres", dsn)
	if err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() { _ = db.Close() })
	return db
}

// gooseCutover is a goose history of two versions, squashed into a baseline
// that declares it, plus the first forge migration on top. The baseline's DDL
// is NOT idempotent, so running it against goose's schema fails: an adopted
// database proves the baseline's SQL did not run.
var gooseCutover = map[string]string{
	"20260201000000_baseline.up.sql": "-- forge:adopts goose 20260101000001 20260101000002\n" +
		"CREATE TABLE accounts (id INT PRIMARY KEY);\n" +
		"CREATE TABLE plans (id INT PRIMARY KEY, account_id INT REFERENCES accounts (id));\n",
	"20260202000000_add_orgs.up.sql": "CREATE TABLE orgs (id INT PRIMARY KEY);\n",
}

// gooseMigratedDatabase builds the database the last goose release left: goose's
// table as goose v3 creates it, the schema, one row per applied version, and
// a customer row the adoption must not touch.
func gooseMigratedDatabase(t *testing.T, applied ...string) (string, *sql.DB) {
	t.Helper()
	dsn := scratchDatabase(t)
	db := openScratch(t, dsn)
	stmts := []string{
		`CREATE TABLE goose_db_version (
			id integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
			version_id bigint NOT NULL,
			is_applied boolean NOT NULL,
			tstamp timestamp NOT NULL DEFAULT now()
		)`,
		"INSERT INTO goose_db_version (version_id, is_applied) VALUES (0, true)",
		"CREATE TABLE accounts (id INT PRIMARY KEY)",
		"CREATE TABLE plans (id INT PRIMARY KEY, account_id INT REFERENCES accounts (id))",
		"INSERT INTO accounts (id) VALUES (42)",
	}
	for _, v := range applied {
		stmts = append(stmts, "INSERT INTO goose_db_version (version_id, is_applied) VALUES ("+v+", true)")
	}
	for _, s := range stmts {
		if _, err := db.Exec(s); err != nil {
			t.Fatalf("build the goose database: %s: %v", s, err)
		}
	}
	return dsn, db
}

func TestDBMigrateUp_AdoptsAGooseMigratedDatabase(t *testing.T) {
	if testing.Short() {
		t.Skip("needs a real postgres server")
	}
	dsn, db := gooseMigratedDatabase(t, "20260101000001", "20260101000002")
	proj := migrateTestProject(t, gooseCutover)
	elsewhere(t)

	out, err := runForgeDB(t, "-C", proj, "db", "migrate", "up", "--dsn", dsn)
	if err != nil {
		t.Fatalf("migrate up over a goose database: %v\n%s", err, out)
	}
	for _, want := range []string{
		"ADOPTED a database goose migrated: 20260201000000_baseline.up.sql recorded as applied without running its SQL (2 goose versions verified",
		"migrations applied: 20260201000000 -> 20260202000000",
	} {
		if !strings.Contains(out, want) {
			t.Errorf("migrate up output lacks %q:\n%s", want, out)
		}
	}
	if n := countRows(t, db, `SELECT count(*) FROM information_schema.tables WHERE table_name = 'orgs'`); n != 1 {
		t.Errorf("the migration after the baseline did not run (orgs tables = %d)", n)
	}
	if n := countRows(t, db, `SELECT count(*) FROM accounts WHERE id = 42`); n != 1 {
		t.Errorf("the customer row is gone (count = %d)", n)
	}
	if n := countRows(t, db, `SELECT count(*) FROM goose_db_version`); n != 3 {
		t.Errorf("goose_db_version has %d rows, want its 3 untouched: it is the rollback target", n)
	}
	if n := countRows(t, db, `SELECT count(*) FROM schema_migrations WHERE version = 20260202000000 AND NOT dirty`); n != 1 {
		t.Error("schema_migrations is not clean at 20260202000000")
	}

	// Adoption happens once; the next run is an ordinary no-op.
	out, err = runForgeDB(t, "-C", proj, "db", "migrate", "up", "--dsn", dsn)
	if err != nil || !strings.Contains(out, "no pending migrations (version=20260202000000)") || strings.Contains(out, "ADOPTED") {
		t.Errorf("second migrate up: err=%v, want a plain no-op:\n%s", err, out)
	}
}

// A goose database BEHIND the baseline is refused, naming the version, and
// nothing runs.
func TestDBMigrateUp_RefusesAGooseDatabaseBehindTheBaseline(t *testing.T) {
	if testing.Short() {
		t.Skip("needs a real postgres server")
	}
	dsn, db := gooseMigratedDatabase(t, "20260101000001")
	proj := migrateTestProject(t, gooseCutover)

	out, err := runForgeDB(t, "-C", proj, "db", "migrate", "up", "--dsn", dsn)
	if err == nil {
		t.Fatalf("migrate up adopted a goose database missing a declared version:\n%s", out)
	}
	for _, want := range []string{"has NOT applied 1 of the 2 goose migration(s) the baseline lists: 20260101000002", "NOTHING WAS APPLIED"} {
		if !strings.Contains(err.Error(), want) {
			t.Errorf("refusal lacks %q:\n%v", want, err)
		}
	}
	if n := countRows(t, db, `SELECT count(*) FROM information_schema.tables WHERE table_name = 'orgs'`); n != 0 {
		t.Error("a refused adoption applied the next migration anyway")
	}
}

// `forge db migrate up` keeps the applied record a server's AutoMigrate checks,
// so the server boots on a database the CLI migrated.
func TestDBMigrateUp_LeavesARecordAServerBootAccepts(t *testing.T) {
	if testing.Short() {
		t.Skip("needs a real postgres server")
	}
	dsn := scratchDatabase(t)
	proj := migrateTestProject(t, map[string]string{"20260101000000_accounts.up.sql": "CREATE TABLE accounts (id INT PRIMARY KEY);"})
	migrations := os.DirFS(filepath.Join(proj, "db", "migrations"))
	pool := openScratch(t, dsn)

	// The server booted first, so the record exists.
	if err := migratekit.AutoMigrate(migrations, ".")(pool, nil); err != nil {
		t.Fatalf("first boot: %v", err)
	}
	addMigrations(t, proj, map[string]string{"20260102000000_plans.up.sql": "CREATE TABLE plans (id INT PRIMARY KEY);"})
	if out, err := runForgeDB(t, "-C", proj, "db", "migrate", "up", "--dsn", dsn); err != nil {
		t.Fatalf("migrate up: %v\n%s", err, out)
	}
	if err := migratekit.AutoMigrate(migrations, ".")(pool, nil); err != nil {
		t.Fatalf("a server booting after `forge db migrate up` refused the database: %v", err)
	}
}

// The recovery the dirty refusal prints, followed step by step through the
// CLI: fail part-way, get refused with the steps, repair by hand, force, up.
func TestDBMigrate_DirtyRecoveryRunsThroughForceAndUp(t *testing.T) {
	if testing.Short() {
		t.Skip("needs a real postgres server")
	}
	dsn := scratchDatabase(t)
	db := openScratch(t, dsn)
	proj := migrateTestProject(t, map[string]string{
		"20260101000000_accounts.up.sql": "CREATE TABLE accounts (id INT PRIMARY KEY);",
		"20260102000000_ledger.up.sql":   "CREATE TABLE ledger (id INT PRIMARY KEY);\nINSERT INTO no_such_table VALUES (1);",
	})
	run := func(args ...string) (string, error) {
		return runForgeDB(t, append([]string{"-C", proj, "db", "migrate"}, append(args, "--dsn", dsn)...)...)
	}

	if out, err := run("status"); err != nil || !strings.Contains(out, "version: none") || !strings.Contains(out, "pending: 2") {
		t.Errorf("status on a fresh database: err=%v\n%s", err, out)
	}
	if out, err := run("up"); err == nil {
		t.Fatalf("up over a broken migration succeeded:\n%s", out)
	}
	_, err := run("up")
	if err == nil || !strings.Contains(err.Error(), "forge db migrate force 20260102000000") {
		t.Fatalf("up on the dirty database must print the recovery naming `forge db migrate force 20260102000000`; got %v", err)
	}
	if out, err := run("version"); err != nil || strings.TrimSpace(out) != "20260102000000 (dirty)" {
		t.Errorf("version on the dirty database = %q, %v; want \"20260102000000 (dirty)\"", out, err)
	}

	// Step 1: repair what the migration intended. Step 2: force it.
	if _, err := db.Exec("CREATE TABLE ledger (id INT PRIMARY KEY)"); err != nil {
		t.Fatal(err)
	}
	if out, err := run("force", "20260102000000"); err != nil || !strings.Contains(out, "forced version 20260102000000") {
		t.Fatalf("force: %v\n%s", err, out)
	}
	// Step 3: up — through the next release's migration.
	addMigrations(t, proj, map[string]string{"20260103000000_audit.up.sql": "CREATE TABLE audit (id INT PRIMARY KEY);"})
	out, err := run("up")
	if err != nil {
		t.Fatalf("up after the documented recovery: %v\n%s", err, out)
	}
	if !strings.Contains(out, "migrations applied: 20260102000000 -> 20260103000000") {
		t.Errorf("up output:\n%s", out)
	}
	if out, err := run("version"); err != nil || strings.TrimSpace(out) != "20260103000000" {
		t.Errorf("version = %q, %v; want 20260103000000", out, err)
	}
	if out, err := run("status"); err != nil || !strings.Contains(out, "version: 20260103000000") || !strings.Contains(out, "pending: 0") {
		t.Errorf("status after the recovery: err=%v\n%s", err, out)
	}
}
