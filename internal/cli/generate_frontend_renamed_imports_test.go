// The repoint pass edits files forge OWNS as well as files it does not.
// A Tier-1 file carries a forge:hash marker certifying its bytes, so an
// edit that changes the bytes without re-certifying them leaves the file
// claiming a hash it no longer has — and the NEXT run's stomp guard reads
// that as a hand-edit and aborts, on forge's own output.
//
// That is not hypothetical. It is how a project upgrading across the
// `_gen` rename got stuck: an emitter declines to overwrite a pristine
// render of an older vintage (the non-destructive default), the repoint
// pass rewrites its import line anyway, and `forge generate` then refuses
// to run until the user discards edits nobody made.
func TestRewriteRenamedImportsInFile_RestampsTier1Marker(t *testing.T) {
	dir := t.TempDir()
	rel := filepath.Join("frontends", "web", "src", "mocks", "scenarios", "index_gen.ts")
	path := filepath.Join(dir, rel)
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		t.Fatal(err)
	}

	body := "// Code generated by forge. DO NOT EDIT.\n" +
		"// forge-owned: regenerated every run — do not edit\n\n" +
		"import type { Scenario } from \"../scenario-types\";\n\n" +
		"export const scenarios: Scenario[] = [];\n"
	stamped, ok := checksums.Stamp(rel, []byte(body))
	if !ok {
		t.Fatalf("Stamp(%s) reported the path unstampable", rel)
	}
	if err := os.WriteFile(path, stamped, 0o644); err != nil {
		t.Fatal(err)
	}
	if got := checksums.Verify(stamped); got != checksums.Pristine {
		t.Fatalf("fixture is not pristine before the rewrite: %v", got)
	}

	renames := []renamedFrontendModule{
		{old: "../scenario-types", new: "../scenario-types_gen"},
	}
	if !rewriteRenamedImportsInFile(path, renames) {
		t.Fatal("rewriteRenamedImportsInFile reported no change; expected the specifier to be repointed")
	}

	after, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(string(after), `"../scenario-types_gen"`) {
		t.Errorf("specifier was not repointed:\n%s", after)
	}
	// The whole point: the marker must certify the bytes on disk, so the
	// next run sees forge's own output rather than a phantom hand-edit.
	if got := checksums.Verify(after); got != checksums.Pristine {
		embedded, _ := checksums.ExtractMarker(after)
		t.Errorf("after repoint, marker does not certify the written bytes: Verify = %v\n  embedded  = %s\n  bodyHash  = %s\n  (the next `forge generate` will report this file as hand-edited)",
			got, embedded, checksums.BodyHash(after))
	}
}

// A file forge does NOT own has no marker, and the repoint pass must not
// invent one: stamping a user's connect.ts would claim forge authorship of
// a scaffold-once file and make the stomp guard start policing it.
func TestRewriteRenamedImportsInFile_LeavesUnmarkedFileUnstamped(t *testing.T) {
	dir := t.TempDir()
	path := filepath.Join(dir, "connect.ts")
	body := "// yours: scaffolded once\nconst t = require(\"@/lib/mock-transport\");\n"
	if err := os.WriteFile(path, []byte(body), 0o644); err != nil {
		t.Fatal(err)
	}

	renames := []renamedFrontendModule{
		{old: "@/lib/mock-transport", new: "@/lib/mock-transport_gen"},
	}
	if !rewriteRenamedImportsInFile(path, renames) {
		t.Fatal("expected the specifier to be repointed")
	}

	after, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(string(after), `"@/lib/mock-transport_gen"`) {
		t.Errorf("specifier was not repointed:\n%s", after)
	}
	if _, found := checksums.ExtractMarker(after); found {
		t.Errorf("repoint pass stamped a file forge does not own:\n%s", after)
	}
}

// Re-certifying must not become a way for forge to bless a hand-edit. A
// Tier-1 file the user has edited is the stomp guard's to report; if the
// repoint pass re-stamped it, the guard would go quiet and the user's
// deviation from the template would be silently adopted as forge's own.
// So the import is repointed (a dangling specifier helps nobody) and the
// file is left uncertified.
func TestRewriteRenamedImportsInFile_DoesNotBlessHandEdit(t *testing.T) {
	dir := t.TempDir()
	rel := filepath.Join("frontends", "web", "src", "mocks", "scenarios", "index_gen.ts")
	path := filepath.Join(dir, rel)
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		t.Fatal(err)
	}

	body := "// Code generated by forge. DO NOT EDIT.\n\nimport type { Scenario } from \"../scenario-types\";\n"
	stamped, ok := checksums.Stamp(rel, []byte(body))
	if !ok {
		t.Fatalf("Stamp(%s) reported the path unstampable", rel)
	}
	handEdited := append(stamped, []byte("\n// the user changed this\n")...)
	if err := os.WriteFile(path, handEdited, 0o644); err != nil {
		t.Fatal(err)
	}
	if got := checksums.Verify(handEdited); got != checksums.Modified {
		t.Fatalf("fixture should read as hand-edited before the rewrite, got %v", got)
	}

	renames := []renamedFrontendModule{
		{old: "../scenario-types", new: "../scenario-types_gen"},
	}
	if !rewriteRenamedImportsInFile(path, renames) {
		t.Fatal("expected the specifier to be repointed even on a hand-edited file")
	}

	after, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(string(after), `"../scenario-types_gen"`) {
		t.Errorf("specifier was not repointed:\n%s", after)
	}
	if !strings.Contains(string(after), "// the user changed this") {
		t.Errorf("the user's edit was lost:\n%s", after)
	}
	if got := checksums.Verify(after); got != checksums.Modified {
		t.Errorf("hand-edited file was re-certified (Verify = %v); the stomp guard can no longer see the user's edit", got)
	}
}

// Idempotence is what keeps `forge generate` twice in a row clean: after a
// rewrite no old specifier remains, so the second pass must find nothing
// and leave the bytes untouched — marker included.
func TestRewriteRenamedImportsInFile_SecondPassIsNoOp(t *testing.T) {
	dir := t.TempDir()
	rel := filepath.Join("frontends", "web", "src", "lib", "mock-transport_gen.ts")
	path := filepath.Join(dir, rel)
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		t.Fatal(err)
	}
	body := "// Code generated by forge. DO NOT EDIT.\n\nimport * as s from \"../mocks/scenarios\";\n"
	stamped, ok := checksums.Stamp(rel, []byte(body))
	if !ok {
		t.Fatalf("Stamp(%s) reported the path unstampable", rel)
	}
	if err := os.WriteFile(path, stamped, 0o644); err != nil {
		t.Fatal(err)
	}

	renames := []renamedFrontendModule{
		{old: "../mocks/scenarios", new: "../mocks/scenarios/index_gen"},
	}
	if !rewriteRenamedImportsInFile(path, renames) {
		t.Fatal("first pass reported no change")
	}
	first, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	if rewriteRenamedImportsInFile(path, renames) {
		t.Error("second pass rewrote the file again; the repoint must be idempotent")
	}
	second, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	if string(first) != string(second) {
		t.Errorf("second pass changed the bytes:\n--- first ---\n%s\n--- second ---\n%s", first, second)
	}
}
