// File: internal/cli/generate_cleanup_upgrade_managed_test.go
//
// Tests that `forge generate`'s stale-artifact sweep does NOT flag
// files managed by `forge project upgrade` as stale. The regression these
// tests pin: pre-fix, `forge generate` warned that 7 actively-used
// files (cmd/main.go, .golangci.yml, .github/CODEOWNERS, etc.) were
// "stale" and would-be-deleted with --force-cleanup. The user's only
// workaround was hand-flipping `forked: true` in checksums.json, which
// silenced the warning but also broke `forge project upgrade`'s ability to
// re-emit the file on the next version bump.
//
// The fix consults generator.UpgradeManagedPaths() — the union over
// every kind/binary combination of the upgrade-managed file list —
// and excludes those paths from the deletion candidate list. (The
// manifest-era inverse "tracked but missing" finding is gone with the
// manifest: nothing records absent files anymore.)
package cli

import (
	"path/filepath"
	"reflect"
	"sort"
	"testing"

	"github.com/reliant-labs/forge/internal/checksums"
	"github.com/reliant-labs/forge/internal/codegen"
	"github.com/reliant-labs/forge/internal/generator"
)

// TestCleanupStaleArtifacts_SkipsUpgradeManagedPaths is the headline
// pin: cmd/main.go, .golangci.yml, and .github/CODEOWNERS all carry
// forge's certification marker AND none are written by this `forge
// generate` run AND no owner gate covers them — pre-fix the cleanup
// pass would have flagged them as stale. Post-fix they're excluded
// because UpgradeManagedPaths() lists them.
func TestCleanupStaleArtifacts_SkipsUpgradeManagedPaths(t *testing.T) {
	resetCleanupRunState(t)
	dir := t.TempDir()

	managed := []string{
		// The command tree moved to cmd/<bin>/cmd; the name-less union the
		// cleanup uses yields the bare cmd/cmd/<file>.go form. (main.go is NOT
		// here — it is scaffold-once OWNED code, not upgrade-managed.)
		//
		// db.go and version.go are in this list for the scaffold-once
		// MIGRATION reason rather than because upgrade emits them: both were
		// Tier-1 in older projects, so a marker-bearing copy sits in the tree
		// that no run rewrites. That is precisely the shape the sweep would
		// otherwise call stale and delete.
		"cmd/cmd/db.go",
		"cmd/cmd/version.go",
		"cmd/cmd/root.go",
		".golangci.yml",
		".github/CODEOWNERS",
		".github/pull_request_template.md",
		".github/workflows/e2e.yml",
	}
	// Put each managed file on disk WITH a pristine marker so the
	// marker scan really does see them — we want to prove the
	// UpgradeManagedPaths exclusion fires, not "no marker, no scan".
	for _, p := range managed {
		full := filepath.Join(dir, p)
		mustMkdir(t, filepath.Dir(full))
		mustWriteStamped(t, full, p, "// Code generated by forge. DO NOT EDIT.\npackage main\n")
	}
	cs := &checksums.FileChecksums{}

	ctx := newCleanupCtx(dir, cs, []codegen.ServiceDef{{Name: "SomeService"}}, nil)
	sweep, err := cleanupStaleArtifacts(ctx)
	if err != nil {
		t.Fatalf("cleanup: %v", err)
	}
	if len(sweep.Removed) != 0 {
		t.Errorf("removed = %v, want empty (upgrade-managed paths must not be flagged stale)", sweep.Removed)
	}
	if len(sweep.HandEdited) != 0 {
		t.Errorf("handEdited = %v, want empty", sweep.HandEdited)
	}
}

// TestUpgradeManagedPaths_CoversReportedFiles confirms the helper
// returns at least the 7 paths the cp-forge project audit-cleanup agent
// reported as false-positive stale candidates. Pins the contract that
// these paths are recognized as upgrade-managed (and so cleanup
// excludes them). If a future refactor moves any of these to be
// `forge generate`-emitted, that emitter will also call
// WrittenThisRun for the path and the exclusion becomes redundant
// (safe) — but we still want explicit coverage here so the
// inventory doesn't silently shrink.
func TestUpgradeManagedPaths_CoversReportedFiles(t *testing.T) {
	got := generator.UpgradeManagedPaths()
	want := []string{
		// NOTE: cmd/main.go is deliberately NOT here. The composition-root
		// main.go is SCAFFOLD-ONCE OWNED code (write-if-absent, hand-wired,
		// carries no generated banner), not an upgrade-managed forge file — so
		// the cleanup sweep never sees a marker on it and there is nothing to
		// exclude. This reverses the interim registry-kill state that made
		// main.go a generated/managed file.
		".golangci.yml",
		".github/CODEOWNERS",
		".github/pull_request_template.md",
		".github/workflows/e2e.yml",
		// Tier-1 command-tree files under upgrade ownership. The tree moved
		// to cmd/<bin>/cmd; the name-less UpgradeManagedPaths union yields the
		// bare cmd/cmd/<file>.go form.
		"cmd/cmd/root.go",
		"cmd/cmd/root.go",
		// These four are in the set for a DIFFERENT reason than their
		// neighbours, and the difference is the point. None is
		// upgrade-managed at all anymore — each became scaffold-once
		// user-owned when its invariant half moved into a forge library
		// (pkg/serverkit, pkg/cmdkit, pkg/migratekit). They are listed
		// because every project scaffolded BEFORE those splits has a copy on
		// disk still carrying forge's certification markers, and nothing
		// writes them anymore: the sweep would read "certified, not written
		// this run" as stale and --force-cleanup would DELETE the user's
		// serve pipeline, ServeSpec, version stamp and migration policy.
		"cmd/cmd/serve.go",
		"cmd/cmd/server.go",
		"cmd/cmd/version.go",
		"cmd/cmd/db.go",
		// Tier-2 scaffolds also upgrade-managed.
		"buf.yaml",
		"Taskfile.yml",
		"Dockerfile",
		"docker-compose.yml",
		".gitignore",
		"deploy/observability/otel-collector.yaml",
		"deploy/observability/otel-profiles.yaml",
		"deploy/observability/profiles-schema.sql",
	}
	var missing []string
	for _, p := range want {
		if !got[p] {
			missing = append(missing, p)
		}
	}
	if len(missing) > 0 {
		sort.Strings(missing)
		t.Errorf("UpgradeManagedPaths() missing expected entries: %v", missing)
	}
}

// TestCleanupStaleArtifacts_StillFlagsRealStaleAfterExclusion is the
// negative case: the exclusion is narrowly scoped to upgrade-managed
// paths. A real codegen-emitted (certified) file that the run didn't
// re-write must still surface as a candidate so the user can either
// --force-cleanup or rename their service back.
func TestCleanupStaleArtifacts_StillFlagsRealStaleAfterExclusion(t *testing.T) {
	resetCleanupRunState(t)
	dir := t.TempDir()

	// Mix one upgrade-managed path with one real stale codegen file —
	// both certified. cmd/cmd/serve.go is genuinely upgrade-managed (main.go is
	// no longer — it's scaffold-once owned — so it can't stand in here).
	mustMkdir(t, filepath.Join(dir, "cmd", "cmd"))
	mustWriteStamped(t, filepath.Join(dir, "cmd", "cmd", "serve.go"), "cmd/cmd/serve.go",
		"// Code generated by forge. DO NOT EDIT.\npackage cmd\n")

	mustMkdir(t, filepath.Join(dir, "internal", "handlers", "renamed"))
	stale := filepath.Join(dir, "internal", "handlers", "renamed", "handlers_crud_gen.go")
	mustWriteStamped(t, stale, "handlers/renamed/handlers_crud_gen.go",
		"// Code generated by forge. DO NOT EDIT.\npackage renamed\n")

	cs := &checksums.FileChecksums{}

	ctx := newCleanupCtx(dir, cs, []codegen.ServiceDef{{Name: "KeptService"}}, nil)
	sweep, err := cleanupStaleArtifacts(ctx)
	if err != nil {
		t.Fatalf("cleanup: %v", err)
	}
	// Only the renamed handler should be flagged stale; cmd/cmd/serve.go
	// excluded by UpgradeManagedPaths.
	want := []string{"internal/handlers/renamed/handlers_crud_gen.go"}
	if !reflect.DeepEqual(sweep.Removed, want) {
		t.Errorf("removed = %v, want %v", sweep.Removed, want)
	}
}

