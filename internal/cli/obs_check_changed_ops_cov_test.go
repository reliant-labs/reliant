func TestMapOpChangesSkipsOpsTheCheckoutNoLongerDefines(t *testing.T) {
	dir, first, second := covAOpsRepo(t)
	ctx := context.Background()
	if err := os.Remove(filepath.Join(dir, "internal/billing/middleware_gen.go")); err != nil {
		t.Fatal(err)
	}
	cmd := exec.Command("git", "-c", "user.name=t", "-c", "user.email=t@t", "commit", "-qam", "drop the decorator")
	cmd.Dir = dir
	cmd.Env = append(os.Environ(), "GIT_CONFIG_GLOBAL=/dev/null", "GIT_CONFIG_NOSYSTEM=1")
	if out, err := cmd.CombinedOutput(); err != nil {
		t.Fatalf("%v\n%s", err, out)
	}
	// billing.Charge exists at first..second but the checkout's index no
	// longer has the decorator, so nothing of it is left to judge.
	ch := mapOpChanges(ctx, dir, first, second)
	if !ch.Read || len(ch.Ops) != 0 || ch.Base != first {
		t.Errorf("an op the checkout no longer defines must not be reported: %+v", ch)
	}
}
