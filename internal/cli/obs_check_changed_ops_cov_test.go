// covAOpsRepo is a forge project (one component with a generated decorator) in
// a git repository with two commits: covABillingService, then a change to
// Charge's body. It returns the dir and both commit ids, and chdirs into it.
func covAOpsRepo(t *testing.T) (dir, first, second string) {
	t.Helper()
	testkit.Slow(t, "runs git in a temporary repository")
	dir = t.TempDir()
	git := func(args ...string) string {
		t.Helper()
		cmd := exec.Command("git", args...)
		cmd.Dir = dir
		cmd.Env = append(os.Environ(), "GIT_AUTHOR_NAME=t", "GIT_AUTHOR_EMAIL=t@t", "GIT_COMMITTER_NAME=t", "GIT_COMMITTER_EMAIL=t@t",
			"GIT_CONFIG_GLOBAL=/dev/null", "GIT_CONFIG_NOSYSTEM=1")
		out, err := cmd.CombinedOutput()
		if err != nil {
			t.Fatalf("git %v: %v\n%s", args, err, out)
		}
		return strings.TrimSpace(string(out))
	}
	write := func(rel, body string) {
		t.Helper()
		if err := os.MkdirAll(filepath.Dir(filepath.Join(dir, rel)), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(filepath.Join(dir, rel), []byte(body), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	git("init", "-q", "-b", "main")
	write("forge.yaml", "name: shop\nmodule_path: example.com/app\n")
	write("internal/billing/contract.go", covABillingContract)
	write("internal/billing/service.go", covABillingService)
	write("internal/billing/middleware_gen.go", covABillingMW)
	git("add", ".")
	git("commit", "-q", "-m", "first")
	first = git("rev-parse", "HEAD")
	write("internal/billing/service.go", covABillingChanged)
	git("add", ".")
	git("commit", "-q", "-m", "fix(billing): guard negative charges (#7)")
	second = git("rev-parse", "HEAD")
	t.Chdir(dir)
	return dir, first, second
}

func covAFakeLedger(t *testing.T, data releasetimeline.Data, loadErr, openErr error) {
	t.Helper()
	prev := openReleasesBackend
	openReleasesBackend = func(context.Context, string) (releasesBackend, error) {
		if openErr != nil {
			return releasesBackend{}, openErr
		}
		return releasesBackend{Name: "fake", Source: covALedgerSource{data, loadErr}}, nil
	}
	t.Cleanup(func() { openReleasesBackend = prev })
}

type covALedgerSource struct {
	data releasetimeline.Data
	err  error
}

func (s covALedgerSource) Load(context.Context, string, time.Time) (releasetimeline.Data, error) {
	return s.data, s.err
}

func covASingleOp(t *testing.T, ch opChanges) changedOp {
	t.Helper()
	if !ch.Read || len(ch.Ops) != 1 {
		t.Fatalf("changes = %+v, want one mapped op", ch)
	}
	return ch.Ops[0]
}

