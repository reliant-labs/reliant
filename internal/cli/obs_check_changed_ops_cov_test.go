func TestCheckoutOpChangesLocalEnvMapsEditsSinceP(t *testing.T) {
	dir, first, second := covAOpsRepo(t)
	_ = dir
	ctx := context.Background()

	// P between the two commits' committer dates is awkward to fake, so use
	// the one that is always true: P in the far future means the base is the
	// newest commit, and with a clean tree nothing changed.
	future := time.Now().Add(24 * time.Hour)
	ch := checkoutOpChanges(ctx, "dev", releasehealth.Subject{PromotedAt: future})
	if !ch.Read || len(ch.Ops) != 0 || ch.Base != second {
		t.Errorf("clean tree at HEAD: %+v, want read, no ops, base %s", ch, second[:7])
	}

	// An uncommitted edit to Charge is named, with the pseudo-commit "".
	if err := os.WriteFile(filepath.Join(dir, "internal/billing/service.go"), []byte(covABillingChanged+"\n// edit\nfunc (s *service) unused() {}\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	ch = checkoutOpChanges(ctx, "dev", releasehealth.Subject{PromotedAt: future})
	op := covASingleOp(t, ch)
	if op.Name != "billing.Charge" || op.Kind != releasehealth.OpKindComponent || len(op.Commits) == 0 || op.Commits[0].SHA != "" {
		t.Errorf("op = %+v: an uncommitted edit is the pseudo-commit with no sha", op)
	}

	// P before every commit: there is no base to diff against.
	ch = checkoutOpChanges(ctx, "dev", releasehealth.Subject{PromotedAt: time.Date(2001, 1, 1, 0, 0, 0, 0, time.UTC)})
	if ch.Read || len(ch.NotEvaluated) != 1 || !strings.Contains(ch.NotEvaluated[0], "no commit of HEAD predates 2001-01-01T00:00:00Z") {
		t.Errorf("changes = %+v", ch)
	}
	_ = first
}

func TestCheckoutOpChangesPromotionMapsTheLedgersRange(t *testing.T) {
	_, first, second := covAOpsRepo(t)
	ctx := context.Background()
	rel := func(v, commit string) release.Release {
		r := release.Release{Version: v}
		r.Git.Commit = commit
		return r
	}
	data := releasetimeline.Data{
		Env:        "prod",
		Releases:   []release.Release{rel("v1", first), rel("v2", second)},
		Promotions: []release.Promotion{{ID: "p1", Env: "prod", Release: "v1"}, {ID: "p2", Env: "prod", Release: "v2"}},
	}

	t.Run("the range between the two releases", func(t *testing.T) {
		covAFakeLedger(t, data, nil, nil)
		ch := checkoutOpChanges(ctx, "prod", releasehealth.Subject{PromotionID: "p2", Release: "v2", PreviousRelease: "v1"})
		op := covASingleOp(t, ch)
		if op.Name != "billing.Charge" || len(op.Commits) != 1 || op.Commits[0].SHA != second || op.Commits[0].PR != 7 ||
			op.Commits[0].Subject != "fix(billing): guard negative charges (#7)" {
			t.Errorf("op = %+v", op)
		}
		if ch.Base != first {
			t.Errorf("base = %s, want %s", ch.Base, first)
		}
	})
	t.Run("a subject the timeline does not know falls back to the ledger's releases", func(t *testing.T) {
		covAFakeLedger(t, data, nil, nil)
		ch := checkoutOpChanges(ctx, "prod", releasehealth.Subject{Release: "v2", PreviousRelease: "v1", GitCommit: second})
		if op := covASingleOp(t, ch); op.Name != "billing.Charge" {
			t.Errorf("op = %+v", op)
		}
	})
	t.Run("a range this checkout does not hold", func(t *testing.T) {
		d := data
		d.Releases = []release.Release{rel("v1", first), rel("v2", strings.Repeat("ab", 20))}
		covAFakeLedger(t, d, nil, nil)
		ch := checkoutOpChanges(ctx, "prod", releasehealth.Subject{Release: "v2", PreviousRelease: "v1"})
		if ch.Read || len(ch.NotEvaluated) != 1 || !strings.Contains(ch.NotEvaluated[0], "the release's commits are not in this checkout (") {
			t.Errorf("changes = %+v", ch)
		}
	})
}

func TestPromotionRangeSayswhyItCannotLook(t *testing.T) {
	ctx := context.Background()
	rel := func(v, commit string) release.Release {
		r := release.Release{Version: v}
		r.Git.Commit = commit
		return r
	}
	tests := []struct {
		name     string
		data     releasetimeline.Data
		loadErr  error
		openErr  error
		subject  releasehealth.Subject
		wantFrom string
		wantTo   string
		wantSkip string
	}{
		{name: "the ledger cannot be opened", openErr: errors.New("no ledger"), subject: releasehealth.Subject{Release: "v2"},
			wantSkip: "the release ledger of prod could not be opened: no ledger"},
		{name: "the ledger cannot be read", loadErr: errors.New("timeout"), subject: releasehealth.Subject{Release: "v2"},
			wantSkip: "the release ledger of prod could not be read: timeout"},
		{name: "no previous release in the ledger", data: releasetimeline.Data{Releases: []release.Release{rel("v2", "bbb")}},
			subject: releasehealth.Subject{Release: "v2", PreviousRelease: "v1"}, wantSkip: "no commit range is recorded for v2 (the release before it, or its commit, is not in the ledger)"},
		{name: "a promotion with no range and no commit", subject: releasehealth.Subject{PromotionID: "p9"},
			wantSkip: "no commit range is recorded for promotion p9"},
		{name: "releases named by the subject", data: releasetimeline.Data{Releases: []release.Release{rel("v1", "aaa"), rel("v2", "bbb")}},
			subject: releasehealth.Subject{Release: "v2", PreviousRelease: "v1"}, wantFrom: "aaa", wantTo: "bbb"},
		{name: "the subject's own commit beats the ledger's", data: releasetimeline.Data{Releases: []release.Release{rel("v1", "aaa"), rel("v2", "bbb")}},
			subject: releasehealth.Subject{Release: "v2", PreviousRelease: "v1", GitCommit: "ccc"}, wantFrom: "aaa", wantTo: "ccc"},
	}
	for _, tc := range tests {
		t.Run(tc.name, func(t *testing.T) {
			covAFakeLedger(t, tc.data, tc.loadErr, tc.openErr)
			from, to, skip := promotionRange(ctx, "prod", tc.subject)
			if tc.wantSkip != "" {
				if from != "" || to != "" || len(skip.NotEvaluated) != 1 || !strings.Contains(skip.NotEvaluated[0], tc.wantSkip) {
					t.Errorf("from=%q to=%q skip=%+v, want skip containing %q", from, to, skip, tc.wantSkip)
				}
				return
			}
			if from != tc.wantFrom || to != tc.wantTo || skip.Read || len(skip.NotEvaluated) != 0 {
				t.Errorf("from=%q to=%q skip=%+v, want %q..%q", from, to, skip, tc.wantFrom, tc.wantTo)
			}
		})
	}
}

func TestPromotionRangeAMoveBehindMapsTheCommitsItTakesAway(t *testing.T) {
	// v2 then v1 again: the second promotion is a rollback, so the commits
	// it changes are the ones v2 added, walked from v2 back to v1.
	rel := func(v, commit string) release.Release {
		r := release.Release{Version: v}
		r.Git.Commit = commit
		return r
	}
	r1, r2 := rel("v1", "aaa"), rel("v2", "bbb")
	r2.CreatedAt = time.Date(2026, 10, 2, 0, 0, 0, 0, time.UTC)
	r1.CreatedAt = time.Date(2026, 10, 1, 0, 0, 0, 0, time.UTC)
	at := time.Date(2026, 10, 3, 0, 0, 0, 0, time.UTC)
	data := releasetimeline.Data{
		Env:      "prod",
		Releases: []release.Release{r1, r2},
		Promotions: []release.Promotion{
			{ID: "p1", Env: "prod", Release: "v1", PromotedAt: at},
			{ID: "p2", Env: "prod", Release: "v2", PromotedAt: at.Add(time.Hour)},
			{ID: "p3", Env: "prod", Release: "v1", PromotedAt: at.Add(2 * time.Hour)},
		},
	}
	covAFakeLedger(t, data, nil, nil)
	from, to, skip := promotionRange(context.Background(), "prod", releasehealth.Subject{PromotionID: "p3"})
	if len(skip.NotEvaluated) != 0 || from != "aaa" || to != "bbb" {
		t.Errorf("from=%q to=%q skip=%+v: a rollback to v1 maps v2's commits (bbb..aaa reversed to the range moved over)", from, to, skip)
	}
}

