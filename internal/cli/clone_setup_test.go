// cloneSetupRepo is a git clone holding a forge project that every piece of
// forge's per-clone setup would act on: a forge-managed pre-commit hook
// (core.hooksPath) and forge.yaml (the generated-file merge driver's
// info/attributes routes).
func cloneSetupRepo(t *testing.T) string {
	t.Helper()
	isolateGit(t)
	t.Setenv(mergeDriverOptOutEnv, "")
	repo, err := filepath.EvalSymlinks(t.TempDir())
	if err != nil {
		t.Fatal(err)
	}
	gitOut(t, repo, "init", "-q")
	writeTestFile(t, filepath.Join(repo, "forge.yaml"), "name: svc\nmodule_path: example.com/svc\n")
	writeTestFile(t, filepath.Join(repo, ".githooks", "pre-commit"),
		"#!/bin/sh\n# forge-managed git pre-commit hook — regenerated by `forge generate`.\nexit 0\n")
	return repo
}

// cloneGitSetup reads what forge's per-clone setup writes: the repository
// config and info/attributes ("<absent>" when the file does not exist).
func cloneGitSetup(t *testing.T, repo string) map[string]string {
	t.Helper()
	got := map[string]string{}
	for _, rel := range []string{filepath.Join(".git", "config"), filepath.Join(".git", "info", "attributes")} {
		body, err := os.ReadFile(filepath.Join(repo, rel))
		switch {
		case os.IsNotExist(err):
			got[rel] = "<absent>"
		case err != nil:
			t.Fatal(err)
		default:
			got[rel] = string(body)
		}
	}
	return got
}

// A command that only takes a heavy slot, or only reads the project, must
// leave the clone's git configuration alone. Every forge command used to
// point the merge driver at itself and activate the hooks as a side effect,
// so `forge slot run` and `forge env list` rewrote .git/config — shared by
// every linked worktree, and raced by every agent working in one.
func TestReadOnlyCommandsLeaveTheCloneGitSetupAlone(t *testing.T) {
	for _, args := range [][]string{
		{"slot", "run", "--", "true"},
		{"env", "list"},
		{"generate", "--plan"},
	} {
		t.Run(strings.Join(args, " "), func(t *testing.T) {
			if args[0] == "slot" && runtime.GOOS == "windows" {
				t.Skip("runs `true`")
			}
			repo := cloneSetupRepo(t)
			clearProjectDir(t)
			before := cloneGitSetup(t, repo)

			if _, err := runForge(t, append([]string{"-C", repo}, args...)...); err != nil && args[0] == "slot" {
				t.Fatalf("forge %s: %v", strings.Join(args, " "), err)
			}

			after := cloneGitSetup(t, repo)
			for file, want := range before {
				if after[file] != want {
					t.Errorf("forge %s rewrote %s:\n--- before\n%s\n--- after\n%s", strings.Join(args, " "), file, want, after[file])
				}
			}
		})
	}
}

// The setup still happens, on the commands that write the files it exists
// for. `project disown` writes .forge/disowned.json; the path need not exist
// for the root pre-run to have configured the clone first.
func TestWritingCommandsStillSetUpTheClone(t *testing.T) {
	if testing.Short() {
		t.Skip("builds real git repositories; runs in task test")
	}
	repo := cloneSetupRepo(t)
	clearProjectDir(t)
	_, _ = runForge(t, "-C", repo, "project", "disown", "no-such-file_gen.go", "--reason", "test")

	after := cloneGitSetup(t, repo)
	if !strings.Contains(after[filepath.Join(".git", "info", "attributes")], mergeAttributesBegin) {
		t.Errorf("a writing command did not route generated files to the merge driver:\n%s", after[filepath.Join(".git", "info", "attributes")])
	}
	if got := gitOut(t, repo, "config", "--local", "--default", "", "core.hooksPath"); got != ".githooks" {
		t.Errorf("a writing command did not activate forge's hooks: core.hooksPath = %q", got)
	}
}

// Which commands may set up the clone, read off the real command tree.
func TestConfiguresCloneCommandSet(t *testing.T) {
	root := newTestRootCmd(t)
	for _, tc := range []struct {
		path  string
		flags map[string]string
		want  bool
	}{
		{path: "generate", want: true},
		{path: "generate", flags: map[string]string{"check": "true"}, want: false},
		{path: "generate", flags: map[string]string{"plan": "true"}, want: false},
		{path: "generate", flags: map[string]string{"dry-run": "true"}, want: false},
		{path: "scaffold", want: true},
		{path: "scaffold", flags: map[string]string{"dry-run": "true"}, want: false},
		{path: "scaffold service", want: true},
		{path: "scaffold package", flags: map[string]string{"dry-run": "true"}, want: false},
		{path: "project disown", want: true},
		{path: "project disown", flags: map[string]string{"dry-run": "true"}, want: false},
		{path: "project delete service", want: true},
		{path: "project delete service", flags: map[string]string{"dry-run": "true"}, want: false},
		{path: "package new", want: true},
		{path: "package new", flags: map[string]string{"dry-run": "true"}, want: false},
		{path: "slot run", want: false},
		{path: "env status", want: false},
		{path: "env render", want: false},
		{path: "env deploy", want: false},
		{path: "ci verify-generated", want: false},
		{path: "lint", want: false},
	} {
		cmd, _, err := root.Find(strings.Fields(tc.path))
		if err != nil || cmd.CommandPath() != "forge "+tc.path {
			t.Fatalf("find %q: %v (got %q)", tc.path, err, cmd.CommandPath())
		}
		for name, val := range tc.flags {
			if err := cmd.Flags().Set(name, val); err != nil {
				t.Fatalf("%s --%s: %v", tc.path, name, err)
			}
		}
		if got := cmdutil.ConfiguresCloneFor(cmd); got != tc.want {
			t.Errorf("forge %s %v: configures the clone = %v, want %v", tc.path, tc.flags, got, tc.want)
		}
	}
}
