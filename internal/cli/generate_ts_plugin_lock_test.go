package cli

import (
	"os"
	"path/filepath"
	"strings"
	"testing"
)

func writeLockedPlugin(t *testing.T, dir, installed, locked string) string {
	t.Helper()
	pkgDir := filepath.Join(dir, "node_modules", "@bufbuild", "protoc-gen-es")
	if err := os.MkdirAll(pkgDir, 0o755); err != nil {
		t.Fatal(err)
	}
	if installed != "" {
		os.WriteFile(filepath.Join(pkgDir, "package.json"), []byte(`{"version":"`+installed+`"}`), 0o644)
	}
	writeTSPluginBin(t, dir)
	if locked != "" {
		lock := `{"packages":{"node_modules/@bufbuild/protoc-gen-es":{"version":"` + locked + `"}}}`
		os.WriteFile(filepath.Join(dir, "package-lock.json"), []byte(lock), 0o644)
	}
	return "./frontends/web/node_modules/.bin/protoc-gen-es"
}

// The header "@generated by protoc-gen-es vX" is the installed plugin's version,
// so an installed plugin older than the lockfile must not be allowed to generate.
func TestEnsureTSPluginMatchesLock_StaleInstallFails(t *testing.T) {
	t.Setenv("FORGE_SKIP_NPM_INSTALL", "1")
	projectDir := t.TempDir()
	feDir := filepath.Join("frontends", "web")
	rel := writeLockedPlugin(t, filepath.Join(projectDir, feDir), "2.14.0", "2.16.0")

	err := ensureTSPluginMatchesLock("web", projectDir, feDir, rel)
	if err == nil {
		t.Fatal("installed 2.14.0 vs locked 2.16.0 must be rejected")
	}
	for _, want := range []string{"2.14.0", "2.16.0", "npm ci"} {
		if !strings.Contains(err.Error(), want) {
			t.Errorf("error %q should mention %q", err, want)
		}
	}
}

func TestEnsureTSPluginMatchesLock_MatchingInstallPasses(t *testing.T) {
	t.Setenv("FORGE_SKIP_NPM_INSTALL", "1")
	projectDir := t.TempDir()
	feDir := filepath.Join("frontends", "web")
	rel := writeLockedPlugin(t, filepath.Join(projectDir, feDir), "2.16.0", "2.16.0")
	if err := ensureTSPluginMatchesLock("web", projectDir, feDir, rel); err != nil {
		t.Fatalf("matching install rejected: %v", err)
	}
}

func TestEnsureTSPluginMatchesLock_NoLockfileIsNoOp(t *testing.T) {
	t.Setenv("FORGE_SKIP_NPM_INSTALL", "1")
	projectDir := t.TempDir()
	feDir := filepath.Join("frontends", "web")
	rel := writeLockedPlugin(t, filepath.Join(projectDir, feDir), "2.14.0", "")
	if err := ensureTSPluginMatchesLock("web", projectDir, feDir, rel); err != nil {
		t.Fatalf("no lockfile means nothing to pin to, got %v", err)
	}
}

// Workspace layout: plugin hoisted to the project root, lockfile at the root.
func TestEnsureTSPluginMatchesLock_HoistedWorkspace(t *testing.T) {
	t.Setenv("FORGE_SKIP_NPM_INSTALL", "1")
	projectDir := t.TempDir()
	writeLockedPlugin(t, projectDir, "2.14.0", "2.16.0")
	rel := "./node_modules/.bin/protoc-gen-es"
	if err := ensureTSPluginMatchesLock("web", projectDir, filepath.Join("frontends", "web"), rel); err == nil {
		t.Fatal("hoisted stale plugin must be rejected")
	}
}
