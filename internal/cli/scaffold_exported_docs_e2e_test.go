// revive's `exported` rule is OFF in the scaffolded .golangci.yml
// (internal/templates/project/golangci.yml.tmpl says why: its cheapest
// suggested repair — "or be unexported" — silently deletes the
// cross-package errors.Is seam on an error sentinel).
//
// Off as a GATE is not off as a STANDARD. The template promises that
// re-enabling the rule is a supported choice, i.e. that the only findings
// a user gets are on code they wrote. This file is what makes that promise
// true: it scaffolds a wide project, turns `exported` back on, and requires
// zero findings in files forge authored.
//
// Without it the promise decays on the next template that adds an exported
// symbol, and nothing would notice — the rule is not in the shipped config,
// so no other test runs it.

// exportedDocsGateConfig is DELIBERATELY stricter than the .golangci.yml
// forge ships, in one direction: it lifts the forge-owned path exclusions
// (`.*_gen\.go$` above all) so the gate sees every file forge writes, not
// just the ones a user's default config happens to lint. `gen/`, `*.pb.go`
// and `*.connect.go` stay excluded because protoc-gen-go wrote them, not
// forge, and forge cannot fix findings there.
const exportedDocsGateConfig = `version: "2"
run:
  timeout: 10m
issues:
  max-issues-per-linter: 0
  max-same-issues: 0
linters:
  default: none
  enable:
    - revive
  settings:
    revive:
      rules:
        - name: exported
  exclusions:
    generated: disable
    paths:
      - "(^|/)gen/"
      - ".*node_modules.*"
      - ".*frontends.*"
      - ".*\\.forge-pkg.*"
      - ".*\\.pb\\.go$"
      - ".*\\.connect\\.go$"
`

// generatedBannerLine is the Tier-1 marker forge stamps on every file it
// regenerates. It is BOTH the property this test derives the file set from
// and — see stripGeneratedBanners — the thing that would make half the
// assertion vacuous if left in place.
const generatedBannerLine = "// Code generated by forge. DO NOT EDIT."

// TestE2EScaffoldIsReviveExportedClean is the acceptance gate for
// "everything forge emits is documented to `exported`'s standard".
//
// The project is scaffolded WIDE on purpose — service + CRUD entity +
// custom RPC + standalone package + adapter + library + worker + binary +
// operator + CRD + webhook. Each noun is a different template family, and a
// narrow project would leave most of them unmeasured. (The CRD family is
// why this test exists: its state/phase const blocks were the only
// `exported` findings in forge's entire emitted surface when it was
// written.)
//
// No `--frontend`: the frontend lane costs an `npm install` and emits no
// Go, and TestE2EFreshScaffoldFrontendLintClean already covers it.
func TestE2EScaffoldIsReviveExportedClean(t *testing.T) {
	t.Parallel()
	requireTool(t, "golangci-lint")
	forgeBin := buildforgeBinary(t)
	dir := t.TempDir()

	runCmd(t, dir, forgeBin, "project", "new", "docsapp", "--mod", "example.com/docsapp", "--service", "orders")
	projectDir := filepath.Join(dir, "docsapp")
	addCorpusForgePkgReplace(t, projectDir)

	// A CRUD entity (with an enum and an optional field) plus a genuine
	// custom RPC: between them they pull in the ORM, the CRUD handler
	// scaffolds and the pb-through stub.
	protoPath := filepath.Join(projectDir, "proto", "services", "orders", "v1", "orders.proto")
	proto := readFileE2E(t, protoPath)
	proto = strings.Replace(proto, "  // TODO: Add your RPC methods here.",
		"  rpc ArchiveOrder(ArchiveOrderRequest) returns (ArchiveOrderResponse);", 1)
	proto += `
// forge:entity
message Order {
  string id = 1;
  string customer_name = 2;
  OrderStatus status = 3;
  optional string note = 4;
}

enum OrderStatus {
  ORDER_STATUS_UNSPECIFIED = 0;
  ORDER_STATUS_PENDING = 1;
  ORDER_STATUS_SHIPPED = 2;
}

message ArchiveOrderRequest {
  string id = 1;
}

message ArchiveOrderResponse {
  bool archived = 1;
}
`
	writeFileE2E(t, protoPath, proto)
	runCmd(t, projectDir, forgeBin, "scaffold")

	for _, nouns := range [][]string{
		{"package", "pricing"},
		{"adapter", "stripeadp"},
		{"library", "mathutil"},
		{"worker", "cleanup"},
		{"binary", "indexer"},
		{"operator", "fleet"},
		{"crd", "Widget", "--group", "fleet"},
		{"webhook", "stripe", "--service", "orders"},
	} {
		runCmd(t, projectDir, forgeBin, append([]string{"scaffold"}, nouns...)...)
	}
	runCmd(t, projectDir, forgeBin, "generate")
	runCmd(t, projectDir, "go", "build", "./...")

	generated, scaffoldOnce := classifyForgeAuthoredGo(t, projectDir)

	// A fresh scaffold contains nothing but forge's own output, so "every
	// non-test .go file under the project" IS the forge-authored set — no
	// hand-maintained list to drift. Both halves must be non-empty: this
	// test's assertion is a search over a file set, and a search over
	// nothing succeeds.
	if len(generated) == 0 {
		t.Fatalf("no Tier-1 generated Go files found under %s — either the scaffold regressed or the "+
			"%q banner changed, and this gate would pass vacuously", projectDir, generatedBannerLine)
	}
	if len(scaffoldOnce) == 0 {
		t.Fatalf("no scaffold-once Go files found under %s — the scaffold-once half of this gate "+
			"would pass vacuously", projectDir)
	}
	t.Logf("gate covers %d Tier-1 generated + %d scaffold-once forge-authored Go file(s)",
		len(generated), len(scaffoldOnce))

	stripGeneratedBanners(t, projectDir, generated)

	gateConfig := filepath.Join(projectDir, ".golangci.exported-gate.yml")
	writeFileE2E(t, gateConfig, exportedDocsGateConfig)

	// The lane must be able to FAIL before its silence is worth anything.
	// A config typo, a linter rename or a `default: none` that switched off
	// the wrong thing all present as "0 issues", indistinguishable from a
	// clean tree.
	assertExportedGateCanFail(t, projectDir, gateConfig)

	if findings := runExportedGate(t, projectDir, gateConfig); len(findings) > 0 {
		t.Errorf("forge emits %d exported symbol(s) with no doc comment. The scaffolded .golangci.yml "+
			"says re-enabling `revive: exported` only reports code the USER wrote; each of these makes "+
			"that false. Fix the TEMPLATE that emitted the file (a doc comment starting with the "+
			"symbol's name), never the scaffold output:\n%s",
			len(findings), strings.Join(findings, "\n"))
	}
}

// classifyForgeAuthoredGo splits a freshly-scaffolded project's Go files
// into the two tiers, keyed off the banner forge stamps rather than a list
// of names: a file carrying the Tier-1 "Code generated" banner is
// regenerated every run, and everything else is written once and inherited
// by the user.
//
// Excluded: `gen/` and `*.pb.go` / `*.connect.go` (protoc-gen-go's output,
// not forge's), the vendored `.forge-pkg` bridge, frontends, and `_test.go`
// files — revive's `exported` rule skips test files unconditionally, so
// including them would inflate the reported breadth without adding an inch
// of covered surface.
func classifyForgeAuthoredGo(t *testing.T, projectDir string) (generated, scaffoldOnce []string) {
	t.Helper()
	err := filepath.WalkDir(projectDir, func(path string, d fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if d.IsDir() {
			switch d.Name() {
			case "gen", "node_modules", "frontends", ".forge-pkg", ".git":
				return filepath.SkipDir
			}
			return nil
		}
		name := d.Name()
		if !strings.HasSuffix(name, ".go") ||
			strings.HasSuffix(name, "_test.go") ||
			strings.HasSuffix(name, ".pb.go") ||
			strings.HasSuffix(name, ".connect.go") {
			return nil
		}
		data, rerr := os.ReadFile(path)
		if rerr != nil {
			return rerr
		}
		rel, rerr := filepath.Rel(projectDir, path)
		if rerr != nil {
			return rerr
		}
		if strings.Contains(string(data), generatedBannerLine) {
			generated = append(generated, rel)
		} else {
			scaffoldOnce = append(scaffoldOnce, rel)
		}
		return nil
	})
	if err != nil {
		t.Fatalf("walk %s for forge-authored Go files: %v", projectDir, err)
	}
	sort.Strings(generated)
	sort.Strings(scaffoldOnce)
	return generated, scaffoldOnce
}

// stripGeneratedBanners removes the Tier-1 banner LINE from each generated
// file, in the throwaway scaffold only.
//
// revive's `exported` rule never fires in a file whose head carries
// "Code generated ... DO NOT EDIT." — the skip is inside revive and
// golangci-lint's `linters.exclusions.generated: disable` does not reach
// it. Leaving the banner on would therefore make the Tier-1 half of this
// gate silently vacuous: every generated file would report clean whether or
// not it had a single doc comment.
//
// Stripping is legitimate because the banner states LIFECYCLE (forge
// rewrites this file), not doc quality. The question this gate asks —
// "would a reader of this file find every exported symbol explained?" —
// does not become less relevant because a generator produced the bytes.
func stripGeneratedBanners(t *testing.T, projectDir string, generated []string) {
	t.Helper()
	for _, rel := range generated {
		path := filepath.Join(projectDir, rel)
		before := readFileE2E(t, path)
		after := strings.Replace(before, generatedBannerLine+"\n", "", 1)
		if after == before {
			t.Fatalf("%s was classified Tier-1 but the banner line could not be removed — the "+
				"classifier and the stripper disagree, and revive would silently skip the file", rel)
		}
		writeFileE2E(t, path, after)
	}
}

// runExportedGate runs golangci-lint with the exported-only config and
// returns the finding lines. A non-zero exit is expected when there are
// findings, so the error is not fatal on its own — but output that parses
// to zero findings AND a non-zero exit means the linter itself failed
// (config error, build error), which must be loud.
func runExportedGate(t *testing.T, projectDir, gateConfig string) []string {
	t.Helper()
	cmd := exec.Command("golangci-lint", golangciLintRunArgs("--config", gateConfig, "./...")...)
	cmd.Dir = projectDir
	cmd.Env = goexec.WithTrimpath(append(os.Environ(), "GOFLAGS="))
	out, err := cmd.CombinedOutput()
	findings := parseExportedFindings(string(out))
	if err != nil && len(findings) == 0 {
		t.Fatalf("golangci-lint failed without reporting a single `exported` finding — the gate did not "+
			"run, so its silence means nothing: %v\n%s", err, out)
	}
	return findings
}

// parseExportedFindings pulls the `path:line:col: exported: ...` lines out
// of golangci-lint's text output, dropping the source-echo and caret lines
// it interleaves.
func parseExportedFindings(out string) []string {
	var findings []string
	for _, line := range strings.Split(out, "\n") {
		if strings.Contains(line, ": exported: ") {
			findings = append(findings, strings.TrimSpace(line))
		}
	}
	return findings
}

// assertExportedGateCanFail plants an undocumented exported type in a
// forge-authored package, requires the gate to report it, and removes it.
//
// This is the witness that the lane is live. Every other assertion in this
// test is "the gate found nothing", which is exactly what a broken gate
// also says.
func assertExportedGateCanFail(t *testing.T, projectDir, gateConfig string) {
	t.Helper()
	probe := filepath.Join(projectDir, "internal", "pricing", "zz_exported_gate_probe.go")
	writeFileE2E(t, probe, "package pricing\n\ntype ExportedGateProbe struct{}\n")
	defer func() {
		if err := os.Remove(probe); err != nil {
			t.Fatalf("remove gate probe: %v", err)
		}
	}()

	cmd := exec.Command("golangci-lint", golangciLintRunArgs("--config", gateConfig, "./internal/pricing/")...)
	cmd.Dir = projectDir
	cmd.Env = goexec.WithTrimpath(append(os.Environ(), "GOFLAGS="))
	out, _ := cmd.CombinedOutput()
	if !strings.Contains(string(out), "ExportedGateProbe") {
		t.Fatalf("the `revive: exported` lane did not report a deliberately undocumented exported type. "+
			"Every other assertion in this test reads a clean run as a pass, so a lane that cannot fail "+
			"turns the whole gate green over unread code:\n%s", out)
	}
}
