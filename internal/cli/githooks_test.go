package cli

import (
	"path/filepath"
	"testing"
)

// ensureGitHooksActivated may point core.hooksPath at .githooks only when the
// pre-commit there is forge's. An in-place adopted repository keeps its own
// .githooks/pre-commit (reliant's runs `make fmt` on every commit), and the
// setting lands in the clone's shared .git/config — every linked worktree —
// so activating it would switch the project's hooks on for everyone the
// first time anyone ran any forge command there.
func TestEnsureGitHooksActivated(t *testing.T) {
	const forgeHook = "#!/bin/sh\n# forge-managed git pre-commit hook — regenerated by `forge generate`.\nexit 0\n"
	const projectHook = "#!/bin/bash\n# Pre-commit hook to format staged Go files\nmake fmt\n"

	for _, tc := range []struct {
		name   string
		hook   string // "" = no .githooks/pre-commit
		optOut string // env var set to 1, "" = none
		want   string
	}{
		{name: "forge's hook is activated", hook: forgeHook, want: ".githooks"},
		{name: "the project's own hook is left alone", hook: projectHook, want: ""},
		{name: "no hook, nothing to activate", hook: "", want: ""},
		{name: "FORGE_NO_GIT_HOOKS opts out", hook: forgeHook, optOut: gitHooksOptOutEnv, want: ""},
		// The earlier name: a clone opted out under it stays opted out.
		{name: "FORGE_NO_HOOKS still opts out", hook: forgeHook, optOut: legacyGitHooksOptOutEnv, want: ""},
	} {
		t.Run(tc.name, func(t *testing.T) {
			isolateGit(t)
			if tc.optOut != "" {
				t.Setenv(tc.optOut, "1")
			}
			repo := t.TempDir()
			gitOut(t, repo, "init", "-q")
			if tc.hook != "" {
				writeTestFile(t, filepath.Join(repo, ".githooks", "pre-commit"), tc.hook)
			}

			ensureGitHooksActivated(repo)

			got := gitOut(t, repo, "config", "--local", "--default", "", "core.hooksPath")
			if got != tc.want {
				t.Errorf("core.hooksPath = %q, want %q", got, tc.want)
			}
		})
	}
}

// A core.hooksPath the user already set is never replaced, forge hook or not.
func TestEnsureGitHooksActivated_KeepsExistingSetting(t *testing.T) {
	isolateGit(t)
	repo := t.TempDir()
	gitOut(t, repo, "init", "-q")
	gitOut(t, repo, "config", "--local", "core.hooksPath", ".husky")
	writeTestFile(t, filepath.Join(repo, ".githooks", "pre-commit"),
		"#!/bin/sh\n# forge-managed git pre-commit hook\nexit 0\n")

	ensureGitHooksActivated(repo)

	if got := gitOut(t, repo, "config", "--local", "core.hooksPath"); got != ".husky" {
		t.Errorf("core.hooksPath = %q, want the user's .husky kept", got)
	}
}
