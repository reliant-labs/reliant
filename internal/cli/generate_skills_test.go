package cli

import (
	"os"
	"path/filepath"
	"testing"

	"github.com/reliant-labs/forge/internal/checksums"
	"github.com/reliant-labs/forge/internal/config"
)

func newRetireCtx(t *testing.T, harness string) *pipelineContext {
	t.Helper()
	checksums.ResetSkipWrite()
	t.Cleanup(checksums.ResetSkipWrite)
	root := t.TempDir()
	return &pipelineContext{
		ProjectDir: root,
		AbsPath:    root,
		Checksums:  &checksums.FileChecksums{},
		Cfg:        &config.ProjectConfig{Harness: harness},
	}
}

// Forge never writes skills, whatever the harness (including unset).
func TestStepRetireAgentSkillsWritesNothing(t *testing.T) {
	for _, harness := range []string{"", "claude", "reliant", "cursor", "copilot", "codex"} {
		t.Run("harness="+harness, func(t *testing.T) {
			ctx := newRetireCtx(t, harness)
			if err := stepRetireAgentSkills(ctx); err != nil {
				t.Fatal(err)
			}
			if _, err := os.Stat(filepath.Join(ctx.AbsPath, ".claude")); !os.IsNotExist(err) {
				t.Errorf("harness %q created .claude/ (err=%v)", harness, err)
			}
		})
	}
}

// A previously delivered, unmodified forge copy is swept; modified and
// user-authored files survive.
func TestStepRetireAgentSkillsSweepsOnlyForgeOwnedCopies(t *testing.T) {
	ctx := newRetireCtx(t, "claude")
	skills := filepath.Join(ctx.AbsPath, ".claude", "skills")
	write := func(name string, body []byte) string {
		p := filepath.Join(skills, name, "SKILL.md")
		if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(p, body, 0o644); err != nil {
			t.Fatal(err)
		}
		return p
	}

	rel := ".claude/skills/db/SKILL.md"
	stamped, ok := checksums.Stamp(rel, []byte("---\nname: db\n---\n<!-- Code generated by forge. DO NOT EDIT. -->\nguidance\n"))
	if !ok {
		t.Fatal("SKILL.md should be stampable")
	}
	delivered := write("db", stamped)
	legacy := write("api", []byte("---\nname: api\n---\n<!-- Code generated by forge v0.0.1. DO NOT EDIT -->\nold\n"))
	modified := write("testing", []byte("---\nname: testing\n---\n<!-- forge:hash=deadbeef -->\nmy edits\n"))
	userOwn := write("my-own", []byte("# mine\n"))

	if err := stepRetireAgentSkills(ctx); err != nil {
		t.Fatal(err)
	}
	for _, p := range []string{delivered, legacy} {
		if _, err := os.Stat(p); !os.IsNotExist(err) {
			t.Errorf("forge-owned copy %s survived (err=%v)", p, err)
		}
	}
	for _, p := range []string{modified, userOwn} {
		if _, err := os.Stat(p); err != nil {
			t.Errorf("non-forge-owned file %s was removed: %v", p, err)
		}
	}
}

// An emptied skills tree is pruned.
func TestStepRetireAgentSkillsPrunesEmptyTree(t *testing.T) {
	ctx := newRetireCtx(t, "")
	p := filepath.Join(ctx.AbsPath, ".claude", "skills", "db", "SKILL.md")
	if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(p, []byte("<!-- Code generated by forge. DO NOT EDIT. -->\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	if err := stepRetireAgentSkills(ctx); err != nil {
		t.Fatal(err)
	}
	if _, err := os.Stat(filepath.Join(ctx.AbsPath, ".claude")); !os.IsNotExist(err) {
		t.Errorf(".claude/ survived (err=%v)", err)
	}
}
