// TestGenerate_PackageWithoutSeamGetsADefaultChainDecorator: a hand-written
// component with no `// forge:constructor` and no owned observe_chain.go is
// instrumented anyway. Its decorator builds observe.DefaultComponentChain, so
// nothing is scaffolded into the package. (An earlier forge emitted a
// decorator calling newObserveChain and broke its own build on
// `undefined: newObserveChain`, then scaffolded the seam to cover it.) Once a
// package declares the seam, the decorator calls it instead and generate
// leaves it alone.
func TestGenerate_PackageWithoutSeamGetsADefaultChainDecorator(t *testing.T) {
	// A RELATIVE project root, the way `forge generate` runs it (projectDir
	// ".").
	t.Chdir(t.TempDir())
	root := "."
	mustWrite(t, filepath.Join(root, "go.mod"), "module example.com/proj\n\ngo 1.24\n")
	pkg := filepath.Join(root, "internal", "vendorapi")
	if err := os.MkdirAll(pkg, 0o755); err != nil {
		t.Fatal(err)
	}
	mustWrite(t, filepath.Join(pkg, "contract.go"), `// forge:outbound-io
package vendorapi

import "context"

type Service interface {
	Ping(ctx context.Context) error
}

type Deps struct{}
`)
	mustWrite(t, filepath.Join(pkg, "client.go"), `package vendorapi

import "context"

type client struct{}

// New builds the adapter.
func New(Deps) Service { return &client{} }

func (c *client) Ping(context.Context) error { return nil }
`)

	if err := generateInternalPackageContracts(root, &config.ProjectConfig{Name: "proj"}, nil); err != nil {
		t.Fatalf("generateInternalPackageContracts: %v", err)
	}

	decorator, err := os.ReadFile(filepath.Join(pkg, "middleware_gen.go"))
	if err != nil {
		t.Fatalf("decorator not generated for an unmarked package: %v", err)
	}
	if !strings.Contains(string(decorator), `observe.DefaultComponentChain("example.com/proj/internal/vendorapi", "vendorapi", slog.LevelDebug)`) {
		t.Fatalf("decorator does not build the default chain:\n%s", decorator)
	}
	if _, err := os.Stat(filepath.Join(pkg, "observe_chain.go")); !os.IsNotExist(err) {
		t.Fatalf("observe_chain.go was scaffolded into the package (err=%v)", err)
	}

	// A seam the package declares replaces the default, and stays the user's.
	seam := "package vendorapi\n\nimport \"github.com/reliant-labs/forge/pkg/observe\"\n\n// mine\nfunc newObserveChain() *observe.ComponentChain { return observe.NewComponentChain() }\n"
	mustWrite(t, filepath.Join(pkg, "observe_chain.go"), seam)
	if err := generateInternalPackageContracts(root, &config.ProjectConfig{Name: "proj"}, nil); err != nil {
		t.Fatalf("second generate: %v", err)
	}
	decorator, _ = os.ReadFile(filepath.Join(pkg, "middleware_gen.go"))
	if !strings.Contains(string(decorator), "newObserveChain()") || strings.Contains(string(decorator), "DefaultComponentChain") {
		t.Fatalf("decorator does not route through the declared seam:\n%s", decorator)
	}
	if got, _ := os.ReadFile(filepath.Join(pkg, "observe_chain.go")); string(got) != seam {
		t.Fatalf("generate overwrote the owned seam")
	}
}

// TestGenerate_KeepsTheWrapperNameHandOwnedCodeCalls is the control-plane
// regression. internal/daemonpat's decorator was generated, by an earlier
// forge, as NewSecretsWithForgeMiddleware (named from `return &secrets{}`),
// and hand-owned code calls it by that name. ResolveMiddlewareWrapper PINS an
// existing declaration so no forge upgrade can rename it — but the contracts
// step deleted middleware_gen.go (removeLegacyWrappers) BEFORE resolving the
// name, so the pin never saw the file and the wrapper was re-emitted as
// NewServiceWithForgeMiddleware: `undefined: daemonpat.NewSecretsWithForgeMiddleware`
// at generate-validation in every caller.
func TestGenerate_KeepsTheWrapperNameHandOwnedCodeCalls(t *testing.T) {
	t.Chdir(t.TempDir())
	root := "."
	mustWrite(t, filepath.Join(root, "go.mod"), "module example.com/proj\n\ngo 1.24\n")
	pkg := filepath.Join(root, "internal", "daemonpat")
	if err := os.MkdirAll(pkg, 0o755); err != nil {
		t.Fatal(err)
	}
	mustWrite(t, filepath.Join(pkg, "contract.go"), `package daemonpat

import "context"

type Service interface {
	Provision(ctx context.Context) error
}

type Deps struct{}
`)
	mustWrite(t, filepath.Join(pkg, "provision.go"), `package daemonpat

import "context"

type secrets struct{}

// New builds the provisioner.
//
// forge:constructor
func New(Deps) Service { return &secrets{} }

func (s *secrets) Provision(context.Context) error { return nil }
`)
	mustWrite(t, filepath.Join(pkg, "observe_chain.go"), "package daemonpat\n\nfunc newObserveChain() any { return nil }\n")
	// The decorator an earlier forge emitted, under the name callers use.
	mustWrite(t, filepath.Join(pkg, "middleware_gen.go"), `// Code generated by forge. DO NOT EDIT.
package daemonpat

func NewSecretsWithForgeMiddleware(inner Service) Service {
	return &forgeMiddlewareSecrets{inner: inner}
}

type forgeMiddlewareSecrets struct{ inner Service }
`)

	if err := generateInternalPackageContracts(root, &config.ProjectConfig{Name: "proj"}, nil); err != nil {
		t.Fatalf("generateInternalPackageContracts: %v", err)
	}
	decorator, err := os.ReadFile(filepath.Join(pkg, "middleware_gen.go"))
	if err != nil {
		t.Fatalf("decorator not regenerated: %v", err)
	}
	if !strings.Contains(string(decorator), "func NewSecretsWithForgeMiddleware(inner Service) Service") {
		t.Fatalf("generate renamed a wrapper hand-owned code calls — the pin was lost:\n%s", decorator)
	}
	if strings.Contains(string(decorator), "NewServiceWithForgeMiddleware") {
		t.Fatalf("a second, renamed wrapper was emitted:\n%s", decorator)
	}
}
