// a real package to emit mock_gen.go for.
func writeMockContractPackage(t *testing.T, projectDir, pkg string) {
	t.Helper()
	mustMkdir(t, filepath.Join(projectDir, "internal", pkg))
	mustWrite(t, filepath.Join(projectDir, "internal", pkg, "contract.go"),
		"package "+pkg+"\n\nimport \"context\"\n\n"+
			"// Service is the package contract.\n"+
			"type Service interface {\n\tGet(ctx context.Context, id string) (string, error)\n}\n")
}

// TestInternalContracts_MockGenRecordedWrittenThisRun pins the emit-side
// fix for kalshi FORGE_BACKLOG #15: the contract/mock emitter must route
// internal/<pkg>/mock_gen.go through the certification chokepoint so the
// path is stamped AND lands in the per-run WrittenThisRun set.
// Pre-fix the emitter wrote via raw os.WriteFile, so a tracked mock was
// flagged "stale" by the sweep on every run.
func TestInternalContracts_MockGenRecordedWrittenThisRun(t *testing.T) {
	resetCleanupRunState(t)
	dir := t.TempDir()
	writeMockContractPackage(t, dir, "climate")

	cs := &checksums.FileChecksums{}
	if err := generateInternalPackageContracts(dir, nil, cs); err != nil {
		t.Fatalf("generateInternalPackageContracts: %v", err)
	}

	rel := filepath.ToSlash(filepath.Join("internal", "climate", "mock_gen.go"))
	onDisk, err := os.ReadFile(filepath.Join(dir, "internal", "climate", "mock_gen.go"))
	if err != nil {
		t.Fatalf("mock_gen.go not emitted: %v", err)
	}
	if !checksums.WasWrittenThisRun(rel) {
		t.Errorf("%s not in WrittenThisRun — stale sweep would flag a live mock", rel)
	}
	if checksums.Verify(onDisk) != checksums.Pristine {
		t.Errorf("%s not certified (no verifying forge:hash marker) — the emitter bypassed the chokepoint", rel)
	}
}

// TestCleanupStaleArtifacts_MockGenSurvivesForceCleanup is the
// disaster-case pin for kalshi FORGE_BACKLOG #15: a certified
// internal/<pkg>/mock_gen.go that the mock emitter just regenerated must
// survive `forge generate --force-cleanup`. Pre-fix, the raw-write emit
// left the path out of WrittenThisRun and --force-cleanup deleted live
// mocks that package tests compile against.
func TestCleanupStaleArtifacts_MockGenSurvivesForceCleanup(t *testing.T) {
	resetCleanupRunState(t)
	checksums.ResetPerRunState()
	defer checksums.ResetPerRunState()
	dir := t.TempDir()
	writeMockContractPackage(t, dir, "climate")

	// The mock already exists certified from a prior run — stamped from
	// an OLDER render, the exact shape kalshi was in (8 tracked
	// mock_gen.go files, all flagged). The writer auto-heals it.
	rel := "internal/climate/mock_gen.go"
	mustWriteStamped(t, filepath.Join(dir, rel), rel,
		"// Code generated by forge. DO NOT EDIT.\npackage climate\n// stale prior render\n")

	cs := &checksums.FileChecksums{}

	// Emit step runs first (pipeline order: contracts before cleanup).
	if err := generateInternalPackageContracts(dir, nil, cs); err != nil {
		t.Fatalf("generateInternalPackageContracts: %v", err)
	}

	ctx := newCleanupCtx(dir, cs, []codegen.ServiceDef{{Name: "KeptService"}}, nil)
	ctx.ForceCleanup = true // the widest sweep — exactly the disaster path
	sweep, err := cleanupStaleArtifacts(ctx)
	if err != nil {
		t.Fatalf("cleanup: %v", err)
	}
	for _, p := range sweep.Removed {
		if strings.HasSuffix(p, "mock_gen.go") {
			t.Errorf("live mock flagged for deletion: %s", p)
		}
	}
	if _, err := os.Stat(filepath.Join(dir, rel)); err != nil {
		t.Fatalf("mock_gen.go deleted by --force-cleanup: %v", err)
	}
}

// TestCleanupStaleArtifacts_MockGenOwnerGateWhenContractsDisabled covers
// the gated-off-emitter variant: features.contracts=false means
// stepInternalContracts never runs, so absence-from-WrittenThisRun is
// uninformative for internal/*/mock_gen.go. The owner-gate registry must
// keep the mocks out of the candidate set (depth-1 and nested packages).
func TestCleanupStaleArtifacts_MockGenOwnerGateWhenContractsDisabled(t *testing.T) {
	resetCleanupRunState(t)
	dir := t.TempDir()

	banner := "// Code generated by forge. DO NOT EDIT.\npackage x\n"
	mustMkdir(t, filepath.Join(dir, "internal", "climate"))
	mustWriteStamped(t, filepath.Join(dir, "internal", "climate", "mock_gen.go"),
		"internal/climate/mock_gen.go", banner)
	mustMkdir(t, filepath.Join(dir, "internal", "mcp", "database"))
	mustWriteStamped(t, filepath.Join(dir, "internal", "mcp", "database", "mock_gen.go"),
		"internal/mcp/database/mock_gen.go", banner)

	cs := &checksums.FileChecksums{}

	cfg := &config.ProjectConfig{Features: config.FeaturesConfig{}.With(config.FeatureContracts, false)}
	ctx := newCleanupCtx(dir, cs, []codegen.ServiceDef{{Name: "KeptService"}}, cfg)
	sweep, err := cleanupStaleArtifacts(ctx)
	if err != nil {
		t.Fatalf("cleanup: %v", err)
	}
	if len(sweep.Removed) != 0 {
		t.Errorf("removed = %v, want empty (contracts emitter gated off — not a stale signal)", sweep.Removed)
	}
	for _, rel := range []string{"internal/climate/mock_gen.go", "internal/mcp/database/mock_gen.go"} {
		if _, err := os.Stat(filepath.Join(dir, rel)); err != nil {
			t.Errorf("%s deleted despite gated-off emitter: %v", rel, err)
		}
	}
}

// TestCleanupStaleArtifacts_DisownedPathNotACandidate pins the
// user-owned-by-intent rule: a disowned path (marker stripped at disown
// time, recorded in .forge/disowned.json) is never re-emitted by forge,
// so "not written this run" is its permanent steady state — never a
// deletion candidate and never hand-edited drift.
func TestCleanupStaleArtifacts_DisownedPathNotACandidate(t *testing.T) {
	resetCleanupRunState(t)
	dir := t.TempDir()

	mustMkdir(t, filepath.Join(dir, "internal", "handlers", "keep"))
	kept := filepath.Join(dir, "internal", "handlers", "keep", "handlers_crud_gen.go")
	// Disown strips the marker — the steady disowned shape is unmarked.
	mustWrite(t, kept, "// Code generated by forge. DO NOT EDIT.\npackage keep\n")

	rel := "internal/handlers/keep/handlers_crud_gen.go"
	cs := &checksums.FileChecksums{Disowned: map[string]checksums.DisownedEntry{
		rel: {Reason: "test", DisownedAt: "2026-06-01T00:00:00Z"},
	}}

	ctx := newCleanupCtx(dir, cs, []codegen.ServiceDef{{Name: "KeepService"}}, nil)
	sweep, err := cleanupStaleArtifacts(ctx)
	if err != nil {
		t.Fatalf("cleanup: %v", err)
	}
	if len(sweep.Removed) != 0 {
		t.Errorf("removed = %v, want empty (disowned path is alive by intent)", sweep.Removed)
	}
	if len(sweep.HandEdited) != 0 {
		t.Errorf("handEdited = %v, want empty (disowned files are not drift)", sweep.HandEdited)
	}
	if _, err := os.Stat(kept); err != nil {
		t.Errorf("disowned path deleted: %v", err)
	}
}

