// File: internal/cli/db_squash_output.go
//
// What `forge db squash` writes around the dump: the baseline's header, and
// the next steps it prints.
//
// THE HEADER IS A FUNCTION OF THE SQUASHED HISTORY AND NOTHING ELSE. It used
// to carry the wall-clock time and the absolute --from-dir path, so a second
// squash of the same history never reproduced the file byte for byte, and a
// reviewer could not tell "re-cut" from "changed". reliant stripped it with
// `tail -n +6`. What a reader needs to know about where the baseline came
// from is stable: which migrations it replaces. So the header names their
// count and version range, declares them (`-- forge:adopts forge ...`), and
// lists the dump flags; the body is pg_dump's, which is deterministic for one
// history and one image (squashBaseline drops the one random part,
// `\restrict <key>`).
//
// THE DECLARATION IS WHAT LETS THE DATABASES THAT HISTORY BUILT TAKE THE
// BASELINE. They already have its schema, recorded in forge's own tables;
// without the list the migrator could only refuse them (it used to call them
// AHEAD, or report the baseline MISSING). With it, migratekit adopts each one
// whose record holds every listed version: the baseline is recorded as
// applied and none of its SQL runs. See pkg/migratekit/adopt_forge.go.

package cli

import (
	"fmt"
	"io"
	"slices"
	"strings"

	"github.com/reliant-labs/forge/pkg/migratekit/compat"
)

// squashHeader is the comment a squashed baseline opens with: where it came
// from, the forge versions it replaces, and that it is backward-compatible.
//
// It is backward-compatible by construction — it builds exactly the schema
// the squashed history left, which is the schema the release before the
// squash runs on. Declaring it is what lets that release, rolled back to,
// read an adopted database (now at the baseline's version) as a compatible
// schema ahead of it rather than refusing it.
func squashHeader(squashed []compat.Migration) string {
	var b strings.Builder
	from := "no migrations"
	switch n := len(squashed); n {
	case 0:
	case 1:
		from = fmt.Sprintf("1 migration, %d", squashed[0].Version)
	default:
		from = fmt.Sprintf("%d migrations, %d through %d", n, squashed[0].Version, squashed[n-1].Version)
	}
	b.WriteString("-- Generated by `forge db squash` from " + from + ".\n")
	if len(squashed) > 0 {
		b.WriteString("-- It replaces them: a database they built is adopted, never re-run (see the forge skill\n")
		b.WriteString("-- db/deploy-migrations, \"Squashing a forge history\").\n")
		vs := squashedVersions(squashed)
		for i := 0; i < len(vs); i += adoptsPerLine {
			end := min(i+adoptsPerLine, len(vs))
			b.WriteString(compat.AdoptsDirective + " " + compat.ToolForge)
			for _, v := range vs[i:end] {
				fmt.Fprintf(&b, " %d", v)
			}
			b.WriteByte('\n')
		}
		b.WriteString("-- It builds the schema the release before the squash runs on:\n")
		b.WriteString(compat.Directive + "\n")
	}
	b.WriteString("-- pg_dump --no-owner --inserts --exclude-table=public.schema_migrations --exclude-table=public.schema_migrations_compat --exclude-table=public.schema_migrations_applied\n")
	b.WriteString("-- pg_dump's session prelude (SET, set_config), psql meta-commands (\\restrict) and every privilege but forge_dash's grants and PUBLIC's are stripped.\n\n")
	return b.String()
}

// squashedVersions are the versions a baseline replaces, ascending.
func squashedVersions(squashed []compat.Migration) []int64 {
	vs := make([]int64, len(squashed))
	for i, m := range squashed {
		vs[i] = int64(m.Version)
	}
	slices.Sort(vs)
	return vs
}

// checkSquashBaselineVersion refuses a baseline numbered as one of the
// migrations it replaces: a database at that version would read the
// baseline as a different file under its own number, and the migrator
// refuses a baseline that lists a version it carries.
func checkSquashBaselineVersion(stem string, version uint64, ok bool, squashed []compat.Migration) error {
	if !ok {
		return nil
	}
	for _, m := range squashed {
		if uint64(m.Version) == version {
			last := squashed[len(squashed)-1].Version
			return fmt.Errorf("--to %s: version %d is one of the migrations being squashed (%s); number the baseline outside "+
				"the history it replaces — above %d keeps the release before the squash able to roll back onto an adopted database",
				stem, version, m.Name, last)
		}
	}
	return nil
}

// checkWrittenForgeAdoption parses a baseline the way the migrator does and
// confirms it declares exactly the squashed versions.
func checkWrittenForgeAdoption(content string, squashed []compat.Migration) error {
	got, err := compat.ParseAdoption(content)
	if err != nil {
		return fmt.Errorf("its adoption declaration does not parse: %w", err)
	}
	if got == nil || got.Tool != compat.ToolForge || !slices.Equal(got.Versions, squashedVersions(squashed)) {
		return fmt.Errorf("its adoption declaration does not list the %d squashed versions", len(squashed))
	}
	return nil
}

// printSquashNextSteps tells the user what to do with the baseline.
//
// It used to end with "`forge db migrate force <id>` against any pre-existing
// databases so they accept the new baseline". That is unsafe advice: force
// records a version as applied without checking anything, so it would mark a
// baseline applied on a database whose schema is not the one the baseline
// builds, and skip the verification adoption exists to do. The baseline
// declares the history it replaces instead, and a database that history
// built adopts it — the claim TestSquashNextStepsClaimsHoldAgainstTheMigrator
// checks against the migrator.
func printSquashNextSteps(w io.Writer, fromDir, baselineName string, baselineVersion uint64, haveVersion bool, squashed []compat.Migration) {
	p := func(s string) { _, _ = fmt.Fprintln(w, s) }
	p("\nNext steps:")
	p("  1. Review the baseline: it should hold what the squashed migrations built (their schema, and")
	p("     the rows they inserted) and nothing an application wrote.")
	_, _ = fmt.Fprintf(w, "  2. Replace the squashed migrations with it: move them out of %s (git keeps them).\n", fromDir)
	p("     The migrator refuses the baseline while a version it lists is still a file beside it.")
	_, _ = fmt.Fprintf(w, "  3. A database the squashed migrations built ADOPTS it on its next `migrate up` or AutoMigrate:\n")
	_, _ = fmt.Fprintf(w, "     the baseline lists the %d versions it replaces (`%s %s ...`). The migrator\n", len(squashed), compat.AdoptsDirective, compat.ToolForge)
	p("     checks the database applied every one, records the baseline as applied, runs none of its SQL,")
	p("     and applies what comes after it. One that is behind this history, or past it, is refused with")
	p("     the versions named, and nothing changes.")
	p("  4. Preview every database before it meets this release: `forge db migrate status --dsn <dsn>`,")
	p("     then `forge db migrate up --dsn <dsn>` against a copy. A fresh database applies the baseline.")
	p("     Never `forge db migrate force` the baseline onto a database: force records it as applied")
	p("     without checking that the schema is the one it builds.")
	if len(squashed) == 0 {
		return
	}
	if last := squashed[len(squashed)-1]; haveVersion && baselineVersion < uint64(last.Version) {
		_, _ = fmt.Fprintf(w, "  Note: %s is numbered below the history it replaces (last: %d), so the release before the\n", baselineName, last.Version)
		p("     squash cannot read an adopted database. Number it above that history (--to <version>_baseline)")
		p("     to keep rolling back to that release possible.")
	}
	if first := squashed[0]; first.Adopts != nil && first.Adopts.Tool != compat.ToolForge {
		_, _ = fmt.Fprintf(w, "  Note: the squashed history begins with %s, which adopts databases %s migrated. This\n", first.Name, first.Adopts.Tool)
		_, _ = fmt.Fprintf(w, "     baseline adopts only databases forge migrated: a database still on %s must first run a\n", first.Adopts.Tool)
		_, _ = fmt.Fprintf(w, "     release that carries %s.\n", first.Name)
	}
}
