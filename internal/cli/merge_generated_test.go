// fixtureManifest is a fixture-manifest_gen.ts as forge emits it, reduced to
// the lines that matter: a hash header, the seed fingerprints, and a body.
func fixtureManifest(hash, seed, files, body string) []byte {
	return []byte("// Code generated by forge. DO NOT EDIT.\n" +
		"// forge:hash=" + hash + "\n" +
		"//\n" +
		"export const SEED_FINGERPRINT = \"" + seed + "\";\n" +
		"export const SEED_CONFIG_FINGERPRINT = \"cfg-" + seed + "\";\n" +
		"export const SEED_FINGERPRINT_FILES = " + files + ";\n" +
		"\n" +
		body)
}

const fixtureBody = "export const tables = [\n  \"accounts\",\n  \"invoices\",\n  \"projects\",\n  \"users\",\n];\n" +
	"\n// unrelated\n// lines\n// between\n// the\n// two\n// edits\n" +
	"export const counts = {\n  accounts: 10,\n  users: 10,\n};\n"

// Two branches that each add a migration regenerate the fixture manifest: both
// change the hash header and the seed fingerprints, and they change the body
// in different places. Plain git conflicts on the fingerprint lines — the
// 2026-10-07 pin-PR conflicts. The driver merges the body and keeps this
// side's fingerprints for `forge generate` to refresh.
func TestMergeGenerated_FingerprintLinesNeverConflict(t *testing.T) {
	base := fixtureManifest("aaaa", "seed-base", "40", fixtureBody)
	ours := fixtureManifest("bbbb", "seed-ours", "41",
		strings.Replace(fixtureBody, "  \"accounts\",\n", "  \"accounts\",\n  \"coupons\",\n", 1))
	theirs := fixtureManifest("cccc", "seed-theirs", "41",
		strings.Replace(fixtureBody, "  users: 10,\n", "  users: 10,\n  webhooks: 10,\n", 1))

	// The baseline: git's own merge conflicts on the fingerprint lines.
	if plainGitMergeConflicts(t, base, ours, theirs) == 0 {
		t.Fatal("precondition: plain git merge-file should conflict on the fingerprint lines")
	}

	merged, clean, err := mergeGenerated(context.Background(), base, ours, theirs, 7)
	if err != nil {
		t.Fatal(err)
	}
	if !clean {
		t.Fatalf("a merge that differs only in fingerprints and separate body hunks conflicted:\n%s", merged)
	}
	got := string(merged)
	for _, want := range []string{"\"coupons\",", "webhooks: 10,", "forge:hash=bbbb", "SEED_FINGERPRINT = \"seed-ours\"", "SEED_FINGERPRINT_FILES = 41;"} {
		if !strings.Contains(got, want) {
			t.Errorf("merged file lacks %q:\n%s", want, got)
		}
	}
	if strings.Contains(got, volatilePlaceholder) {
		t.Errorf("a placeholder leaked into the merge:\n%q", got)
	}
}

