// The header names the history, never the DSN or the time, and its adoption
// lines are what the migrator reads back: every goose version, wrapped.
func TestDSNSquashHeader(t *testing.T) {
	versions := []int64{20260101000001, 20260101000002, 20260101000003, 20260101000004, 20260101000005,
		20260101000006, 20260101000007, 20260101000008, 20260101000009, 20260101000010}
	excludes := slices.Clone(squashBookkeepingTables)
	got := dsnSquashHeader(&gooseHistory{Versions: versions}, excludes)

	if !strings.HasPrefix(got, "-- Generated by `forge db squash --from-dsn` from a database goose migrated: 10 versions, 20260101000001 through 20260101000010.\n") {
		t.Errorf("header opens:\n%s", got)
	}
	for _, line := range []string{
		"-- forge:adopts goose 20260101000001 20260101000002 20260101000003 20260101000004 20260101000005 20260101000006 20260101000007 20260101000008\n",
		"-- forge:adopts goose 20260101000009 20260101000010\n",
		" --exclude-table=goose_db_version --exclude-table=goose_db_version_id_seq\n",
	} {
		if !strings.Contains(got, line) {
			t.Errorf("header lacks %q:\n%s", line, got)
		}
	}
	adoption, err := compat.ParseAdoption(got)
	if err != nil || adoption == nil || adoption.Tool != compat.ToolGoose || !slices.Equal(adoption.Versions, versions) {
		t.Errorf("the migrator reads back %+v (err %v), want goose %v", adoption, err, versions)
	}
	if err := checkWrittenAdoption(got+"CREATE TABLE t (id INT);\n", &gooseHistory{Versions: versions}); err != nil {
		t.Errorf("checkWrittenAdoption: %v", err)
	}
	if err := checkWrittenAdoption(got, &gooseHistory{Versions: versions[:9]}); err == nil {
		t.Error("checkWrittenAdoption accepted a declaration listing a version goose did not apply")
	}

	none := dsnSquashHeader(nil, excludes)
	if a, err := compat.ParseAdoption(none); a != nil || err != nil {
		t.Errorf("a database with no goose history got an adoption: %+v, %v", a, err)
	}
	if !strings.Contains(none, "no goose history (no goose_db_version)") {
		t.Errorf("header without goose:\n%s", none)
	}
}

func TestPrintBaselineRows(t *testing.T) {
	var b bytes.Buffer
	printBaselineRows(&b, "CREATE TABLE public.plans (id int);\nINSERT INTO public.plans VALUES (1);\nINSERT INTO public.plans VALUES (2);\nINSERT INTO public.accounts (id) VALUES (1);\n")
	if want := "It carries 3 row(s), which every fresh database will get: public.accounts (1), public.plans (2).\n"; !strings.Contains(b.String(), want) {
		t.Errorf("got %q, want %q", b.String(), want)
	}
	b.Reset()
	printBaselineRows(&b, "CREATE TABLE t (id int);\n")
	if !strings.Contains(b.String(), "no rows") {
		t.Errorf("got %q", b.String())
	}
}

// The flags that configure squash's own container mean nothing to
// --from-dsn, and --exclude-table means nothing without it: refused, not
// ignored.
func TestDBSquashFromDSNRefusesFlagsThatDoNotApply(t *testing.T) {
	for _, tc := range []struct {
		args []string
		want string
	}{
		{[]string{"--from-dsn", "postgres://u@localhost/db", "--from-dir", "db/migrations"}, "--from-dir does not apply to --from-dsn"},
		{[]string{"--from-dsn", "postgres://u@localhost/db", "--db-pass", "x"}, "--db-pass does not apply to --from-dsn"},
		{[]string{"--exclude-table", "flyway_schema_history"}, "--exclude-table applies only to --from-dsn"},
	} {
		cmd := newDBSquashCommand()
		cmd.SetArgs(tc.args)
		cmd.SetOut(&bytes.Buffer{})
		cmd.SetErr(&bytes.Buffer{})
		if err := cmd.Execute(); err == nil || !strings.Contains(err.Error(), tc.want) {
			t.Errorf("%v: err = %v, want %q", tc.args, err, tc.want)
		}
	}
}

// goose's table read the way migratekit's adoption reads it: the latest row
// for a version decides, and version 0 is goose's own.
func TestReadGooseHistory(t *testing.T) {
	if testing.Short() {
		t.Skip("needs a real postgres server")
	}
	db := openScratch(t, scratchDatabase(t))
	if h, err := readGooseHistory(t.Context(), db); h != nil || err != nil {
		t.Fatalf("no goose table: got %+v, %v", h, err)
	}
	mustExec(t, db, `CREATE TABLE goose_db_version (
		id integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
		version_id bigint NOT NULL, is_applied boolean NOT NULL, tstamp timestamp NOT NULL DEFAULT now())`)
	mustExec(t, db, "INSERT INTO goose_db_version (version_id, is_applied) VALUES (0, true)")
	if _, err := readGooseHistory(t.Context(), db); err == nil || !strings.Contains(err.Error(), "records no applied migration") {
		t.Errorf("a goose table holding only goose's own row: err = %v", err)
	}
	mustExec(t, db, "INSERT INTO goose_db_version (version_id, is_applied) VALUES (3, true), (1, true), (2, true), (2, false)")
	h, err := readGooseHistory(t.Context(), db)
	if err != nil || h == nil || !slices.Equal(h.Versions, []int64{1, 3}) {
		t.Errorf("got %+v, %v; want versions [1 3] (2 was rolled back)", h, err)
	}

	mustExec(t, db, "CREATE TABLE flyway_schema_history (installed_rank int)")
	mustExec(t, db, "CREATE TABLE invoices (id int)")
	got, err := historyLookalikes(t.Context(), db, squashBookkeepingTables)
	if err != nil || !slices.Equal(got, []string{"public.flyway_schema_history"}) {
		t.Errorf("lookalikes = %v, %v; want flyway's table and not goose's (excluded)", got, err)
	}
	if got, _ := historyLookalikes(t.Context(), db, append(slices.Clone(squashBookkeepingTables), "public.flyway_schema_history")); len(got) != 0 {
		t.Errorf("an excluded table is still listed: %v", got)
	}
}

func mustExec(t *testing.T, db *sql.DB, q string) {
	t.Helper()
	if _, err := db.Exec(q); err != nil {
		t.Fatalf("%s: %v", q, err)
	}
}
