func TestDockerDumpTarget(t *testing.T) {
	for _, tc := range []struct {
		name, dsn, goos string
		target          string
		net             []string
		password        string
	}{
		{
			name:   "linux shares the host network, so a loopback DSN works as written",
			dsn:    "postgres://app:s3cret@127.0.0.1:5434/goose_built?sslmode=disable",
			goos:   "linux",
			target: "postgres://app@127.0.0.1:5434/goose_built?sslmode=disable", net: []string{"--network", "host"}, password: "s3cret",
		},
		{
			name:   "Docker Desktop reaches the host's loopback as host.docker.internal",
			dsn:    "postgres://app:s3cret@localhost:5432/goose_built",
			goos:   "darwin",
			target: "postgres://app@host.docker.internal:5432/goose_built", net: []string{"--add-host", "host.docker.internal:host-gateway"}, password: "s3cret",
		},
		{
			name:   "a remote host is reached as written",
			dsn:    "postgresql://app@db.internal:5432/goose_built",
			goos:   "windows",
			target: "postgresql://app@db.internal:5432/goose_built",
		},
	} {
		t.Run(tc.name, func(t *testing.T) {
			target, net, password, err := dockerDumpTarget(tc.dsn, tc.goos)
			if err != nil {
				t.Fatal(err)
			}
			if target != tc.target || !slices.Equal(net, tc.net) || password != tc.password {
				t.Errorf("got (%q, %q, %q), want (%q, %q, %q)", target, net, password, tc.target, tc.net, tc.password)
			}
			if strings.Contains(target, "s3cret") {
				t.Errorf("the password stayed in the DSN docker sees on its command line: %q", target)
			}
		})
	}
}

