//go:build e2e

package cli

import (
	"os"
	"path/filepath"
	"strings"
	"testing"
)

// TestE2EObservedDecoratorGeneratedAndWired is the end-to-end proof of Phase 1
// of the component-middleware feature: the per-package observability decorator
// is GENERATED from the Service interface (replacing the former hand-written
// observe.go), routes every method through the in-process observe.ComponentChain
// assembled in the OWNED observe_chain.go seam, is wired into compose as
// NewServiceWithForgeMiddleware(New(...)), regenerates idempotently, and — the headline win —
// grows a new wrapper automatically when a method is added to the interface
// (no hand-maintenance).
//
// Uses the corpus-style local replace so it pins CURRENT-tree behavior and
// never skips on an unpublished pkg tag.
func TestE2EObservedDecoratorGeneratedAndWired(t *testing.T) {
	t.Parallel() // independent project in its own t.TempDir; binary shared via sync.Once
	forgeBin := buildforgeBinary(t)
	dir := t.TempDir()

	// A service is included so the full service-shaped pipeline runs (a
	// zero-service scaffold would fail to build for reasons unrelated to this
	// feature). The adapter package below is what actually exercises the
	// decorator.
	runCmd(t, dir, forgeBin, "project", "new", "obsdemo", "--mod", "example.com/obsdemo", "--service", "api")
	projectDir := filepath.Join(dir, "obsdemo")
	addCorpusForgePkgReplace(t, projectDir)

	// An adapter is the ideal subject: its New returns the Service interface
	// (fallible), and it ships with a real HealthCheck method — so the
	// decorator wraps something, and the compose emission exercises the
	// fallible NewServiceWithForgeMiddleware(localVar) branch.
	runCmd(t, projectDir, forgeBin, "scaffold", "package", "checkout", "--type", "adapter")

	pkgDir := filepath.Join(projectDir, "internal", "checkout")
	decoratorPath := filepath.Join(pkgDir, "middleware_gen.go")
	seamPath := filepath.Join(pkgDir, "observe_chain.go")

	// The owned seam is scaffolded; the retired hand-written observe.go is not.
	assertPathExistsE2E(t, seamPath)
	if _, err := os.Stat(filepath.Join(pkgDir, "observe.go")); err == nil {
		t.Fatal("legacy hand-written observe.go must not be scaffolded any more")
	}
	if seam := readFileE2E(t, seamPath); !strings.Contains(seam, "func newObserveChain() *observe.ComponentChain {") {
		t.Fatalf("observe_chain.go seam missing newObserveChain builder:\n%s", seam)
	}

	runCmd(t, projectDir, forgeBin, "generate")

	// (1) The decorator is GENERATED (not a hand-written observe.go), Tier-1,
	// and wraps the Service interface's HealthCheck method through the chain.
	assertPathExistsE2E(t, decoratorPath)
	dec := readFileE2E(t, decoratorPath)
	for _, want := range []string{
		"// Code generated by forge. DO NOT EDIT.",
		"func NewServiceWithForgeMiddleware(inner Service) Service {",
		"chain: newObserveChain()",
		"type forgeMiddlewareService struct {",
		`o.chain.Run(ctx, "checkout.HealthCheck", func(ctx context.Context) error {`,
		"return o.inner.HealthCheck(ctx)",
	} {
		if !strings.Contains(dec, want) {
			t.Fatalf("generated decorator missing %q\n---\n%s", want, dec)
		}
	}

	// (2) compose wires the wrapped construction (fallible New form).
	compose := readFileE2E(t, filepath.Join(projectDir, "internal", "app", "compose.go"))
	if !strings.Contains(compose, "checkout.NewServiceWithForgeMiddleware(") {
		t.Fatalf("compose.go did not wire checkout.NewServiceWithForgeMiddleware(...):\n%s", compose)
	}

	// (3) The whole generated tree builds and vets.
	runCmd(t, projectDir, "go", "build", "./...")
	runCmd(t, projectDir, "go", "vet", "./...")

	// (4) generate ×2 is idempotent — the decorator is byte-identical.
	runCmd(t, projectDir, forgeBin, "generate")
	if again := readFileE2E(t, decoratorPath); again != dec {
		t.Fatalf("decorator changed on a second generate (not idempotent):\n--- first ---\n%s\n--- second ---\n%s", dec, again)
	}

	// (5) THE WIN: add a method to the Service interface + its impl, regenerate,
	// and the decorator gains the wrapper AUTOMATICALLY (the old hand-written
	// observe.go would have left the decorator missing the method → build fail).
	// The added method returns (T, error) so this step also covers the
	// chain.Around branch that HealthCheck's bare-error shape does not.
	contractPath := filepath.Join(pkgDir, "contract.go")
	contractSrc := readFileE2E(t, contractPath)
	contractSrc = strings.Replace(contractSrc,
		"HealthCheck(ctx context.Context) error",
		"HealthCheck(ctx context.Context) error\n\n\tLookup(ctx context.Context, id string) (string, error)",
		1)
	if err := os.WriteFile(contractPath, []byte(contractSrc), 0o644); err != nil {
		t.Fatalf("rewrite contract.go: %v", err)
	}
	implPath := filepath.Join(pkgDir, "adapter.go")
	impl := readFileE2E(t, implPath) +
		"\n\n// Lookup is a stub added to exercise decorator regeneration.\nfunc (s *service) Lookup(ctx context.Context, id string) (string, error) { return \"\", nil }\n"
	if err := os.WriteFile(implPath, []byte(impl), 0o644); err != nil {
		t.Fatalf("rewrite adapter.go: %v", err)
	}

	runCmd(t, projectDir, forgeBin, "generate")

	grown := readFileE2E(t, decoratorPath)
	if !strings.Contains(grown, `o.chain.Around(ctx, "checkout.Lookup", func(ctx context.Context) (string, error) {`) {
		t.Fatalf("regenerated decorator did not gain the Lookup wrapper automatically:\n%s", grown)
	}

	// And the grown tree still builds — the decorator's new method keeps the
	// wrapped construction satisfying the (now larger) interface.
	runCmd(t, projectDir, "go", "build", "./...")
}
