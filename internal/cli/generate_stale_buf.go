// Stale buf plugin output.
//
// `buf generate` writes one output file per proto file and never prunes, so
// deleting proto/services/foo/v1/foo.proto left gen/services/foo/v1/foo.pb.go,
// its connect stub and the frontend's foo_pb.ts on disk forever. The
// marker-driven sweep (generate_cleanup.go) cannot see them: protoc-gen-go,
// protoc-gen-connect-go and protoc-gen-es stamp no forge:hash marker. Worse,
// the frontend's service-defaults mocks are emitted from whatever _pb.ts files
// exist, so a leftover stub kept regenerating a mock for the deleted service.
//
// The authorship record here is the plugin's own header, which names the
// proto the file was generated from:
//
//	// Code generated by protoc-gen-go. DO NOT EDIT.   …   // source: <p>.proto
//	// Code generated by protoc-gen-connect-go. …       …   // Source: <p>.proto
//	// @generated by protoc-gen-es …                    // @generated from file <p>.proto (…)
//
// A file under a buf template's `out` directory that carries such a header
// is stale when its source proto exists in none of the project's proto roots.
// It is deleted right after the buf step that owns the directory, so the
// emitters that read those stubs (descriptor, hooks, mocks) never see it.
//
// Guardrails, each one keeping a file rather than guessing:
//   - no recognised plugin header → not buf output, never touched;
//   - the source is in a dependency's namespace (google/, buf/, forge/: the
//     well-known types, BSR deps pulled in by include_imports, and the
//     vendored annotation protos) → never touched;
//   - the source's top-level directory is not a local proto namespace held by
//     exactly one proto root → it came from somewhere this project does not
//     hold, or from a root that cannot be told apart, so absence proves
//     nothing;
//   - the root buf.gen.yaml generates from a non-directory input (a BSR
//     module, a git repository) → nothing is swept;
//   - forge-certified files (forge:hash) belong to the marker sweep;
//   - disowned paths and scaffold.exclude are the user's.
//
// Every delete is journaled (the out directories are also captured before buf
// runs), so a run that fails later restores them.

// bufDependencyNamespaces are source-path prefixes whose generated output is
// never swept: protos a project imports but does not own.
var bufDependencyNamespaces = []string{"google/", "buf/", "forge/"}

// pruneStaleBufOutput deletes the buf plugin output under outDirs whose
// source proto no longer exists, prints what it removed, and returns those
// project-relative paths, sorted.
func pruneStaleBufOutput(ctx *pipelineContext, outDirs []string) []string {
	removed := staleBufOutputs(ctx, outDirs)
	var gone []string
	for _, rel := range removed {
		full := filepath.Join(ctx.ProjectDir, filepath.FromSlash(rel))
		if err := checksums.RemoveJournaled(full); err != nil {
			fmt.Fprintf(os.Stderr, "⚠️  cleanup partial: could not remove %s (%v)\n", full, err)
			continue
		}
		gone = append(gone, rel)
		if root := containingOutDir(full, ctx.ProjectDir, outDirs); root != "" {
			pruneEmptyDirsUpTo(filepath.Dir(full), root)
		}
	}
	if len(gone) > 0 {
		fmt.Printf("🧹 Removed %d stale buf output file(s) — their source proto is gone:\n", len(gone))
		for _, rel := range gone {
			fmt.Printf("  - %s\n", rel)
		}
	}
	return gone
}

// staleBufOutputs lists, without deleting anything, the buf plugin output
// files under outDirs whose source proto is gone. Sorted, slash-separated,
// project-relative.
func staleBufOutputs(ctx *pipelineContext, outDirs []string) []string {
	if ctx == nil || len(outDirs) == 0 {
		return nil
	}
	if bufGenHasRemoteInputs(ctx.ProjectDir) {
		return nil
	}
	roots := protoSourceRoots(ctx.ProjectDir)
	namespaces := localProtoNamespaces(ctx.ProjectDir, roots)
	if len(namespaces) == 0 {
		return nil
	}
	var stale []string
	seen := map[string]bool{}
	for _, dir := range outDirs {
		absDir := filepath.Join(ctx.ProjectDir, filepath.FromSlash(dir))
		_ = filepath.WalkDir(absDir, func(p string, d fs.DirEntry, err error) error {
			if err != nil {
				return nil
			}
			if d.IsDir() {
				if d.Name() == "node_modules" || (p != absDir && strings.HasPrefix(d.Name(), ".")) {
					return filepath.SkipDir
				}
				return nil
			}
			if !d.Type().IsRegular() {
				return nil
			}
			rel, relErr := filepath.Rel(ctx.ProjectDir, p)
			if relErr != nil {
				return nil
			}
			rel = filepath.ToSlash(rel)
			if seen[rel] {
				return nil
			}
			seen[rel] = true
			source, ok := bufOutputSource(p)
			if !ok || !sweepableBufSource(source, namespaces) {
				return nil
			}
			if protoSourceExists(ctx.ProjectDir, roots, source) {
				return nil
			}
			if ctx.Checksums.IsDisowned(rel) {
				return nil
			}
			if _, excluded := checksums.ExcludedBy(ctx.ProjectDir, rel); excluded {
				return nil
			}
			stale = append(stale, rel)
			return nil
		})
	}
	sort.Strings(stale)
	return stale
}

// bufOutputSource reads the leading comment block of a file and returns the
// source proto its protoc plugin header names. ok is false for a file with
// no recognised plugin banner, a forge-certified file, or one whose header
// names no source.
func bufOutputSource(file string) (source string, ok bool) {
	f, err := os.Open(file)
	if err != nil {
		return "", false
	}
	defer func() { _ = f.Close() }()
	head, err := io.ReadAll(io.LimitReader(f, 4096))
	if err != nil {
		return "", false
	}
	return parseBufOutputHeader(head)
}

// parseBufOutputHeader is bufOutputSource over bytes already read.
func parseBufOutputHeader(head []byte) (source string, ok bool) {
	if bytes.Contains(head, []byte("forge:hash=")) {
		return "", false // the marker sweep's
	}
	sc := bufio.NewScanner(bytes.NewReader(head))
	first := true
	for sc.Scan() {
		line := strings.TrimSpace(sc.Text())
		if first {
			first = false
			goBanner := strings.HasPrefix(line, "// Code generated by protoc-gen-") && strings.Contains(line, "DO NOT EDIT")
			esBanner := strings.HasPrefix(line, "// @generated by protoc-gen-")
			if !goBanner && !esBanner {
				return "", false
			}
			continue
		}
		if !strings.HasPrefix(line, "//") {
			if line == "" {
				continue
			}
			break // end of the header comment block
		}
		body := strings.TrimSpace(strings.TrimPrefix(line, "//"))
		switch {
		case strings.HasPrefix(body, "source: "):
			source = strings.TrimSpace(strings.TrimPrefix(body, "source: "))
		case strings.HasPrefix(body, "Source: "):
			source = strings.TrimSpace(strings.TrimPrefix(body, "Source: "))
		case strings.HasPrefix(body, "@generated from file "):
			source = strings.TrimSpace(strings.TrimPrefix(body, "@generated from file "))
			if i := strings.Index(source, " ("); i >= 0 {
				source = source[:i]
			}
		default:
			continue
		}
		if strings.HasSuffix(source, ".proto") {
			return source, true
		}
		return "", false
	}
	return "", false
}

// sweepableBufSource reports whether output generated from source may be
// swept at all: a clean relative .proto path, outside every dependency
// namespace, whose top-level directory is one of the project's own proto
// namespaces.
func sweepableBufSource(source string, namespaces map[string]bool) bool {
	clean := cleanProjectRel(source)
	if clean == "" || clean != source {
		return false
	}
	for _, ns := range bufDependencyNamespaces {
		if strings.HasPrefix(source, ns) {
			return false
		}
	}
	top, _, found := strings.Cut(source, "/")
	return found && namespaces[top]
}

// protoSourceRoots are the directories a source path in a plugin header may
// be relative to: every module path buf.yaml declares, every `directory`
// input of the root buf.gen.yaml, proto/ (forge's default) and the project
// root. Listing extra roots only ever keeps more files.
func protoSourceRoots(projectDir string) []string {
	roots := []string{"proto", "."}
	if data, err := os.ReadFile(filepath.Join(projectDir, "buf.yaml")); err == nil {
		var cfg struct {
			Modules []struct {
				Path string `yaml:"path"`
			} `yaml:"modules"`
		}
		if yaml.Unmarshal(data, &cfg) == nil {
			for _, m := range cfg.Modules {
				if p := cleanProjectRel(m.Path); p != "" {
					roots = append(roots, p)
				}
			}
		}
	}
	if data, err := os.ReadFile(filepath.Join(projectDir, "buf.gen.yaml")); err == nil {
		var tmpl struct {
			Inputs []struct {
				Directory string `yaml:"directory"`
			} `yaml:"inputs"`
		}
		if yaml.Unmarshal(data, &tmpl) == nil {
			for _, in := range tmpl.Inputs {
				if p := cleanProjectRel(in.Directory); p != "" {
					roots = append(roots, p)
				}
			}
		}
	}
	return dedupeSorted(roots)
}

// localProtoNamespaces are the top-level directories that exactly ONE proto
// root (other than the project root itself) holds .proto files under: the
// namespaces whose output can be traced to the root it was generated from.
// A namespace two roots share (proto/services and api/services) is left out,
// so its output is never swept: a source path is relative to whichever root
// produced it, and its absence from one root proves nothing about another.
func localProtoNamespaces(projectDir string, roots []string) map[string]bool {
	holders := map[string]int{}
	for _, root := range roots {
		if root == "." {
			continue
		}
		absRoot := filepath.Join(projectDir, filepath.FromSlash(root))
		entries, err := os.ReadDir(absRoot)
		if err != nil {
			continue
		}
		for _, e := range entries {
			if !e.IsDir() || strings.HasPrefix(e.Name(), ".") {
				continue
			}
			if dirHoldsProto(filepath.Join(absRoot, e.Name())) {
				holders[e.Name()]++
			}
		}
	}
	out := map[string]bool{}
	for ns, n := range holders {
		if n == 1 {
			out[ns] = true
		}
	}
	return out
}

// bufGenHasRemoteInputs reports whether the root buf.gen.yaml generates from
// any input that is not a local directory (a BSR module, a git repository, a
// tarball, a proto_file…). Output from such an input names a source this
// project does not hold, so nothing is swept for it.
func bufGenHasRemoteInputs(projectDir string) bool {
	data, err := os.ReadFile(filepath.Join(projectDir, "buf.gen.yaml"))
	if err != nil {
		return false
	}
	var tmpl struct {
		Inputs []map[string]any `yaml:"inputs"`
	}
	if yaml.Unmarshal(data, &tmpl) != nil {
		return true // unreadable: assume the worst
	}
	for _, in := range tmpl.Inputs {
		if _, local := in["directory"]; !local {
			return true
		}
	}
	return false
}

func dirHoldsProto(dir string) bool {
	found := false
	_ = filepath.WalkDir(dir, func(p string, d fs.DirEntry, err error) error {
		if err != nil {
			return nil
		}
		if !d.IsDir() && strings.HasSuffix(d.Name(), ".proto") {
			found = true
			return filepath.SkipAll
		}
		return nil
	})
	return found
}

// protoSourceExists reports whether source names a file under any root.
func protoSourceExists(projectDir string, roots []string, source string) bool {
	for _, root := range roots {
		if _, err := os.Stat(filepath.Join(projectDir, filepath.FromSlash(path.Join(root, source)))); err == nil {
			return true
		}
	}
	return false
}

// containingOutDir returns the absolute out directory (of outDirs) that
// holds file, the deepest when they nest; "" when none does.
func containingOutDir(file, projectDir string, outDirs []string) string {
	best := ""
	for _, o := range outDirs {
		abs := filepath.Join(projectDir, filepath.FromSlash(o))
		if strings.HasPrefix(file, abs+string(filepath.Separator)) && len(abs) > len(best) {
			best = abs
		}
	}
	return best
}
