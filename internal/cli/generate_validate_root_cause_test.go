// TestRunGoBuildValidate_RootCauseQuotesFirstCompilerError pins the ROOT
// CAUSE line of a failed validate build against a REAL `go build`.
//
// Dogfood evidence (roofers): generate stopped emitting an op that a
// hand-written sibling file called. The ROOT CAUSE line read
//
//	go build failed: exit status 1. Fix: ensure all referenced types are imported and re-run 'forge generate'
//
// — the advice was wrong and the actual error, `invoice_ops.go:64:10:
// s.crudCreatePaymentOp undefined`, was only in the compiler dump further
// down. The line must quote the first compiler error (file:line:col and
// message) and say whose file it is.
func TestRunGoBuildValidate_RootCauseQuotesFirstCompilerError(t *testing.T) {
	t.Setenv("GOWORK", "off") // the temp module must not join an ambient workspace
	projectDir := t.TempDir()
	write := func(rel, body string) {
		t.Helper()
		path := filepath.Join(projectDir, rel)
		if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(path, []byte(body), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	write("go.mod", "module example.com/rootcause\n\ngo 1.22\n")
	write("internal/handlers/invoices/service.go", "package invoices\n\ntype Service struct{}\n")
	// The hand-written sibling, calling an op this generate did not emit.
	write("internal/handlers/invoices/invoice_ops.go", "package invoices\n\n"+
		"func (s *Service) CreatePayment() error {\n"+
		"\treturn s.crudCreatePaymentOp()\n"+
		"}\n")

	err := runGoBuildValidate(projectDir)
	if err == nil {
		t.Fatal("runGoBuildValidate succeeded on a package that does not compile")
	}

	var report strings.Builder
	writeRollbackReport(&report, rollbackReport{StepErr: err, Consistency: rollbackConsistency{Checked: true, Builds: true}})
	lines := strings.Split(report.String(), "\n")
	rootCause := ""
	for i, line := range lines {
		if strings.Contains(line, rollbackRootCauseMarker) && i+1 < len(lines) {
			rootCause = lines[i+1]
			break
		}
	}
	if rootCause == "" {
		t.Fatalf("no ROOT CAUSE line in the report:\n%s", report.String())
	}

	for _, want := range []string{
		// Verbatim, so in the compiler's own spelling: go build prints the
		// path with the platform separator (internal\handlers\... on Windows).
		filepath.FromSlash("internal/handlers/invoices/invoice_ops.go") + ":4:11: s.crudCreatePaymentOp undefined",
		"invoice_ops.go is hand-written",
	} {
		if !strings.Contains(rootCause, want) {
			t.Errorf("ROOT CAUSE line must contain %q, got:\n%s", want, rootCause)
		}
	}
	for _, bad := range []string{"exit status 1", "ensure all referenced types are imported"} {
		if strings.Contains(rootCause, bad) {
			t.Errorf("ROOT CAUSE line must not say %q, got:\n%s", bad, rootCause)
		}
	}
}

// TestCompilerErrorLines counts errors, not output lines: package headers,
// indented continuations and the compiler's "too many errors" notice are
// not errors, so they must not inflate the "+N more" count.
func TestCompilerErrorLines(t *testing.T) {
	out := "# example.com/app/internal/db\n" +
		"internal/db/a_gen.go:1:2: undefined: crud.UpdateOption\n" +
		"internal/db/b_gen.go:3:4: cannot use x (variable of type int) as string value in argument to f\n" +
		"\thave (int)\n\twant (string)\n" +
		"internal/db/b_gen.go:9:9: too many errors\n"
	got := compilerErrorLines(out)
	want := []string{
		"internal/db/a_gen.go:1:2: undefined: crud.UpdateOption",
		"internal/db/b_gen.go:3:4: cannot use x (variable of type int) as string value in argument to f",
	}
	if strings.Join(got, "\n") != strings.Join(want, "\n") {
		t.Errorf("compilerErrorLines() =\n%s\nwant\n%s", strings.Join(got, "\n"), strings.Join(want, "\n"))
	}
}

// TestRunGoBuildValidate_RootCauseNamesGeneratedFile: when the first error
// cites a generated file, the remedy is its inputs, not the file.
func TestRunGoBuildValidate_RootCauseNamesGeneratedFile(t *testing.T) {
	t.Setenv("GOWORK", "off")
	projectDir := t.TempDir()
	if err := os.WriteFile(filepath.Join(projectDir, "go.mod"), []byte("module example.com/rootcause\n\ngo 1.22\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	gen := "// Code generated by forge. DO NOT EDIT.\n\npackage rootcause\n\nvar x = undefinedThing\n"
	if err := os.WriteFile(filepath.Join(projectDir, "thing_gen.go"), []byte(gen), 0o644); err != nil {
		t.Fatal(err)
	}

	err := runGoBuildValidate(projectDir)
	if err == nil {
		t.Fatal("runGoBuildValidate succeeded on a package that does not compile")
	}
	msg := err.Error()
	for _, want := range []string{"thing_gen.go:5:9: undefined: undefinedThing", "thing_gen.go is generated — do not edit it"} {
		if !strings.Contains(msg, want) {
			t.Errorf("error must contain %q, got:\n%s", want, msg)
		}
	}
}
