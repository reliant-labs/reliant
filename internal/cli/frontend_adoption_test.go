// frontend_adoption_test.go — generate into a frontend forge did not
// scaffold (config.FrontendConfig.Adopted). Each test is one of the four
// collisions adopting reliant's web app produced (P9 plan §2, C1-C4): 0 → 149
// TypeScript errors from a single `forge generate`.

func writeAdoptionFile(t *testing.T, root, rel, body string) {
	t.Helper()
	p := filepath.Join(root, filepath.FromSlash(rel))
	if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(p, []byte(body), 0o644); err != nil {
		t.Fatal(err)
	}
}

func readAdoptionFile(t *testing.T, root, rel string) string {
	t.Helper()
	b, err := os.ReadFile(filepath.Join(root, filepath.FromSlash(rel)))
	if err != nil {
		t.Fatalf("read %s: %v", rel, err)
	}
	return string(b)
}

func leftAloneFor(rel string) (string, bool) {
	for _, l := range checksums.LeftAloneThisRun() {
		if l.Path == rel {
			return l.Why, true
		}
	}
	return "", false
}

func adoptedWeb(feType string) config.FrontendConfig {
	fe := config.FrontendConfig{Name: "web", Type: feType}.WithDir("frontends/web")
	fe.Adopted = true
	return fe
}

// C4: the starter set is not installed into an adopted frontend at all.
func TestAdoptedFrontendGetsNoStarterComponents(t *testing.T) {
	dir := t.TempDir()
	writeAdoptionFile(t, dir, "frontends/web/src/components/Button.tsx", "export const Button = 1;\n")
	cfg := &config.ProjectConfig{Name: "app", Frontends: []config.FrontendConfig{adoptedWeb("vite-spa")}}
	if err := ensureFrontendComponents(cfg, dir); err != nil {
		t.Fatalf("ensureFrontendComponents: %v", err)
	}
	if _, err := os.Stat(filepath.Join(dir, "frontends/web/src/components/ui")); !os.IsNotExist(err) {
		t.Fatalf("an adopted frontend got src/components/ui (err=%v)", err)
	}
}

// C1: one writer per stub directory.
func TestTSStubOwnership(t *testing.T) {
	rootTemplate := `version: v2
plugins:
  - local: [node, tools/protoc-gen-es/node_modules/protoc-gen-es-v2.15.0/bin/protoc-gen-es]
    out: frontends/web/src/gen
    include_imports: true
    opt:
      - target=ts
      - ts_nocheck=true
`
	t.Run("a root template writing src/gen makes the stubs project-owned", func(t *testing.T) {
		dir := t.TempDir()
		writeAdoptionFile(t, dir, "buf.gen.yaml", rootTemplate)
		writeAdoptionFile(t, dir, "frontends/web/package.json", "{}")
		got, err := decideTSStubOwnership(dir, "web", "frontends/web")
		if err != nil || got != tsStubsProject {
			t.Fatalf("decideTSStubOwnership = %v, %v; want project-owned", got, err)
		}
		// The whole frontend went through runBufGenerateTypeScript and wrote
		// no template of its own: a second writer is never created.
		fe := config.FrontendConfig{Name: "web", Type: "vite-spa"}.WithDir("frontends/web")
		if err := runBufGenerateTypeScript(fe, &config.ProjectConfig{Name: "app"}, dir); err != nil {
			t.Fatalf("runBufGenerateTypeScript: %v", err)
		}
		if _, err := os.Stat(filepath.Join(dir, "frontends/web/buf.gen.yaml")); !os.IsNotExist(err) {
			t.Fatalf("forge wrote frontends/web/buf.gen.yaml beside the project's template (err=%v)", err)
		}
	})
	t.Run("a nested out (buf.gen.controlplane.yaml → src/gen/controlplane) is not the src/gen writer", func(t *testing.T) {
		dir := t.TempDir()
		writeAdoptionFile(t, dir, "buf.gen.controlplane.yaml", strings.ReplaceAll(rootTemplate, "src/gen", "src/gen/controlplane"))
		if got, err := decideTSStubOwnership(dir, "web", "frontends/web"); err != nil || got != tsStubsForge {
			t.Fatalf("decideTSStubOwnership = %v, %v; want forge", got, err)
		}
	})
	t.Run("the project's template and forge's per-frontend one is two writers", func(t *testing.T) {
		dir := t.TempDir()
		writeAdoptionFile(t, dir, "buf.gen.yaml", rootTemplate)
		writeAdoptionFile(t, dir, "frontends/web/buf.gen.yaml", "version: v2\nplugins:\n  - local: ./frontends/web/node_modules/.bin/protoc-gen-es\n    out: frontends/web/src/gen\n")
		_, err := decideTSStubOwnership(dir, "web", "frontends/web")
		if err == nil {
			t.Fatal("two writers for frontends/web/src/gen were accepted")
		}
		for _, want := range []string{"buf.gen.yaml (node tools/protoc-gen-es", "frontends/web/buf.gen.yaml", "delete frontends/web/buf.gen.yaml"} {
			if !strings.Contains(err.Error(), want) {
				t.Errorf("refusal does not name %q:\n%v", want, err)
			}
		}
	})
	t.Run("stubs from an undeclared generator are left alone and named", func(t *testing.T) {
		checksums.ResetPerRunState()
		dir := t.TempDir()
		writeAdoptionFile(t, dir, "frontends/web/src/gen/app/v1/app_pb.ts",
			"// @generated by protoc-gen-es v2.15.0 with parameter \"target=ts,ts_nocheck=true\"\n// @ts-nocheck\n")
		got, err := decideTSStubOwnership(dir, "web", "frontends/web")
		if err != nil || got != tsStubsForeign {
			t.Fatalf("decideTSStubOwnership = %v, %v; want foreign", got, err)
		}
		why, ok := leftAloneFor("frontends/web/src/gen")
		if !ok || !strings.Contains(why, `protoc-gen-es v2.15.0 with parameter "target=ts,ts_nocheck=true"`) {
			t.Fatalf("the summary does not name the foreign stubs: %q", why)
		}
	})
	t.Run("a template whose out still names the directory the frontend moved from is named", func(t *testing.T) {
		checksums.ResetPerRunState()
		dir := t.TempDir()
		writeAdoptionFile(t, dir, "buf.gen.yaml", strings.ReplaceAll(rootTemplate, "frontends/web/src/gen", "web/src/gen"))
		writeAdoptionFile(t, dir, "frontends/web/src/gen/app/v1/app_pb.ts",
			"// @generated by protoc-gen-es v2.15.0 with parameter \"target=ts,ts_nocheck=true\"\n")
		if got, err := decideTSStubOwnership(dir, "web", "frontends/web"); err != nil || got != tsStubsForeign {
			t.Fatalf("decideTSStubOwnership = %v, %v; want foreign", got, err)
		}
		if why, _ := leftAloneFor("frontends/web/src/gen"); !strings.Contains(why, "buf.gen.yaml still writes web/src/gen") {
			t.Fatalf("the stale out: is not named: %q", why)
		}
	})
	t.Run("stubs forge's own options produced stay forge's", func(t *testing.T) {
		dir := t.TempDir()
		writeAdoptionFile(t, dir, "frontends/web/src/gen/app/v1/app_pb.ts",
			"// @generated by protoc-gen-es v2.10.2 with parameter \"import_extension=.js,target=ts\"\n")
		if got, err := decideTSStubOwnership(dir, "web", "frontends/web"); err != nil || got != tsStubsForge {
			t.Fatalf("decideTSStubOwnership = %v, %v; want forge", got, err)
		}
	})
}

// C2: the hooks barrel never overwrites a hand-written src/hooks/index.ts,
// and the run's summary names it.
func TestHooksBarrelLeavesHandWrittenFile(t *testing.T) {
	checksums.ResetPerRunState()
	dir := t.TempDir()
	const rel = "frontends/web/src/hooks/index.ts"
	const mine = "export { useFullscreen } from './useFullscreen';\n"
	writeAdoptionFile(t, dir, rel, mine)
	files := []hookFileEntry{{fileName: "user-service-hooks_gen.ts", nsAlias: "userService", symbols: []string{"useGetUser"}}}

	if err := writeHooksBarrel(dir, rel, files, &checksums.FileChecksums{}); err != nil {
		t.Fatalf("writeHooksBarrel: %v", err)
	}
	if got := readAdoptionFile(t, dir, rel); got != mine {
		t.Fatalf("hand-written barrel was rewritten:\n%s", got)
	}
	if why, ok := leftAloneFor(rel); !ok || !strings.Contains(why, "project disown "+rel) {
		t.Fatalf("summary entry = %q, %v", why, ok)
	}

	// forge's own barrel (banner, from any vintage) is still regenerated.
	writeAdoptionFile(t, dir, rel, "// Code generated by forge. DO NOT EDIT.\nexport * from \"./old-hooks_gen\";\n")
	if err := writeHooksBarrel(dir, rel, files, &checksums.FileChecksums{}); err != nil {
		t.Fatalf("writeHooksBarrel: %v", err)
	}
	if got := readAdoptionFile(t, dir, rel); !strings.Contains(got, `export * from "./user-service-hooks_gen";`) {
		t.Fatalf("forge's barrel was not regenerated:\n%s", got)
	}
}

// F9-6: the package.json hooks allowlist narrows which services get hooks.
func TestGenerateFrontendHooksHonoursAllowlist(t *testing.T) {
	dir := t.TempDir()
	fe := adoptedWeb("vite-spa")
	fe.Hooks = []string{"UserService"}
	cfg := &config.ProjectConfig{Name: "app", Frontends: []config.FrontendConfig{fe}}
	services := []codegen.ServiceDef{
		fakeService("UserService", "proto/services/users/v1/users.proto"),
		fakeService("ToolsDaemonService", "proto/services/tools/v1/tools.proto"),
	}
	if err := generateFrontendHooks(cfg, services, dir, nil); err != nil {
		t.Fatalf("generateFrontendHooks: %v", err)
	}
	if _, err := os.Stat(filepath.Join(dir, "frontends/web/src/hooks/user-service-hooks_gen.ts")); err != nil {
		t.Errorf("allowlisted service got no hooks: %v", err)
	}
	if _, err := os.Stat(filepath.Join(dir, "frontends/web/src/hooks/tools-daemon-service-hooks_gen.ts")); !os.IsNotExist(err) {
		t.Errorf("a service outside the allowlist got hooks (err=%v)", err)
	}
}

// C3: the seams the generated hooks import are scaffolded once into an
// adopted frontend, and never over the app's own.
func TestAdoptedFrontendSeams(t *testing.T) {
	services := []codegen.ServiceDef{fakeService("UserService", "proto/services/users/v1/users.proto")}

	t.Run("missing seams are scaffolded once", func(t *testing.T) {
		checksums.ResetPerRunState()
		dir := t.TempDir()
		writeAdoptionFile(t, dir, "forge.yaml", "name: app\n")
		cfg := &config.ProjectConfig{Name: "app", Frontends: []config.FrontendConfig{adoptedWeb("vite-spa")}}
		if err := ensureAdoptedFrontendSeams(cfg, services, dir); err != nil {
			t.Fatalf("ensureAdoptedFrontendSeams: %v", err)
		}
		connect := readAdoptionFile(t, dir, "frontends/web/src/lib/connect.ts")
		for _, want := range []string{"export function connectClient", "export function setTransport", "service.typeName"} {
			if !strings.Contains(connect, want) {
				t.Errorf("connect.ts lacks %q", want)
			}
		}
		readAdoptionFile(t, dir, "frontends/web/src/lib/api-base.ts")
		if !strings.Contains(readAdoptionFile(t, dir, "frontends/web/src/lib/test-utils.tsx"), "export function mockTransport") {
			t.Error("test-utils.tsx lacks mockTransport")
		}
		if !checksums.ScaffoldRecorded(dir, "frontends/web/src/lib/connect.ts") {
			t.Error("the birth was not recorded, so a deletion would read as never-born")
		}

		// Deleted on purpose: not written again, and named.
		if err := os.Remove(filepath.Join(dir, "frontends/web/src/lib/test-utils.tsx")); err != nil {
			t.Fatal(err)
		}
		if err := ensureAdoptedFrontendSeams(cfg, services, dir); err != nil {
			t.Fatalf("ensureAdoptedFrontendSeams (2nd): %v", err)
		}
		if _, err := os.Stat(filepath.Join(dir, "frontends/web/src/lib/test-utils.tsx")); !os.IsNotExist(err) {
			t.Error("a deleted seam was scaffolded again")
		}
		if why, ok := leftAloneFor("frontends/web/src/lib/test-utils.tsx"); !ok || !strings.Contains(why, "@/lib/test-utils") {
			t.Errorf("summary entry = %q, %v", why, ok)
		}
	})
	t.Run("the app's own connect.ts is the seam", func(t *testing.T) {
		dir := t.TempDir()
		writeAdoptionFile(t, dir, "forge.yaml", "name: app\n")
		const mine = "export const connectClient = () => null;\n"
		writeAdoptionFile(t, dir, "frontends/web/src/lib/connect.ts", mine)
		cfg := &config.ProjectConfig{Name: "app", Frontends: []config.FrontendConfig{adoptedWeb("vite-spa")}}
		if err := ensureAdoptedFrontendSeams(cfg, services, dir); err != nil {
			t.Fatal(err)
		}
		if got := readAdoptionFile(t, dir, "frontends/web/src/lib/connect.ts"); got != mine {
			t.Fatalf("connect.ts was rewritten:\n%s", got)
		}
	})
	t.Run("no seams for a frontend forge scaffolded, or one that gets no hooks", func(t *testing.T) {
		dir := t.TempDir()
		writeAdoptionFile(t, dir, "forge.yaml", "name: app\n")
		scaffolded := config.FrontendConfig{Name: "web", Type: "vite-spa"}.WithDir("frontends/web")
		noHooks := adoptedWeb("vite-spa")
		noHooks.Name = "other"
		noHooks = noHooks.WithDir("frontends/other")
		noHooks.Adopted, noHooks.Hooks = true, []string{}
		cfg := &config.ProjectConfig{Name: "app", Frontends: []config.FrontendConfig{scaffolded, noHooks}}
		if err := ensureAdoptedFrontendSeams(cfg, services, dir); err != nil {
			t.Fatal(err)
		}
		for _, rel := range []string{"frontends/web/src/lib/connect.ts", "frontends/other/src/lib/connect.ts"} {
			if _, err := os.Stat(filepath.Join(dir, rel)); !os.IsNotExist(err) {
				t.Errorf("%s was scaffolded (err=%v)", rel, err)
			}
		}
	})
}
