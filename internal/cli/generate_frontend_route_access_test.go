package cli

import (
	"os"
	"path/filepath"
	"strings"
	"testing"

	"github.com/reliant-labs/forge/internal/checksums"
	"github.com/reliant-labs/forge/internal/config"
)

// TestGenerateFrontendNav_EmitsRouteAccess pins src/lib/auth/route-access_gen.ts
// as a Tier-1 file every scaffolded browser frontend gets on `forge generate`.
//
// The scaffolded nav.tsx imports useCanVisit from it, and a pristine nav.tsx is
// refreshed in EXISTING projects too (emitScaffoldUntilTouched). Were the
// module only in the scaffold tree, that refresh would hand a project
// scaffolded before it a nav importing a file it does not have, and
// `tsc --noEmit` would fail on the next generate.
func TestGenerateFrontendNav_EmitsRouteAccess(t *testing.T) {
	projectDir := t.TempDir()
	cfg := &config.ProjectConfig{
		Name: "demo",
		Frontends: []config.FrontendConfig{
			{Name: "web", Type: "nextjs"},
			{Name: "spa", Type: "vite-spa"},
			{Name: "adopted", Type: "nextjs", Adopted: true},
		},
	}
	cs := &checksums.FileChecksums{}

	if err := generateFrontendNav(cfg, nil, projectDir, nil, cs); err != nil {
		t.Fatalf("generateFrontendNav: %v", err)
	}

	for _, fe := range []string{"web", "spa"} {
		rel := filepath.Join("frontends", fe, "src", "lib", "auth", "route-access_gen.ts")
		body, err := os.ReadFile(filepath.Join(projectDir, rel))
		if err != nil {
			t.Fatalf("%s: expected route-access_gen.ts after generate, got: %v", fe, err)
		}
		for _, want := range []string{
			"// Code generated by forge. DO NOT EDIT.",
			// The nav reads this hook and the route guard provides this
			// context; renaming either breaks an owned file that imports it.
			"export function useCanVisit(): CanVisit",
			"export const RouteAccessContext = createContext<CanVisit>(everyRoute);",
		} {
			if !strings.Contains(string(body), want) {
				t.Errorf("%s: route-access_gen.ts missing %q", fe, want)
			}
		}
		if got := checksums.Verify(body); got != checksums.Pristine {
			t.Errorf("%s: route-access_gen.ts Verify = %v, want Pristine", fe, got)
		}
	}

	nav, err := os.ReadFile(filepath.Join(projectDir, "frontends", "web", "src", "components", "nav.tsx"))
	if err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(string(nav), `import { useCanVisit } from "@/lib/auth/route-access_gen";`) {
		t.Errorf("nav.tsx does not filter its routes through useCanVisit")
	}

	// An adopted app has its own layout and auth; forge writes no starter
	// plumbing into it.
	if _, err := os.Stat(filepath.Join(projectDir, "frontends", "adopted", "src", "lib", "auth", "route-access_gen.ts")); !os.IsNotExist(err) {
		t.Errorf("an adopted frontend got route-access_gen.ts (stat err = %v)", err)
	}
}
