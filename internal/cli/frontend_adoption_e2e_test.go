//go:build e2e

package cli

import (
	"os"
	"path/filepath"
	"strings"
	"testing"
)

// TestE2EGenerateIntoAdoptedFrontend drives the real binary over the shape
// that broke adopting reliant's web app (P9 plan §2): an existing Vite app
// moved under frontends/, with its own hooks barrel, its own PascalCase
// components, its own package.json and TypeScript stubs from its own
// generator. One `forge generate` used to take it from 0 to 149 TypeScript
// errors. Now forge writes only Tier-1 codegen plus the seams that code
// imports, leaves every one of the app's files byte-identical, names what it
// declined in the summary, and stays that way on a second run (the births it
// records inside the frontend must not turn it into a "scaffolded" one).
func TestE2EGenerateIntoAdoptedFrontend(t *testing.T) {
	t.Parallel() // independent project in its own t.TempDir; binary shared via sync.Once
	forgeBin := buildforgeBinary(t)
	dir := t.TempDir()

	runCmd(t, dir, forgeBin, "project", "new", "adopt", "--mod", "example.com/adopt", "--service", "users")
	projectDir := filepath.Join(dir, "adopt")
	addCorpusForgePkgReplace(t, projectDir)

	// One custom rpc, so the service has hooks to generate (and the hooks
	// have seams to import).
	protoPath := filepath.Join(projectDir, "proto", "services", "users", "v1", "users.proto")
	proto := readFileE2E(t, protoPath)
	open := strings.Index(proto, "\nservice ")
	brace := strings.Index(proto[open:], "{")
	if open < 0 || brace < 0 {
		t.Fatalf("no service block in %s:\n%s", protoPath, proto)
	}
	at := open + brace + 1
	proto = proto[:at] + "\n  rpc GetGreeting(GetGreetingRequest) returns (GetGreetingResponse);\n" + proto[at:] +
		"\nmessage GetGreetingRequest {}\nmessage GetGreetingResponse { string text = 1; }\n"
	if err := os.WriteFile(protoPath, []byte(proto), 0o644); err != nil {
		t.Fatal(err)
	}
	runCmd(t, projectDir, forgeBin, "scaffold")

	app := filepath.Join(projectDir, "frontends", "legacy")
	own := map[string]string{
		"vite.config.ts":                     "export default {};\n",
		"package.json":                       "{\n  \"name\": \"legacy\",\n  \"private\": true,\n  \"dependencies\": {\n    \"@reliantlabs/forge-web-runtime\": \"^0.5.0\"\n  }\n}\n",
		"src/hooks/index.ts":                 "export { useFullscreen } from \"./useFullscreen\";\n",
		"src/components/ui/Button.tsx":       "export const Button = () => null;\n",
		"src/gen/legacy/v1/legacy_pb.ts":     "// @generated by protoc-gen-es v2.15.0 with parameter \"target=ts,ts_nocheck=true\"\n// @ts-nocheck\nexport {};\n",
		"src/components/forge-ui/status.tsx": "export const Status = () => null;\n",
	}
	for rel, body := range own {
		writeFileE2E(t, filepath.Join(app, filepath.FromSlash(rel)), body)
	}

	generate := func() string {
		t.Helper()
		return runCmdOutput(t, projectDir, forgeBin, "generate")
	}
	out := generate()

	for rel, body := range own {
		if got := readFileE2E(t, filepath.Join(app, filepath.FromSlash(rel))); got != body {
			t.Errorf("forge changed the app's own %s:\n%s", rel, got)
		}
	}
	// C4: no starter set, no case collision, no CRUD/nav starter code.
	for _, rel := range []string{"src/components/ui/button.tsx", "src/components/ui/login_form.tsx", "src/hooks/use-query-resource.ts", "buf.gen.yaml"} {
		if _, err := os.Stat(filepath.Join(app, filepath.FromSlash(rel))); !os.IsNotExist(err) {
			t.Errorf("generate wrote %s into an adopted frontend (err=%v)", rel, err)
		}
	}
	// Tier-1 codegen + the seams it imports did land.
	if hooks, _ := filepath.Glob(filepath.Join(app, "src", "hooks", "*-service-hooks_gen.ts")); len(hooks) == 0 {
		t.Error("adopted frontend got no generated hooks")
	}
	for _, rel := range []string{"src/lib/apiurl_gen.ts", "src/lib/connect.ts", "src/lib/api-base.ts", "src/lib/test-utils.tsx"} {
		if _, err := os.Stat(filepath.Join(app, filepath.FromSlash(rel))); err != nil {
			t.Errorf("adopted frontend is missing %s: %v", rel, err)
		}
	}
	// C1 + C2 are named in the closing summary, not just mid-run.
	summary := out[strings.LastIndex(out, "Code generation complete"):]
	for _, want := range []string{"frontends/legacy/src/hooks/index.ts: a hand-written file", "frontends/legacy/src/gen: holds TypeScript stubs from protoc-gen-es v2.15.0"} {
		if !strings.Contains(summary, want) {
			t.Errorf("summary does not name %q:\n%s", want, summary)
		}
	}
	if !strings.Contains(out, "bump it when you review") {
		t.Errorf("the package.json runtime bump was neither made nor reported:\n%s", out)
	}

	// Second run: still adopted, still nothing of the app's touched.
	generate()
	if _, err := os.Stat(filepath.Join(app, "src", "components", "ui", "card.tsx")); !os.IsNotExist(err) {
		t.Fatalf("the second generate installed the starter set (err=%v): the births of the first made the frontend look scaffolded", err)
	}
	for rel, body := range own {
		if got := readFileE2E(t, filepath.Join(app, filepath.FromSlash(rel))); got != body {
			t.Errorf("second generate changed the app's own %s", rel)
		}
	}
}
