const refundSrc = `package billing

func Refund(x int) int {
	if x < 0 {
		return 0
	}
	return x
}
`

const enumSrc = `// Code generated by forge. DO NOT EDIT.

package billing

func Name() string { return "a" }
`

const refundDiff = `diff --git a/billing/refund.go b/billing/refund.go
index 1..2 100644
--- a/billing/refund.go
+++ b/billing/refund.go
@@ -4,0 +5,1 @@ func Refund(x int) int {
+		return 0
`

func unitCover() string {
	return "mode: atomic\n" +
		fxModule + "/billing/refund.go:3.24,4.11 1 3\n" +
		fxModule + "/billing/refund.go:4.11,6.3 1 0\n" +
		fxModule + "/billing/refund.go:7.2,7.10 1 3\n" +
		fxModule + "/billing/enum.go:5.21,5.35 1 0\n" +
		fxModule + "/billing/mock_gen.go:3.10,3.20 1 0\n"
}

func integrationCover() string {
	return "mode: atomic\n" +
		fxModule + "/billing/refund.go:3.24,4.11 1 1\n" +
		fxModule + "/billing/refund.go:4.11,6.3 1 1\n" +
		fxModule + "/billing/refund.go:7.2,7.10 1 0\n"
}

// fxShop is a project with two clean lanes of one commit.
func fxShop(t *testing.T) (string, *fakeGit) {
	t.Helper()
	root := fxProject(t, map[string]string{"billing/refund.go": refundSrc, "billing/enum.go": enumSrc, "billing/mock_gen.go": "package billing\n"})
	t0 := time.Date(2026, 11, 20, 10, 0, 0, 0, time.UTC)
	fxWriteRun(t, root, fxRun{id: "01AAAA", created: t0, commit: fxCommit, tree: fxTree, branch: "feat", lanes: []fxLane{
		{name: "unit", results: goJSON(fxModule + "/billing:TestRefund:pass"), cover: unitCover()},
	}})
	fxWriteRun(t, root, fxRun{id: "01BBBB", created: t0.Add(time.Minute), commit: fxCommit, tree: fxTree, branch: "feat", lanes: []fxLane{
		{name: "integration", results: goJSON(fxModule + "/billing:TestRefundIT:pass"), cover: integrationCover()},
	}})
	g := &fakeGit{top: root, head: fxCommit, diff: refundDiff,
		blobs: blobsOf(t, root, "billing/refund.go", "billing/enum.go", "billing/mock_gen.go", "go.mod")}
	return root, g
}

func TestListAndSelectRuns(t *testing.T) {
	root, _ := fxShop(t)
	fxWriteRun(t, root, fxRun{id: "01CCCC", created: time.Date(2026, 11, 20, 11, 0, 0, 0, time.UTC), commit: fxCommit, tree: "dirtytree", dirty: true,
		lanes: []fxLane{{name: "unit", results: goJSON("p:TestA:pass")}}})
	runs, problems, err := List(root)
	if err != nil || len(problems) > 0 {
		t.Fatalf("List: %v %v", err, problems)
	}
	if got := []string{runs[0].ID, runs[1].ID, runs[2].ID}; strings.Join(got, ",") != "01CCCC,01BBBB,01AAAA" {
		t.Fatalf("not newest first: %v", got)
	}
	if got := CommitRuns(runs, fxCommit[:8]); len(got) != 2 {
		t.Fatalf("CommitRuns kept %d runs; a dirty run must never join a commit's report", len(got))
	}
	if got := TreeRuns(runs, runs[0]); len(got) != 1 || got[0].ID != "01CCCC" {
		t.Fatalf("TreeRuns of the dirty run = %v", got)
	}
	if r, err := Resolve(root, "01bb", runs); err != nil || r.ID != "01BBBB" {
		t.Fatalf("Resolve by prefix: %v %v", r, err)
	}
	if _, err := Resolve(root, "01", runs); err == nil {
		t.Fatal("an ambiguous prefix resolved")
	}
	if runs[1].Lanes[0].ResultsPath() == "" || len(runs[2].Lanes[0].CoverageInputs()) != 1 {
		t.Fatal("lane files not found")
	}
}

func TestAssembleMergesLanesWithRepoPathsAndBlobs(t *testing.T) {
	root, g := fxShop(t)
	runs, _, _ := List(root)
	a, err := Assemble(context.Background(), Options{ProjectRoot: root, Runs: runs, AllRuns: runs, Git: g.run})
	if err != nil {
		t.Fatal(err)
	}
	if len(a.Runs) != 2 || a.Commit != fxCommit || a.Tree != fxTree {
		t.Fatalf("assembly: %+v", a)
	}
	files := map[string]testreport.CoverageFile{}
	for _, f := range a.Coverage.Files {
		files[f.Path] = f
	}
	refund := files["billing/refund.go"]
	if refund.BlobID != g.blobs["billing/refund.go"] || refund.Excluded != "" {
		t.Fatalf("refund.go: path/blob not filled: %+v", refund)
	}
	if files["billing/enum.go"].Excluded != testreport.ExcludedGenerated {
		t.Fatal("a file headed 'Code generated … DO NOT EDIT.' counted")
	}
	if files["billing/mock_gen.go"].Excluded != testreport.ExcludedGenerated {
		t.Fatal("mock_gen.go counted")
	}
	s := a.Coverage.Summary()
	if s.Combined.Pct != 100 || s.Lanes["unit"].Covered != 2 || s.Lanes["integration"].Covered != 2 {
		t.Fatalf("summary: %+v", s)
	}
	if a.BaseSHA != fxBase || len(a.Changed) != 1 || a.Changed[0].Ranges[0] != (testreport.LineRange{Start: 5, End: 5}) {
		t.Fatalf("diff: base %s changed %+v", a.BaseSHA, a.Changed)
	}
	rep := a.Report("")
	if rep.ExitCode != 0 || rep.Project != "shop" || rep.Coverage.Diff.Lines != 1 || rep.Coverage.Diff.Covered != 1 {
		t.Fatalf("report: exit %d, %+v", rep.ExitCode, rep.Coverage)
	}
	if rep.Coverage.Delta != nil || rep.Coverage.DeltaReason == "" {
		t.Fatal("a delta was computed with no base report")
	}
	if rep.Coverage.Excluded.GeneratedStatements != 2 {
		t.Fatalf("generated statements = %d, want 2", rep.Coverage.Excluded.GeneratedStatements)
	}
}

