func TestNonGoPathsBecomeRepoRelative(t *testing.T) {
	// A frontend under the project wrote LCOV with paths relative to its
	// own directory; the project itself sits in a subdirectory of the repo.
	repo := t.TempDir()
	root := filepath.Join(repo, "app")
	src := "export const a = 1\n"
	if err := os.MkdirAll(filepath.Join(root, "frontends/web/src"), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(root, "frontends/web/src/a.ts"), []byte(src), 0o644); err != nil {
		t.Fatal(err)
	}
	fxWriteRun(t, root, fxRun{id: "01X", created: time.Now(), commit: fxCommit, tree: fxTree, lanes: []fxLane{{name: "web", format: testreport.LaneFormatJUnit,
		results: `<testsuites><testsuite name="s"><testcase classname="t" name="ok"/></testsuite></testsuites>`}}})
	ldir := filepath.Join(testreport.RunsRoot(root), "01X", "web")
	if err := os.WriteFile(filepath.Join(ldir, "lcov.info"), []byte("TN:\nSF:src/a.ts\nDA:1,4\nend_of_record\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	g := &fakeGit{top: repo, blobs: map[string]string{"app/frontends/web/src/a.ts": testreport.GitBlobID([]byte(src))}}
	runs, _, _ := List(root)
	a, err := Assemble(context.Background(), Options{ProjectRoot: root, Runs: runs, Git: g.run, NoDiff: true})
	if err != nil {
		t.Fatal(err)
	}
	if len(a.Coverage.Files) != 1 {
		t.Fatalf("files: %+v", a.Coverage.Files)
	}
	f := a.Coverage.Files[0]
	if f.Path != "app/frontends/web/src/a.ts" || f.BlobID == "" {
		t.Fatalf("file: %+v", f)
	}
}

func TestExports(t *testing.T) {
	root, g := fxShop(t)
	runs, _, _ := List(root)
	a, err := Assemble(context.Background(), Options{ProjectRoot: root, Runs: runs, Git: g.run, NoDiff: true})
	if err != nil {
		t.Fatal(err)
	}
	var lcov bytes.Buffer
	if err := WriteLCOV(&lcov, a.Coverage); err != nil {
		t.Fatal(err)
	}
	want := "TN:\nSF:billing/refund.go\nDA:3,4\nDA:4,1\nDA:5,1\nDA:6,1\nDA:7,3\nLF:5\nLH:5\nend_of_record\n"
	if lcov.String() != want {
		t.Fatalf("lcov:\n%s\nwant:\n%s", lcov.String(), want)
	}
	if _, err := testreport.ParseCoverage(bytes.NewReader(lcov.Bytes()), testreport.CoverageOptions{Lane: "x"}); err != nil {
		t.Fatalf("the LCOV export does not parse back: %v", err)
	}
	var cob bytes.Buffer
	if err := WriteCobertura(&cob, a.Coverage, root, time.Unix(0, 0)); err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(cob.String(), `filename="billing/refund.go"`) || !strings.Contains(cob.String(), `lines-valid="5"`) {
		t.Fatalf("cobertura:\n%s", cob.String())
	}
	if _, err := testreport.ParseCoverage(bytes.NewReader(cob.Bytes()), testreport.CoverageOptions{Lane: "x"}); err != nil {
		t.Fatalf("the Cobertura export does not parse back: %v", err)
	}
	var page bytes.Buffer
	if err := WriteHTML(&page, a.Coverage, root, "Coverage <shop>"); err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(page.String(), "return 0") || strings.Contains(page.String(), "<shop>") {
		t.Fatal("the page does not show the matching source, or does not escape")
	}
	// Changed since the run: counts only, never highlights over other source.
	if err := os.WriteFile(filepath.Join(root, "billing/refund.go"), []byte("package billing\n// changed\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	page.Reset()
	if err := WriteHTML(&page, a.Coverage, root, "c"); err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(page.String(), "the file has changed since the run") || strings.Contains(page.String(), "// changed") {
		t.Fatal("the page drew counts over source that is not the run's")
	}
}

// A report already inside the lane it is ingested into is refused before
// anything is written, and it stays byte for byte as it was; a batch with one
// bad input writes none of them.
func TestIngestRefusesAReportInsideItsLane(t *testing.T) {
	root := fxProject(t, map[string]string{})
	dir := fxWriteRun(t, root, fxRun{id: "01X", created: time.Unix(1_700_000_000, 0), commit: fxCommit, tree: fxTree})
	lane := filepath.Join(dir, "py")
	if err := os.MkdirAll(lane, 0o755); err != nil {
		t.Fatal(err)
	}
	lcovBody := []byte("TN:\nSF:a.py\nDA:1,1\nend_of_record\n")
	inside := filepath.Join(lane, "lcov.info")
	if err := os.WriteFile(inside, lcovBody, 0o644); err != nil {
		t.Fatal(err)
	}
	if _, err := Ingest(IngestOptions{RunDir: dir, Lane: "py", Format: "lcov", Files: []string{inside}}); err == nil || !strings.Contains(err.Error(), "already inside lane py") {
		t.Fatalf("a report inside its lane: err %v, want it refused", err)
	}
	if got, err := os.ReadFile(inside); err != nil || !bytes.Equal(got, lcovBody) {
		t.Fatalf("the report inside the lane changed: %q (%v)", got, err)
	}
	if names, _ := os.ReadDir(lane); len(names) != 1 {
		t.Errorf("the refused ingest wrote into the lane: %v", names)
	}

	good := filepath.Join(t.TempDir(), "lcov.info")
	bad := filepath.Join(t.TempDir(), "not-lcov.info")
	if err := os.WriteFile(good, lcovBody, 0o644); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(bad, []byte(`<testsuites></testsuites>`), 0o644); err != nil {
		t.Fatal(err)
	}
	if _, err := Ingest(IngestOptions{RunDir: dir, Lane: "py2", Format: "lcov", Files: []string{good, bad}}); err == nil {
		t.Fatal("a batch with a non-LCOV input was accepted")
	}
	if names, _ := os.ReadDir(filepath.Join(dir, "py2")); len(names) != 0 {
		t.Errorf("a refused batch wrote its good inputs: %v", names)
	}
}

func TestIngest(t *testing.T) {
	root := fxProject(t, map[string]string{})
	dir := fxWriteRun(t, root, fxRun{id: "01X", created: time.Now(), commit: fxCommit, tree: fxTree})
	junit := filepath.Join(t.TempDir(), "report.xml")
	if err := os.WriteFile(junit, []byte(`<testsuites><testsuite name="s"><testcase classname="t" name="ok"/></testsuite></testsuites>`), 0o644); err != nil {
		t.Fatal(err)
	}
	lcov := filepath.Join(t.TempDir(), "lcov.info")
	if err := os.WriteFile(lcov, []byte("TN:\nSF:a.py\nDA:1,1\nend_of_record\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	if _, err := Ingest(IngestOptions{RunDir: dir, Lane: "py", Format: "junit", Files: []string{junit}}); err != nil {
		t.Fatal(err)
	}
	if _, err := Ingest(IngestOptions{RunDir: dir, Lane: "py", Format: "lcov", Files: []string{lcov}}); err != nil {
		t.Fatal(err)
	}
	if _, err := Ingest(IngestOptions{RunDir: dir, Lane: "py", Format: "junit", Files: []string{junit}}); err == nil {
		t.Fatal("a second results file was accepted into one lane")
	}
	if _, err := Ingest(IngestOptions{RunDir: dir, Lane: "py2", Format: "cobertura", Files: []string{lcov}}); err == nil {
		t.Fatal("LCOV was accepted as Cobertura")
	}
	r, err := Open(dir)
	if err != nil {
		t.Fatal(err)
	}
	if len(r.Lanes) != 1 || r.Lanes[0].Results != testreport.LaneResultsParsed || len(r.Lanes[0].Coverage) != 1 {
		t.Fatalf("lane: %+v", r.Lanes)
	}
	if len(r.RunManifest.Lanes) != 1 || r.RunManifest.Lanes[0] != "py" {
		t.Fatalf("run.json lanes: %v", r.RunManifest.Lanes)
	}
	a, err := Assemble(context.Background(), Options{ProjectRoot: root, Runs: []*Run{r}, Git: (&fakeGit{}).run, NoDiff: true})
	if err != nil {
		t.Fatal(err)
	}
	if rep := a.Report(""); rep.ExitCode != 0 || rep.Totals.Passed != 1 || rep.Coverage == nil {
		t.Fatalf("ingested lane not reported: %+v", rep)
	}
}

// A clean run that records no commit is never merged into, or attributed to,
// another run's commit: the commit is never adopted from a sibling run.
func TestAssembleRefusesACleanRunWithNoCommit(t *testing.T) {
	root, g := fxShop(t)
	fxWriteRun(t, root, fxRun{id: "01NOCOMMIT", created: time.Date(2026, 11, 20, 12, 0, 0, 0, time.UTC), tree: fxTree,
		lanes: []fxLane{{name: "integration", results: goJSON("p:TestB:pass")}}})
	all, _, _ := List(root)
	byID := map[string]*Run{}
	for _, r := range all {
		byID[r.ID] = r
	}
	for _, pair := range [][2]string{{"01AAAA", "01NOCOMMIT"}, {"01NOCOMMIT", "01AAAA"}} {
		a, err := Assemble(context.Background(), Options{ProjectRoot: root, Runs: []*Run{byID[pair[0]], byID[pair[1]]}, Git: g.run, NoDiff: true})
		var se *SourceError
		if !errors.As(err, &se) || !strings.Contains(se.Detail, "01NOCOMMIT records no commit") {
			t.Fatalf("%v merged (commit %q): err %v", pair, func() string {
				if a == nil {
					return ""
				}
				return a.Commit
			}(), err)
		}
	}
	// --commit never selects it.
	for _, r := range CommitRuns(all, fxCommit) {
		if r.ID == "01NOCOMMIT" {
			t.Fatal("CommitRuns selected a run that records no commit")
		}
	}
}
