func TestReportExitCodes(t *testing.T) {
	cases := []struct {
		name string
		lane fxLane
		want int
	}{
		{"pass", fxLane{name: "unit", results: goJSON("p:TestA:pass")}, 0},
		{"failure", fxLane{name: "unit", exit: 1, results: goJSON("p:TestA:fail", "p:TestB:pass")}, 1},
		{"no results file", fxLane{name: "unit"}, 2},
		{"exited non-zero with no failure recorded", fxLane{name: "unit", exit: 2, results: goJSON("p:TestA:pass")}, 2},
		{"command never ran", fxLane{name: "unit", exit: 127, errorMsg: "go: not found"}, 2},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			root := fxProject(t, map[string]string{})
			fxWriteRun(t, root, fxRun{id: "01X", created: time.Now(), commit: fxCommit, tree: fxTree, lanes: []fxLane{tc.lane}})
			runs, _, _ := List(root)
			a, err := Assemble(context.Background(), Options{ProjectRoot: root, Runs: runs, Git: (&fakeGit{}).run, NoDiff: true})
			if err != nil {
				t.Fatal(err)
			}
			if got := a.Report("").ExitCode; got != tc.want {
				t.Fatalf("exit %d, want %d (undetermined %v)", got, tc.want, a.Undetermined)
			}
		})
	}
}

