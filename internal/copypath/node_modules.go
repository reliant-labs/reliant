// A copied node_modules is an install, and only an install.
//
// Two things went wrong when it was copied whole into a checkout of another
// revision, and both showed up as errors that blamed the branch:
//
//   - Build output that tools keep under node_modules came along. Vite's
//     tsconfig convention puts `tsc -b`'s outDir and *.tsbuildinfo in
//     node_modules/.tmp. The copies are newer than the new checkout's
//     sources, so `tsc -b` found them up to date and typechecked against the
//     source checkout's declarations: "no exported member
//     DownloadFileRequestSchema" for a symbol the branch's own source has.
//     It survives a frozen install, which leaves .tmp alone.
//   - The install itself may not be the one this checkout's lockfile
//     describes: the source was installed from a different lockfile, or was
//     never reinstalled after its own lockfile moved. vitest then failed at
//     import ("Missing \"./session\" specifier") before any edit.
//
// So Copy drops the build state (it is a cache: whatever made it rebuilds
// it), and StaleInstall says, with the command to run, when the install
// cannot be trusted to match the lockfile beside it. It does not run that
// install itself: the copy carries files, it does not run a project's tools.

// nodeModulesBuildState are the children of a node_modules that hold its
// checkout's build output or tool caches, never installed packages:
// node_modules/.tmp (tsc -b's outDir and tsbuildinfo in Vite's tsconfigs) and
// node_modules/.cache (find-cache-dir's home: babel, eslint, webpack, terser).
// Top-level *.tsbuildinfo files are dropped too. node_modules/.vite is kept:
// Vite keys its dependency cache on the lockfile and config, so it
// invalidates itself.
var nodeModulesBuildState = []string{".tmp", ".cache"}

// isNodeModules reports whether a copy_files entry is a node_modules directory.
func isNodeModules(entry string) bool { return path.Base(entry) == "node_modules" }

// dropBuildState removes nodeModulesBuildState and top-level *.tsbuildinfo
// from a node_modules that was just copied to dir.
func dropBuildState(dir string) error {
	entries, err := os.ReadDir(dir)
	if err != nil {
		return err
	}
	var errs []error
	for _, e := range entries {
		name := e.Name()
		drop := strings.HasSuffix(name, ".tsbuildinfo")
		for _, state := range nodeModulesBuildState {
			drop = drop || name == state
		}
		if drop {
			if err := os.RemoveAll(filepath.Join(dir, name)); err != nil {
				errs = append(errs, fmt.Errorf("drop the source checkout's build state %s: %w", name, err))
			}
		}
	}
	return errors.Join(errs...)
}

// installers are the package managers whose install StaleInstall can judge:
// the lockfile beside node_modules, the file inside node_modules the
// install rewrites every time it runs (pnpm 12 rewrites .modules.yaml even on
// a no-op install; npm writes .package-lock.json), and the install to run.
// An empty stamp means only the lockfile comparison applies.
var installers = []struct {
	lockfile, stamp, install string
}{
	{"pnpm-lock.yaml", ".modules.yaml", "pnpm install --frozen-lockfile"},
	{"package-lock.json", ".package-lock.json", "npm ci"},
	{"yarn.lock", "", "yarn install"},
	{"bun.lock", "", "bun install --frozen-lockfile"},
}

// StaleInstall reports why the node_modules copied from srcRoot to dstRoot
// at entry may not match the lockfile beside it in dstRoot, as a sentence
// naming the install to run, or "" when nothing says so. It reads only
// lockfiles and install stamp files: it is a cheap check, not proof that an
// install is current. Entries other than node_modules are never judged;
// unsupported lockfiles make the install's origin uncertain.
func StaleInstall(srcRoot, dstRoot, entry string) string {
	if !isNodeModules(entry) {
		return ""
	}
	dir := path.Dir(entry)
	// Lockfiles and stamps from different managers do not identify which
	// manager produced the copied install, even if one lockfile matches.
	// A destination-only lockfile is also applicable: the source may have
	// lost that manager's lockfile and may not carry an install stamp.
	applicableManagers := 0
	for _, inst := range installers {
		_, lockErr := os.Stat(filepath.Join(srcRoot, filepath.FromSlash(dir), inst.lockfile))
		_, dstLockErr := os.Stat(filepath.Join(dstRoot, filepath.FromSlash(dir), inst.lockfile))
		stampExists := false
		if inst.stamp != "" {
			_, stampErr := os.Stat(filepath.Join(srcRoot, filepath.FromSlash(entry), inst.stamp))
			stampExists = stampErr == nil
		}
		if lockErr == nil || dstLockErr == nil || stampExists {
			applicableManagers++
		}
	}
	var reasons []string
	for _, root := range []string{srcRoot, dstRoot} {
		if unknownInstallLockfile(filepath.Join(root, filepath.FromSlash(dir))) {
			reasons = append(reasons, fmt.Sprintf("%s may not match this checkout: an unsupported lockfile or unreadable lockfile directory makes the copied install's origin ambiguous. Run this project's package manager install in %s before building or testing.", entry, dirLabel(dir)))
			break
		}
	}
	for _, inst := range installers {
		want, err := os.ReadFile(filepath.Join(dstRoot, filepath.FromSlash(dir), inst.lockfile))
		if err != nil {
			continue
		}
		lock := path.Join(dir, inst.lockfile)
		srcLock := filepath.Join(srcRoot, filepath.FromSlash(lock))
		have, err := os.ReadFile(srcLock)
		var why string
		switch {
		case err != nil:
			why = fmt.Sprintf("the source checkout has no %s to have installed it from", lock)
		case !bytes.Equal(have, want):
			why = fmt.Sprintf("it was installed from the source checkout's %s, which differs from this checkout's", lock)
		case inst.stamp != "" && installPredatesLock(filepath.Join(srcRoot, filepath.FromSlash(entry), inst.stamp), srcLock):
			why = fmt.Sprintf("the source checkout's install is older than its own %s (it was not reinstalled after the lockfile changed)", lock)
		case applicableManagers > 1:
			why = "the checkouts have lockfiles or install stamps for multiple package managers, so the copied install's origin is ambiguous"
		default:
			continue
		}
		run := inst.install
		if inst.lockfile == "pnpm-lock.yaml" {
			run += "` (add `--offline` to install from the machine's pnpm store, usually in about a second)"
		} else {
			run += "`"
		}
		reasons = append(reasons, fmt.Sprintf("%s may not match this checkout's %s: %s. Run `%s in %s before building or testing.", entry, lock, why, run, dirLabel(dir)))
	}
	return strings.Join(reasons, " ")
}

// unknownInstallLockfile conservatively recognizes lockfile naming conventions,
// not just a fixed list of managers (including Deno and binary Bun locks).
// Unreadable directories cannot establish the install's origin either.
func unknownInstallLockfile(dir string) bool {
	entries, err := os.ReadDir(dir)
	if err != nil {
		return true
	}
	for _, entry := range entries {
		name := entry.Name()
		known := false
		for _, inst := range installers {
			known = known || name == inst.lockfile
		}
		if known {
			continue
		}
		if strings.HasSuffix(name, ".lock") || strings.HasSuffix(name, ".lockb") ||
			strings.Contains(name, "-lock.") || strings.Contains(name, ".lock.") ||
			strings.Contains(name, "lockfile") || name == "npm-shrinkwrap.json" {
			return true
		}
	}
	return false
}

// installPredatesLock reports whether the install stamp is older than the
// lockfile. A missing stamp says nothing either way.
func installPredatesLock(stamp, lock string) bool {
	si, err := os.Stat(stamp)
	if err != nil {
		return false
	}
	li, err := os.Stat(lock)
	if err != nil {
		return false
	}
	return si.ModTime().Before(li.ModTime())
}

func dirLabel(dir string) string {
	if dir == "." {
		return "the workspace root"
	}
	return dir
}
