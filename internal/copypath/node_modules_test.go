// A copied node_modules carries the install, never the source checkout's
// tsc -b output: copied, it is newer than the new checkout's sources, so
// tsc -b trusts it and typechecks against another revision's declarations.
func TestCopyNodeModulesDropsTheSourceCheckoutsBuildState(t *testing.T) {
	src, dst := t.TempDir(), t.TempDir()
	tree(t, src, map[string]string{
		"web/node_modules/pkg/index.js":                        "js",
		"web/node_modules/.vite/deps/_metadata.json":           "{}",
		"web/node_modules/.tmp/tsc/src/gen/filesystem_pb.d.ts": "stale",
		"web/node_modules/.tmp/tsconfig.app.tsbuildinfo":       "stale",
		"web/node_modules/.cache/babel-loader/x.json":          "stale",
		"web/node_modules/tsconfig.tsbuildinfo":                "stale",
		"web/node_modules/pkg/.tmp/kept-inside-a-package.txt":  "pkg",
		"web/other/.tmp/not-node-modules.txt":                  "kept",
	})

	res := Copy(src, dst, []string{"web/node_modules", "web/other"})

	require.Empty(t, res.Failed)
	assert.Equal(t, []string{"web/node_modules", "web/other"}, res.Copied)
	assert.Equal(t, "js", read(t, filepath.Join(dst, "web/node_modules/pkg/index.js")))
	assert.FileExists(t, filepath.Join(dst, "web/node_modules/.vite/deps/_metadata.json"), "vite's dependency cache invalidates itself")
	assert.NoDirExists(t, filepath.Join(dst, "web/node_modules/.tmp"))
	assert.NoDirExists(t, filepath.Join(dst, "web/node_modules/.cache"))
	assert.NoFileExists(t, filepath.Join(dst, "web/node_modules/tsconfig.tsbuildinfo"))
	assert.FileExists(t, filepath.Join(dst, "web/node_modules/pkg/.tmp/kept-inside-a-package.txt"), "only node_modules' own top level is build state")
	assert.FileExists(t, filepath.Join(dst, "web/other/.tmp/not-node-modules.txt"), "other directories are copied whole")
	assert.FileExists(t, filepath.Join(src, "web/node_modules/.tmp/tsconfig.app.tsbuildinfo"), "the source is never touched")
}

func TestCopyNodeModulesNamesAnInstallThatMayNotMatchTheLockfile(t *testing.T) {
	const lock = "lockfileVersion: '9.0'\n"
	setup := func(t *testing.T, srcLock, dstLock string) (string, string) {
		t.Helper()
		src, dst := t.TempDir(), t.TempDir()
		files := map[string]string{"web/node_modules/.modules.yaml": "{}", "web/node_modules/pkg/index.js": "js"}
		if srcLock != "" {
			files["web/pnpm-lock.yaml"] = srcLock
			files["web/node_modules/.pnpm/lock.yaml"] = srcLock
		}
		tree(t, src, files)
		if dstLock != "" {
			tree(t, dst, map[string]string{"web/pnpm-lock.yaml": dstLock})
		}
		// The install ran after its lockfile was written.
		old := time.Now().Add(-time.Hour)
		if srcLock != "" {
			require.NoError(t, os.Chtimes(filepath.Join(src, "web/pnpm-lock.yaml"), old, old))
		}
		return src, dst
	}

	t.Run("same lockfile, installed after it: nothing to say", func(t *testing.T) {
		src, dst := setup(t, lock, lock)
		res := Copy(src, dst, []string{"web/node_modules"})
		assert.Empty(t, res.Stale)
	})

	t.Run("the destination's lockfile differs", func(t *testing.T) {
		src, dst := setup(t, lock, lock+"# bumped\n")
		res := Copy(src, dst, []string{"web/node_modules"})
		require.Len(t, res.Stale, 1)
		assert.Equal(t, "web/node_modules", res.Stale[0].Path)
		assert.Contains(t, res.Stale[0].Reason, "differs from this checkout's")
		assert.Contains(t, res.Stale[0].Reason, "Run `pnpm install --frozen-lockfile` (add `--offline`")
		assert.Contains(t, res.Stale[0].Reason, "in web before building or testing")
	})

	t.Run("source lock changed but destination matches installed snapshot", func(t *testing.T) {
		src, dst := setup(t, lock, lock)
		tree(t, src, map[string]string{"web/pnpm-lock.yaml": lock + "# bumped\n"})
		res := Copy(src, dst, []string{"web/node_modules"})
		require.Empty(t, res.Failed)
		require.Len(t, res.Stale, 1)
		assert.Contains(t, res.Stale[0].Reason, "differs from this checkout's")
		assert.Contains(t, res.Stale[0].Reason, "Run `pnpm install --frozen-lockfile`")
	})

	t.Run("identical lockfile rewritten after install is still current", func(t *testing.T) {
		src, dst := setup(t, lock, lock)
		later := time.Now().Add(time.Hour)
		require.NoError(t, os.Chtimes(filepath.Join(src, "web/pnpm-lock.yaml"), later, later))
		res := Copy(src, dst, []string{"web/node_modules"})
		assert.Empty(t, res.Stale)
	})

	t.Run("changed lockfile with preserved old mtime is uncertain", func(t *testing.T) {
		src, dst := setup(t, lock, lock)
		tree(t, src, map[string]string{"web/node_modules/.pnpm/lock.yaml": "previous resolution"})
		res := Copy(src, dst, []string{"web/node_modules"})
		require.Len(t, res.Stale, 1)
		assert.Contains(t, res.Stale[0].Reason, "freshness is uncertain")
	})

	t.Run("stamp alone cannot establish freshness", func(t *testing.T) {
		src, dst := setup(t, lock, lock)
		require.NoError(t, os.Remove(filepath.Join(src, "web/node_modules/.pnpm/lock.yaml")))
		res := Copy(src, dst, []string{"web/node_modules"})
		require.Len(t, res.Stale, 1)
		assert.Contains(t, res.Stale[0].Reason, "freshness is uncertain")
	})

	t.Run("the source has no lockfile", func(t *testing.T) {
		src, dst := setup(t, "", lock)
		res := Copy(src, dst, []string{"web/node_modules"})
		require.Len(t, res.Stale, 1)
		assert.Contains(t, res.Stale[0].Reason, "has no web/pnpm-lock.yaml")
	})

	t.Run("no lockfile in the destination: nothing to judge", func(t *testing.T) {
		src, dst := setup(t, lock, "")
		res := Copy(src, dst, []string{"web/node_modules"})
		assert.Empty(t, res.Stale)
	})
}

func TestStaleInstallChecksMultipleManagers(t *testing.T) {
	for _, tc := range []struct {
		name      string
		npmLock   string
		oldStamp  bool
		stampOnly bool
		want      string
	}{
		{name: "later lockfile differs", npmLock: "different", want: "package-lock.json, which differs"},
		{name: "old stamp cannot resolve ambiguity", npmLock: "npm", oldStamp: true, want: "origin is ambiguous"},
		{name: "matching lockfiles are ambiguous", npmLock: "npm", want: "origin is ambiguous"},
		{name: "another manager's stamp is ambiguous", stampOnly: true, want: "origin is ambiguous"},
	} {
		t.Run(tc.name, func(t *testing.T) {
			src, dst := t.TempDir(), t.TempDir()
			tree(t, src, map[string]string{
				"web/pnpm-lock.yaml":                  "pnpm",
				"web/node_modules/.modules.yaml":      "{}",
				"web/node_modules/.package-lock.json": "{}",
			})
			tree(t, dst, map[string]string{"web/pnpm-lock.yaml": "pnpm"})
			if !tc.stampOnly {
				tree(t, src, map[string]string{"web/package-lock.json": "npm"})
				tree(t, dst, map[string]string{"web/package-lock.json": tc.npmLock})
			}
			old := time.Unix(1000000000, 0)
			for _, lock := range []string{"pnpm-lock.yaml", "package-lock.json"} {
				if tc.stampOnly && lock == "package-lock.json" {
					continue
				}
				require.NoError(t, os.Chtimes(filepath.Join(src, "web", lock), old, old))
			}
			if tc.oldStamp {
				older := old.Add(-time.Hour)
				require.NoError(t, os.Chtimes(filepath.Join(src, "web/node_modules/.package-lock.json"), older, older))
			}

			why := StaleInstall(src, dst, "web/node_modules")
			assert.Contains(t, why, tc.want)
			if !tc.stampOnly {
				assert.Contains(t, why, "Run `npm ci`")
			}
		})
	}
}

func TestStaleInstallDestinationOnlyManagerIsAmbiguous(t *testing.T) {
	for _, inst := range installers {
		if inst.lockfile == "pnpm-lock.yaml" {
			continue
		}
		t.Run(inst.lockfile, func(t *testing.T) {
			src, dst := t.TempDir(), t.TempDir()
			// No source lockfile or stamp identifies the second manager;
			// its destination lockfile must still make the origin ambiguous.
			tree(t, src, map[string]string{
				"web/pnpm-lock.yaml":            "pnpm",
				"web/node_modules/pkg/index.js": "js",
			})
			tree(t, dst, map[string]string{
				"web/pnpm-lock.yaml":   "pnpm",
				"web/" + inst.lockfile: "other",
			})

			why := StaleInstall(src, dst, "web/node_modules")
			assert.Contains(t, why, "origin is ambiguous")
			assert.Contains(t, why, "Run `pnpm install --frozen-lockfile`")
			assert.Contains(t, why, "has no web/"+inst.lockfile)
			assert.Contains(t, why, "Run `"+inst.install+"`")
		})
	}
}

func TestStaleInstallUnsupportedLockfilesAreAmbiguous(t *testing.T) {
	for _, lock := range []string{"deno.lock", "bun.lockb", "npm-shrinkwrap.json", "other-lock.yaml", "other.lock.json", "other.lockfile"} {
		for _, side := range []string{"source", "destination"} {
			t.Run(lock+"/"+side, func(t *testing.T) {
				src, dst := t.TempDir(), t.TempDir()
				tree(t, src, map[string]string{"web/yarn.lock": "same"})
				tree(t, dst, map[string]string{"web/yarn.lock": "same"})
				root := src
				if side == "destination" {
					root = dst
				}
				tree(t, root, map[string]string{"web/" + lock: "other"})

				why := StaleInstall(src, dst, "web/node_modules")
				assert.Contains(t, why, "origin ambiguous")
				assert.Contains(t, why, "before building or testing")
			})
		}
	}
}

func TestStaleInstallUnsupportedLockfileWithoutRecognizedManager(t *testing.T) {
	src, dst := t.TempDir(), t.TempDir()
	tree(t, src, map[string]string{"deno.lock": "same", "node_modules/pkg/index.js": "js"})
	tree(t, dst, map[string]string{"deno.lock": "same"})
	res := Copy(src, dst, []string{"node_modules"})
	require.Empty(t, res.Failed)
	require.Len(t, res.Stale, 1)
	assert.Contains(t, res.Stale[0].Reason, "origin ambiguous")
	assert.FileExists(t, filepath.Join(dst, "node_modules/pkg/index.js"))
}

func TestStaleInstallAtTheRootAndForNpm(t *testing.T) {
	src, dst := t.TempDir(), t.TempDir()
	tree(t, src, map[string]string{"package-lock.json": "a", "node_modules/.package-lock.json": "{}"})
	tree(t, dst, map[string]string{"package-lock.json": "b"})

	why := StaleInstall(src, dst, "node_modules")
	assert.Contains(t, why, "Run `npm ci` in the workspace root")
	assert.Empty(t, StaleInstall(src, dst, ".env"), "only a node_modules is judged")
}
