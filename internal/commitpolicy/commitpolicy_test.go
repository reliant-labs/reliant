// TestCheck_GoBuildCacheIsNotProjectCode: a Go build cache inside the
// project is not generated project code, however much it looks like it.
//
// Agents run with a private GOCACHE at $WORKTREE/.gocache so concurrent
// worktrees don't contend on one cache. That directory is gitignored (it is
// a build cache), and its entries are verbatim copies of compiler input —
// including generated Go source, so an entry's first line really is
// "// Code generated by 'go test'. DO NOT EDIT.". isGenerated matched those,
// and because the directory is ignored BY DESIGN, every entry became a
// "generated code, but excluded from git" violation: 133 of them in a
// control-plane worktree, 276 reported in the field, drowning the real
// findings the rule exists to surface.
//
// The fix keys on Go's own sentinel — the README it writes in every GOCACHE
// root — not on the directory's name, which is GOCACHE-configurable and so
// cannot be hardcoded. Honouring .gitignore instead would be wrong in a
// deeper way: this rule's entire purpose is to find generated files that ARE
// gitignored, so skipping ignored paths would make it a permanent no-op.
func TestCheck_GoBuildCacheIsNotProjectCode(t *testing.T) {
	if testing.Short() {
		t.Skip("builds real git repositories and worktrees; runs in task test")
	}
	dir := newRepo(t)

	// Two caches, under different names, to prove the sentinel — not the
	// name ".gocache" — is what does the work. Real generated code that IS
	// wrongly ignored stays in the fixture: the carve-out must be scoped to
	// the cache, not blunt the rule.
	write(t, dir, ".gitignore", ".gocache/\nbuild-cache/\npkg/middleware/*_gen.go\n")

	// A Go build cache as `go build` lays it out: the sentinel README in the
	// root, entries in sharded subdirectories. The entries carry real
	// generated-code banners, which is what tripped the scan.
	write(t, dir, ".gocache/README", GoBuildCacheSentinel+"\nRun \"go clean -cache\" if the directory is getting too large.\n")
	write(t, dir, ".gocache/trim.txt", "1700000000\n")
	write(t, dir, ".gocache/02/02e6c0de012f0c56287da4ddf0bb6fde-d",
		"\n// Code generated by 'go test'. DO NOT EDIT.\n\npackage main\n")
	write(t, dir, ".gocache/a1/a1b2c3d4e5f60718293a4b5c6d7e8f90-d", forgeBanner+"package x\n")

	write(t, dir, "build-cache/README", GoBuildCacheSentinel+"\n")
	write(t, dir, "build-cache/7f/7f00ba115eed-d", forgeBanner+"package y\n")

	write(t, dir, "pkg/middleware/procedures_gen.go", forgeBanner+"package middleware\n")

	git(t, dir, "add", "-A")
	git(t, dir, "commit", "-qm", "init")

	vs, err := Check(dir)
	if err != nil {
		t.Fatalf("Check: %v", err)
	}
	for _, v := range vs {
		if strings.HasPrefix(v.Path, ".gocache/") || strings.HasPrefix(v.Path, "build-cache/") {
			t.Errorf("Go build-cache entry reported as generated project code: %s", v.Path)
		}
	}
	if len(vs) != 1 || vs[0].Path != "pkg/middleware/procedures_gen.go" {
		t.Fatalf("want only the genuinely-ignored generated file reported, got %d:\n%s", len(vs), Format(vs))
	}
}

// TestCheck_ForeignProjectTreesAreNotJudged: a gitignored copy of ANOTHER
// project inside this one is that project's generated code, not this one's.
//
// control-plane keeps a build context at context/ — a checkout of the reliant
// module, written by a script for an image build and gitignored by design.
// Its .pb.go, connect and sqlc stubs matched isGenerated, and because the
// directory is ignored every one became a "generated code, but excluded from
// git" violation: 199 of them, so `forge lint` could never exit 0 there.
//
// Two boundaries mark a tree as another project's, and both are what the
// toolchains themselves honour:
//   - a nested git repository (a submodule, a nested worktree, a cloned
//     dependency) — the outer repository cannot commit its files at all;
//   - a nested go.mod declaring a module outside this project's module path
//     — the boundary `go build ./...` stops at.
//
// Skipping every ignored path is not the fix: this rule exists to find
// generated files that ARE ignored. So the project's own trees — including
// its own nested modules, like gen/ — must still be caught.
func TestCheck_ForeignProjectTreesAreNotJudged(t *testing.T) {
	if testing.Short() {
		t.Skip("builds real git repositories and worktrees; runs in task test")
	}
	dir := newRepo(t)
	write(t, dir, "go.mod", "module example.com/app\n\ngo 1.27\n")
	write(t, dir, ".gitignore", "context/\n.worktrees/\ngen/*\n!gen/go.mod\npkg/middleware/*_gen.go\n")

	// A copied-in foreign module, generated code and all.
	write(t, dir, "context/other/go.mod", "module example.com/other\n\ngo 1.27\n")
	write(t, dir, "context/other/gen/other/v1/other.pb.go", "// Code generated by protoc-gen-go. DO NOT EDIT.\npackage otherv1\n")
	write(t, dir, "context/other/internal/db/queries.sql.go", "// Code generated by sqlc. DO NOT EDIT.\npackage db\n")
	write(t, dir, "context/other/internal/x/mock_gen.go", forgeBanner+"package x\n")
	// A nested worktree of THIS repository: same module path, but its own
	// checkout, so the module rule alone would not catch it.
	write(t, dir, ".worktrees/feature/.git", "gitdir: /elsewhere/.git/worktrees/feature\n")
	write(t, dir, ".worktrees/feature/go.mod", "module example.com/app\n\ngo 1.27\n")
	write(t, dir, ".worktrees/feature/pkg/middleware/procedures_gen.go", forgeBanner+"package middleware\n")

	// This project's own generated code, wrongly ignored: still violations,
	// including inside its own nested gen module.
	write(t, dir, "gen/go.mod", "module example.com/app/gen\n\ngo 1.27\n")
	write(t, dir, "gen/services/api/v1/api.pb.go", "// Code generated by protoc-gen-go. DO NOT EDIT.\npackage apiv1\n")
	write(t, dir, "pkg/middleware/procedures_gen.go", forgeBanner+"package middleware\n")

	git(t, dir, "add", "-A")
	git(t, dir, "commit", "-qm", "init")

	vs, err := Check(dir)
	if err != nil {
		t.Fatalf("Check: %v", err)
	}
	got := map[string]Violation{}
	for _, v := range vs {
		got[v.Path] = v
		if strings.HasPrefix(v.Path, "context/") || strings.HasPrefix(v.Path, ".worktrees/") {
			t.Errorf("another project's generated file judged by this project's commit policy: %s", v.Path)
		}
	}
	for _, want := range []string{"gen/services/api/v1/api.pb.go", "pkg/middleware/procedures_gen.go"} {
		if _, ok := got[want]; !ok {
			t.Errorf("this project's ignored generated file %s must still be reported, got:\n%s", want, Format(vs))
		}
	}
	if len(vs) != 2 {
		t.Errorf("want exactly the project's 2 ignored generated files, got %d:\n%s", len(vs), Format(vs))
	}
}

// TestCheck_OutsideAGitRepoIsSilent: no commit state, no verdict.
func TestCheck_OutsideAGitRepoIsSilent(t *testing.T) {
	dir := t.TempDir()
	seedGenerated(t, dir)
	if vs, err := Check(dir); err != nil || len(vs) != 0 {
		t.Fatalf("Check outside git = (%v, %v), want (nil, nil)", vs, err)
	}
}

func keys(m map[string]Violation) []string {
	var out []string
	for k := range m {
		out = append(out, k)
	}
	return out
}
