// EmitFrontendMockSurface writes the mock/scenario surface for ONE browser
// frontend, rooted at root (the project directory) under the
// project-relative feRel (e.g. "frontends/dashboard"), and returns the
// number of per-entity fixture files written.
//
// Every file it emits except the seeded `scenarios/default.ts` is Tier-1 —
// it carries the "Code generated by forge. DO NOT EDIT." banner and IS
// rewritten on every `forge generate` — so all of them go through the
// certification chokepoint (WriteGeneratedFileTier1) that stamps the
// embedded forge:hash marker. Until they did, the header on every one of
// them named a command that refused the file:
//
//	forge project disown frontends/web/src/mocks/products.ts
//	Error: 1 path(s) carry no forge certification …
//	Fix: … scaffold-once files are yours from birth
//
// — an answer that was false about a file forge overwrites on every run,
// while the drift lint reported "no hand-edits to forge-generated files"
// for a tree in which every one of these had been hand-edited. A plain
// os.WriteFile emits the claim without the evidence for it.
//
// The surface is:
//
//   - src/lib/mock-transport.ts — the transport carrying scenario dispatch,
//     hybrid passthrough, and the Unimplemented fallback.
//   - src/mocks/<entity>_gen.ts — per-entity fixtures, carrying the values
//     the project's own seed plan writes into the dev database for those
//     rows. There is deliberately no barrel over them: mock-transport_gen.ts
//     imports each module by name (see retireMocksIndex).
//   - src/mocks/scenario-types.ts, src/mocks/scenario-rpcs_gen.ts, and
//     src/mocks/scenarios/{default,index}.ts — the scenarios scaffolding.
//     See docs/adr/0002-frontend-scenarios.md.
//
// It has TWO callers, and the split is the point:
//
//   - GenerateFrontendFilesWithOptions calls it with no services/entities as
//     part of the scaffold. `connect.ts` references "@/lib/mock-transport"
//     statically (Vite ESM) or via a literal `require()` (Next.js/webpack),
//     so a scaffold that omits the module leaves a tree that does not
//     typecheck (`tsc`: TS2307) and does not build (`next build`: "Module not
//     found"). The scaffold emits what the scaffold imports.
//   - The `forge generate` frontend-mocks step calls it with the project's
//     parsed services + entities, re-rendering the same files with the real
//     fixture dispatch table.
//
// seed is the project's dev dataset (codegen.BuildSeedProjection), the source
// every per-entity fixture value is read from so the mocks and the seeded
// database hold the same rows. The scaffold-time caller has no entities and
// passes nil.
//
// Scenario support is DECOUPLED from entity-CRUD: the transport's
// scenario-dispatch pipeline depends only on the scenarios scaffolding
// (always emitted), not on entity fixtures. The per-entity fixture switch is
// the ONLY part gated on entities — with none, the template omits that
// section, leaving a fully scenario-capable transport (never a do-nothing
// stub that would silently drop the scenario mechanism) that also carries no
// `@/gen/...` imports, so the scaffold-time render stands alone before the
// TypeScript stubs exist.
func EmitFrontendMockSurface(root, feRel string, services []codegen.ServiceDef, entities []codegen.EntityDef, seed *codegen.SeedProjection, cs *FileChecksums) (int, error) {
	mockDataTmplContent, err := templates.FrontendTemplates().Get(filepath.Join("mocks", "mock-data.ts.tmpl"))
	if err != nil {
		return 0, fmt.Errorf("read mock-data template: %w", err)
	}
	mockDataTmpl, err := template.New("mock-data.ts.tmpl").Funcs(templates.FuncMap()).Parse(string(mockDataTmplContent))
	if err != nil {
		return 0, fmt.Errorf("parse mock-data template: %w", err)
	}

	mockTransportTmplContent, err := templates.FrontendTemplates().Get(filepath.Join("mocks", "mock-transport.ts.tmpl"))
	if err != nil {
		return 0, fmt.Errorf("read mock-transport template: %w", err)
	}
	mockTransportTmpl, err := template.New("mock-transport.ts.tmpl").Funcs(templates.FuncMap()).Parse(string(mockTransportTmplContent))
	if err != nil {
		return 0, fmt.Errorf("parse mock-transport template: %w", err)
	}

	// Build entity→service mapping: match entity names to the service that
	// owns them, and the transport's per-entity dispatch rows.
	entities, _ = codegen.FrontendEntities(entities)
	entityToService := buildEntityServiceMap(services, entities)
	transportEntities := codegen.ExtractMockTransportEntities(services, entities)

	mocksRel := filepath.Join(feRel, "src", "mocks")
	if err := os.MkdirAll(filepath.Join(root, mocksRel), 0o755); err != nil {
		return 0, fmt.Errorf("create mocks directory: %w", err)
	}

	// Always emit the scenarios scaffolding (types + default + registry)
	// before the per-entity mocks. The registry walks src/mocks/scenarios/
	// for *.ts files and re-exports them; rerunning is idempotent.
	if err := EmitScenarioScaffolding(root, mocksRel, services, cs); err != nil {
		return 0, fmt.Errorf("emit scenario scaffolding: %w", err)
	}

	var mockFileCount int

	// Generate per-entity mock data files
	for _, entity := range entities {
		svc, ok := entityToService[entity.Name]
		if !ok {
			continue
		}

		data := codegen.EntityDefToMockData(entity, svc, seed)

		var buf bytes.Buffer
		if err := mockDataTmpl.Execute(&buf, data); err != nil {
			return 0, fmt.Errorf("render mock data for %s: %w", entity.Name, err)
		}

		slug := codegen.PascalToKebab(inflection.Plural(entity.Name))
		rel := filepath.Join(mocksRel, slug+"_gen.ts")
		if _, err := WriteGeneratedFileTier1(root, rel, buf.Bytes(), cs, true); err != nil {
			return 0, fmt.Errorf("write mock data file %s: %w", rel, err)
		}
		// The pre-`_gen` copy of this fixture module, from a project
		// generated before the rename. Reclaimed here, in the emitter that
		// supersedes it, so the project is left with one file rather than
		// two that drift apart.
		codegen.RetireRenamedGenerated(root, filepath.Join(mocksRel, slug+".ts"), cs)
		mockFileCount++
	}

	// Generate mock transport. The rich template is ALWAYS used — see the
	// scenario/entity decoupling note on this function.
	libRel := filepath.Join(feRel, "src", "lib")
	if err := os.MkdirAll(filepath.Join(root, libRel), 0o755); err != nil {
		return 0, fmt.Errorf("create lib directory: %w", err)
	}

	transportData := codegen.NewMockTransportTemplateData(transportEntities)

	var buf bytes.Buffer
	if err := mockTransportTmpl.Execute(&buf, transportData); err != nil {
		return 0, fmt.Errorf("render mock transport: %w", err)
	}
	if _, err := WriteGeneratedFileTier1(root, filepath.Join(libRel, "mock-transport_gen.ts"), buf.Bytes(), cs, true); err != nil {
		return 0, fmt.Errorf("write mock transport: %w", err)
	}
	// Retire the pre-`_gen` transport. Two live copies would both register
	// module-scope scenario state, and connect.ts would resolve whichever
	// one its specifier names — so the stale copy is not merely untidy, it
	// is a second, divergent mock pipeline.
	codegen.RetireRenamedGenerated(root, filepath.Join(libRel, "mock-transport.ts"), cs)

	// The mocks barrel is RETIRED, not written. It re-exported the entity
	// fixture modules — a list forge already knows, and one nothing imported:
	// mock-transport_gen.ts names each `@/mocks/<slug>_gen` module directly,
	// because it needs the per-entity namespace anyway to build its dispatch
	// table. A barrel over a known list with no importers is scaffolded code
	// that only exists to be regenerated.
	//
	// Both spellings are reclaimed: `index_gen.ts` from a project generated
	// after the `_gen` rename, and the pre-rename `index.ts` behind it. Each
	// goes through the ownership test, so a copy the user disowned or
	// hand-edited is left alone.
	retireMocksIndex(root, mocksRel, cs)

	return mockFileCount, nil
}

// buildEntityServiceMap creates a mapping from entity name to the service
// that owns the CRUD RPCs for that entity.
func buildEntityServiceMap(services []codegen.ServiceDef, entities []codegen.EntityDef) map[string]codegen.ServiceDef {
	result := make(map[string]codegen.ServiceDef, len(entities))
	for _, svc := range services {
		pages := codegen.ExtractCRUDEntities(svc)
		for _, page := range pages {
			for _, entity := range entities {
				if entity.Name == page.EntityName {
					result[entity.Name] = svc
				}
			}
		}
	}
	return result
}

// retireMocksIndex reclaims the mocks barrel, which forge no longer emits.
//
// It was five lines of which one was real — `export * from "./orders_gen";`
// per entity — over a list forge derives from the same entities it just wrote
// fixtures for, and NOTHING imported it: the only consumer of the fixtures,
// mock-transport_gen.ts, imports each module under its own namespace
// (`import * as ordersMocks from "@/mocks/orders_gen"`) because its dispatch
// table needs them separated, not flattened.
//
// Both spellings are swept, newest first: `index_gen.ts` from a project
// generated after the `_gen` rename, and `index.ts` from one generated before
// it. Neither is a rename — there is no successor file — so both go through
// RetireGenerated rather than RetireRenamedGenerated, and a user's disowned
// or hand-edited barrel is left in place as an ordinary module of theirs.
func retireMocksIndex(root, mocksRel string, cs *FileChecksums) {
	codegen.RetireGenerated(root, filepath.Join(mocksRel, "index_gen.ts"), cs)
	codegen.RetireGenerated(root, filepath.Join(mocksRel, "index.ts"), cs)
}

// EmitScenarioScaffolding writes the scenarios files under the
// project-relative <mocksRel>/scenarios/ inside root:
//
//   - scenario-types.ts (Tier-1 — the contract type)
//   - scenario-rpcs_gen.ts (Tier-1 — typed per-RPC handler map derived
//     from the proto descriptor; empty-but-valid when the project has no
//     services yet)
//   - default.ts (scaffold-once; yours from birth, safe to hand-edit)
//   - index.ts (Tier-1 — regenerated by walking the directory for *.ts)
//
// The tier split is what each file's own header already claims, and the
// writer is now the thing that makes the claim true: the three Tier-1
// files go through WriteGeneratedFileTier1 (stamped, disownable,
// drift-covered) and default.ts through WriteScaffoldIfMissing (written
// once, never touched again).
//
// scenario-types.ts and scenario-rpcs_gen.ts are emitted one level up at
// <mocksRel>/ so user scenarios can `import { defineScenario } from
// "../scenario-types"`. The regeneration is idempotent: running
// `forge generate` twice produces the same output.
//
// User-authored scenarios (created with `forge scaffold scenario`) are NEVER
// touched here — the registry just re-exports them.
func EmitScenarioScaffolding(root, mocksRel string, services []codegen.ServiceDef, cs *FileChecksums) error {
	scenariosRel := filepath.Join(mocksRel, "scenarios")
	if err := os.MkdirAll(filepath.Join(root, scenariosRel), 0o755); err != nil {
		return fmt.Errorf("create scenarios directory: %w", err)
	}

	// 1) scenario-types.ts (Tier-1 — generator-owned).
	typesContent, err := templates.FrontendTemplates().Get(filepath.Join("mocks", "scenarios", "scenario-types.ts.tmpl"))
	if err != nil {
		return fmt.Errorf("read scenario-types template: %w", err)
	}
	if _, err := WriteGeneratedFileTier1(root, filepath.Join(mocksRel, "scenario-types_gen.ts"), typesContent, cs, true); err != nil {
		return fmt.Errorf("write scenario-types_gen.ts: %w", err)
	}
	codegen.RetireRenamedGenerated(root, filepath.Join(mocksRel, "scenario-types.ts"), cs)

	// 1b) scenario-rpcs_gen.ts (Tier-1 — generator-owned). The typed
	// handler map every Scenario.handlers literal checks against.
	rpcsTmplContent, err := templates.FrontendTemplates().Get(filepath.Join("mocks", "scenarios", "scenario-rpcs.ts.tmpl"))
	if err != nil {
		return fmt.Errorf("read scenario-rpcs template: %w", err)
	}
	rpcsTmpl, err := template.New("scenario-rpcs.ts.tmpl").Funcs(templates.FuncMap()).Parse(string(rpcsTmplContent))
	if err != nil {
		return fmt.Errorf("parse scenario-rpcs template: %w", err)
	}
	var rpcsBuf bytes.Buffer
	if err := rpcsTmpl.Execute(&rpcsBuf, codegen.BuildScenarioRPCData(services)); err != nil {
		return fmt.Errorf("render scenario-rpcs_gen: %w", err)
	}
	if _, err := WriteGeneratedFileTier1(root, filepath.Join(mocksRel, "scenario-rpcs_gen.ts"), rpcsBuf.Bytes(), cs, true); err != nil {
		return fmt.Errorf("write scenario-rpcs_gen.ts: %w", err)
	}

	// 2) default.ts — scaffold-once ("yours" banner): written when absent,
	// never touched again.
	defaultContent, err := templates.FrontendTemplates().Get(filepath.Join("mocks", "scenarios", "default-scenario.ts.tmpl"))
	if err != nil {
		return fmt.Errorf("read default-scenario template: %w", err)
	}
	if wrote, err := WriteScaffoldIfMissing(root, filepath.Join(scenariosRel, "default.ts"), defaultContent); err != nil {
		return fmt.Errorf("write default.ts: %w", err)
	} else if wrote {
		// With the birth hash, so it is pristine until edited (see
		// recordFrontendScaffoldBirth).
		recordFrontendScaffoldBirth(root, filepath.Join(root, scenariosRel, "default.ts"), defaultContent)
	}

	// 3) index.ts — regenerated by walking the directory.
	if err := WriteScenariosIndex(root, scenariosRel, cs); err != nil {
		return fmt.Errorf("write scenarios index: %w", err)
	}

	return nil
}

// scenarioIndexEntry is the per-file shape consumed by
// scenarios-index.ts.tmpl. Slug is the filename without the `.ts`
// extension; Ident is a valid TS identifier derived from the slug
// (kebab-case → camelCase, suffixed with "Scenario").
type scenarioIndexEntry struct {
	Slug  string
	Ident string
}

// WriteScenariosIndex walks the project-relative <scenariosRel> inside
// root for *.ts files (excluding index.ts itself) and renders
// scenarios-index.ts.tmpl with one entry per file. Ordering is
// alphabetical for deterministic output — re-running `forge generate` on
// the same set of files produces the same bytes.
//
// The barrel is Tier-1: it carries the generated banner and is rewritten
// whenever the directory's contents change, so it goes through the
// certification chokepoint like every other regenerated file.
func WriteScenariosIndex(root, scenariosRel string, cs *FileChecksums) error {
	scenariosDir := filepath.Join(root, scenariosRel)
	tmplContent, err := templates.FrontendTemplates().Get(filepath.Join("mocks", "scenarios", "scenarios-index.ts.tmpl"))
	if err != nil {
		return fmt.Errorf("read scenarios-index template: %w", err)
	}
	tmpl, err := template.New("scenarios-index.ts.tmpl").Funcs(templates.FuncMap()).Parse(string(tmplContent))
	if err != nil {
		return fmt.Errorf("parse scenarios-index template: %w", err)
	}

	entries, err := os.ReadDir(scenariosDir)
	if err != nil {
		return fmt.Errorf("read scenarios directory: %w", err)
	}

	var slugs []string
	for _, e := range entries {
		if e.IsDir() {
			continue
		}
		name := e.Name()
		// Skip the registry barrel under BOTH names: the current
		// `index_gen.ts` and the pre-rename `index.ts` that may still be
		// on disk in an older project when this walk runs (it is retired
		// below, after the barrel is written). Treating either as a
		// scenario would make the barrel import itself.
		if name == "index_gen.ts" || name == "index.ts" {
			continue
		}
		if !strings.HasSuffix(name, ".ts") {
			continue
		}
		// Skip the registry barrel; the `default.ts` placeholder is
		// handled the same as any other scenario — its `name` field is
		// "default" so byName("default") works.
		slug := strings.TrimSuffix(name, ".ts")
		slugs = append(slugs, slug)
	}
	sort.Strings(slugs)

	indexEntries := make([]scenarioIndexEntry, 0, len(slugs))
	for _, slug := range slugs {
		indexEntries = append(indexEntries, scenarioIndexEntry{
			Slug:  slug,
			Ident: scenarioImportIdent(slug),
		})
	}

	var buf bytes.Buffer
	if err := tmpl.Execute(&buf, struct {
		Scenarios []scenarioIndexEntry
	}{Scenarios: indexEntries}); err != nil {
		return fmt.Errorf("render scenarios-index: %w", err)
	}

	if _, err := WriteGeneratedFileTier1(root, filepath.Join(scenariosRel, "index_gen.ts"), buf.Bytes(), cs, true); err != nil {
		return err
	}
	codegen.RetireRenamedGenerated(root, filepath.Join(scenariosRel, "index.ts"), cs)
	return nil
}

// scenarioImportIdent converts a kebab-case scenario slug into a valid
// TS identifier suitable for use as the local binding of a default
// import. Examples: "default" -> "scenario_default",
// "github-connected" -> "scenario_githubConnected". The "scenario_"
// prefix avoids collisions with reserved words (default) and with the
// `defaultScenario` named re-export emitted by scenarios-index.ts.tmpl.
//
// Parts that begin with a digit (e.g. "1") are passed through as-is —
// the leading-letter rule on the slug itself (validated by
// validateScenarioName) guarantees the resulting identifier is valid.
func scenarioImportIdent(slug string) string {
	parts := strings.Split(slug, "-")
	var out strings.Builder
	out.WriteString("scenario_")
	for i, p := range parts {
		if p == "" {
			continue
		}
		if i == 0 {
			out.WriteString(p)
			continue
		}
		r, sz := utf8.DecodeRuneInString(p)
		out.WriteRune(unicode.ToUpper(r))
		out.WriteString(p[sz:])
	}
	return out.String()
}
