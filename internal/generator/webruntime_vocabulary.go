// Package generator — does the INSTALLED web runtime ship what forge's
// generated code uses?
//
// The scaffold floor (webRuntimePublishedRange) is a version range, and a
// version says nothing about content: a project whose lockfile resolves an
// admitted-but-old runtime, or a forge commit ahead of the last runtime
// release, gets generated code that names runtime features the installed
// package does not have. An unknown export fails the build with TS2305; an
// unknown OPTION fails nothing at all. otel_gen.ts started passing
// initBrowserTelemetry's `rpcForensics` (forge#2348) while the newest
// published runtime, 0.13.19, had no such option, so every consumer that
// regenerated got a no-op and no word about it.
//
// Two ways a consumer lands there, neither of them a mistake on its part:
//
//   - a released forge: release-forge.sh syncs the floor to the runtime it
//     published in the bookkeeping commit AFTER the tag, so the released
//     binary scaffolds the previous floor (v1.8.0 ships ^0.13.17; its commit
//     published 0.13.19), and a lockfile at 0.13.17 is never raised;
//   - a pin of an untagged forge commit: its templates may use runtime code
//     that is published only at the next release cut.
//
// So the check is on CONTENT, not version numbers. webruntime_vocabulary.txt
// lists every identifier forge's generated frontend code shares with the
// runtime's declarations (TestWebRuntimeVocabularyIsCurrent keeps it in step
// with the templates and web-runtime/src). After generate settles a
// frontend, WebRuntimeContentNotices compares its generated imports with
// the installed public entrypoints, and checks generated option keys against
// the declaration of the API that accepts them.
package generator

import (
	_ "embed"
	"encoding/json"
	"fmt"
	"io/fs"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strings"
	"sync"

	"github.com/reliant-labs/forge/internal/frontenddeps"
)

//go:embed webruntime_vocabulary.txt
var webRuntimeVocabularyText string

// generatedTSHeader is the first line of every TypeScript file forge
// regenerates (templates and Go-emitted files alike). Only those files are
// forge's to judge: the project's own code is checked by its own typecheck.
const generatedTSHeader = "// Code generated by forge. DO NOT EDIT."

var (
	webRuntimeVocabularyOnce sync.Once
	webRuntimeVocabularySet  map[string]bool
)

// webRuntimeVocabulary parses the embedded list: one identifier per line,
// `#` comments and blank lines ignored.
func webRuntimeVocabulary() map[string]bool {
	webRuntimeVocabularyOnce.Do(func() {
		webRuntimeVocabularySet = map[string]bool{}
		for _, line := range strings.Split(webRuntimeVocabularyText, "\n") {
			line = strings.TrimSpace(line)
			if line == "" || strings.HasPrefix(line, "#") {
				continue
			}
			webRuntimeVocabularySet[line] = true
		}
	})
	return webRuntimeVocabularySet
}

// tsIdentifierRe matches a JavaScript identifier for maintaining the
// checked-in vocabulary (not for inferring installed module exports).
var tsIdentifierRe = regexp.MustCompile(`[A-Za-z_$][A-Za-z0-9_$]*`)

func addIdentifiers(set map[string]bool, text string) {
	for _, id := range tsIdentifierRe.FindAllString(text, -1) {
		set[id] = true
	}
}

// tsCommentRe matches a block or line comment, and tsStringRe a single- or
// double-quoted string literal on one line. Stripping is approximate (a `//`
// inside a string truncates that line), which only ever drops tokens.
var (
	tsCommentRe = regexp.MustCompile(`(?s)/\*.*?\*/|//[^\n]*`)
	tsStringRe  = regexp.MustCompile(`"(?:[^"\\\n]|\\.)*"|'(?:[^'\\\n]|\\.)*'`)
)

// stripTSProse removes comments and quoted strings, so neither the prose in a
// generated file's header nor a module specifier
// ("@reliantlabs/forge-web-runtime/…") is read as a use of a runtime feature.
func stripTSProse(text string) string {
	return tsStringRe.ReplaceAllString(tsCommentRe.ReplaceAllString(text, " "), " ")
}

// installedWebRuntimeDir finds the runtime package a frontend resolves:
// node_modules/@reliantlabs/forge-web-runtime in the frontend or any
// directory above it up to the project root (hoisted workspaces). Symlinks
// (pnpm's store layout) are resolved.
func installedWebRuntimeDir(projectDir, feRelDir string) (string, bool) {
	stop, err := filepath.Abs(projectDir)
	if err != nil {
		return "", false
	}
	dir := filepath.Join(stop, feRelDir)
	for {
		candidate := filepath.Join(dir, "node_modules", filepath.FromSlash(WebRuntimePackage))
		if _, err := os.Stat(filepath.Join(candidate, "package.json")); err == nil {
			resolved, err := filepath.EvalSymlinks(candidate)
			if err != nil {
				return "", false
			}
			return resolved, true
		}
		if dir == stop {
			return "", false
		}
		parent := filepath.Dir(dir)
		if parent == dir || !strings.HasPrefix(parent, stop) {
			return "", false
		}
		dir = parent
	}
}

// generatedFrontendFiles returns the frontend's TypeScript files forge
// regenerates (first line generatedTSHeader), relative to feAbs, with their
// contents. Dependency, build-output and dot directories are skipped.
func generatedFrontendFiles(feAbs string) map[string]string {
	out := map[string]string{}
	_ = filepath.WalkDir(feAbs, func(path string, d fs.DirEntry, err error) error {
		if err != nil {
			return nil //nolint:nilerr // an unreadable entry is skipped, not fatal
		}
		if d.IsDir() {
			name := d.Name()
			if path != feAbs && (strings.HasPrefix(name, ".") || name == "node_modules" ||
				name == "dist" || name == "out" || name == "build") {
				return filepath.SkipDir
			}
			return nil
		}
		if ext := filepath.Ext(path); ext != ".ts" && ext != ".tsx" {
			return nil
		}
		body, readErr := os.ReadFile(path)
		if readErr != nil || !strings.HasPrefix(string(body), generatedTSHeader) {
			return nil //nolint:nilerr // unreadable or not forge's: not judged
		}
		rel, relErr := filepath.Rel(feAbs, path)
		if relErr != nil {
			return nil //nolint:nilerr // cannot name it: not judged
		}
		out[filepath.ToSlash(rel)] = string(body)
		return nil
	})
	return out
}

// WebRuntimeContentNotices reports, for the frontend rooted at feRelDir, the
// runtime features forge's generated code there uses that the INSTALLED
// @reliantlabs/forge-web-runtime does not ship. One notice, or none.
//
// It judges only what is on disk: no install (node_modules absent), a
// runtime with no compiled output, or a project bridged to a dev forge's
// checkout (which IS the runtime the generator was built with) reports
// nothing.
func WebRuntimeContentNotices(projectDir, feRelDir string) []string {
	if devWebRuntimeBridged(projectDir) {
		return nil
	}
	pkgDir, ok := installedWebRuntimeDir(projectDir, feRelDir)
	if !ok {
		return nil
	}
	raw, err := os.ReadFile(filepath.Join(pkgDir, "package.json"))
	var manifest webRuntimeManifest
	if err != nil || json.Unmarshal(raw, &manifest) != nil {
		return nil
	}
	surface := webRuntimeSurface{dir: pkgDir, manifest: manifest, entries: map[string]checkedRuntimeEntry{}}
	usedBy := map[string][]string{} // missing identifier -> generated files using it
	files := generatedFrontendFiles(filepath.Join(projectDir, feRelDir))
	paths := make([]string, 0, len(files))
	for p := range files {
		paths = append(paths, p)
	}
	sort.Strings(paths)
	for _, p := range paths {
		for id := range surface.missing(files[p]) {
			usedBy[id] = append(usedBy[id], p)
		}
	}
	if len(usedBy) == 0 {
		return nil
	}

	missing := make([]string, 0, len(usedBy))
	for id := range usedBy {
		missing = append(missing, id)
	}
	sort.Strings(missing)
	parts := make([]string, 0, len(missing))
	for _, id := range missing {
		parts = append(parts, fmt.Sprintf("%s (%s)", id, strings.Join(usedBy[id], ", ")))
	}

	version := manifest.Version
	if version == "" {
		version = "(unknown version)"
	}
	update := "npm update"
	if lock, ok := frontenddeps.FindLock(filepath.Join(projectDir, feRelDir), projectDir); ok {
		switch lock.Runner {
		case "pnpm":
			update = "pnpm update"
		case "yarn":
			update = "yarn up"
		}
	}
	return []string{fmt.Sprintf(
		"the installed %s %s does not ship %d runtime feature(s) forge's generated code uses: %s. "+
			"Until a runtime that ships them is installed, an unknown option is silently ignored and an unknown import fails the build. "+
			"Install the newest runtime your range admits (`%s %s`); if that changes nothing, this forge is ahead of the last "+
			"runtime release, and the next release publishes them",
		WebRuntimePackage, version, len(missing), strings.Join(parts, "; "), update, WebRuntimePackage)}
}
