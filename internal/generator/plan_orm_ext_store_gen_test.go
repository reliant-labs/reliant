// taskExtQueries is a Task seam holding the shapes the ext store must carry:
// a plain query, a variadic one, named results, a result-less one, a
// parameter named after its function, one named like the receiver, and a
// function the store must leave out.
const taskExtQueries = `package db

import (
	"context"

	"github.com/reliant-labs/forge/pkg/orm"
)

// TasksByTitle lists the tasks with this title.
func TasksByTitle(ctx context.Context, db orm.Context, title string, opts ...orm.QueryOption) ([]*Task, error) {
	return ListTask(ctx, db, append(opts, orm.WhereEq(TaskFieldTitle, title))...)
}

// CountAndFirst counts the tasks and returns the first.
func CountAndFirst(ctx context.Context, db orm.Context) (n int64, first *Task, err error) {
	return 0, nil, nil
}

func Touch(ctx context.Context, db orm.Context, s string) {}

func Echo(ctx context.Context, db orm.Context, Echo string) (string, error) { return Echo, nil }

func Generic[T any](ctx context.Context, db orm.Context, v T) error { return nil }
`

func taskExtStorePath(root string) string {
	return filepath.Join(root, "internal", "db", "task_ext_store_gen.go")
}

func generateTask(t *testing.T, root string) {
	t.Helper()
	if err := GeneratePlanORM(root, config.ORMConfig{}, []config.PlanEntity{taskPlanEntity()}, nil); err != nil {
		t.Fatalf("GeneratePlanORM: %v", err)
	}
}

func readGenFile(t *testing.T, path string) string {
	t.Helper()
	b, err := os.ReadFile(path)
	if err != nil {
		t.Fatalf("read %s: %v", path, err)
	}
	return string(b)
}

// G8: a query in the ext seam is a package function, so no Deps interface
// could name it without a hand-written passthrough adapter (reliant's
// plan_repo_ext.go: seven of them). forge now binds them as it binds the
// generated CRUD: <Entity>ExtStore, its adapter, constructor, WithTx and the
// aggregate's accessor.
func TestExtStore_BindsTheSeamsQueries(t *testing.T) {
	root := t.TempDir()
	writeDBFile(t, root, "task_repo_ext.go", taskExtQueries)
	generateTask(t, root)

	src := readGenFile(t, taskExtStorePath(root))
	if _, err := parser.ParseFile(token.NewFileSet(), "", src, 0); err != nil {
		t.Fatalf("ext store does not parse: %v\n%s", err, src)
	}
	for _, want := range []string{
		"// Code generated by forge. DO NOT EDIT.",
		"// Source: the exported query functions of task_repo_ext.go beside it.",
		"type TaskExtStore interface {",
		"\t// TasksByTitle lists the tasks with this title.\n\tTasksByTitle(ctx context.Context, title string, opts ...orm.QueryOption) ([]*Task, error)",
		"\tCountAndFirst(ctx context.Context) (n int64, first *Task, err error)",
		"\tTouch(ctx context.Context, s string)\n",
		"\tEcho(ctx context.Context, Echo string) (string, error)",
		"\tWithTx(tx orm.Context) TaskExtStore",
		"type taskExtStore struct{ db orm.Context }",
		"func NewTaskExtStore(db orm.Context) TaskExtStore { return taskExtStore{db: db} }",
		"return TasksByTitle(ctx, s.db, title, opts...)",
		"return CountAndFirst(ctx, s.db)",
		// The receiver yields to a parameter named s, and a parameter named
		// after its function is renamed, or the call would name it.
		"func (s2 taskExtStore) Touch(ctx context.Context, s string) {\n\tTouch(ctx, s2.db, s)\n}",
		"func (s taskExtStore) Echo(ctx context.Context, EchoArg string) (string, error) {\n\treturn Echo(ctx, s.db, EchoArg)\n}",
		"func (s taskExtStore) WithTx(tx orm.Context) TaskExtStore { return taskExtStore{db: tx} }",
		"var _ TaskExtStore = taskExtStore{}",
		// The exact line compose's store seam (codegen.storeAccessorRE) wires a
		// db.TaskExtStore Deps field through.
		"func (s Store) TasksExt() TaskExtStore { return taskExtStore{db: s.db} }",
	} {
		if !strings.Contains(src, want) {
			t.Errorf("ext store missing %q\n%s", want, src)
		}
	}
	if strings.Contains(src, "Generic") {
		t.Errorf("a generic function cannot be an interface method:\n%s", src)
	}
	if !strings.Contains(src, "import (\n\t\"context\"\n\n\t\"github.com/reliant-labs/forge/pkg/orm\"\n)") {
		t.Errorf("imports must be goimports-grouped, stdlib first:\n%s", src)
	}

	// <Entity>Store is not widened: hand fakes of it keep compiling.
	store := readGenFile(t, filepath.Join(root, "internal", "db", "task_store_gen.go"))
	if strings.Contains(store, "TasksByTitle") {
		t.Errorf("TaskStore must not gain the ext queries:\n%s", store)
	}

	// Idempotent: a second run writes the same bytes.
	generateTask(t, root)
	if again := readGenFile(t, taskExtStorePath(root)); again != src {
		t.Errorf("a second generate changed the ext store:\n--- first\n%s\n--- second\n%s", src, again)
	}
}

// The scaffolded seam has no queries, so a new entity gets no ext store; and
// once the last query leaves the seam, the file it produced goes too.
func TestExtStore_FollowsTheSeam(t *testing.T) {
	root := t.TempDir()
	generateTask(t, root)
	if _, err := os.Stat(taskExtStorePath(root)); !os.IsNotExist(err) {
		t.Fatalf("a freshly scaffolded seam has no queries, so no ext store; stat err = %v", err)
	}
	seam := readGenFile(t, filepath.Join(root, "internal", "db", "task_repo_ext.go"))
	if !strings.Contains(seam, "TaskExtStore (task_ext_store_gen.go") {
		t.Errorf("the scaffolded seam must say its queries become TaskExtStore:\n%s", seam)
	}

	writeDBFile(t, root, "task_repo_ext.go", taskExtQueries)
	generateTask(t, root)
	if _, err := os.Stat(taskExtStorePath(root)); err != nil {
		t.Fatalf("ext store not written: %v", err)
	}

	writeDBFile(t, root, "task_repo_ext.go", "package db\n")
	generateTask(t, root)
	if _, err := os.Stat(taskExtStorePath(root)); !os.IsNotExist(err) {
		t.Fatalf("the seam lost its last query; its ext store must be removed, stat err = %v", err)
	}
}

// A project that already declares one of the ext store's names — a
// hand-written adapter of exactly this shape is the likely case — keeps its
// own and compiles as before; generate names the declaration instead of
// writing a file that redeclares it.
func TestExtStore_YieldsToANameTheProjectDeclares(t *testing.T) {
	for name, decl := range map[string]string{
		"interface":   "package db\n\ntype TaskExtStore interface{}\n",
		"constructor": "package db\n\nfunc NewTaskExtStore() {}\n",
		"accessor":    "package db\n\nfunc (s *Store) TasksExt() {}\n",
	} {
		t.Run(name, func(t *testing.T) {
			root := t.TempDir()
			dbDir := filepath.Join(root, "internal", "db")
			writeDBFile(t, root, "task_repo_ext.go", taskExtQueries)
			writeDBFile(t, root, "adapters.go", decl)
			ents := []config.PlanEntity{taskPlanEntity()}
			exts, notes := renderExtStores(dbDir, "internal/db", "db", ents, nil)
			if len(exts) != 0 {
				t.Fatalf("rendered an ext store that redeclares the project's name")
			}
			joined := strings.Join(notes, "\n")
			if !strings.Contains(joined, "internal/db/adapters.go:3") || !strings.Contains(joined, "no TaskExtStore") {
				t.Fatalf("the note must name the declaration and what was not generated: %q", joined)
			}

			generateTask(t, root)
			if _, err := os.Stat(taskExtStorePath(root)); !os.IsNotExist(err) {
				t.Fatalf("ext store written beside the project's own declaration")
			}
		})
	}
}

// An entity named <Entity>Ext has its own <Entity>ExtStore, in the same file
// name: the ext store yields to it rather than overwrite it.
