package contract

import "text/template"

// templateData is the input to the mock template. Earlier versions of
// this generator emitted three additional shim wrappers
// (middleware/tracing/metrics), but those were superseded by the
// observe.* Connect interceptors and helper APIs. The struct shape is
// preserved so future per-package generators can reuse it without
// re-deriving Imports / InterfaceNames.
type templateData struct {
	Package          string
	Source           string // the file the interfaces were read from (contract.go, deps.go)
	Receiver         string // every mock method's receiver; see mockReceiver
	Imports          []ImportDef
	Interfaces       []InterfaceDef
	InterfaceNames   map[string]bool   // local interface names (for zeroValue)
	PrimitiveAliases map[string]string // local named primitive aliases (for zeroValue)
}

// contractkitImport is the canonical import path injected for the mock
// template (Recorder embed + MockNotSet). Holding it in one place keeps
// the "is contractkit needed" guard in the generator easy to audit.
const contractkitImport = "github.com/reliant-labs/forge/pkg/contractkit"

// mockReceiver is the receiver every generated mock method declares. A
// contract parameter of the same name is renamed in the mock rather than
// this changing per method (MethodDef.withBodyScopedNames), so the receiver
// reads the same in every mock forge writes.
const mockReceiver = "m"

// mockTmpl generates mock_gen.go with function-field mocks.
//
// The mock embeds contractkit.Recorder by value so that methods like
// CallCount and Calls are promoted onto MockX without a constructor.
// Each generated method records its arguments and either delegates to
// the user-set XxxFunc or returns the canonical
// "MockX.<Method>Func not set" error from contractkit.MockNotSet —
// preserving the exact behavioural fingerprint that dogfood tests
// assert against.
//
// Each mock is its own self-certified section (checksums/sections.go): a
// change to one interface rewrites that mock's lines and its own section
// hash, so two branches that change different interfaces of one package
// merge with plain git into what forge generate renders for both. The
// blank line before each section line is what keeps the end of one mock
// and the start of the next from being adjacent changes.
var mockTmpl = template.Must(template.New("mock").Parse(`// Code generated by forge. DO NOT EDIT.
// forge-owned: regenerated every run — do not edit (forge project disown to take ownership)
// Source: {{ .Source }} in this package.
//
// To customize: edit {{ .Source }} (the interface IS the public surface) and
// re-run "forge generate". This file is regenerated unconditionally.
package {{ .Package }}

{{ if .Imports -}}
import (
{{ range .Imports }}	{{ .Declaration }}
{{ end }})
{{ end -}}

{{ range $iface := .Interfaces -}}
// forge:section {{ $iface.MockName }}

// {{ $iface.MockName }} is a test mock for the {{ $iface.QualifiedName }} interface.
//
// The embedded contractkit.Recorder records every call so tests can
// assert call counts and captured arguments. Set XxxFunc fields to
// override per-method behaviour; unset methods return the canonical
// "{{ $iface.MockName }}.<Method>Func not set" error.
type {{ $iface.MockName }} struct {
	contractkit.Recorder
{{ range $iface.Methods }}	{{ .Name }}Func {{ .FuncFieldType }}
{{ end }}}

{{ range $m := $iface.Methods -}}
// {{ $m.Name }} records the call and delegates to {{ $m.Name }}Func when set.
func ({{ $.Receiver }} *{{ $iface.MockName }}) {{ $m.Name }}({{ $m.ParamSignature }}){{ with $m.ResultSignature }} {{ . }}{{ end }} {
	{{ $.Receiver }}.Recorder.Record("{{ $m.Name }}"{{ with $m.RecordArgs }}, {{ . }}{{ end }})
	if {{ $.Receiver }}.{{ $m.Name }}Func != nil {
		{{ if $m.HasResults }}return {{ end }}{{ $.Receiver }}.{{ $m.Name }}Func({{ $m.CallArgs }}){{ if not $m.HasResults }}
		return{{ end }}
	}
{{ if $m.HasResults }}	return {{ $m.ZeroResults $iface.MockName $.InterfaceNames $.PrimitiveAliases }}
{{ end }}}

{{ end -}}
// Compile-time check.
var _ {{ $iface.QualifiedName }} = (*{{ $iface.MockName }})(nil)

{{ end -}}
`))
