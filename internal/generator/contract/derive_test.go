package contract

import (
	"os"
	"path/filepath"
	"strings"
	"testing"
)

func writeDeriveFiles(t *testing.T, files map[string]string) string {
	t.Helper()
	dir := t.TempDir()
	for name, src := range files {
		if err := os.WriteFile(filepath.Join(dir, name), []byte(src), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	return dir
}

// TestRenderDerivedContract: the derived interface is the marked type's
// DECLARED exported method set — pointer and value receivers, across files,
// in file then source order — with each method's doc (method-level
// forge:no-observe included) and the imports its signatures name, aliases
// kept. Unexported methods, promoted methods and other types' methods are
// not the contract.
func TestRenderDerivedContract(t *testing.T) {
	dir := writeDeriveFiles(t, map[string]string{
		"service.go": `package email

import (
	"context"
	"io"

	mailv1 "example.com/proj/gen/mail/v1"
)

// service sends mail.
//
//forge:contract
type service struct {
	io.Writer // promoted Write is not part of the contract
	deps Deps
}

type Deps struct{}

// Send delivers one message.
func (s *service) Send(ctx context.Context, to, subject string) (*mailv1.Receipt, error) { return nil, nil }

func (s *service) helper() {}

// Name is a value-receiver method.
//
// forge:no-observe
func (s service) Name() string { return "" }

type other struct{}

func (other) Ignored() {}

// New builds the service.
func New(deps Deps) (Service, error) { return &service{deps: deps}, nil }
`,
		"batch.go": `package email

import (
	"context"
	"time"
)

// Batch is declared in another file.
func (s *service) Batch(ctx context.Context, every time.Duration, msgs ...Message) error { return nil }

type Message struct{}
`,
	})

	got, err := RenderDerivedContract(dir, nil)
	if err != nil {
		t.Fatalf("RenderDerivedContract: %v", err)
	}
	src := string(got)
	for _, want := range []string{
		"// Code generated by forge. DO NOT EDIT.",
		"// Source: the //forge:contract type service in service.go.",
		"package email",
		`"context"`,
		`"time"`,
		`mailv1 "example.com/proj/gen/mail/v1"`,
		"// service sends mail.",
		"type Service interface {",
		"\t// Batch is declared in another file.\n\tBatch(ctx context.Context, every time.Duration, msgs ...Message) error",
		"\t// Send delivers one message.\n\tSend(ctx context.Context, to, subject string) (*mailv1.Receipt, error)",
		"\t// forge:no-observe\n\tName() string",
		"var _ Service = (*service)(nil)",
	} {
		if !strings.Contains(src, want) {
			t.Errorf("contract_gen.go lacks %q:\n%s", want, src)
		}
	}
	for _, unwanted := range []string{"helper", "Ignored", "Write(", `"io"`, "\n//forge:contract\n"} {
		if strings.Contains(src, unwanted) {
			t.Errorf("contract_gen.go has %q, which is not the contract:\n%s", unwanted, src)
		}
	}
	// batch.go sorts before service.go: file order, then source order.
	if strings.Index(src, "Batch(") > strings.Index(src, "Send(") || strings.Index(src, "Send(") > strings.Index(src, "Name()") {
		t.Errorf("methods are not in file-then-source order:\n%s", src)
	}
}

// TestRenderDerivedContract_Refusals: every shape the derived interface
// cannot express is an error naming what to change.
func TestRenderDerivedContract_Refusals(t *testing.T) {
	cases := []struct {
		name  string
		files map[string]string
		want  string
	}{
		{
			name: "hand-written Service too",
			files: map[string]string{
				"contract.go": "package p\n\ntype Service interface{ Do() }\n",
				"service.go":  "package p\n\n//forge:contract\ntype service struct{}\n\nfunc (s *service) Do() {}\n",
			},
			want: "declares its contract twice",
		},
		{
			name: "marked interface too",
			files: map[string]string{
				"contract.go": "package p\n\n//forge:contract\ntype Gateway interface{ Do() }\n",
				"service.go":  "package p\n\n//forge:contract\ntype service struct{}\n\nfunc (s *service) Do() {}\n",
			},
			want: "declares its contract twice",
		},
		{
			name:  "generic",
			files: map[string]string{"service.go": "package p\n\n//forge:contract\ntype service[T any] struct{ v T }\n\nfunc (s *service[T]) Do() {}\n"},
			want:  "generic type service",
		},
		{
			name: "two marked",
			files: map[string]string{
				"a.go": "package p\n\n//forge:contract\ntype a struct{}\n",
				"b.go": "package p\n\n//forge:contract\ntype b struct{}\n",
			},
			want: "2 types carry //forge:contract",
		},
		{
			name:  "alias",
			files: map[string]string{"service.go": "package p\n\ntype impl struct{}\n\n//forge:contract\ntype service = impl\n"},
			want:  "alias service",
		},
		{
			name:  "named Service",
			files: map[string]string{"service.go": "package p\n\n//forge:contract\ntype Service struct{}\n"},
			want:  "rename the type",
		},
		{
			name:  "a func named Service",
			files: map[string]string{"service.go": "package p\n\n//forge:contract\ntype service struct{}\n\nfunc Service() {}\n"},
			want:  "declares a func named Service",
		},
		{
			name: "one name for two packages",
			files: map[string]string{
				"a.go": "package p\n\nimport v1 \"example.com/a/v1\"\n\n//forge:contract\ntype service struct{}\n\nfunc (s *service) A() v1.T { return v1.T{} }\n",
				"b.go": "package p\n\nimport v1 \"example.com/b/v1\"\n\nfunc (s *service) B() v1.T { return v1.T{} }\n",
			},
			want: "alias one of the imports",
		},
		{
			// contract_gen.go builds everywhere; the marked type must too.
			name:  "marked type in a //go:build file",
			files: map[string]string{"service.go": "//go:build linux\n\npackage p\n\n//forge:contract\ntype service struct{}\n\nfunc (s *service) Do() {}\n"},
			want:  "build constraints leave out of some builds",
		},
		{
			name:  "marked type in a _GOOS file",
			files: map[string]string{"service_windows.go": "package p\n\n//forge:contract\ntype service struct{}\n\nfunc (s *service) Do() {}\n"},
			want:  "build constraints leave out of some builds",
		},
		{
			name: "exported method in a constrained file",
			files: map[string]string{
				"service.go":       "package p\n\n//forge:contract\ntype service struct{}\n\nfunc (s *service) Do() {}\n",
				"service_linux.go": "package p\n\nfunc (s *service) Linux() {}\n",
			},
			want: "service.Linux is declared in a file build constraints leave out",
		},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			_, err := RenderDerivedContract(writeDeriveFiles(t, tc.files), nil)
			if err == nil || !strings.Contains(err.Error(), tc.want) {
				t.Fatalf("err = %v, want one containing %q", err, tc.want)
			}
		})
	}
}

// TestSyncDerivedContract_MockCoversServiceAndDeps: mock_gen.go generated
// from a derived contract mocks Service AND the package's hand-declared
// dependency interfaces (deps.go, and a contract.go kept beside the marked
// type), and names the marked type's file as the one to edit. Removing the
// marker removes contract_gen.go.
func TestSyncDerivedContract_MockCoversServiceAndDeps(t *testing.T) {
	dir := writeDeriveFiles(t, map[string]string{
		"service.go": `package email

import "context"

//forge:contract
type service struct{ deps Deps }

type Deps struct {
	Store Store
	Clock Clock
}

func (s *service) Send(ctx context.Context, to string) error { return nil }

func New(deps Deps) (Service, error) { return &service{deps: deps}, nil }
`,
		"deps.go":     "// forge:deps — consumer-declared interfaces for this package's Deps.\npackage email\n\nimport \"context\"\n\ntype Store interface {\n\tSave(ctx context.Context, id string) error\n}\n",
		"contract.go": "package email\n\nimport \"time\"\n\n// Clock is a dependency declared in contract.go.\ntype Clock interface{ Now() time.Time }\n",
	})

	if out, err := SyncDerivedContract(dir, Options{}); err != nil || out != DeriveWritten {
		t.Fatalf("SyncDerivedContract = %v, %v; want DeriveWritten", out, err)
	}
	if out, err := SyncDerivedContract(dir, Options{}); err != nil || out != DeriveUnchanged {
		t.Fatalf("second SyncDerivedContract = %v, %v; want DeriveUnchanged", out, err)
	}
	if err := GenerateMock(filepath.Join(dir, "contract_gen.go"), Options{Resolver: &Resolver{names: map[string]string{}}}); err != nil {
		t.Fatalf("GenerateMock: %v", err)
	}
	mock, err := os.ReadFile(filepath.Join(dir, "mock_gen.go"))
	if err != nil {
		t.Fatal(err)
	}
	for _, want := range []string{"type MockService struct", "type MockStore struct", "type MockClock struct", "edit service.go", `"time"`} {
		if !strings.Contains(string(mock), want) {
			t.Errorf("mock_gen.go lacks %q:\n%s", want, mock)
		}
	}

	// Unmarking removes the derived file.
	src, _ := os.ReadFile(filepath.Join(dir, "service.go"))
	if err := os.WriteFile(filepath.Join(dir, "service.go"), []byte(strings.Replace(string(src), "//forge:contract\n", "", 1)), 0o644); err != nil {
		t.Fatal(err)
	}
	if out, err := SyncDerivedContract(dir, Options{}); err != nil || out != DeriveRemoved {
		t.Fatalf("SyncDerivedContract after unmarking = %v, %v; want DeriveRemoved", out, err)
	}
	if _, err := os.Stat(filepath.Join(dir, "contract_gen.go")); !os.IsNotExist(err) {
		t.Fatalf("contract_gen.go survived its marker (err=%v)", err)
	}
}

// TestSyncDerivedContract_KeepsAContractGenForgeNeverWrote: a contract_gen.go
// with no forge header and no marker behind it is somebody's own file.
func TestSyncDerivedContract_KeepsAContractGenForgeNeverWrote(t *testing.T) {
	dir := writeDeriveFiles(t, map[string]string{
		"contract_gen.go": "package p\n\n// mine\ntype X interface{}\n",
	})
	if out, err := SyncDerivedContract(dir, Options{}); err != nil || out != DeriveKept {
		t.Fatalf("SyncDerivedContract = %v, %v; want DeriveKept", out, err)
	}
}

// TestRenderDerivedContract_AssertionNamesTheSatisfyingMethodSet: the
// compile-time assertion uses *T when a method has a pointer receiver, and a
// T value when every method has a value receiver.
func TestRenderDerivedContract_AssertionNamesTheSatisfyingMethodSet(t *testing.T) {
	cases := []struct {
		name, src, want string
	}{
		{"pointer", "package p\n\n//forge:contract\ntype service struct{}\n\nfunc (s service) A() {}\n\nfunc (s *service) B() {}\n", "var _ Service = (*service)(nil)"},
		{"value struct", "package p\n\n//forge:contract\ntype service struct{}\n\nfunc (s service) A() {}\n", "var _ Service = service{}"},
		{"value non-composite", "package p\n\n//forge:contract\ntype level int\n\nfunc (l level) A() {}\n", "var _ Service = *new(level)"},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			got, err := RenderDerivedContract(writeDeriveFiles(t, map[string]string{"service.go": tc.src}), nil)
			if err != nil {
				t.Fatal(err)
			}
			if !strings.Contains(string(got), tc.want) {
				t.Fatalf("want %q in:\n%s", tc.want, got)
			}
		})
	}
}
