// writeContract writes a contract.go into a fresh temp dir and returns the dir.
func writeContract(t *testing.T, src string) string {
	t.Helper()
	dir := t.TempDir()
	if err := os.WriteFile(filepath.Join(dir, "contract.go"), []byte(src), 0o644); err != nil {
		t.Fatalf("write contract.go: %v", err)
	}
	return dir
}

func genDecorator(t *testing.T, dir, iface, ns string) string {
	t.Helper()
	cf, err := ParseContract(filepath.Join(dir, "contract.go"))
	if err != nil {
		t.Fatalf("parse: %v", err)
	}
	// The wrapper's constructor/struct names are resolved by the caller
	// (codegen.ResolveMiddlewareWrapper, keyed off the concrete return type) and
	// threaded in. For the canonical single-impl shape the concrete type
	// `service` title-cases to the interface name, so these match what the real
	// pipeline passes for a package whose New returns `iface`.
	ctorName := "New" + iface + "WithForgeMiddleware"
	structName := "forgeMiddleware" + iface
	written, err := WriteObservedDecorator(cf, dir, iface, ctorName, structName, ns, nil, Options{})
	if err != nil {
		t.Fatalf("WriteObservedDecorator: %v", err)
	}
	if !written {
		t.Fatalf("expected decorator to be written for iface %q", iface)
	}
	out, err := os.ReadFile(filepath.Join(dir, "middleware_gen.go"))
	if err != nil {
		t.Fatalf("read decorator: %v", err)
	}
	return string(out)
}

func TestObservedDecorator_AllMethodShapes(t *testing.T) {
	dir := writeContract(t, `package checkout

import "context"

type Service interface {
	Run(ctx context.Context, in RunInput) (RunResult, error)
	Ping(ctx context.Context) error
	Close() error
	Lookup(ctx context.Context, id string) (string, int, error)
	Snapshot() State
}

type RunInput struct{ ID string }
type RunResult struct{ OK bool }
type State struct{ N int }
`)
	got := genDecorator(t, dir, "Service", "checkout")

	// Header + slim shape.
	for _, want := range []string{
		"// Code generated by forge. DO NOT EDIT.",
		"func NewServiceWithForgeMiddleware(inner Service) Service {",
		"return &forgeMiddlewareService{inner: inner, chain: newObserveChain()}",
		"type forgeMiddlewareService struct {",
		"chain *observe.ComponentChain",
	} {
		if !strings.Contains(got, want) {
			t.Errorf("decorator missing %q\n---\n%s", want, got)
		}
	}

	// (T, error) → generic Around one-liner with the correct op name.
	if !strings.Contains(got, `o.chain.Around(ctx, "checkout.Run", func(ctx context.Context) (RunResult, error) {`) {
		t.Errorf("Run wrapper not the Around one-liner:\n%s", got)
	}
	// error-only → Run one-liner.
	if !strings.Contains(got, `o.chain.Run(ctx, "checkout.Ping", func(ctx context.Context) error {`) {
		t.Errorf("Ping wrapper not the Run one-liner:\n%s", got)
	}
	// non-ctx error-only → context.Background(), unnamed closure ctx.
	if !strings.Contains(got, `o.chain.Run(context.Background(), "checkout.Close", func(_ context.Context) error {`) {
		t.Errorf("Close wrapper not background-ctx Run:\n%s", got)
	}
	// (A, B, error) → general capture form.
	if !strings.Contains(got, `err := o.chain.Run(ctx, "checkout.Lookup"`) ||
		!strings.Contains(got, "return r0, r1, err") {
		t.Errorf("Lookup wrapper not the multi-result capture form:\n%s", got)
	}
	// non-ctx, non-error single result.
	if !strings.Contains(got, `o.chain.Run(context.Background(), "checkout.Snapshot"`) ||
		!strings.Contains(got, "return r0") {
		t.Errorf("Snapshot wrapper not the non-error capture form:\n%s", got)
	}
}

