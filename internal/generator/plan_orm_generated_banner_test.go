// TestGeneratePlanORM_EveryGeneratedFileCarriesGoGeneratedBanner pins the
// ownership statement of every file the ORM projection writes, in both
// placements (the default internal/db and database.orm.package).
//
// A file is forge-generated when it carries the forge:hash stamp — the
// Tier-1 writer's mark. Every such file must ALSO carry Go's own
// generated-code banner before its package clause, judged by
// go/ast.IsGenerated (the `^// Code generated .* DO NOT EDIT\.$` rule
// gopls and golangci-lint use). store_gen.go was stamped but had no banner,
// so golangci-lint treated it as hand-written: `forge lint`'s auto-fix pass
// rewrote it and forge's own drift gate then failed on that rewrite.
//
// The _repo_ext.go seams are the opposite case — scaffold-once and the
// user's from birth — so they must carry neither the stamp nor the banner.
func TestGeneratePlanORM_EveryGeneratedFileCarriesGoGeneratedBanner(t *testing.T) {
	entities := []config.PlanEntity{taskPlanEntity(), constraintTestEntity(nil)}
	for _, orm := range []config.ORMConfig{{}, {Package: "internal/store"}} {
		t.Run(orm.PackageDir(), func(t *testing.T) {
			root := t.TempDir()
			if err := GeneratePlanORM(root, orm, entities, nil); err != nil {
				t.Fatalf("GeneratePlanORM: %v", err)
			}
			dir := filepath.Join(root, filepath.FromSlash(orm.PackageDir()))
			files, err := os.ReadDir(dir)
			if err != nil {
				t.Fatal(err)
			}

			var generated, owned []string
			for _, e := range files {
				name := e.Name()
				body, err := os.ReadFile(filepath.Join(dir, name))
				if err != nil {
					t.Fatal(err)
				}
				f, err := parser.ParseFile(token.NewFileSet(), name, body, parser.ParseComments|parser.PackageClauseOnly)
				if err != nil {
					t.Fatalf("%s: %v", name, err)
				}
				stamped := checksums.Verify(body) != checksums.NoMarker
				if stamped {
					generated = append(generated, name)
				} else {
					owned = append(owned, name)
				}
				switch {
				case stamped && !ast.IsGenerated(f):
					t.Errorf("%s/%s is forge-generated (forge:hash stamped) but Go does not recognise it as generated — "+
						"it needs `// Code generated by forge. DO NOT EDIT.` before the package clause. Header:\n%s",
						orm.PackageDir(), name, firstNLines(string(body), 5))
				case !stamped && ast.IsGenerated(f):
					t.Errorf("%s/%s is user-owned (no forge:hash stamp) but claims to be generated", orm.PackageDir(), name)
				}
				if stamped && checksums.Verify(body) != checksums.Pristine {
					t.Errorf("%s/%s: the forge:hash stamp does not certify the bannered render", orm.PackageDir(), name)
				}
			}

			// The classification itself is pinned, so a new ORM output (or a
			// seam that starts being stamped) has to update this list on purpose.
			sort.Strings(generated)
			sort.Strings(owned)
			if got, want := strings.Join(generated, " "), "job_orm_gen.go store_gen.go task_orm_gen.go"; got != want {
				t.Errorf("forge-generated ORM files = %s, want %s", got, want)
			}
			if got, want := strings.Join(owned, " "), "job_repo_ext.go task_repo_ext.go"; got != want {
				t.Errorf("user-owned ORM files = %s, want %s", got, want)
			}
		})
	}
}
