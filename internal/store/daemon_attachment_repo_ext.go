// The lease is written on every daemon heartbeat (15s per connected daemon)
// and read on routing and liveness checks, each statement carrying a
// timestamp that differs on every call. bun formats arguments into the text,
// which under pgx's statement cache makes every such call a new prepared
// statement (internal/db/SCHEMA.md, rule 2). So the heartbeat writes and the
// lease reads below bind their values: through the generated by-key
// delegates (which bind) or orm.Context's raw passthrough with $N. The
// once-per-session statements (upsert at connect, release at teardown, the
// reaper) stay bun-formatted.

// UpsertDaemonAttachment writes the lease a new stream session holds. A
// re-attachment resets memory telemetry and detected ports: a new stream is
// a fresh daemon session. It reports whether it wrote: another user's lease
// is replaceable only by the daemon row's owner (which heals a lease a past
// hijack left behind), so a refusal writes nothing.
func UpsertDaemonAttachment(ctx context.Context, db orm.Context, att *core.DaemonAttachment) (bool, error) {
	res, err := db.Bun().NewRaw(`
		INSERT INTO daemon_attachment (daemon_id, user_id, source, pod_ip, pod_port, attached_at, last_stream_activity)
		VALUES (?0, ?1, ?2, ?3, ?4, ?5, ?6)
		ON CONFLICT (daemon_id) DO UPDATE SET
			user_id = EXCLUDED.user_id,
			source = EXCLUDED.source,
			pod_ip = EXCLUDED.pod_ip,
			pod_port = EXCLUDED.pod_port,
			attached_at = EXCLUDED.attached_at,
			last_stream_activity = EXCLUDED.last_stream_activity,
			memory_used_bytes = 0,
			memory_limit_bytes = 0,
			memory_pressure = FALSE,
			detected_ports = '[]'
		WHERE daemon_attachment.user_id = EXCLUDED.user_id
		   OR EXISTS (SELECT 1 FROM daemons d WHERE d.id = EXCLUDED.daemon_id AND d.user_id = EXCLUDED.user_id)`,
		att.DaemonID, att.UserID, string(att.Source), att.PodIP, att.PodPort, att.AttachedAt, att.LastStreamActivity,
	).Exec(ctx)
	return rowsWritten(res, err)
}

// RenewDaemonAttachment renews the lease of a stream the caller holds right
// now, re-creating the row if it is gone, and reports whether it had to. The
// row only moves forward (last_stream_activity and attached_at keep the
// later value), the insert is fenced on the daemons row still being the
// user's, and another user's lease is never touched; either refusal is
// created == false with no error. xmax = 0 holds only for a row this
// statement inserted. Bound ($N): it runs on every heartbeat.
func RenewDaemonAttachment(ctx context.Context, db orm.Context, att *core.DaemonAttachment) (created bool, err error) {
	err = db.QueryRow(ctx, `
		INSERT INTO daemon_attachment (daemon_id, user_id, source, pod_ip, pod_port, attached_at, last_stream_activity)
		SELECT $1, $2, $3, $4, $5, $6, $7
		WHERE EXISTS (SELECT 1 FROM daemons d WHERE d.id = $1 AND d.user_id = $2)
		ON CONFLICT (daemon_id) DO UPDATE SET
			last_stream_activity = GREATEST(daemon_attachment.last_stream_activity, EXCLUDED.last_stream_activity),
			attached_at = GREATEST(daemon_attachment.attached_at, EXCLUDED.attached_at)
		WHERE daemon_attachment.user_id = EXCLUDED.user_id
		RETURNING (xmax = 0)`,
		att.DaemonID, att.UserID, string(att.Source), att.PodIP, att.PodPort, att.AttachedAt, att.LastStreamActivity,
	).Scan(&created)
	if errors.Is(err, sql.ErrNoRows) {
		return false, nil
	}
	return created, err
}

// SetDaemonAttachmentMemory records a heartbeat's workspace memory telemetry
// on the lease. A no-op when there is no lease; last_stream_activity is left
// to RenewDaemonAttachment.
func SetDaemonAttachmentMemory(ctx context.Context, db orm.Context, daemonID string, usedBytes, limitBytes int64, pressure bool) error {
	row := &DaemonAttachment{DaemonID: daemonID, MemoryUsedBytes: usedBytes, MemoryLimitBytes: limitBytes, MemoryPressure: pressure}
	return ignoreNoRows(UpdateDaemonAttachmentMasked(ctx, db, row,
		[]string{DaemonAttachmentFieldMemoryUsedBytes, DaemonAttachmentFieldMemoryLimitBytes, DaemonAttachmentFieldMemoryPressure},
		crud.NoReadBack()))
}

// SetDaemonAttachmentPorts records a heartbeat's detected listener ports on
// the lease, JSON-encoded (nil is []). A no-op when there is no lease.
func SetDaemonAttachmentPorts(ctx context.Context, db orm.Context, daemonID string, ports []uint32) error {
	if ports == nil {
		ports = []uint32{}
	}
	encoded, err := json.Marshal(ports)
	if err != nil {
		return fmt.Errorf("encoding detected ports: %w", err)
	}
	s := string(encoded)
	row := &DaemonAttachment{DaemonID: daemonID, DetectedPorts: &s}
	return ignoreNoRows(UpdateDaemonAttachmentMasked(ctx, db, row,
		[]string{DaemonAttachmentFieldDetectedPorts}, crud.NoReadBack()))
}

// ReleaseDaemonAttachment deletes the lease a stream session created when it
// ends — the row whose attached_at is at or before the session's own, so a
// stale teardown cannot delete a newer session's lease — and moves the
// released lease's last_stream_activity onto daemons.last_seen_at, forward
// only, in the same statement.
func ReleaseDaemonAttachment(ctx context.Context, db orm.Context, daemonID string, attachedAt time.Time) error {
	_, err := db.Bun().NewRaw(`
		WITH released AS (
			DELETE FROM daemon_attachment
			WHERE daemon_id = ?0 AND attached_at <= ?1
			RETURNING daemon_id, last_stream_activity
		)
		UPDATE daemons d
		SET last_seen_at = GREATEST(d.last_seen_at, released.last_stream_activity)
		FROM released
		WHERE d.id = released.daemon_id`,
		daemonID, attachedAt,
	).Exec(ctx)
	return err
}

// DeleteStaleDaemonAttachments removes leases not renewed since cutoff and
// returns how many. The row count is advisory: a driver that cannot report
// it does not fail the GC.
func DeleteStaleDaemonAttachments(ctx context.Context, db orm.Context, cutoff time.Time) (int64, error) {
	res, err := db.Bun().NewDelete().Model((*DaemonAttachment)(nil)).
		Where("last_stream_activity < ?", cutoff).
		Exec(ctx)
	if err != nil {
		return 0, err
	}
	n, err := res.RowsAffected()
	if err != nil {
		return 0, nil
	}
	return n, nil
}

// IsUserDaemonAttached reports whether any of the user's daemons holds a
// lease renewed after cutoff. Bound ($N): a liveness read.
func IsUserDaemonAttached(ctx context.Context, db orm.Context, userID string, cutoff time.Time) (bool, error) {
	return leaseExists(ctx, db, `SELECT 1 FROM daemon_attachment WHERE user_id = $1 AND last_stream_activity > $2 LIMIT 1`, userID, cutoff)
}

// IsDaemonIDAttached reports whether the daemon holds a lease renewed after
// cutoff. Bound ($N): a routing read.
func IsDaemonIDAttached(ctx context.Context, db orm.Context, daemonID string, cutoff time.Time) (bool, error) {
	return leaseExists(ctx, db, `SELECT 1 FROM daemon_attachment WHERE daemon_id = $1 AND last_stream_activity > $2 LIMIT 1`, daemonID, cutoff)
}

func leaseExists(ctx context.Context, db orm.Context, query string, key string, cutoff time.Time) (bool, error) {
	var n int
	err := db.QueryRow(ctx, query, key, cutoff).Scan(&n)
	if errors.Is(err, sql.ErrNoRows) {
		return false, nil
	}
	if err != nil {
		return false, fmt.Errorf("checking daemon attachment: %w", err)
	}
	return true, nil
}

// ListAttachedDaemonIDsForUser returns the user's daemons holding a lease
// renewed after cutoff. Bound ($N): a liveness read.
func ListAttachedDaemonIDsForUser(ctx context.Context, db orm.Context, userID string, cutoff time.Time) ([]string, error) {
	rows, err := db.Query(ctx, `SELECT daemon_id FROM daemon_attachment WHERE user_id = $1 AND last_stream_activity > $2`, userID, cutoff)
	if err != nil {
		return nil, fmt.Errorf("listing attached daemon ids: %w", err)
	}
	defer rows.Close()
	var ids []string
	for rows.Next() {
		var id string
		if err := rows.Scan(&id); err != nil {
			return nil, fmt.Errorf("scanning attached daemon id: %w", err)
		}
		ids = append(ids, id)
	}
	if err := rows.Err(); err != nil {
		return nil, fmt.Errorf("iterating attached daemon ids: %w", err)
	}
	return ids, nil
}

// ListFreshDaemonAttachmentsForUser returns the user's full lease records
// (memory telemetry included) renewed after cutoff. Bound ($N): a liveness
// read.
func ListFreshDaemonAttachmentsForUser(ctx context.Context, db orm.Context, userID string, cutoff time.Time) ([]*core.DaemonAttachment, error) {
	rows, err := db.Query(ctx, `SELECT `+daemonAttachmentColumns+` FROM daemon_attachment WHERE user_id = $1 AND last_stream_activity > $2`, userID, cutoff)
	if err != nil {
		return nil, fmt.Errorf("listing attachments: %w", err)
	}
	return scanDaemonAttachments(rows)
}

// ListOutboundAttachments returns every outbound lease. Unbounded.
func ListOutboundAttachments(ctx context.Context, db orm.Context) ([]*core.DaemonAttachment, error) {
	return listDaemonAttachments(ctx, db, func(q *bun.SelectQuery) {
		q.Where("source = ?", core.DaemonAttachmentSourceOutbound)
	})
}

// ListAllDaemonAttachments returns every lease, whatever its source.
// Unbounded, like ListOutboundAttachments.
func ListAllDaemonAttachments(ctx context.Context, db orm.Context) ([]*core.DaemonAttachment, error) {
	return listDaemonAttachments(ctx, db, func(*bun.SelectQuery) {})
}

func listDaemonAttachments(ctx context.Context, db orm.Context, filter func(*bun.SelectQuery)) ([]*core.DaemonAttachment, error) {
	var rows []*DaemonAttachment
	q := db.Bun().NewSelect().Model(&rows)
	filter(q)
	if err := q.Scan(ctx); err != nil {
		return nil, fmt.Errorf("listing attachments: %w", err)
	}
	out := make([]*core.DaemonAttachment, len(rows))
	for i, row := range rows {
		var detected string
		if row.DetectedPorts != nil {
			detected = *row.DetectedPorts
		}
		var podPort *int
		if row.PodPort != nil {
			v := int(*row.PodPort)
			podPort = &v
		}
		out[i] = daemonAttachmentToCore(row.DaemonID, row.UserID, row.Source, row.PodIP, podPort,
			row.AttachedAt, row.LastStreamActivity, row.MemoryUsedBytes, row.MemoryLimitBytes, row.MemoryPressure, detected)
	}
	return out, nil
}

// daemonAttachmentColumns is the column list scanDaemonAttachments reads, in order.
const daemonAttachmentColumns = `daemon_id, user_id, source, pod_ip, pod_port, attached_at, last_stream_activity, memory_used_bytes, memory_limit_bytes, memory_pressure, detected_ports`

func scanDaemonAttachments(rows *sql.Rows) ([]*core.DaemonAttachment, error) {
	defer rows.Close()
	var out []*core.DaemonAttachment
	for rows.Next() {
		var (
			daemonID, userID, source, detected string
			podIP                              sql.NullString
			podPort                            sql.NullInt64
			attachedAt, lastActivity           time.Time
			used, limit                        int64
			pressure                           bool
		)
		if err := rows.Scan(&daemonID, &userID, &source, &podIP, &podPort, &attachedAt, &lastActivity, &used, &limit, &pressure, &detected); err != nil {
			return nil, fmt.Errorf("scanning attachment: %w", err)
		}
		var ip *string
		if podIP.Valid {
			ip = &podIP.String
		}
		var port *int
		if podPort.Valid {
			v := int(podPort.Int64)
			port = &v
		}
		out = append(out, daemonAttachmentToCore(daemonID, userID, core.DaemonAttachmentSource(source), ip, port,
			attachedAt, lastActivity, used, limit, pressure, detected))
	}
	if err := rows.Err(); err != nil {
		return nil, fmt.Errorf("iterating attachments: %w", err)
	}
	return out, nil
}

// daemonAttachmentToCore builds the lease record. detected_ports is JSON; a decode
// failure degrades to "no ports" rather than failing the liveness read.
func daemonAttachmentToCore(daemonID, userID string, source core.DaemonAttachmentSource, podIP *string, podPort *int,
	attachedAt, lastActivity time.Time, used, limit int64, pressure bool, detected string) *core.DaemonAttachment {
	att := &core.DaemonAttachment{
		DaemonID: daemonID, UserID: userID, Source: source, PodIP: podIP, PodPort: podPort,
		AttachedAt: attachedAt, LastStreamActivity: lastActivity,
		MemoryUsedBytes: used, MemoryLimitBytes: limit, MemoryPressure: pressure,
	}
	if detected != "" && detected != "[]" {
		_ = json.Unmarshal([]byte(detected), &att.DetectedPorts)
	}
	return att
}

// ignoreNoRows turns a missing row into success.
func ignoreNoRows(err error) error {
	if errors.Is(err, orm.ErrNoRows) {
		return nil
	}
	return err
}

