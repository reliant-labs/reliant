// The chat reads (P5b L1b) go through the chats_with_activity view: it is the
// one definition of a chat's computed state (activity, display_state,
// list_in_sidebar, the root workflow status, the usage-limit wait), so every
// read of a chat returns it. The view stays SQL; ChatsWithActivity is its
// generated read-only projection.

// GetChat returns the chat with its computed state, or core.ErrChatNotFound.
// The generated by-key read binds its argument.
func GetChat(ctx context.Context, db orm.Context, id string) (*core.Chat, error) {
	row, err := GetChatsWithActivityByID(ctx, db, id)
	if errors.Is(err, sql.ErrNoRows) {
		return nil, fmt.Errorf("%w: %s", core.ErrChatNotFound, id)
	}
	if err != nil {
		return nil, fmt.Errorf("failed to get chat: %w", err)
	}
	return chatFromView(row), nil
}

// GetChatWithUserCheck returns the chat only when userID owns it; any other
// chat is core.ErrChatNotFound, exactly like one that does not exist. The
// owner is compared in Go after the bound by-key read rather than filtered in
// SQL, because the list builder formats its values into the statement text
// and this read runs on every chat RPC.
func GetChatWithUserCheck(ctx context.Context, db orm.Context, id, userID string) (*core.Chat, error) {
	row, err := GetChatsWithActivityByID(ctx, db, id)
	if errors.Is(err, sql.ErrNoRows) || (err == nil && chatViewString(row.UserID) != userID) {
		return nil, fmt.Errorf("%w: %s", core.ErrChatNotFound, id)
	}
	if err != nil {
		return nil, fmt.Errorf("failed to get chat: %w", err)
	}
	return chatFromView(row), nil
}

// ListChats lists a user's chats, most recently active first. The optional
// filters are composed orm.QueryOptions, appended only when set, so each call
// sends exactly the predicates it uses. Every caller passes a Limit; a zero
// Limit lists up to the generated List's default cap.
func ListChats(ctx context.Context, db orm.Context, f core.ChatFilters) ([]*core.Chat, error) {
	opts := []orm.QueryOption{orm.WhereEq(ChatsWithActivityFieldUserID, f.UserID)}
	if f.ProjectID != nil {
		opts = append(opts, orm.WhereEq(ChatsWithActivityFieldProjectID, *f.ProjectID))
	}
	if f.State != nil {
		opts = append(opts, orm.WhereEq(ChatsWithActivityFieldState, *f.State))
	}
	if f.ExcludeArchived {
		opts = append(opts, orm.WhereNotEq(ChatsWithActivityFieldState, core.ChatStateArchived))
	}
	if f.SidebarOnly {
		// The policy lives in ONE place, the view's list_in_sidebar column.
		opts = append(opts, orm.WhereEq(ChatsWithActivityFieldListInSidebar, true))
	}
	opts = append(opts, orm.WithOrderBy(ChatsWithActivityFieldLastActive, orm.Desc))
	if f.Limit > 0 {
		opts = append(opts, orm.WithLimit(f.Limit))
	}
	if f.Offset > 0 {
		opts = append(opts, orm.WithOffset(f.Offset))
	}
	rows, err := ListChatsWithActivity(ctx, db, opts...)
	if err != nil {
		return nil, fmt.Errorf("failed to list chats: %w", err)
	}
	return chatsFromView(rows), nil
}

// SearchChats lists a user's chats whose title, or any text block of any of
// their messages, contains the query; most recently active first. A non-empty
// ProjectID narrows it to that project; empty searches all of the user's. A
// blank query matches nothing.
//
// It searches the chat list, so it applies the chat list's policy
// (list_in_sidebar): an automation's runs are searched in Runs, not here.
func SearchChats(ctx context.Context, db orm.Context, f core.ChatSearchFilters) ([]*core.Chat, error) {
	query := strings.TrimSpace(f.SearchQuery)
	if query == "" {
		return []*core.Chat{}, nil
	}
	pattern := "%" + query + "%"
	var rows []*ChatsWithActivity
	q := db.Bun().NewSelect().Model(&rows).Distinct().
		Join("LEFT JOIN messages m ON chats_with_activity.id = m.chat_id").
		// block_type 1 is CONTENT_BLOCK_TYPE_TEXT.
		Join("LEFT JOIN message_content_blocks mcb ON m.id = mcb.message_id AND mcb.block_type = 1").
		Where("chats_with_activity.user_id = ?", f.UserID).
		Where("chats_with_activity.list_in_sidebar")
	if f.ProjectID != "" {
		q = q.Where("chats_with_activity.project_id = ?", f.ProjectID)
	}
	if f.State != nil {
		q = q.Where("chats_with_activity.state = ?", *f.State)
	}
	q = q.Where("(chats_with_activity.title LIKE ? OR mcb.content LIKE ?)", pattern, pattern).
		OrderExpr("chats_with_activity.last_active DESC")
	if f.Limit > 0 {
		q = q.Limit(int64(f.Limit))
	}
	if f.Offset > 0 {
		q = q.Offset(int64(f.Offset))
	}
	if err := q.Scan(ctx); err != nil {
		return nil, fmt.Errorf("failed to search chats: %w", err)
	}
	return chatsFromView(rows), nil
}

// listArchivedChatsSQL lists a user's archived chats with their worktree
// name. It reads chats_with_activity (not chats) so the root workflow state
// and last_message_at come back like every other chat read, and falls back to
// the name captured at archive time, then the project's, when the worktree
// row is gone.
//
// The sidebar's Archived tab, so it lists what the sidebar lists: the
// list_in_sidebar policy, as ListChats applies it with SidebarOnly. An
// automation archives its own runs once they succeed; those are history in
// Runs (ListRuns with include_archived), not chats the user put away.
//
// The view's columns are named, never c.*: migrations re-create this view
// with new columns, and a star prepared before one fails after it
// (columns.go).
var listArchivedChatsSQL = `
SELECT
    ` + columnsOf[ChatsWithActivity]("c") + `,
    COALESCE(w.name, c.archived_worktree_name, p.name) AS worktree_name,
    w.deleted_at AS worktree_deleted_at
FROM chats_with_activity c
LEFT JOIN worktrees w ON c.worktree_id = w.id
LEFT JOIN projects p ON c.project_id = p.id
WHERE c.state = 3
  AND c.user_id = ?0
  AND c.list_in_sidebar
ORDER BY c.updated_at DESC`

// ListArchivedChats lists the user's archived chats, most recently updated
// first.
func ListArchivedChats(ctx context.Context, db orm.Context, userID string) ([]*core.ArchivedChatInfo, error) {
	var rows []struct {
		ChatsWithActivity
		WorktreeName      *string    `bun:"worktree_name"`
		WorktreeDeletedAt *time.Time `bun:"worktree_deleted_at"`
	}
	if err := db.Bun().NewRaw(listArchivedChatsSQL, userID).Scan(ctx, &rows); err != nil {
		return nil, fmt.Errorf("failed to list archived chats: %w", err)
	}
	items := make([]*core.ArchivedChatInfo, len(rows))
	for i := range rows {
		name := chatViewString(rows[i].WorktreeName)
		items[i] = &core.ArchivedChatInfo{
			Chat:              *chatFromView(&rows[i].ChatsWithActivity),
			WorktreeName:      &name,
			WorktreeDeletedAt: rows[i].WorktreeDeletedAt,
		}
	}
	return items, nil
}

// GetChatActivity returns the chat's computed activity (0, IDLE, when the view
// has none).
func GetChatActivity(ctx context.Context, db orm.Context, chatID string) (int, error) {
	state, err := GetChatActivityState(ctx, db, chatID)
	if err != nil {
		return 0, err
	}
	return state.Activity, nil
}

// GetChatActivityState returns the chat's computed activity and working-thread
// count. It runs after every write that can move either, so it selects the two
// columns through the raw passthrough with a bound $1: the view is inlined
// into the query, so only those expressions are evaluated, and the statement
// text is the same on every call.
func GetChatActivityState(ctx context.Context, db orm.Context, chatID string) (core.ChatActivityState, error) {
	var state core.ChatActivityState
	err := db.QueryRow(ctx,
		`SELECT COALESCE(activity, 0), COALESCE(working_threads, 0) FROM chats_with_activity WHERE id = $1`,
		chatID).Scan(&state.Activity, &state.WorkingThreads)
	if err != nil {
		return core.ChatActivityState{}, fmt.Errorf("failed to get chat activity: %w", err)
	}
	return state, nil
}

func chatsFromView(rows []*ChatsWithActivity) []*core.Chat {
	chats := make([]*core.Chat, len(rows))
	for i, row := range rows {
		chats[i] = chatFromView(row)
	}
	return chats
}

// chatFromView maps a view row onto core.Chat. Every view column is nullable
// in the catalog (a view has no NOT NULL), so the base columns come back as
// pointers and are flattened here.
func chatFromView(row *ChatsWithActivity) *core.Chat {
	activity := 0
	if row.Activity != nil {
		activity = int(*row.Activity)
	}
	chat := &core.Chat{
		ID:                   row.ID,
		Title:                chatViewString(row.Title),
		ProjectID:            chatViewString(row.ProjectID),
		WorktreeID:           row.WorktreeID,
		ArchivedWorktreeName: row.ArchivedWorktreeName,
		UserID:               chatViewString(row.UserID),
		WorkflowName:         row.WorkflowName,
		WorkflowID:           row.WorkflowID,
		RunID:                row.RunID,
		SelectedPresets:      chatPresetsFromColumn(row.SelectedPresets),
		CreatedAt:            chatViewTime(row.CreatedAt),
		UpdatedAt:            chatViewTime(row.UpdatedAt),
		LastActive:           chatViewTime(row.LastActive),
		LastMessageAt:        row.LastMessageAt,
		Activity:             &activity,
		Unread:               row.Unread != nil && *row.Unread != 0,
		ActiveDaemonID:       row.ActiveDaemonID,
		NoMachine:            row.NoMachine != nil && *row.NoMachine,
		AdoptedAt:            row.AdoptedAt,
		ListInSidebar:        row.ListInSidebar != nil && *row.ListInSidebar,
		LaunchKind:           chatViewString(row.LaunchKind),
		TriggerID:            row.TriggerID,
		UsageLimitResumesAt:  row.UsageLimitResumesAt,
		UsageLimitProvider:   chatViewString(row.UsageLimitProvider),
		UsageLimitProbing:    row.UsageLimitProbing != nil && *row.UsageLimitProbing,
	}
	if row.WorkingThreads != nil {
		chat.WorkingThreads = int(*row.WorkingThreads)
	}
	if row.Origin != nil {
		chat.Origin = *row.Origin
	}
	if row.State != nil {
		chat.State = *row.State
	}
	// root_workflow_state and stop_reason are NULL together when the chat has
	// no root workflow row, which is the zero status (UNSPECIFIED), not any of
	// the real lifecycle states.
	if row.RootWorkflowState != nil {
		chat.RootStatus.State = *row.RootWorkflowState
		if row.RootWorkflowStopReason != nil {
			chat.RootStatus.StopReason = *row.RootWorkflowStopReason
		}
	}
	return chat
}

// chatPresetsFromColumn decodes chats.selected_presets, a JSON object of
// item type to preset name. NULL, empty or undecodable reads as no presets.
func chatPresetsFromColumn(s *string) map[string]string {
	if s == nil || *s == "" {
		return nil
	}
	var presets map[string]string
	if err := json.Unmarshal([]byte(*s), &presets); err != nil {
		return nil
	}
	return presets
}

func chatViewString(s *string) string {
	if s == nil {
		return ""
	}
	return *s
}

func chatViewTime(t *time.Time) time.Time {
	if t == nil {
		return time.Time{}
	}
	return *t
}

