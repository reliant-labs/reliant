-- forge:backward-compatible — nullable admission metadata leaves existing events unchanged.
-- Admission owns no separate queue: pending trigger events remain the durable intent.
ALTER TABLE trigger_events
    ADD COLUMN admission_scope TEXT,
    ADD COLUMN admission_key TEXT,
    ADD COLUMN admission_head TEXT,
    ADD COLUMN admission_order BIGINT GENERATED BY DEFAULT AS IDENTITY,
    ADD COLUMN admission_state TEXT,
    ADD COLUMN admission_run_id TEXT,
    -- Immutable execution root, deliberately NOT a foreign key to deletable chats.
    ADD COLUMN admission_workflow_id TEXT,
    ADD COLUMN superseded_by TEXT;
ALTER TABLE trigger_events ADD CONSTRAINT trigger_events_admission_state_check
    CHECK (admission_state IS NULL OR admission_state IN ('queued','reserved','released','superseded','overloaded'));
ALTER TABLE trigger_events ADD CONSTRAINT trigger_events_admission_shape_check
    CHECK (admission_state IS NULL OR
        (admission_scope IS NOT NULL AND admission_key IS NOT NULL AND octet_length(admission_key) BETWEEN 1 AND 512));
CREATE UNIQUE INDEX trigger_events_admission_reserved_key ON trigger_events (admission_scope, admission_key)
    WHERE admission_state = 'reserved';
CREATE UNIQUE INDEX trigger_events_admission_queued_key ON trigger_events (admission_scope, admission_key)
    WHERE admission_state = 'queued';
CREATE INDEX trigger_events_admission_queue ON trigger_events (admission_scope, admission_order)
    WHERE admission_state = 'queued';
CREATE INDEX trigger_events_admission_reserved ON trigger_events (admission_scope, admission_order)
    WHERE admission_state = 'reserved';
