-- user_updates.worktree_id is ON DELETE CASCADE from worktrees, so every
-- worktree delete looks up the updates that name it. With no index that
-- lookup is a full scan of user_updates (over a million rows in prod) PER
-- WORKTREE deleted.
-- That is what made DeleteProject on a project with 1.4M messages run for 17
-- minutes holding the project row, with every write for that user queued
-- behind it (prod, 2026-11-13).
--
-- Partial on IS NOT NULL: the referential-integrity lookup is an equality on
-- the column, which implies it, so NULL rows need no entry.
--
-- CONCURRENTLY cannot run in a transaction block, so this is the only
-- statement in the file. A build that fails leaves an INVALID index that
-- IF NOT EXISTS then skips: drop it with DROP INDEX CONCURRENTLY idx_user_updates_worktree
-- and re-run.
CREATE INDEX CONCURRENTLY IF NOT EXISTS idx_user_updates_worktree ON public.user_updates (worktree_id) WHERE worktree_id IS NOT NULL;
