-- The live threads (status 2 running, 6 paused) of a workflow, by workflow_id.
-- threads had no index on workflow_id, so the two statements that close or
-- reap live threads each read the whole table:
--   - the terminal cascade (store.CascadeTerminalStatusToThreadSubtree), run
--     every time a workflow ends: a recursive subtree of workflow ids, then
--     UPDATE threads ... WHERE t.workflow_id = subtree.id AND t.status IN
--     (2, 6). In prod 13 a minute at ~130ms each, a Seq Scan of ~108k rows;
--   - the reconciler's reap (store.ReapOrphanedThreads), every pass on every
--     api-server: threads with status IN (2, 6) whose workflow is terminal, a
--     parallel Seq Scan of the same table.
-- Live threads are a sliver of the table (83 of 108k in prod), so a partial
-- index keeps it tiny; both statements spell the same literal predicate,
-- which is what lets the planner use it.
--
-- CONCURRENTLY cannot run in a transaction block, so this is the only
-- statement in the file. IF NOT EXISTS makes a retry after a failed build a
-- no-op only when the index is valid; an INVALID leftover is dropped by hand
-- (DROP INDEX CONCURRENTLY idx_threads_live_workflow) before the retry.
CREATE INDEX CONCURRENTLY IF NOT EXISTS idx_threads_live_workflow ON public.threads (workflow_id) WHERE status IN (2, 6);
