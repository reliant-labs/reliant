-- The sidebar's Archived tab (store.ListArchivedChats) pages a user's archived
-- chats newest-updated first, keyset on (updated_at, id). No index answered
-- it: idx_chats_user_created_id orders by created_at, and selects nothing when
-- one user owns nearly every chat (46,523 of 46,624 in prod on 2026-11-18,
-- 44,283 of them archived automation runs), so every read was a Seq Scan of
-- chats plus a sort of every archived row through chats_with_activity (p50
-- ~480ms, 5,277 calls / 24h).
--
-- Partial on what the list can return: archived (state 3), and a sidebar
-- chat by its own columns (origin USER, an origin not recorded yet, or
-- adopted). That is the base-column half of chats_with_activity's
-- list_in_sidebar, which the query repeats so the planner can prove the
-- predicate. It leaves out the automation runs that archive themselves, so a
-- page reads the user's archived chats, not the tens of thousands of runs
-- between them.
--
-- CONCURRENTLY cannot run in a transaction block, so this is the only
-- statement in the file. A build that fails leaves an INVALID index that
-- IF NOT EXISTS then skips: drop it with DROP INDEX CONCURRENTLY
-- idx_chats_user_archived and re-run.
--
-- Rollback: none needed. An extra index changes no result; the previous
-- release ignores it, so it stays when the application is rolled back.
CREATE INDEX CONCURRENTLY IF NOT EXISTS idx_chats_user_archived ON public.chats (user_id, updated_at, id) WHERE state = 3 AND (origin IS NULL OR origin = 1 OR adopted_at IS NOT NULL);
