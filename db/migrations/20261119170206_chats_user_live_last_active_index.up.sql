--
-- The chat list (store.ListChats, which ListChats and the worktree reads call
-- with ExcludeArchived) reads the caller's chats that are not archived, most
-- recently active first. No index answered it: idx_chats_user_created_id and
-- idx_chats_user_org lead with user_id and select nothing when one user owns
-- nearly every chat. In prod on 2026-11-18 one user owned 46,639 chats, 44,385
-- of them archived automation runs, and ListChats was a Seq Scan of chats
-- that discarded 46,783 rows to return 26 (EXPLAIN ANALYZE with the view
-- inlined: ~60ms, before the per-row view columns). Each automation run the
-- user keeps adds an archived row the scan reads forever.
--
-- Partial on the non-archived rows, so it holds the ~2,250 live chats rather
-- than all of them, and ordered by last_active DESC, the list's order. The
-- predicate is `state <> 3` (3 is CHAT_STATE_ARCHIVED), the exact predicate
-- ListChats sends (orm.WhereNotEq): Postgres does not prove that
-- `state IS DISTINCT FROM 3` is implied by `state <> 3`, so an index declared
-- with IS DISTINCT FROM was never chosen for it. A NULL state is excluded
-- by both the index and the query.
--
-- CONCURRENTLY cannot run in a transaction block, so this is the only
-- statement in the file. A build that fails leaves an INVALID index that
-- IF NOT EXISTS then skips: drop it with DROP INDEX CONCURRENTLY
-- idx_chats_user_live_last_active and re-run.
--
-- Rollback: none needed for the index. An extra index changes no result; the
-- previous release ignores it, so it stays when the application is rolled
-- back.
--
-- Post-deploy check (index valid, ListChats adopts it) and the response to a
-- failed build: dev-docs/chat-list-live-index-rollout.md.
CREATE INDEX CONCURRENTLY IF NOT EXISTS idx_chats_user_live_last_active ON public.chats (user_id, last_active DESC) WHERE state <> 3;
